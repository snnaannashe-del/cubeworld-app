/* ═══════════════════════════════════════════════════════════════════════
   КАКОЙ ФАЙЛ СОЗДАТЬ.

       CW.открыть('new-file', { папка: {id,…}, свои: ['txt',…], потом: fn });

   Список видов — не наш выдуманный, а тот, что держит сервер
   (ФАЙЛ_ВИДЫ в database.py). Поэтому напротив каждого вида здесь
   написано честно, что с ним будет:

       «правится здесь»  — файл откроется и будет править текстом
       «только хранится» — чужой формат: создать запись можем, собрать
                           сам файл нечем. Такой лучше загрузить готовым
                           скрепкой в папке.

   Врать подписями тут нельзя: человек выбирает «Документ Word», ждёт
   Word, а получает пустую запись. Пусть видит это до нажатия, а не
   после.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('new-file', function (данные) {
  'use strict';
  данные = данные || {};

  /* Список видов тут больше не свой: он один на всю программу и лежит
     в shared/файлы.js. Своих списков было три — в этом окне, в папке и
     в окне файла, — и они разошлись: слайды были в одном, подписи во
     втором, а третий о них не знал. */
  return CW.нужен('shared/файлы.js')
    .then(function () { return CW.нужен('shared/правка.js'); })
    .then(function () { return собрать(); });

  function собрать() {
  var ПАПКА = данные.папка || {};

  var М = CW.модалка({
    имя: 'новый-файл',
    знак: 'лист',
    заголовок: Т('Создать файл'),
    подзаголовок: ПАПКА.name || ''
  });
  М.открыть();

  /* ── Полками, а не одним длинным списком ──
     Видов тринадцать, и подряд они занимали два экрана: до «Печати»
     человек доезжал прокруткой. Полки те же, что в «Новом посте», и
     собираются тем же CW.разделы — своего раскрывания здесь нет.

     Порядок полок — от того, что заводят чаще, к редкому. Первая
     открыта: окно не должно встречать человека одними заголовками. */
  var ПОЛКИ = [
    { ключ: 'лист',    имя: 'Лист и текст', виды: ['svg', 'txt', 'md'] },
    { ключ: 'бумаги',  имя: 'Документы',    виды: ['pdf', 'docx', 'slides'] },
    { ключ: 'таблицы', имя: 'Таблицы',      виды: ['csv', 'xlsx'] },
    { ключ: 'код',     имя: 'Код',          виды: ['py', 'html', 'json'] },
    { ключ: 'знаки',   имя: 'Подпись и печать', виды: ['sign', 'stamp'] }
  ];

  М.тело.innerHTML = ПОЛКИ.map(function (п, и) {
    return CW.разделы.рисовать(п.ключ, п.имя, '', и === 0);
  }).join('');

  ПОЛКИ.forEach(function (п) {
    var нутро = М.тело.querySelector('[data-разд="' + п.ключ + '"] .вщ-нутро');
    п.виды.forEach(function (к) {
      var в = CW.файлы.поВиду(к);
      if (!в) return;
      нутро.appendChild(строкаВида(в));
    });
  });

  CW.разделы.завести(М.тело, { открыт: ПОЛКИ[0].ключ });

  function строкаВида(в) {
    var свой = CW.правка.умеем(в.правим);
    var б = document.createElement('button');
    б.type = 'button';
    б.className = 'пп-вид' + (свой ? '' : ' чужой');
    б.innerHTML =
        '<span class="зн">' + CW.значок(в.зн) + '</span>'
      + '<span class="про"><span class="имя"></span>'
      + '<span class="под"></span></span>'
      + '<span class="тип">' + CW.файлы.чип(в.к) + '</span>';
    б.querySelector('.имя').textContent = Т(в.имя);
    /* Подпись честная: «правится здесь» стоит только у тех видов, чей
       редактор уже на месте. */
    б.querySelector('.под').textContent = свой ? Т('правится здесь')
                                               : Т('редактор переносится');
    б.onclick = function () { спроситьИмя(в, свой); };
    return б;
  }

  /* ── имя файла ──
     Спрашиваем одной строкой прямо здесь: отдельное окно ради одного
     поля — это лишний экран, который потом надо закрывать. */
  function спроситьИмя(в, свой) {
    var старое = М.тело.querySelector('.пп-ввод');
    if (старое) старое.remove();

    var гнездо = document.createElement('div');
    гнездо.className = 'пп-ввод';
    гнездо.innerHTML =
        '<label></label>'
      + '<button type="button" class="пп-отмена" title="' + CW.безопасно(Т('Отменить')) + '">✕</button>'
      + '<div class="ряд"><input type="text" maxlength="64" spellcheck="false">'
      + '<button type="button" class="кнопка главная">' + CW.безопасно(Т('Создать')) + '</button></div>'
      + '<div class="беда"></div>';
    гнездо.querySelector('label').textContent = Т('Имя файла · ') + Т(в.имя);
    М.тело.insertBefore(гнездо, М.тело.firstChild);

    var поле = гнездо.querySelector('input');
    /* Именно кнопка из ряда с полем, а не первая кнопка в гнезде:
       первой стоит крестик отмены, и «Создать» оставалось без
       действия. */
    var кн = гнездо.querySelector('.ряд .кнопка');
    var беда = гнездо.querySelector('.беда');
    поле.value = 'Новый.' + в.к;
    поле.focus();
    поле.setSelectionRange(0, поле.value.length - в.к.length - 1);

    поле.onkeydown = function (е) {
      if (е.key === 'Enter') { е.preventDefault(); создать(); }
      if (е.key === 'Escape') гнездо.remove();
    };
    кн.onclick = создать;
    /* Крестик — та же отмена, что и Escape: про Escape знают не все. */
    гнездо.querySelector('.пп-отмена').onclick = function () { гнездо.remove(); };

    function создать() {
      var имя = поле.value.trim();
      if (!имя) { беда.textContent = Т('Имя пустое'); return; }
      кн.disabled = true;
      беда.textContent = '';

      CW.спросить('/folders/' + ПАПКА.id + '/files', {
        способ: 'POST',
        тело: { name: имя, kind: в.к, body: заготовка(в.к) }
      }).then(function (о) {
        М.убрать();
        if (данные.потом) данные.потом();
        /* Свой вид открываем сразу: человек нажал «создать», он хочет
           писать, а не смотреть на список. Чужой открывать нечем. */
        if (свой && о && о.file) {
          CW.открыть('file', { файл: о.file, папка: ПАПКА,
                               правится: true, потом: данные.потом });
        } else {
          CW.сказать(Т('Файл создан. Открыть его можно будет, когда приедет ')
                   + 'редактор вида «' + в.имя + '»');
        }
      }).catch(function (е) {
        кн.disabled = false;
        беда.textContent = е && е.сеть ? 'Нет связи с сервером'
                                       : ((е && е.message) || 'Не создалось');
      });
    }
  }

  /* Пустой файл — плохой подарок: открыл и не понял, что делать.
     Кладём внутрь одну строку, с которой видно, что это за вид. */
  function заготовка(вид) {
    if (вид === 'md')   return '# Заголовок\n\nТекст.\n';
    if (вид === 'json') return '{\n  "имя": "значение"\n}\n';
    if (вид === 'html') return '<!doctype html>\n<meta charset="utf-8">\n<h1>' + CW.безопасно(Т('Привет')) + '</h1>\n';
    if (вид === 'py')   return '# -*- coding: utf-8 -*-\nprint("привет")\n';
    if (вид === 'csv')  return 'столбец,столбец\nзначение,значение\n';
    if (вид === 'svg')  return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">\n'
                             + '  <circle cx="50" cy="50" r="40" fill="none" stroke="#4a9eff" stroke-width="3"/>\n'
                             + '</svg>\n';
    return '';
  }
  }
});
