/* ═══════════════════════════════════════════════════════════════════════
   ПОЖАЛОВАТЬСЯ.

   Жалоба — это не донос, а просьба посмотреть. Поэтому окно короткое:
   выбрать причину одним нажатием и, если хочется, дописать словами.
   Длинная форма отпугивает ровно тех, кто наткнулся на что-то
   действительно плохое и хочет уйти поскорее.

   После отправки говорим, что будет дальше, — иначе человек не знает,
   произошло ли что-нибудь вообще.

       CW.открыть('report', {пост: 12});
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('report', function (данные) {
  'use strict';
  данные = данные || {};

  var ПРИЧИНЫ = [
    { знач: 'spam',     подпись: Т('Спам') },
    { знач: 'abuse',    подпись: Т('Оскорбления') },
    { знач: 'adult',    подпись: Т('Взрослое') },
    { знач: 'violence', подпись: Т('Жестокость') },
    { знач: 'fraud',    подпись: Т('Обман, развод') },
    { знач: 'minors',   подпись: Т('Вред детям') },
    { знач: 'other',    подпись: Т('Другое') }
  ];

  var М = CW.модалка({
    имя: 'жалоба',
    знак: 'внимание',
    заголовок: Т('Пожаловаться'),
    подзаголовок: Т('посмотрят люди, а не робот'),
    главная: { зн: 'послать', подсказка: Т('Отправить'), делать: послать }
  });

  var Ф = CW.поля(М.тело, [
    { имя: 'причина', подпись: Т('Что не так'), вид: 'фишки', обяз: true,
      пункты: ПРИЧИНЫ },
    { имя: 'слова', подпись: Т('Подробнее'), вид: 'много', строк: 3, предел: 600,
      намёк: 'Необязательно, но помогает разобраться' }
  ]);

  М.открыть();

  function послать() {
    if (!Ф.проверить()) return;
    if (!данные.пост) {
      CW.сказать(Т('Окно открыто без записи: не на что жаловаться'));
      return;
    }

    var з = Ф.взять();
    var причина = з.причина + (з.слова ? (': ' + String(з.слова).trim()) : '');

    М.занят(true);
    CW.спросить('/feed/' + данные.пост + '/report', {
      способ: 'POST', сроком: 20000, тело: { reason: причина }
    }).then(function () {
      М.имя(Т('Жалоба отправлена'), Т('спасибо'));
      М.тело.innerHTML = '';
      М.занят(false);
      /* Нижнего объяснения здесь больше нет: Анна его убрала. Галка и
         слово «Отправлено» говорят всё, что человеку нужно знать, а
         абзац под ними только задерживал его в окне, которое он уже
         закрывает. */
      М.пусто({
        знак: 'галка',
        заголовок: Т('Отправлено')
      });
      /* Жалоба ушла — отправлять второй раз нечего. Остаётся крестик. */
      М.кнопки['главная'].style.display = 'none';
    }).catch(function (е) {
      М.занят(false);
      CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                             : ((е && е.message) || 'Жалоба не ушла'));
    });
  }

  return М;
});
