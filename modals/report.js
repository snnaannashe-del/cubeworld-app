/* ═══════════════════════════════════════════════════════════════════════
   ПОЖАЛОВАТЬСЯ.

   Жалоба — это не донос, а просьба посмотреть. Поэтому окно короткое:
   выбрать причину одним нажатием и, если хочется, дописать словами.
   Длинная форма отпугивает ровно тех, кто наткнулся на что-то
   действительно плохое и хочет уйти поскорее.

   После отправки говорим, что будет дальше, — иначе человек не знает,
   произошло ли что-нибудь вообще.

       CW.открыть('report', {пост: 12});
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('report', function (данные) {
  'use strict';
  данные = данные || {};

  var ПРИЧИНЫ = [
    { знач: 'spam',     подпись: 'Спам' },
    { знач: 'abuse',    подпись: 'Оскорбления' },
    { знач: 'adult',    подпись: 'Взрослое' },
    { знач: 'violence', подпись: 'Жестокость' },
    { знач: 'fraud',    подпись: 'Обман, развод' },
    { знач: 'minors',   подпись: 'Вред детям' },
    { знач: 'other',    подпись: 'Другое' }
  ];

  var М = CW.модалка({
    имя: 'жалоба',
    знак: 'внимание',
    заголовок: 'Пожаловаться',
    подзаголовок: 'посмотрят люди, а не робот',
    главная: { зн: 'послать', подсказка: 'Отправить', делать: послать }
  });

  var Ф = CW.поля(М.тело, [
    { имя: 'причина', подпись: 'Что не так', вид: 'фишки', обяз: true,
      пункты: ПРИЧИНЫ },
    { имя: 'слова', подпись: 'Подробнее', вид: 'много', строк: 3, предел: 600,
      намёк: 'Необязательно, но помогает разобраться' }
  ]);

  М.открыть();

  function послать() {
    if (!Ф.проверить()) return;
    if (!данные.пост) {
      CW.сказать('Окно открыто без записи: не на что жаловаться');
      return;
    }

    var з = Ф.взять();
    var причина = з.причина + (з.слова ? (': ' + String(з.слова).trim()) : '');

    М.занят(true);
    CW.спросить('/feed/' + данные.пост + '/report', {
      способ: 'POST', сроком: 20000, тело: { reason: причина }
    }).then(function () {
      М.имя('Жалоба отправлена', 'спасибо');
      М.тело.innerHTML = '';
      М.занят(false);
      М.пусто({
        знак: 'галка',
        заголовок: 'Отправлено',
        текст: 'Запись посмотрят люди. Если нарушение подтвердится, её '
             + 'уберут, а автор получит замечание. Отвечать тебе отдельно '
             + 'не станут: но жалобу прочитают.'
      });
      /* Жалоба ушла — отправлять второй раз нечего. Остаётся крестик. */
      М.кнопки['главная'].style.display = 'none';
    }).catch(function (е) {
      М.занят(false);
      CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                             : ((е && е.message) || 'Жалоба не ушла'));
    });
  }

  return М;
});
