/* ═══════════════════════════════════════════════════════════════════════
   ПОДПИСКИ · ПОДПИСЧИКИ · ЛАЙКИ — одно окно на три списка.

       CW.открыть('people', {кто: 12, полка: 'подписчики', имя: 'Kriga'});

   Открывается из портфолио нажатием на любое из трёх чисел. Полка та,
   на которую нажали, две другие рядом — переключаются на месте, без
   закрытия окна.

   Списки у сервера уже готовы и одной формы:

       /follow/{кто}/following    на кого он подписан
       /follow/{кто}/followers    кто подписан на него
       /likes/человек/{кто}       кто поставил ему лайк

   В каждой строке сервер сразу говорит «я на него подписан» и «он
   подписан на меня» — поэтому кнопка в строке знает своё состояние, и
   список из полусотни человек не спрашивает сервер полсотни раз.

   Поиск здесь свой и по уже скачанному списку: эти люди уже в руках, и
   ходить за ними к серверу ради отбора по имени незачем.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('people', function (данные) {
  'use strict';
  данные = данные || {};

  var КТО = Number(данные.кто || 0);

  var ПОЛКИ = [
    { ключ: 'подписки',   подпись: 'Подписки',
      адрес: function () { return '/follow/' + КТО + '/following'; },
      пусто: 'Пока ни на кого не подписан' },
    { ключ: 'подписчики', подпись: 'Подписчики',
      адрес: function () { return '/follow/' + КТО + '/followers'; },
      пусто: 'Пока никто не подписался' },
    { ключ: 'лайки',      подпись: 'Лайки',
      адрес: function () { return '/likes/человек/' + КТО; },
      пусто: 'Пока никто не поставил лайк' }
  ];

  var полка = данные.полка || 'подписки';
  var ищем = '';
  var РЯДЫ = {};            /* ключ полки → скачанный список */

  var М = CW.модалка({
    имя: 'люди-профиля',
    знак: 'люди',
    заголовок: подписьПолки(),
    подзаголовок: данные.имя ? String(данные.имя) : ''
  });
  М.открыть();

  if (!КТО) {
    М.пусто({ знак: 'внимание', заголовок: 'Не указан человек',
              текст: 'Окно открыто без номера: показывать нечего.' });
    return М;
  }

  /* ── полки и поиск стоят над списком и не уезжают с ним ── */
  var шапка = CW.кусок('лд-верх');
  var полкиРяд = CW.кусок('лд-полки');
  шапка.appendChild(полкиРяд);

  var строкаПоиска = CW.строкаПоиска({
    подпись: 'Искать человека…',
    искать: function (текст) { ищем = текст; нарисовать(); }
  });
  строкаПоиска.classList.add('лд-поиск');
  шапка.appendChild(строкаПоиска);
  М.сверху(шапка);

  нарисоватьПолки();
  собрать();

  function подписьПолки() {
    var п = ПОЛКИ.filter(function (х) { return х.ключ === полка; })[0];
    return (п || ПОЛКИ[0]).подпись;
  }

  function нарисоватьПолки() {
    полкиРяд.innerHTML = '';
    ПОЛКИ.forEach(function (п) {
      var б = CW.эл('button', 'лд-полка' + (полка === п.ключ ? ' тут' : ''), п.подпись);
      б.type = 'button';
      б.onclick = function () {
        полка = п.ключ;
        М.имя(подписьПолки(), данные.имя || '');
        нарисоватьПолки();
        собрать();
      };
      полкиРяд.appendChild(б);
    });
  }

  function собрать() {
    var ключ = полка;
    if (РЯДЫ[ключ]) { нарисовать(); return; }

    CW.ждём(М.тело);
    var п = ПОЛКИ.filter(function (х) { return х.ключ === ключ; })[0];
    CW.спросить(п.адрес(), { тихо: true })
      .then(function (д) {
        РЯДЫ[ключ] = Array.isArray(д) ? д : ((д && (д.items || д.people)) || []);
        if (полка === ключ) нарисовать();
      })
      .catch(function (е) {
        if (полка !== ключ) return;
        М.пусто({ знак: 'внимание', заголовок: 'Не открылось',
                  текст: (е && е.сеть) ? 'Нет связи с сервером'
                                       : ((е && е.message) || 'Сервер не ответил') });
      });
  }

  function подходит(ч) {
    if (!ищем) return true;
    return CW.ровно([ч.display_name, ч.username, '#' + ч.id, ч.id].join(' '))
             .indexOf(CW.ровно(ищем)) >= 0;
  }

  function нарисовать() {
    var все = РЯДЫ[полка] || [];
    var п = ПОЛКИ.filter(function (х) { return х.ключ === полка; })[0];
    var видно = все.filter(подходит);

    М.тело.innerHTML = '';

    if (!все.length) {
      М.тело.appendChild(CW.кусок('пусто-строка', п.пусто));
      return;
    }
    if (!видно.length) {
      М.тело.appendChild(CW.кусок('пусто-строка', 'Никого с таким именем'));
      return;
    }

    видно.forEach(function (ч) { М.тело.appendChild(строка(ч)); });
  }

  function строка(ч) {
    var с = document.createElement('div');
    с.className = 'ок-строка';
    с.appendChild(CW.кружок({ размер: 38, кто: ч.id, снимок: ч.avatar_url,
                              версия: ч.avatar_ver, значок: '👤' }));

    var т = document.createElement('div');
    т.className = 'текст';
    т.innerHTML = '<b>' + CW.безопасно(CW.имяЧеловека(ч)) + '</b>'
                + '<span>' + CW.безопасно(
                    ч.username ? ('@' + ч.username)
                               : (ч.follows_me ? 'подписан на тебя' : '#' + ч.id))
                + '</span>';
    if (CW.лица) CW.лица.подписать(т.querySelector('b'), ч.id, CW.имяЧеловека(ч));
    с.appendChild(т);

    /* Нажатие на строку открывает портфолио этого человека — за тем
       список и смотрят. */
    т.style.cursor = 'pointer';
    т.onclick = function () {
      CW.вПортфолио(ч.id);
    };

    /* Себе подписаться нельзя, и кнопки у своей строки нет. */
    if (!ч.is_me) с.appendChild(кнопкаПодписки(ч));
    return с;
  }

  function кнопкаПодписки(ч) {
    var б = document.createElement('button');
    б.type = 'button';
    нарисоватьКнопку();

    б.onclick = function () {
      var было = !!ч.i_follow;
      б.disabled = true;
      CW.спросить('/follow/' + ч.id, { способ: было ? 'DELETE' : 'POST' })
        .then(function () {
          ч.i_follow = !было;
          б.disabled = false;
          нарисоватьКнопку();
          CW.сказать(было ? 'Отписалась' : 'Подписалась', 2000);
        })
        .catch(function (е) {
          б.disabled = false;
          CW.сказать((е && е.message) || 'Не вышло', 5000);
        });
    };

    function нарисоватьКнопку() {
      б.className = 'лд-кн' + (ч.i_follow ? ' уже' : '');
      б.textContent = ч.i_follow ? 'Вы подписаны' : 'Подписаться';
    }
    return б;
  }

  return М;
});
