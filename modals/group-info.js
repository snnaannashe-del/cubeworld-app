/* ═══════════════════════════════════════════════════════════════════════
   ИНФОРМАЦИЯ О ГРУППЕ — одно окно про группу целиком.

       CW.открыть('group-info', {группа: 12});

   Открывается пунктом «Информация о группе» в меню переписки. Прежде
   там было голое окно «Участники» — список имён и больше ничего. Это
   окно показывает то же, что показывает работающая программа:

       кто это            название, значок, публичная или приватная
       описание           своими словами хозяина
       пригласить         ссылка на группу и кнопка «Копировать»
       теги               из /groups/{ид}/extra
       снимки группы      оттуда же, картинками
       файлы переписки    фото · видео · аудио · ссылки, счётом
       участники          с поиском, с пометкой хозяина, с «убрать»
       покинуть группу    внизу, красным

   Три запроса: /groups/{ид}/info, /groups/{ид}/extra и
   /groups/{ид}/members. Файлы переписки считаются по уже скачанным
   сообщениям — их передаёт окно переписки (данные.сообщения), и
   второй раз за ними никто не ходит.

   ── Чего здесь нарочно нет ─────────────────────────────────────────
   Числа «онлайн» и пометок «Владелец / Админ» у кого попало. В боевой
   программе онлайн считается как «четверть участников, но не меньше
   одного», а владельцем помечается первый в списке, админом — второй.
   Это выдуманные числа: сервер их не знает. Хозяина мы помечаем по
   owner_id, и это правда; остальных не помечаем никак.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('group-info', function (данные) {
  'use strict';
  данные = данные || {};

  var ИД = данные.группа;
  var СООБЩЕНИЯ = Array.isArray(данные.сообщения) ? данные.сообщения : [];

  var М = CW.модалка({
    имя: 'о-группе',
    знак: 'люди',
    заголовок: Т('Информация'),
    подзаголовок: Т('спрашиваю…')
  });
  М.открыть();

  if (!ИД) {
    М.пусто({ знак: 'внимание', заголовок: Т('Не указана группа'),
              текст: Т('Окно открыто без номера группы, показывать нечего.') });
    return М;
  }

  var ГРУППА = {}, ДОП = {}, ЛЮДИ = [];
  var ищем = '', строкаПоиска = null;
  var полка = 'фото';          /* какая полка файлов переписки открыта */

  CW.ждём(М.тело);
  собрать();

  function собрать() {
    Promise.all([
      CW.спросить('/groups/' + ИД + '/info', { тихо: true }),
      CW.спросить('/groups/' + ИД + '/extra', { тихо: true })
        .catch(function () { return {}; }),
      CW.спросить('/groups/' + ИД + '/members', { тихо: true })
        .catch(function () { return []; })
    ]).then(function (о) {
      ГРУППА = о[0] || {};
      ДОП    = о[1] || {};
      ЛЮДИ   = рядами(о[2]);
      нарисовать();
    }).catch(function (е) {
      М.пусто({ знак: 'внимание', заголовок: Т('Не открылось'),
                текст: (е && е.сеть) ? 'Нет связи с сервером'
                                     : ((е && е.message) || 'Сервер не ответил') });
    });
  }

  /* ═════════════════════════════════════════════════════════════════════
     ОТРИСОВКА
     ═════════════════════════════════════════════════════════════════════ */
  function нарисовать() {
    var я = (CW.ясныйЯ() || {}).id;
    var яХозяин = Number(ГРУППА.owner_id) === Number(я);
    var сколько = ЛЮДИ.length || Number(ГРУППА.member_count || 0);

    М.имя(ГРУППА.name || Т.с('Группа #{н}', { н: ИД }),
          (ГРУППА.type === 'private' ? Т('Приватная группа') : Т('Публичная группа'))
          + ' · ' + сколько + ' ' + склонение(сколько));

    М.тело.innerHTML = '';

    /* ── описание ── */
    раздел('Описание');
    М.тело.appendChild(CW.кусок('гр-текст' + (ГРУППА.description ? '' : ' тихо'),
      ГРУППА.description ? CW.безопасно(ГРУППА.description) : 'без описания'));

    /* ── пригласить ──
       Ссылка ведёт прямо в окно группы. Человек, который по ней придёт,
       в публичную группу входит сам: окно спросит и вступит. В
       приватную сервер не пустит, и окно это честно скажет. */
    раздел('Пригласить в группу');
    /* Полный адрес, а не наш внутренний: ссылку кладут в сообщение, и
       «../windows/group.html» у чужого человека не откроется ничем.
       Считаем от текущей страницы — тогда она верна и на сайте, и на
       стенде, и в папке на столе. */
    /* Сам адрес окна считаем через URL, а «?ид=» дописываем после: внутри
       URL кириллица превратилась бы в проценты, и человек получил бы
       ссылку, в которой ничего не разобрать. Браузер закодирует её сам
       при переходе. */
    var адрес = new URL(CW.окно('group'), location.href).href + '?ид=' + ИД;
    var коробка = CW.кусок('гр-ссылка',
        '<span class="зн">' + CW.значок('звено', 15) + '</span>'
      + '<span class="сама">' + CW.безопасно(адрес) + '</span>'
      + '<button type="button" class="кн-копия">' + CW.безопасно(Т('Копировать')) + '</button>');
    коробка.querySelector('button').onclick = function () {
      CW.вбуфер(адрес, Т('Ссылка скопирована'));
    };
    М.тело.appendChild(коробка);

    /* ── теги ── */
    раздел('Теги');
    var теги = String(ДОП.tags || '').split(',')
                 .map(function (т) { return т.trim(); })
                 .filter(function (т) { return !!т; });
    if (!теги.length) {
      М.тело.appendChild(CW.кусок('гр-текст тихо', 'без тегов'));
    } else {
      var ряд = CW.кусок('гр-теги');
      теги.forEach(function (т) {
        ряд.appendChild(CW.кусок('гр-тег', CW.безопасно(т)));
      });
      М.тело.appendChild(ряд);
    }

    /* ── снимки группы ──
       Адрес снимка открыт и ключа не просит, поэтому обычный <img>. */
    var снимки = (ДОП.media || []).filter(function (м) {
      return String(м.mime || '').indexOf('image/') === 0;
    });
    if (снимки.length) {
      раздел('Снимки группы');
      var плитки = CW.кусок('гр-снимки');
      снимки.forEach(function (м, и) {
        var п = CW.кусок('гр-снимок');
        var и_ = document.createElement('img');
        и_.src = CW.адрес + м.url;
        и_.alt = '';
        п.appendChild(и_);
        if (и === 0) п.appendChild(CW.кусок('главный', 'Главный'));
        плитки.appendChild(п);
      });
      М.тело.appendChild(плитки);
    }

    /* ── общие файлы переписки ── */
    файлыПереписки();

    /* ── участники ── */
    раздел('Участники');
    if (!ЛЮДИ.length) {
      М.тело.appendChild(CW.кусок('гр-текст тихо', 'пока никого'));
    } else {
      /* Строка поиска — когда искать есть среди чего: на пятерых она
         только занимает место. */
      if (ЛЮДИ.length >= 8) сделатьПоиск();
      var видно = ЛЮДИ.filter(подходит);
      if (!видно.length) {
        М.тело.appendChild(CW.кусок('гр-текст тихо',
          'среди участников никого с таким именем'));
      } else {
        видно.forEach(function (ч) { М.тело.appendChild(строкаЧеловека(ч, я, яХозяин)); });
      }
    }

    /* ── покинуть группу ── */
    var выход = document.createElement('button');
    выход.type = 'button';
    выход.className = 'гр-уйти';
    выход.textContent = Т('Покинуть группу');
    выход.onclick = спроситьВыход;
    М.тело.appendChild(выход);
  }

  function раздел(имя) {
    М.тело.appendChild(CW.кусок('гр-раздел', имя));
  }

  /* ═════════════════════════════════════════════════════════════════════
     ФАЙЛЫ ПЕРЕПИСКИ

     Считаем по сообщениям, которые окно переписки уже скачало: за ними
     незачем ходить второй раз, и никакого отдельного хранилища «общих
     файлов» у сервера нет — есть сообщения со своим видом.
     ═════════════════════════════════════════════════════════════════════ */
  function полки() {
    var ссылки = [];
    СООБЩЕНИЯ.forEach(function (м) {
      if (м.msg_type && м.msg_type !== 'text') return;
      var найдено = String(м.content || '').match(/https?:\/\/[^\s<>"']+/g);
      if (найдено) найдено.forEach(function (с) { ссылки.push({ адрес: с, когда: м.created_at }); });
    });
    function вида(вид) {
      return СООБЩЕНИЯ.filter(function (м) { return м.msg_type === вид; });
    }
    return [
      { ключ: 'фото',   подпись: Т('Фото'),   ряды: вида('image') },
      { ключ: 'видео',  подпись: Т('Видео'),  ряды: вида('video') },
      { ключ: 'аудио',  подпись: Т('Аудио'),  ряды: вида('audio') },
      { ключ: 'ссылки', подпись: Т('Ссылки'), ряды: ссылки }
    ];
  }

  function файлыПереписки() {
    var все = полки();
    раздел('Общие файлы переписки');

    var ряд = CW.кусок('гр-полки');
    все.forEach(function (п) {
      var б = document.createElement('button');
      б.type = 'button';
      б.className = 'гр-полка' + (полка === п.ключ ? ' тут' : '');
      б.textContent = п.подпись + (п.ряды.length ? ' · ' + п.ряды.length : '');
      б.onclick = function () { полка = п.ключ; нарисовать(); };
      ряд.appendChild(б);
    });
    М.тело.appendChild(ряд);

    var эта = все.filter(function (п) { return п.ключ === полка; })[0];
    if (!эта || !эта.ряды.length) {
      М.тело.appendChild(CW.кусок('гр-текст тихо', 'в этой переписке пока ничего нет'));
      return;
    }

    if (полка === 'фото') {
      var плитки = CW.кусок('гр-снимки');
      эта.ряды.forEach(function (м) {
        var п = CW.кусок('гр-снимок');
        var и = document.createElement('img');
        и.src = адресВложения(м);
        и.alt = '';
        п.appendChild(и);
        плитки.appendChild(п);
      });
      М.тело.appendChild(плитки);
      return;
    }

    эта.ряды.forEach(function (м) {
      var адрес = полка === 'ссылки' ? м.адрес : адресВложения(м);
      var строка = CW.кусок('гр-файл');
      var ссылка = document.createElement('a');
      ссылка.href = адрес;
      ссылка.target = '_blank';
      ссылка.rel = 'noopener';
      ссылка.textContent = полка === 'ссылки' ? м.адрес : имяИзАдреса(адрес);
      строка.appendChild(CW.кусок('зн',
        CW.значок(полка === 'видео' ? 'плёнка' : полка === 'аудио' ? 'нота' : 'звено', 15)));
      строка.appendChild(ссылка);
      var когда = м.когда || м.created_at;
      if (когда) строка.appendChild(CW.кусок('когда', CW.подпись(когда)));
      М.тело.appendChild(строка);
    });
  }

  function адресВложения(м) {
    /* В content у вложения лежит адрес, а под ним — служебные строки:
       кнопки сообщения и привью ролика. В адрес они попадать не
       должны, иначе полка «Видео» ведёт в никуда. Снимает их общая
       рука (shared/кнопки-сообщения.js), та же, что и везде. */
    var своё = String(м.content || '');
    if (CW.кнопкиСообщения) своё = CW.кнопкиСообщения.без(своё);
    var а = м.file_url || своё.trim() || '';
    return /^https?:/.test(а) ? а : (CW.адрес + а);
  }

  function имяИзАдреса(адрес) {
    var с = String(адрес || '').split('?')[0].split('/');
    return с[с.length - 1] || 'файл';
  }

  /* ═════════════════════════════════════════════════════════════════════
     УЧАСТНИКИ
     ═════════════════════════════════════════════════════════════════════ */
  function строкаЧеловека(ч, я, яХозяин) {
    var ид = ч.id || ч.user_id;
    var хозяин = Number(ГРУППА.owner_id) === Number(ид);
    var это_я  = Number(я) === Number(ид);

    var с = document.createElement('div');
    с.className = 'ок-строка';
    var круг = CW.кружок({ размер: 36, кто: ид, снимок: ч.avatar_url,
                           версия: ч.avatar_ver });
    /* Лицо и имя участника ведут в его портфолио — так же, как в
       чатах. Своё лицо никуда не ведёт: ты и так на своей странице,
       а в портфолио есть кнопка в полосе наверху.

       Крестик в портфолио вернёт в ЭТУ группу: адрес запоминает
       CW.вПортфолио. */
    if (!это_я) {
      круг.style.cursor = 'pointer';
      круг.title = Т('Открыть портфолио');
      круг.onclick = function () { CW.вПортфолио(ид); };
    }
    с.appendChild(круг);

    var т = document.createElement('div');
    т.className = 'текст';
    т.innerHTML = '<b>' + CW.безопасно(CW.имяЧеловека(ч)) + '</b>'
                + (это_я ? '<span>' + CW.безопасно(Т('это ты')) + '</span>' : '');
    if (CW.лица) CW.лица.подписать(т.querySelector('b'), ид, CW.имяЧеловека(ч));
    if (!это_я) {
      т.style.cursor = 'pointer';
      т.onclick = function () { CW.вПортфолио(ид); };
    }
    с.appendChild(т);

    /* Хозяина помечаем по owner_id — это единственная роль, которую
       сервер знает. Админов в группах у него нет вовсе. */
    if (хозяин) с.appendChild(CW.кусок('гр-роль', 'хозяин группы'));

    /* Убирать может только хозяин, и не себя. */
    if (яХозяин && !хозяин && !это_я) {
      var кн = document.createElement('button');
      кн.className = 'ок-кн опасная';
      кн.type = 'button';
      кн.title = Т('Убрать из группы');
      кн.innerHTML = CW.рисунок('M6 6 18 18M18 6 6 18');
      кн.onclick = function () { спроситьУбрать(ч); };
      с.appendChild(кн);
    }
    return с;
  }

  function подходит(ч) {
    if (!ищем) return true;
    var ид = String(ч.id || ч.user_id || '');
    return CW.ровно([ч.display_name, ч.username, ч.uid, '#' + ид, ид].join(' '))
             .indexOf(CW.ровно(ищем)) >= 0;
  }

  function сделатьПоиск() {
    if (строкаПоиска) return;
    строкаПоиска = document.createElement('div');
    строкаПоиска.className = 'уч-поиск';
    строкаПоиска.innerHTML = '<span class="зн">' + CW.значок('лупа') + '</span>'
      + '<input type="text" spellcheck="false" autocomplete="off"'
      /* Та же подпись, что в поиске получателя перевода в кошельке:
         «Имя, Ник, UID». Прежде здесь стояло «Имя, @ник или #номер» -
         те же три вещи, но названные иначе, да ещё с решётками и
         собачками, которых вводить не надо. Одно название на всю
         программу, чтобы человек не гадал, одно это поле или разные. */
      + ' placeholder="' + CW.безопасно(Т('Имя, Ник, UID')) + '">';
    var поле = строкаПоиска.querySelector('input');
    поле.oninput = function () { ищем = поле.value.trim(); нарисовать(); };
    М.сверху(строкаПоиска);
  }

  function спроситьУбрать(ч) {
    var имя = CW.имяЧеловека(ч);
    CW.лист([
      { заголовок: Т('Убрать «') + имя + '» из группы?' },
      { зн: CW.значок('внимание', 16), подпись: Т('Убрать'), опасная: true,
        делать: function () {
          CW.спросить('/groups/' + ИД + '/kick', {
            способ: 'POST', тело: { user_id: ч.id || ч.user_id }
          }).then(function () { CW.сказать(Т('Убрала')); собрать(); })
            .catch(function (е) { CW.сказать((е && е.message) || 'Не вышло убрать'); });
        } },
      { зн: CW.рисунок('M6 6 18 18M18 6 6 18', 15), подпись: Т('Оставить') }
    ]);
  }

  function спроситьВыход() {
    CW.лист([
      { заголовок: Т('Выйти из «') + (ГРУППА.name || 'группы') + '»?' },
      { зн: CW.значок('выйти', 16), подпись: Т('Покинуть'), опасная: true,
        делать: function () {
          CW.спросить('/groups/' + ИД + '/leave', { способ: 'POST' })
            .then(function () {
              CW.сказать(Т('Вышла из группы'));
              М.закрыть();
              if (typeof данные.ушла === 'function') данные.ушла();
            })
            .catch(function (е) { CW.сказать((е && е.message) || 'Не вышло'); });
        } },
      { зн: CW.значок('назад', 16), подпись: Т('Остаться') }
    ]);
  }

  /* ═════════════════════════════════════════════════════════════════════
     МЕЛОЧЬ
     ═════════════════════════════════════════════════════════════════════ */
  function рядами(д) {
    if (!д) return [];
    if (Array.isArray(д)) return д;
    return д.items || д.members || [];
  }

  function склонение(н) {
    return CW.склонение(н, 'участник', 'участника', 'участников');
  }

  return М;
});
