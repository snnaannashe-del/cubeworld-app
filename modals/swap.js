/* ═══════════════════════════════════════════════════════════════════════
   СВАЙП: КРИПТА ⇄ CUBE.

   Здесь раньше стояла заглушка со словами «обмена пока нет». Это была
   неправда: у сервера есть и справочник монет, и расчёт, и заявки —
   /swap/catalogue, /swap/quote, /swap/start, /swap/my. Нет только
   одного — подключённого приёма платежей, то есть адреса, на который
   деньги приходят. Это разные вещи, и говорить надо именно про это:
   курс считается, заявка сохраняется, адрес пока не выдаётся.

   ── Что считаем МЫ и что считает СЕРВЕР ────────────────────────────
   Мы не считаем ничего. Сумму, курс, комиссию и дневной остаток даёт
   /swap/quote. Иначе у разных людей получились бы разные числа: курс
   в браузере берётся в момент, когда страница его спросила, а деньги
   меняются в момент, когда заявка создана. Разница между этими двумя
   моментами и есть то, за что потом спорят.

   ── Почему заявку всё равно создаём, когда приёма нет ──────────────
   Сервер отвечает reason: 'provider_not_ready' и СОХРАНЯЕТ заявку.
   Человек видит её номер в списке — значит его намерение записано, и
   когда приём заработает, заявку зачтут. Просто отказать значило бы
   потерять это.

       CW.открыть('swap');
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('swap', function (данные) {
  'use strict';
  данные = данные || {};

  var СПР = null;              /* справочник с сервера */
  var сторона = 'in';          /* in — крипта в CUBE, out — обратно */
  var монета = 'USDT';
  var сеть = 'TRON';
  var расчёт = null;
  var часы = null;

  var М = CW.модалка({
    имя: 'свайп',
    знак: 'обмен',
    заголовок: 'Свайп'
  });
  М.открыть();
  CW.ждём(М.тело);

  CW.спросить('/swap/catalogue', { сроком: 20000 })
    .then(построить)
    .catch(function (е) {
      М.пусто({ знак: 'внимание', заголовок: 'Обмен сейчас недоступен',
                текст: (е && е.сеть) ? 'Нет связи с сервером'
                                     : ((е && е.message) || 'Сервер не ответил') });
    });

  /* ═════════════════════════════════════════════════════════════════════
     РАЗМЕТКА
     ═════════════════════════════════════════════════════════════════════ */
  function построить(с) {
    СПР = с || {};
    var монеты = СПР.coins || [];
    if (!монеты.length) {
      М.пусто({ знак: 'внимание', заголовок: 'Монет нет',
                текст: 'Сервер не прислал ни одной монеты для обмена.' });
      return;
    }
    if (!найтиМонету(монета)) монета = монеты[0].sym;
    сеть = перваяСеть(монета);

    М.тело.innerHTML =
        '<div class="св-пара">'
      +   '<button type="button" data-с="in" class="тут">Крипта → CUBE</button>'
      +   '<button type="button" data-с="out">CUBE → крипта</button>'
      + '</div>'

      + '<div class="св-метка">Монета</div>'
      + '<div class="св-сетка св-монеты"></div>'

      + '<div class="св-метка">Сеть</div>'
      + '<div class="св-сети"></div>'

      + '<div class="св-метка">Отдаёшь</div>'
      + '<div class="св-сумма">'
      +   '<input class="св-даю" type="number" inputmode="decimal" min="0" step="any"'
      +   ' placeholder="0" autocomplete="off"><span class="св-даю-з">USDT</span></div>'

      + '<div class="св-стрелка">↓</div>'

      + '<div class="св-метка">Получаешь</div>'
      + '<div class="св-сумма">'
      +   '<input class="св-беру" type="number" inputmode="decimal" min="0" step="any"'
      +   ' placeholder="0" autocomplete="off"><span class="св-беру-з">CUBE</span></div>'

      /* Адрес выплаты спрашиваем только при выводе: при вводе деньги
         идут к нам, и куда их класть, знает сервер. */
      + '<div class="св-куда" style="display:none">'
      +   '<div class="св-метка">Куда отправить</div>'
      +   '<div class="св-сумма"><input class="св-адрес" type="text" autocomplete="off"'
      +   ' placeholder="Адрес кошелька" class="строкой"></div>'
      + '</div>'

      + '<div class="св-курс"></div>'
      + '<div class="св-вести"></div>'

      + '<button type="button" class="кнопка главная св-ход">'
      +   'Получить адрес для перевода</button>'

      + '<div class="св-метка" style="margin-top:22px">Мои заявки</div>'
      + '<div class="св-заявки"><div class="св-мелко">Пока пусто</div></div>';

    нарисоватьМонеты();
    нарисоватьСети();
    поля();

    где('св-пара').onclick = function (е) {
      var б = е.target.closest('button'); if (!б) return;
      сторона = б.dataset['с'];
      [].slice.call(this.children).forEach(function (х) {
        х.classList.toggle('тут', х === б);
      });
      поля(); пересчитать();
    };

    где('св-монеты').onclick = function (е) {
      var б = е.target.closest('.св-монета'); if (!б) return;
      монета = б.dataset.м;
      сеть = перваяСеть(монета);
      нарисоватьМонеты(); нарисоватьСети(); поля(); пересчитать();
    };

    где('св-сети').onclick = function (е) {
      var б = е.target.closest('.св-сеть'); if (!б) return;
      сеть = б.dataset.н;
      нарисоватьСети(); пересчитать();
    };

    где('св-даю').oninput  = function () { отложить('даю'); };
    где('св-беру').oninput = function () { отложить('беру'); };
    где('св-ход').onclick  = отправить;

    /* Сразу говорим, чего не хватает, — до того, как человек наберёт
       сумму и упрётся в это на последнем шаге. */
    if (!СПР.provider_ready) {
      весть('<b>Приём платежей ещё не подключён.</b><br>'
          + 'Курс и расчёт работают, но адреса для перевода пока не выдаются.',
            'плохо');
    }
    заявки();
  }

  /* Ищем ТОЛЬКО внутри своего окна, а не по всей странице.

     По имени через всю страницу искать нельзя: закрытое окно остаётся
     в разметке, и поиск находит прошлый экземпляр. Со второго открытия
     монеты, сети и предупреждение рисовались в мёртвое окно, а человек
     смотрел на пустые заголовки. Каркас теперь старое окно убирает, но
     полагаться на это здесь незачем: своё тело окно знает само. */
  function где(класс) { return М.тело.querySelector('.' + класс); }

  function найтиМонету(с) {
    return (СПР.coins || []).filter(function (м) { return м.sym === с; })[0];
  }
  function перваяСеть(с) {
    var м = найтиМонету(с);
    return (м && м.nets && м.nets[0]) ? м.nets[0].code : '';
  }

  function нарисоватьМонеты() {
    где('св-монеты').innerHTML = (СПР.coins || []).map(function (м) {
      return '<button type="button" class="св-монета' + (м.sym === монета ? ' тут' : '')
           + '" data-м="' + м.sym + '" title="' + CW.безопасно(м.name) + '">'
           + м.sym + '</button>';
    }).join('');
  }

  function нарисоватьСети() {
    var м = найтиМонету(монета);
    где('св-сети').innerHTML = !м ? '' : (м.nets || []).map(function (н) {
      return '<button type="button" class="св-сеть' + (н.code === сеть ? ' тут' : '')
           + '" data-н="' + н.code + '">' + CW.безопасно(н.name) + '</button>';
    }).join('');
  }

  /* Подписи и кнопка зависят от стороны. Меняем их одной рукой, а не
     в пяти местах по ходу дела. */
  function поля() {
    var ввод = сторона === 'in';
    где('св-даю-з').textContent  = ввод ? монета : 'CUBE';
    где('св-беру-з').textContent = ввод ? 'CUBE' : монета;
    где('св-куда').style.display = ввод ? 'none' : '';
    где('св-ход').textContent = ввод ? 'Получить адрес для перевода'
                                     : 'Создать заявку на вывод';
  }

  /* ═════════════════════════════════════════════════════════════════════
     ПЕРЕСЧЁТ

     Считает сервер. Мы только говорим ему, какое из двух полей человек
     заполнил, — второе он досчитает сам.
     ═════════════════════════════════════════════════════════════════════ */
  function отложить(кто) {
    clearTimeout(часы);
    часы = setTimeout(function () { пересчитать(кто); }, 320);
  }

  function пересчитать(кто) {
    var даю = где('св-даю'), беру = где('св-беру');
    if (!даю) return;
    var ввод = сторона === 'in';
    var от = Number((кто === 'беру' ? беру : даю).value);

    if (!от || от <= 0) {
      if (кто === 'беру') даю.value = ''; else беру.value = '';
      где('св-курс').textContent = '';
      расчёт = null;
      где('св-ход').disabled = false;
      return;
    }

    var тело = { direction: сторона, coin: монета, net: сеть };
    if (ввод) тело[кто === 'беру' ? 'cube_amount' : 'amount_crypto'] = от;
    else      тело[кто === 'беру' ? 'amount_crypto' : 'cube_amount'] = от;

    CW.спросить('/swap/quote', { способ: 'POST', тело: тело, тихо: true })
      .then(function (к) {
        расчёт = к;
        if (ввод) {
          if (кто !== 'даю')  даю.value  = округлить(к.amount_crypto);
          if (кто !== 'беру') беру.value = округлить(к.cube_amount);
        } else {
          if (кто !== 'даю')  даю.value  = округлить(к.cube_amount);
          if (кто !== 'беру') беру.value = округлить(к.amount_crypto);
        }
        где('св-курс').innerHTML =
            '1 CUBE = <b>$' + Number(к.cube_usd || 0).toFixed(2) + '</b> · 1 '
          + монета + ' = <b>$' + ч(к.coin_usd, к.coin_usd < 1 ? 6 : 2) + '</b><br>'
          + 'Сумма <b>$' + ч(к.usd_value) + '</b>'
          + (к.fee_usd ? ' · комиссия <b>$' + ч(к.fee_usd) + '</b>'
                       : ' · без комиссии')
          + '<br>Сегодня осталось <b>$' + ч(к.day_left_usd) + '</b> из $'
          + ч(СПР.max_usd_day, 0);

        var мало = Number(к.usd_value) < Number(к.min_usd || 5);
        где('св-ход').disabled = мало;
        if (мало) весть('Меньше $' + (к.min_usd || 5) + ' не меняем', 'плохо');
        else if (!СПР.provider_ready) {
          весть('<b>Приём платежей ещё не подключён.</b><br>'
              + 'Курс и расчёт работают, но адреса для перевода пока не выдаются.',
                'плохо');
        } else весть(null);
      })
      .catch(function (е) {
        расчёт = null;
        где('св-курс').textContent = (е && е.message) || 'Курс сейчас недоступен';
      });
  }

  /* ═════════════════════════════════════════════════════════════════════
     ЗАЯВКА
     ═════════════════════════════════════════════════════════════════════ */
  function отправить() {
    if (!расчёт) { CW.сказать('Сначала укажи сумму'); return; }

    var тело = { direction: сторона, coin: монета, net: сеть };
    if (сторона === 'in') тело.amount_crypto = расчёт.amount_crypto;
    else {
      тело.cube_amount = расчёт.cube_amount;
      тело.payout_address = (где('св-адрес').value || '').trim();
    }

    М.занят(true);
    где('св-ход').disabled = true;

    CW.спросить('/swap/start', { способ: 'POST', тело: тело, сроком: 25000 })
      .then(function (о) {
        М.занят(false);
        где('св-ход').disabled = false;
        var з = (о && о.swap) || {};

        /* Приёма нет — но заявка записана, и у неё есть номер. */
        if (о && о.reason === 'provider_not_ready') {
          весть('<b>Приём платежей ещё не подключён.</b><br>'
              + 'Адреса для перевода пока нет, ничего не отправляй. Заявка №'
              + з.id + ' сохранена, зачтём её, как только приём заработает.',
                'плохо');
          заявки(); return;
        }

        if (сторона === 'out') {
          весть('<b>Заявка №' + з.id + ' принята.</b><br>'
              + CW.безопасно(з.message || '')
              + '<br>Удержано <b>' + ч(з.cube_amount) + ' CUBE</b>.', 'хорошо');
          заявки(); return;
        }

        /* Адрес и сеть — то, из-за чего теряют деньги. Поэтому сеть
           названа отдельной строкой, а не вскользь в конце абзаца. */
        весть('<b>Переведи ровно ' + округлить(з.amount_crypto) + ' ' + монета
            + '</b> в сети <b>' + CW.безопасно(сеть) + '</b>.<br>'
            + 'Другая сеть: деньги потеряются.'
            + '<div class="св-адрес">'
            + CW.безопасно(з.pay_address || '') + '</div>'
            + (з.pay_memo ? '<div class="св-адрес">memo / tag: '
                          + CW.безопасно(з.pay_memo) + '</div>' : '')
            + '<button type="button" class="кнопка св-копия св-коп">'
            + 'Скопировать адрес</button>', 'хорошо');

        var коп = где('св-коп');
        /* Было: writeText без запасного пути и с try/catch вокруг
           обещания — отказ браузера приходил мимо catch, и кнопка молча
           ничего не копировала. */
        if (коп) коп.onclick = function () {
          CW.вбуфер(з.pay_address || '', 'Адрес скопирован');
        };
        заявки();
      })
      .catch(function (е) {
        М.занят(false);
        где('св-ход').disabled = false;
        весть(CW.безопасно((е && е.message) || 'Не получилось создать заявку'),
              'плохо');
      });
  }

  /* ═════════════════════════════════════════════════════════════════════
     МОИ ЗАЯВКИ

     Состояний девять, и человеку важны не их имена, а что от него
     сейчас требуется: ждать, перевести, ничего.
     ═════════════════════════════════════════════════════════════════════ */
  var ВИД = {
    'new':              ['Создана',              'ждём'],
    'awaiting_payment': ['Ждём перевод',         'ждём'],
    'awaiting_setup':   ['Приём не подключён',   'плохо'],
    'paid':             ['Деньги в пути',        'ждём'],
    'queued':           ['В очереди на выплату', 'держим'],
    'done':             ['Готово',               'хорошо'],
    'failed':           ['Не прошла',            'плохо'],
    'cancelled':        ['Отменена',             'плохо'],
    'refunded':         ['CUBE возвращены',      'плохо']
  };

  function заявки() {
    CW.спросить('/swap/my', { тихо: true }).then(function (о) {
      var куда = где('св-заявки');
      if (!куда) return;
      var ряды = (о && о.swaps) || [];
      if (!ряды.length) {
        куда.innerHTML = '<div class="св-мелко">Пока пусто</div>';
        return;
      }
      куда.innerHTML = ряды.map(function (з) {
        var в = ВИД[з.status] || [з.status, 'ждём'];
        var ввод = з.direction === 'in';
        var строка = ввод
          ? (округлить(з.amount_crypto) + ' ' + з.coin + ' → ' + ч(з.cube_amount) + ' CUBE')
          : (ч(з.cube_amount) + ' CUBE → ' + округлить(з.amount_crypto) + ' ' + з.coin);
        return '<div class="св-ряд"><div class="св-ряд-т">'
             + '<div class="св-ряд-и">' + CW.безопасно(строка) + '</div>'
             + '<div class="св-мелко">№' + з.id + ' · ' + CW.безопасно(з.net)
             + ' · $' + ч(з.usd_value) + '</div></div>'
             + '<span class="св-метко ' + в[1] + '">' + в[0] + '</span></div>';
      }).join('');
    }).catch(function () { /* список не главное — молчим */ });
  }

  /* ═════════════════════════════════════════════════════════════════════
     МЕЛОЧЬ
     ═════════════════════════════════════════════════════════════════════ */
  function весть(что, род) {
    var у = где('св-вести');
    if (!у) return;
    у.innerHTML = что ? ('<div class="св-весть ' + (род || '') + '">' + что + '</div>') : '';
  }

  function ч(н, знаков) {
    return Number(н || 0).toLocaleString('ru', {
      maximumFractionDigits: знаков === undefined ? 2 : знаков });
  }

  /* Крипта бывает дорогой и дешёвой: 0,00031 BTC и 420 DOGE — одинаково
     верные суммы. Поэтому у большого числа режем знаки после запятой, а
     у малого держим значащие цифры. */
  function округлить(х) {
    х = Number(х || 0);
    if (!х) return '';
    return х >= 1 ? х.toFixed(4).replace(/0+$/, '').replace(/\.$/, '')
                  : Number(х.toPrecision(6)).toString();
  }

  return М;
});
