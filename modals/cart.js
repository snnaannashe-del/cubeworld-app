/* ═══════════════════════════════════════════════════════════════════════
   ОПЛАТА КОРЗИНЫ — ОДНИМ РАЗОМ ЗА ВСЁ.
   /home/claude/новое/cubeworld-app/modals/cart.js

       CW.открыть('cart', { потом: function (итог) {…} });

   Корзину собирает и хранит shared/корзина.js, здесь только оплата.

   ── ЧТО ОКНО ДЕЛАЕТ ПО ПОРЯДКУ ────────────────────────────────────
   1. Спрашивает у сервера КАЖДЫЙ товар заново: цену, наличие, не снят
      ли с витрины. Цена в корзине - это память о том, что было вчера;
      платить по памяти нельзя.
   2. Складывает итог и сравнивает с балансом. Не хватает - говорит, на
      сколько, и предлагает убрать лишнее, а не упирается в «ошибку».
   3. У вещей спрашивает адрес - ОДИН на всю доставку: человек покупает
      себе, а не в пять разных городов.
   4. Платит по одному, по очереди. Что купилось - уходит из корзины,
      что не купилось - остаётся вместе с причиной.

   ── ПОЧЕМУ ПО ОДНОМУ, А НЕ ОДНИМ ЗАПРОСОМ ─────────────────────────
   У сервера нет ручки «купить всё»: у каждого товара своя - /shop/…/buy
   и /market/…/buy, - и каждая сама списывает деньги и заводит заказ.
   Сделать одну общую значит переписать обе и выложить сервер заново. А
   по очереди работает уже сегодня и ничем не хуже: деньги списываются
   теми же списаниями, просто подряд.

   Честно о том, чего это стоит: если на середине кончатся деньги или
   товар разберут, часть покупок уже случится. Поэтому итог считаем
   ДО оплаты и не начинаем, пока денег не хватает на всё.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('cart', function (данные) {
  'use strict';
  данные = данные || {};

  var СТРОКИ = (CW.корзина ? CW.корзина.список() : []);
  var БАЛАНС = 0;
  var Ф = null;
  var ИТОГ = 0;

  var М = CW.модалка({
    имя: 'корзина',
    знак: 'тележка',
    заголовок: Т('Оплата корзины'),
    подзаголовок: Т('Считаю…'),
    главная: { зн: 'монета', подсказка: Т('Оплатить'), делать: подтвердить }
  });

  var список = document.createElement('div');
  список.className = 'крз-список';
  М.тело.appendChild(список);

  var итогряд = document.createElement('div');
  итогряд.className = 'крз-итог';
  М.тело.appendChild(итогряд);

  М.открыть();
  М.занят(true);
  освежить();

  /* ── 1. СПРОСИТЬ ВСЁ ЗАНОВО ─────────────────────────────────────── */
  function освежить() {
    var дела = СТРОКИ.map(function (з) {
      var путь = (з.род === 'shop' ? '/shop/' : '/market/') + з.ид;
      return CW.спросить(путь, { тихо: true })
        .then(function (д) {
          var т = (д && (д.item || д)) || {};
          з.цена = Number(т.price != null ? т.price : з.цена) || 0;
          з.валюта = String(т.currency || з.валюта || 'CUBE').toUpperCase();
          з.имя = т.title || з.имя;
          з.вналичии = (з.род === 'shop') ? (Number(т.qty) || 0) : null;
          з.снят = (т.status && т.status !== 'active') ? true : false;
          з.куплен = !!т.bought;
          з.нет = (з.род === 'shop' && !з.вналичии) || з.снят;
          if (з.род === 'shop' && з.вналичии) {
            з.сколько = Math.max(1, Math.min(з.сколько || 1, з.вналичии));
          }
        })
        .catch(function () { з.нет = true; з.пропал = true; });
    });
    дела.push(CW.кто(true).then(function (я) {
      БАЛАНС = Number((я && я.cube_balance) || 0);
    }).catch(function () {}));

    Promise.all(дела).then(function () {
      М.занят(false);
      нарисовать();
    });
  }

  /* ── 2. ПОКАЗАТЬ ────────────────────────────────────────────────── */
  function нарисовать() {
    список.innerHTML = '';
    if (!СТРОКИ.length) {
      М.пусто({ знак: 'тележка', заголовок: Т('Корзина пуста'),
                текст: Т('Нажми «В корзину» у товара на витрине.') });
      итогряд.style.display = 'none';
      if (М.кнопки['главная']) М.кнопки['главная'].style.display = 'none';
      М.имя(null, '');
      return;
    }

    СТРОКИ.forEach(function (з) {
      var чужаяВалюта = String(з.валюта || 'CUBE').toUpperCase() !== 'CUBE';
      var р = document.createElement('div');
      р.className = 'крз-строка' + ((з.нет || чужаяВалюта) ? ' нельзя' : '');

      var кадр = document.createElement('span');
      кадр.className = 'крз-кадр';
      if (з.снимок) {
        кадр.innerHTML = '<img src="' + CW.безопасно(CW.файл(з.снимок)) + '" alt="">';
      } else {
        кадр.innerHTML = CW.значок(з.род === 'shop' ? 'сумка' : 'дискета', 18);
      }
      р.appendChild(кадр);

      var середина = document.createElement('span');
      середина.className = 'крз-имя';
      середина.innerHTML = '<b>' + CW.безопасно(з.имя) + '</b>'
        + '<span class="крз-мелко">' + CW.безопасно(з.продавец || '')
        + (з.род === 'shop' && з.сколько > 1 ? ' · ' + з.сколько + ' шт.' : '')
        + (з.нет ? (з.пропал ? ' · товара больше нет'
                             : (з.снят ? ' · снят с витрины' : ' · разобрали'))
                 : '')
        + (з.куплен ? ' · уже куплен' : '')
        + (String(з.валюта || 'CUBE').toUpperCase() !== 'CUBE'
             ? ' · цена не в CUBE, платить придётся продавцу напрямую' : '')
        + '</span>';
      р.appendChild(середина);

      var цена = document.createElement('span');
      цена.className = 'крз-цена';
      цена.textContent = з.валюта !== 'CUBE'
        ? (з.цена + ' ' + з.валюта)
        : (з.цена ? ((з.цена * (з.сколько || 1)) + ' CUBE') : 'даром');
      р.appendChild(цена);

      var урна = document.createElement('button');
      урна.type = 'button';
      урна.className = 'крз-убрать';
      урна.title = Т('Убрать из корзины');
      урна.innerHTML = CW.значок('урна', 16);
      урна.onclick = function () {
        CW.корзина.убрать(з.ключ);
        СТРОКИ = СТРОКИ.filter(function (д) { return д !== з; });
        нарисовать();
      };
      р.appendChild(урна);

      список.appendChild(р);
    });

    /* Адрес - один на всю доставку, и только если в корзине есть вещи. */
    var естьВещи = СТРОКИ.some(function (з) { return з.род === 'shop' && !з.нет; });
    if (естьВещи && !Ф) {
      Ф = CW.поля(М.тело, [
        { имя: 'адрес', подпись: Т('Куда везти'), вид: 'много', строк: 3,
          предел: 400, обяз: true,
          намёк: 'Страна, город, улица, дом, получатель' },
        { имя: 'записка', подпись: Т('Записка продавцам'), предел: 400,
          намёк: 'Необязательно' }
      ]);
    }

    считать();
  }

  function считать() {
    var платим = СТРОКИ.filter(годен);
    ИТОГ = платим.reduce(function (с, з) {
      return с + (Number(з.цена) || 0) * (з.род === 'shop' ? (з.сколько || 1) : 1);
    }, 0);

    var хватает = ИТОГ <= БАЛАНС;
    итогряд.style.display = '';
    итогряд.innerHTML =
        '<div class="крз-строчка"><span>' + CW.безопасно(Т('Товаров к оплате')) + '</span><b>'
      + платим.length + '</b></div>'
      + '<div class="крз-строчка"><span>' + CW.безопасно(Т('Итого')) + '</span><b>' + ИТОГ + ' CUBE</b></div>'
      + '<div class="крз-строчка' + (хватает ? '' : ' мало') + '">'
      + '<span>' + CW.безопасно(Т('На балансе')) + '</span><b>' + Math.round(БАЛАНС) + ' CUBE</b></div>'
      + (хватает ? ''
         : '<div class="крз-мало">' + CW.безопасно(Т('Не хватает')) + ' ' + (ИТОГ - Math.round(БАЛАНС))
           + ' ' + CW.безопасно(Т('CUBE. Убери что-нибудь из корзины или пополни баланс.')) + '</div>');

    М.имя(null, платим.length
      ? Т.с('{сколько} к оплате · {итог} CUBE',
            { сколько: платим.length, итог: ИТОГ })
      : Т('Оплачивать нечего'));

    var кн = М.кнопки['главная'];
    if (кн) {
      кн.style.display = платим.length ? '' : 'none';
      кн.title = Т.с('Оплатить {н} CUBE', { н: ИТОГ });
      кн.disabled = !хватает;
      кн.style.opacity = хватает ? '' : '.45';
    }
  }

  /* Годен к оплате: есть в продаже, цена в наших деньгах, ещё не куплен. */
  function годен(з) {
    return !з.нет && !з.куплен && String(з.валюта || 'CUBE').toUpperCase() === 'CUBE';
  }

  /* ── 3. ПОДТВЕРЖДЕНИЕ ───────────────────────────────────────────── */
  function подтвердить() {
    var платим = СТРОКИ.filter(годен);
    if (!платим.length) { CW.сказать(Т('Оплачивать нечего')); return; }
    if (ИТОГ > БАЛАНС) {
      CW.сказать(Т.с('Не хватает {н} CUBE',
                     { н: ИТОГ - Math.round(БАЛАНС) }), 6000);
      return;
    }
    var естьВещи = платим.some(function (з) { return з.род === 'shop'; });
    if (естьВещи && Ф && !Ф.проверить()) return;

    CW.лист([
      { заголовок: Т.с('Списать {н} CUBE за {к} {слово}?',
                       { н: ИТОГ, к: платим.length,
                         слово: Т.мн(платим.length,
                                     'товар', 'товара', 'товаров') }) },
      { зн: CW.значок('монета', 16), подпись: Т('Оплатить'),
        делать: function () { платить(платим); } },
      { зн: CW.значок('стрелка', 16), подпись: Т('Передумать') }
    ]);
  }

  /* ── 4. ОПЛАТА ПО ОЧЕРЕДИ ───────────────────────────────────────── */
  function платить(платим) {
    М.занят(true);
    var адрес = (Ф && String(Ф.взять('адрес') || '').trim()) || '';
    var записка = (Ф && String(Ф.взять('записка') || '').trim()) || '';
    var купили = 0, беды = [];

    (function дальше(и) {
      if (и >= платим.length) { закончить(купили, беды); return; }
      var з = платим[и];
      var путь = (з.род === 'shop' ? '/shop/' : '/market/') + з.ид + '/buy';
      var тело = з.род === 'shop'
        ? { qty: з.сколько || 1, address: адрес, note: записка }
        : null;
      CW.спросить(путь, { способ: 'POST', сроком: 25000, тело: тело })
        .then(function (о) {
          купили++;
          if (о && о.balance != null) {
            БАЛАНС = Number(о.balance);
            if (CW.обновитьБаланс) CW.обновитьБаланс(о.balance);
          }
          CW.корзина.убрать(з.ключ);
          СТРОКИ = СТРОКИ.filter(function (д) { return д !== з; });
        })
        .catch(function (е) {
          беды.push((з.имя || 'товар') + ': '
                  + ((е && е.message) || 'не вышло'));
        })
        .then(function () { дальше(и + 1); });
    })(0);
  }

  function закончить(купили, беды) {
    М.занят(false);
    if (купили && !беды.length) {
      CW.сказать(купили === 1 ? 'Куплено' : ('Куплено ' + купили + ' товара'), 3000);
      М.убрать();
      if (данные.потом) данные.потом({ купили: купили, беды: беды });
      return;
    }
    if (купили) {
      CW.сказать(Т.с('Куплено {н}, остальное осталось в корзине',
                     { н: купили }), 6000);
    }
    if (беды.length) CW.сказать(беды[0], 8000);
    нарисовать();
    if (данные.потом) данные.потом({ купили: купили, беды: беды });
  }

  return М;
});
