/* ═══════════════════════════════════════════════════════════════════════
   НОВЫЙ ПОСТ.

   Здесь раньше была одна короткая форма: текст, теги, вложение. Ролик
   она вообще не принимала и уводила человека в другое окно. В боевой
   программе окно другое, и оно умнее: два вида записи и четыре раздела,
   открытых сразу.

       ТИП               SHORT (видео) или POST (фото · файл · текст)
       ВИДЕО И ОБЛОЖКА   два окошка 9:16 — ролик и титульный кадр
       ПОДПИСЬ           заголовок, музыка, описание
       ТЕГИ              #хэштег1 #хэштег2

   ── Разделы открыты все сразу ─────────────────────────────────────
   Сперва здесь было «открыт всегда один»: окно короче, зато человек,
   заполнив подпись, закрывал её, чтобы добраться до тегов, и переставал
   видеть написанное. Для четырёх коротких разделов это лишняя работа
   руками. Теперь открыто всё, заголовки — мелкие подписи, а длину окна
   держит прокрутка в теле.

   Строк «или вставь ссылку…» больше нет ни у ролика, ни у файла. Они
   обещали то, чего не делали: чужую ссылку никто не проверял и не
   забирал к себе, и запись уезжала в ленту со ссылкой на чужой сервер,
   которая завтра перестанет открываться. Кладём только своё — через
   загрузку.

   ── Почему у SHORT два окошка, а не одно ──────────────────────────
   Оба 9:16 — ровно как ролик в ленте. Слева видео, справа обложка.
   Обложка кладётся в image_url: лента берёт заставку оттуда, и без
   неё в ленте стоит чёрный прямоугольник, пока ролик не запустят.

       CW.открыть('create-post', {куб: 12});
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('create-post', function (данные) {
  'use strict';
  данные = данные || {};

  var вид = 'short';          /* short — ролик, ball — пост */
  var видео = '';             /* адрес залитого ролика */
  var обложка = '';           /* адрес залитого титульного кадра */
  var вложение = '';          /* адрес фото или файла у поста */
  var вложениеИмя = '';

  var ЧЕРНОВИК = данные.черновик || null;   /* правим уже сохранённый */

  var М = CW.модалка({
    имя: 'новый-пост',
    знак: 'лист',
    заголовок: Т('Новый пост'),
    /* Одна дверь на всё, что не «опубликовать сейчас»: сохранить в
       черновики, назначить время, открыть прежние. Тремя кнопками в
       шапке это был бы ряд из пяти кругляшей. */
    кнопки: [{ имя: 'черновики', зн: 'буфер', подсказка: Т('Черновики и отложенные'),
               делать: менюЧерновиков }],
    /* Крестик и нажатие мимо зовут закрыть(), а не убрать(): черновик
       надо спасать именно здесь, иначе закрытое крестиком окно уносит
       всё написанное. */
    при_закрытии: function () { самСохранить(); },
    главная: { зн: 'послать', подсказка: Т('Опубликовать'), делать: отправить }
  });

  /* ═════════════════════════════════════════════════════════════════════
     РАЗМЕТКА
     ═════════════════════════════════════════════════════════════════════ */
  М.тело.innerHTML =
      раздел('тип', 'Тип',
          /* ── ПЕРЕКЛЮЧАТЕЛЬ ВМЕСТО ДВУХ ПЛИТОК ──
             Было: две большие плитки со значками и подписями. Выбор
             из двух не стоит двух плиток: это одно и то же решение,
             и ползунок говорит его короче. Оправа светится синим
             слева и красным справа и слегка дышит, чтобы глаз сразу
             нашёл, с чего форма начинается. */
          /* Ползунок и дверь в редактор стоят одним рядом: это два
             решения одного шага - каким будет ролик и откуда он
             возьмётся. Внизу, под окошками загрузки, кнопка редактора
             занимала отдельную строку и ещё одну под ней. */
          '<div class="нп-типряд">'
        +   '<div class="нп-тип">'
        +     '<div class="нп-виды нп-тумблер">'
        +       '<span class="нп-бегун"></span>'
        +       ползунок('short', 'Short')
        +       ползунок('ball',  'Post')
        +     '</div>'
        +   '</div>'
        +   '<button type="button" class="кнопка нп-редактор">'
        +     CW.значок('плёнка', 16)
        +     '<span>' + CW.безопасно(Т('Контент редактор')) + '</span></button>'
        + '</div>')

    + раздел('медиа', 'Видео и обложка',
          '<div class="нп-ряд">'
        +   слот('видео',   'плёнка', 'Нажми чтобы загрузить видео',
                 'MP4, WebM, MOV · до 50 МБ', 'Видео')
        +   слот('обложка', 'картинка', 'Обложка',
                 'Титульный кадр ролика', 'Обложка')
        + '</div>')

    + раздел('файл', 'Фото или файл',
          '<div class="нп-ряд один">'
        +   слот('вложение', 'скрепка', 'Прикрепи файл или фото',
                 'Изображение, PDF, документ · до 20 МБ', 'Вложение')
        + '</div>')

    + раздел('подпись', 'Подпись',
          '<input class="нп-строка нп-заголовок" type="text" autocomplete="off"'
        + ' placeholder="' + CW.безопасно(Т('Заголовок')) + '" maxlength="300">'
        + '<input class="нп-строка нп-музыка" type="text" autocomplete="off"'
        + ' placeholder="' + CW.безопасно(Т('Музыка')) + '" maxlength="200">'
        + '<textarea class="нп-строка нп-описание" rows="3"'
        + ' placeholder="' + CW.безопасно(Т('Описание')) + '" maxlength="2000"></textarea>')

    + раздел('теги', 'Теги',
          '<input class="нп-строка нп-теги" type="text" autocomplete="off"'
        + ' placeholder="' + CW.безопасно(Т('#хэштег')) + '" maxlength="120">')

    + '<div class="нп-беда"></div>';

  /* Полки общие: CW.разделы из shared/window.js. Своих у окна было
     четыре строчки разметки и свой же обработчик нажатия — ровно то,
     что уже лежит в общем сборщике, только стрелка смотрела в другую
     сторону. Четвёртый довод «true» — полка открыта сразу: заполнять
     форму, открывая разделы по одному, лишняя работа руками. */
  function раздел(ключ, имя, внутри) {
    /* Пятый довод «голый»: без стрелки и без сворачивания. Здесь все
       полки открыты всегда, и стрелка обещала дверцу, в которую никто
       не ходит. */
    return CW.разделы.рисовать(ключ, имя, внутри, true, true);
  }

  function ползунок(ключ, имя) {
    return '<button type="button" class="нп-вид' + (ключ === вид ? ' тут' : '')
         + '" data-вид="' + ключ + '">' + имя + '</button>';
  }

  function слот(ключ, знак, имя, под, титр) {
    return '<div class="нп-клетка">'
         + '<div class="нп-слот нп-слот-' + ключ + '" data-слот="' + ключ + '"'
         +      ' title="' + CW.безопасно(Т(имя) + ' · ' + Т(под)) + '">'
         +   '<span class="зн">' + CW.значок(знак) + '</span>'
         +   '<span class="имя">' + CW.безопасно(Т(имя)) + '</span>'
         +   '<span class="под">' + CW.безопасно(Т(под)) + '</span>'
         +   '<span class="нп-ход"><i></i></span>'
         +   '<button type="button" class="нп-снять" title="' + CW.безопасно(Т('Убрать')) + '">✕</button>'
         + '</div>'
         + '<div class="нп-титр">' + CW.безопасно(Т(титр)) + '</div></div>';
  }

  /* ═════════════════════════════════════════════════════════════════════
     РАЗДЕЛЫ ОТКРЫТЫ ВСЕ. Тело окна прокручивается — иначе форма
     перерастает экран на невысоком мониторе.
     ═════════════════════════════════════════════════════════════════════ */
  /* Окно было на 620 точек и прокручивалось почти всегда: на обычном
     мониторе под ним оставалась пустая треть экрана, а форму всё равно
     приходилось листать. Берём высоту по экрану — до 900 точек. */
  /* Форма должна помещаться целиком: листать её ради четырёх полей
     незачем. Потолок поднят с 78 до 86 процентов высоты экрана -
     замерено, что при 1366 на 768 форме нужно 632 точки, а 86
     процентов дают 660. Прокрутка остаётся на самый тесный экран,
     но в обычной жизни полосы не видно. */
  М.тело.style.cssText =
    'max-height:min(86vh, 900px);overflow-y:auto;overscroll-behavior:contain;'
    + 'padding:4px 22px 14px';

  var Р = CW.разделы.завести(М.тело);

  /* ── выбор вида ──
     Разделы «Видео и обложка» и «Фото или файл» — это один и тот же шаг
     для двух видов записи. Показываем тот, который к делу. */
  М.тело.querySelector('.нп-виды').onclick = function (е) {
    var б = е.target.closest('.нп-вид');
    if (!б) return;
    поставитьВид(б.dataset.вид);
  };

  /* Вид ставится одним местом на всё окно: его переключает рука, его
     же ставит черновик при открытии и редактор, отдавший готовый
     ролик. Три одинаковых куска кода тут однажды разъехались бы, и
     бегунок остался бы не на той половине. */
  function поставитьВид(ключ) {
    вид = (ключ === 'ball') ? 'ball' : 'short';
    var полка = М.тело.querySelector('.нп-виды');
    полка.classList.toggle('пост', вид === 'ball');
    [].slice.call(полка.querySelectorAll('.нп-вид')).forEach(function (х) {
      х.classList.toggle('тут', х.dataset.вид === вид);
    });
    поВиду();
  }

  function поВиду() {
    найти('медиа').style.display = вид === 'short' ? '' : 'none';
    найти('файл').style.display  = вид === 'short' ? 'none' : '';
    /* ── РЕДАКТОР ЕСТЬ НА ОБЕИХ СТОРОНАХ ──
       Прежде на стороне Post кнопка пряталась: мол, редактор собирает
       ролик, а у поста ролика нет. Анна: «почему в пост ты убираешь
       контент редактор, оставь и там».

       И правильно: дверь не в пустую комнату. Редактор отдаёт готовый
       ролик, и окно само встаёт на Short, когда он приезжает (смотри
       открытьРедактор ниже). То есть нажать её со стороны Post можно,
       и она делает ровно то, чего от неё ждут, - просто заодно
       переключает вид. Прятать её значило заставлять человека сперва
       догадаться, что редактор живёт на соседней половине
       переключателя. */
    беда('');
  }

  function найти(ключ) { return Р.найти(ключ); }
  function вМне(класс) { return М.тело.querySelector('.' + класс); }

  поставитьВид(вид);

  /* ═════════════════════════════════════════════════════════════════════
     ФАЙЛЫ

     Поле выбора лежит в разметке заранее: созданное по нажатию, оно в
     части браузеров не открывает окно выбора вовсе.
     ═════════════════════════════════════════════════════════════════════ */
  /* Виды у сервера свои и только эти: image · audio · doc · clip · movie.
     Здесь стоял выдуманный «video» — сервер подписывал билет видом «doc»,
     подпись не сходилась, и КАЖДАЯ загрузка ролика отвечала 403. Ролик в
     ленту — это «clip» (до 300 МБ у сервера; окно держит 50, потому что
     больше браузер кладёт кусками, а окна для этого ещё нет). */
  var ВЫБОР = {
    видео:    { принимать: 'video/*',  вид: 'clip',  предел: 50 },
    обложка:  { принимать: 'image/*',  вид: 'image', предел: 10 },
    вложение: { принимать: 'image/*,.pdf,.zip,.txt,.doc,.docx', вид: 'doc', предел: 20 }
  };

  var поле = document.createElement('input');
  поле.type = 'file';
  поле.style.cssText =
    'position:fixed;left:0;top:0;width:1px;height:1px;opacity:0;pointer-events:none';
  document.body.appendChild(поле);
  var ждёт = null;

  /* ── РЕДАКТОР ──
     Окно монтажа отдаёт готовый ролик одним файлом. Дальше он идёт
     тем же путём, что и выбранный с диска: проверка размера, загрузка
     с полосой, кадр в окошке. Второй дороги для «своего» ролика
     заводить не надо. */
  вМне('нп-редактор').onclick = function () {
    /* Монтажный стол тащим по требованию: он нужен одному окну из
       сорока, и возить его на каждой странице незачем. */
    CW.нужен('shared/видеостол.js').then(открытьРедактор)
      .catch(function () { беда(Т('Монтажный стол не приехал')); });
  };

  function открытьРедактор() {
    CW.открыть('редактор', {
      холст: '9:16',
      потом: function (файл) {
        поставитьВид('short');
        взять('видео', файл);
      }
    });
  }

  М.тело.addEventListener('click', function (е) {
    var снять = е.target.closest('.нп-снять');
    if (снять) {
      е.stopPropagation();
      очистить(снять.closest('.нп-слот').dataset.слот);
      return;
    }
    var слот = е.target.closest('.нп-слот');
    if (!слот) return;
    ждёт = слот.dataset.слот;
    поле.accept = ВЫБОР[ждёт].принимать;
    поле.value = '';
    поле.click();
  });

  поле.onchange = function () {
    var ф = поле.files && поле.files[0];
    поле.value = '';
    if (!ф || !ждёт) return;
    взять(ждёт, ф);
  };

  function взять(ключ, ф) {
    var о = ВЫБОР[ключ];
    /* Предел проверяем ДО загрузки. Пятьдесят мегабайт уходят минуту, и
       узнать на последней секунде, что столько нельзя, — обидно. */
    if (ф.size > о.предел * 1024 * 1024) {
      беда(ф.name + ': больше ' + о.предел + ' МБ');
      return;
    }

    var слот = вМне('нп-слот-' + ключ);
    слот.classList.add('грузится');
    var полоса = слот.querySelector('.нп-ход i');
    полоса.style.width = '0%';
    беда('');
    М.занят(true);

    CW.залить(ф, о.вид, function (п) { полоса.style.width = п + '%'; })
      .then(function (ответ) {
        М.занят(false);
        слот.classList.remove('грузится');
        положить(ключ, ответ.адрес, ф);
      })
      .catch(function (е) {
        М.занят(false);
        слот.classList.remove('грузится');
        беда(Т.с('Не загрузилось: {беда}',
                 { беда: (е && е.message) || Т('непонятно почему') }));
      });
  }

  function положить(ключ, адрес, ф) {
    var слот = вМне('нп-слот-' + ключ);
    слот.classList.add('есть');

    /* Старую картинку убираем: иначе кадры копятся друг на друге. */
    var прежний = слот.querySelector('img,video');
    if (прежний) прежний.remove();

    if (ключ === 'видео') {
      видео = адрес;
      var в = document.createElement('video');
      в.src = CW.файл(адрес);
      /* Загруженный ролик сразу крутится в окошке — без звука, по кругу.
         Стоячий первый кадр у многих роликов чёрный, и человек не
         понимал, то ли загрузилось не то, то ли не загрузилось вовсе.
         Играющий кадр отвечает на это сам. autoplay без muted браузер
         не пускает, поэтому muted обязателен, а не для красоты. */
      в.muted = true; в.playsInline = true; в.loop = true;
      в.autoplay = true; в.preload = 'auto';
      слот.appendChild(в);
      var пуск = в.play();
      if (пуск && пуск.catch) пуск.catch(function () { /* не дали — не беда */ });
    } else if (ключ === 'обложка') {
      обложка = адрес;
      var к = document.createElement('img');
      к.src = CW.файл(адрес);
      слот.appendChild(к);
    } else {
      вложение = адрес;
      вложениеИмя = ф ? ф.name : '';
      if (ф && /^image\//.test(ф.type)) {
        var с = document.createElement('img');
        с.src = CW.файл(адрес);
        слот.appendChild(с);
      } else {
        /* У документа кадра нет — показываем имя, иначе окошко пустое
           и непонятно, выбрали что-то или нет. */
        слот.classList.remove('есть');
        слот.classList.add('назван');
        слот.querySelector('.имя').textContent = ф ? ф.name : 'Файл';
        слот.querySelector('.под').textContent = Т('Файл выбран');
      }
    }
  }

  function очистить(ключ) {
    var слот = вМне('нп-слот-' + ключ);
    слот.classList.remove('есть', 'назван', 'грузится');
    var прежний = слот.querySelector('img,video');
    if (прежний) прежний.remove();
    if (ключ === 'видео') видео = '';
    else if (ключ === 'обложка') обложка = '';
    else {
      вложение = ''; вложениеИмя = '';
      слот.querySelector('.имя').textContent = Т('Прикрепи файл или фото');
      слот.querySelector('.под').textContent =
        Т('Изображение, PDF, документ · до 20 МБ');
    }
  }

  function беда(текст) {
    вМне('нп-беда').textContent = текст || '';
  }

  /* ── ЧЕРНОВИК СОХРАНЯЕТСЯ САМ ──
     Человек набрал текст, загрузил ролик и закрыл окно крестиком —
     и всё пропало. Теперь при закрытии с незаконченной записью она
     тихо ложится в черновики: вернуться к ней можно тем же значком
     папки. Опубликованное так не сохраняем — его уже нет в окне.

     Говорим об этом коротким словом внизу, а не молчим: тихая запись
     туда, куда человек не просил, должна быть видимой. */
  var ОПУБЛИКОВАЛИ = false;
  /* Склад черновиков тащим сразу, как открыли окно: при закрытии
     ждать загрузку файла уже поздно — окно закрывается тут же. */
  CW.нужен('shared/черновики.js').catch(function () {});
  function самСохранить() {
    if (ОПУБЛИКОВАЛИ || !CW.черновики) return;
    var о = собратьЧерновик();
    if (!о.заголовок && !о.описание && !о.видео && !о.вложение) return;
    /* Ничего не менялось с прошлого сохранения — второй раз не пишем. */
    if (ЧЕРНОВИК && тотЖе(ЧЕРНОВИК, о)) return;
    CW.черновики.сохранить(о);
    CW.сказать(Т('Осталось в черновиках'), 3000);
  }

  function тотЖе(а, б) {
    return а.заголовок === б.заголовок && а.описание === б.описание
        && а.видео === б.видео && а.обложка === б.обложка
        && а.вложение === б.вложение && а.теги === б.теги && а.вид === б.вид;
  }

  М.открыть();

  /* ═════════════════════════════════════════════════════════════════════
     ПУБЛИКАЦИЯ
     ═════════════════════════════════════════════════════════════════════ */
  function отправить() {
    var заголовок = вМне('нп-заголовок').value.trim();
    var музыка    = вМне('нп-музыка').value.trim();
    var описание  = вМне('нп-описание').value.trim();
    var теги      = CW.теги(вМне('нп-теги').value);

    /* ── В КАКОЙ КУБ ПУБЛИКУЕМ ──
       Раньше здесь стояло «|| 1»: не знаем куба — шлём в куб №1. Это
       выдумка вместо отказа, и пост молча уезжал к чужим людям. Куб
       берём из того, с чем модалку открыли, или из адреса страницы;
       не знаем ни того, ни другого — не публикуем и говорим прямо. */
    var куб = данные.куб || CW.какойКуб();
    if (!куб) {
      беда(Т('Не вижу, в какой куб публиковать. Открой куб и повтори.'));
      return;
    }

    var тело = {
      cube_id: куб,
      post_type: вид,
      title: заголовок,
      music: музыка,
      description: описание,
      tags: теги,
      video_url: '',
      image_url: ''
    };

    if (вид === 'short') {
      тело.video_url = видео;
      /* Обложка ложится в image_url: лента берёт заставку ролика
         оттуда. Без неё в ленте чёрный прямоугольник. */
      тело.image_url = обложка;
      if (!тело.video_url) {
        открытьРаздел('медиа');
        беда(Т('SHORT: это ролик. Загрузи видео или выбери POST.'));
        return;
      }
    } else {
      тело.image_url = вложение;
      тело.file_url = вложение;
      if (!заголовок && !описание && !вложение) {
        открытьРаздел('подпись');
        беда(Т('Добавь заголовок, текст или файл'));
        return;
      }
    }

    /* Сервер требует, чтобы хоть что-то было написано. Если человек
       заполнил только заголовок, отдаём его же: отказывать из-за
       пустого второго поля, когда первое заполнено, незачем. */
    if (!тело.description) тело.description = заголовок || '-';

    беда('');
    М.занят(true);

    CW.спросить('/feed/post', { способ: 'POST', тело: тело, сроком: 25000 })
      .then(function (ответ) {
        CW.сказать(вид === 'short' ? 'Ролик опубликован' : 'Пост опубликован');
        /* Опубликованный черновик больше не черновик: убираем, иначе
           он останется в списке и человек отправит его второй раз. */
        ОПУБЛИКОВАЛИ = true;
        if (ЧЕРНОВИК && CW.черновики) CW.черновики.убрать(ЧЕРНОВИК.ид);
        М.убрать();
        if (данные.потом) { данные.потом(ответ); return; }

        /* ── КУДА ЧЕЛОВЕКА ВЕСТИ ПОСЛЕ ПУБЛИКАЦИИ ──
           Раньше здесь был просто переход в ленту. И получалось глупо:
           человек стоял на вкладке «Шортс», опубликовал ПОСТ, лента
           открылась снова на «Шортсе» — а поста там нет, он в «Постах».
           Человек решает, что публикация не прошла.

           Теперь в адрес кладём номер новой записи. Лента по этому
           номеру сама переключится на нужную вкладку и подведёт к ней
           полосу. Номер может и не прийти — тогда ведём как прежде,
           без выдумок. */
        var н = ответ && (ответ.id || (ответ.post && ответ.post.id));
        var куда = CW.раздел('feed', CW.какойКуб());
        if (н) куда += (куда.indexOf('?') >= 0 ? '&' : '?') + 'пост=' + н;
        CW.уйти(куда);
      })
      .catch(function (е) {
        М.занят(false);
        беда(е && е.сеть ? Т('Нет связи с сервером')
                         : ((е && е.message) || Т('Не опубликовалось')));
      });
  }

  /* ═════════════════════════════════════════════════════════════════════
     ЧЕРНОВИКИ И ОТЛОЖЕННЫЕ

     Сам склад — общий файл (shared/черновики.js): он же шлёт
     отложенное по времени с любого экрана. Здесь только дверь к нему
     и перенос полей формы туда и обратно.

     Говорим прямо, где они лежат: черновик виден на этом устройстве,
     отложенная запись уходит, когда настанет время и CubeWorld
     открыт. Сервер про то и другое пока не знает.
     ═════════════════════════════════════════════════════════════════════ */
  function сЧерновиками(дальше) {
    CW.нужен('shared/черновики.js').then(дальше)
      .catch(function () { беда(Т('Черновики не приехали')); });
  }

  function собратьЧерновик() {
    return {
      ид: ЧЕРНОВИК ? ЧЕРНОВИК.ид : '',
      куб: данные.куб || CW.какойКуб(),
      вид: вид,
      видео: видео, обложка: обложка,
      вложение: вложение, вложениеИмя: вложениеИмя,
      заголовок: вМне('нп-заголовок').value.trim(),
      музыка: вМне('нп-музыка').value.trim(),
      описание: вМне('нп-описание').value.trim(),
      теги: вМне('нп-теги').value.trim(),
      когда: ЧЕРНОВИК ? ЧЕРНОВИК.когда : 0
    };
  }

  function менюЧерновиков(е, кнопка) {
    сЧерновиками(function () {
      var список = CW.черновики.список();
      var пункты = [
        { заголовок: Т('Черновики · на этом устройстве') },
        { зн: CW.значок('дискета', 16),
          подпись: Т(ЧЕРНОВИК ? 'Сохранить изменения'
                              : 'Сохранить в черновики'),
          делать: вЧерновики },
        { зн: CW.значок('часы', 16), подпись: Т('Запланировать публикацию'),
          делать: спроситьВремя }
      ];

      if (список.length) {
        пункты.push('-');
        список.slice(0, 12).forEach(function (ч) {
          пункты.push({
            зн: CW.значок(ч.когда ? 'часы' : 'лист', 16),
            подпись: имяЧерновика(ч),
            делать: function () { чтоСЧерновиком(ч); }
          });
        });
      }
      CW.лист(пункты, кнопка ? { узел: кнопка } : null);
    });
  }

  function имяЧерновика(ч) {
    var имя = ч.заголовок || ч.описание || (ч.вид === 'short' ? 'Ролик' : 'Пост');
    имя = имя.length > 28 ? имя.slice(0, 26) + '…' : имя;
    if (ч.беда) return имя + ' · не ушло: ' + ч.беда;
    if (ч.когда) return имя + ' · ' + CW.черновики.когдаСловами(ч.когда);
    return имя;
  }

  /* ── ЧТО СДЕЛАТЬ С СОХРАНЁННЫМ ──
     Нажатие на черновик раньше просто открывало его, и убрать
     ненужный было нечем: список рос и зарастал. Теперь три двери, и
     все они что-то делают. */
  function чтоСЧерновиком(ч) {
    CW.лист([
      { заголовок: имяЧерновика(ч) },
      { зн: CW.значок('карандаш', 16), подпись: Т('Открыть и править'),
        делать: function () { открытьЧерновик(ч); } },
      { зн: CW.значок('послать', 16), подпись: Т('Опубликовать сейчас'),
        делать: function () { прямоСейчас(ч); } },
      ч.когда ? { зн: CW.значок('часы', 16), подпись: Т('Снять назначенное время'),
                  делать: function () {
                    ч.когда = 0;
                    CW.черновики.сохранить(ч);
                    CW.сказать(Т('Время снято, запись осталась черновиком'), 3500);
                  } } : null,
      '-',
      { зн: CW.значок('урна', 16), подпись: Т('Убрать черновик'), опасная: true,
        делать: function () {
          CW.черновики.убрать(ч.ид);
          if (ЧЕРНОВИК && ЧЕРНОВИК.ид === ч.ид) ЧЕРНОВИК = null;
          CW.сказать(Т('Черновик убран'), 2500);
        } }
    ].filter(Boolean));
  }

  function прямоСейчас(ч) {
    М.занят(true);
    CW.черновики.опубликовать(ч)
      .then(function () {
        М.занят(false);
        ОПУБЛИКОВАЛИ = true;
        if (ЧЕРНОВИК && ЧЕРНОВИК.ид === ч.ид) ЧЕРНОВИК = null;
        CW.сказать(Т('Опубликовано'), 3000);
        М.убрать();
        CW.уйти(CW.раздел('feed', данные.куб || CW.какойКуб()));
      })
      .catch(function (е) {
        М.занят(false);
        беда((е && е.message) || Т('Не опубликовалось'));
      });
  }

  function вЧерновики() {
    сЧерновиками(function () {
      var о = собратьЧерновик();
      if (!о.заголовок && !о.описание && !о.видео && !о.вложение) {
        беда(Т('В черновик нечего класть: пусто'));
        return;
      }
      ЧЕРНОВИК = CW.черновики.сохранить(о);
      CW.сказать(о.когда ? 'Сохранено и назначено' : 'Сохранено в черновики', 3000);
    });
  }

  /* ── КОГДА ОТПРАВИТЬ ──
       Браузерное поле «дата и время» — то самое, к которому человек
       привык в своём телефоне. Своего календаря не рисуем: он был бы
       хуже и другим. */
  function спроситьВремя() {
    сЧерновиками(function () {
      var о = собратьЧерновик();
      if (о.вид === 'short' && !о.видео) {
        открытьРаздел('медиа');
        беда(Т('Отложить можно только готовую запись: загрузи видео.'));
        return;
      }
      if (о.вид !== 'short' && !о.заголовок && !о.описание && !о.вложение) {
        беда(Т('Отложить нечего: добавь текст или файл'));
        return;
      }

      var О = CW.модалка({
        имя: 'когда-публиковать', знак: 'часы',
        заголовок: Т('Запланировать'), подзаголовок: Т('когда отправить запись'),
        главная: { зн: 'галка', подсказка: Т('Назначить'), делать: назначить }
      });

      var поле = document.createElement('input');
      поле.type = 'datetime-local';
      поле.className = 'нп-строка';
      var через = new Date(Date.now() + 60 * 60 * 1000);
      поле.value = местноеВремя(через);
      поле.min = местноеВремя(new Date(Date.now() + 60 * 1000));
      О.тело.appendChild(поле);

      var слово = document.createElement('div');
      слово.className = 'нп-ред-под';
      слово.style.textAlign = 'left';
      слово.textContent =
        Т('Запись уйдёт в назначенное время, если CubeWorld открыт хотя бы ')
        + 'в одной вкладке. Закрыт: уйдёт при первом открытии после срока. '
        + 'Отправки с выключенным устройством сервер пока не умеет.';
      О.тело.appendChild(слово);

      var ряд = document.createElement('div');
      ряд.className = 'рд-ряд';
      ряд.style.marginTop = '10px';
      [['Через час', 60], ['Вечером в 19:00', -1900], ['Завтра утром', -900]]
        .forEach(function (п) {
          var б = document.createElement('button');
          б.type = 'button';
          б.className = 'кнопка рд-кн';
          б.textContent = п[0];
          б.onclick = function () { поле.value = местноеВремя(быстро(п[1])); };
          ряд.appendChild(б);
        });
      О.тело.appendChild(ряд);
      О.открыть();

      function назначить() {
        var миг = new Date(поле.value).getTime();
        if (!миг || isNaN(миг)) { CW.сказать(Т('Не разобрал время')); return; }
        if (миг < Date.now() + 30000) {
          CW.сказать(Т('Выбери время хотя бы на минуту вперёд'));
          return;
        }
        о.когда = миг;
        ЧЕРНОВИК = CW.черновики.сохранить(о);
        CW.черновики.часовой();
        О.убрать();
        CW.сказать(Т.с('Уйдёт {когда}',
                       { когда: CW.черновики.когдаСловами(миг) }), 5000);
        ОПУБЛИКОВАЛИ = true;      /* уже записано назначенным, второй раз не надо */
        М.убрать();
      }
    });
  }

  /* Поле datetime-local понимает только местное время без зоны. */
  function местноеВремя(д) {
    function два(ч) { return (ч < 10 ? '0' : '') + ч; }
    return д.getFullYear() + '-' + два(д.getMonth() + 1) + '-' + два(д.getDate())
         + 'T' + два(д.getHours()) + ':' + два(д.getMinutes());
  }

  function быстро(код) {
    var д = new Date();
    if (код > 0) return new Date(Date.now() + код * 60000);
    if (код === -1900) {
      д.setHours(19, 0, 0, 0);
      if (д.getTime() < Date.now() + 60000) д.setDate(д.getDate() + 1);
      return д;
    }
    д.setDate(д.getDate() + 1);
    д.setHours(9, 0, 0, 0);
    return д;
  }

  function открытьЧерновик(ч) {
    ЧЕРНОВИК = ч;
    поставитьВид(ч.вид || 'short');

    видео = ч.видео || '';
    обложка = ч.обложка || '';
    вложение = ч.вложение || '';
    вложениеИмя = ч.вложениеИмя || '';

    ['видео', 'обложка', 'вложение'].forEach(function (к) { очистить(к); });
    if (ч.видео)    { видео = ч.видео;       положить('видео', ч.видео, null); }
    if (ч.обложка)  { обложка = ч.обложка;   положить('обложка', ч.обложка, null); }
    if (ч.вложение) {
      вложение = ч.вложение;
      /* Картинку показываем картинкой, документ — именем: вид
         определяем по самому адресу, как и везде в программе. */
      положить('вложение', ч.вложение, {
        name: ч.вложениеИмя || '',
        type: (CW.картинкаЛи && CW.картинкаЛи(ч.вложение)) ? 'image/*' : 'application/octet-stream'
      });
    }

    вМне('нп-заголовок').value = ч.заголовок || '';
    вМне('нп-музыка').value = ч.музыка || '';
    вМне('нп-описание').value = ч.описание || '';
    вМне('нп-теги').value = ч.теги || '';

    беда(ч.беда ? Т.с('Прошлая отправка не прошла: {беда}',
                      { беда: ч.беда }) : '');
    CW.сказать(ч.когда ? ('Черновик открыт · назначен на '
                          + CW.черновики.когдаСловами(ч.когда))
                       : 'Черновик открыт', 4000);
  }

  /* Раньше окно открывало нужный раздел; теперь все открыты, и к месту
     отказа надо просто подвести глаз. */
  function открытьРаздел(ключ) {
    var р = найти(ключ);
    if (р && р.scrollIntoView) р.scrollIntoView({ block: 'nearest' });
  }

  return М;
});
