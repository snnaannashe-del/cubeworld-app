/* ═══════════════════════════════════════════════════════════════════════
   ЗАКОНЧИТЬ ЭФИР — МАЛЕНЬКОЕ ПОДТВЕРЖДЕНИЕ БЕЗ СЛОВ.

   Прежде конец эфира спрашивало общее окно «Удалить» (modals/delete.js):
   заголовок, подзаголовок, два предложения объяснения и кнопка со
   словом. Анна: «удалить весь текст, оставить как иконку 2 на 1 см,
   стильно сделать».

   Почему это можно. Общее окно нужно там, где надо НАЗВАТЬ, что
   исчезнет: удаляя группу, человек должен прочитать её имя и число
   сообщений. Здесь исчезать нечему: эфир заканчивается, разговор и
   подарки остаются на своих местах, а что именно заканчивается, видно
   прямо за окном - сам эфир.

   Поэтому здесь ровно две кнопки, обе кругляшом и обе со знаком:

       [ ■ ]  красная — закончить эфир
       [ ✕ ]  серая   — передумал

   Опасная справа или слева? В общем окне опасная стоит справа. Здесь
   наоборот: палец сам идёт к правому краю телефона, и класть под него
   конец эфира нельзя. Поэтому красная слева, уход справа, и перепутать
   их нельзя - они разного цвета и разного знака.

   Слов нет, но немые кнопки - не безымянные: у каждой есть подсказка
   (title) и имя для чтения с экрана (aria-label).

       CW.открыть('live-end', { делать: function () { … } });

   Размер окна - 100 на 50 точек, то есть ровно 2 на 1 сантиметр
   (в программе 50 точек = 1 см). Правила - в shared/window.css.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('live-end', function (данные) {
  'use strict';
  данные = данные || {};

  var М = CW.модалка({
    имя: 'эфир-конец',
    шапка: false,
    поля: false,
    узкое: true
  });

  var ряд = CW.эл('div', 'кэ-ряд');

  var конец = CW.эл('button', 'кэ-кнопка кэ-конец');
  конец.type = 'button';
  конец.title = Т('Закончить эфир');
  конец.setAttribute('aria-label', Т('Закончить эфир'));
  конец.innerHTML = CW.значок('пауза', 16);
  конец.onclick = кончить;

  var мимо = CW.эл('button', 'кэ-кнопка кэ-мимо');
  мимо.type = 'button';
  мимо.title = Т('Остаться в эфире');
  мимо.setAttribute('aria-label', Т('Остаться в эфире'));
  мимо.innerHTML = CW.значок('крест', 15);
  мимо.onclick = function () { М.закрыть(); };

  ряд.appendChild(конец);
  ряд.appendChild(мимо);
  М.тело.appendChild(ряд);

  М.открыть();

  function кончить() {
    if (!данные.делать) { М.закрыть(); return; }
    конец.disabled = true;
    мимо.disabled = true;
    Promise.resolve(данные.делать())
      .then(function (о) {
        CW.сказать(данные.сказать || 'Эфир окончен');
        М.убрать();
        if (данные.потом) данные.потом(о);
      })
      .catch(function (е) {
        конец.disabled = false;
        мимо.disabled = false;
        CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                               : ((е && е.message) || 'Не вышло закончить'));
      });
  }

  return М;
});
