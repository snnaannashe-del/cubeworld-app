/* ═══════════════════════════════════════════════════════════════════════
   ДОБАВИТЬ АККАУНТ.

       cubeworld-app/modals/add-account.js
       CW.открыть('add-account');

   Аккаунт здесь — это ключ. Ни почты, ни телефона: ключ и есть вход.
   Значит «добавить аккаунт» — это ввести другой ключ, и ничего больше.
   Поэтому в окне ровно одно поле. Кнопок внизу нет: галка в шапке —
   войти, крестик рядом — уйти. Так во всех наших окнах, и это окно не
   исключение.

   ── Почему в окне нет пояснений ───────────────────────────────────
   Они тут уже были — и в боевой, и у нас, — и оба раза их убрали.
   Поле с образцом CUBE-XXXX-XXXX-XXXX говорит само за себя, а абзац
   над ним человек всё равно не читает: он пришёл сюда вставить строку.

   ── Что уходит вместе с прежним аккаунтом ─────────────────────────
   Вход заменяется целиком, а вместе с ним вычищается всё, что лежит в
   браузере от прежнего человека: отбор кубов, избранное, недавний
   поиск, своё фото и свои действия. Иначе новый вошедший увидел бы в
   своём мире чужой Юниверс и чужие вещи — на одном ноутбуке это
   случается первым же днём.

   Оформление, язык и настройки голоса остаются: они про устройство, а
   не про человека.

   ── Прежний ключ мы не храним ─────────────────────────────────────
   В боевой список прежних ключей жил в браузере, и вернуться можно
   было одним нажатием. Мы так не делаем: ключ — это полный доступ к
   балансу и кубам, а список таких ключей в браузере значит, что все
   аккаунты забирают вместе с устройством. Человек хранит ключ там, где
   считает нужным, и вводит его сам.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('add-account', function (данные) {
  'use strict';
  данные = данные || {};

  /* Что в браузере принадлежит человеку, а не устройству, знает
     shared/auth.js: тот же список нужен и при входе другим ключом. */

  var М = CW.модалка({
    имя: 'добавить-аккаунт',
    /* Значка в шапке нет нарочно: «Добавить аккаунт» написано словами
       рядом, и человечек с плюсом повторял надпись картинкой.
       Окно вполовину уже остальных — внутри одна строка под ключ. */
    узкое: true,
    заголовок: Т('Добавить аккаунт'),
    /* Войти — значком в шапке, как во всех наших окнах, а не кнопкой
       внизу. Отмена отдельной кнопки не требует: для неё есть крестик
       рядом и нажатие мимо окна. */
    главная: { зн: 'галка', подсказка: Т('Войти'), делать: войти }
  });

  /* Поле собираем руками, а не общим сборщиком форм: тому нужна подпись
     над полем, а здесь подписи нет — только образец внутри. */
  var гнездо = document.createElement('div');
  гнездо.className = 'ок-поле';          /* общая одёжка полей — без подписи */
  М.тело.appendChild(гнездо);

  var поле = document.createElement('input');
  поле.type = 'text';
  поле.placeholder = 'CUBE-XXXX-XXXX-XXXX';
  поле.autocomplete = 'off';
  поле.spellcheck = false;
  поле.maxLength = 40;
  поле.style.cssText = 'font-family:ui-monospace,SFMono-Regular,Menlo,monospace;'
    + 'letter-spacing:.06em';
  гнездо.appendChild(поле);

  /* Отказ стоит под полем, а не всплывает внизу экрана: всплывающую
     строку человек не успевает прочитать и жмёт «Войти» ещё раз с тем
     же ключом. */
  var беда = document.createElement('div');
  беда.className = 'ок-беда';
  гнездо.appendChild(беда);

  /* Ключи у нас прописные. Переводим по ходу набора, а не при отправке:
     человек должен видеть то, что отправится. */
  поле.addEventListener('input', function () {
    var где = this.selectionStart;
    this.value = this.value.toUpperCase();
    try { this.setSelectionRange(где, где); } catch (е) {}
    беда.classList.remove('видно');
    гнездо.classList.remove('плохо');
  });
  поле.onkeydown = function (е) {
    if (е.key === 'Enter') { е.preventDefault(); войти(); }
  };

  М.открыть();
  setTimeout(function () { CW.встать(поле); }, 60);

  function сказатьБеду(текст) {
    беда.textContent = текст;
    беда.classList.add('видно');
    гнездо.classList.add('плохо');
    поле.focus();
  }

  function войти() {
    /* Ключ почти всегда приезжает в сообщении с пробелами и переносом.
       Отказывать из-за этого — мелочная придирка. */
    var ключ = String(поле.value || '').trim().replace(/\s+/g, '').toUpperCase();

    if (!ключ) { сказатьБеду('Введи ключ'); return; }
    if (ключ === String(CW.взять(CW.КЛЮЧИ.ключ) || '').toUpperCase()) {
      сказатьБеду('Это ключ нынешнего аккаунта');
      return;
    }

    беда.classList.remove('видно');
    гнездо.classList.remove('плохо');
    М.занят(true);

    CW.войти(ключ).then(function () {
      почистить();
      М.убрать();
      CW.сказать(Т('Вошли другим ключом'));
      /* В мир, а не на ту же страницу: страница могла быть кубом или
         перепиской прежнего аккаунта, и новый человек открыл бы её
         первым делом. */
      CW.уйти(CW.раздел('world'));
    }).catch(function (е) {
      М.занят(false);
      сказатьБеду(попонятнее(е));
    });
  }

  /* Сервер отвечает по-английски — переводим то, что человек увидит. */
  function попонятнее(е) {
    if (е && е.сеть) return 'Нет связи с сервером';
    var с = String((е && е.message) || '');
    if (/not found|invalid|expired|не найден/i.test(с)) {
      return 'Такого ключа нет или он больше не действует';
    }
    if (/banned|blocked|заблок/i.test(с)) return 'Этот ключ заблокирован';
    return с || 'Ключ не подошёл';
  }

  function почистить() {
    if (CW.забытьЛичное) CW.забытьЛичное();
  }

  return М;
});
