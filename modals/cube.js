/* ═══════════════════════════════════════════════════════════════════════
   CUBE КОШЕЛЁК — КОРОТКИЙ ВЗГЛЯД.

       cubeworld-app/modals/cube.js
       CW.открыть('cube');

   Открывается с жёлтой пилюли «N CUBE» в полосе мира.

   ── Зачем окно, если есть целый раздел «Кошелёк» ──────────────────
   Пилюля раньше уводила в кошелёк. Но нажимают её не затем, чтобы
   переводить и выводить, а затем, чтобы посмотреть: сколько у меня и
   сколько набежало сегодня. Ради одного взгляда человек терял мир —
   страница кошелька грузится заново, а вернуться потом нечем.

   Теперь взгляд — здесь, одним окном поверх мира.

   ── Кнопка одна ───────────────────────────────────────────────────
   Крестик в правом верхнем углу, и всё. Стрелки «в кошелёк» в шапке
   больше нет: окно — именно взгляд, а раздел «Кошелёк» лежит там же,
   где лежал, в меню у лица. Выходят отсюда крестиком, нажатием мимо
   окна и клавишей Escape — как из любого нашего окна.

   ── Полосы уровня тут нет ─────────────────────────────────────────
   Была; убрана нарочно, чтобы окно повторяло боевое один в один.
   Уровень стоит плиткой, а «сколько до следующего» — в разделе
   «Заработать», где за опытом и приходят.

   ── Откуда числа ──────────────────────────────────────────────────
   Всё с сервера, ничего из головы:
       /cube/balance   баланс, уровень, сегодня, всего заработано
       /plans          сколько кубов даёт тариф
       /me/cubes       сколько кубов уже заведено
   Не ответил сервер — так и скажем, а не покажем ноль: ноль здесь
   значит «пусто», и врать им нельзя.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('cube', function (данные) {
  'use strict';
  данные = данные || {};

  var М = CW.модалка({
    имя: 'куб-кошелёк',
    /* Значок стоит прямо у названия, одной линией и без квадрата —
       как в боевой. Подзаголовка нет: «баланс и уровень» повторяло то,
       что написано крупными числами строкой ниже. */
    знак: 'кошелёк',
    знакЦвет: '#a78bfa',
    заголовок: Т('CUBE Кошелёк')
  });

  М.открыть();
  М.занят(true);

  Promise.all([
    CW.спросить('/cube/balance', { сроком: 20000 }).catch(пусто),
    CW.спросить('/plans',        { тихо: true }).catch(пусто),
    CW.спросить('/me/cubes',     { тихо: true }).catch(пусто)
  ]).then(function (о) {
    М.занят(false);
    var б = о[0], планы = о[1], мои = о[2];

    if (!б) {
      М.пусто({ знак: 'внимание', заголовок: Т('Баланс не приехал'),
                текст: 'Сервер не ответил. Открой окно ещё раз или загляни '
                     + 'в кошелёк целиком.' });
      return;
    }

    var вид = б.key_type || 'free';
    var план = (планы && планы.plans && планы.plans[вид]) || null;
    var предел = план ? план.cubes : null;
    var кубов = рядами(мои).length;

    М.тело.innerHTML =
        '<div class="кш-тариф">'
      +   '<b>' + CW.безопасно(Т('Тариф:')) + ' '
      +   CW.безопасно(план ? Т(план.name) : названиеТарифа(вид)) + '</b>'
      /* «кубов 5 из 3» читается как поломка, а это правда: предел тарифа
         сервер пока не навязывает, и кубов может быть больше. Говорим
         тогда иначе — числом и пределом по отдельности. */
      +   '<span>' + CW.безопасно(предел == null
                     ? Т.с('кубов {н}', { н: кубов })
                     : (кубов > предел
                         ? Т.с('кубов {н} · тариф даёт {предел}',
                               { н: кубов, предел: предел })
                         : Т.с('кубов {н} из {предел}',
                               { н: кубов, предел: предел }))) + '</span>'
      + '</div>'
      + '<div class="кш-баланс">'
      +   '<span class="подпись">' + CW.безопасно(Т('Баланс')) + '</span>'
      +   '<b>' + деньги(б.balance) + '</b>'
      +   '<span class="вид">CUBE Token</span>'
      + '</div>'
      + '<div class="кш-плитки">'
      +   плитка('зелёная', деньги(б.earned_today), Т('Сегодня'))
      +   плитка('синяя',   String(б.level == null ? '-' : б.level), Т('Уровень'))
      +   плитка('',        деньги(б.earned_total), Т('Всего заработано'))
      + '</div>';
    /* Строки «CUBE можно обменять…» внизу больше нет. Окно — взгляд на
       баланс, а не рассказ о том, что такое CUBE; рассказ лежит в
       документах, в разделе про CUBE. */
  });

  /* ── мелочи ── */
  function плитка(класс, число, подпись) {
    return '<div class="кш-плитка ' + класс + '">'
         + '<b>' + CW.безопасно(число) + '</b>'
         + '<span>' + CW.безопасно(подпись) + '</span></div>';
  }

  /* Целое показываем целым: «0.00 CUBE» читается как поломка. */
  function деньги(ч) {
    var з = Number(ч || 0);
    if (!isFinite(з)) return '0';
    return Number.isInteger(з) ? з.toLocaleString('ru') : з.toFixed(2);
  }

  function названиеТарифа(в) {
    return Т({ free: 'ВИП', silver: 'Сильвер', gold: 'Голд' }[в] || в);
  }

  function рядами(о) {
    if (!о) return [];
    if (Array.isArray(о)) return о;
    if (Array.isArray(о.items)) return о.items;
    if (Array.isArray(о.cubes)) return о.cubes;
    return [];
  }

  function пусто() { return null; }

  return М;
});
