/* ═══════════════════════════════════════════════════════════════════════
   ПЕРЕСЛАТЬ СООБЩЕНИЕ.

       CW.открыть('forward', {
         текст: 'что пересылаем',
         адрес: '/uploads/ab12.jpg',   если это вложение
         вид:   'image',               его род для сервера
         имя:   'ab12.jpg',
         потом: function () {}
       });

   Окно показывает, кому можно переслать: переписки из «Чатов» и свои
   группы. Выбрал — сообщение ушло туда теми же запросами, которыми
   пишут руками (/dm/{кто} и /groups/{ид}/messages), и никаких особых
   «пересылок» на сервере для этого не нужно.

   Почему окно, а не прежняя ссылка. «Поделиться» уводило на
   chats.html?переслать=…, а эта страница про такой довод ничего не
   знала: человек приходил в список чатов и сам догадывался, что
   делать. Пустое обещание убрано, здесь оно выполняется.

   Чего тут нет: пересылки нескольким сразу. Это «Выбрать» — отдельная
   работа, и обещать её значком в этом окне нечестно.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('forward', function (данные) {
  'use strict';
  данные = данные || {};

  var М = CW.модалка({
    имя: 'переслать',
    знак: 'поделиться',
    заголовок: 'Переслать',
    подзаголовок: 'выбери, кому'
  });

  var поиск = CW.эл('input', 'переслать-поиск');
  поиск.type = 'text';
  поиск.placeholder = 'Кого ищем…';
  М.тело.appendChild(поиск);

  var список = CW.эл('div', 'переслать-список');
  М.тело.appendChild(список);

  var ВСЕ = [];

  ждём();
  Promise.all([
    CW.спросить('/dm/inbox', { тихо: true }),
    CW.спросить('/groups', { тихо: true })
  ]).then(function (о) {
    var чаты = разобрать(о[0]);
    var группы = разобрать(о[1]);

    /* Сервер отдаёт переписку строкой на каждое сообщение, и один и
       тот же человек приходит в списке несколько раз. Себя тоже
       отбрасываем: переслать самому себе — это «Избранное», и для
       него есть своё место. */
    var яСам = (CW.ясныйЯ && CW.ясныйЯ() || {}).id;
    var виделиЧата = {};

    чаты.forEach(function (ч) {
      var кто = ч.peer_id || ч.user_id || ч.id;
      if (!кто) return;
      if (Number(кто) === Number(яСам)) return;
      if (виделиЧата[кто]) return;
      виделиЧата[кто] = true;
      ВСЕ.push({
        род: 'чат', ид: кто,
        имя: CW.имяЧеловека ? CW.имяЧеловека(ч) : (ч.display_name || ('#' + кто)),
        кружок: { кто: кто }
      });
    });
    группы.forEach(function (г) {
      if (!г || !г.id) return;
      ВСЕ.push({
        род: 'группа', ид: г.id,
        имя: г.name || ('Группа #' + г.id),
        кружок: { группа: г.id, снимок: г.icon || '', значок: 'люди' }
      });
    });
    нарисовать('');
  }).catch(function () {
    список.innerHTML = '';
    var б = CW.эл('div', 'беда', 'Список не приехал');
    список.appendChild(б);
  });

  поиск.oninput = function () { нарисовать(поиск.value.trim().toLowerCase()); };

  М.открыть();
  поиск.focus();

  function ждём() {
    список.innerHTML = '';
    if (CW.ждём) CW.ждём(список);
  }

  function разобрать(о) {
    if (Array.isArray(о)) return о;
    if (!о) return [];
    return о.items || о.conversations || о.groups || о.messages || [];
  }

  function нарисовать(слово) {
    список.innerHTML = '';
    var видно = ВСЕ.filter(function (э) {
      return !слово || String(э.имя).toLowerCase().indexOf(слово) >= 0;
    });
    if (!видно.length) {
      список.appendChild(CW.эл('div', 'пусто-строка',
        слово ? 'Никого с таким именем' : 'Переписок и групп пока нет'));
      return;
    }
    видно.forEach(function (э) {
      var строка = CW.эл('button', 'переслать-строка');
      строка.type = 'button';
      строка.appendChild(CW.кружок(э.кружок));
      var т = CW.эл('div', 'нм');
      т.innerHTML = '<b>' + CW.безопасно(э.имя) + '</b>'
                  + '<span>' + (э.род === 'группа' ? 'Группа' : 'Переписка') + '</span>';
      строка.appendChild(т);
      строка.onclick = function () { отправить(э, строка); };
      список.appendChild(строка);
    });
  }

  function отправить(куда, строка) {
    строка.disabled = true;
    var тело = { content: данные.текст || данные.адрес || '' };
    if (данные.адрес) {
      тело.content = данные.адрес;
      тело.msg_type = данные.вид || 'file';
      тело.file_url = данные.адрес;
      тело.file_name = данные.имя || '';
    }
    var путь = куда.род === 'группа'
      ? '/groups/' + куда.ид + '/messages'
      : '/dm/' + куда.ид;

    CW.спросить(путь, { способ: 'POST', тело: тело, сроком: 20000 })
      .then(function () {
        CW.сказать('Переслано: ' + куда.имя, 2500);
        М.убрать();
        if (данные.потом) данные.потом(куда);
      })
      .catch(function (е) {
        строка.disabled = false;
        CW.сказать((е && е.message) || 'Не переслалось');
      });
  }

  return М;
});
