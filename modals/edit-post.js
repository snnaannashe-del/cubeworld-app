/* ═══════════════════════════════════════════════════════════════════════
   ПРАВКА ЗАПИСИ.

       cubeworld-app/modals/edit-post.js
       CW.открыть('edit-post', { пост: п, потом: function (новое) {…} });

   Сервер умеет править запись давно (PUT /feed/{id}), а окна к этому
   не было ни одного: написать пост можно было, а исправить в нём
   опечатку — нет. Отсюда это окно.

   Правим только то, что человек писал словами: заголовок, текст и
   теги. Ролик и обложку не трогаем — подменить видео под уже
   собранными лайками значит обмануть тех, кто их поставил. Нужно
   другое видео — это другая запись.

   Поля собирает общий сборщик (CW.поля): двадцать четыре формы,
   написанные по отдельности, — это двадцать четыре слегка разных
   «Названия».
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('edit-post', function (данные) {
  'use strict';
  данные = данные || {};
  var П = данные.пост || {};
  if (!П.id) { CW.сказать('Нечего править'); return null; }

  var М = CW.модалка({
    имя: 'правка-записи',
    знак: 'карандаш',
    заголовок: 'Редактировать',
    подзаголовок: 'заголовок, текст и теги',
    главная: { зн: 'галка', подсказка: 'Сохранить', делать: сохранить }
  });

  var Ф = CW.поля(М.тело, [
    { имя: 'заголовок', подпись: 'Заголовок', предел: 120 },
    { имя: 'текст', подпись: 'Текст', вид: 'много', предел: 5000 },
    { имя: 'теги', подпись: 'Теги', предел: 200 }
  ]);

  Ф.поставить({
    заголовок: П.title || '',
    текст: П.description || '',
    теги: CW.тегиСтрокой(П.tags)
  });

  М.открыть();

  function сохранить() {
    var т = String(Ф.взять('заголовок') || '').trim();
    var о = String(Ф.взять('текст') || '').trim();
    if (!т && !о) {
      CW.сказать('Пустую запись не сохранить: напиши заголовок или текст');
      return;
    }

    var новое = { title: т, description: о || т, tags: CW.теги(Ф.взять('теги')) };
    М.занят(true);

    /* Шлём все три поля сразу, даже если человек правил одно: сервер
       берёт пришедшее, а неотправленное оставляет как было. */
    CW.спросить('/feed/' + П.id, { способ: 'PUT', тело: новое, сроком: 20000 })
      .then(function () {
        CW.сказать('Исправлено');
        М.убрать();
        if (данные.потом) данные.потом(новое);
      })
      .catch(function (е) {
        М.занят(false);
        CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                               : ((е && е.message) || 'Не сохранилось'));
      });
  }

  return М;
});
