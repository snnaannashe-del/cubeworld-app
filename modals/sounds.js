/* ═══════════════════════════════════════════════════════════════════════
   ЗВУКИ: полка музыки и проигрыватель.

       CW.открыть('sounds');

   Окно состоит из двух частей, и они не равны по важности:

       СВЕРХУ — проигрыватель: имя, полоса с перемоткой, время и четыре
                кнопки. Он главный: за ним сюда и приходят.
       НИЖЕ  — полка: что ещё есть, нажал — играет.

   ── Перемотка ──────────────────────────────────────────────────────
   Полоса тащится пальцем и мышью и слушается одиночного нажатия в
   любое место. Пока браузер не узнал длину песни, перематывать некуда
   — полоса в этот момент не врёт и просто не двигается.

   ── Музыка не обрывается на закрытии ОКНА ──────────────────────────
   Сам звук живёт в shared/музыка.js, на странице, а не в этом окне.
   Закрыл окно — песня играет дальше, и это нарочно: включил и пошёл
   смотреть ленту.

   А вот крестик на самой карточке плеера — другое дело: он и прячет
   карточку, и глушит песню. После него управлять музыкой было бы
   нечем, и оставлять её играть означало бы запереть человека наедине
   со звуком без кнопок.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('sounds', function (данные) {
  'use strict';
  данные = данные || {};

  var М = CW.модалка({
    имя: 'звуки',
    знак: 'нота',
    заголовок: Т('Звуки'),
    подзаголовок: Т('спрашиваю…'),
    кнопки: [{ имя: 'залить', зн: 'скрепка', подсказка: Т('Добавить песню'),
               делать: залить }]
  });
  М.открыть();
  CW.ждём(М.тело);

  /* Поле выбора стоит в разметке с самого начала: созданное на нажатие,
     оно в части браузеров молча не сообщает о выборе. */
  var поле = document.createElement('input');
  поле.type = 'file';
  поле.accept = 'audio/*';
  поле.style.cssText =
    'position:fixed;left:0;top:0;width:1px;height:1px;opacity:0;pointer-events:none';
  document.body.appendChild(поле);
  поле.onchange = принять;

  var узлы = null;

  CW.нужен('shared/музыка.js')
    .then(function () { return CW.музыка.загрузить(); })
    .then(собрать)
    .catch(function () {
      М.пусто({ знак: 'внимание', заголовок: 'Музыка не открылась',
                текст: 'Не вышло прочитать полку. Проверь связь и открой ещё раз.' });
    });

  function собрать() {
    М.тело.innerHTML = '';
    узлы = проигрыватель();
    М.тело.appendChild(узлы.корпус);
    var полка = document.createElement('div');
    полка.className = 'му-полка';
    М.тело.appendChild(полка);
    узлы.полка = полка;

    CW.музыка.следить(обновить);
    нарисоватьПолку();
    обновить(CW.музыка.что());
  }

  /* ── проигрыватель ── */
  function проигрыватель() {
    var корпус = document.createElement('div');
    корпус.className = 'му-плеер';
    корпус.innerHTML =
        '<button type="button" class="закрыть" title="' + CW.безопасно(Т('Закрыть плеер')) + '"></button>'
      + '<div class="имя">' + CW.безопасно(Т('Ничего не играет')) + '</div>'
      + '<div class="полоса"><div class="залито"></div><div class="точка"></div></div>'
      + '<div class="время"><span class="сейчас">0:00</span>'
      + '<span class="всего">0:00</span></div>'
      + '<div class="ряд">'
      +   '<button type="button" class="кн назад" title="' + CW.безопасно(Т('Предыдущая')) + '"></button>'
      +   '<button type="button" class="кн пуск главная" title="' + CW.безопасно(Т('Играть')) + '"></button>'
      +   '<button type="button" class="кн дальше" title="' + CW.безопасно(Т('Следующая')) + '"></button>'
      + '</div>';

    var полоса = корпус.querySelector('.полоса');
    var о = {
      корпус: корпус, полоса: полоса,
      залито: корпус.querySelector('.залито'),
      точка: корпус.querySelector('.точка'),
      имя: корпус.querySelector('.имя'),
      сейчас: корпус.querySelector('.сейчас'),
      всего: корпус.querySelector('.всего'),
      пуск: корпус.querySelector('.пуск')
    };

    /* Крестик закрывает плеер: карточка прячется, музыка смолкает.
       Оставлять звук играть «где-то там» нельзя — после закрытия
       управлять им было бы нечем, и человек остался бы с песней и без
       кнопок. Вернуть плеер — кнопкой «Плеер» у любой песни.

       Здесь именно «стоп», а не «пауза». Разница появилась вместе с
       тем, что музыка переживает переход на другую страницу: после
       паузы она на следующей странице продолжится с той же секунды, а
       после крестика человек ждёт тишины. Стоп стирает закладку. */
    корпус.querySelector('.закрыть').innerHTML = CW.рисунок('M6 6 18 18M18 6 6 18');
    корпус.querySelector('.закрыть').onclick = function () {
      CW.музыка.стоп();
      корпус.classList.add('спрятан');
    };

    корпус.querySelector('.назад').innerHTML = CW.значок('песня-назад');
    корпус.querySelector('.дальше').innerHTML = CW.значок('песня-дальше');
    о.пуск.innerHTML = CW.значок('играть');

    корпус.querySelector('.назад').onclick = function () { CW.музыка.назад(); };
    корпус.querySelector('.дальше').onclick = function () { CW.музыка.дальше(); };
    о.пуск.onclick = function () {
      var что = CW.музыка.что();
      if (что.идёт) { CW.музыка.пауза(); return; }
      if (что.id) { CW.музыка.играть(что.id); return; }
      var полка = CW.музыка.полка();
      if (полка.length) CW.музыка.играть(полка[0].id);
    };

    /* ── ПЕРЕМОТКА ──
       Одно правило на палец и мышь: нажали — ведём, отпустили —
       перемотали. Пока ведём, полосу рисуем сами, иначе она дёргается
       между пальцем и песней. */
    var тащим = false;

    function доля(е) {
      var р = полоса.getBoundingClientRect();
      var x = (е.touches && е.touches[0] ? е.touches[0].clientX : е.clientX) - р.left;
      return Math.max(0, Math.min(1, x / (р.width || 1)));
    }
    function показать(д) {
      о.залито.style.width = (д * 100) + '%';
      о.точка.style.left = (д * 100) + '%';
    }
    function начать(е) {
      тащим = true; показать(доля(е)); е.preventDefault();
    }
    function вести(е) { if (тащим) показать(доля(е)); }
    function кончить(е) {
      if (!тащим) return;
      тащим = false;
      CW.музыка.перемотать(доля(е));
    }

    полоса.addEventListener('mousedown', начать);
    document.addEventListener('mousemove', вести);
    document.addEventListener('mouseup', кончить);
    полоса.addEventListener('touchstart', начать, { passive: false });
    полоса.addEventListener('touchmove', вести, { passive: true });
    полоса.addEventListener('touchend', function (е) {
      /* У touchend координат нет — берём последнее касание. */
      var т = е.changedTouches && е.changedTouches[0];
      кончить(т ? { clientX: т.clientX } : { clientX: 0 });
    });

    о.тащим = function () { return тащим; };
    о.показать = показать;
    return о;
  }

  function обновить(что) {
    if (!узлы) return;
    узлы.имя.textContent = что.имя || Т('Ничего не играет');
    узлы.пуск.innerHTML = CW.значок(что.идёт ? 'пауза' : 'играть');
    узлы.пуск.title = что.идёт ? Т('Пауза') : Т('Играть');
    узлы.сейчас.textContent = мм(что.время);
    узлы.всего.textContent = мм(что.всего);
    if (!узлы.тащим()) {
      узлы.показать(что.всего ? (что.время / что.всего) : 0);
    }
    М.имя(Т('Звуки'), строкаСчёта());
    пометить(что.id);
  }

  function строкаСчёта() {
    var н = CW.музыка.полка().length;
    if (!н) return Т('полка пуста');
    return н + ' ' + CW.склонение(н, 'песня', 'песни', 'песен');
  }

  function нарисоватьПолку() {
    var полка = CW.музыка.полка();
    узлы.полка.innerHTML = '';

    if (!полка.length) {
      var п = document.createElement('div');
      п.className = 'пусто-строка';
      п.textContent = Т('Пока нет аудиофайлов.');
      узлы.полка.appendChild(п);
      return;
    }

    полка.forEach(function (з) {
      var ряд = document.createElement('div');
      ряд.className = 'пп-ряд му-строка';
      ряд.setAttribute('data-песня', з.id);

      var знак = document.createElement('span');
      знак.className = 'пп-знак';
      знак.innerHTML = CW.значок('нота');
      ряд.appendChild(знак);

      var про = document.createElement('span');
      про.className = 'пп-про';
      про.innerHTML = '<span class="имя"></span><span class="под"></span>';
      про.querySelector('.имя').textContent = з.имя || 'Без имени';
      про.querySelector('.под').textContent = размер(з.сколько);
      ряд.appendChild(про);
      про.onclick = знак.onclick = function () {
        узлы.корпус.classList.remove('спрятан');
        CW.музыка.играть(з.id);
      };

      /* ── ЧЕТЫРЕ КНОПКИ У КАЖДОЙ ПЕСНИ ──
         Поделиться, скачать, плеер, удалить — ровно в этом порядке:
         сперва то, что отдаёт песню другим, потом то, что делает с ней
         что-то здесь, и последним — опасное. Опасное всегда с краю,
         чтобы рука не попадала в него на ходу. */
      ряд.appendChild(кнопка('поделиться', Т('Поделиться'), function () {
        CW.открыть('share', { ссылка: CW.файл(з.адрес), имя: з.имя || 'Песня' });
      }));

      ряд.appendChild(кнопка('скачать', 'Скачать', function () {
        CW.скачать(CW.файл(з.адрес), з.имя || 'песня');
      }));

      /* «Плеер» — показать карточку наверху и включить эту песню.
         Если плеер был закрыт крестиком, он возвращается. */
      ряд.appendChild(кнопка('играть', 'Плеер', function () {
        узлы.корпус.classList.remove('спрятан');
        CW.музыка.играть(з.id);
      }));

      ряд.appendChild(кнопка('крест', 'Убрать с полки', function () {
        CW.музыка.убрать(з.id);
        нарисоватьПолку();
        обновить(CW.музыка.что());
      }, true));

      узлы.полка.appendChild(ряд);
    });
    пометить(CW.музыка.что().id);
  }

  function пометить(id) {
    if (!узлы || !узлы.полка) return;
    [].slice.call(узлы.полка.querySelectorAll('.му-строка')).forEach(function (р) {
      р.classList.toggle('играет', String(р.getAttribute('data-песня')) === String(id));
    });
  }

  /* ── добавить песню ── */
  function залить() { поле.value = ''; поле.click(); }

  function принять() {
    var ф = поле.files && поле.files[0];
    if (!ф) return;
    М.занят(true);
    М.имя(Т('Звуки'), Т('везу песню…'));

    CW.залить(ф, 'audio')
      .then(function (о) {
        CW.музыка.добавить({ имя: ф.name || 'Песня', адрес: о.адрес,
                             сколько: о.размер || ф.size || 0 });
        М.занят(false);
        нарисоватьПолку();
        обновить(CW.музыка.что());
        CW.сказать(Т('Песня на полке'));
      })
      .catch(function (е) {
        М.занят(false);
        обновить(CW.музыка.что());
        CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                               : ((е && е.message) || 'Песня не уехала'));
      });
  }

  function кнопка(знак, подсказка, делать, опасная) {
    var б = document.createElement('button');
    б.type = 'button';
    б.className = 'пп-кн' + (опасная ? ' опасная' : '');
    б.innerHTML = знак === 'крест' ? CW.рисунок('M6 6 18 18M18 6 6 18')
                                   : CW.значок(знак);
    б.title = подсказка;
    б.onclick = function (е) { е.stopPropagation(); делать(); };
    return б;
  }

  function мм(с) {
    с = Math.max(0, Math.floor(Number(с) || 0));
    var м = Math.floor(с / 60), о = с % 60;
    return м + ':' + (о < 10 ? '0' : '') + о;
  }

  function размер(б) {
    б = Number(б || 0);
    if (!б) return 'на полке';
    if (б < 1024 * 1024) return Math.round(б / 1024) + ' КБ';
    return (б / 1048576).toFixed(1) + ' МБ';
  }
});
