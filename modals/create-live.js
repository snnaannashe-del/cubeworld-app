/* ═══════════════════════════════════════════════════════════════════════
   НАЧАТЬ ЭФИР.

   Окно короткое нарочно: название и три режима, больше тут решать
   нечего.

   ТРИ РЕЖИМА — ЭТО ТРИ РЕЖИМА СЕРВЕРА, и зовутся они его словами:

       куб     «Камера и кубы» — играем в кубы, зрители смотрят
       камера  «Эфир»          — обычная трансляция с камеры
       чистый  «Только голос»  — без картинки, один звук

   Прежде окно слало свои слова — camera, screen, audio. Сервер таких
   не знает и молча ставил «куб» ВСЕМ трём: что ни выбери, эфир
   заводился одинаковым. Теперь значения те же, что у сервера, и выбор
   доезжает.

   Чего пока нет: само видео принимать некому, нужен медиасервер.
   Эфир заводится, зрители видят название и имя, и об этом сказано
   вслух после кнопки — чтобы окно не разрасталось объяснениями.

       CW.открыть('create-live');
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('create-live', function (данные) {
  'use strict';
  данные = данные || {};

  var М = CW.модалка({
    имя: 'новый-эфир',
    знак: 'камера',
    заголовок: Т('Начать эфир'),
    подзаголовок: Т('прямая трансляция'),
    главная: { зн: 'камера', подсказка: Т('Завести эфир'),
               делать: завести }
  });

  var Ф = CW.поля(М.тело, [
    { имя: 'название', подпись: Т('О чём эфир'), обяз: true, предел: 80,
      намёк: 'Видно всем в списке эфиров' },
    { имя: 'вид', подпись: Т('Что показываем'), вид: 'фишки', значение: 'camera',
      пункты: [
        { знач: 'куб',    подпись: Т('Камера и кубы'), зн: 'куб' },
        { знач: 'камера', подпись: Т('Эфир'),          зн: 'камера' },
        { знач: 'чистый', подпись: Т('Только голос'),  зн: 'микрофон' }
      ] }
  ]);

  М.открыть();
  var первое = М.тело.querySelector('input');
  if (первое) первое.focus();

  function завести() {
    if (!Ф.проверить()) return;
    var з = Ф.взять();

    М.занят(true);
    CW.спросить('/streams', {
      способ: 'POST', сроком: 20000,
      тело: { title: з.название, mode: з.вид, cube_id: CW.какойКуб() || null }
    }).then(function (э) {
      /* Правду про видео говорим здесь, а не в окне: объяснение на
         четыре строки над кнопкой делало короткую форму длинной. */
      CW.сказать(Т('Эфир заведён'), 3000);
      М.убрать();
      /* Сразу открываем сам эфир: окно создания своё дело сделало, а
         человек хотел не запись в списке, а быть в эфире. */
      CW.открыть('live', { эфир: { id: э && э.id, title: з.название,
                                   mode: з.вид, user_id: (CW.ясныйЯ && CW.ясныйЯ() || {}).id },
                           свой: true, вид: з.вид });
      if (данные.потом) данные.потом(э);
    }).catch(function (е) {
      М.занят(false);
      CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                             : ((е && е.message) || Т('Эфир не завёлся')));
    });
  }

  return М;
});
