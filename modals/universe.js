/* ═══════════════════════════════════════════════════════════════════════
   МОЙ ЮНИВЕРС — какие кубы стоят в твоём мире.

   Кубов в программе много, а мир — один экран. Юниверс — это отбор:
   человек отмечает галочками те кубы, которые хочет видеть, и мир
   показывает только их.

       CW.открыть('universe', {потом: fn});   fn(список) — после отбора

   ── Две вкладки, и они разные ──────────────────────────────────────
       ВСЕ КУБЫ   всё, что открыто в мире, плюс свои. Отсюда отбирают.
       МОИ КУБЫ   только свои, включая погасшие. Здесь их ещё и удаляют.

   ── Правило пустого отбора ─────────────────────────────────────────
   Пустой список значит «показываем всё». Иначе человек, который ни
   разу не открывал это окно, смотрел бы на пустой мир и думал, что
   кубов нет. Поэтому галочки у всех и стоят, пока он не выбрал сам.

   ── Отбор запоминается дважды ──────────────────────────────────────
   В браузере (мгновенно, чтобы мир перерисовался без ожидания) и на
   сервере (/me/universe), чтобы с другого устройства мир был тот же.
   Браузер — быстро, сервер — надолго; одного мало.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('universe', function (данные) {
  'use strict';
  данные = данные || {};

  var ПАМЯТЬ = 'cw_юниверс';

  var С = {
    вкладка: 'все',
    все: [],            /* [{id, name, icon, type, life, своё}] */
    мои: [],
    отбор: взятьИзБрауэра(),
    поиск: ''
  };

  var М = CW.модалка({
    имя: 'юниверс',
    знак: 'планета',
    знакЦвет: '#6fc8e8',
    заголовок: 'Юниверс',
    кнопки: [{ имя: 'создать', зн: 'плюс', подсказка: 'Создать куб',
               делать: создатьКуб }],
    главная: { зн: 'галка', подсказка: 'Сохранить отбор', делать: сохранить }
  });

  М.тело.innerHTML =
      '<div class="юн-вкладки">'
    +   '<button type="button" class="юн-вкладка тут" data-в="все">Все кубы</button>'
    +   '<button type="button" class="юн-вкладка" data-в="мои">Мои кубы</button>'
    + '</div>'
    + '<div class="юн-поиск">'
    +   '<span class="зн">' + CW.значок('лупа') + '</span>'
    +   '<input type="text" spellcheck="false" autocomplete="off"'
    +   ' placeholder="Поиск кубов по названию…">'
    + '</div>'
    + '<div class="юн-счёт"></div>'
    + '<div class="юн-список"><div class="пусто-строка">' + CW.ждём.слово + '</div></div>';

  function где(класс) { return М.тело.querySelector('.' + класс); }

  где('юн-поиск').querySelector('input').oninput = function () {
    С.поиск = this.value;
    нарисовать();
  };

  где('юн-вкладки').onclick = function (е) {
    var б = е.target.closest('.юн-вкладка');
    if (!б) return;
    С.вкладка = б.dataset.в;
    [].slice.call(this.children).forEach(function (х) {
      х.classList.toggle('тут', х === б);
    });
    нарисовать();
  };

  М.открыть();
  собрать();

  /* ═════════════════════════════════════════════════════════════════════
     ОТКУДА БЕРЁМ КУБЫ

     Два вопроса сразу: общий список мира и свои кубы. Свои приезжают
     отдельным адресом, потому что в общем списке их нет, когда они
     погасли, — а в «Моих кубах» погасшие нужны: их удаляют.
     ═════════════════════════════════════════════════════════════════════ */
  function собрать() {
    Promise.all([
      CW.спросить('/cubes',        { тихо: true }).catch(пусто),
      CW.спросить('/me/cubes',     { тихо: true }).catch(пусто),
      CW.спросить('/me/universe',  { тихо: true }).catch(пусто)
    ]).then(function (о) {
      var все = рядами(о[0]), мои = рядами(о[1]);
      var сСервера = (о[2] && о[2].universe) || [];

      /* Сервер главнее браузера: человек мог отобрать кубы на другом
         устройстве. Но пустой ответ сервера браузерный отбор не
         затирает — иначе первый же заход с нового устройства стёр бы
         всё, что отобрано здесь. */
      if (сСервера.length) С.отбор = сСервера.map(String);

      С.мои = мои.map(вид);
      /* Свои кубы ставим первыми и не повторяем: в общем списке они
         тоже есть, пока живы. */
      var видели = {}, итог = [];
      С.мои.concat(все.map(вид)).forEach(function (к) {
        if (!к || к.id == null || видели[к.id]) return;
        видели[к.id] = true;
        итог.push(к);
      });
      С.все = итог;
      нарисовать();
    });
  }

  function пусто() { return null; }
  function рядами(о) {
    if (!о) return [];
    if (Array.isArray(о)) return о;
    return о.items || о.cubes || [];
  }

  function вид(к) {
    var осталось = (к.life_left_seconds != null) ? Number(к.life_left_seconds)
                 : null;
    return {
      id: String(к.id),
      name: к.name || ('Куб #' + к.id),
      icon: к.icon || '📦',
      цвет: к.color || '#4a9eff',
      цветЗнака: (CW.цветЗначка && CW.цветЗначка(к)) || к.color || '#4a9eff',
      type: к.type || 'public',
      /* Куб площадки — без хозяина. Такие стоят в мире сразу, пока
         человек не собрал свой отбор. */
      площадкин: к.owner_id == null,
      осталось: осталось,
      погас: (к.is_active === 0) || (осталось != null && осталось <= 0)
    };
  }

  /* ═════════════════════════════════════════════════════════════════════
     РИСУЕМ
     ═════════════════════════════════════════════════════════════════════ */
  function нарисовать() {
    var список = (С.вкладка === 'мои' ? С.мои : С.все);
    var что = CW.ровно(С.поиск.trim());
    var видно = список.filter(function (к) {
      return !что || CW.ровно(к.name).indexOf(что) >= 0;
    });

    /* Подписи под названием окна нет совсем: в шапке стоит одно слово
       «Юниверс». Где человек находится, говорят вкладки прямо под ней —
       подзаголовок повторял их другими словами, и строка уходила на то,
       что и так видно. Сколько кубов отобрано, пишет счётчик. */
    где('юн-счёт').textContent = счёт();

    var куда = где('юн-список');
    if (!список.length) {
      куда.innerHTML = '<div class="пусто-строка">'
        + (С.вкладка === 'мои'
            ? 'У тебя пока нет кубов. Создай первый, кнопка с плюсом наверху.'
            : 'Сейчас ни одного открытого куба. Создай свой.')
        + '</div>';
      return;
    }
    if (!видно.length) {
      куда.innerHTML = '<div class="пусто-строка">Ничего не нашлось. '
                     + 'Поищи по части названия.</div>';
      return;
    }

    куда.innerHTML = видно.map(карточка).join('');
  }

  /* ── ЗНАЧОК КУБА В СПИСКЕ ──
     В мире подпись куба уже рисуется нашим значком в цвете куба. Здесь
     стояли смайлы на сером квадратике — тот же куб выглядел двумя
     разными иконками, а восемь смайлов подряд ещё и разной высоты.

     В квадратике стоит тот значок, который выбрал хозяин куба. Своих
     значков линиями вместо смайла мы больше не подставляем: человек
     выбирал яблоко, а в списке оказывался ящик — пары яблоку нет,
     зато она есть у коробки по умолчанию.                            */
  function лицоКуба(к) {
    if (String(к.icon).indexOf('data:') === 0) {
      return '<img class="юн-лицо" src="' + CW.безопасно(к.icon) + '" alt="">';
    }
    /* Квадратик под значком — в цвете куба, сам значок — в своём: цвет
       значка человек выбирает отдельным меню. Смайл красится фильтром,
       цветом текста ему не укажешь. */
    var ц = к.цвет || '#4a9eff';
    var цЗн = к.цветЗнака || ц;
    var лицо = CW.значокКуба ? CW.значокКуба(к.icon)
                             : { вид: 'смайл', знак: к.icon || '📦' };
    var нутро = лицо.вид === 'линия'
      ? '<i style="color:' + CW.безопасно(цЗн) + '">' + CW.значок(лицо.имя) + '</i>'
      : '<i' + (CW.тонЗнака ? ' style="filter:' + CW.тонЗнака(цЗн) + '"' : '')
        + '>' + CW.безопасно(лицо.знак || '📦') + '</i>';
    return '<span class="юн-лицо" style="background:' + прозрачно(ц, .14)
         + ';border-color:' + прозрачно(ц, .45) + '">' + нутро + '</span>';
  }

  /* Цвет куба приходит строкой «#rrggbb». Полупрозрачный фон из него
     собираем сами: rgba() нужен, чтобы под значком просвечивало окно,
     а не лежал глухой светлый квадрат. Цвет непонятного вида отдаём
     как есть — лучше глухая заливка, чем пустое место. */
  function прозрачно(цвет, доля) {
    var м = /^#([0-9a-f]{6})$/i.exec(String(цвет).trim());
    if (!м) return цвет;
    var ч = parseInt(м[1], 16);
    return 'rgba(' + ((ч >> 16) & 255) + ',' + ((ч >> 8) & 255) + ','
         + (ч & 255) + ',' + доля + ')';
  }

  function карточка(к) {
    var отмечен = помечен(к.id);
    return '<div class="юн-куб' + (отмечен ? ' тут' : '')
         +   (к.погас ? ' погас' : '') + '" data-куб="' + к.id + '">'
      + '<div class="юн-ряд" data-жать="' + (к.погас ? '' : к.id) + '">'
      +   лицоКуба(к)
      +   '<span class="юн-про">'
      +     '<span class="юн-имя">' + CW.безопасно(к.name)
      +       (к.погас ? '<i class="юн-погас">истёк</i>' : '') + '</span>'
      +     '<span class="юн-под">'
      +       (к.type === 'private' ? 'Приватный' : 'Публичный')
      +       ' · ' + срок(к) + '</span>'
      +   '</span>'
      +   (к.погас ? '' : '<span class="юн-галка">'
           + (отмечен ? CW.значок('галка') : '') + '</span>')
      + '</div>'
      /* Дела над кубом только на своей вкладке: на общей рядом стоят
         чужие кубы, и красная кнопка у каждого — приглашение нажать
         не туда.

         Два дела в ряд: убрать человека из куба и убрать сам куб.
         «Люди» обычной кнопкой, куб — красной: куб удаляется насовсем,
         а человек всего лишь перестаёт в него входить. */
      + (С.вкладка === 'мои'
          ? '<div class="юн-дела">'
            + '<button type="button" class="юн-дело" data-люди="'
            + к.id + '">' + CW.значок('люди') + ' Убрать юзера</button>'
            + '<button type="button" class="юн-дело опасное" data-убрать="'
            + к.id + '">' + CW.значок('урна') + ' Удалить куб</button>'
            + '</div>'
          : '')
      + '</div>';
  }

  function срок(к) {
    if (к.погас) return 'истёк';
    if (к.осталось == null) return 'живёт';
    if (к.осталось > 604800) return 'навсегда';
    var ч = Math.floor(к.осталось / 3600);
    if (ч >= 24) return 'ещё ' + Math.floor(ч / 24) + ' дн.';
    if (ч >= 1)  return 'ещё ' + ч + ' ч';
    return 'ещё ' + Math.max(1, Math.floor(к.осталось / 60)) + ' мин';
  }

  /* Подпись считает разное на разных вкладках: на общей — сколько
     отобрано из всех, на своей — сколько у тебя живых и сколько из них
     в мире. Одна строка на две вкладки врала бы на одной из них. */
  function счёт() {
    if (С.вкладка === 'мои') {
      var живые = С.мои.filter(function (к) { return !к.погас; });
      var своих = живые.filter(function (к) { return помечен(к.id); }).length;
      return 'Мои активные кубы: ' + живые.length + ' · Выбрано: ' + своих;
    }
    var отмечено = С.все.filter(function (к) { return помечен(к.id); }).length;
    return 'Выбрано: ' + отмечено + ' из ' + С.все.length + ' '
         + склонение(С.все.length);
  }

  /* «из 1 куба», «из 2 кубов», «из 11 кубов». Падеж здесь родительный —
     других вариантов после «из» не бывает. */
  /* Было своё правило, и оно врало: «3 кубов» и «1 куба». Теперь
     общее — shared/ui.js. */
  function склонение(н) {
    return CW.склонение(н, 'куб', 'куба', 'кубов');
  }

  /* Пустой отбор значит «в мире стоят кубы площадки»: галочки у них, а
     не у всех подряд. Так новый человек видит восемь постоянных кубов,
     а чужие добавляет сам. */
  function помечен(ид) {
    if (С.отбор.length) return С.отбор.indexOf(String(ид)) >= 0;
    var к = С.все.concat(С.мои).filter(function (к) {
      return String(к.id) === String(ид);
    })[0];
    return !!(к && к.площадкин);
  }

  /* ═════════════════════════════════════════════════════════════════════
     НАЖАТИЯ
     ═════════════════════════════════════════════════════════════════════ */
  где('юн-список').addEventListener('click', function (е) {
    var убрать = е.target.closest('[data-убрать]');
    if (убрать) { спроситьУдаление(убрать.dataset.убрать); return; }

    var люди = е.target.closest('[data-люди]');
    if (люди) {
      var этот = (С.мои || []).filter(function (к) {
        return String(к.id) === String(люди.dataset.люди);
      })[0] || {};
      CW.открыть('cube-members', { куб: Number(люди.dataset.люди), имя: этот.name || '' });
      return;
    }

    var ряд = е.target.closest('[data-жать]');
    if (!ряд || !ряд.dataset.жать) return;
    переключить(ряд.dataset.жать);
  });

  function переключить(ид) {
    ид = String(ид);
    /* Пустой отбор — это «стоят кубы площадки». Первая же галочка
       должна добавить куб К НИМ, а не оставить в мире его одного. */
    if (!С.отбор.length) {
      С.отбор = С.все.concat(С.мои)
        .filter(function (к) { return к.площадкин; })
        .map(function (к) { return String(к.id); });
    }
    var место = С.отбор.indexOf(ид);
    if (место >= 0) С.отбор.splice(место, 1); else С.отбор.push(ид);

    /* Сохраняем сразу, не дожидаясь «Сохранить»: человек, закрывший
       окно крестиком, вправе ожидать, что его галочки остались. */
    положитьВБраузер();
    нарисовать();
  }

  /* ═════════════════════════════════════════════════════════════════════
     УДАЛЕНИЕ КУБА

     Куб уносит с собой всё, что в нём, и это не отменить. Спрашиваем не
     здесь, а общим окном подтверждения: оно называет, ЧТО исчезнет, и
     одинаково во всей программе — ломать эту привычку в таком месте
     нельзя.
     ═════════════════════════════════════════════════════════════════════ */
  function спроситьУдаление(ид) {
    var к = С.мои.filter(function (х) { return х.id === String(ид); })[0];
    if (!к) return;

    CW.открыть('delete', {
      чего: 'куб',
      что: к.name,
      ещё: 'Вместе с кубом исчезнет всё, что в нём: переписки, посты, люди. '
         + 'Те, кто сейчас внутри, выйдут в мир.',
      навсегда: true,
      сказать: 'Куб «' + к.name + '» удалён',
      делать: function () {
        return CW.спросить('/cubes/' + к.id, { способ: 'DELETE' });
      },
      потом: function () {
        С.мои = С.мои.filter(function (х) { return х.id !== к.id; });
        С.все = С.все.filter(function (х) { return х.id !== к.id; });
        С.отбор = С.отбор.filter(function (и) { return и !== к.id; });
        положитьВБраузер();
        нарисовать();
        if (данные.потом) данные.потом(С.отбор);
      }
    });
  }

  /* ═════════════════════════════════════════════════════════════════════
     СОЗДАТЬ КУБ ОТСЮДА

     Окно создания — своё, отдельное. Новый куб сразу попадает в отбор:
     человек, создавший куб, точно хочет его видеть.
     ═════════════════════════════════════════════════════════════════════ */
  function создатьКуб() {
    CW.открыть('create-cube', {
      потом: function (к) {
        if (к && к.id != null) {
          if (С.отбор.length) С.отбор.push(String(к.id));
          положитьВБраузер();
        }
        собрать();
        if (данные.потом) данные.потом(С.отбор);
      }
    });
  }

  /* ═════════════════════════════════════════════════════════════════════
     СОХРАНИТЬ
     ═════════════════════════════════════════════════════════════════════ */
  function сохранить() {
    if (!С.отбор.length) {
      /* Пустой отбор равен «показывать всё» — так и говорим, вместо
         отказа «выбери хотя бы один». */
      CW.сказать('Отмечены все кубы: мир покажет всё');
    }
    положитьВБраузер();
    М.занят(true);
    CW.спросить('/me/universe', {
      способ: 'POST', тело: { universe: С.отбор }
    }).then(function () {
      М.занят(false);
      CW.сказать('Вселенная обновлена');
      М.убрать();
      if (данные.потом) данные.потом(С.отбор);
    }).catch(function (е) {
      М.занят(false);
      /* Отбор уже лежит в браузере и уже действует. Сервер — это
         «и на другом устройстве тоже»; если он не ответил, честно
         говорим именно это, а не «не сохранилось». */
      CW.сказать(е && е.сеть
        ? 'Сохранила здесь, но до сервера не дошло, на другом устройстве '
          + 'отбор будет прежним'
        : ((е && е.message) || 'Сервер отбор не принял'));
      if (данные.потом) данные.потом(С.отбор);
    });
  }

  function взятьИзБрауэра() {
    try {
      var с = JSON.parse(CW.взять(ПАМЯТЬ) || '[]');
      return Array.isArray(с) ? с.map(String) : [];
    } catch (е) { return []; }
  }
  function положитьВБраузер() {
    try { CW.положить(ПАМЯТЬ, JSON.stringify(С.отбор)); } catch (е) {}
  }

  return М;
});
