/* ═══════════════════════════════════════════════════════════════════════
   ПОКУПКА.

   Перенесено из market.html. Одно окно на оба рода товара, потому что
   покупка у них одна, а разного — ровно две вещи:

       цифровой товар   ничего везти не надо, окно короткое;
       вещь             нужен адрес и количество, и итог надо считать.

   Три правила, вынесенные прямо в окно, а не в правила площадки.

   1. ИТОГ ВИДЕН ДО НАЖАТИЯ. Сумма, которая выясняется после кнопки, —
      это не покупка, а сюрприз.
   2. ДЕНЬГИ ЛЕЖАТ У ПЛОЩАДКИ, пока покупатель не скажет «получил».
      Сказать это должен не продавец.
   3. АДРЕС ВИДЯТ ДВОЕ. Чужой адрес — чужая тайна.

   Покупаем только за CUBE. Чужую валюту площадка держать не умеет, и
   кнопку для неё не показываем вовсе — вместо неё объяснение.

       CW.открыть('purchase', {товар: {...}, род: 'shop'|'market'});
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('purchase', function (данные) {
  'use strict';
  данные = данные || {};
  var т = данные.товар || {};
  var вещь = (данные.род || 'shop') === 'shop';
  var цена = Number(т.price || 0);
  var сколькоЕсть = Math.max(1, Number(т.qty || 1));

  /* Чужая валюта — не ошибка товара, а то, чего площадка не умеет.
     Говорим это до всего остального и кнопку не рисуем. */
  var валюта = String(т.currency || 'CUBE').toUpperCase();
  if (валюта !== 'CUBE') {
    var О = CW.модалка({
      имя: 'покупка',
      знак: 'тележка',
      заголовок: Т('Купить нельзя'),
      подзаголовок: CW.безопасно(т.title || ''),
    });
    О.пусто({
      знак: 'внимание',
      заголовок: Т('Цена не в CUBE, а в ') + валюта,
      текст: 'Площадка держит деньги у себя, пока покупатель не скажет '
           + '«получил», а держать она умеет только CUBE. '
           + 'Договаривайтесь с продавцом напрямую.'
    });
    О.открыть();
    return О;
  }

  var М = CW.модалка({
    имя: 'покупка',
    знак: 'тележка',
    заголовок: вещь ? 'Купить вещь' : 'Купить',
    подзаголовок: (т.title || '') + (цена ? ' · ' + цена + ' CUBE' : ' · даром')
                + (вещь && цена ? ' за штуку' : ''),
    главная: { зн: 'тележка', подсказка: Т('Купить'), делать: спросить }
  });

  var Ф = null;

  if (вещь) {
    Ф = CW.поля(М.тело, [
      { имя: 'сколько', подпись: Т('Сколько'), вид: 'число', значение: '1',
        шаг: '1', наим: 1, рядом: 'верх', менять: пересчитать },
      { имя: 'итого', подпись: Т('Итого'), рядом: 'верх', значение: цена + ' CUBE' },
      { имя: 'адрес', подпись: Т('Куда везти'), вид: 'много', строк: 3,
        предел: 400, обяз: true,
        намёк: 'Страна, город, улица, дом, получатель' },
      { имя: 'записка', подпись: Т('Записка продавцу'), предел: 400,
        намёк: 'Необязательно' }
    ]);
    Ф.узлы['итого'].readOnly = true;
    Ф.узлы['сколько'].max = сколькоЕсть;

    var замечание = document.createElement('div');
    замечание.className = 'подсказ';
    замечание.style.cssText = 'margin-top:4px;line-height:1.6';
    замечание.textContent = Т('Деньги лежат у площадки, пока ты не скажешь ')
      + '«получил». Адрес видят только двое: ты и продавец.';
    М.тело.appendChild(замечание);
  } else {
    var что = document.createElement('div');
    что.className = 'ок-пусто';
    что.style.cssText = 'text-align:left;padding:6px 2px';
    что.innerHTML = '<b>' + CW.безопасно(т.title || 'Товар') + '</b>'
      + CW.безопасно(т.description || '')
      + '<br><br>' + CW.безопасно(Т('После покупки откроется то, что приготовил продавец:')) + ' '
      + 'ключ, ссылка или файл. Видеть это будешь только ты.';
    М.тело.appendChild(что);
  }

  /* Сумму на значок не напишешь — она уходит в подпись окна, где
     видна всё время, пока человек правит количество. */
  М.кнопки['главная'].title = цена ? ('Купить за ' + цена + ' CUBE') : 'Забрать';
  М.открыть();

  function пересчитать() {
    var н = Math.max(1, Math.min(сколькоЕсть, Number(Ф.взять('сколько')) || 1));
    Ф.поставить({ сколько: н, итого: (цена * н) + ' CUBE' });
    М.кнопки['главная'].title = цена ? ('Купить за ' + (цена * н) + ' CUBE')
                                     : 'Забрать';
    М.имя(null, (т.title || '') + ' · ' + (цена * н) + ' CUBE'
                + (н > 1 ? ' за ' + н + ' шт.' : ''));
  }

  /* Покупка — действие с деньгами. В подтверждении называем сумму и
     что именно покупается, а не спрашиваем «точно?». */
  function спросить() {
    if (Ф && !Ф.проверить()) return;
    var сколько = вещь
      ? Math.max(1, Math.min(сколькоЕсть, Number(Ф.взять('сколько')) || 1)) : 1;
    var всего = цена * сколько;

    CW.лист([
      { заголовок: всего ? ('Списать ' + всего + ' CUBE?') : 'Забрать товар?' },
      { зн: CW.значок('тележка', 16),
        подпись: (т.title || 'товар') + (вещь && сколько > 1
                   ? ' · ' + сколько + ' шт.' : '') },
      '-',
      { зн: CW.значок('монета', 16), подпись: всего ? 'Купить' : 'Забрать',
        делать: function () { купить(сколько); } },
      { зн: CW.значок('стрелка', 16), подпись: Т('Передумать') }
    ]);
  }

  function купить(сколько) {
    М.занят(true);
    var адрес = вещь ? ('/shop/' + т.id + '/buy') : ('/market/' + т.id + '/buy');
    var тело = вещь
      ? { qty: сколько,
          address: String(Ф.взять('адрес') || '').trim(),
          note: String(Ф.взять('записка') || '').trim() }
      : null;

    CW.спросить(адрес, { способ: 'POST', сроком: 25000, тело: тело })
      .then(function (о) {
        CW.сказать(вещь ? 'Заказ оформлен: он в «Моих покупках»'
                 : (о && о.already) ? 'Этот товар уже был у тебя'
                 : 'Готово, товар твой');
        if (о && о.balance != null) CW.обновитьБаланс(о.balance);
        М.убрать();
        if (данные.потом) данные.потом(о);
      })
      .catch(function (е) {
        М.занят(false);
        CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                               : ((е && е.message) || 'Не вышло'));
      });
  }

  return М;
});
