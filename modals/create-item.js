/* ═══════════════════════════════════════════════════════════════════════
   НОВАЯ ВЕЩЬ (шопинг).

   Вещь покупают глазами, поэтому снимки здесь открыты всем — они и есть
   витрина. И вещь надо везти: отсюда количество, состояние и доставка.

   ── Что здесь было и чего не было ─────────────────────────────────
   Было: название, бренд, раздел, цена, количество, состояние, описание,
   доставка. Одной простынёй.

   Не было ничего из этого:
       СНИМКИ И РОЛИКИ    до двадцати, первый — обложка
       КУБ С ТВОИМ ИМЕНЕМ фигура, надпись и цвет на карточке
       ХАРАКТЕРИСТИКИ     материал, страна — строками «что / какое»
       РАЗМЕРЫ И ЦВЕТА    покупатель выбирает из них при покупке
       ВАЛЮТА             CUBE, USD или EUR

   Сервер всё это принимал всегда (specs, variants, shape, currency,
   /shop/{id}/media) — окно просто не спрашивало.

   ── Восемь разделов, открыт один ──────────────────────────────────
   Полей здесь под тридцать. В столбик они не помещаются ни на один
   экран, и человек листает форму, чтобы найти кнопку. Сложенные —
   окно помещается целиком, а раскрывают то, что заполняют. Первым
   открыто «Главное»: с него и начинают.

   ── Снимки ужимаем здесь ──────────────────────────────────────────
   До 1600 точек по длинной стороне. Карточка из двадцати фотографий с
   телефона весила бы сотни мегабайт, и грузилась бы соответственно.
   Ролики идут как есть, до 12 МБ.

       CW.открыть('create-item', {разделы:[…], состояния:[…], потом: fn});
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('create-item', function (данные) {
  'use strict';
  данные = данные || {};

  var РАЗДЕЛЫ = (данные.разделы && данные.разделы.length)
    ? данные.разделы : [{ id: 'other', name: 'Разное', icon: '📦', subs: [] }];
  var СОСТОЯНИЯ = (данные.состояния && данные.состояния.length)
    ? данные.состояния : [{ id: 'new', name: 'Новое' }];

  /* Список фигур здесь больше не лежит. Он один на всю программу — в
     shared/формы.js, — и рисуется тем же мешем, которым мир рисует
     куб, а вещь показывает на витрине. Прежде тут стоял свой список
     из смайлов: «🔻» и конус разные вещи, а «⬡» на одной системе
     шестиугольник, на другой кружок, — человек выбирал одно, а на
     карточке получал другое. */
  /* Красок своим списком здесь больше нет: ряд собирает общий
     CW.рядКрасок (shared/ui.js) из тех же шести, что в «Оформлении» и
     в «Цвете куба». Прежде тут лежали свои восемь, в кубе другие
     восемь — одна программа, три палитры. */
  var ПЕРВАЯ_КРАСКА = '#fbbf24';

  var МАКС_МЕДИА = 20;
  var МАКС_ФАЙЛ = 12 * 1024 * 1024;

  var С = {
    раздел: РАЗДЕЛЫ[0].id, подраздел: '',
    валюта: 'CUBE', состояние: СОСТОЯНИЯ[0].id,
    фигура: 'кристалл', цвет: ПЕРВАЯ_КРАСКА,
    снимки: [],          /* {файл, адрес, вид} — ещё не отправленные */
    свояФигура: null,    /* файл для «своё фото или видео» */
    свойства: [{ к: '', з: '' }]
  };

  /* Значок без подложки и без подзаголовка: название окна говорит всё,
     а квадрат под тележкой и строчка под названием были лишней рамой. */
  var М = CW.модалка({
    имя: 'новая-вещь',
    знак: 'тележка',
    заголовок: Т('Добавить товар'),
    главная: { зн: 'послать', подсказка: Т('Выставить'), делать: выставить }
  });

  /* ═════════════════════════════════════════════════════════════════════
     РАЗМЕТКА
     ═════════════════════════════════════════════════════════════════════ */
  М.тело.innerHTML =
      раздел('главное', 'Главное',
          метка('Название товара')
        + '<input class="вщ-строка вщ-имя" type="text" maxlength="140"'
        + ' autocomplete="off" placeholder="' + CW.безопасно(Т('Например: Куртка Gucci GG Canvas')) + '">'
        + метка('Бренд или автор')
        + '<input class="вщ-строка вщ-бренд" type="text" maxlength="60"'
        + ' autocomplete="off" placeholder="' + CW.безопасно(Т('Gucci, своя марка, твоё имя')) + '">'
        + метка('Раздел')
        + '<div class="вщ-фишки вщ-разделы"></div>'
        + метка('Подраздел')
        + '<div class="вщ-фишки вщ-подразделы"></div>')

    + раздел('цена', 'Цена и наличие',
          '<div class="вщ-пара">'
        +   '<div>' + метка('Цена')
        +     '<input class="вщ-строка вщ-цена" type="number" min="0" step="0.01"'
        +     ' placeholder="0"></div>'
        +   '<div>' + метка('В чём')
        +     '<div class="вщ-фишки вщ-валюты">'
        +       ['CUBE', 'USD', 'EUR'].map(function (в) {
                  return фишка(в, в, в === С.валюта);
                }).join('')
        +     '</div></div>'
        + '</div>'
        + метка('Сколько штук')
        + '<input class="вщ-строка вщ-сколько" type="number" min="1" step="1" value="1">'
        + метка('Состояние')
        + '<div class="вщ-фишки вщ-состояния">'
        +   СОСТОЯНИЯ.map(function (с) {
              return фишка(с.id, Т(с.name), с.id === С.состояние);
            }).join('')
        + '</div>')

    /* Абзаца про то, как ужимаются снимки, здесь больше нет: человеку,
       который выкладывает вещь, он ничего не говорит. Сама работа
       никуда не делась — снимки по-прежнему ужимаются до 1600 точек, а
       про тяжёлый ролик окно скажет красной строкой, когда он попадётся. */
    + раздел('снимки', 'Снимки и ролики',
          '<div class="вщ-медиа"></div>')

    + раздел('фигура', 'Куб с твоим именем',
          метка('Надпись на фигуре')
        + '<input class="вщ-строка вщ-надпись" type="text" maxlength="16"'
        + ' autocomplete="off" placeholder="GUCCI">'
        + '<div class="вщ-фигура">'
        +   '<div class="вщ-образец"><canvas width="200" height="200"></canvas>'
        +     '<span class="надпись"></span></div>'
        /* Плитки встают сюда, когда приедет движок форм: на каждой
           рисуется та же фигура, что встанет на карточку. */
        +   '<div class="вщ-формы"></div>'
        + '</div>'
        /* Строчки под кнопкой больше нет — убрана по просьбе. Чтобы
           знание не пропало совсем, то же сказано подсказкой самой
           кнопки: наведёшь — увидишь. */
        + '<button type="button" class="кнопка вщ-своя"'
        + ' title="' + CW.безопасно(Т('Натянется на фигуру вместо цвета. Ролик, до тридцати секунд.')) + '">'
        + '' + CW.безопасно(Т('Своё фото или видео')) + '</button>'
        + метка('Цвет')
        /* Пусто нарочно: ряд красок встаёт сюда готовым узлом ниже —
           он общий на всю программу, и рисовать его разметкой здесь
           значило бы завести четвёртую копию. */
        + '<div class="вщ-цвета"></div>')

    + раздел('описание', 'Описание',
          '<textarea class="вщ-строка вщ-описание" rows="4" maxlength="6000"'
        + ' placeholder="' + CW.безопасно(Т('Что это, в каком состоянии, что входит '
        + 'в комплект, есть ли изъяны')) + '"></textarea>')

    + раздел('свойства', 'Характеристики',
          '<div class="вщ-свойства"></div>'
        + '<button type="button" class="кнопка вщ-ещё-строка">+ '
        + CW.безопасно(Т('Добавить строку')) + '</button>')

    + раздел('варианты', 'Размеры и цвета',
          метка('Размеры')
        + '<input class="вщ-строка вщ-размеры" type="text" autocomplete="off"'
        + ' placeholder="XS, S, M, L, XL">'
        + метка('Цвета')
        + '<input class="вщ-строка вщ-цвета-текст" type="text" autocomplete="off"'
        + ' placeholder="' + CW.безопасно(Т('Чёрный, Бежевый, Красный')) + '">'
        + метка('Своя строка выбора (название)')
        + '<div class="вщ-пара">'
        +   '<input class="вщ-строка вщ-своё-имя" type="text" autocomplete="off"'
        +   ' placeholder="' + CW.безопасно(Т('Например: Объём')) + '">'
        +   '<input class="вщ-строка вщ-свои-знач" type="text" autocomplete="off"'
        +   ' placeholder="' + CW.безопасно(Т('128 ГБ, 256 ГБ')) + '">'
        + '</div>')

    + раздел('доставка', 'Доставка и возврат',
          '<textarea class="вщ-строка вщ-доставка" rows="3" maxlength="600"'
        + ' placeholder="' + CW.безопасно(Т('Откуда отправляешь, за сколько дней, '
        + 'чем, что с возвратом')) + '"></textarea>')

    + '<div class="вщ-беда"></div>';

  /* Полки — общие: сборщик и поведение лежат в shared/window.js. */
  /* Имя полки и метка поля идут через машинку: CW.разделы.рисовать()
     слова не переводит, оно только собирает разметку. Без этого окно
     «Добавить товар» на чужом языке стояло наполовину по-русски. */
  function раздел(ключ, имя, внутри) {
    return CW.разделы.рисовать(ключ, имя, внутри);
  }
  function метка(т) { return '<div class="вщ-метка">' + CW.безопасно(Т(т)) + '</div>'; }
  function фишка(знач, подпись, выбрана) {
    return '<button type="button" class="вщ-фишка' + (выбрана ? ' тут' : '')
         + '" data-з="' + знач + '">' + подпись + '</button>';
  }

  function вМне(класс) { return М.тело.querySelector('.' + класс); }

  /* ═════════════════════════════════════════════════════════════════════
     РАЗДЕЛЫ: СВЁРНУТЫ ВСЕ, ОТКРЫТ ВСЕГДА ОДИН

     Окно открывается оглавлением: восемь строк с названиями полок. Что
     раскрыл — то и лежит раскрытым. Всё поведение — в shared/window.js.
     ═════════════════════════════════════════════════════════════════════ */
  var Р = CW.разделы.завести(М.тело);
  function открытьРаздел(ключ) { Р.открыть(ключ); }

  /* ═════════════════════════════════════════════════════════════════════
     ФИШКИ: РАЗДЕЛЫ, ПОДРАЗДЕЛЫ, ВАЛЮТА, СОСТОЯНИЕ
     ═════════════════════════════════════════════════════════════════════ */
  /* Значок раздела — наша линия, та же, что на витрине (витрина её и
     присылает). Смайл остаётся запасным: если линии для раздела нет,
     лучше смайл, чем голое слово. */
  вМне('вщ-разделы').innerHTML = РАЗДЕЛЫ.map(function (р) {
    var зн = р.линия
      ? '<span class="зн">' + CW.рисунок(р.линия, 15) + '</span>'
      : (р.icon ? CW.безопасно(р.icon) + ' ' : '');
    return фишка(р.id, зн + CW.безопасно(Т(р.name)), р.id === С.раздел);
  }).join('');
  нарисоватьПодразделы();

  function нарисоватьПодразделы() {
    var р = РАЗДЕЛЫ.filter(function (х) { return х.id === С.раздел; })[0];
    var список = (р && р.subs) || [];
    var куда = вМне('вщ-подразделы');
    /* Пустая полоса «Подраздел» без единой кнопки читается как поломка —
       на её месте говорим словами, что подразделов нет. */
    куда.innerHTML = список.length
      ? список.map(function (с) {
          return фишка(с, Т(с), с === С.подраздел);
        }).join('')
      : '<span class="подсказ">' + CW.безопасно(Т('У этого раздела подразделов нет')) + '</span>';
  }

  М.тело.addEventListener('click', function (е) {
    var ф = е.target.closest('.вщ-фишка');
    if (ф) {
      var ряд = ф.parentNode;
      var один = ряд.classList.contains('вщ-подразделы')
                 && ф.classList.contains('тут');
      [].slice.call(ряд.children).forEach(function (х) {
        if (х.classList) х.classList.remove('тут');
      });
      if (!один) ф.classList.add('тут');
      var знач = один ? '' : ф.dataset.з;
      if (ряд.classList.contains('вщ-разделы')) {
        С.раздел = знач; С.подраздел = ''; нарисоватьПодразделы();
      } else if (ряд.classList.contains('вщ-подразделы')) С.подраздел = знач;
      else if (ряд.classList.contains('вщ-валюты'))      С.валюта = знач || 'CUBE';
      else if (ряд.classList.contains('вщ-состояния'))   С.состояние = знач;
      return;
    }
    var форма = е.target.closest('.вщ-форма');
    if (форма) {
      С.фигура = форма.dataset.ф;
      [].slice.call(форма.parentNode.children).forEach(function (х) {
        х.classList.toggle('тут', х === форма);
      });
      нарисоватьОбразец();
      return;
    }
    if (е.target.closest('.вщ-ещё-строка')) {
      С.свойства.push({ к: '', з: '' });
      нарисоватьСвойства();
      return;
    }
    var убрать = е.target.closest('.вщ-убрать-свойство');
    if (убрать) {
      С.свойства.splice(Number(убрать.dataset.н), 1);
      if (!С.свойства.length) С.свойства.push({ к: '', з: '' });
      нарисоватьСвойства();
      return;
    }
    if (е.target.closest('.вщ-добавить-снимок')) { полеСнимков.click(); return; }
    var снять = е.target.closest('.вщ-снять-снимок');
    if (снять) {
      var н = Number(снять.dataset.н);
      URL.revokeObjectURL(С.снимки[н].адрес);
      С.снимки.splice(н, 1);
      нарисоватьСнимки();
      return;
    }
    if (е.target.closest('.вщ-своя')) { полеФигуры.click(); return; }
  });

  /* ═════════════════════════════════════════════════════════════════════
     ОБРАЗЕЦ ФИГУРЫ

     Показываем ровно то, что встанет на карточку: ту же фигуру, тем же
     мешем, в выбранной краске, а если натянули своё фото или ролик —
     с ним. Прежде здесь стоял смайл и подпись под ним: человек выбирал
     «🔻», а на витрине получал конус, и своё фото до образца не
     доходило вовсе.

     Имя фигуры в надписи больше не подставляем: надпись — это слово
     хозяина («GUCCI»), а не название формы.
     ═════════════════════════════════════════════════════════════════════ */
  var надписьПоле = вМне('вщ-надпись');
  var своёПоказать = null;    /* Image или video со своим файлом */
  надписьПоле.oninput = нарисоватьОбразец;
  вМне('вщ-бренд').oninput = нарисоватьОбразец;

  /* Ряд красок — общий, тот же, что в «Оформлении» и в «Цвете куба».
     Радуга открывает палитру на свой цвет: она приезжает отдельным
     файлом, поэтому просим её по нажатию, а не заранее. */
  var палитраЦвета = null;
  var краскиРяд = CW.рядКрасок({
    выбран: С.цвет,
    выбрать: function (ц) {
      if (палитраЦвета) { палитраЦвета.убрать(); палитраЦвета = null; }
      С.цвет = ц;
      нарисоватьОбразец();
    },
    свой: свояКраска
  });
  вМне('вщ-цвета').appendChild(краскиРяд);

  function свояКраска() {
    if (палитраЦвета) { палитраЦвета.убрать(); палитраЦвета = null; return; }
    CW.нужен('shared/выбор-знака.js').then(function () {
      var гнездо = вМне('вщ-цвета');
      палитраЦвета = CW.палитраЦвета(гнездо.parentNode, {
        цвет: С.цвет,
        меняется: function (ц) {
          С.цвет = ц; краскиРяд.показать(ц); нарисоватьОбразец();
        },
        закрыли: function () { палитраЦвета = null; }
      });
      палитраЦвета.узел.classList.add('встрой');
      гнездо.parentNode.insertBefore(палитраЦвета.узел, гнездо.nextSibling);
    }).catch(function () { CW.сказать(Т('Палитра не приехала')); });
  }

  CW.нужен('shared/формы.js').then(function () {
    нарисоватьПлитки();
    нарисоватьОбразец();
  }).catch(function () {
    вМне('вщ-формы').innerHTML =
      '<div class="подсказ">' + CW.безопасно(Т('Фигуры не приехали. Обнови страницу.')) + '</div>';
  });

  function нарисоватьПлитки() {
    var куда = вМне('вщ-формы');
    куда.innerHTML = CW.формы.СПИСОК.map(function (ф) {
      return '<button type="button" class="вщ-форма'
           + (ф.к === С.фигура ? ' тут' : '') + '" data-ф="' + ф.к + '">'
           + '<canvas width="84" height="84"></canvas>'
           + '<span>' + CW.безопасно(Т(ф.имя)) + '</span></button>';
    }).join('');
    [].slice.call(куда.children).forEach(function (б) {
      CW.формы.образец(б.querySelector('canvas'), б.dataset.ф, С.цвет);
    });
  }

  function нарисоватьОбразец() {
    var о = вМне('вщ-образец');
    if (!о) return;
    о.style.setProperty('--свой', С.цвет);
    о.querySelector('.надпись').textContent =
      (надписьПоле.value || вМне('вщ-бренд').value || '').slice(0, 16);
    if (!CW.формы) return;
    CW.формы.образец(о.querySelector('canvas'), С.фигура, С.цвет, своёПоказать);
    /* Плитки красятся тем же цветом: выбрал золото — все фигуры
       золотые, и видно, как они будут выглядеть. */
    [].slice.call(вМне('вщ-формы').children).forEach(function (б) {
      var х = б.querySelector('canvas');
      if (х) CW.формы.образец(х, б.dataset.ф, С.цвет);
    });
  }

  /* ═════════════════════════════════════════════════════════════════════
     ХАРАКТЕРИСТИКИ
     ═════════════════════════════════════════════════════════════════════ */
  нарисоватьСвойства();

  function нарисоватьСвойства() {
    var куда = вМне('вщ-свойства');
    куда.innerHTML = С.свойства.map(function (с, н) {
      return '<div class="вщ-свойство">'
           + '<input class="вщ-строка" type="text" placeholder="' + CW.безопасно(Т('Что')) + '"'
           + ' data-к="' + н + '" value="' + CW.безопасно(с.к) + '">'
           + '<input class="вщ-строка" type="text" placeholder="' + CW.безопасно(Т('Какое')) + '"'
           + ' data-з="' + н + '" value="' + CW.безопасно(с.з) + '">'
           + '<button type="button" class="ок-кн опасная вщ-убрать-свойство"'
           + ' data-н="' + н + '" title="' + CW.безопасно(Т('Убрать')) + '">'
           + CW.рисунок('M6 6 18 18M18 6 6 18') + '</button></div>';
    }).join('');
    куда.oninput = function (е) {
      var п = е.target;
      if (п.dataset.к != null) С.свойства[Number(п.dataset.к)].к = п.value;
      if (п.dataset.з != null) С.свойства[Number(п.dataset.з)].з = п.value;
    };
  }

  /* ═════════════════════════════════════════════════════════════════════
     СНИМКИ
     ═════════════════════════════════════════════════════════════════════ */
  var полеСнимков = скрытоеПоле('image/*,video/*', true);
  var полеФигуры  = скрытоеПоле('image/*,video/*', false);
  нарисоватьСнимки();

  полеСнимков.onchange = function () {
    var взятые = [].slice.call(полеСнимков.files || []);
    полеСнимков.value = '';
    принять(взятые, 0);
  };

  полеФигуры.onchange = function () {
    var ф = полеФигуры.files && полеФигуры.files[0];
    полеФигуры.value = '';
    if (!ф) return;
    if (ф.size > МАКС_ФАЙЛ) { беда(Т('Файл тяжелее 12 МБ')); return; }
    С.свояФигура = ф;
    вМне('вщ-своя').textContent = Т('Заменить: ') + ф.name;
    беда('');
    /* Сразу натягиваем выбранный файл на образец: иначе до самой
       выкладки непонятно, что получится. */
    показатьСвоё(ф);
  };

  function показатьСвоё(файл) {
    var адрес = URL.createObjectURL(файл);
    var ролик = /^video\//.test(файл.type || '');
    var у = document.createElement(ролик ? 'video' : 'img');
    if (ролик) { у.muted = true; у.playsInline = true; у.preload = 'metadata'; }
    у[ролик ? 'onloadeddata' : 'onload'] = function () {
      своёПоказать = у;
      нарисоватьОбразец();
    };
    у.onerror = function () { URL.revokeObjectURL(адрес); };
    у.src = ролик ? (адрес + '#t=0.1') : адрес;
  }

  /* По одному и по очереди: ужать снимок — работа не мгновенная, а
     двадцать штук разом подвесили бы страницу. */
  function принять(список, н) {
    if (н >= список.length) { нарисоватьСнимки(); return; }
    if (С.снимки.length >= МАКС_МЕДИА) {
      беда(Т('Больше двадцати не влезет'));
      нарисоватьСнимки();
      return;
    }
    ужать(список[н]).then(function (ф) {
      if (ф.size > МАКС_ФАЙЛ) {
        беда('«' + (список[н].name || Т('файл')) + '» ' + Т('тяжелее 12 МБ: не беру'));
      } else {
        С.снимки.push({ файл: ф, адрес: URL.createObjectURL(ф),
                        вид: /^video\//.test(ф.type) ? 'ролик' : 'снимок' });
      }
      принять(список, н + 1);
    });
  }

  function ужать(файл) {
    return new Promise(function (готово) {
      if (!/^image\//.test(файл.type || '')) { готово(файл); return; }
      var адрес = URL.createObjectURL(файл);
      var и = new Image();
      и.onload = function () {
        var П = 1600;
        var доля = Math.min(1, П / Math.max(и.width, и.height));
        var холст = document.createElement('canvas');
        холст.width  = Math.round(и.width * доля);
        холст.height = Math.round(и.height * доля);
        холст.getContext('2d').drawImage(и, 0, 0, холст.width, холст.height);
        URL.revokeObjectURL(адрес);
        холст.toBlob(function (б) {
          готово(б ? new File([б], (файл.name || 'снимок') + '.jpg',
                              { type: 'image/jpeg' }) : файл);
        }, 'image/jpeg', 0.86);
      };
      и.onerror = function () { URL.revokeObjectURL(адрес); готово(файл); };
      и.src = адрес;
    });
  }

  function нарисоватьСнимки() {
    вМне('вщ-медиа').innerHTML =
        С.снимки.map(function (с, н) {
          return '<div class="вщ-кадр">'
               + (с.вид === 'ролик'
                   ? '<video src="' + с.адрес + '" muted playsinline></video>'
                   : '<img src="' + с.адрес + '" alt="">')
               + '<button type="button" class="вщ-снять-снимок" data-н="' + н
               + '" title="' + CW.безопасно(Т('Убрать')) + '">✕</button>'
               + (н === 0 ? '<span class="обложка">' + CW.безопасно(Т('обложка')) + '</span>' : '')
               + '</div>';
        }).join('')
      + '<button type="button" class="вщ-добавить-снимок">'
      +   CW.значок('плюс', 15) + '' + CW.безопасно(Т('Добавить')) + '</button>';
  }

  М.открыть();
  /* Курсор в название ставим только мышью: на телефоне клавиатура,
     выехавшая сама, закрывает пол-окна (shared/ui.js, CW.встать). */
  CW.встать(вМне('вщ-имя'));

  /* ═════════════════════════════════════════════════════════════════════
     ВЫСТАВЛЕНИЕ
     ═════════════════════════════════════════════════════════════════════ */
  function выставить() {
    var название = вМне('вщ-имя').value.trim();
    if (название.length < 2) {
      открытьРаздел('главное');
      беда(Т('Дай вещи название'));
      вМне('вщ-имя').focus();
      return;
    }

    /* Варианты: то, из чего покупатель выбирает при покупке. Пустые не
       шлём — пустой выбор в карточке выглядит как сломанный. */
    var варианты = {};
    var размеры = списком(вМне('вщ-размеры').value);
    var цвета   = списком(вМне('вщ-цвета-текст').value);
    if (размеры.length) варианты['Размер'] = размеры;
    if (цвета.length)   варианты['Цвет']   = цвета;
    var своёИмя = вМне('вщ-своё-имя').value.trim();
    var своиЗнач = списком(вМне('вщ-свои-знач').value);
    if (своёИмя && своиЗнач.length) варианты[своёИмя.slice(0, 40)] = своиЗнач;

    var тело = {
      title: название,
      brand: вМне('вщ-бренд').value.trim(),
      category: С.раздел || 'other',
      subcategory: С.подраздел || '',
      price: Number(вМне('вщ-цена').value || 0),
      currency: С.валюта || 'CUBE',
      condition: С.состояние || 'new',
      qty: Math.max(1, Number(вМне('вщ-сколько').value || 1)),
      description: вМне('вщ-описание').value.trim(),
      specs: С.свойства
        .filter(function (с) { return String(с.к || '').trim(); })
        .map(function (с) { return { k: с.к.trim(), v: String(с.з || '').trim() }; }),
      variants: варианты,
      shipping: вМне('вщ-доставка').value.trim(),
      shape: С.фигура,
      shape_text: надписьПоле.value.trim(),
      shape_color: С.цвет
    };

    беда('');
    М.занят(true);

    CW.спросить('/shop', { способ: 'POST', тело: тело, сроком: 30000 })
      .then(function (о) {
        var ид = (о && (о.id || (о.item && о.item.id))) || null;
        if (!ид) { готово(о, 0); return; }
        послать(ид, функцияПосле(о));
      })
      .catch(function (е) {
        М.занят(false);
        беда(е && е.сеть ? Т('Нет связи с сервером')
                         : ((е && е.message) || Т('Не вышло выставить')));
      });
  }

  function функцияПосле(о) {
    return function (ушло) { готово(о, ушло); };
  }

  /* Снимки и своя фигура уходят ПОСЛЕ создания вещи: сервер кладёт их
     по номеру, а номер появляется только когда вещь создана. */
  function послать(ид, дальше) {
    var очередь = С.снимки.slice(), ушло = 0;
    (function шаг() {
      if (!очередь.length) { своюФигуру(ид, function () { дальше(ушло); }); return; }
      var с = очередь.shift();
      М.имя(Т('Добавить товар'),
            Т.с('снимок {н} из {всего}…', { н: ушло + 1, всего: С.снимки.length }));
      var пачка = new FormData();
      пачка.append('file', с.файл, с.файл.name);
      CW.спросить('/shop/' + ид + '/media',
                  { способ: 'POST', тело: пачка, сроком: 90000 })
        .then(function () { ушло++; шаг(); })
        .catch(function () { шаг(); });
    })();
  }

  function своюФигуру(ид, дальше) {
    if (!С.свояФигура) { дальше(); return; }
    М.имя(Т('Добавить товар'), Т('фигура…'));
    var пачка = new FormData();
    пачка.append('file', С.свояФигура, С.свояФигура.name);
    CW.спросить('/shop/' + ид + '/shape-media',
                { способ: 'POST', тело: пачка, сроком: 90000 })
      .then(дальше).catch(дальше);
  }

  function готово(о, ушло) {
    CW.сказать(ушло ? Т.с('Вещь на витрине · снимков: {н}', { н: ушло })
                    : Т('Вещь на витрине'));
    С.снимки.forEach(function (с) { URL.revokeObjectURL(с.адрес); });
    М.убрать();
    if (данные.потом) данные.потом(о);
  }

  /* ═════════════════════════════════════════════════════════════════════
     МЕЛОЧЬ
     ═════════════════════════════════════════════════════════════════════ */
  function беда(текст) { вМне('вщ-беда').textContent = текст || ''; }

  function списком(строка) {
    return String(строка || '').split(',')
      .map(function (с) { return с.trim(); })
      .filter(Boolean).slice(0, 24);
  }

  /* Поле выбора лежит в разметке заранее: созданное по нажатию, оно в
     части браузеров не открывает окно выбора вовсе. */
  function скрытоеПоле(принимать, много) {
    var п = document.createElement('input');
    п.type = 'file';
    п.accept = принимать;
    if (много) п.multiple = true;
    п.style.cssText =
      'position:fixed;left:0;top:0;width:1px;height:1px;opacity:0;pointer-events:none';
    document.body.appendChild(п);
    return п;
  }

  return М;
});
