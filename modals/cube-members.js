/* ═══════════════════════════════════════════════════════════════════════
   ЛЮДИ В КУБЕ — кто заходил и кого можно убрать.

       CW.открыть('cube-members', {куб: 14, имя: 'Дидас'});

   Окно для хозяина куба. Сервер отдаёт всех, кто сейчас в кубе и кто
   бывал в нём раньше (/cubes/{id}/online), а убирает человека
   /cubes/{id}/kick. Убранный тут же получает отказ и обратно по тому
   же ключу не войдёт: вместе с ним сервер запоминает его устройство.

   ── Почему без подтверждения ───────────────────────────────────────
   Так попросила хозяйка программы: в кубе своего человека знаешь в
   лицо, и лишнее окно «точно убрать?» только мешает. Вместо него —
   строка внизу «Убран» сразу после нажатия, чтобы было видно, что
   случилось, и список, который тут же перерисовался.

   ── Почему поиск ───────────────────────────────────────────────────
   В куб заходят сотнями, а убрать надо одного. Ищем по имени, нику и
   UID: имена повторяются, UID один. Мерка та же, что у всех поисков
   программы — без регистра и без ё.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('cube-members', function (данные) {
  'use strict';
  данные = данные || {};

  var ИД  = данные.куб;
  var ИМЯ = String(данные.имя || '');

  var М = CW.модалка({
    имя: 'люди-куба',
    знак: 'люди',
    знакЦвет: '#e0484d',
    заголовок: Т('Люди в кубе'),
    подзаголовок: ИМЯ ? '«' + ИМЯ + '»' : Т('спрашиваю…')
  });
  М.открыть();

  if (!ИД) {
    М.пусто({ знак: 'внимание', заголовок: Т('Не указан куб'),
              текст: Т('Окно открыто без номера куба, '
                     + 'показывать нечего.') });
    return М;
  }

  var ЛЮДИ = [];
  var ищем = '';
  var строкаПоиска = null;

  CW.ждём(М.тело);
  собрать();

  function собрать() {
    CW.спросить('/cubes/' + ИД + '/online', { тихо: true })
      .then(function (о) {
        ЛЮДИ = рядами(о);
        нарисовать();
      })
      .catch(function (е) {
        М.пусто({
          знак: 'внимание',
          заголовок: Т(е && е.код === 403 ? 'Это не твой куб' : 'Не открылось'),
          текст: (е && е.сеть) ? Т('Нет связи с сервером')
                               : ((е && е.message) || Т('Сервер не ответил'))
        });
      });
  }

  function подходит(ч) {
    if (!ищем) return true;
    var ид = String(ч.id || '');
    /* UID тоже: поле обещает искать по нему, значит он должен быть и в
       том, по чему ищем. Сервер его в этом списке прежде не отдавал
       вовсе - добавлено вместе с ником в /cubes/{id}/online. */
    return CW.ровно([ч.display_name, ч.username, ч.uid, '#' + ид, ид].join(' '))
             .indexOf(CW.ровно(ищем)) >= 0;
  }

  /* Строка поиска появляется, когда искать есть среди чего: на троих
     она только занимает место. */
  function сделатьПоиск() {
    if (строкаПоиска) return;
    строкаПоиска = document.createElement('div');
    строкаПоиска.className = 'уч-поиск';
    строкаПоиска.innerHTML = '<span class="зн">' + CW.значок('лупа') + '</span>'
      + '<input type="text" spellcheck="false" autocomplete="off"'
      /* Подпись одна на всю программу: так же названо поле поиска
         получателя в кошельке и поиск участников группы. */
      + ' placeholder="' + CW.безопасно(Т('Имя, Ник, UID')) + '">';
    var поле = строкаПоиска.querySelector('input');
    поле.oninput = function () { ищем = поле.value.trim(); нарисовать(); };
    М.сверху(строкаПоиска);
  }

  function нарисовать() {
    /* Под заголовком и имя куба, и счёт: окно открывают из списка, где
       кубов много, и «1 человек» без имени не говорит, в каком кубе. */
    М.имя(Т('Люди в кубе'), (ИМЯ ? '«' + ИМЯ + '» · ' : '')
                       + ЛЮДИ.length + ' ' + склонение(ЛЮДИ.length));
    М.тело.innerHTML = '';

    if (!ЛЮДИ.length) {
      М.пусто({ знак: 'люди', заголовок: Т('Пока никого'),
                текст: Т('В этот куб ещё никто не заходил, кроме тебя.') });
      return;
    }
    if (ЛЮДИ.length >= 6) сделатьПоиск();

    var видно = ЛЮДИ.filter(подходит);
    if (!видно.length) {
      var у = document.createElement('div');
      у.className = 'пусто-строка';
      у.textContent = Т('Никого с таким именем среди тех, кто заходил.');
      М.тело.appendChild(у);
      return;
    }

    видно.forEach(function (ч) {
      var с = document.createElement('div');
      с.className = 'ок-строка';
      с.appendChild(CW.кружок({ размер: 38, кто: ч.id, снимок: ч.avatar_url,
                                версия: ч.avatar_ver }));

      var т = document.createElement('div');
      т.className = 'текст';
      т.innerHTML = '<b>' + CW.безопасно(CW.имяЧеловека(ч)) + '</b>'
                  + '<span>'
                  + CW.безопасно(Т(ч.is_online ? 'сейчас в кубе' : 'заходил'))
                  + ' · UID ' + CW.безопасно('#' + ч.id) + '</span>';
      if (CW.лица) CW.лица.подписать(т.querySelector('b'), ч.id, CW.имяЧеловека(ч));
      с.appendChild(т);

      var кн = document.createElement('button');
      /* Крестик сразу красный, а не только под курсором: на телефоне
         курсора нет, а кнопка убирает человека из куба. */
      кн.className = 'ок-кн опасная всегда';
      кн.type = 'button';
      кн.title = Т('Убрать из куба');
      кн.innerHTML = CW.рисунок('M6 6 18 18M18 6 6 18');
      кн.onclick = function () { убрать(ч, кн); };
      с.appendChild(кн);

      М.тело.appendChild(с);
    });
  }

  function убрать(ч, кн) {
    кн.disabled = true;
    CW.спросить('/cubes/' + ИД + '/kick', { способ: 'POST', тело: { uid: ч.id } })
      .then(function () {
        CW.сказать(Т.с('Убран: {кто}', { кто: CW.имяЧеловека(ч) }));
        ЛЮДИ = ЛЮДИ.filter(function (ч2) { return ч2.id !== ч.id; });
        нарисовать();
      })
      .catch(function (е) {
        кн.disabled = false;
        CW.сказать((е && е.message) || Т('Не вышло убрать'));
      });
  }

  function рядами(д) {
    if (!д) return [];
    var с = Array.isArray(д) ? д : (д.items || д.members || д.users || []);
    return с.filter(function (ч) { return ч && ч.id != null; });
  }

  function склонение(н) {
    /* Пятым полем — ключ для чужих словарей: по-русски «1 человек» и
       «5 человек» одно слово, а в английском нужны person и people. */
    return CW.склонение(н, 'человек', 'человека', 'человек', 'людей');
  }

  return М;
});
