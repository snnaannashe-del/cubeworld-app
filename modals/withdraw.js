/* ═══════════════════════════════════════════════════════════════════════
   ВЫВОД ДЕНЕГ.

   Половина этого окна работает, половина нет, и важно не перепутать,
   какая именно.

   РАБОТАЕТ: посчитать, сколько можно вывести, проверить, что есть куда
   (привязанный кошелёк), и собрать заявку.

   НЕ РАБОТАЕТ: отправить заявку. У сервера есть только админская
   сторона выплат (/admin/payouts) — та, где заявки одобряют. Ручки, в
   которую человек подаёт заявку, нет.

   Поэтому кнопка не притворяется. Она говорит, чего не хватает, и
   предлагает единственное честное действие: написать в поддержку.
   Молча показать «Отправлено» и потерять заявку — худшее, что можно
   сделать с чужими деньгами.

       CW.открыть('withdraw');
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('withdraw', function (данные) {
  'use strict';
  данные = данные || {};

  var баланс = 0, кошельки = [];

  var М = CW.модалка({
    имя: 'вывод',
    знак: 'кошелёк',
    заголовок: Т('Вывести'),
    подзаголовок: Т('смотрю кошелёк…')
  });
  М.открыть();
  CW.ждём(М.тело);

  Promise.all([
    CW.спросить('/cube/balance', { тихо: true }),
    CW.спросить('/wallet/my',    { тихо: true }).catch(function () { return []; })
  ]).then(function (о) {
    баланс = Number((о[0] && о[0].balance) || 0);
    кошельки = Array.isArray(о[1]) ? о[1] : [];
    нарисовать();
  }).catch(function (е) {
    М.пусто({ знак: 'внимание', заголовок: Т('Не открылось'),
              текст: (е && е.сеть) ? 'Нет связи с сервером'
                                   : ((е && е.message) || 'Сервер не ответил') });
  });

  function нарисовать() {
    М.имя(Т('Вывести'), Т.с('на счету {сколько} CUBE', { сколько: Math.round(баланс) }));
    М.тело.innerHTML = '';

    var Ф = CW.поля(М.тело, [
      { имя: 'сколько', подпись: Т('Сколько вывести'), вид: 'число',
        шаг: '1', наим: 1, намёк: String(Math.floor(баланс) || 0),
        подсказ: 'Доступно ' + Math.round(баланс) + ' CUBE' },
      { имя: 'куда', подпись: Т('Куда'), вид: кошельки.length ? 'выбор' : 'текст',
        намёк: '0x… адрес кошелька',
        значение: кошельки.length ? кошельки[0].address : '',
        пункты: кошельки.map(function (к) {
          return { знач: к.address,
                   подпись: к.address + (к.verified ? ' · проверен'
                                                    : ' · непроверен') };
        }) }
    ]);

    if (!кошельки.length) {
      var нет = document.createElement('div');
      нет.className = 'подсказ';
      нет.style.marginTop = '-6px';
      нет.innerHTML = 'Привязанных кошельков нет. ';
      var сс = document.createElement('a');
      сс.href = '#'; сс.textContent = Т('Привязать');
      сс.onclick = function (е) {
        е.preventDefault();
        М.закрыть();
        CW.открыть('wallet-link');
        return false;
      };
      нет.appendChild(сс);
      М.тело.appendChild(нет);
    }

    /* ── честная часть ── */
    var весть = document.createElement('div');
    весть.className = 'ок-пусто';
    весть.style.cssText = 'text-align:left;padding:20px 2px 4px';
    весть.innerHTML =
        '<b>' + CW.безопасно(Т('Подать заявку отсюда пока нельзя')) + '</b>'
      + 'У сервера есть только та сторона выплат, где заявки одобряют. '
      + 'Ручки, в которую заявка подаётся, ещё нет, и показать тебе '
      + '' + CW.безопасно(Т('«Отправлено», потеряв заявку, было бы хуже всего.')) + '<br><br>'
      + 'Пока напиши в поддержку и назови сумму и адрес. Всё, что нужно '
      + 'для письма, можно скопировать кнопкой ниже.';
    М.тело.appendChild(весть);

    var копия = document.createElement('button');
    копия.className = 'кнопка';
    копия.style.cssText = 'width:100%;margin-top:12px';
    копия.textContent = Т('Скопировать сумму и адрес');
    копия.onclick = function () {
      var з = Ф.взять();
      var текст = 'Вывод CUBE\nСумма: ' + (з.сколько || '-')
                + '\nАдрес: ' + (з.куда || '-')
                + '\nUID: ' + ((CW.ясныйЯ() || {}).uid || '-');
      скопировать(текст);
    };
    М.тело.appendChild(копия);
  }

  /* Буфер обмена не везде разрешён (нужен https и жест человека).
     Поэтому у копирования есть запасной путь, а не молчание. */
  function скопировать(текст) {
    CW.вбуфер(текст, Т('Скопировано'));
  }

  return М;
});
