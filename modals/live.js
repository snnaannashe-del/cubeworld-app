      /* Автор эфира стал известен только сейчас: вторая кнопка под
         эфиром знает, кому чаевые, только отсюда. */
      рисоватьДеньги();
      показать(э);
      /* Режим теперь известен — можно просить камеру (и кубы, если
         эфир с кубами). Свёрнутое окно ждёт своего часа. */
      var подложка = М.тело.closest ? М.тело.closest('.ок-подложка') : null;
