/* ═══════════════════════════════════════════════════════════════════════
   АРХИВ ЧАТОВ.

       CW.открыть('archive', { открыть: function (uid, имя) {…} });

   Здесь лежат переписки, убранные из списка. Ничего не удалено: вся
   переписка на месте, её просто не видно в чатах. Отсюда её возвращают
   одной кнопкой.

   Сам список живёт в shared/архив.js и на сервере — архив едет с
   человеком на другое устройство, а не остаётся в одном браузере.

   Нажатие по строке открывает переписку, не вынимая её из архива: часто
   нужно просто заглянуть. Вынуть — это отдельная кнопка, и она названа
   словом «Вернуть», а не значком: действие редкое, и угадывать значок
   человеку тут незачем.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('archive', function (данные) {
  'use strict';
  данные = данные || {};

  var М = CW.модалка({
    имя: 'архив',
    знак: 'архив',
    заголовок: Т('Архив'),
    подзаголовок: Т('спрашиваю…')
  });
  М.открыть();
  CW.ждём(М.тело);

  CW.нужен('shared/архив.js')
    .then(function () { return CW.архив.загрузить(); })
    .then(нарисовать)
    .catch(function () {
      М.пусто({ знак: 'внимание', заголовок: Т('Архив не открылся'),
                текст: Т('Не вышло прочитать список. Проверь связь и открой ещё раз.') });
    });

  function нарисовать() {
    var список = CW.архив.список();
    /* Пустой архив ничего не приписывает под именем: слово «пусто»
       там повторяло строку в самом окне. */
    М.имя(Т('Архив'), список.length ? счёт(список.length) : '');
    М.тело.innerHTML = '';

    if (!список.length) {
      М.тело.appendChild(ок('div', 'пусто-строка', Т('Архив пуст')));
      return;
    }

    список.forEach(function (з) {
      var ряд = ок('div', 'пп-ряд');

      var знак = ок('span', 'пп-знак');
      знак.innerHTML = CW.значок('человек');
      ряд.appendChild(знак);

      var про = ок('span', 'пп-про');
      про.innerHTML = '<span class="имя"></span><span class="под">' + CW.безопасно(Т('в архиве')) + '</span>';
      про.querySelector('.имя').textContent = з.имя || ('#' + з.uid);
      ряд.appendChild(про);
      про.onclick = знак.onclick = function () {
        М.убрать();
        if (данные.открыть) данные.открыть(з.uid, з.имя);
      };

      var вернуть = ок('button', 'пп-вернуть');
      вернуть.type = 'button';
      вернуть.textContent = Т('Вернуть');
      вернуть.onclick = function (е) {
        е.stopPropagation();
        CW.архив.вернуть(з.uid);
        нарисовать();
        CW.сказать(Т('Переписка вернулась в список'));
        if (данные.потом) данные.потом();
      };
      ряд.appendChild(вернуть);

      М.тело.appendChild(ряд);
    });
  }

  function счёт(н) {
    return н + ' ' + CW.склонение(н, 'переписка', 'переписки', 'переписок');
  }

  function ок(тег, класс, текст) { return CW.эл(тег, класс, текст); }
});
