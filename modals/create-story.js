/* ═══════════════════════════════════════════════════════════════════════
   ДОБАВИТЬ СТОРИС.

   Сторис живёт сутки и уходит. Поэтому здесь нет ни тегов, ни описания,
   ни выбора раздела: всё, что нужно, — снимок или короткий ролик и,
   если хочется, подпись.

   Файл уходит в ручку сторис целиком (multipart), она сама заводит
   запись — поэтому общая загрузка тут не используется.

       CW.открыть('create-story');
       CW.открыть('create-story', {файл: ф});   // файл уже выбран

   Окно умеет открыться с уже выбранным файлом: в чатах «+» сразу
   открывает галерею (там нажатие человека ещё живо, и браузер пускает),
   а сюда приезжает готовый снимок — и видно его, а не пустую рамку.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('create-story', function (данные) {
  'use strict';
  данные = данные || {};

  var файл = null;
  var показ = null;        /* objectURL — его надо отпускать */

  var М = CW.модалка({
    имя: 'новая-сторис',
    знак: 'огонь',
    заголовок: 'Добавить сторис',
    подзаголовок: 'видно сутки, потом исчезнет',
    при_закрытии: отпустить,
    главная: { зн: 'огонь', подсказка: 'Выложить сторис',
               делать: выложить }
  });

  var поле = document.createElement('input');
  поле.type = 'file';
  поле.accept = 'image/*,video/*';
  поле.style.cssText =
    'position:fixed;left:0;top:0;width:1px;height:1px;opacity:0;pointer-events:none';
  document.body.appendChild(поле);

  var окошко = document.createElement('button');
  окошко.type = 'button';
  окошко.className = 'за-бросок';
  окошко.style.margin = '0 0 14px';
  окошко.style.width = '100%';
  окошко.innerHTML = '<span class="зн">' + CW.значок('картинка') + '</span>'
    + '<b>Выбери снимок или ролик</b>'
    + '<span>Вертикальный 9:16 — так его увидят</span>';
  окошко.onclick = function () { поле.click(); };
  М.тело.appendChild(окошко);

  var Ф = CW.поля(М.тело, [
    { имя: 'подпись', подпись: 'Подпись', предел: 120,
      намёк: 'Необязательно' }
  ]);

  поле.onchange = function () {
    var ф = поле.files && поле.files[0];
    поле.value = '';
    принять(ф);
  };

  /* Показать выбранное. Зовётся и из своего поля выбора, и когда файл
     приехал снаружи — из чатов, где галерею открывает сам «+». */
  function принять(ф) {
    if (!ф) return;
    отпустить();
    файл = ф;
    показ = URL.createObjectURL(ф);
    окошко.innerHTML = /^video\//.test(ф.type)
      ? '<video src="' + показ + '" muted playsinline autoplay loop '
        + 'style="max-height:220px;border-radius:12px"></video>'
      : '<img src="' + показ + '" alt="" style="max-height:220px;border-radius:12px">';
    окошко.style.padding = '12px';
  }

  if (данные.файл) принять(данные.файл);

  М.открыть();

  function выложить() {
    if (!файл) { CW.сказать('Сперва выбери снимок или ролик'); return; }

    М.занят(true);
    var пачка = new FormData();
    пачка.append('file', файл);
    var подпись = String(Ф.взять('подпись') || '').trim();
    if (подпись) пачка.append('caption', подпись);

    CW.спросить('/stories', { способ: 'POST', тело: пачка, сроком: 180000 })
      .then(function (с) {
        CW.сказать('Сторис выложена: сутки её будет видно');
        М.убрать();
        if (данные.потом) данные.потом(с);
      })
      .catch(function (е) {
        М.занят(false);
        CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                               : ((е && е.message) || 'Не выложилось'));
      });
  }

  /* objectURL держит файл в памяти, пока его не отпустишь. */
  function отпустить() {
    if (показ) { try { URL.revokeObjectURL(показ); } catch (е) {} показ = null; }
  }

  return М;
});
