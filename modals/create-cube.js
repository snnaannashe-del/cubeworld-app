/* ═══════════════════════════════════════════════════════════════════════
   СОЗДАТЬ КУБ.

   Куб — это земля. У него есть лицо (значок), цвет, размер в мире и
   срок жизни. Про срок говорим прямо здесь, до создания, а не после:
   человек, который узнаёт про таймер постфактум, чувствует себя
   обманутым, и он прав.

   ── Что здесь было и чего не было ──────────────────────────────────
   Было: название, описание, двенадцать значков, шесть цветов, «кто
   может войти» и три срока.

   Не было ничего из этого:
       ВРЕМЯ ЖИЗНИ    шесть сроков, от часа до «навсегда»
       ЗНАЧОК         девяносто три, и своё фото вместо значка
       ЦВЕТ           сто двадцать восемь
       РАЗМЕР         XS…XXL — каким куб встанет в мире
       KEY 2          ключ куба показывается сразу после создания

   Значок и цвет выбирают в общем окне — shared/выбор-знака.js: восемь
   полок со смайлами, ряд цветов и «Картинка», как в боевой. Оно одно
   на весь проект: то же окно открывают значок группы и лицо в
   профиле. В самом окне стоит образец — чтобы видеть, что выбрано, не
   открывая сетку снова.

   ── Четыре свёрнутые полки ─────────────────────────────────────────
       НАЗВАНИЕ И ОПИСАНИЕ      как куб зовут
       КТО ВХОДИТ И НАСКОЛЬКО   публичный или по ключу, срок жизни
       КАК ОН ВЫГЛЯДИТ          значок, цвет, размер
       КЛЮЧ КУБА (KEY 2)        что за ключ выдадут после создания

   Семь полей в столбик — окно во весь экран, по которому надо листать
   до кнопки. Полками оно открывается оглавлением из четырёх строк.
   Полки общие: CW.разделы из shared/window.js, тот же вид, что у
   «Новой вещи» и «Игр с кубами».

   ── Про размер ─────────────────────────────────────────────────────
   Раньше размер знал только тот браузер, где куб создали: он лежал в
   его памяти. Остальные видели куб среднего размера — то есть НЕ ТОТ,
   который выбрал хозяин. Теперь размер уходит на сервер и приезжает
   всем вместе с кубом.

       CW.открыть('create-cube', {потом: fn});
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('create-cube', function (данные) {
  'use strict';
  данные = данные || {};

  /* Значок и цвет выбирают в общем окне — shared/выбор-знака.js:
     там восемь полок смайлов, ряд цветов и «Картинка». Свои списки
     отсюда ушли: их копия жила бы ещё и в группе, и в профиле. */
  /* Краски здесь не вписаны своим списком: ряд собирает общий
     CW.рядКрасок (shared/ui.js) из тех же шести красок, что стоят в
     «Оформлении». Свой список жил тут, второй такой же в цвете фигуры
     товара, третий в выборе значка — три разные палитры в одной
     программе. */
  var ПЕРВЫЙ_ЦВЕТ = '#4a9eff';
  var СПИСКИ = {};        /* что лежит в каждой строке-списке */

  var СРОКИ = [
    ['1', '1 час'], ['6', '6 часов'], ['24', '24 часа'],
    ['168', '7 дней'], ['720', '1 месяц'], ['8760', 'Навсегда']
  ];

  /* Размер — число, на которое мир умножает ребро куба. XS…XXL — это
     просто понятные имена для шести значений. */
  var РАЗМЕРЫ = [
    ['1',   'XS: Маленький'], ['1.5', 'S: Малый'],
    ['2',   'M: Средний'],    ['2.5', 'L: Большой'],
    ['3',   'XL: Огромный'],  ['3.5', 'XXL: Гигантский']
  ];

  /* Два цвета, и они разные: один у значка (плитка, на которой он
     стоит), другой у самого куба. В каждом меню выбирают свой, и
     применяется он к своей строке. */
  var С = { значок: '📦', фото: '', цвет: ПЕРВЫЙ_ЦВЕТ, цветЗначка: ПЕРВЫЙ_ЦВЕТ };

  var М = CW.модалка({
    имя: 'новый-куб',
    знак: 'алмаз',
    знакЦвет: '#7fd4c1',
    заголовок: Т('Создать куб'),
    главная: { зн: 'галка', подсказка: Т('Создать куб'), делать: создать }
  });

  /* ═════════════════════════════════════════════════════════════════════
     РАЗМЕТКА — ТРИ СВЁРНУТЫЕ ПОЛКИ

     Семь полей в столбик — это окно во весь экран, по которому надо
     листать до кнопки. Полками окно открывается оглавлением из трёх
     строк, а раскрывают ту, которую собрались менять. Сборщик полок
     общий, из shared/window.js: так же устроены «Новая вещь» и
     «Игры с кубами».

     Весть про Key 2 — четвёртая полка, последней строкой внизу: она
     ничего не спрашивает, а рассказывает, и в развёрнутом виде занимала
     под окном больше места, чем все три полки вместе.
     ═════════════════════════════════════════════════════════════════════ */
  М.тело.innerHTML =
      раздел('главное', 'Название и описание',
          метка('Название')
        /* ── ПОЧЕМУ SAFARI ПРЕДЛАГАЛ ЗДЕСЬ БАНКОВСКИЕ КАРТЫ ──
           Поле называлось cc-name. В веб-стандарте «cc-name» — это ровно
           «имя держателя карты» (cc = credit card), и Safari читает имена
           полей как подсказку. Он честно решал, что человек вводит имя с
           карты, и показывал над клавиатурой Visa и Mastercard.
           Здесь у поля нет ни имени, ни автозаполнения — только класс. */
        + '<input class="кб-строка кб-имя" type="text" maxlength="40"'
        + ' placeholder="' + CW.безопасно(Т('Мой куб')) + '" autocomplete="off" autocorrect="off"'
        + ' autocapitalize="sentences" spellcheck="false" inputmode="text"'
        + ' data-lpignore="true" data-form-type="other">'
        + '<div class="ок-беда кб-беда-имя"></div>'

        /* Описания в боевой не спрашивали — и подпись под кубом в мире
           поэтому всегда была пустой. Поле необязательное. */
        + метка('Описание')
        + '<textarea class="кб-строка кб-описание" rows="2" maxlength="200"'
        + ' placeholder="' + CW.безопасно(Т('Пара слов, о чём он')) + '"></textarea>')

    + раздел('кто', 'Кто входит и насколько',
          метка('Тип куба')
        + выбор('кб-тип', [
            ['public',  'Публичный: виден всем в мире'],
            ['private', 'Приватный: только по ключу']
          ], 'public')

        + метка('Время жизни куба')
        + выбор('кб-срок', СРОКИ, '8760'))

    + раздел('вид', 'Как он выглядит',
          метка('Иконка куба')
        + '<button type="button" class="кб-курок кб-курок-значка">'
        +   '<span class="кб-лицо кб-лицо-значка">📦</span>'
        +   '<span class="кб-что кб-что-значка">' + CW.безопасно(Т('Выбрать иконку')) + '</span>'
        +   '<span class="кб-стрелка">' + CW.значок('шеврон') + '</span>'
        + '</button>'

        /* Цвет куба выбирают прямо здесь, без отдельного окна: восемь
           кружков и девятый радужный, за которым палитра. Ради одного
           ряда кружков окно открывать незачем. */
        + метка('Цвет куба')
        + '<div class="кб-цвета"></div>'

        + метка('Размер куба')
        + выбор('кб-размер', РАЗМЕРЫ, '2'))

    + раздел('ключ', 'Ключ куба (Key 2)',
          '<div class="кб-ключ-весть">'
        +   '<b>' + CW.безопасно(Т('После создания ты получишь Key 2')) + '</b>' + CW.безопасно(Т(', ключ куба. Он действует')) + ' '
        +   CW.безопасно(Т('всё время жизни куба: поделись им с теми, кого хочешь '
                         + 'пустить внутрь. Ключ всегда можно посмотреть снова в самом кубе.'))
        + '</div>');

  /* Полки — общие: сборщик и поведение лежат в shared/window.js. */
  function раздел(ключ, имя, внутри) {
    return CW.разделы.рисовать(ключ, имя, внутри);
  }
  /* Метка переводится здесь, в одном месте: иначе Т() пришлось бы
     писать у каждой из семи подписей, и первая же забытая снова
     оставила бы в английском окне русское слово. */
  function метка(т) { return '<div class="кб-метка">' + CW.безопасно(Т(т)) + '</div>'; }
  /* ── СВОЙ ВЫБОР ВМЕСТО <select> ──
     Системный список браузер рисует сам: на маке это широкая серая
     простыня поверх окна, в которой наша тёмная программа тонет.
     Поэтому строка — обычная наша кнопка, а список открывается нашим
     же меню (CW.лист), тем самым, что висит под кружками в мире:
     тёмное, с галочкой у выбранного, по ширине кнопки.

     Значение живёт в самом узле (узел.знач), и «создать» читает его
     оттуда — так же коротко, как раньше читало select.value. */
  function выбор(класс, пункты, что) {
    СПИСКИ[класс] = пункты;
    var имя = Т((пункты.filter(function (п) { return п[0] === что; })[0] || пункты[0])[1]);
    return '<button type="button" class="кб-курок ' + класс + '" data-знач="'
         + что + '"><span class="кб-что">' + CW.безопасно(имя) + '</span>'
         + '<span class="кб-стрелка вниз">' + CW.значок('шеврон') + '</span></button>';
  }

  /* Одно нажатие на любую из трёх строк — и открывается её список. */
  М.тело.addEventListener('click', function (е) {
    var к = е.target.closest('.кб-курок');
    if (!к) return;
    var класс = Object.keys(СПИСКИ).filter(function (и) {
      return к.classList.contains(и);
    })[0];
    if (!класс) return;
    CW.лист(СПИСКИ[класс].map(function (п) {
      return { подпись: Т(п[1]), выбран: п[0] === к.dataset.знач,
               зн: п[0] === к.dataset.знач ? CW.значок('галка', 15) : '',
               делать: function () {
                 к.dataset.знач = п[0];
                 к.querySelector('.кб-что').textContent = Т(п[1]);
               } };
    }), { узел: к, поШирине: true });
  });
  function где(класс) { return М.тело.querySelector('.' + класс); }

  /* ═════════════════════════════════════════════════════════════════════
     ОБРАЗЕЦ: ЧТО ВЫБРАНО, ВИДНО БЕЗ ОТКРЫВАНИЯ СЕТКИ
     ═════════════════════════════════════════════════════════════════════ */
  var лицоЗначка = где('кб-лицо-значка');
  var рядЦветов = где('кб-цвета');
  var палитра = null;

  var краски = CW.рядКрасок({
    выбран: С.цвет,
    выбрать: function (ц) {
      if (палитра) { палитра.убрать(); палитра = null; }
      С.цвет = ц;
    },
    свой: своййЦвет
  });
  рядЦветов.appendChild(краски);

  /* Радужный кружок разворачивает палитру прямо под рядом: квадрат,
     ползунок тона, пипетка, R/G/B и строка «#». Она общая —
     shared/выбор-знака.js, та же, что в окне иконки. */
  function своййЦвет() {
    if (палитра) { палитра.убрать(); палитра = null; return; }
    CW.нужен('shared/выбор-знака.js').then(function () {
      палитра = CW.палитраЦвета(рядЦветов.parentNode, {
        цвет: С.цвет,
        меняется: function (ц) { С.цвет = ц; показатьЦвет(); },
        закрыли: function () { палитра = null; }
      });
      палитра.узел.classList.add('встрой');
      рядЦветов.parentNode.insertBefore(палитра.узел, рядЦветов.nextSibling);
    }).catch(function () { CW.сказать(Т('Палитра не приехала')); });
  }

  показатьЗначок();
  показатьЦвет();

  function показатьЗначок() {
    /* Сам смайл стоит в своём цвете — том, что выбрали в меню значка.
       Красит его тот же фильтр, что и сетку в окне выбора: что видел
       там, то и здесь. */
    лицоЗначка.style.setProperty('--тон',
      (!С.фото && CW.тонЗнака) ? CW.тонЗнака(С.цветЗначка) : 'none');
    /* Подпись в строке не повторяет выбранное: сам значок уже стоит
       слева в квадратике, и писать рядом «Выбрано: 📦» значит показать
       одну и ту же картинку дважды. Строка просто называет, что будет,
       если по ней щёлкнуть. */
    if (С.фото && CW.видеоЛи && CW.видеоЛи(С.фото)) {
      /* Ролик картинкой-подложкой не нарисуешь: ставим само видео,
         без звука и по кругу. В мире над гранью у такого куба
         по-прежнему стоит 📸: полотно роликов не натягивает. */
      лицоЗначка.style.backgroundImage = '';
      лицоЗначка.innerHTML = '<video muted loop autoplay playsinline '
        + 'style="width:100%;height:100%;object-fit:cover;display:block" '
        + 'src="' + CW.безопасно(CW.файл(С.фото)) + '"></video>';
    } else if (С.фото) {
      лицоЗначка.textContent = '';
      лицоЗначка.style.backgroundImage = 'url(' + С.фото + ')';
    } else {
      лицоЗначка.style.backgroundImage = '';
      лицоЗначка.innerHTML = '<span class="вз-зн">' + CW.безопасно(С.значок) + '</span>';
    }
  }
  /* Отметку в ряду ставит сам ряд: он знает свои краски и умеет
     показать, что цвет взят в палитре. */
  function показатьЦвет() { краски.показать(С.цвет); }

  где('кб-курок-значка').onclick = выбратьЗначок;


  /* Полки свёрнуты все: окно открывается тремя строками оглавления.
     Поле названия поэтому не трогаем — наводить курсор в спрятанное
     поле значит открыть клавиатуру в никуда. */
  var Р = CW.разделы.завести(М.тело);

  М.открыть();

  /* ═════════════════════════════════════════════════════════════════════
     ДВА МЕНЮ, И В КАЖДОМ ОКНО ЦЕЛИКОМ

     Строки две — «Иконка куба» и «Цвет куба», — и это разные меню: в
     одно заходят за лицом куба, в другое за цветом. Но окно в них
     одно и то же и полное, как в боевой: полки со смайлами, сетка,
     ряд цветов внизу, «Картинка» и «Готово» значками в шапке. Человек,
     зашедший за цветом, тут же видит и значок, и наоборот — ходить
     между двумя окнами, чтобы собрать одно лицо, не нужно.

     Своё фото ужимаем до 64 точек: значок рисуется на грани куба
     размером с ноготь, и полная фотография ехала бы в каждом списке
     кубов.
     ═════════════════════════════════════════════════════════════════════ */
  function окноВыбора(что) {
    CW.нужен('shared/выбор-знака.js').then(function () {
      CW.выборЗнака(что);
    }).catch(function () { CW.сказать(Т('Окно выбора не приехало')); });
  }

  /* ── ИКОНКА КУБА ──
     Полное окно: полки со смайлами, сетка, «Картинка» и ряд цветов.
     Цвет здесь свой — им красится плитка значка, а не куб. */
  function выбратьЗначок() {
    окноВыбора({
      заголовок: Т('Иконка куба'),
      знак: С.фото ? '' : С.значок,
      цвет: С.цветЗначка,
      цвета: true,
      фото: true,
      видео: true,
      сторона: 64,
      потом: function (о) {
        if (о.фото) С.фото = о.фото;
        else if (о.значок) { С.значок = о.значок; С.фото = ''; }
        if (о.цвет) С.цветЗначка = о.цвет;
        показатьЗначок();
      }
    });
  }

  /* ═════════════════════════════════════════════════════════════════════
     СОЗДАТЬ
     ═════════════════════════════════════════════════════════════════════ */
  function создать() {
    var имя = где('кб-имя').value.trim();
    /* Длину считаем по знакам, а не по длине строки: один смайл — это
       два-четыре «символа» в памяти браузера, и человек, набравший
       десять смайлов, получал отказ «слишком длинно». */
    var длина = Array.from(имя).length;
    var беда = где('кб-беда-имя');

    /* Беда пишется внутри полки «Название и описание». Если она свёрнута,
       человек увидел бы, что кнопка не работает, и ни слова почему —
       поэтому полку раскрываем сами. */
    if (!длина) {
      беда.textContent = Т('Введи название куба: от 1 до 40 знаков');
      беда.classList.add('видно');
      Р.открыть('главное');
      где('кб-имя').focus();
      return;
    }
    if (длина > 40) {
      беда.textContent = Т('Название слишком длинное: максимум 40 знаков ')
                       + '(сейчас ' + длина + ')';
      беда.classList.add('видно');
      Р.открыть('главное');
      return;
    }
    беда.classList.remove('видно');

    var часы = parseInt(где('кб-срок').dataset.знач, 10) || 24;
    var тело = {
      name: имя,
      description: где('кб-описание').value.trim().slice(0, 200),
      icon: С.фото || С.значок,
      color: С.цвет,
      /* Цвет значка едет отдельно от цвета куба: это два разных меню и
         два разных цвета. Раньше он оставался в этом браузере, и в мире
         значок красился цветом куба — не тем, который выбрали. */
      icon_color: С.цветЗначка || '',
      type: где('кб-тип').dataset.знач === 'private' ? 'private' : 'public',
      life_hours: часы,
      size: parseFloat(где('кб-размер').dataset.знач) || 2
    };

    М.занят(true);
    CW.спросить('/cubes', { способ: 'POST', сроком: 25000, тело: тело })
      .then(function (к) {
        М.убрать();
        /* Пока сервер старый и поле icon_color выбрасывает, цвет значка
           помнит этот браузер: иначе человек выбрал цвет, а в мире
           обычный смайл. */
        if (к && к.id && CW.цветЗначка) CW.цветЗначка.запомнить(к.id, С.цветЗначка);
        /* Свой куб сразу отмечаем в Юниверсе: человек его только что
           сделал, значит хочет видеть. Пустой отбор при этом остаётся
           пустым — он и так значит «показываем всё». */
        if (к && к.id && CW.вЮниверс) CW.вЮниверс(к.id);
        if (данные.потом) данные.потом(к);
        /* Ключ куба показываем сразу: другого места, где человек его
           увидит в первый раз, нет, а без ключа в закрытый куб не
           войдёт никто, включая тех, кого он позвал. */
        if (к && к.cube_key) {
          CW.открыть('cube-key', {
            создан: true,
            ключ: к.cube_key, имя: имя, часы: часы,
            значок: тело.icon, цветЗначка: С.цветЗначка, куб: к.id
          });
        } else {
          CW.сказать(Т.с('Куб «{имя}» создан', { имя: имя }));
          if (!данные.потом && к && к.id) CW.уйти(CW.раздел('feed', к.id));
        }
      })
      .catch(function (е) {
        М.занят(false);
        /* 402 — это не поломка, а предел тарифа, и сервер присылает
           внятную строку. Её и показываем, а не «куб не создался». */
        CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                               : ((е && е.message) || Т('Куб не создался')));
      });
  }

  return М;
});
