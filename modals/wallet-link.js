/* ═══════════════════════════════════════════════════════════════════════
   ПРИВЯЗАТЬ КОШЕЛЁК.

   Сама плитка кошельков живёт в shared/wallets.js и стоит на двух
   экранах. Здесь она же, но окном поверх — чтобы привязать кошелёк
   можно было из любого места, где это вдруг понадобилось: из вывода,
   из свайпа, из заработка.

   Про подпись. Её делает сам кошелёк, мы её только передаём серверу.
   Денег это не трогает: выплата уходит на адрес из заявки, а не на
   привязанный. Адрес без подписи сервер хранит как «непроверен» — так
   его и показываем, а не выдаём за проверенный.

       CW.открыть('wallet-link');
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('wallet-link', function (данные) {
  'use strict';
  данные = данные || {};

  var М = CW.модалка({
    имя: 'кошелёк',
    знак: 'кошелёк',
    заголовок: Т('Кошельки'),
    подзаголовок: Т('привязать адрес для выплат')
  });

  /* Кусок кошельков живёт в shared/wallets.js и стоит на двух экранах.
     Лента его не грузит — значит, подтягиваем сами. */
  М.тело.innerHTML = '<div class="пусто-строка">' + CW.безопасно(Т('Загрузка…')) + '</div>';
  CW.нужен('shared/wallets.js').then(function () {
    М.тело.innerHTML = '';
    М.тело.appendChild(CW.кусокКошельков());
    М.тело.appendChild(хвост);
  }).catch(function () {
    М.пусто({ знак: 'внимание', заголовок: Т('Не открылось'),
              текст: Т('Кусок кошельков не приехал. Попробуй обновить страницу.') });
  });

  var хвост = document.createElement('div');
  хвост.className = 'подсказ';
  хвост.style.cssText = 'margin-top:14px;line-height:1.65';
  хвост.textContent = Т('Привязка ничего не списывает и не даёт нам доступа к '
    + 'твоим деньгам: кошелёк только подписывает строчку, подтверждая, что '
    + 'адрес твой. Выплата всё равно уходит на адрес, указанный в заявке.');
  М.открыть();
  return М;
});
