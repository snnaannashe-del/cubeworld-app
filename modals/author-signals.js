/* ═══════════════════════════════════════════════════════════════════════
   АВТОР СИГНАЛОВ — чем он торговал и что из этого вышло.

       CW.открыть('author-signals', {кто: 12, имя: 'Kriga'});

   Открывается нажатием на автора в карточке сигнала. В карточке о нём
   одна строчка — «закр. 7»; всё остальное здесь.

   Два запроса:
       /signals/authors/{кто}            имя, счёт подписчиков, статистика
       /signals/authors/{кто}/signals    его сигналы, последние тридцать

   ── Чего здесь нарочно нет ─────────────────────────────────────────
   Придуманных процентов. Сервер отдаёт win_rate = null, пока закрытых
   сигналов меньше двадцати, и мы пишем прочерк с подписью «процент
   после 20 закрытых», а не считаем проценты от трёх сделок. По трём
   сделкам процент означает только то, что их было три.

   ── Почему ячейки меньше, чем в «Аналитике» ────────────────────────
   Там четыре числа на всю ширину страницы, здесь шесть в окне шириной
   десять сантиметров. Теми же крупными ячейками окно вытянулось бы на
   два экрана ради шести чисел. Мерка взята из работающей программы:
   число 17, подпись 9.5, зазор 9.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('author-signals', function (данные) {
  'use strict';
  данные = данные || {};

  var КТО = Number(данные.кто || 0);

  /* Уровень считает сервер, а не мы: двадцать закрытых — «автор»,
     пятьдесят и три месяца — «в общей витрине». Своего правила у окна
     нет нарочно, иначе в карточке и здесь стояли бы разные слова. */
  var УРОВНИ = {
    novice: 'новичок',
    author: 'автор',
    global: 'в общей витрине'
  };

  var СОСТОЯНИЯ = {
    open:    'открыт',
    tp:      'взял TP',
    sl:      'поймал SL',
    expired: 'срок вышел',
    closed:  'закрыт автором'
  };

  var М = CW.модалка({
    имя: 'автор-сигналов',
    знак: 'столбики',
    заголовок: String(данные.имя || 'Автор'),
    подзаголовок: Т('считаю…')
  });
  М.открыть();

  if (!КТО) {
    М.пусто({ знак: 'внимание', заголовок: Т('Не указан автор'),
              текст: 'Окно открыто без номера человека, показывать нечего.' });
    return М;
  }

  М.тело.innerHTML = '<div class="пусто-строка">' + CW.безопасно(Т('Считаю…')) + '</div>';

  Promise.all([
    CW.спросить('/signals/authors/' + КТО, { тихо: true }),
    CW.спросить('/signals/authors/' + КТО + '/signals?limit=30', { тихо: true })
  ]).then(function (оба) {
    нарисовать(оба[0] || {}, рядами(оба[1]));
  }).catch(function (е) {
    М.пусто({
      знак: 'внимание',
      заголовок: Т('Не открылось'),
      текст: (е && е.сеть) ? 'Нет связи с сервером'
                           : ((е && е.message) || 'Сервер не ответил')
    });
  });

  function рядами(о) {
    if (!о) return [];
    if (Array.isArray(о)) return о;
    return о.signals || о.items || [];
  }

  function процент(ч) {
    if (ч == null) return '-';
    var з = Number(ч);
    if (!isFinite(з)) return '-';
    return (з > 0 ? '+' : '') + з.toFixed(2) + '%';
  }

  function цена(ч) {
    if (ч == null) return '-';
    var з = Number(ч);
    if (!isFinite(з)) return '-';
    var знаков = з >= 100 ? 2 : з >= 1 ? 4 : 6;
    return з.toLocaleString('ru', { minimumFractionDigits: знаков,
                                    maximumFractionDigits: знаков });
  }

  /* Склонение дней без таблиц: три случая, как в русском языке. */
  function дней(н) {
    н = Math.abs(Number(н) || 0);
    var сто = н % 100, десять = н % 10;
    if (сто > 10 && сто < 20) return н + ' дней';
    if (десять === 1) return н + ' день';
    if (десять >= 2 && десять <= 4) return н + ' дня';
    return н + ' дней';
  }

  function подписчиков(н) {
    н = Math.abs(Number(н) || 0);
    var сто = н % 100, десять = н % 10;
    if (сто > 10 && сто < 20) return н + ' подписчиков';
    if (десять === 1) return н + ' подписчик';
    if (десять >= 2 && десять <= 4) return н + ' подписчика';
    return н + ' подписчиков';
  }

  /* ── ДВЕРЬ В ОТЗЫВЫ О СИГНАЛАХ ──
     Строку рисуем только тогда, когда сводка пришла: на старом сервере
     рейтинга нет, и обещать его пустой строкой незачем. Открывается
     сразу нужная полка — «Сигналы», а не товары. */
  function отзывнаяСтрока() {
    var ряд = CW.кусок('авт-строка авт-отзывы');
    ряд.textContent = Т('Загрузка…');
    М.тело.appendChild(ряд);

    CW.нужен('shared/продавец.js').then(function () {
      return CW.продавец.сводка(КТО);
    }).then(function (с) {
      var р = (с && с.разделы && с.разделы.signals) || null;
      if (!р) { ряд.remove(); return; }
      var отзывов = Number(р.отзывов) || 0;
      ряд.innerHTML = '';
      if (отзывов) {
        ряд.appendChild(CW.кусок('авт-оценка',
            CW.продавец.звёзды(р['звёзд'], 14)
          + '<b>' + Number(р['звёзд']).toFixed(1) + '</b>'
          + '<span>' + отзывов + ' ' + CW.безопасно(Т('об этих сигналах')) + '</span>'));
      } else {
        ряд.appendChild(CW.кусок('авт-оценка',
          '<span>' + CW.безопасно(Т('Отзывов об этих сигналах пока нет')) + '</span>'));
      }
      var б = document.createElement('button');
      б.type = 'button';
      б.className = 'кнопка авт-кн-отзывы';
      б.textContent = отзывов ? 'Отзывы и оценка' : 'Оценить автора';
      б.onclick = function () { CW.продавец.окно(КТО, { раздел: 'signals' }); };
      ряд.appendChild(б);
    }).catch(function () {
      ряд.remove();
    });
  }

  function нарисовать(а, ряды) {
    var ст = а.stats || {};
    var закрытых = Number(ст.closed || 0);

    М.имя(String(а.name || данные.имя || 'Автор'),
          УРОВНИ[ст.level] || УРОВНИ.novice);

    М.тело.innerHTML = '';

    if (!закрытых) {
      /* Ни одного закрытого — судить не по чему. Здесь важно не
         замолчать это, а сказать прямо: иначе пустое окно читается как
         поломка, а не как «пока нечего показывать». */
      М.тело.appendChild(CW.кусок('пусто-строка',
        'Закрытых сигналов пока нет. Судить не по чему, '
        + 'и придумывать проценты мы не станем.'));
    } else {
      var числа = CW.кусок('авт-числа');
      [
        { знач: String(закрытых), под: 'закрытых сигналов' },
        { знач: ст.win_rate == null ? '-' : ст.win_rate + '%',
          под: ст.win_rate == null ? 'процент после 20 закрытых' : 'в плюс',
          краска: ст.win_rate == null ? '' : (Number(ст.win_rate) >= 50 ? 'плюс' : 'минус') },
        { знач: процент(ст.sum_pct), под: 'сумма при равной ставке',
          /* Ровный ноль не красим: зелёный ноль читается как прибыль,
             которой не было. */
          краска: Number(ст.sum_pct || 0) > 0 ? 'плюс'
                : Number(ст.sum_pct || 0) < 0 ? 'минус' : '' },
        { знач: процент(ст.avg_win) + ' / ' + процент(ст.avg_loss),
          под: 'средний плюс / минус' },
        { знач: String(ст.worst_streak || 0), под: 'худшая серия убытков' },
        { знач: процент(-Math.abs(Number(ст.max_dd || 0))),
          под: 'максимальная просадка',
          краска: Number(ст.max_dd || 0) > 0 ? 'минус' : '' }
      ].forEach(function (я) {
        числа.appendChild(CW.кусок('авт-число',
            '<div class="знач ' + (я.краска || '') + '">'
          +   CW.безопасно(я.знач) + '</div>'
          + '<div class="под">' + CW.безопасно(я.под) + '</div>'));
      });
      М.тело.appendChild(числа);

      М.тело.appendChild(CW.кусок('авт-строка',
          'На платформе ' + дней(ст.days) + ' · открытых сейчас '
        + Number(ст.open || 0)
        + (Number(а.subs || 0) ? ' · ' + подписчиков(а.subs) : '')));
    }

    /* Числа выше говорят, как идут сигналы. Люди говорят, каково было
       платить за них, — это другой вопрос. Он живёт в окне продавца на
       полке «Сигналы», и здесь стоит только дверь туда: своих звёзд это
       окно не считает и второго мнения не выдумывает. */
    отзывнаяСтрока();

    if (!ряды.length) return;

    /* «Последние», а не «его»: это окно открывают и на себя — в своей
       же карточке, — и «его сигналы» там читалось бы как чужие. */
    М.тело.appendChild(CW.кусок('авт-раздел', 'Последние сигналы'));

    ряды.forEach(function (с) {
      var открыт = с.status === 'open';
      var з = открыт ? с.pnl : с.result_pct;
      var вид = з == null ? 'никак' : (Number(з) >= 0 ? 'плюс' : 'минус');

      /* Скрытый платный сигнал остаётся скрытым и здесь: в списке
         автора он виден строкой, но без пары и без цен. */
      var пара = с.locked ? 'скрыт' : (с.pair || '-');
      var подпись = (с.dir ? с.dir + ' · ' : '')
                  + (СОСТОЯНИЯ[с.status] || СОСТОЯНИЯ.open)
                  + (!с.locked && !открыт && с.close_price != null
                      ? ' · по ' + цена(с.close_price) : '');

      М.тело.appendChild(CW.кусок('авт-ряд',
          '<span class="пара">' + (с.locked ? CW.значок('замок', 13) : '')
        +   CW.безопасно(пара) + '</span>'
        + '<span class="чем">' + CW.безопасно(подпись) + '</span>'
        + '<span class="итог ' + вид + '">' + процент(з) + '</span>'));
    });
  }

  return М;
});
