/* ═══════════════════════════════════════════════════════════════════════
   ПОДАРИТЬ КЛЮЧ.

   Сервер выдаёт ключ строкой, и дальше его надо кому-то передать.
   Поэтому окно не закрывается сразу после выдачи: сперва показывает
   ключ и даёт его скопировать. Закрыться молча и потерять ключ,
   который уже оплачен, — худшее, что здесь можно сделать.

       CW.открыть('gift-key');
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('gift-key', function (данные) {
  'use strict';
  данные = данные || {};

  var ключНаЭкране = false;

  var М = CW.модалка({
    имя: 'подарить-ключ',
    знак: 'ключик',
    заголовок: Т('Подарить ключ'),
    подзаголовок: Т('сервер выдаст строку: её и передашь'),
    /* Мимо не закрываем ТОЛЬКО когда ключ уже на экране: потерять
       выданный и оплаченный ключ нельзя. А пока ключа нет, окно обязано
       закрываться как все остальные — проверка 18 ноября нашла, что оно
       не закрывалось ни касанием мимо, ни Escape, с первой секунды. */
    мимо: function () { return !ключНаЭкране; },
    главная: { зн: 'ключик', подсказка: Т('Выдать ключ'), делать: выдать }
  });

  var Ф = CW.поля(М.тело, [
    { имя: 'вид', подпись: Т('Какой ключ'), вид: 'фишки', значение: 'silver',
      пункты: [
        { знач: 'silver', подпись: Т('Сильвер'), зн: 'ключик' },
        { знач: 'gold',   подпись: Т('Голд'),   зн: 'кубок'  }
      ] }
  ]);

  var п = document.createElement('div');
  п.className = 'подсказ';
  п.style.cssText = 'margin-top:4px;line-height:1.65';
  п.textContent = Т('Ключ одноразовый: кто первым его введёт, тот и получит. ')
                + 'Передавай тому, кому собирался, и никому больше.';
  М.тело.appendChild(п);

  М.открыть();

  function выдать() {
    М.занят(true);
    CW.спросить('/keys/gift', {
      способ: 'POST', сроком: 25000, тело: { tier: Ф.взять('вид') }
    }).then(function (о) {
      М.занят(false);
      показать((о && (о.key || о.gift_key)) || '');
    }).catch(function (е) {
      М.занят(false);
      CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                             : ((е && е.message) || 'Ключ не выдался'));
    });
  }

  function показать(ключ) {
    if (!ключ) { CW.сказать(Т('Сервер не вернул ключ')); return; }
    ключНаЭкране = true;

    М.имя(Т('Ключ выдан'), Т('скопируй и передай: второй раз его не покажут'));
    М.тело.innerHTML = '';

    var коробка = document.createElement('div');
    коробка.className = 'кл-строка';
    коробка.textContent = ключ;
    М.тело.appendChild(коробка);

    var кн = document.createElement('button');
    кн.className = 'кнопка главная';
    кн.style.cssText = 'width:100%;margin-top:12px';
    кн.textContent = Т('Скопировать ключ');
    кн.onclick = function () { CW.вбуфер(ключ, Т('Ключ скопирован')); };
    М.тело.appendChild(кн);

    var п2 = document.createElement('div');
    п2.className = 'подсказ';
    п2.style.cssText = 'margin-top:12px;line-height:1.65';
    п2.textContent = Т('Записан он только у сервера. Если потеряешь строку, ')
      + 'восстановить её будет нельзя, поэтому скопируй сейчас.';
    М.тело.appendChild(п2);

    /* Ключ выдан — выдавать второй раз нечего. Остаётся крестик. */
    М.кнопки['главная'].style.display = 'none';
  }

  return М;
});
