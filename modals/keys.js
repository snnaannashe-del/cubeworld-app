/* ═══════════════════════════════════════════════════════════════════════
   МАГАЗИН КЛЮЧЕЙ.

   Ключ решает, сколько кубов можно держать и что вообще доступно.
   Поэтому окно показывает не список цен, а РАЗНИЦУ: что меняется по
   сравнению с тем ключом, который у человека сейчас. Цена без разницы
   не объясняет ничего.

   Нынешний ключ не предлагаем купить второй раз, а помечаем «у тебя
   сейчас». Ключ ниже нынешнего не предлагаем вовсе: понижение — это
   отдельный разговор, и оно не делается в один тык.

   ── Безопасность ключа ─────────────────────────────────────────────
   Внизу окна три вещи, которых в программе не было ни одной, хотя на
   сервере они есть с самого начала:

       СМЕНИТЬ КЛЮЧ    ключ утёк — меняем, всё остальное остаётся:
                       кубы, переписки, счёт. Старый гаснет сразу.
       ВЫЙТИ ВЕЗДЕ     гасим все входы: кто сидел по украденному
                       токену, вылетает.
       ПОГАСИТЬ ВХОД   рубильник на крайний случай. Обратно включает
                       только владелец площадки руками в базе.

   Ключ — единственный вход в CubeWorld. Пока сменить его было нельзя,
   утёкший ключ оставался чужим навсегда.

       CW.открыть('keys');
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('keys', function (данные) {
  'use strict';
  данные = данные || {};

  /* Что из плана показывать и как это назвать по-человечески. */
  var ЧТО = [
    { поле: 'cubes',        подпись: 'кубов разом' },
    { поле: 'streams',      подпись: 'эфиры' },
    { поле: 'signals',      подпись: 'сигналы' },
    { поле: 'analytics',    подпись: 'аналитика' },
    { поле: 'closed_cubes', подпись: 'закрытые кубы' },
    { поле: 'fund',         подпись: 'фонд' },
    { поле: 'api',          подпись: 'API' },
    { поле: 'priority',     подпись: 'приоритет' }
  ];

  var М = CW.модалка({
    имя: 'ключи',
    знак: 'ключик',
    заголовок: 'Ключи',
    подзаголовок: 'спрашиваю…'
  });
  М.открыть();
  М.тело.innerHTML = '<div class="пусто-строка">Загрузка…</div>';

  Promise.all([
    CW.спросить('/plans', { тихо: true }),
    CW.кто(true)
  ]).then(function (о) {
    нарисовать(о[0] || {}, о[1] || {});
  }).catch(function (е) {
    М.пусто({ знак: 'внимание', заголовок: 'Не открылось',
              текст: (е && е.сеть) ? 'Нет связи с сервером'
                                   : ((е && е.message) || 'Сервер не ответил') });
  });

  function нарисовать(д, я) {
    var планы = д.plans || {};
    var порядок = д.order || Object.keys(планы);
    var мой = (я.key_type || 'free').toLowerCase();
    var гдеЯ = порядок.indexOf(мой);

    М.имя('Ключи', 'у тебя сейчас: ' + ((планы[мой] && планы[мой].name) || мой));
    М.тело.innerHTML = '';

    порядок.forEach(function (имя, и) {
      var п = планы[имя];
      if (!п) return;

      var это = (имя === мой);
      /* Ключи ниже нынешнего не показываем: предложить человеку
         понижение рядом с повышением — значит однажды получить тык не
         туда и потерянный куб. */
      if (и < гдеЯ) return;

      var к = document.createElement('div');
      к.className = 'кл-ключ' + (это ? ' мой' : '');

      var цена = Number(п.month || 0);
      к.innerHTML =
          '<div class="верх">'
        +   '<b>' + CW.безопасно(п.name || имя) + '</b>'
        +   (это ? '<span class="метка">у тебя сейчас</span>'
                 : (цена ? '<span class="цена">$' + цена + '<i>/мес</i></span>'
                         : '<span class="цена">даром</span>'))
        + '</div>';

      /* Разница, а не список. То, что уже есть, повторять незачем. */
      var мояПлита = планы[мой] || {};
      var строки = [];
      ЧТО.forEach(function (ч) {
        var стало = п[ч.поле], было = мояПлита[ч.поле];
        if (стало === было) return;
        if (typeof стало === 'boolean') {
          if (стало) строки.push('+ ' + ч.подпись);
        } else if (Number(стало) > Number(было || 0)) {
          строки.push('+ ' + ч.подпись + ': ' + было + ' → ' + стало);
        }
      });

      var чем = document.createElement('div');
      чем.className = 'чем';
      чем.textContent = это ? 'Это твой ключ.'
                      : строки.length ? строки.join(' · ')
                      : 'То же самое, что сейчас.';
      к.appendChild(чем);

      if (!это) {
        var б = document.createElement('button');
        б.className = 'кнопка главная';
        б.style.width = '100%';
        б.style.marginTop = '12px';
        б.textContent = 'Перейти на «' + (п.name || имя) + '»';
        б.onclick = function () { спросить(имя, п); };
        к.appendChild(б);
      }

      М.тело.appendChild(к);
    });

    var хвост = document.createElement('div');
    хвост.className = 'подсказ';
    хвост.style.cssText = 'margin-top:14px;line-height:1.65';
    хвост.textContent = 'Ключ меняется сразу. Деньги за него списываются '
      + 'отдельно: оплату показывает сервер, и она проходит не здесь.';
    М.тело.appendChild(хвост);

    безопасность();
  }

  /* ═════════════════════════════════════════════════════════════════════
     БЕЗОПАСНОСТЬ КЛЮЧА

     Три действия, каждое из которых человек делает один раз в жизни и
     каждый раз в беде: ключ утёк, телефон потерян, пора всё погасить.
     Поэтому они не кнопками в ряд, а отдельным блоком внизу, и каждое
     называет вслух, что именно случится.
     ═════════════════════════════════════════════════════════════════════ */
  function безопасность() {
    var б = document.createElement('div');
    б.className = 'кл-охрана';
    б.innerHTML = '<div class="кл-метка">Безопасность</div>';

    б.appendChild(дело('ключик', 'Сменить ключ',
      'Старый перестанет работать сразу. Кубы, переписки и счёт останутся.',
      сменитьКлюч));

    б.appendChild(дело('выйти', 'Выйти на всех устройствах',
      'Все входы погаснут. Здесь тоже придётся войти заново.',
      выйтиВезде));

    б.appendChild(дело('замок', 'Погасить вход насовсем',
      'Ни ключ, ни уже выданные входы работать не будут. Обратно включает '
      + 'только владелец площадки руками.', погасить, true));

    М.тело.appendChild(б);
  }

  function дело(знак, имя, что, делать, опасное) {
    var р = document.createElement('button');
    р.type = 'button';
    р.className = 'кл-дело' + (опасное ? ' опасное' : '');
    р.innerHTML = '<span class="зн">' + CW.значок(знак) + '</span>'
                + '<span class="тк"><b>' + имя + '</b><span>' + что + '</span></span>'
                + '<span class="уг">' + CW.значок('шеврон') + '</span>';
    р.onclick = делать;
    return р;
  }

  /* Нынешний ключ сервер спрашивает нарочно: иначе чужой, добравшийся
     до открытой вкладки, сменил бы ключ и забрал учётку себе. */
  function спроситьКлюч(заголовок, подзаголовок, дальше) {
    var О = CW.модалка({
      имя: 'нынешний-ключ',
      знак: 'ключик',
      заголовок: заголовок,
      подзаголовок: подзаголовок,
      крест: true,
      главная: { зн: 'галка', подсказка: 'Дальше', делать: пуск }
    });
    var Ф = CW.поля(О.тело, [
      { имя: 'ключ', подпись: 'Нынешний ключ', обяз: true,
        намёк: 'CUBE-XXXX-XXXX-XXXX' }
    ]);
    О.открыть();
    var первое = О.тело.querySelector('input');
    if (первое) { первое.focus(); первое.autocomplete = 'off'; }

    function пуск() {
      if (!Ф.проверить()) return;
      var ключ = String(Ф.взять().ключ || '').trim().toUpperCase();
      if (ключ.length < 8) { CW.сказать('Это не похоже на ключ'); return; }
      О.занят(true);
      дальше(ключ, О);
    }
    return О;
  }

  function сменитьКлюч() {
    спроситьКлюч('Сменить ключ', 'старый погаснет сразу',
      function (ключ, О) {
        CW.спросить('/auth/rotate-key', {
          способ: 'POST', сроком: 25000, тело: { current_key: ключ }
        }).then(function (о) {
          О.убрать();
          показатьНовый((о && о.key) || '');
        }).catch(function (е) {
          О.занят(false);
          CW.сказать((е && е.message) || 'Ключ не сменился');
        });
      });
  }

  /* Новый ключ показываем один раз и говорим об этом прямо: сервер его
     не хранит открытым, восстановить нельзя. */
  function показатьНовый(ключ) {
    if (!ключ) { CW.сказать('Сервер не вернул новый ключ'); return; }
    var показан = false;
    var О = CW.модалка({
      имя: 'новый-ключ',
      знак: 'ключик',
      заголовок: 'Новый ключ',
      подзаголовок: 'показываем один раз',
      мимо: function () { return !показан; }
    });
    показан = true;
    var строка = document.createElement('div');
    строка.className = 'кл-ключ';
    строка.textContent = ключ;
    О.тело.appendChild(строка);

    var кн = document.createElement('button');
    кн.className = 'кнопка главная';
    кн.style.cssText = 'width:100%;margin-top:12px';
    кн.textContent = 'Скопировать ключ';
    кн.onclick = function () { CW.вбуфер(ключ, 'Ключ скопирован'); };
    О.тело.appendChild(кн);

    var п = document.createElement('div');
    п.className = 'подсказ';
    п.style.cssText = 'margin-top:12px;line-height:1.65';
    п.textContent = 'Старый ключ больше не работает, и все входы погашены, '
      + 'на этом устройстве тоже. Сохрани новый: восстановить его нельзя.';
    О.тело.appendChild(п);

    var выход = document.createElement('button');
    выход.className = 'кнопка';
    выход.style.cssText = 'width:100%;margin-top:10px';
    выход.textContent = 'Войти заново';
    выход.onclick = function () {
      CW.выйти(false).then(function () { CW.уйти(CW.раздел('index')); });
    };
    О.тело.appendChild(выход);

    О.открыть();
  }

  function выйтиВезде() {
    CW.лист([
      { заголовок: 'Погасить все входы?' },
      { зн: CW.значок('выйти', 16), подпись: 'Погасить', опасная: true,
        делать: function () {
          CW.спросить('/auth/logout-all', { способ: 'POST', сроком: 20000 })
            .then(function (о) {
              var н = (о && Number(о.closed)) || 0;
              CW.сказать(н ? ('Погашено входов: ' + н) : 'Входы погашены');
              /* Наш вход тоже среди погашенных — уводим на вход сами,
                 иначе человек останется на экране, который перестал
                 отвечать, и решит, что всё сломалось. */
              setTimeout(function () {
                CW.выйти(false).then(function () { CW.уйти(CW.раздел('index')); });
              }, 900);
            })
            .catch(function (е) {
              CW.сказать((е && е.message) || 'Не вышло погасить');
            });
        } },
      { зн: CW.значок('стрелка', 16), подпись: 'Оставить' }
    ]);
  }

  function погасить() {
    спроситьКлюч('Погасить вход насовсем', 'обратно включит только владелец',
      function (ключ, О) {
        CW.спросить('/auth/disable', {
          способ: 'POST', сроком: 25000, тело: { current_key: ключ }
        }).then(function () {
          О.убрать();
          CW.сказать('Учётная запись погашена');
          setTimeout(function () {
            CW.выйти(false).then(function () { CW.уйти(CW.раздел('index')); });
          }, 900);
        }).catch(function (е) {
          О.занят(false);
          CW.сказать((е && е.message) || 'Не вышло погасить');
        });
      });
  }

  /* Переход на другой ключ — действие с деньгами, и спрашиваем мы не
     «точно?», а называем, что именно случится. */
  function спросить(имя, п) {
    CW.лист([
      { заголовок: 'Перейти на «' + (п.name || имя) + '»?' },
      { зн: CW.значок('ключик', 16), подпись: 'Перейти', делать: function () {
          М.занят(true);
          CW.спросить('/keys/upgrade', {
            способ: 'POST', тело: { to_type: имя }, сроком: 25000
          }).then(function () {
            CW.сказать('Ключ сменён на «' + (п.name || имя) + '»');
            М.убрать();
            CW.уйти(location.href);
          }).catch(function (е) {
            М.занят(false);
            CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                                   : ((е && е.message) || 'Не вышло сменить ключ'));
          });
        } },
      { зн: CW.значок('стрелка', 16), подпись: 'Передумать' }
    ]);
  }

  return М;
});
