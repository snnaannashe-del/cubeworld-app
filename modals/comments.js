/* ═══════════════════════════════════════════════════════════════════════
   КОММЕНТАРИИ.          /home/claude/новое/cubeworld-app/modals/comments.js

   Перенесено из feed.html, где они жили панелью сбоку и потому
   открывались только там. А комментарии нужны и в профиле, и в
   уведомлениях, и по прямой ссылке на запись.

   Три вещи, которые делают комментарии сносными и которые легко
   потерять при переписывании:

   1. ЛЕНТА ПРОКРУЧЕНА ВНИЗ при открытии — к свежим, а не к первым.
   2. ПОСЛЕ ОТПРАВКИ ПЕРЕЧИТЫВАЕМ с сервера. Дорисовать свой
      комментарий на месте быстрее, но тогда он виден только тебе,
      если на сервере что-то пошло не так.
   3. ЛАЙК переключается на месте и не ждёт ответа: ждать полсекунды
      ради сердечка невыносимо.

   ── Что нашла проверка 18 ноября ────────────────────────────────────
   Окно читало поля, которых сервер не отдаёт: «liked» и «like_count».
   На деле приходят «user_like» ('like' | 'dislike' | null) и «likes».
   Поэтому счётчик всегда был пустым, а своё сердечко никогда не
   горело — даже сразу после нажатия, стоило перечитать список.
   И сам лайк уходил без тела запроса, а сервер ждёт {type:'like'} —
   то есть не ставился вовсе.

   Чего не было совсем, хотя на сервере есть с самого начала:
       ОТВЕТЫ      ветка под комментарием, /feed/comment/{id}/reply
       ПРАВКА      своего комментария и своего ответа
       УДАЛЕНИЕ    своего комментария и своего ответа

       CW.открыть('comments', {пост: 12, потом: fn});
   ═══════════════════════════════════════════════════════════════════════ */
/* ── ЗАПАС: КОММЕНТАРИИ, СПРОШЕННЫЕ ЗАРАНЕЕ ──────────────────────────
   Полка открывается мгновенно, а список в ней ещё едет, и первые
   полсекунды человек смотрит на «Смотрю…». Между тем лента знает,
   какая запись сейчас под носом, задолго до нажатия: можно спросить
   комментарии заранее, пока человек смотрит ролик.

       CW.комментарии.погреть('/feed/12/comments');   лента, заранее
       CW.комментарии.взять('/feed/12/comments');     полка, при открытии

   Запас живёт пятнадцать секунд и одноразовый: открыли полку - дальше
   она читает живое с сервера, как читала. Греем ТИХО: не вышло -
   значит не вышло, полка спросит сама. */
CW.комментарии = CW.комментарии || {};
CW.комментарии.запас = CW.комментарии.запас || {};
CW.комментарии.СРОК = 15000;

CW.комментарии.погреть = function (путь) {
  if (!путь) return null;
  var з = CW.комментарии.запас;
  var было = з[путь];
  if (было && Date.now() - было.когда < CW.комментарии.СРОК) return было.обещание;
  var о = CW.спросить(путь, { сроком: 20000, тихо: true });
  з[путь] = { когда: Date.now(), обещание: о };
  о.catch(function () { delete з[путь]; });
  return о;
};

CW.комментарии.взять = function (путь) {
  var было = CW.комментарии.запас[путь];
  if (!было) return null;
  delete CW.комментарии.запас[путь];
  if (Date.now() - было.когда > CW.комментарии.СРОК) return null;
  return было.обещание;
};

CW.модаль('comments', function (данные) {
  'use strict';
  данные = данные || {};
  var ИД = данные.пост || данные.история;
  /* ── Одни комментарии на запись ленты и на историю ──
     Под историей разговор устроен так же, как под записью: те же
     строки, те же пальцы, ответы и правка. Разные у них только
     адреса на сервере и имя поля с текстом, поэтому второго такого
     окна в программе нет — есть один набор адресов на два случая.
     Так просила боевая: «меню комментариев история = меню
     комментариев лента, точно такое же». */
  var ПОД_ИСТОРИЕЙ = !!данные.история;
  var А = ПОД_ИСТОРИЕЙ ? {
    список: '/stories/' + ИД + '/comments',
    оценка: function (к) { return '/stories/' + ИД + '/comments/' + к.id + '/like'; },
    убрать: function (к) { return '/stories/' + ИД + '/comments/' + к.id; },
    правка: function (к) {
      return { путь: '/stories/' + ИД + '/comments/' + к.id, способ: 'PUT' };
    },
    новый: function () {
      return { путь: '/stories/' + ИД + '/comments', способ: 'POST' };
    },
    тело: function (текст, комуОтвет, доп) {
      var т = { text: текст };
      if (комуОтвет) т.parent_id = Number(комуОтвет) || 0;
      if (доп && доп.срок) т.expire_seconds = доп.срок;
      return т;
    }
  } : {
    список: '/feed/' + ИД + '/comments',
    оценка: function (к, ответЛи) {
      return (ответЛи ? '/feed/reply/' : '/feed/' + ИД + '/comment/') + к.id + '/like';
    },
    убрать: function (к, ответЛи) {
      return (ответЛи ? '/feed/reply/' : '/feed/comment/') + к.id;
    },
    правка: function (к, ответЛи) {
      return { путь: (ответЛи ? '/feed/reply/' : '/feed/comment/') + к.id,
               способ: 'PUT' };
    },
    новый: function (комуОтвет) {
      return { путь: комуОтвет ? ('/feed/' + ИД + '/comment/' + комуОтвет + '/reply')
                               : ('/feed/' + ИД + '/comment'),
               способ: 'POST' };
    },
    тело: function (текст, комуОтвет, доп) {
      var т = { content: текст };
      if (доп && доп.срок) т.expire_seconds = доп.срок;
      return т;
    }
  };
  var Я = (CW.ясныйЯ && CW.ясныйЯ()) || null;
  var ВСЕГО = 0;             /* сколько комментариев вместе с ответами */
  var МОЁ = false;           /* есть ли среди них моё */

  var М = CW.модалка({
    имя: 'комментарии',
    /* ── БЕЗ ВЕРХНЕЙ ШАПКИ ──
       Полка комментариев устроена как полка «Действия» у синей
       стрелки: выезжает снизу и ничего над собой не держит. Шапка со
       значком, названием и крестиком отнимала у неё две строки высоты
       и делала из полки ещё одно окно поверх ролика.
       Сколько всего комментариев — цифрой в правом верхнем углу.
       Выход на месте: касание мимо полки и Escape. */
    шапка: false,
    поля: false,
    /* Лента открывает комментарии ВНУТРИ своего кадра: окно выезжает
       снизу поверх ролика, и видно, к чему эти комментарии. Остальные
       (профиль, уведомления) зовут без «вКадре» — там кадра нет, и
       окно встаёт посреди экрана, как раньше. */
    вКадре: данные.вКадре || null,
    /* В кадре полка встаёт по содержимому: пустой разговор — это две
       строки и поле ввода, а не три четверти экрана. */
    поРосту: !!данные.вКадре
  });
  М.открыть();

  if (!ИД) {
    М.пусто({ знак: 'внимание', заголовок: Т('Не указана запись'),
              текст: 'Окно открыто без номера записи.' });
    return М;
  }

  /* Кто я — нужно, чтобы показать «Править» и «Удалить» только у своих.
     Спрашиваем тихо: если не ответит, просто не будет меню. */
  if (!Я && CW.кто) {
    CW.кто().then(function (д) { Я = д; перечитать(true); }).catch(function () {});
  }

  /* Здесь нутро прокручивается НАРОЧНО, в отличие от остальных
     лежачих окон: комментариев может быть триста, и растить окно
     во весь монитор бессмысленно. Поэтому overflow возвращаем явно —
     общее правило лежачих окон его снимает. */
  /* Сверху поля чуть больше, чем снизу: там, в углу, стоит счёт, и
     первая строка не должна начинаться прямо под ним. */
  /* В кадре (под роликом ленты и под историей) высоту держит сама
     полка: она не выше трёх четвертей кадра и по содержимому, если
     комментариев мало. Прежние «52vh» считались от ОКНА БРАУЗЕРА, а
     не от кадра, и под короткой историей полка оставляла полкадра
     пустоты под строкой ввода. */
  М.тело.style.cssText = данные.вКадре
    ? 'flex:0 1 auto;min-height:0;padding:18px 14px 8px;'
      + 'overflow-y:auto;overscroll-behavior:contain'
    : 'max-height:52vh;padding:24px 14px 8px;overflow-y:auto;overscroll-behavior:contain';

  /* Счёт — цифрой в правом верхнем углу полки. Он там же, где был в
     шапке, только без самой шапки: число никуда не делось, а строка
     под него больше не тратится. */
  var счёт = document.createElement('div');
  счёт.className = 'км-счёт';
  М.окно.appendChild(счёт);

  /* ── КРЕСТИК В УГЛУ ──
     Полка закрывается нажатием мимо и клавишей Escape, но на телефоне
     «мимо» - это узкая полоска ролика над полкой, и попасть по ней
     непросто. Крестик стоит там же, где он стоит у всех окон
     программы, - в правом верхнем углу, рядом со счётом. */
  var крестик = document.createElement('button');
  крестик.type = 'button';
  крестик.className = 'км-закрыть';
  крестик.title = Т('Закрыть');
  крестик.innerHTML = CW.значок('крест', 15);
  крестик.onclick = function () { М.закрыть(); };
  М.окно.appendChild(крестик);

  /* ── ПОЛЕ ВВОДА ВНИЗУ ──
     Берём общее поле переписки (CW.полеВвода): там уже есть смайлы,
     «скрыть через» и предел в пять тысяч знаков. Своё такое же поле
     здесь было бы вторым набором тех же кнопок, которые однажды
     разойдутся.

     Чего нет нарочно:
       скрепка   — комментарий на сервере только текст, файла в нём нет;
       микрофон  — голосом он тоже не принимается.
     Показать эти кнопки значило бы обещать то, чего сервер не умеет.

     Поле живёт в shared/chat.js. Лента, профиль и уведомления этот
     файл не грузят — он им ни к чему, пока не открыли комментарии.
     Поэтому просим его здесь, по надобности: загрузчик привезёт файл
     один раз за посещение и больше не поедет. */
  var ввод = null;

  CW.нужен('shared/chat.js').then(function () {
    ввод = CW.полеВвода({
      /* Подпись короткая нарочно. В поле ввода ровно одна строка, а
         «Написать комментарий…» на телефоне в неё не влезает: вторая
         строка подсказки обрезается ровно пополам, и поле выглядит
         сломанным. Окно и так называется «Комментарии», повторять это
         словом «написать» незачем. */
      подпись: Т('Комментарий…'),
      смайлы: true,
      формат: true,        /* пометки разбирает CW.сРазметкой — см. ниже */
      таймер: true,        /* ∞ — комментарий умеет исчезать по сроку */
      послать: function (текст, готово, доп) { послать(текст, готово, доп, null); }
    });
    М.окно.appendChild(ввод);
    /* Открыли комментарии - показываем их, а не клавиатуру.
       Писать человек начнёт, нажав в поле (shared/ui.js, CW.встать). */
    CW.встать(ввод.поле);
  }).catch(function () {
    CW.сказать(Т('Поле ввода не приехало: обнови страницу'));
  });

  /* ── ТРИ ЗНАЧКА СВОЕГО СООБЩЕНИЯ ОТКРЫВАЮТСЯ НАЖАТИЕМ ──
     Формат, карандаш и урна не показываются сами собой: нажал по
     своему сообщению — открылись, нажал ещё раз или по любому другому
     месту окна — закрылись. Открыто всегда одно сообщение.

     Слушатель один на всё окно, а не по штуке на строку: строк может
     быть триста, и триста слушателей — это триста поводов забыть
     снять один из них при перечитывании. */
  М.окно.addEventListener('click', function (е) {
    var цель = е.target;
    if (!цель || !цель.closest) return;
    /* Нажали по кнопке — это её дело, а не наше. */
    if (цель.closest('button')) return;
    var строка = цель.closest('.км-строка');
    var открыть = !!(строка && строка.querySelector('.км-свои')
                     && !строка.classList.contains('с-делами'));
    закрытьСвои();
    if (открыть) строка.classList.add('с-делами');
  });

  function закрытьСвои() {
    var было = М.тело.querySelectorAll('.км-строка.с-делами');
    [].slice.call(было).forEach(function (с) { с.classList.remove('с-делами'); });
  }

  перечитать();

  /* ═════════════════════════════════════════════════════════════════════
     ЧТЕНИЕ
     ═════════════════════════════════════════════════════════════════════ */
  /* Текст комментария лента зовёт «content», а история — «text».
     Разбирать это в двух местах значит однажды поправить одно и
     забыть другое, поэтому спрашиваем в одном. */
  function словами(к) { return (к && (к.content || к.text)) || ''; }

  function перечитать(тихо) {
    /* Первое чтение берём из запаса, если лента успела его погреть:
       тогда список стоит в полке сразу, без «Смотрю…». */
    var готовое = (!тихо && CW.комментарии && CW.комментарии.взять)
      ? CW.комментарии.взять(А.список) : null;
    if (готовое) {
      return готовое
        .then(function (д) { нарисовать(Array.isArray(д) ? д : ((д && д.items) || [])); })
        .catch(function () { return перечитать(тихо); });
    }
    if (!тихо) CW.ждём(М.тело);
    return CW.спросить(А.список, { сроком: 20000, тихо: !!тихо })
      .then(function (д) { нарисовать(Array.isArray(д) ? д : ((д && д.items) || [])); })
      .catch(function (е) {
        М.тело.innerHTML = '';
        var б = document.createElement('div');
        б.className = 'беда';
        б.textContent = (е && е.сеть) ? 'Нет связи с сервером'
                                      : 'Комментарии не открылись';
        М.тело.appendChild(б);
      });
  }

  /* Сказать позвавшему, что стало. Зовём только перечитав с сервера:
     до этого цифры — наша догадка, а не правда. */
  function сообщить() {
    if (данные.потом) данные.потом({ всего: ВСЕГО, моё: МОЁ });
  }

  function нарисовать(ряды) {
    var всего = ряды.length;
    ряды.forEach(function (к) { всего += ((к.replies || []).length); });

    /* Что сказать позвавшему: сколько их всего и есть ли среди них
       моё. Лента красит по этому свой значок комментариев и ставит
       счёт — прибавлять ей единицу на каждое событие нельзя, потому
       что удаление тоже событие. */
    ВСЕГО = всего;
    МОЁ = !!(Я && ряды.some(function (к) {
      if (Number(к.user_id) === Number(Я.id)) return true;
      return (к.replies || []).some(function (о) {
        return Number(о.user_id) === Number(Я.id);
      });
    }));
    счёт.textContent = всего ? String(всего) : '';
    М.тело.innerHTML = '';

    if (!ряды.length) {
      var п = document.createElement('div');
      п.className = 'пусто-строка';
      п.textContent = Т('Комментариев пока нет. Напиши первым.');
      М.тело.appendChild(п);
      return;
    }

    ряды.forEach(function (к) { М.тело.appendChild(ветка(к)); });
    М.тело.scrollTop = М.тело.scrollHeight;   /* к свежим, а не к первым */
  }

  /* ═════════════════════════════════════════════════════════════════════
     ВЕТКА: комментарий, его ответы и место для ответа

     Ответы стоят под чертой с отступом и сворачиваются одной строкой.
     Без сворачивания ветка на двадцать ответов прячет под собой все
     остальные комментарии.
     ═════════════════════════════════════════════════════════════════════ */
  function ветка(к) {
    var в = document.createElement('div');
    в.className = 'км-ветка';
    в.appendChild(строка(к, false, в));

    var ответы = (к.replies || []);
    var где = document.createElement('div');
    /* Ветка приходит свёрнутой. Раскрытая ветка на двадцать ответов
       закрывает собой все остальные комментарии, а человек пришёл
       смотреть комментарии, а не одну переписку внутри них. */
    где.className = 'км-ответы спрятано';
    ответы.forEach(function (о) { где.appendChild(строка(о, true, в)); });

    if (ответы.length) {
      var свернуть = document.createElement('button');
      свернуть.type = 'button';
      свернуть.className = 'км-свернуть';
      свернуть.textContent = Т('▼ Показать ответы (') + ответы.length + ')';
      свернуть.onclick = function () {
        var спрятано = где.classList.toggle('спрятано');
        свернуть.textContent = спрятано
          ? ('▼ Показать ответы (' + ответы.length + ')') : '▲ Свернуть';
      };
      в.appendChild(свернуть);
    }
    в.appendChild(где);
    return в;
  }

  /* ── одна строка: комментарий или ответ ──
     Отличие ответа — отступ и размер лица. Отвечать можно и на ответ:
     ответ уходит в ту же ветку, к её корню, поэтому лесенки в глубину
     не возникает.  */
  function строка(к, ответЛи, ветка) {
    var у = document.createElement('div');
    у.className = 'км-строка' + (ответЛи ? ' ответ' : '');
    у.appendChild(CW.кружок({ размер: ответЛи ? 26 : 32, кто: к.user_id,
                              снимок: к.avatar_url, версия: к.avatar_ver }));

    var тело = document.createElement('div');
    тело.className = 'тело';
    тело.innerHTML =
        '<div class="кто"><b>' + CW.безопасно(CW.имяЧеловека(к)) + '</b> '
      +   '<span>' + CW.безопасно(CW.прошло ? CW.прошло(к.created_at) : '') + '</span>'
      + '</div>'
      + '<div class="что">' + CW.сРазметкой(словами(к)) + '</div>';
    у.appendChild(тело);
    /* Подпись помнит, чья она: сменит человек имя — сменится и здесь. */
    if (CW.лица) CW.лица.подписать(тело.querySelector('.кто b'), к.user_id,
                                   CW.имяЧеловека(к));

    /* ── СРОК У КОМЕНТАРИЯ ──
       Кнопка «∞» в поле ввода обещает, что комментарий исчезнет, и
       сервер это обещание держит. А на экране про срок не было сказано
       ни слова: человек писал «на 5 минут» и не видел ни подписи, ни
       самого исчезновения, пока не перечитает страницу. Теперь срок
       подписан, как у сообщения в переписке, и строка убирается сама —
       тем же часовым, что и пузыри.

       Стоит он сразу за временем, в одной строке с именем, а не отдельной
       строкой под текстом: под текстом он разрывал комментарий надвое и
       отодвигал кнопки. Так же он стоит и в переписке - сразу за часами. */
    /* Под записью сервер отдаёт время (expire_at), под историей —
       остаток в секундах (expire_in). Разные ручки, разные поля; здесь
       приводим к одному виду, чтобы часовой знал, когда снимать. */
    var истекает = к.expire_at || к.expires_at || '';
    if (!истекает && Number(к.expire_in) > 0) {
      истекает = new Date(Date.now() + Number(к.expire_in) * 1000).toISOString();
    }
    if (истекает) {
      var ктоСтрока = тело.querySelector('.кто');
      (ктоСтрока || тело).appendChild(
        CW.эл('span', 'срок', CW.остаток(истекает)));
      if (CW.гаснет) CW.гаснет(у, истекает);
    }

    /* ── ряд действий под текстом: палец вверх, палец вниз, ответить ──
       Счёт стоит рядом со знаком, а не отдельной строкой: так в боевой
       и так понятно, к чему число. */
    var дела = document.createElement('div');
    дела.className = 'км-дела';
    дела.appendChild(оценка(к, ответЛи, 'like'));
    дела.appendChild(оценка(к, ответЛи, 'dislike'));

    var отв = document.createElement('button');
    отв.type = 'button';
    отв.className = 'км-ответить';
    отв.innerHTML = CW.значок('ответить', 15) + '<span>' + CW.безопасно(Т('Ответить')) + '</span>';
    отв.onclick = function () { отвечать(к, ответЛи, ветка); };
    дела.appendChild(отв);
    тело.appendChild(дела);

    /* ── своё: формат, карандаш и урна справа ──
       Прежде это пряталось в меню по долгому нажатию: мышью его никто
       не находил. Теперь знаки стоят в строке и видны сразу.

       «Форматировать» стоит здесь, а не у поля ввода: пометки ставят в
       СВОЁМ сообщении, а не в пустом поле. Значок берёт сообщение в
       правку и открывает панель пометок; нажал ещё раз — закрылась,
       нажал в любом другом месте окна — тоже закрылась. */
    if (Я && Number(к.user_id) === Number(Я.id)) {
      var свои = document.createElement('div');
      свои.className = 'км-свои';
      свои.appendChild(значок('буквы', 'Форматировать', function () {
        форматировать(к, ответЛи);
      }));
      свои.appendChild(значок('карандаш', 'Править', function () { править(к, ответЛи); }));
      свои.appendChild(значок('урна', 'Удалить', function () { удалить(к, ответЛи); }));
      у.appendChild(свои);
    }

    /* Долгое нажатие и правая кнопка — общее меню сообщения, то же, что
       в чатах, группах и избранном. Значки в строке остаются: мышью их
       находят быстрее, а меню даёт остальное — переслать, скопировать,
       девять пометок. */
    if (CW.наДолгоеНажатие) {
      CW.наДолгоеНажатие(у, function (x, y) { менюКомментария(к, ответЛи, x, y); });
    }
    return у;
  }

  /* Пункта «Закрепить» здесь нет нарочно: у комментария на сервере
     такого поля нет, а закреплять «только у себя» в общей ленте
     бессмысленно — кроме тебя этого никто не увидит. */
  function менюКомментария(к, ответЛи, x, y) {
    var своё = !!(Я && Number(к.user_id) === Number(Я.id));
    CW.нужен('shared/меню-сообщения.js').then(function () {
      CW.менюСообщения({
        род: 'текст',
        своё: своё,
        текст: словами(к),
        когда: CW.когдаСловами(к.created_at || к.time)
             + (к.edited ? ' · изменено' : ''),
        действия: {
          ответить: function () { отвечать(к, ответЛи, null); },
          скопировать: function () { CW.вбуфер(словами(к), Т('Скопировано')); },
          изменить: своё ? function (новый) {
            var п = А.правка(к, ответЛи);
            return CW.спросить(п.путь, {
              способ: п.способ, сроком: 20000, тело: А.тело(новый, null, {})
            }).then(function () { return перечитать(true).then(сообщить); });
          } : null,
          переслать: function () { CW.открыть('forward', { текст: словами(к) }); },
          удалить: своё ? function () { удалить(к, ответЛи); } : null
        }
      }, x, y);
    }).catch(function () { CW.сказать(Т('Меню не приехало')); });
  }

  function значок(имя, подсказка, делать) {
    var б = document.createElement('button');
    б.type = 'button';
    б.className = 'км-дело';
    б.title = подсказка;
    б.innerHTML = CW.значок(имя, 15);
    б.onclick = делать;
    return б;
  }

  /* ── палец вверх и палец вниз ──
     Сервер держит обе оценки в одной таблице: вторым нажатием снимает,
     другой оценкой — переключает. Поэтому кнопка одна на оба случая, а
     её вид берётся из ответа сервера. */
  function оценка(к, ответЛи, вид) {
    var б = document.createElement('button');
    б.type = 'button';
    var горит = (к.user_like === вид);
    б.className = 'км-оценка' + (горит ? ' горит' : '');
    б.title = вид === 'like' ? 'Нравится' : 'Не нравится';
    var число = вид === 'like' ? (Number(к.likes) || 0) : (Number(к.dislikes) || 0);
    б.innerHTML = CW.значок(вид === 'like' ? 'палец-вверх' : 'палец-вниз', 15)
                + '<span>' + число + '</span>';

    б.onclick = function () {
      CW.спросить(А.оценка(к, ответЛи),
                  { способ: 'POST', тихо: true, тело: { type: вид } })
        .then(function (о) {
          if (!о) return;
          к.likes = о.likes; к.dislikes = о.dislikes; к.user_like = о.user_like;
          var ряд = б.parentNode;
          ряд.replaceChild(оценка(к, ответЛи, 'like'), ряд.children[0]);
          ряд.replaceChild(оценка(к, ответЛи, 'dislike'), ряд.children[1]);
        })
        .catch(function () { CW.сказать(Т('Оценка не прошла')); });
    };
    return б;
  }

  /* ═════════════════════════════════════════════════════════════════════
     ОТВЕТ ПРЯМО В ВЕТКЕ

     Поле появляется под той веткой, на которую отвечают, и уже с
     «@именем» внутри. Раньше ответ писали в общем поле внизу, а над
     ним стояла строчка «Отвечаю такому-то»: человек печатал внизу, а
     смотрел наверх.
     ═════════════════════════════════════════════════════════════════════ */
  var ОТВЕТНОЕ = null;

  function отвечать(к, ответЛи, ветка) {
    /* «Ответить» — такой же переключатель, как смайлы и формат:
       нажал — поле открылось, нажал ещё раз у того же комментария —
       закрылось. Прежде второе нажатие молча перерисовывало то же
       поле, и убрать его можно было только отправив ответ.

       Ключ собираем из рода и номера: номера у комментариев и у
       ответов считаются по отдельности, и «ответ 7» легко совпал бы
       с «комментарием 7». */
    var ключ = (ответЛи ? 'о' : 'к') + к.id;
    if (ОТВЕТНОЕ && ОТВЕТНОЕ.кому === ключ) { убратьОтветное(); return; }
    убратьОтветное();
    /* Отвечаем всегда корню ветки: сервер кладёт ответы одним уровнем,
       и лесенка в глубину ему всё равно не нужна. */
    var корень = ответЛи ? (ветка.дляОтвета || к) : к;
    ветка.дляОтвета = корень;

    var поле = CW.полеВвода({
      подпись: Т('Ответить…'),
      смайлы: true,
      таймер: true,
      послать: function (текст, готово, доп) {
        послать(текст, готово, доп, корень.id);
      }
    });
    поле.classList.add('км-ответное');
    поле.поле.value = '@' + CW.имяЧеловека(к) + ' ';
    поле.кому = ключ;
    ОТВЕТНОЕ = поле;
    ветка.appendChild(поле);
    поле.поле.focus();
    поле.поле.selectionStart = поле.поле.selectionEnd = поле.поле.value.length;
  }

  function убратьОтветное() {
    if (ОТВЕТНОЕ && ОТВЕТНОЕ.parentNode) ОТВЕТНОЕ.parentNode.removeChild(ОТВЕТНОЕ);
    ОТВЕТНОЕ = null;
  }

  /* ═════════════════════════════════════════════════════════════════════
     ПРАВКА своего — в общем поле внизу: отдельное окошко ради одной
     строки это лишнее окно, из которого потом ищут выход.
     ═════════════════════════════════════════════════════════════════════ */
  var ПРАВИМ = null;

  function править(к, ответЛи) {
    убратьОтветное();
    ПРАВИМ = { id: к.id, ответ: ответЛи };
    if (!ввод) return;            /* поле ещё едет — править нечем */
    ввод.поле.value = словами(к);
    ввод.поле.focus();
    ввод.classList.add('правим');
  }

  /* Значок «А» у своего сообщения: берём его в правку и открываем
     пометки. Второе нажатие по тому же значку панель закрывает —
     ровно как вторая встреча с любой нашей кнопкой-переключателем. */
  function форматировать(к, ответЛи) {
    if (!ввод) { CW.сказать(Т('Поле ввода ещё едет')); return; }
    if (ввод.форматОткрыт() && ПРАВИМ && ПРАВИМ.id === к.id
        && ПРАВИМ.ответ === ответЛи) {
      ввод.формат(false);
      return;
    }
    править(к, ответЛи);
    ввод.формат(true);
  }

  function удалить(к, ответЛи) {
    CW.лист([
      { заголовок: Т('Удалить насовсем?') },
      { зн: CW.значок('урна', 16), подпись: Т('Удалить'), опасная: true,
        делать: function () {
          CW.спросить(А.убрать(к, ответЛи), { способ: 'DELETE', сроком: 20000 })
            .then(function () {
              CW.сказать(Т('Удалено'));
              return перечитать(true).then(сообщить);
            })
            .catch(function (е) {
              CW.сказать((е && е.message) || 'Не удалилось');
            });
        } },
      { зн: CW.значок('назад', 16), подпись: Т('Оставить') }
    ]);
  }

  /* ═════════════════════════════════════════════════════════════════════
     ОТПРАВКА: новый комментарий, ответ или правка — одна дорога на три
     ═════════════════════════════════════════════════════════════════════ */
  function послать(текст, готово, доп, комуОтвет) {
    текст = String(текст || '').trim();
    if (!текст) { готово(false); return; }

    /* «Скрыть через» сервер принимает полем expire_seconds — и у
       комментария, и у ответа. Ноль значит «навсегда», его не шлём.
       Куда слать и как называется поле с текстом — в наборе адресов
       наверху: под лентой и под историей они разные. */
    var куда = ПРАВИМ ? А.правка(ПРАВИМ, ПРАВИМ.ответ) : А.новый(комуОтвет);
    var тело = А.тело(текст, ПРАВИМ ? 0 : комуОтвет, доп);

    CW.спросить(куда.путь, { способ: куда.способ, тело: тело, сроком: 20000 })
      .then(function () {
        ПРАВИМ = null;
        if (ввод) ввод.classList.remove('правим');
        убратьОтветное();
        готово();
        /* Перечитываем с сервера, а не дорисовываем: иначе свой
           комментарий виден только тебе, если он туда не доехал.
           И только перечитав, говорим ленте настоящие цифры. */
        return перечитать(true).then(сообщить);
      })
      .catch(function (е) {
        готово(false);
        CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                               : ((е && е.message) || 'Не отправилось'));
      });
  }

  return М;
});
