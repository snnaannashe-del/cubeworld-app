  /* Ползунок с числом рядом: цифру человек читает, а тянет ползунок. */
  function ползунок(о) {
    var обёртка = документ.createElement('div');
    обёртка.className = 'рд-ползунок';
    var у = документ.createElement('input');
    у.type = 'range';
    у.min = о.наим; у.max = о.наиб; у.step = о.шаг; у.value = о.знач;
    var чис = документ.createElement('span');
    чис.className = 'чис';
    чис.textContent = о.словом(о.знач);
    у.oninput = function () {
      чис.textContent = о.словом(Number(у.value));
      о.меняется(Number(у.value));
    };
    обёртка.appendChild(у);
    обёртка.appendChild(чис);
    return обёртка;
  }

  function панельКусков(к) {
    if (!к) return;          /* про «плюс» уже написано в пустом кадре */
    var р = ряд();
    р.appendChild(кнопка('◀ Левее', function () {
      СТОЛ.двинуть(ВЫБРАН, -1); ВЫБРАН = Math.max(0, ВЫБРАН - 1); перерисовать();
    }));
    р.appendChild(кнопка('Правее ▶', function () {
      СТОЛ.двинуть(ВЫБРАН, 1);
      ВЫБРАН = Math.min(СТОЛ.клипы.length - 1, ВЫБРАН + 1); перерисовать();
    }));
    р.appendChild(кнопка('Разрезать здесь', function () {
      var место = СТОЛ.где(ПОКАЗ.место());
      if (!место || место.номер !== ВЫБРАН) {
        CW.сказать(Т('Поставь бегунок внутри выбранного куска'));
        return;
      }
      СТОЛ.разрезать(ВЫБРАН, место.своё);
      перерисовать();
    }));
    р.appendChild(кнопка('Убрать кусок', function () {
      СТОЛ.убрать(ВЫБРАН);
      ВЫБРАН = Math.min(ВЫБРАН, СТОЛ.клипы.length - 1);
      ПОКАЗ.кместу(0);
      перерисовать();
    }, true));
    пусто('Кусок ' + (ВЫБРАН + 1) + ' из ' + СТОЛ.клипы.length
          + ' · ' + CW.видеостол.время(СТОЛ.длинаКлипа(к))
          + ' · вся дорожка ' + CW.видеостол.время(СТОЛ.длина()));
  }

  function панельОбрезки(к) {
    if (!к) return;
    if (к.род === 'фото') {
      строка('Сколько стоит снимок', ползунок({
        наим: 0.5, наиб: 15, шаг: 0.5, знач: к.до - к.от,
        словом: function (ч) { return ч.toFixed(1) + ' с'; },
        меняется: function (ч) { к.до = к.от + ч; перерисовать(); }
      }));
      return;
    }
    строка('Начало', ползунок({
      наим: 0, наиб: Math.max(0.1, к.длит), шаг: 0.1, знач: к.от,
      словом: function (ч) { return CW.видеостол.время(ч); },
      меняется: function (ч) {
        к.от = Math.min(ч, к.до - 0.2);
        ПОКАЗ.кместу(СТОЛ.началоКлипа(ВЫБРАН));
        перерисовать();
      }
    }));
    строка('Конец', ползунок({
      наим: 0, наиб: Math.max(0.1, к.длит), шаг: 0.1, знач: к.до,
      словом: function (ч) { return CW.видеостол.время(ч); },
      меняется: function (ч) {
        к.до = Math.max(ч, к.от + 0.2);
        перерисовать();
      }
    }), 'всего в файле ' + CW.видеостол.время(к.длит));
  }

  function панельСкорости(к) {
    if (!к) return;
    if (к.род === 'фото') { пусто('У снимка нет скорости, есть длительность в «Обрезать»'); return; }
    строка('Скорость', ползунок({
      наим: 0.25, наиб: 3, шаг: 0.05, знач: к.скорость || 1,
      словом: function (ч) { return '×' + ч.toFixed(2); },
      меняется: function (ч) { к.скорость = ч; перерисовать(); }
    }), 'меняется и картинка, и звук, и длина куска');
    var р = ряд();
    [0.5, 1, 1.5, 2].forEach(function (с) {
      р.appendChild(кнопка('×' + с, function () { к.скорость = с; перерисовать(); }));
    });
  }

  /* ── ПЕРЕХОД ──
     Переход записан у того куска, В КОТОРЫЙ входим. Поэтому панель
     говорит «как этот кусок появляется», а не «что между ними»: так
     понятнее, какой кусок надо выбрать, чтобы его поправить. */
  function панельПерехода(к) {
    if (!к) return;
    if (!к.переход) к.переход = { вид: '', длит: 0.5 };

    var р = ряд();
    СТОЛ.переходы.forEach(function (п) {
      var б = кнопка(п.имя, function () {
        к.переход.вид = п.к;
        ПОКАЗ.кместу(Math.max(0, СТОЛ.началоКлипа(ВЫБРАН) - 0.4));
        перерисовать();
      });
      if ((к.переход.вид || '') === п.к) б.classList.add('главная');
      р.appendChild(б);
    });

    if (к.переход.вид) {
      строка('Сколько длится', ползунок({
        наим: 0.2, наиб: 1.5, шаг: 0.1, знач: к.переход.длит || 0.5,
        словом: function (ч) { return ч.toFixed(1) + ' с'; },
        меняется: function (ч) { к.переход.длит = ч; ПОКАЗ.рисовать(); }
      }));
    }

  }

  function панельЗвука(к) {
    if (!к) return;
    if (к.род === 'фото') { пусто('У снимка нет своего звука.'); return; }
    строка('Громкость куска', ползунок({
      наим: 0, наиб: 1, шаг: 0.05, знач: к.громкость == null ? 1 : к.громкость,
      словом: function (ч) { return Math.round(ч * 100) + '%'; },
      меняется: function (ч) { к.громкость = ч; }
    }));

    var р = ряд();
    var б = кнопка(к.шумодав ? 'Шумоподавление включено' : 'Шумоподавление',
      function () {
        к.шумодав = !к.шумодав;
        СТОЛ.звукПоправить();
        перерисовать();
      });
    if (к.шумодав) б.classList.add('главная');
    р.appendChild(б);
  }

