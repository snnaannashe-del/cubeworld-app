/* ═══════════════════════════════════════════════════════════════════════
   УДАЛИТЬ.

   Одно подтверждение на всю программу. Без него каждый экран пишет
   своё, и получается, что в одном месте спрашивают, в другом удаляют
   молча, а в третьем спрашивают «Точно?» — вопрос, на который нечего
   ответить, потому что он не говорит, ЧТО исчезнет.

   Правила этого окна:

   1. НАЗЫВАЕМ, ЧТО ИСЧЕЗНЕТ. Не «удалить элемент», а «удалить
      «Разработка CubeWorld» — 142 сообщения».
   2. ГОВОРИМ, ВЕРНЁТСЯ ЛИ. Если нет — говорим прямо, одной строкой.
   3. ОПАСНАЯ КНОПКА СПРАВА И КРАСНАЯ, безопасная слева. Руку ведёт
      привычка, и ломать её здесь нельзя.
   4. МИМО ОКНА — значит «не надо». Это и есть отмена.

       CW.открыть('delete', {
         что: 'Разработка CubeWorld',
         чего: 'группу',
         ещё: '142 сообщения исчезнут вместе с ней',
         навсегда: true,
         делать: function () { return CW.спросить(…); }
       });
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('delete', function (данные) {
  'use strict';
  данные = данные || {};

  /* Окно одно на все «точно?»: удаление, выход из группы, конец эфира.
     Поэтому и название, и значок, и слово на кнопке можно задать —
     «Удалить эфир?» со значком урны было бы неправдой: эфир не
     удаляют, его заканчивают. Без этих доводов всё как было. */
  var М = CW.модалка({
    имя: 'удалить',
    знак: данные.знак || 'внимание',
    заголовок: данные.заголовок
             || Т.с('Удалить {что}?', { что: Т(данные.чего || 'это') }),
    подзаголовок: данные.что || '',
    главная: { зн: данные.знакКнопки || 'урна', опасная: данные.опасная !== false,
               подсказка: данные.кнопка || Т('Удалить'), делать: удалить }
  });

  var текст = document.createElement('div');
  текст.className = 'ок-пусто';
  текст.style.cssText = 'text-align:left;padding:8px 2px 2px';
  текст.innerHTML =
      (данные.ещё ? CW.безопасно(данные.ещё) + '<br><br>' : '')
    + (данные.навсегда === false
        ? Т('Это можно будет вернуть.')
        : '<b style="color:var(--красный);font-size:0.9rem;display:block;'
          + 'margin-bottom:0">' + CW.безопасно(Т('Вернуть будет нельзя.')) + '</b>');
  М.тело.appendChild(текст);


  М.открыть();

  function удалить() {
    if (!данные.делать) { М.закрыть(); return; }
    М.занят(true);
    Promise.resolve(данные.делать())
      .then(function (о) {
        CW.сказать(данные.сказать || 'Удалено');
        М.убрать();
        if (данные.потом) данные.потом(о);
      })
      .catch(function (е) {
        М.занят(false);
        CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                               : ((е && е.message) || Т('Не вышло удалить')));
      });
  }

  return М;
});
