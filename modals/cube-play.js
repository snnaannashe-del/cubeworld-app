/* ═══════════════════════════════════════════════════════════════════════
   ИГРЫ С КУБАМИ.

   Это НЕ раздел «Игры» из верхней полосы: там своё — кубики, угадайка,
   гонка, клад. Здесь одно занятие: кубы в мире летают и слушаются.
   Открывается ладонью в столбике справа, под ключом.

   Кубы в мире перестают просто висеть: они летают внутри стен и
   слушаются — нажатия или движения руки перед камерой.

       CW.открыть('cube-play');

   ── Пять свёрнутых полок ───────────────────────────────────────────
   ЖЕСТЫ           камера видит движение и превращает его в действие
   ДЕЙСТВИЯ        двадцать плиток: броски, взрыв, вихрь, карусель…
   ФОРМЫ ПРЕДМЕТОВ чем куб стоит в мире, и своё фото или ролик на грани
   ПЕРСОНАЖ        ближний куб оживает: лицо, голос, реакции
   СВОИ ДЕЙСТВИЯ   своё имя действию и часть тела, которой его делают

   ── Рукой, головой, ногой, телом ───────────────────────────────────
   Одно и то же движение, сделанное разными частями, делает разное:
   рукой — броски и взрыв, головой — пузыри и фейерверк, ногой —
   прыжки и заморозка, телом — хоровод и карусель. Таблица лежит в
   shared/игра.js, а чем двигали — считает shared/жесты.js, один раз
   на всю программу (им же пользуется персонаж).

   Камера не узнаёт части тела и обещать этого нельзя: она видит, ГДЕ
   в кадре движение и насколько оно крупное. Вверху кадра — голова, в
   середине — рука, внизу — нога, по всему кадру — тело. Так и
   написано в самой полке «Жесты».

   ── Два рода плиток, и это видно ───────────────────────────────────
   Толчок — разовый: нажал, кубы полетели. Режим — держится, пока не
   снимешь, и у него горит подсветка. «Уронить» и «Невесомость» друг
   друга выключают: тяжесть бывает одна. «Заморозка» включается одна и
   гасит всё. У каждого действия свой цвет значка — двадцать одинаково
   синих читались как сплошной список.

   ── Чего здесь нет и почему ────────────────────────────────────────
   В боевой программе рядом была кнопка «Сохранить». Сохранять ей было
   нечего: переключатель жестов действует сразу и сам запоминается в
   браузере. Кнопка, которая ничего не меняет, хуже, чем её отсутствие.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('cube-play', function (данные) {
  'use strict';
  данные = данные || {};

  var ПАМЯТЬ = 'cw_жесты';

  var М = CW.модалка({
    имя: 'игра-с-кубами',
    знак: 'джойстик',
    знакЦвет: '#f0a6c8',
    заголовок: Т('Игры с кубами'),
    /* Окно стоит сбоку и ничего не затемняет: смотреть надо на кубы,
       а не на окно, и мир за ним должен крутиться пальцем. */
    сквозь: true,
    /* Треугольник без рамки, как у всех проигрывателей: кнопка включает
       игру. Когда она идёт, на её месте стоит пауза, а сама кнопка
       краснеет. Микрофона тут не было никогда и быть не должно:
       «тихо» значило «звук выключен», а звук к игре отношения не имеет. */
    главная: { зн: 'играть', подсказка: Т('Включить игру'), делать: переключить },
    /* Окно закрыли — игра остаётся идти: смотреть, как летают кубы, и
       есть всё занятие. Отвязываем только подсветку, чтобы игра не
       звала окно, которого больше нет. */
    при_закрытии: function () {
      if (отписаться) отписаться();
      if (отписатьсяФормы) отписатьсяФормы();
      if (отписатьсяГерой) отписатьсяГерой();
    }
  });

  /* ═════════════════════════════════════════════════════════════════════
     ЕСЛИ ИГРЫ ЗДЕСЬ НЕТ

     Игра живёт на карте мира: там кубы, которые она двигает. Открыли
     окно из ленты — играть нечем, и честнее сказать это и предложить
     уйти туда, чем показать двадцать мёртвых кнопок.
     ═════════════════════════════════════════════════════════════════════ */
  if (!CW.игра || !CW.игра.естьМир()) {
    М.пусто({
      знак: 'ромб',
      заголовок: Т('Игра живёт в мире'),
      текст: Т('Кубы, которые она бросает и крутит, стоят на карте мира. '
           + 'Открой мир, и кнопка «Игры» там заработает.'),
      кнопка: { подпись: Т('Открыть мир'),
                делать: function () { CW.уйти(CW.раздел('world')); } }
    });
    М.открыть();
    return М;
  }

  /* ═════════════════════════════════════════════════════════════════════
     РАЗМЕТКА
     ═════════════════════════════════════════════════════════════════════ */
  М.тело.innerHTML =
      раздел('жесты', 'Жесты',
          '<div class="иг-строка">'
        /* Текст без длинных тире: они рвут короткие строки на части и
           читаются тяжело. Вместо них глаголы и запятые. */
        /* Две строки, и всё. Объяснение про «вверху головой, внизу
           ногой» тут не читают: это видно по самой игре, а в окне оно
           превращало короткую подсказку в абзац. */
        +   '<div class="текст"><b>' + CW.безопасно(Т('Рукой, головой, ногой, телом')) + '</b><span>'
        +     'Взмах рукой в сторону бросает кубы, вверх подбрасывает, '
        +     'вниз роняет. Ладонь вперёд взрывает, круговое движение '
        +     'закручивает вихрь.'
        +   '</span></div>'
        +   '<button type="button" class="ок-тумблер иг-тумблер"></button>'
        + '</div>')

    + раздел('действия', 'Действия',
          '<div class="иг-сетка"></div>')

    + раздел('формы', 'Формы предметов',
          '<div class="фр-сетка"></div>'
        + '<button type="button" class="кнопка фр-вразнобой">' + CW.безопасно(Т('Вразнобой, каждому свою')) + '</button>'
        + '<div class="иг-строка фр-своя">'
        +   '<div class="текст"><b>' + CW.безопасно(Т('Своё фото или ролик')) + '</b>'
        +     '<span class="фр-что">' + CW.безопасно(Т('Ляжет на любую выбранную форму.')) + ' '
        +     '' + CW.безопасно(Т('Квадратом, ролик до 30 секунд.')) + '</span></div>'
        +   '<button type="button" class="ок-тумблер фр-тумблер"></button>'
        + '</div>'
        + '<div class="фр-ряд">'
        +   '<button type="button" class="кнопка фр-выбрать">' + CW.безопасно(Т('Выбрать файл')) + '</button>'
        +   '<button type="button" class="кнопка опасная фр-убрать">' + CW.безопасно(Т('Убрать')) + '</button>'
        + '</div>')

    + раздел('персонаж', 'Персонаж',
          '<div class="пс-сетка"></div>'
        + '<button type="button" class="кнопка опасная пс-убрать">' + CW.безопасно(Т('Убрать персонажа')) + '</button>'
        + '<div class="пс-ряд">'
        +   '<button type="button" class="кнопка пс-дело" data-вид="гладить">' + CW.безопасно(Т('Погладить')) + '</button>'
        +   '<button type="button" class="кнопка пс-дело" data-вид="щекот">' + CW.безопасно(Т('Пощекотать')) + '</button>'
        +   '<button type="button" class="кнопка пс-дело" data-вид="бить">' + CW.безопасно(Т('Побить')) + '</button>'
        + '</div>')

    + раздел('свои', 'Свои действия',
          '<div class="св-список"></div>'
        + метка('Название')
        + '<input class="св-поле св-имя" type="text" maxlength="40"'
        + ' autocomplete="off" placeholder="' + CW.безопасно(Т('Например: Погладить кота')) + '">'
        + метка('Команда голосом')
        + '<input class="св-поле св-команда" type="text" maxlength="40"'
        + ' autocomplete="off" placeholder="' + CW.безопасно(Т('погладь кота')) + '">'
        + метка('Описание')
        + '<input class="св-поле св-опис" type="text" maxlength="120"'
        + ' autocomplete="off" placeholder="' + CW.безопасно(Т('Зачем это и что будет')) + '">'
        + метка('Чем выполнять')
        + '<div class="иг-фишки св-части"></div>'
        + метка('Что происходит')
        + '<div class="иг-фишки св-что"></div>'
        + '<button type="button" class="кнопка главная св-сохранить">' + CW.безопасно(Т('Сохранить действие')) + '</button>');

  /* Полки — общие: сборщик и поведение лежат в shared/window.js. */
  function раздел(ключ, имя, внутри) {
    return CW.разделы.рисовать(ключ, имя, внутри);
  }
  function метка(т) { return '<div class="иг-метка">' + т + '</div>'; }
  function где(класс) { return М.тело.querySelector('.' + класс); }

  /* Полки те же, что у «Новой вещи» и «Создать куб»: свёрнуты все,
     раскрытая так и лежит, открыта всегда одна. */
  CW.разделы.завести(М.тело);

  /* ═════════════════════════════════════════════════════════════════════
     ДВАДЦАТЬ КНОПОК
     ═════════════════════════════════════════════════════════════════════ */
  /* Плитки той же раскладки, что у «Форм предметов»: значок сверху,
     подпись под ним, четыре в ряд. У каждого действия свой цвет значка
     — двадцать одинаково синих читались как сплошной список. Цвет
     лежит у самого действия (shared/игра.js), а не здесь: кнопка в
     мире рисует те же действия и должна красить их так же. */
  где('иг-сетка').innerHTML = CW.игра.ДЕЙСТВИЯ.map(function (д) {
    return '<button type="button" class="иг-кн' + (д.род === 'сброс' ? ' сброс' : '')
         + '" data-к="' + д.к + '">'
         + '<span class="зн" style="color:' + д.цвет + '">' + CW.значок(д.зн) + '</span>'
         + '<span class="имя">' + CW.безопасно(Т(д.имя)) + '</span></button>';
  }).join('');

  где('иг-сетка').onclick = function (е) {
    var б = е.target.closest('.иг-кн');
    if (!б) return;
    CW.игра.сделать(б.dataset.к);
    отметить();
  };

  /* Режим может сняться и не отсюда — например, когда игру выключили
     ладонью в мире. Поэтому подсветку ставит сама игра, а не только
     наше нажатие. Следящих у неё несколько: мы и кнопка в мире. */
  var отписаться = CW.игра.следить(отметить);

  function отметить() {
    var режимы = CW.игра.режимы();
    [].slice.call(М.тело.querySelectorAll('.иг-кн')).forEach(function (б) {
      б.classList.toggle('горит', режимы.indexOf(б.dataset.к) >= 0);
    });
    /* Идёт игра или нет, видно по самой кнопке пуска: она краснеет и
       меняет значок. Подписи под названием окна нет — в шапке одно
       «Игры с кубами», а что держится, видно по подсвеченным плиткам. */
    var г = М.кнопки['главная'];
    if (г) {
      г.classList.toggle('опасная', CW.игра.идёт());
      г.title = CW.игра.идёт() ? 'Выключить игру' : 'Включить игру';
      г.innerHTML = CW.значок(CW.игра.идёт() ? 'пауза' : 'играть');
    }
  }

  /* ── ФОРМЫ ПРЕДМЕТОВ ──
     Двадцать плиток, на каждой сама фигура. Сетку рисует общий
     CW.формы.сетка — ту же сетку просит «Создать куб».

     НАЖАЛ — ПРИМЕНИЛОСЬ И СОХРАНИЛОСЬ. Это главное правило этого
     раздела, и оно было потеряно: плитки лишь «отмечали, из каких
     фигур тасовать», а сами фигуры менялись только кнопкой
     «Вразнобой». Человек нажимал на шар и не видел никакого шара —
     ни сразу, ни после перезахода.

     Теперь щелчок по плитке сразу ставит эту форму всем предметам
     мира и запоминает выбор (CW.формы.поставить пишет его в память
     браузера, и он держится между заходами). Отметка на плитке
     показывает, что стоит сейчас.

     «Вразнобой, каждому свою» осталась и делает ровно то, что
     написано: раздаёт каждому кубу случайную фигуру из всех
     двадцати. Второй раз нажал — раздала заново. */
  var сеткаФорм = CW.формы.сетка(где('фр-сетка'), {
    выбран: CW.формы.общая() || CW.формы.какая(),
    выбрали: function (ключ) {
      CW.формы.поставить(ключ);
      var имя = (CW.формы.СПИСОК.filter(function (ф) { return ф.к === ключ; })[0] || {}).имя;
      CW.сказать(Т('Форма: ') + (имя ? Т(имя) : ключ), 2000);
      отметитьФормы();
    }
  });

  где('фр-вразнобой').onclick = function () {
    var ид = (CW.игра.тела() || []).map(function (т) { return т.куб.id; });
    if (!ид.length) { CW.сказать(Т('В мире пока нет кубов')); return; }
    CW.формы.вразнобой(ид);
    CW.сказать(Т('Каждому кубу своя форма'));
    отметитьФормы();
  };

  /* ── своё фото или ролик ── */
  var полеФайла = document.createElement('input');
  полеФайла.type = 'file';
  полеФайла.accept = 'image/*,video/*';
  полеФайла.style.display = 'none';
  М.тело.appendChild(полеФайла);

  где('фр-выбрать').onclick = function () { полеФайла.click(); };
  полеФайла.onchange = function () {
    var ф = полеФайла.files && полеФайла.files[0];
    полеФайла.value = '';
    if (!ф) return;
    CW.сказать('Беру…');
    CW.формы.принять(ф).then(function (вид) {
      CW.формы.накладкаВкл(true);
      CW.сказать(вид === 'видео' ? 'Ролик лёг на грани' : 'Картинка легла на грани');
      отметитьФормы();
    }).catch(function (е) {
      CW.сказать((е && е.message) || 'Этот файл не подошёл');
    });
  };

  где('фр-убрать').onclick = function () {
    CW.формы.убратьСвоё();
    CW.сказать('Своё убрано');
    отметитьФормы();
  };

  где('фр-тумблер').onclick = function () {
    if (!CW.формы.состояние().есть) {
      CW.сказать('Сперва выбери фото или ролик');
      полеФайла.click();
      return;
    }
    CW.формы.накладкаВкл();
    отметитьФормы();
  };

  var отписатьсяФормы = CW.формы.следить(отметитьФормы);
  отметитьФормы();

  function отметитьФормы() {
    /* Плитка горит та, что стоит сейчас. Раздали вразнобой — общей
       формы нет, и не горит ни одна: это честно, у каждого куба своя.
       Подсвечена в этом случае сама кнопка «Вразнобой». */
    var общая = CW.формы.общая();
    if (сеткаФорм) сеткаФорм.отметить(общая || '');
    где('фр-вразнобой').classList.toggle('главная', CW.формы.вразнобойЛи());

    var с = CW.формы.состояние();
    где('фр-тумблер').classList.toggle('вкл', с.накладка && с.есть);
    где('фр-что').textContent = с.есть
      ? ((с.вид === 'видео' ? 'Ролик' : 'Картинка') + ' выбрана. '
         + (с.накладка ? 'Лежит на всех формах.' : 'Включи, чтобы легла на формы.'))
      : 'Ляжет на любую выбранную форму. Квадратом, ролик до 30 секунд.';
  }

  /* ═════════════════════════════════════════════════════════════════════
     ПЕРСОНАЖ

     На плитке — сам персонаж, нарисованный тем же кодом, что рисует его
     в мире. Смайл «🐱» на одной системе кот, на другой котёнок, а у нас
     он один и тот же везде.
     ═════════════════════════════════════════════════════════════════════ */
  var сеткаГероев = где('пс-сетка');
  сеткаГероев.innerHTML = CW.персонаж.СПИСОК.map(function (п) {
    return '<button type="button" class="пс-кн" data-п="' + п.к + '">'
         + '<canvas width="104" height="104"></canvas>'
         + '<span>' + CW.безопасно(п.имя) + '</span></button>';
  }).join('');

  [].slice.call(сеткаГероев.children).forEach(function (б) {
    var п = б.querySelector('canvas');
    CW.персонаж.нарисовать(п.getContext('2d'), б.dataset.п, 52, 58, 30, false);
  });

  сеткаГероев.onclick = function (е) {
    var б = е.target.closest('.пс-кн');
    if (!б) return;
    var был = CW.персонаж.кто() === б.dataset.п;
    CW.персонаж.включить(был ? null : б.dataset.п);
  };

  где('пс-убрать').onclick = function () { CW.персонаж.включить(null); };

  где('пс-ряд').onclick = function (е) {
    var б = е.target.closest('.пс-дело');
    if (!б) return;
    if (!CW.персонаж.кто()) { CW.сказать(Т('Сперва выбери персонажа')); return; }
    CW.персонаж.реакция(б.dataset.вид);
  };

  /* ═════════════════════════════════════════════════════════════════════
     СВОИ ДЕЙСТВИЯ
     ═════════════════════════════════════════════════════════════════════ */
  var С = { часть: 'рука', что: 'взрыв' };

  где('св-части').innerHTML = CW.персонаж.ЧАСТИ.map(function (ч) {
    return фишка('св-часть', ч.к, ч.имя, ч.к === С.часть);
  }).join('');
  где('св-что').innerHTML = CW.персонаж.ЧТО().map(function (д) {
    return фишка('св-эффект', д.к, д.имя, д.к === С.что);
  }).join('');

  function фишка(класс, знач, подпись, выбрана) {
    return '<button type="button" class="иг-фишка ' + класс
         + (выбрана ? ' тут' : '') + '" data-з="' + знач + '">'
         + CW.безопасно(подпись) + '</button>';
  }

  М.тело.addEventListener('click', function (е) {
    var ф = е.target.closest('.иг-фишка');
    if (!ф) return;
    var ряд = ф.parentNode;
    [].slice.call(ряд.children).forEach(function (х) { х.classList.remove('тут'); });
    ф.classList.add('тут');
    if (ф.classList.contains('св-часть')) С.часть = ф.dataset.з;
    else С.что = ф.dataset.з;
  });

  где('св-сохранить').onclick = function () {
    var имя = где('св-имя').value.trim();
    if (!имя) { CW.сказать(Т('Дай действию название')); где('св-имя').focus(); return; }
    CW.персонаж.добавить({
      имя: имя,
      команда: где('св-команда').value.trim(),
      опис: где('св-опис').value.trim(),
      часть: С.часть, что: С.что
    });
    где('св-имя').value = ''; где('св-команда').value = ''; где('св-опис').value = '';
    CW.сказать(Т('Действие «') + имя + '» сохранено');
  };

  где('св-список').onclick = function (е) {
    var убрать = е.target.closest('[data-убрать]');
    if (убрать) {
      CW.персонаж.убрать(Number(убрать.dataset.убрать));
      return;
    }
    var пуск = е.target.closest('[data-пуск]');
    if (пуск) {
      var д = CW.персонаж.мои()[Number(пуск.dataset.пуск)];
      if (д) CW.персонаж.сделать(д.что);
    }
  };

  var отписатьсяГерой = CW.персонаж.следить(отметитьГероя);
  отметитьГероя();

  function отметитьГероя() {
    var кто = CW.персонаж.кто();
    [].slice.call(сеткаГероев.children).forEach(function (б) {
      б.classList.toggle('тут', б.dataset.п === кто);
    });
    где('пс-убрать').style.display = кто ? '' : 'none';
    где('пс-ряд').style.display = кто ? '' : 'none';

    var мои = CW.персонаж.мои();
    var куда = где('св-список');
    куда.innerHTML = мои.length
      ? мои.map(function (д, и) {
          var что = (CW.персонаж.ЧТО().filter(function (х) {
            return х.к === д.что;
          })[0] || {}).имя || д.что;
          return '<div class="св-своё">'
               + '<button type="button" class="св-пуск" data-пуск="' + и + '">'
               +   '<b>' + CW.безопасно(д.имя) + '</b>'
               +   '<span>' + CW.безопасно(что) + ' · ' + CW.безопасно(д.часть)
               +   (д.команда ? ' · «' + CW.безопасно(д.команда) + '»' : '') + '</span>'
               + '</button>'
               + '<button type="button" class="ок-кн опасная" data-убрать="' + и
               + '" title="' + CW.безопасно(Т('Убрать')) + '">' + CW.рисунок('M6 6 18 18M18 6 6 18') + '</button>'
               + '</div>';
        }).join('')
      : '<div class="пусто-строка">' + CW.безопасно(Т('Пока ни одного')) + '</div>';
  }

  /* ═════════════════════════════════════════════════════════════════════
     ЖЕСТЫ

     Файл с камерой приезжает только здесь и только по нажатию: код,
     который просит камеру, не должен лежать на странице у человека,
     который играет нажатиями.
     ═════════════════════════════════════════════════════════════════════ */
  var тумблер = где('иг-тумблер');
  тумблер.classList.toggle('вкл', !!CW.жестыИдут && CW.жестыИдут());

  тумблер.onclick = function () {
    var надо = !тумблер.classList.contains('вкл');
    тумблер.classList.toggle('вкл', надо);

    if (!надо) {
      if (CW.жестыВыкл) CW.жестыВыкл();
      запомнить(false);
      return;
    }
    CW.нужен('shared/жесты.js').then(function () {
      return CW.жесты(true);
    }).then(function (вышло) {
      тумблер.classList.toggle('вкл', !!вышло);
      запомнить(!!вышло);
      отметить();
    }).catch(function () {
      тумблер.classList.remove('вкл');
      CW.сказать(Т('Жесты не включились, играй нажатиями'));
    });
  };

  function запомнить(да) {
    try { CW.положить(ПАМЯТЬ, да ? '1' : ''); } catch (е) {}
  }

  function переключить() {
    if (CW.игра.идёт()) CW.игра.выключить();
    else CW.игра.включить();
    отметить();
  }

  М.открыть();
  отметить();

  return М;
});
