/* ═══════════════════════════════════════════════════════════════════════
   ВОЙТИ ПО КЛЮЧУ.

   Одно окно на два случая, и это не экономия, а честность: оба раза
   человек делает одно и то же — вставляет присланную строку.

       CW.открыть('join-by-key');                 любой ключ
       CW.открыть('join-by-key', {род: 'куб'});   только ключ куба

   ── Почему вообще два случая ───────────────────────────────────────
   Ключи в программе трёх родов: ключ доступа, ключ группы и Key 2 —
   ключ куба. Человек, которому ключ прислали, не обязан знать, какого
   он рода: ему прислали строку. Поэтому обычное окно пробует все три
   по очереди и говорит, что получилось. Три отказа подряд складываются
   в одно понятное «такой ключ никуда не подошёл».

   Но из мира — с кнопки с ключиком — спрашивают ровно ключ куба: там
   человек уже знает, что ему дали Key 2, и у него на экране мир, в
   который этот куб встанет. В этом случае окно так и называется, и
   образец в поле показывает именно CK-XXXX-XXXX-XXXX. Пробовать на
   таком ключе ещё два чужих адреса незачем, а отказ сервера («ключ не
   найден или куб истёк») точнее нашего общего.

   ── Куб после входа попадает в мир ─────────────────────────────────
   Вошёл по ключу — значит куб нужен. Поэтому он сразу добавляется в
   Юниверс (и в браузер, и на сервер), иначе человек вернулся бы в мир
   и не нашёл там куба, в который только что вошёл.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('join-by-key', function (данные) {
  'use strict';
  данные = данные || {};

  var ТОЛЬКО_КУБ = данные.род === 'куб';
  var ПАМЯТЬ = 'cw_юниверс';

  var ПУТИ = ТОЛЬКО_КУБ
    ? [{ адрес: '/cubes/join', поле: 'cube_key', что: 'куб' }]
    : [
        { адрес: '/keys/redeem',     поле: 'key',      что: 'ключ' },
        { адрес: '/groups/join-key', поле: 'key',      что: 'группа' },
        { адрес: '/cubes/join',      поле: 'cube_key', что: 'куб' }
      ];

  var М = CW.модалка({
    имя: 'вход-по-ключу',
    /* Вполовину уже остальных: внутри одна строка под ключ, как в
       «Добавить аккаунт». Десять сантиметров пустоты вокруг
       шестнадцати знаков выглядели не окном, а полосой.

       Значка и подписи под названием в узком окне нет: на пяти
       сантиметрах рядом с двумя кругляшами они съедали строку, а
       подпись и вовсе обрезалась многоточием. Про Key 2 и про то,
       что ключ даёт хозяин куба, написано под полем — там, где это
       и нужно прочитать. */
    узкое: true,
    заголовок: ТОЛЬКО_КУБ ? 'Ключ куба' : 'Войти по ключу',
    главная: { зн: 'галка', подсказка: 'Войти', делать: войти }
  });

  /* Ни подписи над полем, ни пояснения под ним. Название окна —
     «Ключ куба», образец внутри поля — CK-XXXX-XXXX-XXXX: подпись
     «КЛЮЧ КУБА *» повторяла заголовок слово в слово, а три строки
     пояснения под полем человек всё равно не читает — он пришёл
     вставить строку, которую ему прислали. Лишние пробелы мы и так
     убираем молча, при отправке. */
  var Ф = CW.поля(М.тело, [
    { имя: 'ключ', обяз: true,
      значение: данные.ключ || '',
      намёк: ТОЛЬКО_КУБ ? 'CK-XXXX-XXXX-XXXX' : 'CUBE-XXXX-XXXX-XXXX' }
  ]);

  /* Строка отказа стоит под полем, а не всплывает внизу экрана:
     всплывающую человек не успевает прочитать и жмёт «Войти» ещё раз
     с тем же ключом. */
  var беда = document.createElement('div');
  беда.className = 'ок-беда';
  Ф.узлы['ключ:поле'].appendChild(беда);

  М.открыть();

  var поле = М.тело.querySelector('input');
  if (поле) {
    поле.style.fontFamily = 'ui-monospace,SFMono-Regular,Menlo,monospace';
    поле.style.letterSpacing = '.06em';
    /* Предел ставим полю напрямую, а не через «предел» в описании: там
       он рисует счётчик знаков, а у ключа длина заранее известна, и
       «17/20» под ним — это цифры, которые человек читает и пытается
       понять, зачем они. */
    поле.maxLength = ТОЛЬКО_КУБ ? 20 : 40;
    поле.focus();
    поле.onkeydown = function (е) { if (е.key === 'Enter') войти(); };
    /* Ключи у нас прописные. Переводим по ходу набора, а не при
       отправке: человек должен видеть то, что отправится. */
    поле.addEventListener('input', function () {
      var где = this.selectionStart;
      this.value = this.value.toUpperCase();
      try { this.setSelectionRange(где, где); } catch (е) {}
      беда.classList.remove('видно');
    });
  }

  function сказатьБеду(текст) {
    беда.textContent = текст;
    беда.classList.add('видно');
    Ф.узлы['ключ:поле'].classList.add('плохо');
    if (поле) поле.focus();
  }

  function войти() {
    /* Ключ, присланный в сообщении, почти всегда приезжает с пробелами
       и переносом. Отказывать из-за этого — мелочная придирка. */
    var ключ = String(Ф.взять('ключ') || '').trim().replace(/\s+/g, '')
               .toUpperCase();

    if (!ключ) {
      сказатьБеду(ТОЛЬКО_КУБ ? 'Введи ключ куба' : 'Введи ключ');
      return;
    }
    /* Короткий ключ не стоит и отправлять: сервер ответит тем же
       «не найден», но через секунду и без подсказки, что он неполный. */
    if (ТОЛЬКО_КУБ && ключ.length < 14) {
      сказатьБеду('Введи полный ключ: CK-XXXX-XXXX-XXXX');
      return;
    }

    беда.classList.remove('видно');
    Ф.узлы['ключ:поле'].classList.remove('плохо');
    М.занят(true);
    пробовать(0, '');

    function пробовать(и, последняя) {
      if (и >= ПУТИ.length) {
        М.занят(false);
        /* В режиме куба показываем, что ответил сервер: «ключ не найден
           или куб истёк» — это две разные беды, и человеку важно знать,
           какая из них. В общем режиме сервера три, и их отказы друг
           другу не отвечают: там наша общая строка честнее. */
        сказатьБеду(ТОЛЬКО_КУБ
          ? (последняя || 'Ключ не найден или куб истёк')
          : 'Такой ключ никуда не подошёл, проверь, весь ли он');
        return;
      }
      var п = ПУТИ[и];
      var тело = {};
      тело[п.поле] = ключ;

      /* БЕЗ «тихо». Раньше здесь стояло тихо:true — и это молча ломало
         всё окно: с ним ОТКАЗ сервера не бросается, а возвращается
         пустотой. Пустота проваливалась в последнюю ветку, и на
         неверный ключ окно отвечало «Ключ принят» и перезагружало
         страницу. Отказ должен быть отказом. */
      CW.спросить(п.адрес, { способ: 'POST', тело: тело, сроком: 20000 })
        .then(function (о) {
          if (!о) { пробовать(и + 1, ''); return; }
          if (п.что === 'группа' && о && о.id) {
            М.убрать();
            CW.сказать('Вошли в группу');
            CW.уйти(CW.окно('group') + '?ид=' + о.id);
            return;
          }
          if (п.что === 'куб' && о && (о.id || о.cube_id)) {
            войтиВКуб(о.id || о.cube_id, о.name || 'Куб');
            return;
          }
          М.убрать();
          CW.сказать('Ключ принят');
          if (данные.потом) данные.потом(о);
          else CW.уйти(location.href);
        })
        .catch(function (е) {
          пробовать(и + 1, (е && !е.сеть && е.message) ? е.message
                         : (е && е.сеть ? 'Нет связи с сервером' : ''));
        });
    }
  }

  /* ═════════════════════════════════════════════════════════════════════
     КУБ НАЙДЕН

     Сначала кладём его в Юниверс, потом входим. Порядок важен: если
     уйти со страницы первым, запрос к серверу браузер оборвёт, и куб
     в мире не появится.
     ═════════════════════════════════════════════════════════════════════ */
  function войтиВКуб(ид, имя) {
    CW.вЮниверс(ид).then(function () {
      М.убрать();
      CW.сказать('Куб «' + имя + '» найден: входим');
      if (данные.потом) данные.потом({ id: ид, name: имя });
      else CW.уйти(CW.раздел('feed', ид));
    });
  }

  return М;
});
