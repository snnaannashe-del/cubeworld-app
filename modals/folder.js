/* ═══════════════════════════════════════════════════════════════════════
   ПАПКА ИЗНУТРИ: её файлы.

       CW.открыть('folder', { папка: {id, name, files} });

   Два разных способа положить сюда файл, и путать их нельзя:

       СОЗДАТЬ   — файл заводится прямо здесь, пустым, и живёт текстом
                   в базе. Так делаются заметка, таблица, скрипт.
       ЗАГРУЗИТЬ — готовый файл с компьютера уезжает в хранилище, а
                   здесь остаётся только ссылка на него. Так приезжают
                   PDF, снимок, архив.

   Почему не одной кнопкой: текст в базе можно открыть и править прямо
   в программе, а чужой файл — только скачать. Это разные вещи, и
   обещать одинаковое было бы враньём.

   Стрелка в шапке возвращает к списку папок — туда, откуда пришли.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('folder', function (данные) {
  'use strict';
  данные = данные || {};

  var ПАПКА = данные.папка || {};
  var ФАЙЛЫ = [];

  /* Своего списка видов здесь больше нет: значки, подписи и размеры
     берутся из общего shared/файлы.js. Свой список успел разойтись с
     окном создания файла — в одном были слайды, в другом нет. */
  /* Список мог приехать раньше общего файла: тогда значки нарисованы
     скрепкой, и после приезда перерисовываем. Пустой список не трогаем —
     иначе «Смотрю…» сменится на «Файлов пока нет» раньше ответа. */
  CW.нужен('shared/файлы.js').then(function () { if (ФАЙЛЫ.length) нарисовать(); });

  var М = CW.модалка({
    имя: 'папка',
    знак: 'папка',
    заголовок: ПАПКА.name || Т('Папка'),
    подзаголовок: Т('спрашиваю…'),
    /* Выхода «назад» здесь нет нарочно, и это не забывчивость. Список
       папок никуда не делся — он открыт ПОД этим окном. Стрелка
       «назад» открывала бы его ВТОРЫМ поверх первого, и окна копились
       бы стопкой: нажатие мимо закрывало бы их по одному, -1, -2, -3.
       Крестик закрывает это окно, и под ним оказывается тот самый
       список, из которого сюда пришли. */
    при_закрытии: function () { if (данные.потом) данные.потом(); },
    кнопки: [{ имя: 'залить', зн: 'скрепка', подсказка: Т('Загрузить с компьютера'),
               делать: залить }],
    главная: { зн: 'плюс', подсказка: Т('Новый файл'), делать: новыйФайл }
  });
  М.открыть();
  CW.ждём(М.тело);

  /* Поле выбора файла стоит в разметке с самого начала: поле, созданное
     на нажатие, в части браузеров молча не сообщает о выборе. */
  var поле = document.createElement('input');
  поле.type = 'file';
  поле.style.cssText =
    'position:fixed;left:0;top:0;width:1px;height:1px;opacity:0;pointer-events:none';
  document.body.appendChild(поле);
  поле.onchange = принятьФайл;

  загрузить();

  /* ── расставить файлы рукой ──
     Тот же перенос, что и у папок, и тем же файлом: двух разных
     перетаскиваний в программе быть не должно. */
  CW.нужен('shared/перетаскивание.js').then(function () {
    CW.перетаскивание(М.тело, { строка: '.пп-ряд', сложили: сложили });
  });

  function сложили(узлы) {
    var номера = узлы.map(function (у) { return Number(у.dataset.ид); })
                     .filter(function (н) { return н; });
    ФАЙЛЫ.sort(function (а, б) {
      return номера.indexOf(Number(а.id)) - номера.indexOf(Number(б.id));
    });
    /* «Тихо» здесь не значит «молча»: при сбое ответ приходит пустым,
       и об этом надо сказать вслух — иначе человек решит, что порядок
       записан, а после перезахода увидит прежний. */
    CW.спросить('/folders/' + ПАПКА.id + '/files/order',
                { способ: 'PATCH', тело: { ids: номера }, тихо: true })
      .then(function (о) { if (!о || !о.ok) throw new Error(Т('нет ответа')); })
      .catch(function () {
        CW.сказать(Т('Порядок не записался на сервере'), 5000);
        загрузить();
      });
  }

  function загрузить() {
    CW.спросить('/folders/' + ПАПКА.id + '/files', { сроком: 20000 })
      .then(function (д) {
        ФАЙЛЫ = (д && д.files) || [];
        нарисовать();
      })
      .catch(function (е) {
        М.пусто({ знак: 'внимание', заголовок: Т('Папка не открылась'),
                  текст: (е && е.сеть) ? 'Нет связи с сервером'
                                       : ((е && е.message) || 'Сервер не ответил') });
      });
  }

  function нарисовать() {
    М.имя(ПАПКА.name || Т('Папка'), счёт());
    М.тело.innerHTML = '';

    if (!ФАЙЛЫ.length) {
      М.тело.appendChild(ок('div', 'пусто-строка', Т('Файлов пока нет')));
      return;
    }

    ФАЙЛЫ.forEach(function (ф) {
      var ряд = ок('div', 'пп-ряд');
      ряд.dataset.ид = ф.id;

      var знак = ок('span', 'пп-знак');
      знак.innerHTML = CW.значок(значокВида(видЗаписи(ф)));
      знак.title = ф.name || '';
      ряд.appendChild(знак);

      var про = ок('span', 'пп-про');
      про.innerHTML = '<span class="имя"></span><span class="под"></span>';
      про.querySelector('.имя').textContent = ф.name || 'Без имени';
      /* «Видео · 15.2 КБ» понятнее, чем «MP4 · 15.2 КБ»: человек
         кладёт в папку ролик, а не расширение. */
      про.querySelector('.под').textContent =
        (CW.файлы ? CW.файлы.названием(видЗаписи(ф)) : String(ф.kind || '').toUpperCase())
        + ' · ' + размер(ф);
      ряд.appendChild(про);
      про.onclick = знак.onclick = function () { открыть(ф); };

      ряд.appendChild(кнопка('обмен', 'Перенести в другую папку', function () {
        перенести(ф);
      }));
      ряд.appendChild(кнопка('крест', 'Удалить файл', function () {
        удалить(ф);
      }, true));

      М.тело.appendChild(ряд);
    });
  }

  function счёт() {
    var н = ФАЙЛЫ.length;
    return н + ' ' + CW.склонение(н, 'файл', 'файла', 'файлов');
  }

  function размер(ф) {
    var б = Number(ф.size || 0);
    if (!б) return 'пусто';
    return CW.файлы ? CW.файлы.размер(б) : (б + ' Б');
  }

  /* Значок по виду файла — из общего списка, пока он не приехал,
     обычная скрепка: папка открывается раньше, чем общий файл. */
  function значокВида(вид) {
    return CW.файлы ? CW.файлы.значок(вид) : 'скрепка';
  }

  function открыть(ф) {
    /* Чем открыть файл, решает само окно файла: оно знает и виды, и
       редакторы. Здесь об этом не гадаем. */
    CW.открыть('file', { файл: ф, папка: ПАПКА, потом: загрузить });
  }

  function новыйФайл() {
    CW.открыть('new-file', { папка: ПАПКА, потом: загрузить });
  }

  /* ── загрузка готового файла ── */
  function залить() { поле.value = ''; поле.click(); }

  function принятьФайл() {
    var ф = поле.files && поле.files[0];
    if (!ф) return;
    М.занят(true);
    М.имя(ПАПКА.name || Т('Папка'), Т('везу файл…'));

    /* Вид везём по расширению: у снимка, ролика и бумаги разные
       пределы размера на сервере, и слать ролик «бумагой» значит
       упереться в сто мегабайт там, где можно триста. */
    CW.залить(ф, (CW.файлы && CW.файлы.везёмКак) ? CW.файлы.везёмКак(ф.name) : 'doc')
      .then(function (о) {
        return CW.спросить('/folders/' + ПАПКА.id + '/files', {
          способ: 'POST',
          тело: {
            name: ф.name || 'файл',
            kind: видПоИмени(ф.name),
            url: о.адрес,
            mime: ф.type || '',
            size: о.размер || ф.size || 0
          }
        });
      })
      .then(function () {
        М.занят(false);
        CW.сказать(Т('Файл в папке'));
        загрузить();
      })
      .catch(function (е) {
        М.занят(false);
        нарисовать();
        CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                               : ((е && е.message) || 'Файл не уехал'));
      });
  }

  /* Вид берём из расширения общим разбором. Сервер держит свой список
     и чужое ему не отдаём: что не узнали — то «file», просто файл. */
  function видПоИмени(имя) {
    return CW.файлы ? CW.файлы.видПоИмени(имя) : 'file';
  }

  /* Сервер, который ещё не знает про снимки и ролики, кладёт их видом
     «file». Чтобы строка всё равно показывала «Видео», а не скрепку,
     спрашиваем настоящий вид по имени. */
  function видЗаписи(ф) {
    return CW.файлы ? CW.файлы.видЗаписи(ф) : (ф && ф.kind) || 'file';
  }

  /* ── Перенести файл в другую папку ──
     Папка у файла на сервере одна, и смена её — это одна правка поля
     folder_id. Отдельного «переложить» на сервере нет и не нужно. */
  function перенести(ф) {
    CW.спросить('/folders', { тихо: true }).then(function (о) {
      var папки = (Array.isArray(о) ? о : ((о && о.folders) || []))
        .filter(function (п) { return String(п.id) !== String(ПАПКА.id); });
      if (!папки.length) {
        CW.сказать(Т('Другой папки пока нет: сперва заведи её'), 5000);
        return;
      }
      CW.лист([{ заголовок: Т('В какую папку?') }].concat(папки.map(function (п) {
        return {
          зн: CW.значок('папка', 16),
          подпись: п.name || ('#' + п.id),
          делать: function () {
            CW.спросить('/files/' + ф.id, {
              способ: 'PATCH', тело: { folder_id: п.id }
            }).then(function () {
              CW.сказать('«' + (ф.name || 'Файл') + '» теперь в папке «'
                       + (п.name || '#' + п.id) + '»', 3000);
              загрузить();
            }).catch(function (е) {
              CW.сказать((е && е.message) || 'Не перенеслось', 6000);
            });
          }
        };
      })), {});
    });
  }

  function удалить(ф) {
    CW.открыть('delete', {
      чего: 'файл',
      что: ф.name || 'Без имени',
      навсегда: true,
      делать: function () {
        return CW.спросить('/files/' + ф.id, { способ: 'DELETE' })
          .then(загрузить);
      }
    });
  }

  function кнопка(знак, подсказка, делать, опасная) {
    var б = ок('button', 'пп-кн' + (опасная ? ' опасная' : ''));
    б.type = 'button';
    б.innerHTML = знак === 'крест' ? CW.рисунок('M6 6 18 18M18 6 6 18')
                                   : CW.значок(знак);
    б.title = подсказка;
    б.onclick = function (е) { е.stopPropagation(); делать(); };
    return б;
  }

  function ок(тег, класс, текст) { return CW.эл(тег, класс, текст); }
});
