/* ═══════════════════════════════════════════════════════════════════════
   KEY 2 — КЛЮЧ КУБА.

   Открывается сразу после создания куба и по просьбе хозяина из самого
   куба. Показывает две вещи: сам ключ и ссылку-приглашение, в которой
   этот ключ уже подставлен.

       CW.открыть('cube-key', {ключ:'CK-…', имя:'Мой куб', часы:168,
                               значок:'🧊', куб: 12});

   ── Почему окно, а не строчка снизу ────────────────────────────────
   Ключ — единственное, чем человек пускает других в свой закрытый куб.
   Строчка внизу экрана живёт три секунды и исчезает; ключ надо успеть
   скопировать, переслать и, если нужно, перечитать. Поэтому окно,
   поэтому кнопка копирования у каждой строки и поэтому крупным.

   ── Про «не восстанавливается» ─────────────────────────────────────
   Говорим осторожно и точно: ключ не придумывается заново, но хозяин
   куба всегда может посмотреть его снова — он лежит у куба. Пугать
   «потеряешь навсегда» нельзя: это неправда, а неправда в таком месте
   стоит дорого.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('cube-key', function (данные) {
  'use strict';
  данные = данные || {};

  var КЛЮЧ  = String(данные.ключ || '');
  var ИМЯ   = String(данные.имя || 'Куб');
  var ЧАСЫ  = Number(данные.часы || 0);
  var ЗНАЧОК = String(данные.значок || '🧊');
  /* Цвет значка — тот, что выбрали в меню значка при создании куба.
     Если открывший окно его не передал (а из самого куба и из сигналов
     не передаёт никто), спрашиваем общую память цветов по номеру куба —
     ту же самую, по которой красит значки Юниверс и мир. Иначе здесь
     сидел серый смайл, хотя везде этот куб цветной. */
  var ЦВЕТЗН = String(данные.цветЗначка
                      || (CW.цветЗначка && CW.цветЗначка(данные.куб))
                      || данные.цвет || '');
  var КУБ   = данные.куб;

  /* Ссылка ведёт на титулку с ключом куба в адресе: тот, кто её
     откроет, попадёт в куб, а не на просьбу «введи ключ, который тебе
     и так прислали». Титулка ключ запоминает, и мир открывает куб
     сразу после входа — иначе ссылка работала бы только у тех, кто уже
     вошёл, то есть у своих.

     Адрес берём полный, с именем сервера: ссылку пересылают в чужую
     переписку, где «index.html» не значит ничего. */
  var ССЫЛКА = (function () {
    var путь = location.pathname.replace(/[^/]*$/, '');
    if (CW.вОкне) путь = путь.replace(/windows\/$/, '');
    return location.origin + путь + 'index.html?куб='
         + encodeURIComponent(КЛЮЧ);
  })();

  var М = CW.модалка({
    имя: 'ключ-куба',
    знак: 'ключик',
    /* Знак голый, без квадратика: в шапке и так тесно, а рамка вокруг
       ключика ничего не добавляет. */
    /* Окно открывают дважды за жизнь куба: сразу после создания и
       потом, когда ключ понадобился снова. Одна и та же надпись
       «Куб создан» во втором случае врёт. */
    заголовок: данные.создан ? 'Куб создан' : 'Key 2: ключ куба',
    /* Срок уже написан под именем куба, в теле окна. Второй раз, под
       заголовком, он только занимал строку.

       Стрелка здесь не годится: в шапке она означает «назад». Войти в
       куб — это сам куб, и значок у него тот же, что в мире. Кнопка
       обычная, серая, как крестик рядом: «войти» тут не главное дело,
       главное — забрать ключ. */
    кнопки: КУБ ? [{ имя: 'войти', зн: 'куб', подсказка: 'Войти в куб',
                     делать: войти }] : null
  });

  М.тело.innerHTML =
      '<div class="к2-лицо">'
    +   (фото() ? '<img src="' + CW.безопасно(ЗНАЧОК) + '" alt="">'
                : '<span><i' + (ЦВЕТЗН && CW.тонЗнака
                                ? ' style="filter:' + CW.тонЗнака(ЦВЕТЗН) + '"' : '')
                  + '>' + CW.безопасно(ЗНАЧОК) + '</i></span>')
    +   '<b>«' + CW.безопасно(ИМЯ) + '»</b>'
    +   '<span class="к2-срок">Key 2 действует ' + срокСловами(ЧАСЫ) + '</span>'
    + '</div>'

    + '<div class="к2-метка">Key 2: ключ куба</div>'
    + '<div class="к2-ряд">'
    +   '<code class="к2-ключ">' + CW.безопасно(КЛЮЧ || '-') + '</code>'
    +   '<button type="button" class="ок-кн к2-копия" data-что="ключ"'
    +   ' title="Скопировать ключ">' + CW.значок('копия') + '</button>'
    + '</div>'

    + '<div class="к2-метка">Ссылка-приглашение</div>'
    + '<div class="к2-ряд">'
    +   '<code class="к2-ссылка">' + CW.безопасно(ССЫЛКА) + '</code>'
    +   '<button type="button" class="ок-кн к2-копия" data-что="ссылка"'
    +   ' title="Скопировать ссылку">' + CW.значок('поделиться') + '</button>'
    + '</div>';

  function фото() { return ЗНАЧОК.indexOf('data:') === 0; }

  М.тело.addEventListener('click', function (е) {
    var б = е.target.closest('.к2-копия');
    if (!б) return;
    var что = б.dataset.что === 'ссылка' ? ССЫЛКА : КЛЮЧ;
    скопировать(что, б.dataset.что === 'ссылка' ? 'Ссылка' : 'Ключ');
  });

  М.открыть();

  function войти() {
    М.убрать();
    CW.уйти(CW.раздел('feed', КУБ));
  }

  function срокСловами(ч) {
    if (!ч) return 'пока живёт куб';
    if (ч <= 1)   return '1 час';
    if (ч <= 6)   return ч + ' часов';
    if (ч <= 24)  return '24 часа';
    if (ч <= 72)  return '3 дня';
    if (ч <= 168) return '7 дней';
    if (ч <= 720) return '1 месяц';
    return 'всегда';
  }

  /* У копирования есть запасной путь: в браузере без буфера обмена
     молчащая кнопка читается как поломка. */
  function скопировать(текст, что) {
    CW.вбуфер(текст, что + ' скопирован');
  }

  return М;
});
