/* ═══════════════════════════════════════════════════════════════════════
   ПАПКИ.

   Своё хранилище человека: папки, а в них файлы. Не переписка и не
   лента — просто место, куда кладут и откуда берут.

   Папки живут на СЕРВЕРЕ, а не в браузере. Это важно: папка, сделанная
   на телефоне, должна быть видна на компьютере, иначе это не хранилище,
   а заметка на полях одного браузера.

       CW.открыть('folders');

   Предел — пятьдесят папок на человека, и он не наш выдуманный: его
   держит сервер (ПАПОК_НА_ЧЕЛОВЕКА). Поэтому и показываем его прямо в
   заголовке: «Папки · 1 / 50». Человек должен видеть границу до того,
   как в неё упрётся.

   Что внутри папки — отдельное окно: modals/folder.js.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('folders', function (данные) {
  'use strict';
  данные = данные || {};

  var ПРЕДЕЛ = 50;          /* пока сервер не сказал свой */
  var СПИСОК = [];

  var М = CW.модалка({
    имя: 'папки',
    знак: 'папка',
    заголовок: Т('Папки'),
    подзаголовок: Т('спрашиваю…'),
    главная: { зн: 'плюс', подсказка: Т('Новая папка'), делать: новаяПапка }
  });
  М.открыть();
  CW.ждём(М.тело);

  загрузить();

  /* ── расставить папки рукой ──
     Порядок — дело человека: у одного сверху работа, у другого
     семейные снимки. Сам перенос общий и лежит в
     shared/перетаскивание.js: ровно то же нужно файлам внутри папки. */
  CW.нужен('shared/перетаскивание.js').then(function () {
    CW.перетаскивание(М.тело, { строка: '.пп-ряд', сложили: сложили });
  });

  function сложили(узлы) {
    var номера = узлы.map(function (у) { return Number(у.dataset.ид); })
                     .filter(function (н) { return н; });
    /* Список у себя переставляем сразу: окно не должно ждать сервер,
       чтобы показать то, что человек только что сделал руками. */
    СПИСОК.sort(function (а, б) {
      return номера.indexOf(Number(а.id)) - номера.indexOf(Number(б.id));
    });
    М.имя(Т('Папки'), СПИСОК.length + ' / ' + ПРЕДЕЛ);
    /* «Тихо» здесь не значит «молча»: при сбое ответ приходит пустым,
       и об этом надо сказать вслух — иначе человек решит, что порядок
       записан, а после перезахода увидит прежний. */
    CW.спросить('/folders/order',
                { способ: 'PATCH', тело: { ids: номера }, тихо: true })
      .then(function (о) { if (!о || !о.ok) throw new Error(Т('нет ответа')); })
      .catch(function () {
        CW.сказать(Т('Порядок не записался на сервере'), 5000);
        загрузить();
      });
  }

  function загрузить() {
    CW.спросить('/folders', { сроком: 20000 })
      .then(function (д) {
        д = д || {};
        СПИСОК = д.folders || [];
        if (д.limits && д.limits.folders) ПРЕДЕЛ = д.limits.folders;
        нарисовать();
      })
      .catch(function (е) {
        /* Сервер на поломку списка отвечает ошибкой, а не пустотой —
           и мы её показываем. Пустой список здесь значил бы «папок
           нет», и поломка выглядела бы как обычная пустота. */
        М.пусто({ знак: 'внимание', заголовок: Т('Папки не открылись'),
                  текст: (е && е.сеть) ? 'Нет связи с сервером'
                                       : ((е && е.message) || 'Сервер не ответил') });
      });
  }

  function нарисовать() {
    М.имя(Т('Папки'), СПИСОК.length + ' / ' + ПРЕДЕЛ);
    М.тело.innerHTML = '';

    if (!СПИСОК.length) {
      М.тело.appendChild(ок('div', 'пусто-строка', Т('Папок пока нет')));
      return;
    }

    СПИСОК.forEach(function (п) {
      var ряд = ок('div', 'пп-ряд');
      ряд.dataset.ид = п.id;

      var знак = ок('span', 'пп-знак');
      знак.innerHTML = CW.значок('папка');
      ряд.appendChild(знак);

      var про = ок('span', 'пп-про');
      про.innerHTML = '<span class="имя"></span><span class="под"></span>';
      про.querySelector('.имя').textContent = п.name || 'Без названия';
      про.querySelector('.под').textContent = файлов(п.files);
      ряд.appendChild(про);
      /* Нажатие по ряду — войти в папку. Кнопки справа ловят своё
         нажатие сами и дальше его не пускают. */
      про.onclick = знак.onclick = function () { войти(п); };

      ряд.appendChild(кнопка('карандаш', 'Переименовать', function () {
        переименовать(п);
      }));
      ряд.appendChild(кнопка('крест', 'Удалить папку', function () {
        удалить(п);
      }, true));

      М.тело.appendChild(ряд);
    });
  }

  /* Своего счёта слов тут больше нет: правило одно на всю программу
     и живёт в Т.мн - по-русски три формы, по-английски две. */
  function файлов(н) {
    н = Number(н || 0);
    return Т.с('{н} {слово}',
               { н: н, слово: Т.мн(н, 'файл', 'файла', 'файлов') });
  }

  function войти(п) {
    /* Папка закроется — список под ней перечитает себя: число файлов в
       строке должно сойтись с тем, что человек только что сделал. */
    CW.открыть('folder', { папка: п, потом: загрузить });
  }

  /* ── новая папка ──
     Имя спрашиваем здесь же, строкой под шапкой, а не отдельным окном
     с одним полем: окно ради одной строки — это два нажатия вместо
     одного и ещё один экран, который надо закрыть. */
  function новаяПапка() {
    if (СПИСОК.length >= ПРЕДЕЛ) {
      CW.сказать(Т.с('Папок уже {н}: больше сервер не держит',
                     { н: ПРЕДЕЛ }));
      return;
    }
    спроситьИмя(Т('Название новой папки'), '', function (имя, готово) {
      CW.спросить('/folders', { способ: 'POST', тело: { name: имя } })
        .then(function () { готово(); загрузить(); CW.сказать(Т('Папка заведена')); })
        .catch(function (е) { готово(е); });
    });
  }

  function переименовать(п) {
    спроситьИмя('Новое название', п.name || '', function (имя, готово) {
      CW.спросить('/folders/' + п.id, { способ: 'PATCH', тело: { name: имя } })
        .then(function () { готово(); загрузить(); })
        .catch(function (е) { готово(е); });
    });
  }

  function удалить(п) {
    CW.открыть('delete', {
      чего: 'папку',
      что: п.name || 'Без названия',
      ещё: Number(п.files || 0)
             ? ('Внутри ' + файлов(п.files) + ': они исчезнут вместе с папкой.')
             : 'Папка пустая.',
      навсегда: true,
      делать: function () {
        return CW.спросить('/folders/' + п.id, { способ: 'DELETE' })
          .then(function () { загрузить(); });
      }
    });
  }

  /* ── строка ввода поверх списка ──
     Одна на все три случая: новая папка, переименование папки и имя
     нового файла. Второй такой же строки рядом быть не должно. */
  function спроситьИмя(подпись, было, делать) {
    var старое = М.тело.querySelector('.пп-ввод');
    if (старое) старое.remove();

    var гнездо = ок('div', 'пп-ввод');
    гнездо.innerHTML =
        '<label></label>'
      + '<button type="button" class="пп-отмена" title="' + CW.безопасно(Т('Отменить')) + '">✕</button>'
      + '<div class="ряд"><input type="text" maxlength="64" spellcheck="false">'
      + '<button type="button" class="кнопка главная">' + CW.безопасно(Т('Готово')) + '</button></div>'
      + '<div class="беда"></div>';
    гнездо.querySelector('label').textContent = подпись;
    М.тело.insertBefore(гнездо, М.тело.firstChild);

    var поле = гнездо.querySelector('input');
    /* Именно кнопка из ряда с полем, а не первая кнопка в гнезде:
       первой стоит крестик отмены, и «Готово» оставалось без
       действия — нажимаешь, и ничего не происходит. */
    var кн = гнездо.querySelector('.ряд .кнопка');
    var беда = гнездо.querySelector('.беда');
    поле.value = было;
    поле.focus();
    поле.select();

    поле.onkeydown = function (е) {
      if (е.key === 'Enter') { е.preventDefault(); послать(); }
      if (е.key === 'Escape') гнездо.remove();
    };
    кн.onclick = послать;
    /* Крестик — та же отмена, что и Escape. Про Escape знают не все, а
       строка ввода стоит поверх списка и закрывать её чем-то надо. */
    гнездо.querySelector('.пп-отмена').onclick = function () { гнездо.remove(); };

    function послать() {
      var имя = поле.value.trim();
      if (!имя) { беда.textContent = Т('Название пустое'); return; }
      беда.textContent = '';
      кн.disabled = true;
      делать(имя, function (е) {
        кн.disabled = false;
        if (е) {
          беда.textContent = е.сеть ? 'Нет связи с сервером'
                                    : ((е && е.message) || 'Не вышло');
          return;
        }
        гнездо.remove();
      });
    }
  }

  function кнопка(знак, подсказка, делать, опасная) {
    var б = ок('button', 'пп-кн' + (опасная ? ' опасная' : ''));
    б.type = 'button';
    б.innerHTML = знак === 'крест' ? CW.рисунок('M6 6 18 18M18 6 6 18')
                                   : CW.значок(знак);
    б.title = подсказка;
    б.onclick = function (е) { е.stopPropagation(); делать(); };
    return б;
  }

  function ок(тег, класс, текст) { return CW.эл(тег, класс, текст); }
});
