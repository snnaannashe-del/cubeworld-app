/* ═══════════════════════════════════════════════════════════════════════
   ПОДПИСКА.

   Витрина, а не список: четыре плитки два на два — Силвер и Голд,
   месяц и год. У каждой крупная цена в CUBE, под ней срок и цена в
   долларах, у года плашка с выгодой. Ровно так это выглядит в боевой
   (`~/Desktop/25/world.html`, блок `cw-fix628-витрина`), и мерки взяты
   оттуда, а не подобраны на глаз.

   Платят CUBE'ами со счёта, а не картой: приём карт не подключён, и
   обещать его было бы нечестно. Поэтому окно показывает две вещи
   рядом — сколько стоит и сколько есть. Цена без остатка это кнопка,
   которая отказывает уже после нажатия.

   Выгода года НЕ вписана числом: считается от цены месяца этого же
   тарифа. Поменяется прайс на сервере — поменяется и число на плашке.

       CW.открыть('premium');
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('premium', function (данные) {
  'use strict';
  данные = данные || {};

  var выбран = null;           /* {ключ, срок, cube, …} */
  var ряды = [];
  var баланс = 0;

  /* Ни шапки, ни подвала: и то и другое здесь лишняя рама. Название с
     алмазом и строчка про баланс стоят прямо в теле — так они и
     выглядят в боевой, — а выход даёт крестик в углу окна. Кнопка
     «Отмена» не нужна: крестик и касание мимо делают ровно то же. */
  var М = CW.модалка({
    имя: 'премиум',
    шапка: false,
    крестУгол: true,
    /* Окно закрыли — опрос заказа надо погасить, иначе он будет стучать
       на сервер до конца жизни вкладки. На тариф это не влияет: включает
       его вебхук, а не этот опрос. */
    при_закрытии: function () { if (часы) { clearInterval(часы); часы = null; } }
  });
  М.открыть();
  М.тело.innerHTML = '<div class="пусто-строка">' + CW.безопасно(Т('Загрузка…')) + '</div>';

  var оплатить = null;         /* кнопка внизу тела */

  Promise.all([
    CW.спросить('/premium/price',  { тихо: true }),
    CW.спросить('/premium/status', { тихо: true }),
    CW.спросить('/cube/balance',   { тихо: true })
  ]).then(function (о) {
    баланс = Math.floor(Number((о[2] && о[2].balance) || 0));
    собрать(о[0] || {});
    нарисовать(о[1] || {});
  }).catch(function (е) {
    М.пусто({ знак: 'внимание', заголовок: Т('Не открылось'),
              текст: (е && е.сеть) ? 'Нет связи с сервером'
                                   : ((е && е.message) || 'Сервер не ответил') });
  });

  /* Четыре плитки по порядку: сверху Силвер (месяц, год), снизу Голд. */
  function собрать(цены) {
    ряды = [];
    var планы = (цены && цены.plans) || {};
    ['silver', 'gold'].forEach(function (к) {
      var п = планы[к];
      if (!п) return;
      ['month', 'year'].forEach(function (с) {
        var цифра = Number(п[с] || 0);
        if (!цифра) return;
        var выгода = 0;
        if (с === 'year' && Number(п.month)) {
          выгода = Math.round((1 - (цифра / (12 * Number(п.month)))) * 100);
        }
        ряды.push({
          ключ: к, срок: с,
          имя: Т(п.name || к),
          cube: цифра,
          usd: Number(с === 'year' ? п.usd_year : п.usd_month) || 0,
          выгода: выгода > 0 ? выгода : 0
        });
      });
    });
  }

  /* Название с алмазом и строчка под ним. Алмаз тот же и того же
     цвета, что на карточке «Подписка» в «Заработать»: человек нажал на
     неё и должен узнать окно. */
  function шапкаВТеле(под) {
    var ш = CW.кусок('подп-шапка',
        '<span class="зн">' + CW.значок('алмаз', 22) + '</span>'
      + '<span><b>' + CW.безопасно(Т('Подписка')) + '</b>'
      + (под ? '<span class="под">' + CW.безопасно(под) + '</span>' : '')
      + '</span>');
    М.тело.appendChild(ш);
  }

  function нарисовать(состояние) {
    М.тело.innerHTML = '';
    оплатить = null;

    if (состояние && состояние.is_premium) {
      шапкаВТеле('уже есть');
      М.тело.appendChild(CW.кусок('подп-итог',
        Т('Подписка уже включена.') + ' '
        + (состояние.info && состояние.info.until
            ? Т.с('До {срок}', { срок: CW.безопасно(состояние.info.until) })
            : Т('Продлить можно, когда срок начнёт подходить к концу.'))));
      return;
    }

    if (!ряды.length) {
      шапкаВТеле('');
      М.тело.appendChild(CW.кусок('подп-итог',
          Т('Сервер не прислал ни одного тарифа.')));
      return;
    }

    шапкаВТеле(Т.с('На балансе {н} CUBE', { н: баланс }));

    var витрина = document.createElement('div');
    витрина.className = 'подп-витрина';

    ряды.forEach(function (р) {
      var хватает = баланс >= р.cube;
      var б = document.createElement('button');
      б.type = 'button';
      б.className = 'подп-плитка подп-' + р.ключ
                  + (выбран === р ? ' выбрана' : '')
                  + (хватает ? '' : ' мало');
      б.innerHTML =
          '<span class="имя">' + CW.безопасно(р.имя) + '</span>'
        + '<span class="цена">' + р.cube + ' <small>CUBE</small></span>'
        + '<span class="низ">'
        +   CW.безопасно(р.срок === 'year' ? Т('Год') : Т('Месяц'))
        +   (р.usd ? ' · $' + р.usd : '')
        + '</span>'
        + (р.выгода ? '<span class="скидка">−' + р.выгода + '%</span>' : '');
      /* Плитка выбирается всегда, даже когда CUBE не хватает. Прежде
         нехватка просто отказывала нажатию — и человек с пустым счётом
         не мог ни выбрать тариф, ни добраться до оплаты криптой, которая
         ему как раз и нужна. Нехватку показываем ниже и гасим только
         кнопку списания. */
      б.onclick = function () {
        выбран = р;
        нарисовать(состояние);
      };
      витрина.appendChild(б);
    });

    М.тело.appendChild(витрина);

    /* Строчка под витриной — только когда выбрали: до выбора говорить
       нечего, а место она занимала бы всегда. */
    if (выбран) {
      var довольно = баланс >= выбран.cube;
      М.тело.appendChild(CW.кусок('подп-итог', довольно
        ? ('' + CW.безопасно(Т('Спишем')) + ' <b>' + выбран.cube + ' CUBE</b> '
           + CW.безопасно(Т('за «')) + '' + CW.безопасно(выбран.имя) + '» на '
           + (выбран.срок === 'year' ? 'год' : 'месяц') + '.')
        : CW.безопасно(Т.с('Не хватает {н} CUBE. Можно заплатить криптой.',
                           { н: Math.ceil(выбран.cube - баланс) }))));
    }

    оплатить = document.createElement('button');
    оплатить.type = 'button';
    оплатить.className = 'подп-оплатить';
    оплатить.textContent = Т('Оплатить');
    оплатить.disabled = !выбран || баланс < выбран.cube;
    оплатить.onclick = купить;
    М.тело.appendChild(оплатить);

    /* Вторая дорога: заплатить криптой напрямую, не заводя CUBE на счёт.
       Показываем её всегда, когда тариф выбран, а не только при нехватке
       баланса: человеку с пустым счётом иначе пришлось бы сперва пройти
       свайп, а он может просто не захотеть держать CUBE. */
    if (выбран) {
      var криптой = document.createElement('button');
      криптой.type = 'button';
      криптой.className = 'подп-криптой';
      криптой.textContent = выбран.usd
          ? Т.с('Оплатить криптой · ${сумма}', { сумма: выбран.usd })
          : Т('Оплатить криптой');
      криптой.onclick = выбратьМонету;
      М.тело.appendChild(криптой);
    }
  }

  /* ═════════════════════════════════════════════════════════════════════
     ОПЛАТА КРИПТОЙ

     Цена здесь в долларах, а не в CUBE: сколько это в монете, считает
     провайдер в миг выставления счёта. Считали бы сами — курс успел бы
     уехать между расчётом и переводом, провайдер счёл бы платёж
     неполным, и тариф не включился бы при списанных деньгах.
     ═════════════════════════════════════════════════════════════════════ */
  var часы = null;              /* опрос заказа */

  function выбратьМонету() {
    if (!выбран) return;
    CW.спросить('/swap/catalogue', { тихо: true }).then(function (к) {
      if (!к || !к.provider_ready) {
        CW.сказать(Т('Приём оплаты криптой ещё не подключён'), 5000);
        return;
      }
      var пункты = [{ заголовок: Т('Чем платить') }];
      (к.coins || []).forEach(function (м) {
        (м.nets || []).forEach(function (с) {
          пункты.push({
            подпись: м.sym + ' · ' + (с.name || с.code),
            делать: function () { счёт(м.sym, с.code); }
          });
        });
      });
      пункты.push({ зн: CW.значок('стрелка', 16), подпись: Т('Передумать') });
      CW.лист(пункты);
    }).catch(function () {
      CW.сказать(Т('Не удалось получить список монет'));
    });
  }

  function счёт(монета, сеть) {
    М.занят(true);
    CW.спросить('/plan/invoice', {
      способ: 'POST', сроком: 30000,
      тело: { plan: выбран.ключ, period: выбран.срок, coin: монета, net: сеть }
    }).then(function (з) {
      М.занят(false);
      ждём(з);
    }).catch(function (е) {
      М.занят(false);
      CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                             : ((е && е.message) || Т('Счёт не выставился')));
    });
  }

  /* Экран ожидания перевода. Сеть вынесена отдельной строкой нарочно:
     именно на ней теряют деньги, отправив монету не туда. */
  function ждём(з) {
    М.тело.innerHTML = '';
    /* Имя тарифа и срок — оба уже переведены по отдельности, собирать их
       через словарь незачем: точка между ними одинакова во всех языках. */
    шапкаВТеле(выбран.имя + ' · ' + Т(выбран.срок === 'year' ? 'Год' : 'Месяц'));

    М.тело.appendChild(CW.кусок('подп-итог',
        '<b>' + CW.безопасно(Т('Переведи ровно')) + ' ' + CW.безопасно(String(з.amount))
      + ' ' + CW.безопасно(з.coin) + '</b> '
      + CW.безопасно(Т('в сети', 'блокчейн')) + ' <b>' + CW.безопасно(з.net) + '</b>.<br>'
      + CW.безопасно(Т('Другая сеть: деньги потеряются.'))
      + '<div class="св-адрес подп-адрес">' + CW.безопасно(з.pay_address || '') + '</div>'
      + (з.pay_memo ? '<div class="св-адрес">memo / tag: '
                    + CW.безопасно(з.pay_memo) + '</div>' : '')));

    var коп = document.createElement('button');
    коп.type = 'button';
    коп.className = 'подп-оплатить';
    коп.textContent = Т('Скопировать адрес');
    коп.onclick = function () {
      CW.вбуфер(з.pay_address || '', Т('Адрес скопирован'));
    };
    М.тело.appendChild(коп);

    var ход = CW.кусок('подп-итог', CW.безопасно(
        Т('Ждём перевод. Окно можно закрыть: тариф включится сам, как '
        + 'только деньги дойдут.')));
    М.тело.appendChild(ход);

    /* Опрос, а не вечное ожидание: включает тариф вебхук на сервере, здесь
       мы только показываем, что это уже случилось. */
    var осталось = 120;          /* 120 × 5 с = десять минут */
    if (часы) clearInterval(часы);
    часы = setInterval(function () {
      if (--осталось <= 0) { clearInterval(часы); часы = null; return; }
      CW.спросить('/plan/order/' + з.order_id, { тихо: true })
        .then(function (о) {
          if (!о) return;
          if (о.status === 'done') {
            clearInterval(часы); часы = null;
            CW.сказать(Т('Подписка включена'));
            М.убрать();
            if (данные.потом) данные.потом(о);
          } else if (о.status === 'paid') {
            ход.textContent = Т('Перевод увиден, ждём подтверждения сети.');
          } else if (о.status === 'failed') {
            clearInterval(часы); часы = null;
            ход.textContent = Т('Платёж не прошёл. Деньги, если ушли, '
                              + 'вернутся отправителю.');
          }
        }).catch(function () { /* сеть мигнула — попробуем на следующем круге */ });
    }, 5000);
  }

  function купить() {
    if (!выбран) return;

    /* Называем сумму и что за неё будет — и только потом списываем. */
    CW.лист([
      { заголовок: Т.с('Списать {н} CUBE за «{что}» на {срок}?',
                       { н: выбран.cube, что: выбран.имя,
                         срок: Т(выбран.срок === 'year' ? 'год' : 'месяц') }) },
      { зн: CW.значок('ромб', 16), подпись: Т('Оплатить'), делать: function () {
          М.занят(true);
          CW.спросить('/premium/buy', {
            способ: 'POST', сроком: 30000,
            тело: { plan: выбран.ключ, period: выбран.срок,
                    months: выбран.срок === 'year' ? 12 : 1 }
          }).then(function (о) {
            CW.сказать(Т('Подписка включена'));
            if (о && о.balance != null) CW.обновитьБаланс(о.balance);
            М.убрать();
            if (данные.потом) данные.потом(о);
          }).catch(function (е) {
            М.занят(false);
            CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                                   : ((е && е.message) || Т('Не купилось')));
          });
        } },
      { зн: CW.значок('стрелка', 16), подпись: Т('Передумать') }
    ]);
  }

  return М;
});
