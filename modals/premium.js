/* ═══════════════════════════════════════════════════════════════════════
   ПОДПИСКА.

   Витрина, а не список: четыре плитки два на два — Силвер и Голд,
   месяц и год. У каждой крупная цена в CUBE, под ней срок и цена в
   долларах, у года плашка с выгодой. Ровно так это выглядит в боевой
   (`~/Desktop/25/world.html`, блок `cw-fix628-витрина`), и мерки взяты
   оттуда, а не подобраны на глаз.

   Платят CUBE'ами со счёта, а не картой: приём карт не подключён, и
   обещать его было бы нечестно. Поэтому окно показывает две вещи
   рядом — сколько стоит и сколько есть. Цена без остатка это кнопка,
   которая отказывает уже после нажатия.

   Выгода года НЕ вписана числом: считается от цены месяца этого же
   тарифа. Поменяется прайс на сервере — поменяется и число на плашке.

       CW.открыть('premium');
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('premium', function (данные) {
  'use strict';
  данные = данные || {};

  var выбран = null;           /* {ключ, срок, cube, …} */
  var ряды = [];
  var баланс = 0;

  /* Ни шапки, ни подвала: и то и другое здесь лишняя рама. Название с
     алмазом и строчка про баланс стоят прямо в теле — так они и
     выглядят в боевой, — а выход даёт крестик в углу окна. Кнопка
     «Отмена» не нужна: крестик и касание мимо делают ровно то же. */
  var М = CW.модалка({
    имя: 'премиум',
    шапка: false,
    крестУгол: true
  });
  М.открыть();
  М.тело.innerHTML = '<div class="пусто-строка">' + CW.безопасно(Т('Загрузка…')) + '</div>';

  var оплатить = null;         /* кнопка внизу тела */

  Promise.all([
    CW.спросить('/premium/price',  { тихо: true }),
    CW.спросить('/premium/status', { тихо: true }),
    CW.спросить('/cube/balance',   { тихо: true })
  ]).then(function (о) {
    баланс = Math.floor(Number((о[2] && о[2].balance) || 0));
    собрать(о[0] || {});
    нарисовать(о[1] || {});
  }).catch(function (е) {
    М.пусто({ знак: 'внимание', заголовок: Т('Не открылось'),
              текст: (е && е.сеть) ? 'Нет связи с сервером'
                                   : ((е && е.message) || 'Сервер не ответил') });
  });

  /* Четыре плитки по порядку: сверху Силвер (месяц, год), снизу Голд. */
  function собрать(цены) {
    ряды = [];
    var планы = (цены && цены.plans) || {};
    ['silver', 'gold'].forEach(function (к) {
      var п = планы[к];
      if (!п) return;
      ['month', 'year'].forEach(function (с) {
        var цифра = Number(п[с] || 0);
        if (!цифра) return;
        var выгода = 0;
        if (с === 'year' && Number(п.month)) {
          выгода = Math.round((1 - (цифра / (12 * Number(п.month)))) * 100);
        }
        ряды.push({
          ключ: к, срок: с,
          имя: Т(п.name || к),
          cube: цифра,
          usd: Number(с === 'year' ? п.usd_year : п.usd_month) || 0,
          выгода: выгода > 0 ? выгода : 0
        });
      });
    });
  }

  /* Название с алмазом и строчка под ним. Алмаз тот же и того же
     цвета, что на карточке «Подписка» в «Заработать»: человек нажал на
     неё и должен узнать окно. */
  function шапкаВТеле(под) {
    var ш = CW.кусок('подп-шапка',
        '<span class="зн">' + CW.значок('алмаз', 22) + '</span>'
      + '<span><b>' + CW.безопасно(Т('Подписка')) + '</b>'
      + (под ? '<span class="под">' + CW.безопасно(под) + '</span>' : '')
      + '</span>');
    М.тело.appendChild(ш);
  }

  function нарисовать(состояние) {
    М.тело.innerHTML = '';
    оплатить = null;

    if (состояние && состояние.is_premium) {
      шапкаВТеле('уже есть');
      М.тело.appendChild(CW.кусок('подп-итог',
        Т('Подписка уже включена.') + ' '
        + (состояние.info && состояние.info.until
            ? Т.с('До {срок}', { срок: CW.безопасно(состояние.info.until) })
            : Т('Продлить можно, когда срок начнёт подходить к концу.'))));
      return;
    }

    if (!ряды.length) {
      шапкаВТеле('');
      М.тело.appendChild(CW.кусок('подп-итог',
          Т('Сервер не прислал ни одного тарифа.')));
      return;
    }

    шапкаВТеле(Т.с('На балансе {н} CUBE', { н: баланс }));

    var витрина = document.createElement('div');
    витрина.className = 'подп-витрина';

    ряды.forEach(function (р) {
      var хватает = баланс >= р.cube;
      var б = document.createElement('button');
      б.type = 'button';
      б.className = 'подп-плитка подп-' + р.ключ
                  + (выбран === р ? ' выбрана' : '')
                  + (хватает ? '' : ' мало');
      б.innerHTML =
          '<span class="имя">' + CW.безопасно(р.имя) + '</span>'
        + '<span class="цена">' + р.cube + ' <small>CUBE</small></span>'
        + '<span class="низ">'
        +   CW.безопасно(р.срок === 'year' ? Т('Год') : Т('Месяц'))
        +   (р.usd ? ' · $' + р.usd : '')
        + '</span>'
        + (р.выгода ? '<span class="скидка">−' + р.выгода + '%</span>' : '');
      б.onclick = function () {
        if (!хватает) {
          CW.сказать(Т.с('Не хватает {н} CUBE',
                         { н: Math.ceil(р.cube - баланс) }));
          return;
        }
        выбран = р;
        нарисовать(состояние);
      };
      витрина.appendChild(б);
    });

    М.тело.appendChild(витрина);

    /* Строчка под витриной — только когда выбрали: до выбора говорить
       нечего, а место она занимала бы всегда. */
    if (выбран) {
      М.тело.appendChild(CW.кусок('подп-итог',
          '' + CW.безопасно(Т('Спишем')) + ' <b>' + выбран.cube + ' CUBE</b> ' + CW.безопасно(Т('за «')) + ''
        + CW.безопасно(выбран.имя) + '» на '
        + (выбран.срок === 'year' ? 'год' : 'месяц') + '.'));
    }

    оплатить = document.createElement('button');
    оплатить.type = 'button';
    оплатить.className = 'подп-оплатить';
    оплатить.textContent = Т('Оплатить');
    оплатить.disabled = !выбран;
    оплатить.onclick = купить;
    М.тело.appendChild(оплатить);
  }

  function купить() {
    if (!выбран) return;

    /* Называем сумму и что за неё будет — и только потом списываем. */
    CW.лист([
      { заголовок: Т.с('Списать {н} CUBE за «{что}» на {срок}?',
                       { н: выбран.cube, что: выбран.имя,
                         срок: Т(выбран.срок === 'year' ? 'год' : 'месяц') }) },
      { зн: CW.значок('ромб', 16), подпись: Т('Оплатить'), делать: function () {
          М.занят(true);
          CW.спросить('/premium/buy', {
            способ: 'POST', сроком: 30000,
            тело: { plan: выбран.ключ, period: выбран.срок,
                    months: выбран.срок === 'year' ? 12 : 1 }
          }).then(function (о) {
            CW.сказать(Т('Подписка включена'));
            if (о && о.balance != null) CW.обновитьБаланс(о.balance);
            М.убрать();
            if (данные.потом) данные.потом(о);
          }).catch(function (е) {
            М.занят(false);
            CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                                   : ((е && е.message) || Т('Не купилось')));
          });
        } },
      { зн: CW.значок('стрелка', 16), подпись: Т('Передумать') }
    ]);
  }

  return М;
});
