/* ═══════════════════════════════════════════════════════════════════════
   ЗАЛ ИГР.

       cubeworld-app/modals/games.js
       CW.открыть('games');

   Восемь игр, и все играются: CryptoTetris, CubeRun, DataMine,
   CipherBreak, Phantom Escape, Block Trade, TrustChain, CubeBuilder.
   Открывается с кнопки «Игры» в полосе мира.

   ── Что здесь есть, кроме названий ────────────────────────────────
   Личный рекорд прямо на карточке. Без него зал — список слов: человек
   не помнит, играл ли он в CipherBreak и чем кончилось.

   ── Про CUBE честно ───────────────────────────────────────────────
   Игры дают очки и рекорд, а не монеты. Начисление CUBE живёт на
   сервере, и рисовать монеты в браузере значило бы врать: после
   перезагрузки они всё равно исчезнут. Раньше об этом была строка под
   карточками; её убрали — объяснение осталось в документах, в разделе
   про CUBE, а зал игр снова про игры.

   ── Четыре в ряд ──────────────────────────────────────────────────
   Два в ряд и четыре ряда давали окно 13,5 см высотой: выше, чем
   шире, с прокруткой. Четыре в ряд и два ряда — половина той высоты
   при той же ширине в 10 см.

   Сами игры лежат отдельными файлами в games/ и приезжают по нажатию;
   общая оболочка — shared/игры.js.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('games', function (данные) {
  'use strict';
  данные = данные || {};

  var М = CW.модалка({
    имя: 'игры',
    /* Без квадратной подложки и своего цвета — лилового. Подзаголовка
       «восемь штук» нет: восемь карточек видно и так, а строка под
       названием поднимала шапку. */
    /* Тот же джойстик, что на кнопке в полосе мира, которой это окно и
       открывают: человек нажал значок — и видит его же в шапке. Кубок
       обещал турнирную таблицу, которой тут нет. */
    знак: 'джойстик',
    знакЦвет: '#a78bfa',
    заголовок: Т('Игры')
  });

  CW.нужен('shared/игры.js').then(собрать).catch(function () {
    М.пусто({ знак: 'внимание', заголовок: Т('Игры не приехали'),
              текст: 'Проверь связь и открой зал ещё раз.' });
  });

  М.открыть();

  function собрать() {
    var сетка = document.createElement('div');
    сетка.className = 'зи-сетка';

    CW.игрыСписок().forEach(function (и) {
      var рек = CW.рекордИгры(и.к);
      var к = document.createElement('button');
      к.type = 'button';
      к.className = 'зи-карта';
      к.innerHTML =
          '<span class="зи-знак">' + CW.значок(и.зн) + '</span>'
        + '<span class="зи-имя">' + CW.безопасно(и.имя) + '</span>'
        + '<span class="зи-рек">'
        +   (рек ? ('рекорд ' + рек) : 'рекорда ещё нет')
        + '</span>'
        + '<span class="зи-играть">' + CW.безопасно(Т('Играть')) + '</span>';
      к.querySelector('.зи-знак').style.color = и.цвет;
      к.onclick = function () { М.закрыть(); CW.играть(и.к); };
      сетка.appendChild(к);
    });

    М.тело.innerHTML = '';
    М.тело.appendChild(сетка);

    /* Строки про CUBE внизу больше нет. Она объясняла, чего в зале не
       происходит, — а человек пришёл сюда играть, а не читать, за что
       начисляют монеты. Это написано в документах, в разделе про CUBE. */

    return М;
  }

  return М;
});
