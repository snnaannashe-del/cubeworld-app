/* ═══════════════════════════════════════════════════════════════════════
   УСТАНОВИТЬ CUBE.

       cubeworld-app/modals/download.js
       CW.открыть('download');

   Скачивать нечего и не надо: приложение — это сама страница. Android и
   настольный Chrome ставят её по-настоящему, своим окном и своим
   значком. Айфон умеет то же, но только руками, через «Поделиться».
   Safari на Маке — через «Файл → Добавить в Dock».

   Поэтому строка в меню смотрит, на чём её нажали, и делает то
   единственное, что на этом устройстве возможно:

       уже стоит            — говорим об этом и не открываем окно;
       браузер сам умеет    — зовём настоящее окно установки, без нашего;
       не умеет             — показываем шаги ровно для этого браузера.

   ── Почему окно не рассказывает, что приложения нет ───────────────
   Рассказывало. Это была правда про App Store и неправда про дело:
   значок на экране человек получает сегодня, и он работает. Окно,
   которое начинает с «пока нет», человек закрывает, не дочитав до
   того, что есть.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('download', function (данные) {
  'use strict';
  данные = данные || {};

  var у = String(navigator.userAgent || '');
  var айфон = /iPad|iPhone|iPod/.test(у)
           || (/Macintosh/.test(у) && navigator.maxTouchPoints > 1);
  var мак = /Macintosh/.test(у) && !айфон;

  var ШАГИ = айфон
    ? ['Нажми «Поделиться» внизу экрана',
       'Выбери «На экран „Домой“»',
       'Нажми «Добавить» справа вверху']
    : (мак
       ? ['Открой меню «Файл» в строке сверху',
          'Выбери «Добавить в Dock»']
       : ['Открой меню браузера',
          'Выбери «Установить приложение»']);

  var М = CW.модалка({
    имя: 'установить',
    знак: 'скачать',
    заголовок: Т('Установить Cube')
  });

  /* ── 1. Уже стоит ──
     Проверяем не браузер, а способ запуска: страница, открытая со
     значка, идёт в режиме standalone. Открывать ей окно с шагами
     значило бы учить человека тому, что он уже сделал. */
  var стоит = false;
  try {
    стоит = (window.matchMedia
             && window.matchMedia('(display-mode: standalone)').matches)
         || window.navigator.standalone === true;
  } catch (е) {}

  if (стоит) {
    CW.сказать(Т('Приложение уже установлено'));
    М.убрать();
    return М;
  }

  /* ── 2. Браузер умеет сам ──
     Оболочка ловит beforeinstallprompt и держит его в CW_установка.
     Настоящее окно установки всегда лучше наших картинок: оно ставит
     приложение одним нажатием, а не объясняет, как это сделать. */
  var предложение = window.CW_установка || null;
  if (предложение) {
    window.CW_установка = null;
    М.убрать();
    try {
      предложение.prompt();
      if (предложение.userChoice && предложение.userChoice.then) {
        предложение.userChoice.then(function (в) {
          if (!в || в.outcome !== 'accepted') {
            window.CW_установка = предложение;   /* вернём, чтобы можно было ещё раз */
            CW.сказать(Т('Установка отменена'));
          } else {
            CW.сказать(Т('Готово: значок на месте'));
          }
        });
      }
    } catch (е) {
      window.CW_установка = предложение;
    }
    return М;
  }

  /* ── 3. Шаги ──
     Кнопки «Понятно» внизу нет нарочно: она делала бы ровно то же, что
     крестик в шапке и нажатие мимо окна. Две кнопки на одно действие
     человек читает как два разных действия. */
  var полка = document.createElement('div');
  полка.className = 'ск-шаги';
  полка.innerHTML = ШАГИ.map(function (т, и) {
    return '<div class="ск-шаг"><span class="ск-номер">' + (и + 1) + '</span>'
         + '<span>' + CW.безопасно(т) + '</span></div>';
  }).join('');
  М.тело.appendChild(полка);

  М.открыть();
  return М;
});
