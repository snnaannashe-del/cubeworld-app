/* ═══════════════════════════════════════════════════════════════════════
   ПЕРЕВОД CUBE.

   Деньги уходят человеку, а не номеру. Поэтому окно сперва НАХОДИТ
   получателя и показывает его имя и лицо, и только потом даёт нажать
   «Перевести». Перевод по номеру вслепую — главный способ отправить
   деньги не туда.

   Подтверждение называет сумму и имя. «Точно?» без суммы — не вопрос.

       CW.открыть('transfer', {кому: 7, сколько: 100});

   «кому» и «сколько» приходят уже набранными из строки в кошельке.
   Подтверждение от этого не отменяется: имя — ещё не человек.
   ═══════════════════════════════════════════════════════════════════════ */
CW.модаль('transfer', function (данные) {
  'use strict';
  данные = данные || {};

  var нашли = null;          /* {id, display_name, avatar_url} */
  var баланс = 0, предел = 0;
  var часы = null;

  /* Подзаголовка у окна нет. Строка «на счету 0 CUBE · в день не
     больше 500» висела под названием всегда, даже когда переводить
     нечего, и повторяла то, что и так написано в кошельке. Предел и
     остаток скажет сам перевод, если в них упрёшься. */
  var М = CW.модалка({
    имя: 'перевод',
    знак: 'монета',
    заголовок: 'Перевести CUBE',
    главная: { зн: 'монета', подсказка: 'Перевести', делать: спросить }
  });

  /* Поле «Кому» при открытии ПУСТОЕ, даже когда получатель уже
     известен. Раньше в него клали номер человека («1»), и окно тут же
     показывало «Никого не нашла»: поиск ищет по нику и имени, а не по
     внутреннему номеру, да и человек этого номера не вводил.

     Теперь известного получателя мы просто находим по номеру и
     показываем карточкой с именем и лицом, а поле остаётся пустым и
     служит для поиска, если захочется сменить получателя. */
  var Ф = CW.поля(М.тело, [
    /* «обяз» здесь нет нарочно: заполненность проверяется не по
       буквам в поле, а по НАЙДЕННОМУ человеку — см. спросить(). */
    { имя: 'кому', подпись: 'Кому',
      намёк: '@ник, имя или номер',
      менять: отложенноИскать },
    { имя: 'сколько', подпись: 'Сколько CUBE', вид: 'число', обяз: true,
      шаг: '1', наим: 1, намёк: '100',
      значение: данные.сколько ? String(данные.сколько) : '' },
    { имя: 'записка', подпись: 'Записка', предел: 140,
      намёк: 'Необязательно: получатель её увидит' }
  ]);

  var карточка = document.createElement('div');
  карточка.className = 'пер-кто';
  карточка.style.display = 'none';
  Ф.узлы['кому:поле'].appendChild(карточка);

  М.открыть();
  М.кнопки['главная'].disabled = true;

  /* Остаток нужен для проверки суммы, но на экран его здесь не
     выводим: он есть в кошельке и в верхней полосе. */
  CW.спросить('/cube/balance', { тихо: true }).then(function (б) {
    баланс = Number((б && б.balance) || 0);
    предел = Number((б && б.transfer_day_limit) || 0);
  }).catch(function () {});

  if (данные.кому) поНомеру(данные.кому);

  /* ── ПОЛУЧАТЕЛЬ ИЗВЕСТЕН ЗАРАНЕЕ ──
     «Чаевые автору» и строка в кошельке знают номер человека. Берём по
     нему карточку с сервера: имя, лицо, UID. Не вышло — поле просто
     остаётся пустым, и человек ищет сам. Молча врать номером в поле мы
     больше не будем. */
  function поНомеру(номер) {
    номер = Number(номер) || 0;
    if (!номер) return;
    CW.спросить('/users/' + номер, { тихо: true })
      .then(function (ч) {
        if (!ч || !(ч.id || ч.user_id)) return;
        ч.id = ч.id || ч.user_id;
        показать(ч);
      })
      .catch(function () {});
  }

  /* Искать на каждую букву — это запрос на каждую букву. Ждём паузы. */
  function отложенноИскать(что) {
    нашли = null;
    М.кнопки['главная'].disabled = true;
    карточка.style.display = 'none';
    clearTimeout(часы);
    if (!String(что || '').trim()) return;
    часы = setTimeout(function () { искать(что); }, 300);
  }

  function искать(что) {
    /* Спрашивает общая рука: один разбор ответа на кошелёк, это окно и
       чаты. Прежде три файла разбирали ответ порознь — и это тот
       случай, где расхождение стоит перевода не тому. */
    CW.найтиЛюдей(что)
      .then(function (ряды) {
        var найден = ряды[0];
        if (!найден) { не(); return; }
        показать(найден);
      })
      .catch(не);
  }

  /* Карточка найденного: лицо, имя, UID. Одна на оба пути — и когда
     искали руками, и когда получатель пришёл готовым. */
  function показать(человек) {
    нашли = человек;
    /* В поле НИЧЕГО не вписываем. Поле — строка поиска, его заполняет
       человек. Кому переводим, видно по карточке под ним: лицо, имя,
       UID. Подставленное имя читалось как «я это ввела», хотя никто не
       вводил, и путало ровно так же, как раньше номер. */
    карточка.style.display = 'flex';
    карточка.innerHTML = '';
    карточка.appendChild(CW.кружок({
      размер: 36, кто: человек.id, снимок: человек.avatar_url,
      версия: человек.avatar_ver, значок: '👤' }));
    var кто = document.createElement('div');
    кто.className = 'кто';
    кто.innerHTML = '<b>' + CW.безопасно(CW.имяЧеловека(человек)) + '</b>'
                  + '<span>UID · ' + CW.безопасно(человек.uid || человек.id) + '</span>';
    карточка.appendChild(кто);
    М.кнопки['главная'].disabled = false;
  }

  function не() {
    нашли = null;
    М.кнопки['главная'].disabled = true;
    карточка.style.display = 'flex';
    карточка.innerHTML = '<div class="кто"><b>Никого не нашла</b>'
      + '<span>Проверь @ник или номер</span></div>';
  }

  function спросить() {
    if (!Ф.проверить()) return;          /* сумма */
    if (!нашли) {
      var поле = Ф.узлы['кому:поле'];
      if (поле) поле.classList.add('плохо');
      if (Ф.узлы['кому'] && Ф.узлы['кому'].focus) Ф.узлы['кому'].focus();
      CW.сказать('Сперва найди, кому переводим');
      return;
    }
    if (Ф.узлы['кому:поле']) Ф.узлы['кому:поле'].classList.remove('плохо');

    var сколько = Math.floor(Number(Ф.взять('сколько')) || 0);
    if (сколько <= 0) { CW.сказать('Сумма должна быть больше нуля'); return; }
    if (сколько > баланс) {
      CW.сказать('На счету только ' + Math.round(баланс) + ' CUBE');
      return;
    }

    var имя = CW.имяЧеловека(нашли);

    /* В подтверждении — сумма, имя и номер. Имени мало: тёзки бывают. */
    CW.лист([
      { заголовок: 'Перевести ' + сколько + ' CUBE?' },
      { зн: CW.значок('человек', 16),
        подпись: имя + ' · UID ' + (нашли.uid || нашли.id) },
      '-',
      { зн: CW.значок('монета', 16), подпись: 'Перевести', делать: перевести },
      { зн: CW.значок('стрелка', 16), подпись: 'Передумать' }
    ]);
  }

  function перевести() {
    var сколько = Math.floor(Number(Ф.взять('сколько')) || 0);
    М.занят(true);
    CW.спросить('/cube/transfer', {
      способ: 'POST', сроком: 30000,
      тело: { to_user_id: нашли.id, amount: сколько,
              note: String(Ф.взять('записка') || '').trim() }
    }).then(function (о) {
      CW.сказать('Переведено ' + сколько + ' CUBE');
      if (о && о.balance != null) CW.обновитьБаланс(о.balance);
      else CW.обновитьБаланс(баланс - сколько);
      М.убрать();
      if (данные.потом) данные.потом(о);
    }).catch(function (е) {
      М.занят(false);
      CW.сказать(е && е.сеть ? 'Нет связи с сервером'
                             : ((е && е.message) || 'Перевод не прошёл'));
    });
  }

  return М;
});
