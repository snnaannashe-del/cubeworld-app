/* ═══════════════════════════════════════════════════════════════════════
   АРХИВ ПЕРЕПИСОК.

       shared/архив.js

   Убранная в архив переписка не удаляется и ничего не теряет — она
   просто уходит из списка чатов, чтобы не мозолила глаза. Вернуть её
   можно в любой момент, и вся переписка остаётся на месте.

   ── Почему это общий кусок ─────────────────────────────────────────
   Им пользуются двое: сами чаты (прячут убранные переписки и убирают
   новые) и окно архива (показывает и возвращает). Два списка архива
   рядом разошлись бы на первой же правке.

   ── Где он живёт ───────────────────────────────────────────────────
   В боевой архив лежал ТОЛЬКО в браузере: убрал переписку на
   компьютере — на телефоне она по-прежнему в списке. Это не архив, а
   заметка на полях одного браузера.

   У нас он в личном хранилище на сервере (/me/prefs, ключ «архив») и
   ещё зеркалом в браузере — чтобы список рисовался сразу, не дожидаясь
   сети. Сеть ответила — списки сводятся, и ничего не теряется: чего
   нет в одном месте, то добавляется из другого.

       CW.архив.загрузить()        → обещание; тянет с сервера
       CW.архив.список()           → [{uid, имя, t}]
       CW.архив.внутри(uid)        → правда/ложь
       CW.архив.положить(uid, имя) → убрать переписку в архив
       CW.архив.вернуть(uid)       → достать обратно
       CW.архив.следить(fn)        → позвать, когда список изменился
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  var КЛЮЧ_БРАУЗЕРА = 'cw_архив';
  var КЛЮЧ_СЕРВЕРА = 'архив';
  var ПРЕДЕЛ = 300;        /* больше трёхсот — это уже не архив, а свалка */

  var СПИСОК = изБраузера();
  var СЛУШАТЕЛИ = [];
  var часы = null;

  function изБраузера() {
    try {
      var с = JSON.parse(окно.localStorage.getItem(КЛЮЧ_БРАУЗЕРА) || '[]');
      return Array.isArray(с) ? с.filter(годится) : [];
    } catch (е) { return []; }
  }

  function вБраузер() {
    try {
      окно.localStorage.setItem(КЛЮЧ_БРАУЗЕРА, JSON.stringify(СПИСОК));
    } catch (е) {}
  }

  function годится(з) { return з && з.uid; }

  /* Сводим два списка по номеру человека. Ничего не затираем молча:
     чего нет в одном месте — добавляем, что есть в обоих — берём
     свежее по метке времени. */
  function свести(а, б) {
    var где = {}, итог = [];
    (а || []).concat(б || []).forEach(function (з) {
      if (!годится(з)) return;
      з.uid = String(з.uid);
      var место = где[з.uid];
      if (место === undefined) { где[з.uid] = итог.length; итог.push(з); return; }
      if (Number(з.t || 0) > Number(итог[место].t || 0)) итог[место] = з;
    });
    itogSort(итог);
    if (итог.length > ПРЕДЕЛ) итог = итог.slice(0, ПРЕДЕЛ);
    return итог;
  }

  function itogSort(с) {
    с.sort(function (х, у) { return Number(у.t || 0) - Number(х.t || 0); });
  }

  function сказать() {
    СЛУШАТЕЛИ.forEach(function (fn) { try { fn(СПИСОК); } catch (е) {} });
  }

  function наСервер() {
    clearTimeout(часы);
    часы = setTimeout(function () {
      var тело = {};
      тело[КЛЮЧ_СЕРВЕРА] = { v: JSON.stringify(СПИСОК), t: Date.now() };
      CW.спросить('/me/prefs', { способ: 'POST', тело: { prefs: тело }, тихо: true })
        .catch(function () {});
    }, 500);
  }

  CW.архив = {
    загрузить: function () {
      return CW.спросить('/me/prefs?keys=' + КЛЮЧ_СЕРВЕРА, { тихо: true })
        .then(function (д) {
          var сырое = д && д.prefs && д.prefs[КЛЮЧ_СЕРВЕРА] && д.prefs[КЛЮЧ_СЕРВЕРА].v;
          var сСервера = [];
          try { сСервера = JSON.parse(сырое || '[]') || []; } catch (е) {}
          var было = СПИСОК.length;
          СПИСОК = свести(СПИСОК, Array.isArray(сСервера) ? сСервера : []);
          вБраузер();
          сказать();
          /* На сервере не хватало того, что лежало в браузере — дошлём,
             иначе с другого устройства архив будет неполным. */
          if (СПИСОК.length !== сСервера.length || СПИСОК.length !== было) наСервер();
          return СПИСОК;
        })
        .catch(function () { return СПИСОК; });
    },

    список: function () { return СПИСОК.slice(); },

    внутри: function (uid) {
      uid = String(uid);
      return СПИСОК.some(function (з) { return String(з.uid) === uid; });
    },

    положить: function (uid, имя) {
      uid = String(uid);
      if (CW.архив.внутри(uid)) return;
      СПИСОК.unshift({ uid: uid, имя: имя || ('#' + uid), t: Date.now() });
      if (СПИСОК.length > ПРЕДЕЛ) СПИСОК = СПИСОК.slice(0, ПРЕДЕЛ);
      вБраузер(); наСервер(); сказать();
    },

    вернуть: function (uid) {
      uid = String(uid);
      СПИСОК = СПИСОК.filter(function (з) { return String(з.uid) !== uid; });
      вБраузер(); наСервер(); сказать();
    },

    следить: function (fn) { if (typeof fn === 'function') СЛУШАТЕЛИ.push(fn); }
  };

})(window, document);
