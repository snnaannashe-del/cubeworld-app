/* ═══════════════════════════════════════════════════════════════════════
   РЕДАКТОРЫ ФАЙЛОВ.

       var р = CW.правка.положить(узел, файл, {менялось: fn, счёт: fn});
       р.тело()   — что записать в файл

   Окно файла (modals/file.js) не знает, как устроен каждый вид: оно
   отдаёт сюда пустой узел и файл, а обратно получает одну ручку «что
   записать». Поэтому новый редактор добавляется здесь, а окно не
   меняется ни строкой.

   Сейчас собраны:

       текст · обычное поле (txt, md)
       код   · то же поле моноширинным шрифтом и с номерами строк
               (py, html, json). Запуска нет и не будет: чужой код на
               нашей странице выполнять нельзя
       таблица · клетки с оформлением и знаками поверх них
                 (csv, xlsx)

   Остальные виды — рисунок, слово, слайды, подпись, печать — лежат
   своими файлами и подвозятся в тот миг, когда открыли такой файл.
   ═══════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  var Ф = CW.файлы;

  function эл(тег, класс) {
    var у = document.createElement(тег);
    if (класс) у.className = класс;
    return у;
  }

  /* ── Разметка в Markdown и HTML ──
     Голый код набирать руками незачем: кнопки сами обводят выделенное
     нужными знаками, а списки и заголовки ставят в начало строки. */
  var РАЗМЕТКА = {
    md: [
      { д: 'Ж',  п: 'Жирный',         до: '**', после: '**' },
      { д: 'К',  п: 'Курсив',         до: '*',  после: '*' },
      { д: 'Н1', п: 'Заголовок',      строкой: '# ' },
      { д: 'Н2', п: 'Подзаголовок',   строкой: '## ' },
      { д: '•',  п: 'Список точками', строкой: '- ' },
      { д: '1.', п: 'Список числами', строкой: '1. ' },
      { д: '-',  п: 'Линия',          строкой: '---' },
      { д: '↗',  п: 'Ссылка',         до: '[',  после: '](https://)' }
    ],
    html: [
      { д: 'Ж',  п: 'Жирный',         до: '<b>',  после: '</b>' },
      { д: 'К',  п: 'Курсив',         до: '<i>',  после: '</i>' },
      { д: 'Н1', п: 'Заголовок',      до: '<h1>', после: '</h1>' },
      { д: 'Н2', п: 'Подзаголовок',   до: '<h2>', после: '</h2>' },
      { д: '¶',  п: 'Абзац',          до: '<p>',  после: '</p>' },
      { д: '•',  п: 'Список точками', до: '<ul><li>', после: '</li></ul>' },
      { д: '-',  п: 'Линия',          до: '<hr>', после: '' },
      { д: '↗',  п: 'Ссылка',         до: '<a href="https://">', после: '</a>' }
    ]
  };

  var РАЗМЕРЫ_ТЕКСТА = [10, 12, 14, 18, 24, 32, 48];

  function полосаРазметки(вид, поле, после) {
    var набор = РАЗМЕТКА[вид];
    if (!набор) return null;
    var п = эл('div', 'фл-полоса');
    набор.forEach(function (к, и) {
      var б = эл('button');
      б.type = 'button';
      б.textContent = к.д;
      б.title = к.п;
      б.dataset.и = и;
      п.appendChild(б);
    });
    /* Нажатие на кнопку не должно уводить курсор из поля: иначе
       выделение пропадает ровно в тот миг, когда его надо обвести. */
    п.addEventListener('mousedown', function (е) {
      if (е.target.tagName === 'BUTTON') е.preventDefault();
    });
    п.addEventListener('click', function (е) {
      var к = е.target.closest && е.target.closest('button[data-и]');
      if (!к) return;
      var правило = набор[Number(к.dataset.и)];
      var н = поле.selectionStart, кон = поле.selectionEnd, т = поле.value;
      if (правило.строкой) {
        var слева = т.lastIndexOf('\n', н - 1) + 1;
        var справа = т.indexOf('\n', кон);
        if (справа < 0) справа = т.length;
        var кусок = т.slice(слева, справа).split('\n').map(function (с) {
          return с.indexOf(правило.строкой) === 0 ? с : правило.строкой + с;
        }).join('\n');
        поле.value = т.slice(0, слева) + кусок + т.slice(справа);
        поле.selectionStart = слева;
        поле.selectionEnd = слева + кусок.length;
      } else {
        var выбрано = т.slice(н, кон);
        поле.value = т.slice(0, н) + правило.до + выбрано
                   + (правило.после || '') + т.slice(кон);
        поле.selectionStart = н + правило.до.length;
        поле.selectionEnd = поле.selectionStart + выбрано.length;
      }
      поле.focus();
      после();
    });
    return п;
  }

  /* ── Текст и код ──────────────────────────────────────────────── */
  function полем(куда, ф, код, зов) {
    var столбец = эл('div', 'фл-столбец');
    куда.appendChild(столбец);

    var ряд = эл('div', 'фл-ряд');
    var строки = null;
    if (код) { строки = эл('div', 'фл-строки'); ряд.appendChild(строки); }

    var поле = эл('textarea', 'фл-поле' + (код ? ' фл-код' : ''));
    поле.spellcheck = !код;
    if (код) поле.setAttribute('wrap', 'off');
    поле.value = ф.body || '';
    ряд.appendChild(поле);

    /* Полоса есть у каждого редактора, даже когда класть в неё нечего:
       в её правом конце стоит счёт, и он должен быть на одном месте во
       всех окнах файла. У обычного текста полоса пустая и держит одну
       эту строку. */
    var полоса = полосаРазметки(ф.kind, поле, function () { номера(); счёт(); })
               || эл('div', 'фл-полоса');
    столбец.appendChild(полоса);
    столбец.appendChild(ряд);

    function номера() {
      if (!строки) return;
      var н = поле.value.split('\n').length, с = '';
      for (var i = 1; i <= н; i++) с += i + '\n';
      строки.textContent = с;
      строки.scrollTop = поле.scrollTop;
    }
    function счёт() {
      var т = поле.value;
      зов.счёт(т.length + ' знаков · ' + т.split('\n').length + ' строк');
    }

    поле.addEventListener('input', function () { зов.менялось(); номера(); счёт(); });
    поле.addEventListener('scroll', function () {
      if (строки) строки.scrollTop = поле.scrollTop;
    });
    if (код) {
      /* Отступ в коде делают табом, а не уходом с поля. */
      поле.addEventListener('keydown', function (е) {
        if (е.key !== 'Tab') return;
        е.preventDefault();
        var н = поле.selectionStart, к = поле.selectionEnd;
        поле.value = поле.value.slice(0, н) + '    ' + поле.value.slice(к);
        поле.selectionStart = поле.selectionEnd = н + 4;
        зов.менялось(); номера();
      });
    }

    номера(); счёт();
    /* Курсор ставим только мышью: на телефоне клавиатура, выехавшая
       сама по себе, закрывает пол-окна (shared/ui.js, CW.встать). */
    setTimeout(function () { CW.встать(поле); }, 60);
    return { тело: function () { return поле.value; } };
  }

  /* ── Таблица ──────────────────────────────────────────────────── */
  function таблицей(куда, ф, зов) {
    var сырое = String(ф.body || '');
    var ряды = Ф.разборCSV(Ф.безЗнаков(сырое));
    /* Наряд клеток: что жирное, какого размера, цвета и как ровняется.
       Ключ — «строка:столбец». */
    var наряд = Ф.клеткиНаряда(сырое);
    var выбор = null;                       /* {р1,с1,р2,с2} — прямоугольник */

    var столбец = эл('div', 'фл-столбец');
    var полоса = полосаТаблицы();
    var обёртка = эл('div', 'фл-полотно');
    /* Слой знаков: подпись и печать ложатся НАД клетками, как на
       бумажный счёт. В клетку картинку не положишь, а подписанная
       смета нужна ровно так же, как подписанный документ. Слой лежит
       внутри полотна, поэтому едет вместе с таблицей, когда её
       прокручивают. */
    var слой = эл('div', 'фл-знаки');
    столбец.appendChild(полоса);
    столбец.appendChild(обёртка);
    куда.appendChild(столбец);
    var пред = CW.предметы(слой, { менялось: зов.менялось });

    function полосаТаблицы() {
      var п = эл('div', 'фл-полоса');
      function кн(д, знак, подпись, класс) {
        var б = эл('button', класс || '');
        б.type = 'button'; б.textContent = знак; б.title = подпись;
        б.dataset.д = д;
        return б;
      }
      п.appendChild(кн('ж', 'Ж', 'Жирный', 'жирно'));
      п.appendChild(кн('к', 'К', 'Курсив', 'курсив'));
      п.appendChild(кн('ч', 'Ч', 'Подчёркнутый', 'черта'));
      п.appendChild(эл('span', 'щель'));

      var размер = эл('select');
      размер.dataset.д = 'размер';
      размер.title = 'Размер';
      var пусто = document.createElement('option');
      пусто.value = ''; пусто.textContent = 'Размер';
      размер.appendChild(пусто);
      РАЗМЕРЫ_ТЕКСТА.forEach(function (р) {
        var о = document.createElement('option');
        о.value = р; о.textContent = р;
        размер.appendChild(о);
      });
      п.appendChild(размер);

      /* Цвет — своей палитрой, как и в рисунке: окно браузера красит
         себя само и в тёмной программе выглядит заплаткой. */
      var цвет = эл('button', 'фл-цвет');
      цвет.type = 'button'; цвет.dataset.д = 'цвет';
      цвет.title = 'Цвет текста';
      цвет.style.setProperty('--цвет', '#e8e8f0');
      п.appendChild(цвет);

      п.appendChild(эл('span', 'щель'));
      п.appendChild(кн('left', '◧', 'По левому краю'));
      п.appendChild(кн('center', '◫', 'По центру'));
      п.appendChild(кн('right', '◨', 'По правому краю'));
      п.appendChild(эл('span', 'щель'));
      /* Подписать — та же кнопка и тот же выбор, что в документе: он
         один на всю программу и лежит в shared/знаки.js. */
      var подпись = эл('button');
      подпись.type = 'button';
      подпись.title = 'Подписать';
      подпись.dataset.д = 'подписать';
      подпись.innerHTML = CW.значок('карандаш', 15);
      п.appendChild(подпись);
      п.appendChild(эл('span', 'щель'));
      п.appendChild(кн('снять', '⌫', 'Снять оформление'));
      return п;
    }

    function ключ(р, с) { return р + ':' + с; }

    function вВыборе(р, с) {
      if (!выбор) return false;
      return р >= Math.min(выбор.р1, выбор.р2) && р <= Math.max(выбор.р1, выбор.р2)
          && с >= Math.min(выбор.с1, выбор.с2) && с <= Math.max(выбор.с1, выбор.с2);
    }

    function поВыбору(что) {
      if (!выбор) { CW.сказать('Сначала выбери клетку', 2500); return; }
      for (var р = Math.min(выбор.р1, выбор.р2); р <= Math.max(выбор.р1, выбор.р2); р++)
        for (var с = Math.min(выбор.с1, выбор.с2); с <= Math.max(выбор.с1, выбор.с2); с++) {
          var к = ключ(р, с), о = наряд[к] || {};
          что(о);
          var пусто = true;
          for (var и in о) if (о[и]) пусто = false;
          if (пусто) delete наряд[к]; else наряд[к] = о;
        }
      одеть(); зов.менялось();
    }

    function одеть() {
      обёртка.querySelectorAll('input[data-р]').forEach(function (п) {
        var о = наряд[ключ(Number(п.dataset.р), Number(п.dataset.с))] || {};
        п.style.fontWeight = о.ж ? '700' : '';
        п.style.fontStyle = о.к ? 'italic' : '';
        п.style.textDecoration = о.ч ? 'underline' : '';
        п.style.fontSize = о.р ? (о.р + 'px') : '';
        п.style.color = о.ц ? ('#' + о.ц) : '';
        п.style.textAlign = о.в || '';
        п.classList.toggle('выбран',
          вВыборе(Number(п.dataset.р), Number(п.dataset.с)));
      });
    }

    полоса.addEventListener('mousedown', function (е) {
      if (е.target.tagName === 'BUTTON') е.preventDefault();
    });
    полоса.addEventListener('click', function (е) {
      var к = е.target.closest && е.target.closest('button[data-д]');
      if (!к) return;
      var д = к.dataset.д;
      if (д === 'ж' || д === 'к' || д === 'ч') {
        поВыбору(function (о) { о[д] = о[д] ? 0 : 1; }); return;
      }
      if (д === 'left' || д === 'center' || д === 'right') {
        поВыбору(function (о) { о.в = (о.в === д) ? '' : д; }); return;
      }
      if (д === 'подписать') {
        CW.знаки.выбрать(function (адрес) {
          пред.ставить('<img src="' + CW.безопасно(адрес) + '" alt="">', 0.26);
          CW.сказать('Знак в таблице · его можно двигать', 3500);
        });
        return;
      }
      if (д === 'снять') {
        поВыбору(function (о) {
          о.ж = о.к = о.ч = 0; о.р = 0; о.ц = ''; о.в = '';
        });
      }
    });
    полоса.querySelector('[data-д="размер"]').addEventListener('change', function () {
      var р = Number(this.value);
      this.value = '';
      if (!р) return;
      /* В клетке размер держим в точках экрана — как и в документе. */
      поВыбору(function (о) { о.р = Math.round(р * 4 / 3); });
    });
    var палитра = null;
    полоса.querySelector('[data-д="цвет"]').addEventListener('click', function () {
      var кн = this;
      if (палитра) { палитра.убрать(); палитра = null; return; }
      CW.нужен('shared/выбор-знака.js').then(function () {
        палитра = CW.палитраЦвета(куда.closest('.ок-окно') || куда, {
          цвет: '#e8e8f0',
          меняется: function (ц) {
            кн.style.setProperty('--цвет', ц);
            поВыбору(function (о) { о.ц = String(ц).replace('#', ''); });
          },
          закрыли: function () { палитра = null; }
        });
        палитра.узел.classList.add('под-полосой');
      });
    });

    /* Вставка куска чужой таблицы. Excel, Numbers и Google-таблицы
       кладут в буфер строки через перевод строки, а клетки — через
       табуляцию. Раскладываем это по клеткам, начиная с той, где стоит
       курсор, и дорисовываем недостающие строки и столбцы. Одну клетку
       без табуляций не трогаем: её браузер вставит сам. */
    обёртка.addEventListener('paste', function (е) {
      var буфер = е.clipboardData || window.clipboardData;
      if (!буфер) return;
      var текст = буфер.getData('text/plain') || '';
      if (!текст) return;
      if (!/\t/.test(текст) && !/\n/.test(текст.trim())) return;
      е.preventDefault();
      var раздел = /\t/.test(текст) ? '\t' : ',';
      var кусок = Ф.разборCSV(текст.replace(/\n+$/, ''), раздел);
      if (!кусок.length) return;
      var клетка = (е.target && е.target.matches && е.target.matches('input'))
        ? е.target : null;
      var р0 = клетка ? Number(клетка.dataset.р) : 0;
      var с0 = клетка ? Number(клетка.dataset.с) : 0;
      var нужно = с0 + Math.max.apply(null, кусок.map(function (р) { return р.length; }));
      while (ряды.length < р0 + кусок.length)
        ряды.push(new Array(ряды[0].length).fill(''));
      if (нужно > ряды[0].length)
        ряды.forEach(function (р) { while (р.length < нужно) р.push(''); });
      кусок.forEach(function (р, и) {
        р.forEach(function (з, с) { ряды[р0 + и][с0 + с] = з; });
      });
      зов.менялось();
      нарисовать();
      CW.сказать('Вставлено ' + кусок.length + ' строк · '
               + Math.max.apply(null, кусок.map(function (р) { return р.length; }))
               + ' столбцов', 2500);
    });

    /* Сколько знаков просит клетка: не уже шести и не шире сорока —
       иначе одна длинная строка растянет таблицу на весь экран. */
    function поРазмеру(з) {
      var д = String(з == null ? '' : з).length;
      return Math.max(6, Math.min(40, д + 1));
    }

    /* Столбец ровняем по самой длинной клетке в нём: так таблица
       выглядит таблицей, а не лесенкой. */
    function подравнять() {
      var ширина = ряды[0].length;
      for (var с = 0; с < ширина; с++) {
        var нужно = 6;
        for (var р = 0; р < ряды.length; р++)
          нужно = Math.max(нужно, поРазмеру(ряды[р][с]));
        var клетки = обёртка.querySelectorAll('input[data-с="' + с + '"]');
        for (var i = 0; i < клетки.length; i++) клетки[i].setAttribute('size', нужно);
      }
    }

    function нарисовать() {
      var ширина = ряды[0].length;
      var таблица = эл('table', 'фл-табл');
      var шапка = '<thead><tr><th></th>';
      for (var с = 0; с < ширина; с++) шапка += '<th>' + Ф.буква(с) + '</th>';
      шапка += '</tr></thead><tbody>';
      var тело = '';
      ряды.forEach(function (р, и) {
        тело += '<tr><th>' + (и + 1) + '</th>';
        р.forEach(function (з, с) {
          тело += '<td><input data-р="' + и + '" data-с="' + с
                + '" size="' + поРазмеру(з) + '" value="' + CW.безопасно(з) + '"></td>';
        });
        тело += '</tr>';
      });
      таблица.innerHTML = шапка + тело + '</tbody>';

      /* Слой знаков переживает перерисовку: это тот же самый узел, и
         предметы на нём остаются живыми. Если вычистить полотно
         вместе с ним, подпись после «+ Строка» пришлось бы ставить
         заново. */
      if (слой.parentNode) слой.parentNode.removeChild(слой);
      обёртка.innerHTML = '';
      обёртка.appendChild(таблица);

      var кнопки = эл('div', 'фл-ряд-кнопок');
      [['ряд', '+ Строка'], ['столбец', '+ Столбец'],
       ['-ряд', '− Строка'], ['-столбец', '− Столбец']].forEach(function (к) {
        var б = эл('button', 'кнопка');
        б.type = 'button'; б.textContent = к[1];
        б.onclick = function () {
          if (к[0] === 'ряд') ряды.push(new Array(ряды[0].length).fill(''));
          else if (к[0] === 'столбец') ряды.forEach(function (р) { р.push(''); });
          else if (к[0] === '-ряд') { if (ряды.length > 1) ряды.pop(); }
          else if (ряды[0].length > 1) ряды.forEach(function (р) { р.pop(); });
          зов.менялось(); нарисовать();
        };
        кнопки.appendChild(б);
      });
      обёртка.appendChild(кнопки);
      обёртка.appendChild(слой);

      обёртка.querySelectorAll('input[data-р]').forEach(function (п) {
        п.addEventListener('input', function () {
          ряды[Number(п.dataset.р)][Number(п.dataset.с)] = п.value;
          п.setAttribute('size', поРазмеру(п.value));
          подравнять();
          зов.менялось();
        });
        /* Клетка под рукой — на неё и ложится оформление. С Shift
           берётся прямоугольник: от прежней клетки до нынешней. */
        function взять(е) {
          var р = Number(п.dataset.р), с = Number(п.dataset.с);
          if (е && е.shiftKey && выбор) { выбор.р2 = р; выбор.с2 = с; }
          else выбор = { р1: р, с1: с, р2: р, с2: с };
          одеть();
        }
        п.addEventListener('mousedown', взять);
        п.addEventListener('focus', function () {
          if (!вВыборе(Number(п.dataset.р), Number(п.dataset.с))) взять(null);
        });
      });

      подравнять();
      одеть();
      зов.счёт(ряды.length + ' строк · ' + ширина + ' столбцов');
    }

    нарисовать();
    пред.поставить(Ф.знакиСписком(сырое));
    return {
      /* Сперва сама таблица, потом служебные строки: знаки и наряд
         клеток. В скачанный .csv они не уходят — их отрезает
         Ф.безЗнаков. */
      тело: function () {
        return Ф.сборкаCSV(ряды)
             + Ф.знакамиХвост(пред.рисунками())
             + Ф.нарядомХвост(наряд);
      }
    };
  }

  /* ── Выбор редактора по виду ──────────────────────────────────────
     Лёгкие редакторы (поле и таблица) лежат здесь же: они короткие и
     нужны чаще всего. Тяжёлые едут своими файлами и подвозятся в тот
     миг, когда открыли такой файл, — холст с кистями незачем возить
     тому, кто открыл заметку. */
  /* Знак ставят в пять видов файлов: pdf, слайды, docx, csv и xlsx.
     Везде это одно и то же — выбор знака (shared/знаки.js) и предмет
     поверх листа (shared/предметы.js), поэтому они едут вместе. */
  var ПОДПИСЬЮ = ['shared/предметы.js', 'shared/знаки.js'];

  var ОТДЕЛЬНЫЕ = {
    рисунок: { файл: 'shared/правка-рисунок.js', зовут: 'правкаРисунок' },
    слово:   { файл: 'shared/правка-слово.js',   зовут: 'правкаСлово',
               сперва: ПОДПИСЬЮ },
    /* Слайды — тот же лист, что и документ: полоса оформления у них
       общая и лежит в файле слова, поэтому он едет первым. */
    слайды:  { файл: 'shared/правка-слайды.js',  зовут: 'правкаСлайды',
               сперва: ПОДПИСЬЮ.concat(['shared/правка-слово.js']) },
    /* Подпись хранит росчерк теми же мазками, что и рисунок, и его же
       разбором открывает старые файлы — поэтому рисунок едет первым. */
    подпись: { файл: 'shared/правка-подпись.js', зовут: 'правкаПодпись',
               сперва: ['shared/правка-рисунок.js'] },
    печать:  { файл: 'shared/правка-печать.js',  зовут: 'правкаПечать' }
  };

  /* Везти по очереди, а не разом: следующий файл опирается на
     предыдущий, и приехать раньше него ему нельзя. */
  function повозке(список) {
    return (список || []).reduce(function (ждём, путь) {
      return ждём.then(function () { return CW.нужен(путь); });
    }, Promise.resolve());
  }

  CW.правка = {
    /* Какие виды уже правятся. Окно файла спрашивает это до того, как
       что-то обещать человеку. */
    умеем: function (правим) {
      return правим === 'текст' || правим === 'код' || правим === 'таблица'
          || !!ОТДЕЛЬНЫЕ[правим];
    },

    /* Всегда обещание: один редактор готов сразу, другой сперва едет,
       и окну файла не нужно знать, который именно. */
    положить: function (куда, ф, зов) {
      var вид = Ф.поВиду(ф.kind);
      if (!вид) return Promise.resolve(null);
      /* Таблица лежит здесь же, но знак на неё ставят тем же общим
         выбором, что и в документе, — поэтому она тоже ждёт повозку. */
      if (вид.правим === 'таблица') {
        return повозке(ПОДПИСЬЮ).then(function () { return таблицей(куда, ф, зов); });
      }
      if (вид.правим === 'текст')   return Promise.resolve(полем(куда, ф, false, зов));
      if (вид.правим === 'код')     return Promise.resolve(полем(куда, ф, true, зов));

      var свой = ОТДЕЛЬНЫЕ[вид.правим];
      if (!свой) return Promise.resolve(null);
      return повозке(свой.сперва)
        .then(function () { return CW.нужен(свой.файл); })
        .then(function () { return CW[свой.зовут](куда, ф, зов); });
    }
  };
})();
