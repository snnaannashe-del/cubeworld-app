/* ═══════════════════════════════════════════════════════════════════════
   КОРЗИНА — ОДНА НА ВСЮ ПЛОЩАДКУ.
   /home/claude/новое/cubeworld-app/shared/корзина.js

       CW.корзина.положить(товар, род, сколько)
       CW.корзина.список()      → [строки]
       CW.корзина.убрать(ключ)  · поправить(ключ, сколько) · очистить()
       CW.корзина.итог()        → сколько CUBE выйдет
       CW.корзина.сколько()     → сколько позиций лежит
       CW.корзина.слушать(fn)   → позвать, когда корзина изменилась

   ── ЗАЧЕМ ОНА ─────────────────────────────────────────────────────
   Покупка была по одной: нажал «Купить» - списалось - и снова ищи
   следующее. Набрать пять вещей и оплатить их одним разом было
   нельзя, а именно так покупают: сначала собирают, потом смотрят на
   итог и на баланс, что-то убирают и платят за остальное.

   ── ГДЕ ОНА ЛЕЖИТ ─────────────────────────────────────────────────
   В этом браузере (localStorage) и, если сервер отвечает, в личном
   хранилище человека (/me/prefs) - тем же путём, что и избранное.
   Своей таблицы на сервере у корзины нет и не нужно: корзина - это
   ещё не покупка, а намерение. Пока не оплатил - ничего не занято,
   товар могут купить раньше, и мы об этом честно скажем при оплате.

   ── ЧТО В НЕЙ ЛЕЖИТ ───────────────────────────────────────────────
   Снимок товара на миг добавления: род, номер, имя, цена, валюта,
   количество, картинка, продавец. Цену при оплате СПРАШИВАЕМ ЗАНОВО
   у сервера - продавец мог её поменять, и платить по старой памяти
   нельзя.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  var КЛЮЧ = 'cw_корзина';          /* в браузере */
  var КЛЮЧСЕРВЕРА = 'корзина';      /* в /me/prefs */
  var ПРЕДЕЛ = 50;                  /* позиций: больше - это уже склад */

  var СПИСОК = null;
  var СЛУШАТЕЛИ = [];
  var часыСервера = null;

  function прочитать() {
    if (СПИСОК) return СПИСОК;
    try { СПИСОК = JSON.parse(окно.localStorage.getItem(КЛЮЧ) || '[]') || []; }
    catch (е) { СПИСОК = []; }
    if (!Array.isArray(СПИСОК)) СПИСОК = [];
    return СПИСОК;
  }

  function записать() {
    try { окно.localStorage.setItem(КЛЮЧ, JSON.stringify(прочитать())); }
    catch (е) {}
    наСервер();
    СЛУШАТЕЛИ.forEach(function (ф) { try { ф(прочитать()); } catch (е) {} });
  }

  /* На сервер кладём не сразу: человек жмёт «плюс» несколько раз
     подряд, и каждый раз дёргать сервер незачем. */
  function наСервер() {
    if (!CW.спросить) return;
    окно.clearTimeout(часыСервера);
    часыСервера = окно.setTimeout(function () {
      var тело = {};
      тело[КЛЮЧСЕРВЕРА] = { v: JSON.stringify(прочитать()), t: Date.now() };
      CW.спросить('/me/prefs', { способ: 'POST', тело: { prefs: тело }, тихо: true })
        .catch(function () {});
    }, 800);
  }

  /* Корзина, оставшаяся на сервере с другого устройства. Берём её
     только если здесь пусто: иначе затёрли бы то, что человек набрал
     прямо сейчас. */
  function сСервера() {
    if (!CW.спросить) return Promise.resolve(прочитать());
    return CW.спросить('/me/prefs?keys=' + encodeURIComponent(КЛЮЧСЕРВЕРА),
                       { тихо: true })
      .then(function (д) {
        var сыро = д && д.prefs && д.prefs[КЛЮЧСЕРВЕРА] && д.prefs[КЛЮЧСЕРВЕРА].v;
        var там = [];
        try { там = JSON.parse(сыро || '[]') || []; } catch (е) { там = []; }
        if (Array.isArray(там) && там.length && !прочитать().length) {
          СПИСОК = там.slice(0, ПРЕДЕЛ);
          try { окно.localStorage.setItem(КЛЮЧ, JSON.stringify(СПИСОК)); } catch (е) {}
          СЛУШАТЕЛИ.forEach(function (ф) { try { ф(СПИСОК); } catch (е) {} });
        }
        return прочитать();
      })
      .catch(function () { return прочитать(); });
  }

  function ключом(род, ид) { return String(род || 'shop') + ':' + String(ид); }

  CW.корзина = {
    КЛЮЧСЕРВЕРА: КЛЮЧСЕРВЕРА,

    список: function () { return прочитать().slice(); },

    сколько: function () { return прочитать().length; },

    /* Сколько CUBE выйдет за всё. Чужая валюта в счёт не идёт: её
       площадка не считает, и такие строки оплачиваются не здесь. */
    итог: function () {
      return прочитать().reduce(function (с, з) {
        if (String(з.валюта || 'CUBE').toUpperCase() !== 'CUBE') return с;
        return с + (Number(з.цена) || 0) * (Number(з.сколько) || 1);
      }, 0);
    },

    есть: function (род, ид) {
      var к = ключом(род, ид);
      return прочитать().some(function (з) { return з.ключ === к; });
    },

    /* Положить. Тот же товар второй раз не удваивает строку: у вещи
       прибавляется количество, у цифрового товара количества нет
       вовсе - он один и тот же файл. */
    положить: function (товар, род, сколько) {
      товар = товар || {};
      род = род === 'market' ? 'market' : 'shop';
      var сп = прочитать();
      var к = ключом(род, товар.id);
      var было = сп.filter(function (з) { return з.ключ === к; })[0];
      if (было) {
        if (род === 'shop') {
          было.сколько = Math.max(1, Math.min(Number(было.сколько || 1)
                                            + (Number(сколько) || 1),
                                              Number(товар.qty) || 99));
          записать();
          return { добавлено: false, строка: было };
        }
        return { добавлено: false, строка: было };
      }
      if (сп.length >= ПРЕДЕЛ) {
        return { добавлено: false,
                 беда: Т.с('В корзине уже {н} товаров', { н: ПРЕДЕЛ }) };
      }
      var строка = {
        ключ: к,
        род: род,
        ид: товар.id,
        имя: товар.title || 'Товар',
        цена: Number(товар.price || 0),
        валюта: String(товар.currency || 'CUBE').toUpperCase(),
        сколько: род === 'shop' ? Math.max(1, Number(сколько) || 1) : 1,
        вналичии: Number(товар.qty || 0) || null,
        снимок: (товар.photos && товар.photos[0]) || товар.cover || товар.image || '',
        продавец: товар.seller_name || товар.author || '',
        когда: Date.now()
      };
      сп.push(строка);
      записать();
      return { добавлено: true, строка: строка };
    },

    убрать: function (ключ) {
      СПИСОК = прочитать().filter(function (з) { return з.ключ !== ключ; });
      записать();
    },

    поправить: function (ключ, сколько) {
      прочитать().forEach(function (з) {
        if (з.ключ !== ключ) return;
        var предел = з.вналичии || 99;
        з.сколько = Math.max(1, Math.min(Number(сколько) || 1, предел));
      });
      записать();
    },

    очистить: function () { СПИСОК = []; записать(); },

    слушать: function (ф) {
      if (typeof ф === 'function') СЛУШАТЕЛИ.push(ф);
      return function () {
        СЛУШАТЕЛИ = СЛУШАТЕЛИ.filter(function (д) { return д !== ф; });
      };
    },

    /* Подтянуть корзину, если человек набрал её на другом устройстве. */
    подтянуть: сСервера
  };

})(window, document);
