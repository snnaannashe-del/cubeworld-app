/* ═══════════════════════════════════════════════════════════════════════
   ПРАВАЯ ПОЛКА: «Добавить контент» и «Стримить» — в этом порядке.

   Публикуют каждый день, а стримят изредка; то, что делают чаще, стоит
   первым и выше. Раньше было наоборот.

   Один и тот же кусок стоит в чатах и в группах, а дальше встанет и в
   ленте. Поэтому он живёт здесь:

       правая.appendChild(CW.полка());

   Стили к нему — в оболочке, в разделе общих кусков.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  /* ── ЭТИ ДВЕ КНОПКИ - ТОЛЬКО ДЛЯ НАСТОЛЬНОГО ЭКРАНА ───────────────
     22 ноября я на день переселила их на телефоне в выдвижную полку.
     Это было не то: такими карточками они нарисованы для компьютера,
     где под них есть целая колонка. На телефоне «Добавить пост» - это
     большой плюс в полосе внизу, а «Стримить» - восьмая плитка в
     полке. Карточек на телефоне нет вовсе.

     Поэтому полка собирается одним куском и зовут её только из правой
     колонки: чатов, групп и ленты. */
  CW.полка = function () {
    var где = документ.createElement('div');
    где.className = 'полка';

    var добавить = документ.createElement('button');
    добавить.className = 'добавить';
    /* Между строками стояла строка с «&». Союз на отдельной строке
       ничего не объяснял, а читался как третий пункт списка — две
       строки и так рядом, и понятно, что окно умеет и то и другое. */
    /* SHORT и POST стоят теми же метками, что в кадре ленты: синяя и
       зелёная. Так человек узнаёт их с первого взгляда — это те же два
       слова, которыми подписана каждая запись. Тире между меткой и
       словами убрано: метка и так отделена от текста. */
    добавить.innerHTML =
        '<div class="плюс">' + CW.значок('плюс', 22) + '</div>'
      + '<div class="имя">Добавить контент</div>'
      + '<div class="что">'
      +   '<div><span class="метка short">SHORT</span> видео</div>'
      +   '<div><span class="метка post">POST</span> текст, фото, файл</div>'
      + '</div>';
    /* Открывает «Новый пост» — и больше ничего спрашивать не нужно:
       SHORT и POST выбираются в самом окне, первым же рядом. 18 ноября
       я вставила сюда лишний вопрос «что публикуем» и увела SHORT в
       старое окно windows/upload.html. Это была ошибка: окно поста
       умеет и ролик с обложкой, и текст с фото, а лишний вопрос только
       добавлял шаг. Вернула как было. */
    добавить.onclick = function () {
      CW.открыть('create-post');
    };
    где.appendChild(добавить);

    var стрим = документ.createElement('button');
    стрим.className = 'кн-стрим';
    стрим.innerHTML = '<span class="точка"></span>' + CW.значок('камера') + 'Стримить';
    стрим.onclick = function () {
      CW.открыть('create-live');
    };
    где.appendChild(стрим);

    /* ── ДВЕ ПОЛОСЫ СОВЕТОВ ───────────────────────────────────────────
       Сверху — три товара с маркетплейса, снизу — три ролика «что ещё
       посмотреть». Оба 9:16, как кадр в ленте: иначе обложка ролика
       обрезается и обещает не тот кадр.

       Листаются сами, по одному, раз в несколько секунд, и ползунка у
       них нет: это не список, который читают, а подсказка сбоку. Пальцем
       и колесом прокрутить всё равно можно. */
    /* Обе полосы — реклама, и в «Оформлении» есть строка «Рекламы в
       блоках меню». Выключена (а она выключена по умолчанию) — полос
       нет вовсе и за товарами с роликами никто не ходит: незачем
       будить сервер ради того, чего не покажем. «Добавить контент» и
       «Стримить» остаются всегда: это не реклама, а работа. */
    if (документ.documentElement.getAttribute('data-полка') === 'да') {
      var товары = полоса('Товары', 'market');
      где.insertBefore(товары.узел, где.firstChild);
      /* «Ещё» — одно слово: плашка лежит внутри карточек, и длинное
         название перекрывало сразу две из трёх. */
      var ролики = полоса('Ещё', 'feed');
      где.appendChild(ролики.узел);

      налитьТовары(товары);
      налитьРолики(ролики);
    }

    return где;
  };

  /* ── пустая полоса: название и дорожка ── */
  function полоса(имя, куда) {
    var узел = документ.createElement('div');
    узел.className = 'сов-полоса';
    /* ── МЕСТО ПОД ПОЛОСУ ЗАНЯТО С ПЕРВОГО КАДРА ──
       Прежде полоса была спрятана, пока не приедут товары и ролики, и
       появлялась готовой. Из-за этого «Добавить контент» и «Стримить»
       стояли сперва посреди колонки, а через секунду прыгали вниз или
       вверх — человек видел два разных кадра подряд и справедливо
       считал, что всё дёргается.

       Теперь полоса стоит сразу, со своим ростом и тремя пустыми
       клетками. Приехали карточки — они встают НА ЭТО ЖЕ место, и
       ничего не двигается. Не приехали — место остаётся пустым: это
       честнее прыжка. */
    узел.classList.add('ждёт');

    /* Подпись стоит ПОД карточками: сверху она отодвигала первую
       полосу от края и ломала общий ряд отступов — верх правой колонки
       переставал совпадать с верхом окна слева. */
    var окошко = документ.createElement('div');
    окошко.className = 'сов-окошко';
    var дорожка = документ.createElement('div');
    дорожка.className = 'сов-дорожка';
    окошко.appendChild(дорожка);
    узел.appendChild(окошко);

    var шапка = документ.createElement('div');
    шапка.className = 'сов-шапка';
    шапка.textContent = имя;
    узел.appendChild(шапка);

    /* Три пустые клетки: место под карточки видно сразу, и когда они
       приедут, полоса не изменит ни роста, ни ширины. */
    for (var п = 0; п < 3; п++) {
      var з = документ.createElement('div');
      з.className = 'сов-карта пусто заготовка';
      дорожка.appendChild(з);
    }

    /* Рост полосы считаем по её ширине: три карточки 9:16 в ряд, но не
       выше потолка — иначе на широкой колонке полоса раздувается и
       полка перестаёт помещаться по высоте. Пересчитываем при каждой
       смене ширины: окно браузера тянут, и застывшее число врёт. */
    function померить() {
      var ш = окошко.clientWidth;
      if (!ш) return;
      var рост = Math.round((ш - 16) / 3 * 16 / 9);
      рост = Math.max(104, Math.min(рост, 200));
      узел.style.setProperty('--сов-рост', рост + 'px');
    }
    окно.setTimeout(померить, 0);
    if (окно.ResizeObserver) {
      try { new окно.ResizeObserver(померить).observe(окошко); } catch (е) {}
    }
    окно.addEventListener('resize', померить);

    return { узел: узел, дорожка: дорожка, окошко: окошко, куда: куда,
             померить: померить };
  }

  /* Карточка 9:16: картинка (или ролик), поверх — подпись. */
  function карточка(о) {
    var к = документ.createElement('button');
    к.type = 'button';
    к.className = 'сов-карта';
    /* Своей подсказки у карточки нет: подпись и так написана внутри,
       а всплывающий title повторял её вторым слоем. */

    if (о.ролик) {
      var в = документ.createElement('video');
      в.src = CW.файл(о.ролик);
      в.muted = true; в.loop = true; в.playsInline = true; в.preload = 'metadata';
      if (о.кадр) в.poster = CW.файл(о.кадр);
      к.appendChild(в);
      /* Играет под указателем: три ролика, играющих всё время, съедают
         батарею у того, кто их даже не смотрит. */
      к.onmouseenter = function () { var п = в.play(); if (п && п.catch) п.catch(function () {}); };
      к.onmouseleave = function () { try { в.pause(); } catch (е) {} };
    } else if (о.кадр) {
      var и = документ.createElement('img');
      и.src = CW.файл(о.кадр);
      и.alt = '';
      к.appendChild(и);
    } else {
      к.classList.add('пусто');
      к.innerHTML = '<span class="зн">' + CW.значок(о.знак || 'куб', 18) + '</span>';
    }

    if (о.подпись) {
      var п = документ.createElement('span');
      п.className = 'сов-подпись';
      п.textContent = о.подпись;
      к.appendChild(п);
    }
    к.onclick = о.делать;
    return к;
  }

  /* ── товары ── */
  function налитьТовары(п) {
    CW.спросить('/shop?limit=9', { тихо: true }).then(function (д) {
      var вещи = (д && д.items) || [];
      if (!вещи.length) return;
      убратьЗаготовки(п);
      вещи.forEach(function (в) {
        var кадр = (в.media && в.media[0] && в.media[0].url) || '';
        п.дорожка.appendChild(карточка({
          кадр: кадр,
          знак: 'сумка',
          подпись: (в.price ? в.price + ' ' + (в.currency || 'CUBE') : в.title || ''),
          делать: function () { CW.уйти(CW.раздел('market')); }
        }));
      });
      показать(п);
    }).catch(function () {});
  }

  /* ── ролики ── */
  function налитьРолики(п) {
    var тут = 0;
    try { тут = Number(new окно.URLSearchParams(окно.location.search).get('пост') || 0); }
    catch (е) {}

    CW.спросить('/feed?limit=40&offset=0', { тихо: true }).then(function (д) {
      var записи = (д && (д.posts || д.items)) || (Array.isArray(д) ? д : []);
      var ролики = записи.filter(function (з) {
        return з.video_url && з.id !== тут;
      }).slice(0, 9);
      if (!ролики.length) return;
      убратьЗаготовки(п);
      ролики.forEach(function (з) {
        п.дорожка.appendChild(карточка({
          ролик: з.video_url,
          кадр: з.image_url || '',
          подпись: з.title || з.description || '',
          делать: function () {
            CW.уйти(CW.раздел('feed', CW.какойКуб()) + '?пост=' + з.id);
          }
        }));
      });
      показать(п);
    }).catch(function () {});
  }

  /* Показать полосу и пустить её листаться. Шаг — одна карточка;
     дошли до конца — возвращаемся в начало. */
  function убратьЗаготовки(п) {
    [].slice.call(п.дорожка.querySelectorAll('.заготовка'))
      .forEach(function (з) { з.parentNode.removeChild(з); });
  }

  function показать(п) {
    п.узел.classList.remove('ждёт');
    if (п.померить) п.померить();
    if (п.дорожка.children.length < 4) return;   /* три и меньше — листать нечего */

    var ход = окно.setInterval(function () {
      if (!п.узел.isConnected) { окно.clearInterval(ход); return; }
      var карта = п.дорожка.children[0];
      if (!карта) return;
      var шаг = карта.getBoundingClientRect().width + 8;
      var конец = п.окошко.scrollWidth - п.окошко.clientWidth - 2;
      п.окошко.scrollTo({
        left: п.окошко.scrollLeft >= конец ? 0 : п.окошко.scrollLeft + шаг,
        behavior: 'smooth'
      });
    }, 4000);
  }

})(window, document);
