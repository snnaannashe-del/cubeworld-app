/* ═══════════════════════════════════════════════════════════════════════
   ВХОД: кто я, как войти, как выйти, кого пускать.

   Опирается на связь.js. Больше ничего про вход в программе нет: ни один
   экран не читает ключ из памяти сам и не решает сам, пускать ли.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  var я = null;          /* заполняется после первого вопроса серверу */
  var спрашиваем = null; /* чтобы два экрана не спросили дважды */

  /* ── кто я ───────────────────────────────────────────────────────────
     Первый вызов идёт на сервер, остальные берут готовое.
     CW.кто(true) — спросить заново. */
  CW.кто = function (заново) {
    if (я && !заново) return Promise.resolve(я);
    if (спрашиваем && !заново) return спрашиваем;

    спрашиваем = CW.спросить('/me', { тихо: true }).then(function (д) {
      я = д || null;
      спрашиваем = null;
      return я;
    });
    return спрашиваем;
  };

  CW.ясныйЯ = function () { return я; };      /* без похода на сервер */

  /* ── получить новый ключ ─────────────────────────────────────────────
     Сервер выдаёт ключ, но человека ещё не заводит: учётная запись
     появится при первом входе в мир. Ключ показываем один раз — его
     нельзя восстановить. */
  CW.завестиКлюч = function () {
    return CW.спросить('/auth/generate', { способ: 'POST' })
      .then(function (д) {
        if (!д || !д.key) throw CW.Беда(0, 'Сервер не выдал ключ');
        return д;      /* {key, key_prefix, key_type} */
      });
  };

  /* ── ЧТО В БРАУЗЕРЕ ПРИНАДЛЕЖИТ ЧЕЛОВЕКУ ──────────────────────────
     Отбор кубов, открытые кубы, цвета значков, формы, избранные
     сообщения — всё это про аккаунт, а не про устройство. Вошли другим
     ключом — память прежнего человека должна уйти, иначе новый видит
     в мире кубы предыдущего и его же настройки.

         CW.забытьЛичное();

     Список один на всю программу: им пользуется и вход по ключу, и
     окно «Добавить аккаунт». */
  CW.ЛИЧНОЕ = ['cw_юниверс', 'cw_ключ_куба', 'cw_куб', 'cw_откуда',
               'cw_saved_msgs', 'cw_поиск_недавно', 'cw_смайлы_часто',
               'cw_свои-действия', 'cw_своё-фото', 'cw_своё-вид',
               'cw_своё-на-всех', 'cw_цвет_значка', 'cw_форма',
               'cw_форма-каждому'];
  CW.ЛИЧНОЕ_НАЧАЛО = ['cw_fav_msgs_'];

  CW.забытьЛичное = function () {
    CW.ЛИЧНОЕ.forEach(function (и) { CW.убрать(и); });
    try {
      var наВыброс = [];
      for (var i = 0; i < localStorage.length; i++) {
        var и = localStorage.key(i);
        CW.ЛИЧНОЕ_НАЧАЛО.forEach(function (н) {
          if (и && и.indexOf(н) === 0) наВыброс.push(и);
        });
      }
      наВыброс.forEach(function (и) { CW.убрать(и); });
    } catch (е) {}
    try { sessionStorage.clear(); } catch (е) {}
  };

  /* ── войти по ключу ──────────────────────────────────────────────── */
  CW.войти = function (ключ) {
    ключ = String(ключ || '').trim().toUpperCase();
    if (!ключ) return Promise.reject(CW.Беда(0, 'Введите ключ'));

    return CW.спросить('/auth/login', {
      способ: 'POST',
      тело: { key: ключ },
      сроком: 25000
    }).then(function (д) {
      if (!д || !д.access_token) throw CW.Беда(0, 'Ключ не подошёл');
      /* Ключ другой — значит человек другой: чистим его память до того,
         как положим новый вход. Тот же ключ (перезашли) не трогаем. */
      var прежний = String(CW.взять(CW.КЛЮЧИ.ключ) || '').trim().toUpperCase();
      if (прежний && прежний !== ключ) CW.забытьЛичное();
      CW.положить(CW.КЛЮЧИ.вход, д.access_token);
      if (д.refresh_token) CW.положить(CW.КЛЮЧИ.обновить, д.refresh_token);
      CW.положить(CW.КЛЮЧИ.ключ, ключ);
      CW.положить(CW.КЛЮЧИ.вид, д.key_type || 'free');
      я = null;                       /* заново спросим, кто я */
      return д;
    });
  };

  /* ── страж экрана ────────────────────────────────────────────────────
     Ставится первой строкой каждого экрана, кроме титулки:
         CW.пускать();
     Нет ключа — отправляем на титулку, экран даже не рисуется. */
  CW.пускать = function (кудаЕслиНет) {
    if (CW.вошли()) return true;
    /* Через CW.раздел, а не 'index.html' строкой: окна лежат в windows/,
       и отсюда строкой получилось бы windows/index.html — такой нет. */
    CW.уйти(кудаЕслиНет || CW.раздел('index'));
    return false;
  };

  /* ── язык ────────────────────────────────────────────────────────────
     Имена ключей те же, что у нынешней программы. */
  CW.язык = function (новый) {
    if (новый) {
      CW.положить('cw_lang', новый);
      CW.положить('cw_ui_lang', новый);
      return новый;
    }
    return CW.взять('cw_ui_lang') || CW.взять('cw_lang')
        || (окно.navigator.language || 'ru').slice(0, 2);
  };

})(window);
