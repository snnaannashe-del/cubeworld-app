/* ═══════════════════════════════════════════════════════════════════════
   ФАЙЛЫ В ПАПКАХ: общее знание о видах.

   Один список видов на всю программу: его читают окно «Какой файл
   создать?», список файлов в папке и само окно файла. Пока список был
   написан в каждом из трёх мест по-своему, они и расходились: в одном
   месте слайды были, в другом нет.

       CW.файлы.ВИДЫ            [{к, имя, зн, правим}]
       CW.файлы.поВиду('csv')   строка списка или null
       CW.файлы.чип('slides')   короткая надпись в шапке окна
       CW.файлы.значок('pdf')   имя значка из нашего набора
       CW.файлы.размер(1234)    «1.2 КБ»
       CW.файлы.буква(0)        «A» — подпись столбца таблицы

   «правим» говорит, КАКИМ редактором файл открывается:

       текст · код · таблица · слово · слайды · рисунок · подпись ·
       печать · нет

   «нет» — чужой формат, который мы храним и отдаём, но не правим.

   ── Служебный хвост ──────────────────────────────────────────────────

   В теле файла, кроме самого текста, могут лежать две служебные
   строки: поставленные на лист подписи и печати (⟦знаки⟧) и наряд
   клеток таблицы (⟦клетки⟧) — где жирное, где цветное, где по центру.
   Они приписаны в конец с новой строки, потому что JSON переводов
   строки внутри не содержит и читать их построчно надёжно.

   Наружу, в скачанный .csv, служебные строки не уходят: картинок в
   csv не бывает, и лишняя строка там никому не нужна.
   ═══════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  /* Порядок как в работающей программе: сперва рисунок, потом текст и
     PDF, потом таблицы, документ и код. */
  var ВИДЫ = [
    { к: 'svg',    имя: 'Рисовать',       зн: 'карандаш', правим: 'рисунок' },
    { к: 'txt',    имя: 'Текст',          зн: 'лист',     правим: 'текст'   },
    { к: 'pdf',    имя: 'PDF',            зн: 'лист',     правим: 'слово'   },
    { к: 'slides', имя: 'Слайды',         зн: 'картинка', правим: 'слайды'  },
    { к: 'csv',    имя: 'Таблица CSV',    зн: 'столбики', правим: 'таблица' },
    { к: 'xlsx',   имя: 'Таблица Excel',  зн: 'столбики', правим: 'таблица' },
    { к: 'docx',   имя: 'Документ Word',  зн: 'лист',     правим: 'слово'   },
    { к: 'py',     имя: 'Python',         зн: 'код',      правим: 'код'     },
    { к: 'html',   имя: 'HTML',           зн: 'код',      правим: 'код'     },
    { к: 'json',   имя: 'JSON',           зн: 'код',      правим: 'код'     },
    { к: 'md',     имя: 'Markdown',       зн: 'лист',     правим: 'текст'   },
    { к: 'sign',   имя: 'Подпись',        зн: 'карандаш', правим: 'подпись' },
    { к: 'stamp',  имя: 'Печать',         зн: 'цель',     правим: 'печать'  }
  ];

  /* У слайдов, подписи и печати в шапке понятнее название, а не вид. */
  var ЧИП_НАЗВАНИЕМ = { slides: 1, sign: 1, stamp: 1 };

  var ЗНАЧКИ_ПРОЧИХ = {
    doc: 'лист', xls: 'столбики', zip: 'скрепка', file: 'скрепка'
  };

  /* ── Принесённое с компьютера ──
     Это НЕ то же, что ВИДЫ. ВИДЫ — что мы умеем завести сами («Создать
     файл»), а здесь то, что человек кладёт в папку готовым: снимок,
     ролик, запись голоса. Заводить их у нас нечем — камера и микрофон
     живут в своих окнах, — но хранить, показывать и отдавать мы их
     обязаны: папка это хранилище, а не редактор.

     Каждому виду сказано, чем его показывать: фото — картинкой, видео
     и звук — своим проигрывателем. Браузер умеет и то и другое сам. */
  var ПРИНЕСЁННЫЕ = {
    png:  { имя: 'Снимок',  зн: 'картинка', смотр: 'фото' },
    jpg:  { имя: 'Снимок',  зн: 'картинка', смотр: 'фото' },
    jpeg: { имя: 'Снимок',  зн: 'картинка', смотр: 'фото' },
    gif:  { имя: 'Картинка', зн: 'картинка', смотр: 'фото' },
    webp: { имя: 'Снимок',  зн: 'картинка', смотр: 'фото' },
    avif: { имя: 'Снимок',  зн: 'картинка', смотр: 'фото' },
    mp4:  { имя: 'Видео',   зн: 'плёнка',   смотр: 'видео' },
    webm: { имя: 'Видео',   зн: 'плёнка',   смотр: 'видео' },
    mov:  { имя: 'Видео',   зн: 'плёнка',   смотр: 'видео' },
    m4v:  { имя: 'Видео',   зн: 'плёнка',   смотр: 'видео' },
    mkv:  { имя: 'Видео',   зн: 'плёнка',   смотр: 'видео' },
    mp3:  { имя: 'Запись',  зн: 'нота',     смотр: 'звук' },
    m4a:  { имя: 'Запись',  зн: 'нота',     смотр: 'звук' },
    wav:  { имя: 'Запись',  зн: 'нота',     смотр: 'звук' },
    ogg:  { имя: 'Запись',  зн: 'нота',     смотр: 'звук' },
    opus: { имя: 'Запись',  зн: 'нота',     смотр: 'звук' }
  };

  /* Настоящий вид записи. Сервер, который ещё не знает про снимки и
     ролики, кладёт их видом «file» — тогда смотрим на имя файла.
     Так папка показывает фотографию и до того, как сервер обновят. */
  function видЗаписи(ф) {
    var к = String((ф && ф.kind) || '').toLowerCase();
    if (к && к !== 'file') return к;
    return видПоИмени((ф && ф.name) || '');
  }

  /* Чем показывать принесённое: 'фото' | 'видео' | 'звук' | null. */
  function смотрим(к) {
    var п = ПРИНЕСЁННЫЕ[String(к || '').toLowerCase()];
    return п ? п.смотр : null;
  }

  /* Каким видом везти файл на сервер: у снимка, ролика и бумаги разные
     пределы размера, и слать ролик «бумагой» значит упереться в сто
     мегабайт там, где можно триста. */
  function везёмКак(имя) {
    var с = смотрим(видПоИмени(имя));
    if (с === 'фото') return 'image';
    if (с === 'видео') return 'clip';
    if (с === 'звук') return 'audio';
    return 'doc';
  }

  var ТИПЫ = {
    txt: 'text/plain', md: 'text/markdown', json: 'application/json',
    html: 'text/html', py: 'text/x-python', csv: 'text/csv',
    svg: 'image/svg+xml', pdf: 'application/pdf',
    docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
  };

  var ЗНАКИ_МЕТКА  = '\n⟦знаки⟧';
  var КЛЕТКИ_МЕТКА = '\n⟦клетки⟧';

  function поВиду(к) {
    for (var i = 0; i < ВИДЫ.length; i++) if (ВИДЫ[i].к === к) return ВИДЫ[i];
    return null;
  }

  function чип(к) {
    var в = поВиду(к);
    /* Чип у трёх видов — не расширение, а слово: «СЛАЙДЫ», «ПОДПИСЬ»,
       «ПЕЧАТЬ». Слово надо переводить, расширение — нет. */
    if (в && ЧИП_НАЗВАНИЕМ[к]) {
      var имя = (window.Т ? window.Т(в.имя) : в.имя);
      return String(имя).toUpperCase();
    }
    return String(к || '').toUpperCase();
  }

  function значок(к) {
    var в = поВиду(к);
    if (в) return в.зн;
    к = String(к || '').toLowerCase();
    if (ПРИНЕСЁННЫЕ[к]) return ПРИНЕСЁННЫЕ[к].зн;
    return ЗНАЧКИ_ПРОЧИХ[к] || 'скрепка';
  }

  /* Как называется вид по-человечески: «Снимок», «Видео», «Таблица
     CSV». В списке файлов и в окне это понятнее, чем «MP4». */
  function названием(к) {
    var в = поВиду(к);
    if (в) return в.имя;
    к = String(к || '').toLowerCase();
    return ПРИНЕСЁННЫЕ[к] ? ПРИНЕСЁННЫЕ[к].имя : String(к || 'Файл').toUpperCase();
  }

  function видПоИмени(имя) {
    var точка = String(имя || '').toLowerCase().split('.');
    var х = точка.length > 1 ? точка[точка.length - 1] : '';
    if (поВиду(х) || ПРИНЕСЁННЫЕ[х] || ЗНАЧКИ_ПРОЧИХ[х]) return х;
    return 'file';
  }

  /* Б, КБ, МБ — это сокращения слов, и в других языках они другие:
     по-английски B, KB, MB. Поэтому идут через машинку, а не стоят
     в строке буквами. */
  function размер(б) {
    б = Number(б) || 0;
    if (б < 1024) return б + ' ' + Т('Б');
    if (б < 1024 * 1024) return (б / 1024).toFixed(1) + ' ' + Т('КБ');
    return (б / 1024 / 1024).toFixed(1) + ' ' + Т('МБ');
  }

  /* Подпись столбца: A, B … Z, AA, AB — как в любой таблице. */
  function буква(н) {
    var с = '';
    н = Number(н) || 0;
    do { с = String.fromCharCode(65 + (н % 26)) + с; н = Math.floor(н / 26) - 1; }
    while (н >= 0);
    return с;
  }

  /* ── CSV ──
     Разбор с кавычками и сборка обратно тем же правилом. Разделитель
     задаётся: из Excel через буфер приходит не запятая, а табуляция, а
     правила кавычек там те же. */
  function разборCSV(т, раздел) {
    раздел = раздел || ',';
    var ряды = [], ряд = [], поле = '', вКавычках = false;
    т = String(т || '').replace(/\r\n?/g, '\n');
    for (var i = 0; i < т.length; i++) {
      var з = т[i];
      if (вКавычках) {
        if (з === '"') {
          if (т[i + 1] === '"') { поле += '"'; i++; }
          else вКавычках = false;
        } else поле += з;
      } else if (з === '"') вКавычках = true;
      else if (з === раздел) { ряд.push(поле); поле = ''; }
      else if (з === '\n') { ряд.push(поле); ряды.push(ряд); ряд = []; поле = ''; }
      else поле += з;
    }
    ряд.push(поле); ряды.push(ряд);
    while (ряды.length > 1 && ряды[ряды.length - 1].length === 1
           && ряды[ряды.length - 1][0] === '') ряды.pop();
    var ширина = 0;
    ряды.forEach(function (р) { if (р.length > ширина) ширина = р.length; });
    ряды.forEach(function (р) { while (р.length < ширина) р.push(''); });
    return ряды.length ? ряды : [['', '']];
  }

  function сборкаCSV(ряды) {
    return ряды.map(function (р) {
      return р.map(function (з) {
        з = String(з == null ? '' : з);
        return /[",\n]/.test(з) ? '"' + з.replace(/"/g, '""') + '"' : з;
      }).join(',');
    }).join('\n');
  }

  /* ── Служебный хвост ── */
  function началоСлужебного(т) {
    var а = т.indexOf(ЗНАКИ_МЕТКА), б = т.indexOf(КЛЕТКИ_МЕТКА);
    if (а < 0) return б;
    if (б < 0) return а;
    return Math.min(а, б);
  }

  function безЗнаков(тело) {
    var т = String(тело == null ? '' : тело);
    var н = началоСлужебного(т);
    return н < 0 ? т : т.slice(0, н);
  }

  function служебное(тело, метка) {
    var т = String(тело == null ? '' : тело);
    var н = началоСлужебного(т);
    if (н < 0) return null;
    var ключ = метка.slice(1);
    var строки = т.slice(н + 1).split('\n');
    for (var i = 0; i < строки.length; i++) {
      if (строки[i].indexOf(ключ) !== 0) continue;
      try { return JSON.parse(строки[i].slice(ключ.length)); } catch (е) { return null; }
    }
    return null;
  }

  function клеткиНаряда(тело) {
    var о = служебное(тело, КЛЕТКИ_МЕТКА);
    return (о && typeof о === 'object' && !Array.isArray(о)) ? о : {};
  }

  /* Знаки на таблице: подпись и печать лежат НАД клетками, в самой
     таблице их нет. Храним списком — адрес картинки и место долями от
     полотна, — потому что в клетку картинку не положишь, а место
     должно пережить и смену ширины окна, и другой экран. */
  function знакиСписком(тело) {
    var с = служебное(тело, ЗНАКИ_МЕТКА);
    return Array.isArray(с) ? с : [];
  }

  function знакамиХвост(список) {
    return (список && список.length)
      ? (ЗНАКИ_МЕТКА + JSON.stringify(список)) : '';
  }

  function нарядомХвост(наряд) {
    var есть = false;
    for (var к in наряд) if (наряд[к]) есть = true;
    return есть ? (КЛЕТКИ_МЕТКА + JSON.stringify(наряд)) : '';
  }

  CW.файлы = {
    ВИДЫ: ВИДЫ,
    ТИПЫ: ТИПЫ,
    ЗНАКИ_МЕТКА: ЗНАКИ_МЕТКА,
    КЛЕТКИ_МЕТКА: КЛЕТКИ_МЕТКА,
    поВиду: поВиду,
    чип: чип,
    значок: значок,
    видПоИмени: видПоИмени,
    смотрим: смотрим,
    видЗаписи: видЗаписи,
    везёмКак: везёмКак,
    названием: названием,
    размер: размер,
    буква: буква,
    разборCSV: разборCSV,
    сборкаCSV: сборкаCSV,
    безЗнаков: безЗнаков,
    служебное: служебное,
    клеткиНаряда: клеткиНаряда,
    нарядомХвост: нарядомХвост,
    знакиСписком: знакиСписком,
    знакамиХвост: знакамиХвост
  };
})();
