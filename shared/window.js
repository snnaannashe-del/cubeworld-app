/* ═══════════════════════════════════════════════════════════════════════
   СБОРКА ОКОН. Одно место, где окна собираются, — на все 35 штук.

   Вид лежит в window.css, здесь — сборка. Экран говорит, ЧТО написать;
   как это выглядит, он не знает и знать не должен. Поэтому у тридцати
   пяти окон одна шапка, один выход, один размер кнопок и одна ширина.

   ── Два рода ────────────────────────────────────────────────────────

       CW.стойка({…})    стоячее окно: от верха до низа, прокрутка
                         внутри. Одиннадцать окон поверх программы.

       CW.модалка({…})   лежачее окно: высота по содержимому, по
                         середине экрана. Двадцать четыре модалки.

   Ширина у обоих одна — 10 см. Это её правило на весь проект.

   ── Что принимают ───────────────────────────────────────────────────

       имя          строка. Под ней окно запоминается для перезагрузки
       знак         значок из общего набора ('звезда', 'речь', …)
       знакЦвет     цвет значка вместо синего ('#a78bfa')
       кружок       {снимок, значок, цвет} — вместо знака показать лицо
       заголовок    крупная строка
       подзаголовок мелкая под ней
       назад        fn — выход уводит туда. Нет — выход закрывает окно
       крест        true — выход рисуется крестиком, даже если «назад»
                    есть (окно на весь экран: закрывать его некуда)
       кнопки       [{имя, зн, подсказка, делать, горит, счёт}]
       подвал       [{подпись, главная, опасная, делать, имя}]
       черта        false — убрать линию под шапкой
       крестУгол    true — окну БЕЗ шапки нарисовать крестик прямо в
                    углу окна. Маленькому окну поверх тёмного экрана
                    нужна видимая дверь: «нажми мимо» знают не все
       шапка        false — окна без шапки совсем: ни значка, ни
                    названия, ни выхода. Нужно там, где окно — полка,
                    выехавшая снизу: у полки «Действия» шапки нет, и
                    комментарии к записи должны выглядеть так же.
                    Выход при этом не теряется: касание мимо и Escape
                    работают, как у всех окон.
       поля         false — тело без отступов (лента сообщений)
       мимо         false — запретить выход касанием мимо (платёж)
       сквозь       true — не затемнять то, что под окном, и пропускать
                    нажатия мимо него насквозь (игра с кубами)
       узкое        true — окно вполовину уже, 5 см вместо 10
       поРосту      true — стоячее окно высотой по содержимому, а не
                    во весь экран (карта: под её полкой оставалась
                    пустая половина экрана)
       широкое      true — окно в два столбца: слева список, справа
                    страница. Только для документов, см. ниже
       полуторное   true — полтора обычных окна (15 см). Для списка,
                    где строка «что сделать → каким словом» должна
                    читаться в одну линию: голосовые команды
       при_закрытии fn

   Шире 10 см не бывает ни одно окно. Справочник голосовых команд одно
   время стоял шире, и окно сразу перестало быть своим среди остальных.
   Если строка в 10 см не помещается — переносим строку, а не
   раздвигаем окно.

   Шире обычного — два окна, и оба списки для чтения, а не формы.

   Полтора окна («полуторное», 15 см) — голосовые команды. Там сто
   восемнадцать строк «что сделать → каким словом», и в десяти
   сантиметрах каждая складывалась надвое. Полтора — не на глаз:
   замерено, что при такой ширине ни одна строка не переносится, а
   пустоты в середине остаётся на палец, не на ладонь.

   Шире — ровно одно окно на всю программу: документы. Там слева
   список из семи бумаг, справа сама бумага, и в десяти сантиметрах
   такое не живёт: либо список прячется в меню поверх текста (так у нас
   и было, и это оказалось неудобно), либо текст встаёт в колонку в два
   пальца. Соглашение читают целиком, а не заглядывают в него, — и
   читают с настольного экрана. Это «широкое», и других таких окон нет.

   Уже — бывает, и ровно вдвое: «узкое». Это для окна, внутри которого
   одна короткая строка и больше ничего, как у «Добавить аккаунт» с его
   единственным полем под ключ. Десять сантиметров пустоты вокруг
   восемнадцати знаков выглядели не окном, а полосой. Доля одна — 
   половина, на глаз ширину никто не подбирает.

   ── Что отдают ──────────────────────────────────────────────────────

       {подложка, окно, шапка, тело, подвал,
        кнопки:{имя→узел}, низ:{имя→узел},
        открыть(), закрыть(), занят(да), пусто({…}), имя(заголовок, под)}

   ── Два правила проекта вшиты сюда, чтобы их нельзя было забыть ─────

       1. Из любого окна выходят касанием мимо него (и клавишей Escape).
       2. Перезагрузка возвращает в то же окно, где человек был.

   Экран, который собирает окно руками, эти правила однажды потеряет.
   Собранное здесь — не теряет никогда.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  function э(тег, класс) { return CW.эл(тег, класс); }

  /* Стопка открытых окон. Модалка поверх окна — обычное дело: из
     профиля открыли «подарить ключ». Escape и касание мимо должны
     закрывать верхнее, а не все сразу. */
  var СТОПКА = [];

  function собрать(род, н) {
    н = н || {};

    /* ── СКВОЗНОЕ ОКНО ──
       Обычное окно затемняет то, что под ним: смотреть туда незачем.
       Но у игры с кубами смотреть надо именно туда — на кубы, которые
       она бросает. Затемнение и размытие здесь мешают, а нажатие мимо
       окна должно доставаться миру: мир им крутят.

       Поэтому у такого окна подложка прозрачная и не ловит нажатий, а
       само окно стоит сбоку, а не посередине. */
    /* ── ОКНО ВНУТРИ КАДРА ──
       Обычное окно висит посреди экрана. Но у ленты есть свой кадр —
       столбик с роликом, — и комментарии к ролику должны выезжать
       снизу ВНУТРИ него, как в боевой: человек продолжает видеть, к
       чему эти комментарии. Поэтому окно умеет жить не только в теле
       страницы, но и внутри заданного узла. */
    var вКадре = н.вКадре || null;
    var подложка = э('div', 'ок-подложка ' + род
                      + (н.сквозь ? ' сквозь' : '')
                      + (вКадре ? ' вкадре' : ''));
    var окноУзел = э('div', 'ок-окно ' + род
                      + (н.черта === false ? ' без-черты' : '')
                      + (н.узкое ? ' узкое' : '')
                      + (н.поРосту ? ' порост' : '')
                      + (н.широкое ? ' широкое' : '')
                      + (н.полуторное ? ' полуторное' : ''));

    /* ── шапка ────────────────────────────────────────────────────
       Рисуется отдельной функцией, потому что окна умеют менять режим:
       портфолио становится редактором, список переписок — перепиской.
       Шапка при этом меняется целиком — название, лицо, кнопки, — а
       окно остаётся тем же и не перескакивает. */
    var естьШапка = н.шапка !== false;
    var шапка = э('div', 'ок-шапка');
    var кнопки = {};
    var шапкаСейчас = н;
    var подУзел;

    function рисоватьШапку(ш) {
      шапкаСейчас = ш;
      /* Окну без шапки рисовать нечего. Проверка стоит здесь, а не у
         каждого вызова: шапку перерисовывают из четырёх мест, и забыть
         проверку в одном из них — вопрос времени. */
      if (!естьШапка) return;
      шапка.innerHTML = '';
      кнопки = {};
      он.кнопки = кнопки;

      /* ── ПОРЯДОК ШАПКИ. Один на все окна программы ──────────────────

             [ значок ]  Название .......  [ действие ]  [ ✕ ]

         Слева — чем окно является: значок раздела или лицо человека.
         Рядом с ним название, ровно по его середине.
         Справа, у самого края, — выход. И прямо перед выходом — то
         главное, зачем окно открыли: цветной кругляш с одним значком.

         Почему так, а не кнопками внизу. Ряд «Отмена · Опубликовать»
         под формой — это ещё одна полоса высоты на каждом окне, и на
         длинной форме она уезжает вниз вместе с содержимым: человек
         заполнил поля, а кнопки не видно. В шапке они на месте всегда.

         Выход справа, а не слева: слева его клали по привычке от
         «назад» в браузере, но здесь это не возврат по истории, а
         закрытие. Закрытие живёт в правом верхнем углу — там его
         ищут рукой, не глядя.

         Подпись под названием — по надобности. Если она повторяет
         то, что и так написано в окне, её быть не должно. */

      if (ш.кружок) {
        /* «кто» — номер человека, если в шапке лицо, а не значок
           группы или куба: по нему склад лиц сам поставит снимок и
           сам сменит его, когда человек выберет другой. */
        шапка.appendChild(CW.кружок({
          размер: 34, кто: ш.кружок.кто, группа: ш.кружок.группа,
          снимок: ш.кружок.снимок, версия: ш.кружок.версия,
          значок: ш.кружок.значок, цвет: ш.кружок.цвет
        }));
      } else if (ш.знак) {
        var зн = э('div', 'ок-знак');
        зн.innerHTML = CW.значок(ш.знак);
        if (ш.знакЦвет) зн.style.color = ш.знакЦвет;
        шапка.appendChild(зн);
      }

      var имя = э('div', 'ок-имя');
      имя.innerHTML = '<b></b><span></span>';
      имя.querySelector('b').textContent = ш.заголовок || '';
      подУзел = имя.querySelector('span');
      подУзел.textContent = ш.подзаголовок || '';
      if (!ш.подзаголовок) подУзел.style.display = 'none';
      шапка.appendChild(имя);

      /* «нажатие» — что делать, когда нажали на лицо с именем. Нужно
         переписке: оттуда так заходят в портфолио собеседника. Кружок
         и имя — одна цель: человек целится в лицо, а попадает между
         ним и именем, и ничего не происходит. */
      if (ш.нажатие) {
        имя.classList.add('жмётся');
        имя.onclick = ш.нажатие;
        var лицоШапки = шапка.querySelector('.cw-кружок, .ок-знак');
        if (лицоШапки) {
          лицоШапки.classList.add('жмётся');
          лицоШапки.onclick = ш.нажатие;
        }
      }

      /* Кругляши стоят отдельным рядом со своим, более тесным шагом.
         Между названием и рядом — промежуток шапки; внутри ряда кнопки
         прижаты друг к другу, потому что это одна группа, а не три
         отдельные вещи, разбросанные по правому краю. */
      var ряд = э('div', 'ок-ряд');
      шапка.appendChild(ряд);

      (ш.кнопки || []).forEach(function (к) {
        var б = э('button', 'ок-кн' + (к.горит ? ' горит' : '')
                          + (к.опасная ? ' опасная' : '')
                          + (к.широкая ? ' широкая' : ''));
        б.type = 'button';
        б.innerHTML = (к.зн ? CW.значок(к.зн) : (к.текст || ''))
                    + '<span class="счёт"></span>';
        б.title = к.подсказка || '';
        if (к.счёт) б.querySelector('.счёт').textContent = к.счёт;
        б.onclick = function (е) { if (к.делать) к.делать(е, б); };
        ряд.appendChild(б);
        кнопки[к.имя || к.зн || к.подсказка] = б;
      });

      /* Главное действие окна — цветным кругляшом перед выходом.
         Оно одно: два «главных» действия означают, что окно делает
         две разные вещи и его надо делить. */
      if (ш.главная) {
        var г = э('button', 'ок-кн главная' + (ш.главная.опасная ? ' опасная' : ''));
        г.type = 'button';
        г.innerHTML = CW.значок(ш.главная.зн || 'галка');
        г.title = ш.главная.подсказка || '';
        г.onclick = function (е) { if (ш.главная.делать) ш.главная.делать(е, г); };
        ряд.appendChild(г);
        кнопки['главная'] = г;
      }

      /* Выход — последним, у самого края. Стрелка, когда есть куда
         вернуться; крестик, когда окно просто закрывается на месте.
         Разница не украшение: стрелка обещает возврат, крестик —
         исчезновение. */
      var выход = э('button', 'ок-кн выход');
      выход.type = 'button';
      выход.title = Т((ш.назад && !ш.крест) ? 'Назад' : 'Закрыть');
      /* крест:true — нарисовать крестик, хотя выход уводит. Нужен там,
         где окно и ЕСТЬ весь экран: закрывать его некуда, под ним пустая
         страница с одной строкой, и стрелка обещала бы возврат, которого
         нет. Само поведение при этом не меняется — уводит туда же, куда
         уводил бы «назад». */
      /* Стрелка — длинная, с хвостом, а не шеврон: шеврон читается как
         «свернуть», стрелка — как «вернуться». Так стоит в боевой. */
      выход.innerHTML = (ш.назад && !ш.крест)
                      ? CW.значок('назад')
                      : CW.рисунок('M6 6 18 18M18 6 6 18');
      выход.onclick = function () {
        if (шапкаСейчас.назад) шапкаСейчас.назад(); else он.закрыть();
      };

      /* ── КУДА В РЯДУ ВСТАЁТ ВЫХОД ──
         По умолчанию — последним, у самого края: так во всех окнах, и
         менять это правило целиком нельзя, иначе человек будет искать
         выход в разных местах.

         Окно может сказать «выходМесто: 'первым'» — и тогда выход
         встанет в начале ряда. Это нужно там, где последняя кнопка ряда
         открывает меню: меню выезжает из-под неё вниз, и у самого края
         оно раскрывается точно под своей кнопкой. Избранное — как раз
         такое окно. */
      if ((ш.выходМесто || н.выходМесто) === 'первым') ряд.insertBefore(выход, ряд.firstChild);
      else ряд.appendChild(выход);
    }

    if (естьШапка) окноУзел.appendChild(шапка);

    /* ── крестик в углу ───────────────────────────────────────────
       Окну без шапки выходить нечем: шапка унесла с собой и кнопку
       выхода. Касание мимо и Escape остаются, но это знание, а не
       видимая дверь, и маленькому окну поверх тёмного экрана дверь
       нужна. Рисуем крестик прямо в углу окна, поверх содержимого, —
       он не шапка и ничего не занимает.

       Окну с шапкой этого не нужно: у него крестик и так есть. */
    if (!естьШапка && н.крестУгол) {
      var крестик = э('button', 'ок-крестик');
      крестик.type = 'button';
      крестик.title = Т('Закрыть');
      крестик.innerHTML = CW.рисунок('M6 6 18 18M18 6 6 18', 15);
      крестик.onclick = function () { он.закрыть(); };
      окноУзел.appendChild(крестик);
    }

    /* ── тело ───────────────────────────────────────────────────── */
    var тело = э('div', 'ок-тело' + (н.поля === false ? ' без-полей' : ''));
    окноУзел.appendChild(тело);

    /* ── подвал ─────────────────────────────────────────────────── */
    var подвал = null, низ = {};
    if (н.подвал && н.подвал.length) {
      подвал = э('div', 'ок-подвал');
      н.подвал.forEach(function (к) {
        var б = э('button', 'кнопка' + (к.главная ? ' главная' : '')
                          + (к.опасная ? ' опасная' : ''));
        б.type = 'button';
        б.textContent = к.подпись || '';
        б.onclick = function (е) { if (к.делать) к.делать(е, б); };
        подвал.appendChild(б);
        низ[к.имя || к.подпись] = б;
      });
      окноУзел.appendChild(подвал);
    }

    подложка.appendChild(окноУзел);

    /* ── ОДНО ОКНО НА ИМЯ ──────────────────────────────────────────
       Закрытие окна его не удаляет: подложка остаётся в разметке,
       только спрятанная. Это нарочно — окно, в которое возвращаются,
       не должно собираться заново.

       Но открыть «Свайп» второй раз — значит собрать ВТОРОЙ такой же
       узел рядом с первым. И тогда всё, что окно ищет у себя внутри
       по имени, находит не себя, а прошлый, мёртвый экземпляр: монеты
       и сети рисуются в него, а человек смотрит на пустые заголовки.
       Ровно это и случалось со второго открытия.

       Поэтому прежнее окно с тем же именем убираем здесь, в одном
       месте, а не заставляем каждую модалку помнить об этом. */
    if (н.имя) {
      подложка.dataset.окно = н.имя;
      var прежние = документ.querySelectorAll('.ок-подложка[data-окно="' + н.имя + '"]');
      [].slice.call(прежние).forEach(function (у) {
        if (у.парный) {
          /* Было открыто — убираем и из стопки, иначе «нажал мимо»
             продолжит закрывать узел, которого уже нет в разметке. */
          var м = СТОПКА.indexOf(у.парный);
          if (м >= 0) СТОПКА.splice(м, 1);
        }
        if (у.parentNode) у.parentNode.removeChild(у);
      });
    }

    (вКадре || документ.body).appendChild(подложка);

    /* ── ОКНО НА СВОЕЙ СТРАНИЦЕ НЕ ВЫПЛЫВАЕТ ──
       Подложка проявляется за 0,16 с. Поверх программы это правильно:
       окно приходит в гости. Но на странице окна оно и ЕСТЬ страница,
       приходить ему неоткуда, и за эти 0,16 с сквозь полупрозрачную
       подложку видно оболочку под ней - ту самую шапку раздела.
       Поэтому здесь окно встаёт сразу. */
    var своя = CW.вОкне && !вКадре;
    if (своя) подложка.style.animation = 'none';

    /* ── ПОКА ПОЛКА ОТКРЫТА, ЛЕНТА ПОД НЕЙ СТОИТ ──
       Полка комментариев выезжает ВНУТРИ кадра ленты, а кадр лежит в
       ленте, которая листается пальцем. Палец по полке - и лента под
       ней уезжала на следующий ролик: полка оставалась открытой уже
       над чужой записью и выглядела оторванной. Анна прислала это
       снимком: комментарии висят, а под ними другое видео.

       Поэтому на время, пока полка открыта, лента замирает: её
       прокрутку снимаем, место запоминаем и возвращаем ровно то же,
       когда полку закрыли. Сама полка внутри прокручивается как
       прокручивалась - у неё своя прокрутка.

       Ищем именно ту ленту, в которой лежит кадр: это может быть
       лента записей, полоса историй, список - кто угодно, кто
       прокручивается вверх-вниз. */
    var ЛЕНТА = null, МЕСТО = 0;

    /* Кто листается под кадром - знает общая рука в конце этого файла
       (листаемыйПредок): ровно тот же вопрос задаёт подводка поля под
       клавиатуру, и двух ответов на него быть не должно. */
    function держатьКадр(держать) {
      if (!вКадре) return;
      if (держать) {
        if (ЛЕНТА) return;
        ЛЕНТА = листаемыйПредок(вКадре);
        if (!ЛЕНТА) return;
        МЕСТО = ЛЕНТА.scrollTop;
        ЛЕНТА.classList.add('ок-замерла');
        return;
      }
      if (!ЛЕНТА) return;
      ЛЕНТА.classList.remove('ок-замерла');
      /* Браузер иногда сбрасывает место, пока прокрутки нет: ставим
         его обратно, иначе закрытая полка возвращает человека к началу
         ленты. */
      if (ЛЕНТА.scrollTop !== МЕСТО) ЛЕНТА.scrollTop = МЕСТО;
      ЛЕНТА = null;
    }

    /* ── что умеет готовое окно ─────────────────────────────────── */
    var открыто = false;
    var открылиКогда = 0;
    /* Узел знает своё окно: по узлу, найденному в разметке, надо уметь
       добраться до объекта — например чтобы вычеркнуть его из стопки. */
    подложка.парный = null;
    var он;

    он = {
      подложка: подложка,
      окно: окноУзел,
      шапка: шапка,
      тело: тело,
      подвал: подвал,
      кнопки: кнопки,
      низ: низ,

      открыть: function (что) {
        открылиКогда = Date.now();
        подложка.classList.add('видно');
        окноУзел.classList.remove('занято');
        открыто = true;
        держатьКадр(true);

        /* Оболочка на странице окна ждала этой минуты. Пока окна не
           было видно, она стояла невидимой, чтобы человек не увидел
           сперва шапку раздела, а через полсекунды шапку окна
           (shared/shell.js, «страница окна не мигает шапкой»).

           Снимаем знак именно здесь, а не там, где подложку кладут в
           разметку: положена она сразу, а показывается только этой
           строчкой выше, и всё время между ними человек видел бы голую
           оболочку. Первый заход так и выглядел. */
        if (своя) {
          var рамаСтраницы = документ.querySelector('.об-рама.ждёт-окна');
          if (рамаСтраницы) рамаСтраницы.classList.remove('ждёт-окна');
        }
        if (СТОПКА.indexOf(он) < 0) СТОПКА.push(он);
        /* ПРАВИЛО: перезагрузка возвращает в то же окно. */
        if (н.имя) {
          var память = { окно: н.имя };
          for (var к in (что || {})) {
            if (Object.prototype.hasOwnProperty.call(что, к)) память[к] = что[к];
          }
          CW.гдеБыл(память);
        }
        return он;
      },

      закрыть: function () {
        if (!открыто) return он;
        держатьКадр(false);
        подложка.classList.remove('видно');
        открыто = false;
        var где = СТОПКА.indexOf(он);
        if (где >= 0) СТОПКА.splice(где, 1);
        if (н.имя && !СТОПКА.length) CW.гдеБыл(null);
        if (н.при_закрытии) н.при_закрытии();
        return он;
      },

      убрать: function () {
        он.закрыть();
        if (подложка.parentNode) подложка.parentNode.removeChild(подложка);
      },

      открыто: function () { return открыто; },

      /* Неподвижные полосы над лентой и под ней. Так устроены все три
         переписки: сверху поиск, посередине лента, снизу поле ввода.
         Полосы не прокручиваются вместе с лентой — иначе поле ввода
         уезжает вверх ровно тогда, когда человек хочет ответить. */
      сверху: function (узел) { окноУзел.insertBefore(узел, тело); return узел; },
      снизу:  function (узел) {
        окноУзел.insertBefore(узел, подвал || null);
        return узел;
      },

      /* Пока ждём сервер — окно не нажимается. Иначе человек жмёт
         «Купить» второй раз и платит дважды. */
      занят: function (да) {
        окноУзел.classList.toggle('занято', да !== false);
        return он;
      },

      имя: function (заголовок, под) {
        if (!естьШапка) return он;    /* писать название некуда */
        if (заголовок != null) шапка.querySelector('.ок-имя b').textContent = заголовок;
        if (под !== undefined) {
          подУзел.textContent = под || '';
          подУзел.style.display = под ? '' : 'none';
        }
        return он;
      },

      /* Сменить режим окна целиком: другое название, другое лицо,
         другие кнопки. Окно при этом то же самое и не моргает. */
      шапку: function (ш) {
        рисоватьШапку(ш || шапкаСейчас);
        return он;
      },

      /* Пустое окно обязано объяснить, почему оно пустое. */
      пусто: function (что) {
        что = что || {};
        тело.innerHTML = '';
        var п = э('div', 'ок-пусто');
        п.innerHTML = (что.знак ? '<span class="зн">' + CW.значок(что.знак) + '</span>' : '')
                    + '<b>' + CW.безопасно(что.заголовок || Т('Пока пусто')) + '</b>'
                    + CW.безопасно(что.текст || '');
        тело.appendChild(п);
        if (что.кнопка) {
          var б = э('button', 'кнопка главная');
          б.type = 'button';
          б.style.marginTop = '16px';
          б.textContent = что.кнопка.подпись;
          б.onclick = что.кнопка.делать;
          п.appendChild(б);
        }
        return он;
      }
    };

    подложка.парный = он;

    рисоватьШапку(н);

    /* ПРАВИЛО: из любого окна выходят касанием мимо него.

       Запрет (мимо:false) — редкое исключение: платёж, выданный ключ.
       Но запрет на всё время жизни окна лишний: пока в окне ничего
       ценного нет, оно должно закрываться как все. Поэтому «мимо»
       может быть и функцией: окно спрашивается в тот самый миг, когда
       человек нажал мимо, и отвечает, можно ли сейчас. */
    if (н.мимо !== false) {
      CW.мимоОкна(подложка, выйтиМимо);

      /* ── сквозное окно ловит «мимо» само ──
         У него подложка не ловит нажатий вовсе — иначе за ней нельзя
         было бы крутить мир. Поэтому слушаем документ.

         И отличаем поворот мира от нажатия: если палец проехал больше
         восьми точек, человек крутил сцену, а не промахнулся мимо окна.
         Нажатие, которым окно открыли, тоже не считается: оно приходит
         сюда же, и окно закрывалось бы в тот же миг. */
      if (н.сквозь) {
        var началX = 0, началY = 0, началиГде = null;
        документ.addEventListener('pointerdown', function (е) {
          началX = е.clientX; началY = е.clientY; началиГде = е.target;
        }, true);
        документ.addEventListener('pointerup', function (е) {
          if (!открыто || СТОПКА[СТОПКА.length - 1] !== он) return;
          if (Date.now() - открылиКогда < 400) return;
          var проехал = Math.abs(е.clientX - началX) + Math.abs(е.clientY - началY);
          if (проехал > 8) return;
          if (окноУзел.contains(е.target) || окноУзел.contains(началиГде)) return;
          /* Нажатие по другому окну поверх — тоже не «мимо». */
          if (е.target.closest && е.target.closest('.ок-подложка')) return;
          выйтиМимо();
        }, true);
      }
    }

    function выйтиМимо() {
      /* Окно-функция: спрашиваем прямо сейчас. Сказало «нельзя» —
         остаёмся, и у человека есть крестик. */
      if (typeof н.мимо === 'function' && н.мимо() === false) return;
      /* закрываем только верхнее окно стопки */
      if (СТОПКА[СТОПКА.length - 1] === он) {
        if (шапкаСейчас.назад) шапкаСейчас.назад(); else он.закрыть();
      }
    }

    return он;
  }


  /* ═════════════════════════════════════════════════════════════════
     РАЗДЕЛЫ — СВЁРНУТЫЕ ПОЛКИ ВНУТРИ ОКНА.

     Когда полей больше пяти, столбиком они не помещаются ни на один
     экран, и человек листает форму в поисках кнопки. Разделами окно
     помещается целиком: видно оглавление, а не простыня.

     Этот же вид стоял в трёх окнах, написанный трижды слово в слово
     («Новая вещь», «Игры с кубами», «Создать куб»). Теперь сборщик
     один, и полки во всех окнах открываются одинаково.

         М.тело.innerHTML =
             CW.разделы.рисовать('главное', 'Название и описание', '…')
           + CW.разделы.рисовать('вид',     'Вид куба',            '…');

         var Р = CW.разделы.завести(М.тело);
         Р.открыть('главное');   // раскрыть полку (например, на ошибке)

     По умолчанию свёрнуты все: окно открывается коротким списком
     названий. Полки не закрывают друг друга: открыл вторую — первая
     осталась открытой. Прежде открыта была всегда одна, и человек,
     заполнив подпись, закрывал её, чтобы добраться до тегов, и
     переставал видеть написанное. Длину окна держит прокрутка в теле,
     а не захлопывание соседей.

     Открыть сразу всё — четвёртым доводом у «рисовать» или
     списком у «завести»:

         CW.разделы.рисовать('тип', 'Тип', '…', true)   // открыт сразу
         CW.разделы.завести(М.тело, {открыт: true})     // все
         CW.разделы.завести(М.тело, {открыт: 'главное'})
         CW.разделы.завести(М.тело, {открыт: ['тип', 'теги']})

     Стрелка: свёрнуто — вправо, открыто — вниз. Одна на все окна.

     Вид — window.css, блок «.вщ-разд».
     ═════════════════════════════════════════════════════════════════ */
  CW.разделы = {

    /* Пятый довод «голый» — полка без стрелки и без сворачивания:
       заголовок остаётся, а дверцы нет. Нужно там, где все полки и
       так открыты всегда и сворачивать их незачем: в «Новом посте»
       стрелки только обещали то, чего человек не делает. */
    рисовать: function (ключ, имя, внутри, открыт, голый) {
      return '<div class="вщ-разд' + (открыт || голый ? ' открыт' : '')
           + (голый ? ' голый' : '')
           + '" data-разд="' + ключ + '">'
           + '<div class="вщ-шапка"><span>' + (имя || '') + '</span>'
           + (голый ? ''
               : '<span class="вщ-стрелка">' + CW.значок('шеврон') + '</span>')
           + '</div>'
           + '<div class="вщ-нутро">' + (внутри || '') + '</div>'
           + '</div>';
    },

    завести: function (где, о) {
      о = о || {};
      var корень = где || документ;
      var все = [].slice.call(корень.querySelectorAll('.вщ-разд'));

      function найти(ключ) {
        return корень.querySelector('.вщ-разд[data-разд="' + ключ + '"]');
      }
      function свернуть() {
        все.forEach(function (х) { х.classList.remove('открыт'); });
      }
      /* Открывает одну полку и не трогает соседние: человек сам решает,
         что ему держать открытым. */
      function открыть(ключ) {
        if (ключ === true) { все.forEach(function (х) { х.classList.add('открыт'); }); return; }
        if (Array.isArray(ключ)) { ключ.forEach(открыть); return; }
        var р = (typeof ключ === 'string') ? найти(ключ) : ключ;
        if (!р) return;
        р.classList.add('открыт');
      }

      все.forEach(function (р) {
        /* У голой полки шапка ничего не делает: без стрелки нажатие
           на заголовок свернуло бы раздел неожиданно, и человек не
           понял бы, куда он делся. */
        if (р.classList.contains('голый')) return;
        р.querySelector('.вщ-шапка').onclick = function () {
          р.classList.toggle('открыт');
        };
      });

      if (о.открыт) открыть(о.открыт);

      return { открыть: открыть, свернуть: свернуть, найти: найти, все: все };
    }
  };


  /* ═════════════════════════════════════════════════════════════════
     ПОЛЯ ФОРМЫ. Один сборщик на все двадцать четыре модалки.

     Двадцать четыре формы, написанные по отдельности, — это двадцать
     четыре слегка разных «Название»: где-то подпись прописными, где-то
     нет, где-то поле на три точки выше. Проверено на прошлой программе.

         var Ф = CW.поля(окно.тело, [
           {имя:'название', подпись:'Название', обяз:true, предел:80},
           {имя:'цена', подпись:'Цена', вид:'число', рядом:'валюта'},
           {имя:'валюта', подпись:'Валюта', вид:'выбор',
            пункты:[{знач:'CUBE', подпись:'CUBE'}]},
           {имя:'раздел', подпись:'Раздел', вид:'фишки', пункты:[…]},
           {имя:'видно', подпись:'Показывать всем', вид:'тумблер',
            под:'иначе увидят только по ссылке'}
         ]);

         Ф.взять()        все значения разом
         Ф.взять('цена')  одно
         Ф.поставить({…}) подставить
         Ф.проверить()    true, если обязательные заполнены;
                          незаполненное подсвечивает само

     Виды: текст (по умолчанию) · много · число · выбор · фишки ·
           тумблер · цвет · смайл.
     ═════════════════════════════════════════════════════════════════ */
  CW.поля = function (куда, список) {
    var узлы = {}, значения = {}, ряды = {};

    (список || []).forEach(function (п) {
      значения[п.имя] = п.значение !== undefined ? п.значение
                      : (п.вид === 'тумблер' ? false : '');

      /* «рядом» ставит два поля в строку: цена и валюта, месяц и год. */
      var гнездо = куда;
      if (п.рядом) {
        if (!ряды[п.рядом]) {
          ряды[п.рядом] = э('div', 'ок-пара');
          куда.appendChild(ряды[п.рядом]);
        }
        гнездо = ряды[п.рядом];
      }

      if (п.вид === 'тумблер') {
        var строка = э('div', 'ок-строка');
        строка.innerHTML = '<div class="текст"><b></b><span></span></div>';
        строка.querySelector('b').textContent = п.подпись || '';
        var подп = строка.querySelector('span');
        подп.textContent = п.под || '';
        if (!п.под) подп.style.display = 'none';
        var т = э('button', 'ок-тумблер' + (значения[п.имя] ? ' вкл' : ''));
        т.type = 'button';
        т.onclick = function () {
          значения[п.имя] = !значения[п.имя];
          т.classList.toggle('вкл', значения[п.имя]);
          if (п.менять) п.менять(значения[п.имя]);
        };
        строка.appendChild(т);
        гнездо.appendChild(строка);
        узлы[п.имя] = т;
        return;
      }

      var поле = э('div', 'ок-поле');
      if (п.подпись) {
        var ярлык = э('label');
        ярлык.textContent = п.подпись + (п.обяз ? ' *' : '');
        поле.appendChild(ярлык);
      }

      var у;
      if (п.вид === 'много') {
        у = э('textarea');
        у.rows = п.строк || 3;
      } else if (п.вид === 'выбор') {
        у = э('select');
        (п.пункты || []).forEach(function (к) {
          var о = э('option');
          о.value = к.знач;
          о.textContent = к.подпись;
          у.appendChild(о);
        });
      } else if (п.вид === 'фишки' || п.вид === 'смайл') {
        у = э('div', 'ок-фишки');
        (п.пункты || []).forEach(function (к) {
          var б = э('button', 'ок-фишка'
                    + (значения[п.имя] === к.знач ? ' выбрана' : ''));
          б.type = 'button';
          б.innerHTML = (к.зн ? CW.значок(к.зн) : '')
                      + '<span>' + CW.безопасно(к.подпись) + '</span>';
          б.onclick = function () {
            значения[п.имя] = к.знач;
            [].slice.call(у.children).forEach(function (д) {
              д.classList.remove('выбрана');
            });
            б.classList.add('выбрана');
            поле.classList.remove('плохо');
            if (п.менять) п.менять(к.знач);
          };
          у.appendChild(б);
        });
      } else {
        у = э('input');
        у.type = п.вид === 'число' ? 'number' : 'text';
        if (п.вид === 'число') { у.step = п.шаг || 'any'; у.min = п.наим || 0; }
      }

      if (у.tagName !== 'DIV') {
        у.placeholder = п.намёк || '';
        у.value = значения[п.имя];
        if (п.предел) у.maxLength = п.предел;
        у.oninput = у.onchange = function () {
          значения[п.имя] = this.value;
          поле.classList.remove('плохо');
          if (счётчик) счётчик.textContent = this.value.length + '/' + п.предел;
          if (п.менять) п.менять(this.value);
        };
      }
      поле.appendChild(у);

      /* Счётчик знаков только там, где есть предел: без предела он
         превращается в бессмысленное число, которое человек всё равно
         читает и пытается понять. */
      var счётчик = null;
      if (п.предел) {
        счётчик = э('div', 'подсказ');
        счётчик.style.textAlign = 'right';
        счётчик.textContent = String(значения[п.имя]).length + '/' + п.предел;
        поле.appendChild(счётчик);
      }
      if (п.подсказ) {
        var пс = э('div', 'подсказ');
        пс.textContent = п.подсказ;
        поле.appendChild(пс);
      }

      гнездо.appendChild(поле);
      узлы[п.имя] = у;
      узлы[п.имя + ':поле'] = поле;
    });

    return {
      узлы: узлы,

      взять: function (имя) {
        if (имя) return значения[имя];
        var всё = {};
        for (var к in значения) {
          if (Object.prototype.hasOwnProperty.call(значения, к)) всё[к] = значения[к];
        }
        return всё;
      },

      поставить: function (что) {
        for (var к in (что || {})) {
          if (!Object.prototype.hasOwnProperty.call(значения, к)) continue;
          значения[к] = что[к];
          var у = узлы[к];
          if (!у) continue;
          if (у.classList && у.classList.contains('ок-тумблер')) {
            у.classList.toggle('вкл', !!что[к]);
          } else if (у.tagName !== 'DIV') {
            у.value = что[к];
          }
        }
      },

      /* Подсвечиваем ВСЕ незаполненные разом, а не первое. Иначе
         человек заполняет одно, жмёт, узнаёт про второе, заполняет,
         жмёт, узнаёт про третье. */
      проверить: function () {
        var ладно = true, первое = null;
        (список || []).forEach(function (п) {
          if (!п.обяз) return;
          var пусто = !String(значения[п.имя] == null ? '' : значения[п.имя]).trim();
          var поле = узлы[п.имя + ':поле'];
          if (поле) поле.classList.toggle('плохо', пусто);
          if (пусто) { ладно = false; if (!первое) первое = узлы[п.имя]; }
        });
        if (!ладно) {
          CW.сказать(Т('Заполни то, что подсвечено'));
          if (первое && первое.focus) первое.focus();
        }
        return ладно;
      }
    };
  };

  CW.стойка  = function (н) { return собрать('стоячее', н); };
  CW.модалка = function (н) { return собрать('лежачее', н); };

  /* ═════════════════════════════════════════════════════════════════
     ПОДКЛЮЧЕНИЕ МОДАЛОК ПО ТРЕБОВАНИЮ.

     Двадцать четыре модалки не должны грузиться на каждом экране: на
     ленте нужны комментарии и «поделиться», а «вывод денег» там не
     нужен ни разу. Файл приезжает в тот момент, когда его открывают,
     и второй раз уже не приезжает.

         CW.открыть('share', {пост: 12});

     Файл modals/share.js при загрузке кладёт себя в список:

         CW.модаль('share', function (данные) { … });
     ═════════════════════════════════════════════════════════════════ */
  /* ── подтянуть общий файл по требованию ────────────────────────────
     Модалка может опираться на кусок, которого на этом экране нет:
     «привязать кошелёк» нужен кусок кошельков, а лента его не грузит.
     Тащить все общие файлы на каждый экран ради этого — дорого; пусть
     модалка сама скажет, что ей нужно.

         CW.нужен('shared/wallets.js').then(собрать);

     Второй раз файл не едет. */
  var ПРИЕХАЛО = {};

  CW.нужен = function (путь) {
    if (ПРИЕХАЛО[путь]) return ПРИЕХАЛО[путь];
    ПРИЕХАЛО[путь] = new Promise(function (готово, беда) {
      var с = документ.createElement('script');
      с.src = CW.свежий(CW.путь(путь));
      с.onload = function () { готово(); };
      с.onerror = function () { беда(new Error(Т('не приехал ') + путь)); };
      документ.head.appendChild(с);
    });
    return ПРИЕХАЛО[путь];
  };

  var ЕСТЬ = {};      /* имя → функция открытия */
  var ЕДЕТ = {};      /* имя → обещание загрузки */

  CW.модаль = function (имя, делать) { ЕСТЬ[имя] = делать; };

  CW.открыть = function (имя, данные) {
    if (ЕСТЬ[имя]) return Promise.resolve(ЕСТЬ[имя](данные || {}));

    if (!ЕДЕТ[имя]) {
      ЕДЕТ[имя] = new Promise(function (готово, беда) {
        var с = документ.createElement('script');
        с.src = CW.свежий(CW.путь('modals/' + имя + '.js'));
        с.onload = function () {
          if (ЕСТЬ[имя]) готово();
          else беда(new Error(Т('модалка ') + имя + ' не назвалась'));
        };
        с.onerror = function () { беда(new Error(Т('не приехала модалка ') + имя)); };
        документ.head.appendChild(с);
      });
    }

    return ЕДЕТ[имя].then(function () {
      return ЕСТЬ[имя](данные || {});
    }).catch(function (е) {
      /* Молчащая кнопка хуже честного отказа: человек жмёт её трижды
         и решает, что сломалась программа. */
      CW.сказать(Т.с('Не удалось открыть: {что}', { что: (е && е.message ? е.message : имя) }));
      throw е;
    });
  };

  /* ═══════════════════════════════════════════════════════════════════
     ПОЛЕ, В КОТОРОЕ ВСТАЛИ, ОСТАЁТСЯ НА ВИДУ

     На телефоне клавиатура занимает половину экрана и закрывает ровно
     то поле, в которое человек только что ткнул: он печатает вслепую.
     Анна сняла это на «Ключе куба» - поле оказалось под клавиатурой и
     под её же полосой с галочкой.

     ── ЧТО БЫЛО НЕ ТАК ──────────────────────────────────────────────
     Анна: «когда мы хотим заполнить любую ячейку и подгружается
     клавиатура, она подгружается корректно и не скачет, не каждый раз
     с разной позиции».

     Прежний порядок давал РАЗНЫЙ ответ на одно и то же действие по
     трём причинам:

       1. Ждали ровно треть секунды. Клавиатура выезжает за это время,
          только если её ещё нет. Если она УЖЕ стоит (перешли из поля
          в поле), ждать нечего, и треть секунды - это треть секунды
          неподвижности, после которой экран вдруг дёргается.

       2. Подводили поле К СЕРЕДИНЕ видимого. Середина - это «как
          можно дальше от того места, где поле сейчас»: сдвиг всякий
          раз свой, от нуля до половины экрана, смотря где поле
          стояло. Отсюда и «каждый раз с разной позиции».

       3. Видимое считали от нуля (р.top >= 0). Ноль - это верх
          СТРАНИЦЫ, а при выехавшей клавиатуре видимое окошко сдвинуто
          внутрь страницы, и его верх не ноль.

     ── КАК СТАЛО ────────────────────────────────────────────────────
     Ждём не время, а тишину: клавиатура меняет размер видимой части,
     и мы трогаемся, когда эти изменения прекратились. Уже стоит -
     трогаемся почти сразу.

     Двигаем на МИНИМУМ: столько, чтобы поле целиком вошло в видимое с
     одним и тем же зазором в 14 точек. Поле видно - не двигаем ничего.
     Один и тот же вид даёт один и тот же сдвиг, и это и есть «не
     скачет».

     Двигаем ОДИН слой - ближайший к полю список, который и правда
     прокручивается. Прежний scrollIntoView двигал все слои разом,
     включая раму оболочки, и шапка уезжала за край.
     ═══════════════════════════════════════════════════════════════════ */
  var ЗАЗОР  = 14;     /* воздух между полем и краем клавиатуры, точек */
  var ТИШИНА = 120;    /* столько миллисекунд без изменений = выехала  */
  var ПРЕДЕЛ = 900;    /* дольше не ждём: клавиатуры, видимо, не будет  */

  /* Ближайший предок, который и правда листается вверх-вниз. Рама
     оболочки сюда не попадает: у неё overflow clip, она не листается
     ни для человека, ни из кода. */
  function листаемыйПредок(узел) {
    for (var у = узел; у && у !== документ.body; у = у.parentNode) {
      if (у.nodeType !== 1) continue;
      if (у.scrollHeight - у.clientHeight > 4) {
        var как = окно.getComputedStyle(у).overflowY;
        if (как === 'auto' || как === 'scroll') return у;
      }
    }
    return null;
  }
  CW.листаемыйПредок = листаемыйПредок;

  /* Видимая часть экрана: откуда и докуда. При выехавшей клавиатуре
     это не вся страница, и начинается она не с нуля. */
  function видимоеОкошко() {
    var вв = окно.visualViewport;
    var верх = вв ? (вв.offsetTop || 0) : 0;
    var высота = (вв && вв.height) || окно.innerHeight || 0;
    return { верх: верх, низ: верх + высота, высота: высота };
  }

  /* Дождаться, пока видимая часть перестанет меняться, и только тогда
     делать дело. Нет чем мерить - по-старому, по часам. */
  function когдаУстоится(дело) {
    var вв = окно.visualViewport;
    if (!вв) { окно.setTimeout(дело, 320); return; }
    var тихо = null, всё = null, снято = false;
    function снять() {
      if (снято) return;
      снято = true;
      окно.clearTimeout(тихо); окно.clearTimeout(всё);
      вв.removeEventListener('resize', дрогнуло);
    }
    function готово() { снять(); дело(); }
    function дрогнуло() {
      окно.clearTimeout(тихо);
      тихо = окно.setTimeout(готово, ТИШИНА);
    }
    вв.addEventListener('resize', дрогнуло);
    тихо = окно.setTimeout(готово, ТИШИНА);
    всё  = окно.setTimeout(готово, ПРЕДЕЛ);
  }

  function подвести(у) {
    var р;
    try { р = у.getBoundingClientRect(); } catch (о) { return; }
    var вид = видимоеОкошко();
    if (!вид.высота) return;

    /* Сколько не хватает, чтобы поле целиком стояло в видимом с
       зазором. Ровно столько и подвинем - ни точкой больше. */
    var вниз = (р.bottom + ЗАЗОР) - вид.низ;      /* поле под клавиатурой */
    var вверх = (вид.верх + ЗАЗОР) - р.top;       /* поле над видимым     */
    var сдвиг = вниз > 0 ? вниз : (вверх > 0 ? -вверх : 0);
    if (!сдвиг) return;                            /* видно - не трогаем  */

    /* Если поле выше видимого И не влезает целиком (длинное поле на
       пол-экрана), важнее показать его начало: туда человек печатает. */
    if (вниз > 0 && вверх > 0) сдвиг = -вверх;

    var слой = листаемыйПредок(у);
    if (слой) {
      var было = слой.scrollTop;
      var предел = слой.scrollHeight - слой.clientHeight;
      var стало = Math.max(0, Math.min(предел, было + сдвиг));
      if (стало !== было) {
        try { слой.scrollTo({ top: стало, behavior: 'smooth' }); }
        catch (о) { слой.scrollTop = стало; }
        сдвиг -= (стало - было);
      }
    }
    /* Слою не хватило (или слоя нет) - досдвигаем саму страницу, и
       только если ей есть куда: раму двигать нельзя, она и так стоит
       ровно по видимому. */
    if (Math.abs(сдвиг) > 1) {
      var корень = документ.documentElement;
      if (корень.scrollHeight - корень.clientHeight > 4) {
        try { окно.scrollBy({ top: сдвиг, behavior: 'smooth' }); }
        catch (о) { окно.scrollBy(0, сдвиг); }
      }
    }
  }

  function сКлавиатурой() {
    /* Только там, где есть клавиатура: на настольном экране подводить
       поле к видимому незачем, оно и так видно. */
    return !!(окно.matchMedia && окно.matchMedia('(pointer: coarse)').matches);
  }
  function поле(у) {
    return !!(у && у.matches
              && у.matches('input, textarea, [contenteditable="true"]'));
  }

  /* ═══════════════════════════════════════════════════════════════════
     ПОКА ПИШУТ, НИЖНЕЙ ПОЛОСЫ НЕТ

     Полоса с кнопками «Лента · Чаты · Группы · Ещё» приклеена к низу
     рамы, а рама ростом с видимое. Клавиатура выезжает - видимое
     становится ниже, и полоса едет вверх, садясь прямо на клавиатуру.
     Анна сняла это в поиске групп: «подтягивается нижний блок меню,
     нужно его скрывать всегда, когда мы открываем ячейку для ввода».

     Так и делаем: встали в любое поле - полосы нет; ушли из поля -
     вернулась. В телеграме ровно это: клавиатура просто выезжает, а
     страница остаётся, где стояла.

     Уход из поля ждём полтора десятка кадров: при переходе из поля в
     поле сначала приходит focusout, а потом focusin, и без задержки
     полоса успевала бы мигнуть.
     ═══════════════════════════════════════════════════════════════════ */
  var ПИШЕМ = 'пишем';
  var часыУхода = null;

  function пишемЛи(да) {
    документ.documentElement.classList.toggle(ПИШЕМ, !!да);
  }

  документ.addEventListener('focusin', function (е) {
    var у = е.target;
    if (!поле(у) || !сКлавиатурой()) return;
    окно.clearTimeout(часыУхода);
    пишемЛи(true);
    когдаУстоится(function () {
      if (документ.activeElement !== у) return;   /* успели уйти - не дёргаем */
      подвести(у);
    });
  });

  документ.addEventListener('focusout', function () {
    окно.clearTimeout(часыУхода);
    часыУхода = окно.setTimeout(function () {
      if (поле(документ.activeElement)) return;   /* перешли в соседнее поле */
      пишемЛи(false);
    }, 250);
  });

  /* ── КЛАВИАТУРА МЕНЯЕТСЯ И БЕЗ НОВОГО КАСАНИЯ ──
     Она выезжает позже, чем приходит focusin; растёт и съёживается на
     ходу (строка подсказок у айфона, переключение на смайлы); прячется
     и возвращается при повороте. Поле при этом остаётся выбранным, и
     focusin второй раз не придёт - а поле уже под клавиатурой.

     Поэтому слушаем и саму видимую часть. Подводка от этого не
     зацикливается: прокрутка списка видимую часть не меняет, а
     подвести() не двигает то, что и так видно. */
  if (окно.visualViewport) {
    var часыВида = null;
    окно.visualViewport.addEventListener('resize', function () {
      var у = документ.activeElement;
      if (!поле(у) || !сКлавиатурой()) return;
      окно.clearTimeout(часыВида);
      часыВида = окно.setTimeout(function () {
        if (документ.activeElement !== у) return;
        подвести(у);
      }, ТИШИНА);
    });
  }

})(window, document);
