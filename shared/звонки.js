/* ═══════════════════════════════════════════════════════════════════════
   ЗВОНКИ — сама связь. Кто кому звонит и как два браузера находят
   друг друга.

       CW.звонки.следить()                  слушать входящие (на всех страницах)
       CW.звонки.позвонить({кому, видео})   личный звонок
       CW.звонки.группой({группа, видео})   звонок группе
       CW.звонки.принять(письмо)            ответить на входящий

   ── КАК ДВА БРАУЗЕРА СОЕДИНЯЮТСЯ ────────────────────────────────────

   Напрямую. Звук и картинка идут от человека к человеку, мимо сервера:
   так быстрее и так сервер не платит за трафик разговоров. Но чтобы
   начать, им надо обменяться несколькими письмами — «вот мои адреса,
   вот что я умею». Эти письма передаёт сервер, и это называется
   сигнализацией.

   Своей ручки для звонков у сервера нет, и мы её не добавляли НАРОЧНО:
   всё, что добавлено на сервер, надо выкладывать на Render, а до тех
   пор звонки не работали бы вовсе. Вместо этого письма идут по уже
   работающей дорожке эфиров (stream_sig): сервер в них не смотрит, он
   просто передаёт письмо тому, кому оно адресовано. Поэтому звонки
   работают на том сервере, который выложен сейчас.

   ── ПОРЯДОК ПИСЕМ ───────────────────────────────────────────────────

       cw-ring     «звоню тебе»   (повторяем раз в 3 с, пока не ответят)
       cw-ok       «принял, я в окне звонка»
       cw-no       «отклонил» или «занят»
       cw-offer    предложение соединения (SDP)
       cw-answer   ответ на него
       cw-ice      найденный адрес
       cw-bye      «положил трубку»

   Звонящий ждёт cw-ok и только после него шлёт cw-offer. Почему не
   сразу: принявший в этот миг уходит на страницу звонка, его сокет
   встаёт заново, и предложение, посланное раньше, пропадает в никуда.

   ── ГРУППОВОЙ ЗВОНОК ────────────────────────────────────────────────

   Каждый соединён с каждым (это называют «сеткой»). Для четверых это
   шесть соединений, и звук идёт в обе стороны по каждому — поэтому
   больше шести человек в групповом звонке мы не зовём: дальше нужен
   сервер, который сводит потоки, а это отдельная стройка.

   Кто кому делает предложение, решает номер: меньший номер предлагает,
   больший отвечает. Иначе оба предлагают одновременно, и соединение
   ломается — это известная беда, её зовут «glare».

   ── ЧЕГО НЕТ ────────────────────────────────────────────────────────

   Нет TURN — ретранслятора для сетей, где прямой путь закрыт. В такой
   сети звонок честно скажет «соединение не установилось». Нет записи
   разговора и нет уведомления о пропущенном звонке: сервер не хранит
   событий, а выдумывать их на стороне браузера нельзя — у того, кто
   был офлайн, их всё равно не будет.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  /* ── АДРЕСА ДЛЯ СОЕДИНЕНИЯ ──
     Запасной список на случай, если сервер не ответил: два бесплатных
     STUN Гугла. Их хватает в обычных домашних сетях.

     Настоящий список спрашиваем у сервера, ручка /webrtc/ice. Там он
     собирается из переменных окружения, и как только у площадки
     появится свой ретранслятор TURN, он приедет оттуда сам - в
     программе менять будет нечего. Спрашиваем один раз на страницу и
     держим ответ: звонков за страницу бывает несколько, а список один.

     Почему не зашить TURN сюда числом: пароль от ретранслятора лежал бы
     в открытом файле программы, и пользоваться им мог бы кто угодно -
     а платит за трафик площадка. */
  var ЗАПАСНЫЕ = [
    { urls: 'stun:stun.l.google.com:19302' },
    { urls: 'stun:stun1.l.google.com:19302' }
  ];
  var ЛЕДЯНЫЕ = ЗАПАСНЫЕ;
  var естьРетранслятор = false;
  var спросили = null;

  function адресаЛьда() {
    if (спросили) return спросили;
    спросили = CW.спросить('/webrtc/ice', { тихо: true }).then(function (о) {
      var ряд = о && о.iceServers;
      if (Array.isArray(ряд) && ряд.length) {
        ЛЕДЯНЫЕ = ряд;
        естьРетранслятор = !!о['ретранслятор'];
      }
      return ЛЕДЯНЫЕ;
    }).catch(function () { return ЛЕДЯНЫЕ; });
    return спросили;
  }

  /* Есть ли у площадки ретранслятор. Окно звонка спрашивает это, чтобы
     честно сказать человеку, почему связь не встала. */
  CW.естьРетранслятор = function () { return естьРетранслятор; };

  var ЗВОНИМ_СЕКУНД = 45;     /* сколько звоним, пока не ответят */
  var ПОВТОР_МС = 3000;       /* как часто повторяем «звоню» */
  var В_ГРУППЕ_МАКС = 6;      /* больше сетка не вывозит */

  function э(тег, класс, текст) { return CW.эл(тег, класс, текст); }
  function номер() { return Math.random().toString(36).slice(2, 10); }
  function ясныйЯ() { return (CW.ясныйЯ && CW.ясныйЯ()) || {}; }

  /* ═══════════════════════════════════════════════════════════════════
     ПИСЬМА
     ═══════════════════════════════════════════════════════════════════ */
  function письмо(кому, разговор, вид, что) {
    return CW.сокет.послать({
      type: 'stream_sig',
      to: String(кому),
      sid: разговор,
      kind: вид,
      data: что || null
    });
  }

  /* ═══════════════════════════════════════════════════════════════════
     ВХОДЯЩИЙ ЗВОНОК — окно поверх любой страницы

     Оно живёт на всех страницах разделов: звонок застаёт человека в
     ленте, в кошельке, где угодно, и ждать, пока он зайдёт в чаты,
     бессмысленно.
     ═══════════════════════════════════════════════════════════════════ */
  var звонятСейчас = null;     /* {разговор, от, имя, видео, группа, когда} */
  var окноВходящего = null;
  var часыВходящего = null;

  function показатьВходящий(п) {
    var д = п.data || {};
    /* Уже говорим — второй звонок не показываем, а честно отвечаем
       «занят»: мигающее второе окно поверх разговора хуже отказа. */
    if (CW.звонки.идёт()) { письмо(п.from, п.sid, 'cw-no', { занят: true }); return; }
    if (звонятСейчас && звонятСейчас.разговор === п.sid) return;   /* повтор */

    /* Прошлое окно закрываем ПЕРЕД тем, как записать новый звонок:
       закрытьВходящий() стирает запись о звонящем, и, сделай мы это
       после, окно открылось бы без имени и упало на первом же к нему
       обращении. */
    закрытьВходящий();

    звонятСейчас = {
      разговор: п.sid, от: п.from, имя: п.from_name || ('#' + п.from),
      видео: !!д.видео, группа: д.группа || 0, название: д.название || '',
      когда: Date.now()
    };

    var О = CW.стойка({
      имя: 'входящий',
      знак: д.видео ? 'камера' : 'микрофон',
      заголовок: звонятСейчас.имя,
      подзаголовок: (д.группа ? 'звонок группе «' + (д.название || '') + '»'
                              : (д.видео ? 'видеозвонок' : 'аудиозвонок')),
      назад: отклонить,
      поля: false
    });
    окноВходящего = О;
    О.открыть();

    var м = э('div', 'вх-место');
    м.appendChild(CW.кружок({ размер: 96, род: 'человек' }));
    м.appendChild(э('div', 'вх-имя', звонятСейчас.имя));
    м.appendChild(э('div', 'вх-что', д.группа
      ? ('зовёт в разговор группы' + (д.название ? ' «' + д.название + '»' : ''))
      : (д.видео ? 'видеозвонок' : 'аудиозвонок')));
    О.тело.appendChild(м);

    var ряд = э('div', 'вх-ряд');
    var принять = э('button', 'кнопка главная', 'Ответить');
    var отбой = э('button', 'кнопка опасная', 'Отклонить');
    принять.onclick = function () { CW.звонки.принять(); };
    отбой.onclick = отклонить;
    ряд.appendChild(принять); ряд.appendChild(отбой);
    О.тело.appendChild(ряд);

    звякнуть();

    /* Не ответили за минуту — звонок сам гаснет: вечное окно поверх
       страницы человек закрывает вместе со вкладкой. */
    clearTimeout(часыВходящего);
    часыВходящего = setTimeout(закрытьВходящий, 60000);

    function отклонить() {
      if (звонятСейчас) письмо(звонятСейчас.от, звонятСейчас.разговор, 'cw-no', null);
      закрытьВходящий();
    }
  }

  function закрытьВходящий() {
    clearTimeout(часыВходящего);
    if (окноВходящего) { try { окноВходящего.закрыть(); } catch (е) {} }
    окноВходящего = null;
    звонятСейчас = null;
    замолчать();
  }

  /* ── звук звонка ──
     Коротким писком встроенным синтезатором, без файла: звуковой файл
     пришлось бы грузить, хранить и он молчал бы ровно до первого
     неудачного адреса. */
  var звукЧасы = null, звукУзел = null;
  function звякнуть() {
    замолчать();
    try {
      var Контекст = окно.AudioContext || окно.webkitAudioContext;
      if (!Контекст) return;
      звукУзел = new Контекст();
      var пик = function () {
        var о = звукУзел.createOscillator(), г = звукУзел.createGain();
        о.frequency.value = 660; о.type = 'sine';
        г.gain.value = 0.0001;
        о.connect(г); г.connect(звукУзел.destination);
        var т = звукУзел.currentTime;
        г.gain.exponentialRampToValueAtTime(0.08, т + 0.05);
        г.gain.exponentialRampToValueAtTime(0.0001, т + 0.45);
        о.start(т); о.stop(т + 0.5);
      };
      пик();
      звукЧасы = setInterval(пик, 2200);
    } catch (е) {}
  }
  function замолчать() {
    clearInterval(звукЧасы); звукЧасы = null;
    if (звукУзел) { try { звукУзел.close(); } catch (е) {} звукУзел = null; }
  }

  /* ═══════════════════════════════════════════════════════════════════
     РАЗГОВОР — то, что происходит в окне звонка
     ═══════════════════════════════════════════════════════════════════ */
  var РАЗГОВОР = null;   /* {ид, видео, группа, окно, связи:{ид→{пс,поток}}} */

  function завестиРазговор(н) {
    РАЗГОВОР = {
      ид: н.ид, видео: !!н.видео, группа: н.группа || 0,
      окно: н.окно, связи: {}, живой: true, пошло: false,
      /* Для карточки звонка в переписке: кому звоним, когда начался
         разговор и не записали ли мы его уже. */
      кому: н.кому || 0, принят: !!н.принят, началось: 0, записан: false
    };
    н.окно.наТрубку(положитьВсе);
    return РАЗГОВОР;
  }

  function связьС(ид, имя) {
    ид = String(ид);
    if (!РАЗГОВОР) return null;
    if (РАЗГОВОР.связи[ид]) return РАЗГОВОР.связи[ид];

    var пс;
    try { пс = new окно.RTCPeerConnection({ iceServers: ЛЕДЯНЫЕ }); }
    catch (е) { CW.сказать('Этот браузер не умеет звонить'); return null; }

    var с = РАЗГОВОР.связи[ид] = { пс: пс, имя: имя || '', поток: new окно.MediaStream() };

    var мой = РАЗГОВОР.окно.поток();
    if (мой) мой.getTracks().forEach(function (д) { try { пс.addTrack(д, мой); } catch (е) {} });

    пс.onicecandidate = function (е) {
      if (е.candidate) письмо(ид, РАЗГОВОР.ид, 'cw-ice', е.candidate.toJSON
        ? е.candidate.toJSON() : е.candidate);
    };

    пс.ontrack = function (е) {
      /* Дорожки приходят по одной: сперва звук, потом картинка. Кладём
         их в один поток, иначе картинка заменяет звук и разговор
         становится немым. */
      (е.streams && е.streams[0] ? е.streams[0].getTracks() : [е.track])
        .forEach(function (д) {
          try { if (с.поток.getTrackById(д.id)) return; } catch (_) {}
          с.поток.addTrack(д);
        });
      РАЗГОВОР.окно.чужой(ид, с.поток, с.имя);
      if (!РАЗГОВОР.пошло) {
        РАЗГОВОР.пошло = true;
        РАЗГОВОР.началось = Date.now();
        РАЗГОВОР.окно.пошёл();
      }
    };

    пс.onconnectionstatechange = function () {
      var с2 = пс.connectionState;
      if (с2 === 'failed') {
        /* Прямого пути не нашлось. Это и есть тот случай, для которого
           нужен TURN, и врать про «плохой интернет» здесь нельзя.

           Говорим по-разному, смотря есть ли у площадки ретранслятор.
           Нет - честно называем причину. Есть, а связь всё равно не
           встала, - причина другая, и валить её на ретранслятор было бы
           враньём в обратную сторону. */
        РАЗГОВОР.окно.состояние(естьРетранслятор
          ? 'Соединение не установилось. Попробуй ещё раз или по другой сети.'
          : ('Соединение не установилось: сеть не даёт прямого пути. '
             + 'Нужен сервер-ретранслятор, его у нас пока нет.'));
        убратьСвязь(ид);
      } else if (с2 === 'disconnected' || с2 === 'closed') {
        убратьСвязь(ид);
      }
    };

    return с;
  }

  function убратьСвязь(ид) {
    ид = String(ид);
    if (!РАЗГОВОР) return;
    var с = РАЗГОВОР.связи[ид];
    if (!с) return;
    try { с.пс.close(); } catch (е) {}
    delete РАЗГОВОР.связи[ид];
    var осталось = РАЗГОВОР.окно.убрать(ид);
    /* В личном звонке уход второго — конец разговора. В групповом —
       нет: остальные продолжают говорить. */
    if (!РАЗГОВОР.группа || осталось === 0) {
      if (РАЗГОВОР.живой && РАЗГОВОР.пошло) {
        CW.сказать('Разговор окончен');
        РАЗГОВОР.живой = false;
        setTimeout(function () { try { РАЗГОВОР.окно.положить(); } catch (е) {} }, 600);
      }
    }
  }

  /* ── КАРТОЧКА ЗВОНКА В ПЕРЕПИСКЕ ──
     Звонок — такое же событие переписки, как сообщение: он должен
     остаться в ней строкой. Пишет её ТОТ, КТО ЗВОНИЛ, и только один
     раз: тогда карточка одна, и её видят оба.

     Сервер ничего нового для этого не учит: это обычное сообщение с
     видом «call», а что внутри — разбирает пузырь.

     ── В ГРУППЕ ТОЖЕ ──
     Прежде карточка была только в личке: «у группы переписка общая, и
     „кому“ в ней не один человек». Но человеку и не нужно знать, кому
     именно звонили: ему нужно знать, что разговор БЫЛ, и не пропустить
     его молча. Анна спросила прямо, что делать с пропущенными - вот
     это и делаем: в переписке группы остаётся та же карточка, и тот,
     кого в тот час не было, увидит её, когда откроет группу.

     Пишет её по-прежнему тот, кто звонил, и один раз: так карточка
     одна на всех, а не по штуке от каждого участника. */
  function записатьЗвонок(исход) {
    if (!РАЗГОВОР || РАЗГОВОР.записан) return;
    if (РАЗГОВОР.принят) return;                      /* пишет звонящий */
    if (!РАЗГОВОР.группа && !РАЗГОВОР.кому) return;
    РАЗГОВОР.записан = true;
    var секунды = РАЗГОВОР.началось
      ? Math.max(1, Math.round((Date.now() - РАЗГОВОР.началось) / 1000)) : 0;
    var тело = 'call:' + (РАЗГОВОР.видео ? 'видео' : 'аудио')
             + ':' + исход + ':' + секунды;
    var куда = РАЗГОВОР.группа
      ? ('/groups/' + РАЗГОВОР.группа + '/messages')
      : ('/dm/' + РАЗГОВОР.кому);
    CW.спросить(куда, {
      способ: 'POST', тихо: true,
      тело: { content: тело, msg_type: 'call' }
    });
  }

  function положитьВсе() {
    if (!РАЗГОВОР) return;
    записатьЗвонок(РАЗГОВОР.пошло ? 'состоялся' : 'отменён');
    РАЗГОВОР.живой = false;
    Object.keys(РАЗГОВОР.связи).forEach(function (ид) {
      письмо(ид, РАЗГОВОР.ид, 'cw-bye', null);
      try { РАЗГОВОР.связи[ид].пс.close(); } catch (е) {}
    });
    /* Тем, кто ещё не ответил, тоже говорим «отбой»: иначе у них
       продолжает звонить окно, которого уже некому принять. */
    (РАЗГОВОР.зовём || []).forEach(function (ид) {
      письмо(ид, РАЗГОВОР.ид, 'cw-bye', null);
    });
    clearInterval(РАЗГОВОР.звоним);
    РАЗГОВОР = null;
  }

  function предложить(ид, имя) {
    var с = связьС(ид, имя);
    if (!с) return;
    с.пс.createOffer().then(function (о) {
      return с.пс.setLocalDescription(о).then(function () {
        письмо(ид, РАЗГОВОР.ид, 'cw-offer', { sdp: с.пс.localDescription.sdp,
                                              type: с.пс.localDescription.type });
      });
    }).catch(function () {});
  }

  /* ═══════════════════════════════════════════════════════════════════
     ЧТО ПРИШЛО
     ═══════════════════════════════════════════════════════════════════ */
  function пришло(п) {
    if (!п || п.type !== 'stream_sig') return;
    var вид = String(п.kind || '');
    if (вид.indexOf('cw-') !== 0) return;      /* не наше — это эфиры */

    var от = String(п.from);
    var д = п.data || {};

    if (вид === 'cw-ring') { показатьВходящий(п); return; }

    /* Дальше всё — про текущий разговор. Чужой разговор (например,
       запоздавшее письмо от прошлого звонка) молча выбрасываем. */
    if (вид === 'cw-no') {
      if (РАЗГОВОР && РАЗГОВОР.ид === п.sid) {
        РАЗГОВОР.зовём = (РАЗГОВОР.зовём || []).filter(function (х) { return х !== от; });
        if (!РАЗГОВОР.группа) {
          записатьЗвонок(д && д.занят ? 'занято' : 'пропущен');
          РАЗГОВОР.окно.состояние(д && д.занят ? 'Занят другим разговором'
                                               : 'Отклонил звонок');
          clearInterval(РАЗГОВОР.звоним);
          setTimeout(function () { try { РАЗГОВОР.окно.положить(); } catch (е) {} }, 1800);
        }
      }
      return;
    }

    if (вид === 'cw-bye') {
      if (звонятСейчас && звонятСейчас.разговор === п.sid) { закрытьВходящий(); return; }
      if (РАЗГОВОР && РАЗГОВОР.ид === п.sid) убратьСвязь(от);
      return;
    }

    if (!РАЗГОВОР || РАЗГОВОР.ид !== п.sid) return;

    if (вид === 'cw-ok') {
      /* Он в окне звонка и готов. Предложение делает тот, у кого номер
         меньше, — иначе предложат оба сразу и соединение сломается. */
      clearInterval(РАЗГОВОР.звоним);
      РАЗГОВОР.окно.состояние('соединяю…');
      var я = Number(ясныйЯ().id || 0);
      if (!РАЗГОВОР.группа || я < Number(от)) предложить(от, п.from_name);
      else письмо(от, РАЗГОВОР.ид, 'cw-ok', null);   /* пусть предложит он */
      return;
    }

    if (вид === 'cw-offer') {
      var с = связьС(от, п.from_name);
      if (!с) return;
      с.пс.setRemoteDescription(new окно.RTCSessionDescription(д))
        .then(function () { return с.пс.createAnswer(); })
        .then(function (о) { return с.пс.setLocalDescription(о); })
        .then(function () {
          письмо(от, РАЗГОВОР.ид, 'cw-answer', { sdp: с.пс.localDescription.sdp,
                                                 type: с.пс.localDescription.type });
          РАЗГОВОР.окно.состояние('соединяю…');
        }).catch(function () {});
      return;
    }

    if (вид === 'cw-answer') {
      var с2 = РАЗГОВОР.связи[от];
      if (!с2) return;
      с2.пс.setRemoteDescription(new окно.RTCSessionDescription(д)).catch(function () {});
      return;
    }

    if (вид === 'cw-ice') {
      var с3 = РАЗГОВОР.связи[от];
      if (!с3 || !д) return;
      try { с3.пс.addIceCandidate(new окно.RTCIceCandidate(д)); } catch (е) {}
      return;
    }
  }

  /* ═══════════════════════════════════════════════════════════════════
     НАРУЖУ
     ═══════════════════════════════════════════════════════════════════ */
  var слежу = false;

  CW.звонки = {
    идёт: function () { return !!РАЗГОВОР; },
    звонят: function () { return звонятСейчас; },

    /* Слушать входящие. Зовётся с каждой страницы разделов. */
    следить: function () {
      if (слежу) return;
      слежу = true;
      CW.сокет.завести();
      CW.сокет.слушать('stream_sig', пришло);
      /* Спрашиваем адреса заранее, на всякий входящий: когда человек
         нажмёт «Ответить», ждать ответа сервера будет уже не нужно. */
      адресаЛьда();
    },

    /* ── ЗВОНИТЬ ──
       Окно звонка уже открыто (его открыла страница windows/call.html),
       сюда приходит оно и кому звоним. */
    вести: function (н) {
      var О = н.окно;
      var разговор = н.разговор || номер();
      var кому = (н.кому || []).map(String).filter(function (и) {
        return и && Number(и) !== Number(ясныйЯ().id);
      }).slice(0, В_ГРУППЕ_МАКС - 1);

      CW.звонки.следить();
      var Р = завестиРазговор({ ид: разговор, видео: н.видео, группа: н.группа,
                                окно: О, принят: !!н.принят,
                                /* Для карточки в переписке: в личном звонке
                                   собеседник один, его номер и запоминаем. */
                                кому: (!н.группа && кому.length === 1) ? кому[0] : 0 });
      Р.зовём = кому.slice();

      /* Ждём не только свой микрофон, но и адреса для соединения: без
         них первая же связь встала бы на одних запасных STUN, а
         ретранслятор, если он у площадки есть, остался бы без дела.
         Ответ сервера приходит за доли секунды и спрашивается один раз
         на страницу. */
      Promise.all([О.готов, адресаЛьда()]).then(function () {
        if (н.принят) {
          /* Нас позвали — говорим «я готов» тому, кто звонил (а в
             группе — всем, кто может быть в разговоре). */
          О.состояние('соединяю…');
          кому.forEach(function (ид) { письмо(ид, разговор, 'cw-ok', null); });
          return;
        }

        О.состояние('звоню…');
        CW.сокет.дождаться(6000).then(function (есть) {
          if (!есть) {
            О.состояние('Нет связи с сервером: звонок не уйдёт');
            return;
          }
          звонить();
          Р.звоним = setInterval(звонить, ПОВТОР_МС);
          setTimeout(function () {
            if (!Р.пошло && РАЗГОВОР === Р) {
              clearInterval(Р.звоним);
              О.состояние('Не ответили');
              setTimeout(function () { try { О.положить(); } catch (е) {} }, 1800);
            }
          }, ЗВОНИМ_СЕКУНД * 1000);
        });

        function звонить() {
          кому.forEach(function (ид) {
            письмо(ид, разговор, 'cw-ring', {
              видео: !!н.видео, группа: н.группа || 0,
              название: н.название || ''
            });
          });
        }
      }).catch(function () { /* микрофон не дали — окно уже сказало */ });

      return Р;
    },

    /* Ответить на входящий: уходим в окно звонка и там говорим «готов». */
    принять: function () {
      if (!звонятСейчас) return;
      var з = звонятСейчас;
      замолчать();
      закрытьВходящий();
      var адрес = CW.окно(з.видео ? 'call-video' : 'call')
        + '?' + (з.группа ? ('группа=' + з.группа) : ('кто=' + з.от))
        + '&разговор=' + encodeURIComponent(з.разговор)
        + '&принят=1&от=' + з.от;
      CW.уйти(адрес);
    }
  };

})(window, document);
