/* ═══════════════════════════════════════════════════════════════════════
   ЗАПИСЬ ГОЛОСА — одна на всю программу.

   Нажал — пишем, нажал ещё раз — отдали файл. Больше здесь ничего нет:
   куда этот файл потом уедет, решает тот, кто записывал. В чатах и
   группах он уходит вложением, в избранном ложится заметкой.

       CW.записьГолоса.идёт()            пишем прямо сейчас?
       CW.записьГолоса.нажали(готово)    нажали кнопку микрофона

   «нажали» делает ровно то, что человек ждёт от одной кнопки:

       записи нет  — просит микрофон и начинает писать;
       запись идёт — останавливает и зовёт готово({файл, секунд}).

   Отказ, пустая запись, браузер без MediaRecorder - всё это тоже
   приходит в «готово», но с ошибкой: готово({беда:'…'}). Молча терять
   записанное нельзя, человек уже сказал своё слово в микрофон.

   ── ПОЧЕМУ ЭТО ОТДЕЛЬНЫМ ФАЙЛОМ ────────────────────────────────────
   Записей голоса в программе было ДВЕ, и они разошлись, как и должны
   были разойтись две копии одного дела.

   В чатах (shared/chat.js) формат спрашивали у браузера, и файл
   получался правильный. В избранном (windows/favorites.html) писали
   через «new MediaRecorder(поток)» без формата и всегда называли файл
   «.webm» - а Сафари на айфоне пишет mp4. Имя не сходилось с
   содержимым, и такая запись не игралась вовсе.

   Теперь дело одно и лежит в одном месте. Кому нужна запись - зовёт
   отсюда.

   ── ПОЧЕМУ ФОРМАТ СПРАШИВАЕМ ───────────────────────────────────────
   MediaRecorder с незнакомым типом НЕ ошибается: он молча пишет пустой
   файл. Поэтому перебираем четыре типа и берём первый, про который
   браузер сказал «умею». Имя файла даём по тому типу, который вышел, а
   не по тому, который хотели.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  /* Порядок не случаен: opus в webm - самый лёгкий и его понимают все,
     кроме Сафари; mp4 - это как раз Сафари; ogg - старый Файрфокс. */
  var ФОРМАТЫ = [
    { тип: 'audio/webm;codecs=opus', хвост: 'webm' },
    { тип: 'audio/webm',             хвост: 'webm' },
    { тип: 'audio/mp4',              хвост: 'm4a'  },
    { тип: 'audio/ogg;codecs=opus',  хвост: 'ogg'  },
    { тип: 'audio/ogg',              хвост: 'ogg'  }
  ];

  var писарь = null;          /* тот, кто пишет прямо сейчас */

  function хвостПоТипу(тип) {
    тип = String(тип || '');
    if (/mp4|m4a|aac/.test(тип)) return 'm4a';
    if (/ogg/.test(тип)) return 'ogg';
    return 'webm';
  }

  function выбратьТип() {
    if (!окно.MediaRecorder || !окно.MediaRecorder.isTypeSupported) return '';
    for (var i = 0; i < ФОРМАТЫ.length; i++) {
      if (окно.MediaRecorder.isTypeSupported(ФОРМАТЫ[i].тип)) return ФОРМАТЫ[i].тип;
    }
    return '';
  }

  CW.записьГолоса = {
    идёт: function () { return !!писарь; },

    /* Остановить, ничего не отдавая: нужно при уходе со страницы. */
    бросить: function () {
      if (!писарь) return;
      var п = писарь;
      писарь = null;
      try { п.отменено = true; п.stop(); } catch (е) {}
    },

    нажали: function (готово) {
      готово = готово || function () {};

      /* Пишем - значит, нажатие это «хватит». Сам файл придёт в
         обработчике остановки ниже. */
      if (писарь) {
        try { писарь.stop(); } catch (е) { писарь = null; готово({ беда: 'Запись оборвалась' }); }
        return;
      }

      if (!окно.navigator || !окно.navigator.mediaDevices
          || typeof окно.MediaRecorder !== 'function') {
        готово({ беда: 'Этот браузер не умеет записывать голос' });
        return;
      }

      окно.navigator.mediaDevices.getUserMedia({ audio: true }).then(function (поток) {
        var тип = выбратьТип();
        var п;
        try {
          п = тип ? new окно.MediaRecorder(поток, { mimeType: тип })
                  : new окно.MediaRecorder(поток);
        } catch (е) {
          поток.getTracks().forEach(function (д) { д.stop(); });
          готово({ беда: 'Запись не завелась' });
          return;
        }

        var куски = [];
        var пошло = Date.now();
        п.ondataavailable = function (е) { if (е.data && е.data.size) куски.push(е.data); };
        п.onstop = function () {
          поток.getTracks().forEach(function (д) { д.stop(); });
          var отменено = п.отменено;
          писарь = null;
          if (отменено) return;

          var вышло = п.mimeType || тип || 'audio/webm';
          var капля = new Blob(куски, { type: вышло });
          if (!капля.size) {
            готово({ беда: 'Записи не вышло: браузер отдал пустой файл' });
            return;
          }
          /* Секунда минимум: запись в полсекунды человек всё равно
             считает секундой, а ноль под полоской выглядит поломкой. */
          var секунд = Math.max(1, Math.round((Date.now() - пошло) / 1000));
          var имя = 'голос.' + хвостПоТипу(вышло);
          готово({
            файл: new окно.File([капля], имя, { type: капля.type }),
            секунд: секунд,
            тип: вышло
          });
        };

        try { п.start(); } catch (е) {
          поток.getTracks().forEach(function (д) { д.stop(); });
          готово({ беда: 'Запись не завелась' });
          return;
        }
        писарь = п;
        CW.сказать(Т('Пишу… нажми микрофон ещё раз, чтобы отправить'), 60000);
      }).catch(function () {
        готово({ беда: 'Микрофон не дали' });
      });
    }
  };

  /* Уходим со страницы с открытым микрофоном - отпускаем его. Иначе у
     человека остаётся гореть красная точка записи на вкладке, которой
     уже нет. */
  окно.addEventListener('pagehide', function () { CW.записьГолоса.бросить(); });

})(window);
