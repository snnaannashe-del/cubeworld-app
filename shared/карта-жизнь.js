  function подвязать(){
    if(!window.cwVoiceWords || !window.cwVoiceActions) return false;
    Object.keys(ГОЛОС).forEach(function(к){
      ['ru','en'].forEach(function(я){
        if(window.cwVoiceWords[я] && !window.cwVoiceWords[я][к])
          window.cwVoiceWords[я][к] = ГОЛОС[к].с;
      });
      if(!window.cwVoiceActions[к]) window.cwVoiceActions[к] = ГОЛОС[к].к;
    });
    return true;
  }
