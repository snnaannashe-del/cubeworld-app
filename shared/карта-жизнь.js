  /* ── 5. ГЕОМЕТРИЯ ПУТИ ─────────────────────────────────────────── */
  function поБольшомуКругу(ш1, д1, ш2, д2, t){
    var φ1 = ш1 * РАД, λ1 = д1 * РАД, φ2 = ш2 * РАД, λ2 = д2 * РАД;
    var d = 2 * Math.asin(Math.sqrt(Math.pow(Math.sin((φ2 - φ1) / 2), 2) +
            Math.cos(φ1) * Math.cos(φ2) * Math.pow(Math.sin((λ2 - λ1) / 2), 2)));
    if(!d) return [ш1, д1];
    var A = Math.sin((1 - t) * d) / Math.sin(d), B = Math.sin(t * d) / Math.sin(d);
    var x = A * Math.cos(φ1) * Math.cos(λ1) + B * Math.cos(φ2) * Math.cos(λ2);
    var y = A * Math.cos(φ1) * Math.sin(λ1) + B * Math.cos(φ2) * Math.sin(λ2);
    var z = A * Math.sin(φ1) + B * Math.sin(φ2);
    return [Math.atan2(z, Math.sqrt(x * x + y * y)) / РАД, Math.atan2(y, x) / РАД];
  }
  function вёрсты(ш1, д1, ш2, д2){
    var R = 6371, φ1 = ш1 * РАД, φ2 = ш2 * РАД;
    var dφ = (ш2 - ш1) * РАД, dλ = (д2 - д1) * РАД;
    var a = Math.sin(dφ / 2) * Math.sin(dφ / 2) +
            Math.cos(φ1) * Math.cos(φ2) * Math.sin(dλ / 2) * Math.sin(dλ / 2);
    return 2 * R * Math.asin(Math.min(1, Math.sqrt(a)));
  }
