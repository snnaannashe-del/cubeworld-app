  /* Путь по клеткам: A* с настоящим расстоянием между клетками. */
  function путьПоКлеткам(ш1, д1, ш2, д2, поСуше){
    var м = маска(); if(!м) return null;
    function клетка(ш, д){
      return [Math.max(0, Math.min(МВ - 1, Math.floor((90 - ш) / 180 * МВ))),
              ((Math.floor((д + 180) / 360 * МШ) % МШ) + МШ) % МШ];
    }
    function годится(y, x){ return поСуше ? м[y * МШ + x] : !м[y * МШ + x]; }
    function вКоорд(y, x){ return [90 - (y + 0.5) / МВ * 180, (x + 0.5) / МШ * 360 - 180]; }

    var старт = клетка(ш1, д1), финиш = клетка(ш2, д2);
    /* Если конец не на той стихии — ищем ближайшую подходящую клетку. */
    function ближайшая(к){
      if(годится(к[0], к[1])) return к;
      for(var r = 1; r < 14; r++){
        for(var dy = -r; dy <= r; dy++) for(var dx = -r; dx <= r; dx++){
          var y = к[0] + dy, x = ((к[1] + dx) % МШ + МШ) % МШ;
          if(y < 0 || y >= МВ) continue;
          if(годится(y, x)) return [y, x];
        }
      }
      return null;
    }
    старт = ближайшая(старт); финиш = ближайшая(финиш);
    if(!старт || !финиш) return null;

    var N = МШ * МВ;
    function ном(y, x){ return y * МШ + x; }
    var цель = ном(финиш[0], финиш[1]);
    var откуда_ = ном(старт[0], старт[1]);

    /* Сначала простой вопрос: вообще можно ли туда попасть, не меняя
       стихии? Разлив по соседям отвечает на него мгновенно, и тогда не
       приходится ждать, пока поиск обойдёт полмира впустую. */
    var достижимо = new Uint8Array(N);
    var полка = [откуда_]; достижимо[откуда_] = 1;
    var дошли = (откуда_ === цель);
    while(полка.length && !дошли){
      var т0 = полка.pop();
      var ty = Math.floor(т0 / МШ), tx = т0 % МШ;
      for(var sy = -1; sy <= 1; sy++) for(var sx = -1; sx <= 1; sx++){
        if(!sx && !sy) continue;
        var ny = ty + sy, nx = ((tx + sx) % МШ + МШ) % МШ;
        if(ny < 0 || ny >= МВ) continue;
        var нн = ном(ny, nx);
        if(достижимо[нн] || !годится(ny, nx)) continue;
        достижимо[нн] = 1;
        if(нн === цель){ дошли = true; break; }
        полка.push(нн);
      }
    }
    if(!дошли) return null;

    /* Теперь сам путь. Очередь — двоичная куча: без неё поиск на сетке в
       шестьдесят тысяч клеток пересортировывал список на каждом шаге и
       думал по двадцать секунд. */
    var было = new Float32Array(N); было.fill(Infinity);
    var откуда = new Int32Array(N); откуда.fill(-1);
    /* Куча на обычных массивах, а не на типизированных. Одна и та же
       клетка попадает в очередь несколько раз — каждый раз, когда к ней
       нашёлся путь дешевле. Поэтому записей бывает больше, чем клеток, а
       типизированный массив молча выбрасывает всё, что не влезло: куча
       ломается, и поиск возвращает «пути нет» там, где путь есть. */
    var кучаЦ = [], кучаН = [], кучаРазмер = 0;
    function положить(ц, н){
      var i = кучаРазмер++;
      кучаЦ[i] = ц; кучаН[i] = н;
      while(i > 0){
        var р = (i - 1) >> 1;
        if(кучаЦ[р] <= кучаЦ[i]) break;
        var ц0 = кучаЦ[р], н0 = кучаН[р];
        кучаЦ[р] = кучаЦ[i]; кучаН[р] = кучаН[i];
        кучаЦ[i] = ц0; кучаН[i] = н0;
        i = р;
      }
    }
    function взять(){
      var верх = кучаН[0];
      кучаРазмер--;
      if(кучаРазмер > 0){
        кучаЦ[0] = кучаЦ[кучаРазмер]; кучаН[0] = кучаН[кучаРазмер];
        var i = 0;
        for(;;){
          var л = 2 * i + 1, п = л + 1, м = i;
          if(л < кучаРазмер && кучаЦ[л] < кучаЦ[м]) м = л;
          if(п < кучаРазмер && кучаЦ[п] < кучаЦ[м]) м = п;
          if(м === i) break;
          var ц1 = кучаЦ[м], н1 = кучаН[м];
          кучаЦ[м] = кучаЦ[i]; кучаН[м] = кучаН[i];
          кучаЦ[i] = ц1; кучаН[i] = н1;
          i = м;
        }
      }
      return верх;
    }
    function оценка(y, x){
      var т = вКоорд(y, x), ф = вКоорд(финиш[0], финиш[1]);
      return вёрсты(т[0], т[1], ф[0], ф[1]);
    }
    было[откуда_] = 0;
    положить(оценка(старт[0], старт[1]), откуда_);
    var нашли = false, шагов = 0;
    /* Одна и та же клетка лежит в очереди по нескольку раз. Без отметки
       «уже разобрана» поиск разбирает её снова и снова: на пути почти
       через весь мир — Лиссабон и Сидней стоят почти напротив друг друга —
       это сотни тысяч лишних шагов, и поиск упирался в предел, объявляя
       «пути нет» там, где путь есть. */
    var закрыто = new Uint8Array(N);
    while(кучаРазмер && шагов++ < 400000){
      var текущий = взять();
      if(закрыто[текущий]) continue;
      закрыто[текущий] = 1;
      if(текущий === цель){ нашли = true; break; }
      var y0 = Math.floor(текущий / МШ), x0 = текущий % МШ;
      var а = вКоорд(y0, x0);
      for(var dy = -1; dy <= 1; dy++) for(var dx = -1; dx <= 1; dx++){
        if(!dx && !dy) continue;
        var y = y0 + dy, x = ((x0 + dx) % МШ + МШ) % МШ;
        if(y < 0 || y >= МВ || !годится(y, x)) continue;
        var б = вКоорд(y, x);
        var цена = было[текущий] + вёрсты(а[0], а[1], б[0], б[1]);
        var н = ном(y, x);
        if(цена < было[н]){
          было[н] = цена; откуда[н] = текущий;
          положить(цена + оценка(y, x), н);
        }
      }
    }
    if(!нашли) return null;
    var путь = [], у = цель;
    while(у >= 0){ путь.push(вКоорд(Math.floor(у / МШ), у % МШ)); у = откуда[у]; }
    путь.reverse();
    путь[0] = [ш1, д1]; путь[путь.length - 1] = [ш2, д2];
    return путь;
  }

