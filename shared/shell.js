/* ═══════════════════════════════════════════════════════════════════════
   ОБОЛОЧКА КУБА.

   Рама по центру, верхняя полоса, строка кубов и левое меню — один раз
   на всю программу. Экран меню выглядит так:

       <link rel="stylesheet" href="shared/shell.css">     (из окна — ../shared/)
       ...
       CW.оболочка('refs').then(function (место) {
         // место — пустой блок, в который экран кладёт своё содержимое
       });

   Оболочка сама:
     узнаёт, в каком мы кубе (?id= в адресе или последний открытый);
     спрашивает /me и кубы один раз и помнит ответ в памяти вкладки,
       чтобы при переходе между разделами полоса не моргала;
     подсвечивает текущий пункт;
     на телефоне убирает меню в полку, которая выезжает снизу.

   Значки нарисованы линиями, а не набраны смайлами. Смайл рисует
   система: на маке он цветной и объёмный, на телефоне другой, в Windows
   третий — одно меню выглядело бы тремя разными. Линия везде одна.
   ═══════════════════════════════════════════════════════════════════════ */
