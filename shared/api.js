/* ═══════════════════════════════════════════════════════════════════════
   СВЯЗЬ С СЕРВЕРОМ — одна на всю программу.

   Это единственное место, которое ходит на сервер. Ни один экран не
   делает fetch сам. Почему так: в прежней программе apiCall имел шесть
   хозяев — шесть блоков по очереди оборачивали его своим слоем, и когда
   запрос вёл себя не так, найти виноватого было нечем.

   Здесь один файл, одна функция, один владелец.

   Пользоваться так:
       const я = await CW.спросить('/me');
       await CW.спросить('/dm/send', {способ:'POST', тело:{to:7, text:'…'}});

   Что делает сама:
     · подставляет адрес сервера — боевой или местный;
     · прикладывает ключ входа и номер устройства;
     · если сервер ответил «ключ протух» — один раз обновляет ключ
       и повторяет запрос;
     · на обрыв сети даёт понятную ошибку, а не «undefined».
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно) {
  'use strict';

  var CW = окно.CW = окно.CW || {};

  /* ── адрес сервера ─────────────────────────────────────────────────
     По умолчанию — боевой сервер. Это важно: страницу часто открывают
     просто с диска или с местного сервера страниц, и раньше в этом
     случае программа молча стучалась на localhost:8000, где ничего нет,
     и мир оставался пустым без единого слова почему.

     Свой сервер подключается явно и один раз:
         world.html?сервер=рядом          — на localhost:8000
         world.html?сервер=http://…:9000  — на любой другой
         world.html?сервер=боевой         — вернуться на боевой
     Выбор запоминается, в адресе его держать не нужно. */
  /* ── СБОРКА ────────────────────────────────────────────────────────
     Число, которое меняется при каждой выкладке. Оно приписывается к
     адресам наших же файлов: shared/…js?v=…, modals/…js?v=…

     Зачем. Браузер честно кэширует .js, и это правильно: иначе каждая
     страница каждый раз тянет полмегабайта заново. Но пока файл
     правится по десять раз на дню, кэш означает ровно одно — человек
     открывает страницу и видит вчерашнее окно, не понимая почему.
     Файл на диске новый, на экране старый, и искать нечего.

     С этим числом в адресе браузер считает файл другим и берёт свежий.
     Меняется оно только при выкладке, так что на боевом кэш работает
     как положено.

     На localhost число берём живое: там правки идут поминутно, и ждать
     выкладки, чтобы увидеть свою же правку, незачем. */
  CW.сборка = '20261123-428';

  CW.версия = (function () {
    var х = окно.location.hostname || '';
    var дома = (х === 'localhost' || х === '127.0.0.1' || х === '[::1]'
                || /^192\.168\.|^10\.|^172\.(1[6-9]|2\d|3[01])\./.test(х));
    return дома ? ('dev' + Date.now()) : CW.сборка;
  })();

  /* К своему адресу приписать «?v=…», чужой не трогать. */
  CW.свежий = function (путь) {
    var а = String(путь || '');
    if (!а || /^(https?:|data:|blob:|\/\/)/i.test(а)) return а;
    return а + (а.indexOf('?') >= 0 ? '&' : '?') + 'v=' + CW.версия;
  };

  var БОЕВОЙ = 'https://cubeworld-backend-1.onrender.com';

  CW.адрес = (function () {
    var запас;
    try { запас = окно.localStorage.getItem('cw_сервер'); } catch (е) { запас = null; }

    var спрошено = null;
    try {
      спрошено = new окно.URLSearchParams(окно.location.search).get('сервер');
    } catch (е) {}

    if (спрошено) {
      if (спрошено === 'боевой') запас = null;
      else if (спрошено === 'рядом') запас = (окно.location.protocol === 'https:' ? 'https:' : 'http:')
                                           + '//' + (окно.location.hostname || '127.0.0.1') + ':8000';
      else запас = спрошено;

      try {
        if (запас) окно.localStorage.setItem('cw_сервер', запас);
        else окно.localStorage.removeItem('cw_сервер');
      } catch (е) {}
    }

    return запас || БОЕВОЙ;
  })();

  /* ── память браузера ───────────────────────────────────────────────
     Имена ключей те же, что у нынешней программы: новая страница и
     старая видят один и тот же вход. */
  var КЛЮЧИ = {
    вход:      'cw_access_token',
    обновить:  'cw_refresh_token',
    ключ:      'cw_key',
    вид:       'cw_key_type',
    устройство:'cw_device_id'
  };
  CW.КЛЮЧИ = КЛЮЧИ;

  function взять(имя) {
    try { return окно.localStorage.getItem(имя); } catch (_) { return null; }
  }
  function положить(имя, что) {
    try { окно.localStorage.setItem(имя, что); } catch (_) {}
  }
  function убрать(имя) {
    try { окно.localStorage.removeItem(имя); } catch (_) {}
  }
  CW.взять = взять; CW.положить = положить; CW.убрать = убрать;

  /* Номер устройства нужен серверу, чтобы отличать входы.
     Заводим один раз и больше не трогаем. */
  CW.устройство = (function () {
    var у = взять(КЛЮЧИ.устройство);
    if (у) return у;
    var б = new Uint8Array(16);
    (окно.crypto || окно.msCrypto).getRandomValues(б);
    у = Array.prototype.map.call(б, function (з) {
      return ('0' + з.toString(16)).slice(-2);
    }).join('');
    положить(КЛЮЧИ.устройство, у);
    return у;
  })();

  CW.токен = function () { return взять(КЛЮЧИ.вход); };
  CW.вошли = function () { return !!взять(КЛЮЧИ.вход); };

  /* Любой ответ сервера — в одну понятную строку. */
  function внятно(что) {
    if (!что) return '';
    if (typeof что === 'string') return что;
    if (Array.isArray(что)) {
      return что.map(function (э) {
        if (!э) return '';
        if (typeof э === 'string') return э;
        var где = Array.isArray(э.loc) ? э.loc[э.loc.length - 1] : '';
        return (где ? где + ': ' : '') + (э.msg || э.message || '');
      }).filter(Boolean).join('; ');
    }
    if (typeof что === 'object') return что.msg || что.message || что.detail || '';
    return String(что);
  }

  /* ── ошибка с понятным текстом ─────────────────────────────────────
     Экрану нужно знать три вещи: что случилось, можно ли повторить и
     что показать человеку. Всё в одном предмете. */
  function Беда(код, текст, тело) {
    var о = new Error(текст || 'Не вышло');
    о.код = код;          /* 0 — сети нет, иначе ответ сервера */
    о.тело = тело || null;
    о.сеть = код === 0;
    return о;
  }
  CW.Беда = Беда;

  /* ── обновление ключа входа ────────────────────────────────────────
     Делаем ровно один раз за промежуток: если два экрана одновременно
     получили «ключ протух», оба дождутся одного обновления, а не
     устроят два. */
  var обновление = null;
  function обновитьКлюч() {
    if (обновление) return обновление;
    var освежить = взять(КЛЮЧИ.обновить);
    if (!освежить) return Promise.resolve(false);

    обновление = fetch(CW.адрес + '/auth/refresh', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ refresh_token: освежить })
    }).then(function (о) {
      return о.ok ? о.json() : null;
    }).then(function (д) {
      if (д && д.access_token) {
        положить(КЛЮЧИ.вход, д.access_token);
        if (д.refresh_token) положить(КЛЮЧИ.обновить, д.refresh_token);
        return true;
      }
      return false;
    }).catch(function () {
      return false;
    }).then(function (вышло) {
      обновление = null;
      return вышло;
    });

    return обновление;
  }
  CW.обновитьКлюч = обновитьКлюч;

  /* ── главный вопрос серверу ────────────────────────────────────────
     путь      — '/me', '/groups', '/dm/send'
     настройки — {способ, тело, сроком, тихо, заголовки}
         способ   — 'GET' по умолчанию
         тело     — предмет, уедет как JSON; FormData уедет как есть
         сроком   — сколько ждать, мс (по умолчанию 20000)
         тихо     — true: вернуть null вместо ошибки
     Возвращает разобранный ответ. Пустой ответ (204) — null. */
  CW.спросить = function (путь, настройки) {
    настройки = настройки || {};
    var способ = (настройки.способ || 'GET').toUpperCase();
    var срок = настройки.сроком || 20000;
    var повтор = настройки.__повтор || false;

    var заголовки = { 'X-Device-Id': CW.устройство };
    var токен = CW.токен();
    if (токен) заголовки['Authorization'] = 'Bearer ' + токен;
    if (настройки.заголовки) {
      for (var к in настройки.заголовки) заголовки[к] = настройки.заголовки[к];
    }

    var тело;
    if (настройки.тело !== undefined && настройки.тело !== null) {
      if (окно.FormData && настройки.тело instanceof окно.FormData) {
        тело = настройки.тело;                 /* границу ставит браузер */
      } else {
        заголовки['Content-Type'] = 'application/json';
        тело = JSON.stringify(настройки.тело);
      }
    }

    var стоп = окно.AbortController ? new окно.AbortController() : null;
    var часы = стоп ? setTimeout(function () { стоп.abort(); }, срок) : 0;

    return fetch(CW.адрес + путь, {
      method: способ,
      headers: заголовки,
      body: тело,
      signal: стоп ? стоп.signal : undefined
    }).then(function (о) {
      clearTimeout(часы);

      /* ключ протух — обновляем и повторяем ровно один раз */
      if (о.status === 401 && !повтор && взять(КЛЮЧИ.обновить)) {
        return обновитьКлюч().then(function (вышло) {
          if (!вышло) {
            if (настройки.тихо) return null;
            throw Беда(401, 'Нужно войти заново');
          }
          настройки.__повтор = true;
          return CW.спросить(путь, настройки);
        });
      }

      if (о.status === 204) return null;

      var тип = о.headers.get('content-type') || '';
      var разбор = тип.indexOf('json') !== -1
        ? о.json().catch(function () { return null; })
        : о.text().catch(function () { return null; });

      return разбор.then(function (д) {
        if (о.ok) return д;
        if (настройки.тихо) return null;
        /* FastAPI на непрошедшую проверку отвечает НЕ строкой, а списком
           разборов: [{loc:[…], msg:'…'}]. Прежде он уходил в подсказку как
           есть и человек видел «[object Object]». Теперь разворачиваем. */
        var текст = внятно(д && (д.detail || д.message || д.error))
          || ('Сервер ответил ' + о.status);
        throw Беда(о.status, текст, д);
      });
    }).catch(function (е) {
      clearTimeout(часы);
      if (е && е.код !== undefined) throw е;        /* уже наша Беда */
      if (настройки.тихо) return null;
      var обрыв = (е && (е.name === 'AbortError'))
        ? 'Сервер не ответил за ' + Math.round(срок / 1000) + ' с'
        : 'Нет связи с сервером';
      throw Беда(0, обрыв);
    });
  };

  /* ── короткие имена для частых случаев ─────────────────────────── */
  CW.взятьС = function (путь, настройки) {
    return CW.спросить(путь, настройки);
  };
  CW.послать = function (путь, тело, настройки) {
    настройки = настройки || {};
    настройки.способ = настройки.способ || 'POST';
    настройки.тело = тело;
    return CW.спросить(путь, настройки);
  };

  /* ── выход ─────────────────────────────────────────────────────── */
  /* ── положить файл на сервер ─────────────────────────────────────────
     Два шага, как устроено на той стороне: сперва билет (куда класть и
     чем подписано), потом сами байты. Билет нужен, чтобы в переписку
     нельзя было вписать ссылку на что угодно — хоть на чужой файл.

         CW.залить(файл, 'image').then(function (о) { о.адрес, о.размер });
         CW.залить(ролик, 'movie', function (п) { … });   с процентами

     вид: image | audio | doc | clip | movie */
  CW.залить = function (файл, вид, наПроцент) {
    вид = вид || 'doc';
    return CW.спросить('/upload/ticket', {
      способ: 'POST',
      тело: { filename: файл.name || 'файл', kind: вид, size: файл.size || 0 }
    }).then(function (б) {
      if (!б) throw Беда(0, 'Сервер не выдал разрешение на загрузку');
      if (б.chunked || б.mode === 'chunk') {
        throw Беда(0, 'Файл слишком большой: его нужно класть кусками, '
                    + 'а это отдельное окно, и его ещё нет');
      }
      var куда = б.upload_url || '/upload/direct';
      if (/^https?:/i.test(куда)) {
        throw Беда(0, 'Это хранилище требует отдельного пути загрузки');
      }
      var пачка = new окно.FormData();
      пачка.append('file', файл);
      /* Вид берём ИЗ БИЛЕТА, а не свой: билет подписан именно им.
         18 ноября окно поста просило вид «video», сервер такого не знает
         и подписал билет видом «doc» — подпись не сходилась, и каждая
         загрузка ролика отвечала 403. Теперь спорить не о чем. */
      var видБилета = б.kind || вид;
      куда += '?path=' + encodeURIComponent(б.path)
            + '&exp=' + encodeURIComponent(б.exp)
            + '&sig=' + encodeURIComponent(б.sig)
            + '&kind=' + encodeURIComponent(видБилета);
      /* ── проценты ──
         Для снимка они не нужны, для ролика на сто мегабайт — нужны
         очень: без них человек десять минут смотрит на неподвижную
         надпись и решает, что всё зависло. Проценты умеет считать
         только XHR, поэтому этот шаг идёт через него. */
      if (typeof наПроцент === 'function') {
        return вместеСПроцентами(куда, пачка, наПроцент).then(function (о) {
          var адрес = (о && о.url) || б.public_url;
          if (!адрес) throw Беда(0, 'Файл ушёл, а адреса в ответе нет');
          return { адрес: адрес, размер: (о && о.size) || файл.size || 0 };
        });
      }

      return CW.спросить(куда, { способ: 'POST', тело: пачка, сроком: 180000 })
        .then(function (о) {
          var адрес = (о && о.url) || б.public_url;
          if (!адрес) throw Беда(0, 'Файл ушёл, а адреса в ответе нет');
          return { адрес: адрес, размер: (о && о.size) || файл.size || 0 };
        });
    });
  };

  /* Тот же запрос, но с процентами. Отдельной функцией, а не флагом
     внутри CW.спросить: XHR не умеет половины того, что умеет fetch, и
     тащить его в общий разговор с сервером ради одного места — значит
     испортить все остальные. */
  function вместеСПроцентами(куда, пачка, наПроцент) {
    return new Promise(function (готово, беда) {
      var х = new окно.XMLHttpRequest();
      х.open('POST', /^https?:/i.test(куда) ? куда : (CW.адрес + куда));
      х.timeout = 600000;

      /* Ключ посылаем так же, как и обычный запрос. Сперва его тут не
         было — рассуждение было такое: разрешение уже получено, подпись
         лежит в адресе. Сервер рассудил иначе и ответил 401, и он прав:
         подпись говорит КУДА класть, а ключ — КТО кладёт. */
      var ключ = взять(КЛЮЧИ.вход);
      if (ключ) х.setRequestHeader('Authorization', 'Bearer ' + ключ);

      х.upload.onprogress = function (е) {
        if (!е.lengthComputable) return;
        наПроцент(Math.min(99, Math.round(е.loaded / е.total * 100)),
                  е.loaded, е.total);
      };
      х.onload = function () {
        if (х.status < 200 || х.status >= 300) {
          беда(Беда(х.status, 'Сервер отказался принять файл'));
          return;
        }
        наПроцент(100);
        var о = null;
        try { о = JSON.parse(х.responseText || '{}'); } catch (е) { о = {}; }
        готово(о);
      };
      х.onerror   = function () { беда(Беда(0, 'Нет связи с сервером')); };
      х.ontimeout = function () { беда(Беда(0, 'Сервер не ответил вовремя')); };
      х.onabort   = function () { беда(Беда(0, 'Загрузка отменена')); };

      /* Кнопка «отменить» нужна всегда: передумать посреди загрузки
         стомегабайтного ролика — обычное дело. */
      наПроцент.отменить = function () { try { х.abort(); } catch (е) {} };
      х.send(пачка);
    });
  }

  /* ── адрес файла на сервере ────────────────────────────────────────
     Сервер отдаёт адреса файлов относительными: /uploads/clip/…/a.mp4.
     Внутри одного домена это верно и даже лучше абсолютного. Но у нас
     страницы живут на cube-world.space, а сервер — на отдельном адресе,
     и такой путь браузер ищет у страниц, где его нет. В итоге ролик
     загрузился, запись завелась, а в ленте чёрный квадрат.

     Поэтому КАЖДЫЙ адрес файла, пришедший с сервера, проходит здесь.
     Чужие (http…, data: blob:) не трогаем — они уже полные.

         <img src="' + CW.файл(п.image_url) + '">
  */
  CW.файл = function (путь) {
    var а = String(путь == null ? '' : путь);
    if (!а) return '';
    if (/^(https?:|data:|blob:|\/\/)/i.test(а)) return а;
    return CW.адрес + (а.charAt(0) === '/' ? а : '/' + а);
  };

  /* ═════════════════════════════════════════════════════════════════════
     МИНУТЫ В СЕТИ

     На сервере «Активный день» и бонусы за неделю, месяц и год считаются
     из одной колонки — online_minutes, и растёт она только от запроса
     /activity/ping. Этого запроса в программе не было ни одного: экран
     «Заработать» показывал ставку за активный день, а набрать его было
     нельзя — минуты не росли ни у кого и никогда.

     Шлём раз в минуту и только когда вкладка на виду: ping за свёрнутой
     вкладкой — это не «человек в сети», это открытый браузер.
     ═════════════════════════════════════════════════════════════════════ */
  (function минуты() {
    var часы = null;
    function можно() {
      return !!взять(КЛЮЧИ.вход) && !окно.document.hidden;
    }
    function стук() {
      if (!можно()) return;
      CW.спросить('/activity/ping', { способ: 'POST', тихо: true })
        .catch(function () { /* нет связи — следующая минута своё возьмёт */ });
    }
    function завести() {
      if (часы) return;
      часы = окно.setInterval(стук, 60000);
    }
    function погасить() {
      if (!часы) return;
      окно.clearInterval(часы);
      часы = null;
    }
    окно.document.addEventListener('visibilitychange', function () {
      if (окно.document.hidden) погасить();
      else { завести(); стук(); }
    });
    /* Первый стук не сразу: страница только открылась, и ей есть чем
       заняться помимо нас. */
    окно.setTimeout(function () {
      if (!можно()) return;
      стук(); завести();
    }, 10000);
  })();

  /* ── ГДЕ ЧЕЛОВЕК БЫЛ ДО МИРА ───────────────────────────────────────
     Мир открывается поверх раздела меню, и выйти из него в куб надо
     туда же, откуда пришли. Пишет это меню (shared/shell.js), читает
     мир — поэтому обе руки здесь, в общем файле: мир меню не грузит.

         CW.помнитьРаздел('chats');
         CW.последнийРаздел()   →  'chats'
  */
  CW.помнитьРаздел = function (имя) {
    if (имя) положить('cw_раздел', String(имя));
  };
  CW.последнийРаздел = function () {
    return взять('cw_раздел') || '';
  };

  /* ── НАЙТИ ЧЕЛОВЕКА ────────────────────────────────────────────────
     Один адрес, /cube/find, спрашивают три места: строка перевода в
     кошельке, окно перевода и поиск собеседника в чатах. Сервер
     отвечает на него по-разному — то списком, то {users:[…]}, то одним
     человеком, — и разбирать эти три вида в трёх файлах нельзя: там,
     где деньги, ошибка разбора стоит перевода не тому.

         CW.найтиЛюдей('аня').then(function (люди) { … })

     Отдаёт всегда массив, пусть и пустой. Беду глотает молча: поиск —
     не то место, где человека надо пугать красной полосой, он просто
     ничего не найдёт и наберёт иначе. */
  CW.найтиЛюдей = function (что) {
    что = String(что || '').trim();
    if (!что) return Promise.resolve([]);
    return CW.спросить('/cube/find?q=' + encodeURIComponent(что), { тихо: true })
      .then(function (о) {
        var ряды = Array.isArray(о) ? о
                 : ((о && (о.users || о.items)) || (о && о.id ? [о] : []));
        return ряды.filter(function (ч) { return ч && ч.id; });
      })
      .catch(function () { return []; });
  };

  /* ── КАК ЗОВУТ ЧЕЛОВЕКА: ОДНО ПРАВИЛО НА ВСЮ ПРОГРАММУ ───────────
     Своё имя, иначе @ник, иначе «Участник #номер».

     Правил было четыре, и они расходились: в ленте человек звался
     «Участник #16», в чатах «#16», в комментариях «#16» без решётки у
     ника, а в переводе — ключом «CUBE-9BD9…». Один и тот же человек
     выглядел в трёх окнах тремя разными людьми.

     Ключ именем не показываем никогда: «CUBE-9BD9-G4HR» — это пароль
     от входа, а не имя, и его нельзя показывать соседям по переписке.
     Если в поле имени лежит ключ, человек остаётся «Участником». */
  CW.имяЧеловека = function (ч) {
    if (!ч) return '';
    var имя = String(ч.display_name || ч.name || '').trim();
    if (имя && !/^CUBE-/i.test(имя)) return имя;
    var ник = String(ч.username || '').trim().replace(/^@+/, '');
    if (ник) return '@' + ник;
    var ид = ч.id || ч.user_id || ч.peer_id || ч.uid || '';
    return ид ? ('Участник #' + ид) : 'Участник';
  };

  CW.выйти = function (сказатьСерверу) {
    var прощание = сказатьСерверу
      ? CW.спросить('/auth/logout', { способ: 'POST', тихо: true })
      : Promise.resolve();
    return прощание.then(function () {
      убрать(КЛЮЧИ.вход);
      убрать(КЛЮЧИ.обновить);
      убрать(КЛЮЧИ.ключ);
      убрать(КЛЮЧИ.вид);
      /* Память человека уходит вместе с ним: отбор кубов, цвета
         значков, формы. Иначе следующий, кто войдёт на этом устройстве,
         увидит в мире чужие кубы. */
      if (CW.забытьЛичное) CW.забытьЛичное();
      /* номер устройства оставляем: он не про человека, а про телефон */
    });
  };

})(window);
