/* ═══════════════════════════════════════════════════════════════════════
   ПОДПИСЬ И ПЕЧАТЬ В ЧУЖОМ ФАЙЛЕ.  /home/claude/новое/cubeworld-app/shared/знаки.js

       CW.знаки.выбрать(функция (адрес, файл) { … });

   Показывает полку с подписями и печатями из всех папок, рисует
   выбранную снимком с прозрачным фоном, кладёт снимок в хранилище и
   отдаёт его адрес. Куда его поставить — дело того, кто позвал:
   документ и слайд кладут знак на лист, таблица — на слой поверх
   клеток.

   Своего рисования здесь нет нарочно: подпись и печать — свои виды
   файлов со своими редакторами (shared/правка-подпись.js и
   shared/правка-печать.js), и второй раз их рисовать незачем. Снимок
   собираем теми же редакторами: тогда в документе стоит ровно то, что
   человек нарисовал, а не его пересказ.

   Отдельным файлом — потому что знак ставят в пять видов файлов:
   PDF, слайды, документ Word, таблицу CSV и таблицу Excel. Писать
   выбор и снимок в каждом из редакторов означало бы пять разных
   «Подписать», которые разойдутся на первой же правке.
   ═══════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  /* Все подписи и печати, какие есть у человека: по папкам они
     разложены как угодно, а подписывать он хочет любой. */
  function изПапок() {
    return CW.спросить('/folders', { тихо: true }).then(function (о) {
      var папки = Array.isArray(о) ? о : ((о && (о.folders || о.items)) || []);
      return Promise.all(папки.map(function (п) {
        return CW.спросить('/folders/' + п.id + '/files', { тихо: true })
          .then(function (р) {
            var сп = Array.isArray(р) ? р : ((р && (р.files || р.items)) || []);
            return сп.filter(function (ф) {
              return ф.kind === 'sign' || ф.kind === 'stamp';
            });
          })
          .catch(function () { return []; });
      })).then(function (куски) {
        return куски.reduce(function (всё, ч) { return всё.concat(ч); }, []);
      });
    }).catch(function () { return []; });
  }

  /* Вид файла говорит, каким редактором собирать снимок. Подпись
     читает росчерк теми же мазками, что и рисунок, поэтому рисунок
     едет первым. */
  function снимком(ф) {
    var это = (ф.kind === 'stamp')
      ? { файл: 'shared/правка-печать.js', зовут: 'знакПечать' }
      : { файл: 'shared/правка-подпись.js', зовут: 'знакПодпись' };
    var едет = (ф.kind === 'stamp')
      ? CW.нужен(это.файл)
      : CW.нужен('shared/правка-рисунок.js').then(function () {
          return CW.нужен(это.файл);
        });
    return едет.then(function () {
      return CW.спросить('/files/' + ф.id, { тихо: true });
    }).then(function (полный) {
      var знак = CW[это.зовут];
      var холст = знак.наХолст(знак.изТела((полный && полный.body) || ''), 2);
      return new Promise(function (дать, нет) {
        холст.toBlob(function (б) {
          if (б) дать(new File([б], (ф.name || 'знак') + '.png', { type: 'image/png' }));
          else нет(new Error('Снимок не вышел'));
        }, 'image/png');
      });
    });
  }

  CW.знаки = {
    выбрать: function (когда) {
      CW.сказать('Смотрю подписи и печати…', 20000);
      изПапок().then(function (список) {
        if (!список.length) {
          CW.сказать('Подписей и печатей пока нет. Заведи их в папке: '
                   + '«Новый файл» → «Подпись» или «Печать»', 7000);
          return;
        }
        CW.лист(список.slice(0, 20).map(function (ф) {
          return {
            зн: CW.значок(ф.kind === 'stamp' ? 'цель' : 'карандаш', 16),
            подпись: ф.name || (ф.kind === 'stamp' ? 'Печать' : 'Подпись'),
            делать: function () { поставить(ф); }
          };
        }), {});
      });

      function поставить(ф) {
        CW.сказать('Ставлю…', 60000);
        снимком(ф).then(function (файл) {
          return CW.залить(файл, 'image');
        }).then(function (о) {
          когда(о.адрес, ф);
        }).catch(function (е) {
          CW.сказать((е && е.message) || 'Не вышло поставить знак', 6000);
        });
      }
    }
  };
})();
