/* ═══════════════════════════════════════════════════════════════════════
   ВЕСТИ — уведомления.      /home/claude/новое/cubeworld-app/shared/вести.js

   Одно место, где уведомления СОБИРАЮТСЯ, и одно, где помнится, что
   уже прочитано. Показывают их двое:

       колокольчик в полосе   — меню прямо под кнопкой (CW.менюВестей);
       windows/notifications  — то же самое целым окном, с хвостом и
                                объяснением, откуда что берётся.

   Пока сбор жил внутри окна, меню под колокольчиком пришлось бы
   написать вторым — и первое же новое событие появилось бы в одном
   месте и не появилось в другом. Поэтому сбор здесь, а окно и меню
   только рисуют.

       CW.вести.собрать()        → обещание со списком событий
       CW.вести.прочитано(ключ)  → было ли прочитано
       CW.вести.отметить(ключ)
       CW.вести.всёПрочитано(список)
       CW.вести.новых(список)    → сколько непрочитанных
       CW.менюВестей(кнопка, {откуда})

   ЧТО СЧИТАЕТСЯ ВЕСТЬЮ. Только системное: вошёл в куб, куб скоро
   закроется, начислили или списали CUBE, заявка на выплату и её
   судьба, новый подписчик, предел ключа на исходе. Переписки здесь
   нет: кто кому что написал — видно в чатах, а под колокольчиком
   болтовня хоронила настоящие события.

   У каждого источника: адрес, как превратить ответ в события и что
   делать, когда событие нажали. Добавилась ручка на сервере — сюда
   добавляется строка, и событие появляется само и в окне, и в меню,
   и в счётчике.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};
  function э(тег, класс, текст) { return CW.эл(тег, класс, текст); }

  var ПРОЧИТАНО = {};
  var ЗАГРУЖЕНО = null;
  var КЛЮЧ = 'уведомления.прочитано';
  var ПОМНИМ = 300;

  var ИСТОЧНИКИ = [
    {
      /* КУБЫ. Вошёл в куб, куб скоро закроется — это и есть уведомления
         куба. Время входа сервер отдаёт в joined_at (первая отметка о
         человеке в этом кубе); без него строка висела бы вечным
         «только что». */
      имя: 'кубы',
      адрес: '/me/cube-memberships',
      события: function (д) {
        var вести = [];
        рядами(д).forEach(function (к) {
          var имя = к.name || Т.с('куб #{н}', { н: к.id });
          вести.push({
            ключ: 'куб:' + к.id + ':' + (к.joined_at || ''),
            знак: 'ракета',
            имя: Т.с('Ты вошёл в куб {имя}', { имя: имя }),
            текст: '',
            когда: к.joined_at || к.last_visit || '',
            куда: function () { CW.уйти(CW.раздел('feed', к.id)); }
          });
          var сек = Number(к.life_left_seconds || 0);
          if (сек > 0 && сек < 86400) {
            вести.push({
              ключ: 'кубсрок:' + к.id + ':' + сегодня(),
              знак: 'внимание',
              имя: Т.с('Куб {имя} скоро закроется', { имя: имя }),
              текст: Т.с('Осталось {н} ч жизни куба.',
                        { н: Math.max(1, Math.round(сек / 3600)) }),
              когда: '',
              куда: function () { CW.уйти(CW.раздел('feed', к.id)); }
            });
          }
        });
        return вести;
      }
    },
    {
      /* НАГРАДЫ. Настоящие движения по счёту CUBE: начисления за
         активность, переводы, списания. У каждой строки есть время и
         номер — значит, прочитанное не разъезжается. */
      имя: 'награды',
      адрес: '/cube/transactions?limit=20',
      события: function (д) {
        var ряды = (д && д.transactions) || рядами(д);
        return ряды.map(function (т) {
          var сколько = Number(т.amount || 0);
          return {
            ключ: 'cube:' + (т.id || (т.created_at + ':' + сколько)),
            знак: 'монета',
            имя: (сколько >= 0 ? '+' : '') + округлить(сколько) + ' CUBE',
            текст: т.description || названиеДвижения(т.type),
            когда: т.created_at || '',
            куда: function () { CW.уйти(CW.раздел('wallet')); }
          };
        });
      }
    },
    {
      /* ВЫПЛАТЫ. Заявка на деньги и её судьба — событие, которое человек
         ждёт сильнее всех прочих. */
      имя: 'выплаты',
      адрес: '/rewards/history',
      события: function (д) {
        return рядами(д).map(function (в) {
          return {
            ключ: 'выплата:' + (в.month || '') + ':' + (в.status || ''),
            знак: 'кошелёк',
            имя: 'Выплата $' + округлить(в.usd_amount) + ' за ' + месяцем(в.month),
            текст: названиеСудьбы(в.status),
            когда: в.created_at || '',
            куда: function () { CW.уйти(CW.раздел('earn')); }
          };
        });
      }
    },
    {
      имя: 'подписчики',
      адрес: function () { return '/follow/' + мойНомер() + '/followers'; },
      события: function (д) {
        return рядами(д).map(function (ч) {
          return {
            ключ: 'follow:' + ч.id,
            кружок: { кто: ч.id, снимок: ч.avatar_url,
                      версия: ч.avatar_ver },
            имя: CW.имяЧеловека(ч),
            текст: Т('подписался на тебя'),
            когда: ч.created_at || ч.followed_at || '',
            куда: function () { CW.вПортфолио(ч.id); }
          };
        });
      }
    },
    {
      имя: 'пределы',
      адрес: '/me/limits',
      события: function (д) {
        var пределы = (д && д.limits) || {};
        /* Говорим только о том, что вот-вот кончится. Перечислять все
           пределы каждый день — это шум, из-за которого человек
           перестаёт читать уведомления вообще. */
        return Object.keys(пределы).filter(function (к) {
          var п = пределы[к];
          return п && п.предел > 0 && п.осталось <= Math.max(1, п.предел * 0.1);
        }).map(function (к) {
          var п = пределы[к];
          return {
            ключ: 'предел:' + к + ':' + сегодня(),
            знак: 'внимание',
            имя: 'Осталось ' + п.осталось + ': ' + (п.название || к),
            текст: 'Предел ключа на сегодня: ' + п.предел
                 + '. Больший ключ снимает ограничение.',
            когда: '',
            куда: function () { CW.уйти(CW.раздел('tariff')); }
          };
        });
      }
    }
  ];

  /* ── СБОР ──
     Источник, который промолчал, не гасит остальные: человек пришёл за
     сообщениями, а не за отчётом о том, что ручка подписчиков сегодня
     не отвечает. */
  function собрать() {
    return загрузитьПрочитанное().then(function () {
      return Promise.all(ИСТОЧНИКИ.map(function (и) {
        var адрес = typeof и.адрес === 'function' ? и.адрес() : и.адрес;
        return CW.спросить(адрес, { тихо: true, сроком: 15000 })
          .then(function (д) { return и.события(д) || []; })
          .catch(function () { return []; });
      }));
    }).then(function (пачки) {
      var всё = [];
      пачки.forEach(function (п) { всё = всё.concat(п); });
      всё.sort(function (а, б) {
        return String(б.когда || '').localeCompare(String(а.когда || ''));
      });
      return всё;
    });
  }

  /* ── ЧТО УЖЕ ВИДЕЛИ ──
     Ключи прочитанного храним в настройках человека — значит, и на
     телефоне, и на маке одно и то же. Список подрезаем: иначе через
     год он вырастет до мегабайта и будет ездить с каждым запросом. */
  function загрузитьПрочитанное() {
    if (ЗАГРУЖЕНО) return ЗАГРУЖЕНО;
    ЗАГРУЖЕНО = CW.спросить('/me/prefs?keys=' + encodeURIComponent(КЛЮЧ),
                            { тихо: true })
      .then(function (д) {
        var сырое = д && (д[КЛЮЧ] || (д.prefs && д.prefs[КЛЮЧ]));
        var ряды = !сырое ? []
                 : (typeof сырое === 'string' ? JSON.parse(сырое) : сырое);
        (ряды || []).forEach(function (к) { ПРОЧИТАНО[к] = 1; });
      })
      .catch(function () { /* нет связи — считаем всё новым, это не ошибка */ });
    return ЗАГРУЖЕНО;
  }

  function сохранить() {
    var ряды = Object.keys(ПРОЧИТАНО).slice(-ПОМНИМ);
    var стало = {};
    ряды.forEach(function (к) { стало[к] = 1; });
    ПРОЧИТАНО = стало;

    var тело = {};
    тело[КЛЮЧ] = JSON.stringify(ряды);
    return CW.спросить('/me/prefs', { способ: 'POST', тихо: true,
                                      тело: { prefs: тело } })
      .catch(function () { /* не записалось — на экране уже прочитано */ });
  }

  CW.вести = {
    собрать: собрать,
    прочитано: function (ключ) { return !!ПРОЧИТАНО[ключ]; },
    отметить: function (ключ) {
      if (ПРОЧИТАНО[ключ]) return;
      ПРОЧИТАНО[ключ] = 1;
      сохранить();
    },
    всёПрочитано: function (список) {
      (список || []).forEach(function (с) { ПРОЧИТАНО[с.ключ] = 1; });
      return сохранить();
    },
    новых: function (список) {
      return (список || []).filter(function (с) { return !ПРОЧИТАНО[с.ключ]; }).length;
    },
    когда: когда
  };

  /* ═══════════════════════════════════════════════════════════════════
     МЕНЮ ПОД КОЛОКОЛЬЧИКОМ

     Уведомления открывались целой страницей: человек уходил с ленты,
     читал три строки и возвращался обратно. Теперь они выпадают прямо
     под кнопкой, как в боевой, а целое окно остаётся для тех, кто
     хочет посмотреть всё и разом отметить прочитанным.

     Устроено так же, как меню аккаунта: гнездо у кнопки, слушатель
     «мимо» только пока открыто, Escape закрывает меню, а не окно.
     ═══════════════════════════════════════════════════════════════════ */
  CW.менюВестей = function (кнопка, настройки) {
    if (!кнопка || кнопка.сВестями) return null;
    кнопка.сВестями = true;
    настройки = настройки || {};

    var гнездо = э('div', 'об-лицо-гнездо');
    if (кнопка.parentNode) кнопка.parentNode.insertBefore(гнездо, кнопка);
    гнездо.appendChild(кнопка);

    var меню = э('div', 'об-аккаунт об-вести');
    гнездо.appendChild(меню);

    var шапка = э('div', 'вести-шапка');
    шапка.innerHTML = '<b><span class="зн"></span>' + CW.безопасно(Т('Уведомления')) + ''
                    + ' <i class="счёт"></i></b>';
    шапка.querySelector('.зн').innerHTML = CW.значок('колокол', 15);
    var всё = э('button', 'вести-всё', Т('Прочитать все'));
    шапка.appendChild(всё);
    меню.appendChild(шапка);

    var тело = э('div', 'вести-тело');
    меню.appendChild(тело);

    var СПИСОК = [];

    всё.onclick = function (е) {
      е.stopPropagation();
      CW.вести.всёПрочитано(СПИСОК);
      нарисовать();
      обновитьСчёт();
    };

    кнопка.onclick = function (е) {
      е.stopPropagation();
      if (меню.classList.contains('видно')) { закрыть(); return; }
      меню.classList.add('видно');
      кнопка.classList.add('горит');
      перечитать();
      setTimeout(function () {
        документ.addEventListener('click', мимо, true);
      }, 0);
    };

    function мимо(е) { if (!гнездо.contains(е.target)) закрыть(); }
    function закрыть() {
      меню.classList.remove('видно');
      кнопка.classList.remove('горит');
      документ.removeEventListener('click', мимо, true);
    }
    документ.addEventListener('keydown', function (е) {
      if (е.key === 'Escape' && меню.classList.contains('видно')) {
        е.stopPropagation();
        закрыть();
      }
    }, true);

    function перечитать() {
      тело.innerHTML = '<div class="пусто-строка">' + CW.безопасно(Т('Загрузка…')) + '</div>';
      собрать().then(function (список) {
        СПИСОК = список;
        нарисовать();
        обновитьСчёт();
      });
    }

    function нарисовать() {
      тело.innerHTML = '';
      шапка.querySelector('.счёт').textContent =
        СПИСОК.length ? '(' + CW.вести.новых(СПИСОК) + ')' : '';
      всё.disabled = !CW.вести.новых(СПИСОК);

      if (!СПИСОК.length) {
        тело.appendChild(э('div', 'пусто-строка',
          Т('Пока тихо. Новых событий в кубах и наград нет.')));
        return;
      }

      /* Нижней строки «Открыть все уведомления» здесь нет намеренно:
         меню и есть весь список, уводить человека со страницы незачем.
         Окно windows/notifications осталось тем же списком целиком —
         на случай, если этот файл не загрузился. */
      СПИСОК.slice(0, 12).forEach(function (с) {
        тело.appendChild(строка(с));
      });
    }

    function строка(с) {
      var б = э('button', 'вести-строка'
                        + (CW.вести.прочитано(с.ключ) ? ' прочитано' : ''));
      if (с.кружок) {
        б.appendChild(CW.кружок({ размер: 30, кто: с.кружок.кто,
                                  снимок: с.кружок.снимок,
                                  версия: с.кружок.версия,
                                  значок: с.кружок.значок }));
      } else {
        var зн = э('span', 'зн');
        зн.innerHTML = CW.значок(с.знак || 'колокол', 16);
        б.appendChild(зн);
      }

      var что = э('div', 'что');
      что.innerHTML = '<b></b><span></span>';
      что.querySelector('b').textContent = с.имя;
      что.querySelector('span').textContent =
        [с.текст, с.метка, когда(с.когда)].filter(Boolean).join(' · ');
      б.appendChild(что);

      б.appendChild(э('span', 'точка'));

      б.onclick = function () {
        CW.вести.отметить(с.ключ);
        обновитьСчёт();
        закрыть();
        if (с.куда) с.куда();
      };
      return б;
    }

    /* Счётчик на самом колокольчике — тот же узел, что и был. */
    function обновитьСчёт() {
      var с = документ.getElementById('об-счёт');
      if (!с) return;
      var н = CW.вести.новых(СПИСОК);
      с.textContent = н ? String(н) : '';
      с.style.display = н ? '' : 'none';
    }

    /* Счёт показываем сразу, не дожидаясь, пока человек нажмёт: иначе
       колокольчик молчит о том, ради чего он стоит. */
    собрать().then(function (список) { СПИСОК = список; обновитьСчёт(); });

    return { перечитать: перечитать, закрыть: закрыть };
  };

  /* ── мелочь ── */
  function мойНомер() { return ((CW.ясныйЯ && CW.ясныйЯ()) || {}).id || 0; }

  function рядами(д) {
    if (!д) return [];
    if (Array.isArray(д)) return д;
    return д.items || д.users || д.followers || [];
  }

  function когда(иso) {
    if (!иso) return '';
    try { return CW.когда ? CW.когда(иso) : CW.часы(иso); }
    catch (е) { return ''; }
  }

  function округлить(ч) {
    var н = Number(ч || 0);
    return (Math.round(н * 100) / 100).toString();
  }

  function названиеДвижения(тип) {
    var словарь = {
      reward: 'награда за активность',
      activity: 'награда за активность',
      transfer_in: 'перевод тебе',
      transfer_out: 'перевод',
      purchase: 'покупка',
      key: 'ключ',
      bonus: 'бонус'
    };
    return словарь[тип] || 'движение по счёту';
  }

  /* «2026-10» человеку ничего не говорит, «октябрь 2026» говорит сразу. */
  function месяцем(строка) {
    var м = String(строка || '').match(/^(\d{4})-(\d{2})$/);
    if (!м) return строка || '';
    var имена = ['январь', 'февраль', 'март', 'апрель', 'май', 'июнь', 'июль',
                 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь'];
    return (имена[Number(м[2]) - 1] || м[2]) + ' ' + м[1];
  }

  function названиеСудьбы(статус) {
    var словарь = {
      pending: 'заявка принята, ждёт выплаты',
      paid: 'выплачено',
      rejected: 'отказано',
      cancelled: 'отменено'
    };
    return словарь[статус] || (статус || '');
  }

  function сегодня() {
    var д = new Date();
    return д.getFullYear() + '-' + (д.getMonth() + 1) + '-' + д.getDate();
  }

})(window, document);
