/* ═══════════════════════════════════════════════════════════════════════
   МЕНЮ АККАУНТА — ОДНО НА ВСЮ ПРОГРАММУ.

   Висит под кружком лица и открывается нажатием на него.

       CW.менюАккаунта(кнопка);

   ── Почему отдельным файлом, а не внутри оболочки ──────────────────
   Верхних полос в программе ДВЕ. Разделы (лента, чаты, кошелёк…) живут
   в общей оболочке shared/shell.js, а мир рисует свою полосу сам: у
   него полотно во весь экран и бегущая строка курсов, и общая полоса
   ему не подходит.

   Пока меню лежало внутри оболочки, в мире его просто не было: лицо
   там уводило прямо в профиль. Человек нажимал на кружок в мире и не
   находил ни документов, ни выхода — тех самых, что видел минуту
   назад на ленте.

   Правило у нас простое: код, нужный двум экранам и больше, живёт в
   shared/. Меню нужно двум полосам — значит здесь.

   ── Что меню делает само ───────────────────────────────────────────
   Само закрывается касанием мимо и по Escape, само подставляет имя и
   номер, когда они приедут. Звать его для этого не надо.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  function э(тег, класс) { return CW.эл(тег, класс); }

  /* ── ПРЕДЛОЖЕНИЕ УСТАНОВКИ ──
     Chrome и Edge сами решают, когда предложить поставить площадку
     приложением, и сообщают об этом одним событием. Не перехватишь —
     браузер покажет свою полоску и выбросит событие, а вместе с ним и
     возможность поставить приложение одной кнопкой из нашего окна.

     Ловим здесь, потому что «Скачать Cube» живёт в этом же меню, и
     файл этот есть на каждом экране. */
  окно.addEventListener('beforeinstallprompt', function (е) {
    е.preventDefault();
    окно.CW_установка = е;
  });
  окно.addEventListener('appinstalled', function () {
    окно.CW_установка = null;
    if (CW.сказать) CW.сказать('Готово: значок на месте');
  });

  /* ── ПУНКТЫ ──
     Один список на обе полосы. Появится новый пункт — он добавляется
     сюда, и сразу виден отовсюду. Ради этого всё и затевалось. */
  /* «Мой профиль» здесь нет нарочно: в профиль ведёт сам кружок лица —
     и в полосе разделов, и в мире. Строка в меню вела бы туда же, куда
     и кружок над ней, а два пути в одно место человек читает как два
     разных места и ищет между ними разницу. */
  /* ── ТРИ ЗНАЧКА В ШАПКЕ, ТРИ СТРОКИ ПОД НЕЙ ───────────────────────
     Строк было шесть, и окно выходило в полэкрана. Три из них - то,
     что делают с самим аккаунтом: завести второй, поставить Cube
     себе на устройство, выйти. Они встали кружками в шапку, рядом с
     именем и номером, к которым и относятся, и окно стало вдвое
     короче.

     Строками внизу остались три двери в другие окна: карта, документы
     и голос. У них названия длиннее и путать их нельзя - в карту и в
     документы ходят по делу, а не на ощупь.

     Имена у кружков не потеряны: они остались подсказкой и меткой для
     читалки. */
  function значки(запомнить, кнопка) {
    return [
      { зн: 'человек-плюс', имя: 'Добавить аккаунт', делать: function () {
          CW.открыть('add-account'); } },
      { зн: 'скачать', имя: 'Скачать Cube', делать: function () {
          CW.открыть('download'); } },
      /* Выход кружком, но красным: цвет здесь вместо слова. И он
         по-прежнему спрашивает «точно?» - вопрос встаёт под самим
         кружком лица, а не посреди экрана: меню открылось оттуда,
         туда же и возвращается ответ. */
      { зн: 'выйти', имя: 'Выйти', опасный: true, делать: function () {
          CW.спроситьВыход(кнопка); } }
    ];
  }

  function строки(запомнить) {
    return [
      { зн: 'глобус', имя: 'Живая карта', делать: function () {
          запомнить(); CW.уйти(CW.окно('map')); } },
      { зн: 'лист', имя: 'Документы', делать: function () {
          запомнить(); CW.уйти(CW.окно('docs')); } },
      { зн: 'микрофон', имя: 'Голосовые команды', делать: function () {
          запомнить(); CW.уйти(CW.окно('voice')); } }
    ];
  }

  /* ═══════════════════════════════════════════════════════════════════
     СОБРАТЬ

     Кнопка приходит готовой — её рисует та полоса, которой она
     принадлежит: в оболочке кружок один, в мире другой. Меню только
     вешается под неё.
     ═══════════════════════════════════════════════════════════════════ */
  CW.менюАккаунта = function (кнопка, настройки) {
    if (!кнопка || кнопка.сМеню) return null;
    настройки = настройки || {};

    /* Гнездо нужно, чтобы меню считало координаты от кружка, а не от
       всей полосы. Кнопку кладём внутрь гнезда на её же место. */
    var гнездо = э('div', 'об-лицо-гнездо');
    if (кнопка.parentNode) кнопка.parentNode.insertBefore(гнездо, кнопка);
    гнездо.appendChild(кнопка);

    var меню = э('div', 'об-аккаунт');
    гнездо.appendChild(меню);

    var верх = э('div', 'об-аккаунт-верх');
    var кто = э('div', 'об-аккаунт-кто');
    кто.innerHTML = '<b class="об-аккаунт-имя">Мой аккаунт</b>'
                  + '<span class="об-аккаунт-номер"></span>';
    верх.appendChild(кто);
    меню.appendChild(верх);

    function запомнить() {
      try { окно.sessionStorage.setItem('cw_откуда', настройки.откуда || ''); }
      catch (е) {}
    }

    var ряд = э('div', 'об-аккаунт-значки');
    верх.appendChild(ряд);
    значки(запомнить, кнопка).forEach(function (п) {
      var б = э('button', 'об-аккаунт-значок' + (п.опасный ? ' опасный' : ''));
      б.type = 'button';
      /* Название не потеряно: оно осталось подсказкой. Палец её не
         увидит, но мышь покажет, а читалке для слепых она и вовсе
         единственный способ узнать, что это за кружок. */
      б.title = п.имя;
      б.setAttribute('aria-label', п.имя);
      б.innerHTML = CW.значок(п.зн);
      б.onclick = function (е) { е.stopPropagation(); закрыть(); п.делать(); };
      ряд.appendChild(б);
    });

    строки(запомнить).forEach(function (п) {
      var с = э('button', 'об-аккаунт-ряд' + (п.опасный ? ' опасный' : ''));
      с.type = 'button';
      с.innerHTML = '<span class="зн">' + CW.значок(п.зн) + '</span>'
                  + '<span>' + п.имя + '</span>';
      с.onclick = function (е) { е.stopPropagation(); закрыть(); п.делать(); };
      меню.appendChild(с);
    });

    кнопка.title = 'Аккаунт';
    кнопка.onclick = function (е) {
      е.stopPropagation();
      if (меню.classList.contains('видно')) { закрыть(); return; }
      меню.classList.add('видно');
      кнопка.classList.add('горит');
      /* Слушателя «мимо» вешаем только пока меню открыто: висящий
         всегда перехватывал бы каждое нажатие на странице ради одного
         редкого случая. */
      setTimeout(function () {
        документ.addEventListener('click', мимо, true);
        /* ── И ПО КАСАНИЮ, А НЕ ТОЛЬКО ПО НАЖАТИЮ ──
           Нажатие мимо слушалось событием click. На компьютере этого
           довольно, а в мире на телефоне - нет: небо с кубами ловит
           касание само (оно им вращают) и до click дело не доходит.
           Меню оставалось висеть, и убрать его можно было только тем
           же кружком лица.

           pointerdown приходит раньше всех и до любых отмен. Слушаем
           оба: click остаётся ради клавиатуры и мыши. */
        документ.addEventListener('pointerdown', мимо, true);
      }, 0);
    };

    function мимо(е) { if (!гнездо.contains(е.target)) закрыть(); }
    function закрыть() {
      меню.classList.remove('видно');
      кнопка.classList.remove('горит');
      документ.removeEventListener('click', мимо, true);
      документ.removeEventListener('pointerdown', мимо, true);
    }

    /* Escape закрывает меню, а не окно под ним. */
    документ.addEventListener('keydown', function (е) {
      if (е.key === 'Escape' && меню.classList.contains('видно')) {
        е.stopPropagation();
        закрыть();
      }
    }, true);

    кнопка.сМеню = true;

    /* ── имя и номер ──
       Номер важнее имени: по нему человека находят и ему переводят, а
       имя может быть и пустым. Поэтому номер стоит всегда, даже когда
       имени нет. */
    var он = {
      кто: function (я) {
        if (!я) return он;
        var и = меню.querySelector('.об-аккаунт-имя');
        var н = меню.querySelector('.об-аккаунт-номер');
        if (и) и.textContent = я.display_name || я.username || 'Мой аккаунт';
        if (н) н.textContent = 'UID · ' + (я.uid || ('#' + (я.id || '-')));
        return он;
      },
      закрыть: закрыть,
      узел: меню
    };

    /* Если данные уже приехали до сборки меню — ставим сразу. */
    он.кто(CW.ясныйЯ && CW.ясныйЯ());
    return он;
  };

})(window, document);
