  var доПокоя = 0;
  var возврат = null;         /* обрыв возврата по местам */
  var вруках = null;          /* тело, которое держат пальцем */
  var стукнули = 0;           /* сколько кубов задело за последний кадр */

  var ПОЛЕ = { тяга: { x: 0, y: 0, z: 0 }, магнит: 0, вихрь: 0,
               дрожь: 0, стоп: false, есть: false };

  function тела() {
    try { return (МИР && МИР.тела && МИР.тела()) || []; } catch (е) { return []; }
  }
  function случ(a) { return (Math.random() - 0.5) * 2 * a; }

  /* Тело помнит, где его дом и как медленно оно вращалось до игры:
     после любой выходки оно должно вернуться к прежнему виду. */
  function завести(т) {
    if (т.дом) return т;
    т.дом = { x: т.x, y: т.y, z: т.z };
    т.vx = т.vy = т.vz = 0;
    т.рот0 = т.своёСкор || 0;
    if (т.масш == null) т.масш = 1;
    return т;
  }
  function завестиВсех() { тела().forEach(завести); }

  /* ═════════════════════════════════════════════════════════════════════
     ШАГ. Один на кадр, зовёт его мир из своего круга отрисовки.

     Своего requestAnimationFrame у игры нет нарочно: два круга на одной
     странице — это два разных «сейчас», и кубы в них дрожат.
     ═════════════════════════════════════════════════════════════════════ */
  CW.игра = {};

  CW.игра.шаг = function () {
    if (!идёт) return;
    var о = тела();
    if (!о.length) return;

    var Т = ПОЛЕ.тяга, М = ПОЛЕ.магнит;

    стукнули = 0;

    for (var i = 0; i < о.length; i++) {
      var a = завести(о[i]);

      /* Куб в руке двигает палец, а не поле: иначе он вырывается. */
      if (a === вруках) { a.vx = a.vy = a.vz = 0; }
      else if (ПОЛЕ.стоп) { a.vx = a.vy = a.vz = 0; }
      else {
        a.vx += Т.x; a.vy += Т.y; a.vz += Т.z;

        /* Магнит тянет к середине, но у самой середины — отталкивает.
           Без этого кубы за секунду слипались в один ком и так и
           стояли: смотреть не на что и попасть пальцем не во что.
           Теперь они собираются в живой рой и крутятся вокруг. */
        if (М) {
          var д = Math.sqrt(a.x * a.x + a.y * a.y + a.z * a.z) || 1;
          var ЯДРО = 130;                 /* ближе — отталкивает */
          var k = (д > ЯДРО) ? М / Math.max(60, д) : -М * 0.22 / Math.max(50, д);
          a.vx -= a.x * k; a.vy -= a.y * k; a.vz -= a.z * k;
          /* Лёгкая закрутка вокруг середины: рой живой, а не дрожащий. */
          a.vx += -a.z * 0.0022; a.vz += a.x * 0.0022;
          /* И гасим разгон: без этого рой за минуту раскручивается до
             мельтешения, в котором пальцем уже не попасть. */
          a.vx *= 0.975; a.vy *= 0.975; a.vz *= 0.975;
        }
        if (ПОЛЕ.вихрь) {
          a.vx += -a.z * ПОЛЕ.вихрь * 0.06;
          a.vz +=  a.x * ПОЛЕ.вихрь * 0.06;
          a.своёСкор += 0.0008;
        }
        /* Невесомость — это тяга, равная нулю. Но ровный ноль ниже
           считается покоем, и кубы тихо расползлись бы по домам: режим
           выглядел бы как «ничего не нажато». Поэтому вместо ноля —
           лёгкое дрожание воздуха, в среднем ноль. */
        if (ПОЛЕ.дрожь) {
          a.vx += случ(ПОЛЕ.дрожь); a.vy += случ(ПОЛЕ.дрожь); a.vz += случ(ПОЛЕ.дрожь);
        }

        a.x += a.vx; a.y += a.vy; a.z += a.vz;
        a.vx *= ТРЕНИЕ; a.vy *= ТРЕНИЕ; a.vz *= ТРЕНИЕ;
      }

      /* Стены. Куб не просто останавливается — отскакивает и теряет
         часть хода, иначе всё быстро слипается по углам. */
      var r = (a.размер || 60) / 2;
      ['x', 'y', 'z'].forEach(function (ось) {
        var предел = СТЕНА[ось] - r;
        if (a[ось] > предел) {
          a[ось] = предел; a['v' + ось] = -a['v' + ось] * ОТСКОК; a.своёСкор += 0.0008;
        } else if (a[ось] < -предел) {
          a[ось] = -предел; a['v' + ось] = -a['v' + ось] * ОТСКОК; a.своёСкор -= 0.0008;
        }
      });

      /* Куб о куб: расталкиваем, чтобы не слипались в одну точку.
         Точная физика тут не нужна — нужно, чтобы выглядело живо. */
      for (var j = i + 1; j < о.length; j++) {
        var b = завести(о[j]);
        var dx = b.x - a.x, dy = b.y - a.y, dz = b.z - a.z;
        var д2 = dx * dx + dy * dy + dz * dz;
        var мин = ((a.размер || 60) + (b.размер || 60)) * 0.46;
        if (д2 > 1e-6 && д2 < мин * мин) {
          var р = Math.sqrt(д2);
          var лишку = (мин - р) / 2;
          var nx = dx / р, ny = dy / р, nz = dz / р;
          a.x -= nx * лишку; a.y -= ny * лишку; a.z -= nz * лишку;
          b.x += nx * лишку; b.y += ny * лишку; b.z += nz * лишку;
          var отн = (b.vx - a.vx) * nx + (b.vy - a.vy) * ny + (b.vz - a.vz) * nz;
          if (отн < 0) {
            var и = отн * ОТСКОК;
            a.vx += nx * и; a.vy += ny * и; a.vz += nz * и;
            b.vx -= nx * и; b.vy -= ny * и; b.vz -= nz * и;
          }
          /* Куб, который ведут пальцем, расталкивает соседей сам: его
             скорость ноль, и обычный расчёт удара их бы не тронул. */
          if (a === вруках || b === вруках) {
            var ж = (a === вруках) ? b : a;
            var зн = (a === вруках) ? 1 : -1;
            ж.vx += nx * 3.2 * зн; ж.vy += ny * 3.2 * зн; ж.vz += nz * 3.2 * зн;
            ж.своёСкор += 0.01;
            стукнули++;
          }
        }
      }

      /* Раскрут держим в узде и плавно возвращаем к прежнему: без
         потолка кубы за полминуты превращаются в мельтешение. */
      var раз = (a.своёСкор || 0) - (a.рот0 || 0);
      if (раз > 0.12) a.своёСкор = a.рот0 + 0.12;
      else if (раз < -0.12) a.своёСкор = a.рот0 - 0.12;
      a.своёСкор = a.своёСкор * 0.985 + (a.рот0 || 0) * 0.015;
    }

    /* Улетели — сами вернутся. Пока кубы летят, их никто не трогает:
       удар должен донести их до стены. Но как только разлёт утих, по
       домам их тянет заметно, а не еле-еле: человек ударил, посмотрел,
       как они разлетелись, и ждёт, что мир снова соберётся.
       Тяга мягкая, кубы остаются живыми и ловятся пальцем всю дорогу. */
    if (доПокоя > 0) доПокоя--;
    else if (!ПОЛЕ.есть) {
      /* Каждый куб возвращается сам по себе, как только уймётся. Раньше
         ждали, пока утихнут все разом: один шустрый куб держал дома
         остальные шесть, и мир собирался полминуты. */
      for (var k = 0; k < о.length; k++) {
        var c = о[k];
        if (c === вруках || !c.дом) continue;
        if (Math.abs(c.vx) + Math.abs(c.vy) + Math.abs(c.vz) > 2.2) continue;
        c.vx += (c.дом.x - c.x) * 0.03;
        c.vy += (c.дом.y - c.y) * 0.03;
        c.vz += (c.дом.z - c.z) * 0.03;
        c.vx *= 0.93; c.vy *= 0.93; c.vz *= 0.93;
      }
    }
  };

