/* ═══════════════════════════════════════════════════════════════════════
   ИГРА С КУБАМИ: ФИЗИКА ВНУТРИ СТЕН И ДВАДЦАТЬ ДЕЙСТВИЙ.

   Кубы на карте перестают просто висеть: у каждого появляется скорость,
   и они летают внутри коробки, отскакивая от её стен — выйти нельзя.

       CW.игра.мир({ тела: function () { return М.тела; } });   мир зовёт раз
       CW.игра.шаг();                        мир зовёт каждый кадр
       CW.игра.сделать('взрыв');             окно зовёт по нажатию

   ── Почему физика здесь, а не в мире ───────────────────────────────
   Мир умеет одно: расставить кубы и нарисовать их. Он не должен знать
   ни про взрывы, ни про вихрь, ни про жесты рукой. Поэтому игра живёт
   отдельным куском и трогает у мира ровно три числа каждого тела — x,
   y, z — и скорость вращения. Выключили игру — мир об этом даже не
   узнает: тела просто перестанут двигаться.

   ── Два рода действий, и это главное ───────────────────────────────
   ТОЛЧКИ — взрыв, броски, подбросить, фейерверк, хаос, карусель, волна,
   хоровод, сальто, прыжки, бумеранг, пузыри. Разовые: дали скорость и
   отпустили. Ничего не включают и работают поверх любого режима.

   РЕЖИМЫ — держатся, пока их не снимут, и складываются:
       тяжесть    «Уронить» или «Невесомость» — одно из двух;
       «Магнит» и «Вихрь» — сами по себе, можно вместе и с тяжестью;
       «Заморозка» — включается одна и гасит остальные.

   «По местам» снимает всё и возвращает кубы по домам.

   Ради этого и заведено общее ПОЛЕ: несколько включённых режимов
   складываются в одну тягу, один магнит, один вихрь. Если бы каждое
   действие писало тягу себе, они вытесняли бы друг друга — и
   «выключенный» магнит продолжал бы тянуть.
   ═══════════════════════════════════════════════════════════════════════ */
