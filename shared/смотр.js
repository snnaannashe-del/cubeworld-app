/* ═══════════════════════════════════════════════════════════════════════
   ОКНО ПРОСМОТРА — СНИМОК И РОЛИК ВО ВЕСЬ ЭКРАН.
   /home/claude/новое/cubeworld-app/shared/смотр.js

       CW.смотреть(адрес, { вид: 'image' | 'video', имя: 'кот.jpg' })

   ── ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ ───────────────────────────────────────────
   Смотреть присланное нужно из переписки, из группы, из избранного и
   из поиска по переписке. Прежде этого не умел никто: пузырь звал
   CW.смотреть(), а такой функции в программе не было вовсе, и снимок
   молча уезжал новой вкладкой браузера. Вкладка - это уход из
   программы: человек возвращается назад и оказывается в начале
   переписки.

   ── ЧТО ЗДЕСЬ ЕСТЬ ─────────────────────────────────────────────────
       снимок    во весь экран, вписан целиком, по нажатию приближается
       ролик     во весь экран, со своими кнопками, играет сразу
       выход     крестик, нажатие мимо, Escape
       скачать   ссылка на сам файл, обычной кнопкой

   ── ЧЕГО ЗДЕСЬ НЕТ ─────────────────────────────────────────────────
   Пролистывания соседних снимков стрелками. Для этого окну нужен весь
   список вложений переписки, а он живёт не здесь. Обещать стрелки и
   не дать их было бы хуже, чем не рисовать их вовсе.

   ── ПОЧЕМУ НЕ ОБЫЧНОЕ ОКНО ─────────────────────────────────────────
   У нас окна 8,5 см шириной. Снимок в таком окне - это тот же снимок,
   что и в пузыре, только с крестиком. Смотрят во весь экран, поэтому
   здесь своя подложка во весь экран, а не CW.модалка.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  var ОТКРЫТО = null;

  function э(тег, класс) {
    var у = документ.createElement(тег);
    if (класс) у.className = класс;
    return у;
  }

  CW.закрытьСмотр = function () {
    if (!ОТКРЫТО) return;
    var п = ОТКРЫТО;
    ОТКРЫТО = null;
    документ.removeEventListener('keydown', поКлавише, true);
    /* Ролик глушим до того, как убрали узел: брошенное играть видео
       слышно на всей странице, и человек ищет, откуда звук. */
    var в = п.querySelector('video');
    if (в) { try { в.pause(); } catch (е) {} }
    п.classList.remove('видно');
    окно.setTimeout(function () {
      if (п.parentNode) п.parentNode.removeChild(п);
    }, 160);
  };

  function поКлавише(е) {
    if (е.key !== 'Escape') return;
    /* Гасим событие: окно переписки под нами тоже закрывается по
       Escape, и одно нажатие убрало бы оба. */
    е.stopPropagation();
    е.preventDefault();
    CW.закрытьСмотр();
  }

  CW.смотреть = function (адрес, н) {
    н = н || {};
    if (!адрес) return null;
    CW.закрытьСмотр();

    var вид = н.вид || (/\.(mp4|mov|webm|mkv|m4v)(\?|$)/i.test(адрес) ? 'video' : 'image');

    var подложка = э('div', 'см-подложка');
    var рама = э('div', 'см-рама');

    var кадр;
    if (вид === 'video') {
      кадр = документ.createElement('video');
      кадр.src = адрес;
      кадр.controls = true;
      кадр.playsInline = true;
      кадр.autoplay = true;
      кадр.className = 'см-кадр';
    } else {
      кадр = документ.createElement('img');
      кадр.src = адрес;
      кадр.alt = н.имя || '';
      кадр.className = 'см-кадр';
      /* Нажал на снимок - он вырос до своего настоящего размера и
         стал листаться колесом и пальцем. Нажал ещё раз - вернулся.
         Это весь зум, который нужен, чтобы разглядеть подпись на
         чеке или лицо на дальнем плане. */
      кадр.addEventListener('click', function (е) {
        е.stopPropagation();
        рама.classList.toggle('крупно');
      });
    }

    var верх = э('div', 'см-верх');
    var имя = э('div', 'см-имя');
    имя.textContent = н.имя || '';
    верх.appendChild(имя);

    var скачать = документ.createElement('a');
    скачать.className = 'см-кн';
    скачать.href = адрес;
    скачать.download = н.имя || '';
    скачать.target = '_blank';
    скачать.rel = 'noopener';
    скачать.title = 'Сохранить себе';
    скачать.innerHTML = CW.значок('скачать', 17) || '';
    скачать.onclick = function (е) { е.stopPropagation(); };
    верх.appendChild(скачать);

    var крест = э('button', 'см-кн');
    крест.type = 'button';
    крест.title = 'Закрыть';
    крест.innerHTML = CW.рисунок
      ? CW.рисунок('M6 6 18 18M18 6 6 18')
      : CW.значок('крест', 17);
    крест.onclick = function (е) { е.stopPropagation(); CW.закрытьСмотр(); };
    верх.appendChild(крест);

    рама.appendChild(кадр);
    подложка.appendChild(верх);
    подложка.appendChild(рама);

    /* Нажатие мимо кадра закрывает - так выходят из всех наших окон. */
    подложка.addEventListener('click', function (е) {
      if (е.target === подложка || е.target === рама) CW.закрытьСмотр();
    });

    документ.body.appendChild(подложка);
    ОТКРЫТО = подложка;
    документ.addEventListener('keydown', поКлавише, true);
    /* Подложка появляется не рывком: класс вешаем следующим кадром,
       иначе переход не успевает начаться. */
    окно.requestAnimationFrame(function () { подложка.classList.add('видно'); });
    return подложка;
  };

})(window, document);
