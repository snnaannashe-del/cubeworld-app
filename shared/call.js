/* ═══════════════════════════════════════════════════════════════════════
   ЗВОНОК. Одна механика на аудио и видео.

   Разного у них ровно три вещи: просить ли камеру, показывать ли
   картинку и как выглядит окно, пока никто не ответил. Всё остальное —
   кто собеседник, сколько идёт разговор, выключить микрофон, сменить
   камеру, положить трубку — одно и то же. Поэтому здесь, а не дважды.

       CW.звонок({ видео:true, кто:7, имя:'Пётр', назад:fn });

   ── ЧТО ЗДЕСЬ, А ЧТО РЯДОМ ──────────────────────────────────────────

   Здесь ОКНО: микрофон, камера, своё лицо, чужие лица, время разговора,
   кнопки и трубка. Само соединение — в shared/звонки.js: кто кому
   звонит, как они обмениваются адресами и кто кладёт трубку первым.

   Разделены они нарочно. Окно одинаково для личного и группового
   звонка, для аудио и видео; соединений же может быть несколько сразу
   (в группе каждый соединён с каждым), и мешать это с кнопками значит
   не починить потом ни то, ни другое.

       var З = CW.звонок({ видео, кто, имя, лицо, назад });
       З.готов.then(…)        свой микрофон и камера открыты
       З.поток()              свой поток — его отдают соединению
       З.состояние('звоню…')  строка под именем
       З.чужой(ид, поток, имя) показать того, кто ответил
       З.убрать(ид)           он положил трубку
       З.пошёл()              пошло время разговора
       З.наТрубку(fn)         человек нажал отбой

   ЧЕСТНО О TURN. Браузеры соединяются напрямую, и у большинства это
   выходит: адреса подбирает STUN. Но у части домашних и почти у всех
   корпоративных сетей прямой путь закрыт — там нужен сервер-ретранслятор
   (TURN), а его у нас нет: он стоит денег и живёт отдельно от сервера.
   В таких сетях звонок честно скажет «соединение не установилось», а не
   будет вечно «соединяю…».
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  function э(тег, класс, текст) { return CW.эл(тег, класс, текст); }

  CW.звонок = function (н) {
    н = н || {};
    var видео = !!н.видео;

    var С = {
      поток: null,          /* свой микрофон и камера */
      начали: 0,            /* когда пошёл разговор */
      часы: null,
      микрофон: true,
      камера: видео,
      громко: true,
      камеры: [],           /* какие камеры есть на устройстве */
      какая: 0
    };

    var ОКНО = CW.стойка({
      имя: видео ? 'видеозвонок' : 'звонок',
      память: { кто: н.кто },
      кружок: { снимок: н.лицо },
      заголовок: н.имя || ('#' + (н.кто || '')),
      подзаголовок: Т('готовлю…'),
      назад: положить,
      поля: false
    });
    ОКНО.открыть();

    /* ── что видно ──────────────────────────────────────────────── */
    var экран = э('div', 'зв-экран' + (видео ? ' видео' : ' аудио'));
    ОКНО.тело.appendChild(экран);

    var картинка = null;
    if (видео) {
      картинка = э('video', 'зв-я');
      картинка.muted = true;         /* себя не слушаем — будет свист */
      картинка.playsInline = true;
      картинка.autoplay = true;
      экран.appendChild(картинка);
    }

    /* Чужие — сеткой. В личном звонке он один, в групповом их сколько
       угодно; одна и та же сетка и там, и там, чтобы не держать двух
       разных экранов разговора. */
    var чужие = э('div', 'зв-чужие');
    экран.appendChild(чужие);
    var ЧУЖИЕ = {};        /* ид → {узел, видео, поток} */

    var лицо = э('div', 'зв-лицо');
    лицо.appendChild(CW.кружок({ размер: 112, кто: н.кто, снимок: н.лицо,
                                 }));
    лицо.appendChild(э('div', 'имя', н.имя || ('#' + (н.кто || ''))));
    var состояние = э('div', 'что', Т('готовлю…'));
    лицо.appendChild(состояние);
    экран.appendChild(лицо);

    var время = э('div', 'зв-время');
    экран.appendChild(время);

    /* ── кнопки ──────────────────────────────────────────────────
       ── ПОЧЕМУ ОНИ В ШАПКЕ, А НЕ ВНИЗУ ──
       Анна: «кнопки с нижнего меню переместить в правый верхний угол
       вместо стрелочки». На её снимке видно почему: внизу экрана
       телефона стоит полоса браузера, и ряд кнопок жался вплотную над
       ней - промахнуться мимо трубки было легче, чем попасть.

       Стрелку убираем совсем: выход из звонка теперь один - трубка.
       Это не только порядок на экране. Стрелка уводила со страницы, и
       пока она была, из звонка выходили ею: второй стороне не уходило
       «я положил», а в переписке не оставалось пометки о звонке - в
       группе после разговора не появлялось вообще ничего.

       Само поведение «назад» у окна остаётся прежним: кнопка «назад»
       телефона и клавиша Esc кладут трубку (назад: положить выше), а
       уход со страницы любым другим способом ловит shared/звонки.js. */
    var ряд = ОКНО.шапка && ОКНО.шапка.querySelector('.ок-ряд');
    if (ряд) {
      ряд.classList.add('зв-вшапке');
      var стрелка = ОКНО.шапка.querySelector('.ок-кн.выход');
      if (стрелка) стрелка.style.display = 'none';
    } else {
      ряд = э('div', 'зв-кнопки');      /* окна без шапки: ряд внизу */
      ОКНО.снизу(ряд);
    }

    var кнМикрофон = кнопка('микрофон', Т('Микрофон'), function () {
      С.микрофон = !С.микрофон;
      дорожки('audio').forEach(function (д) { д.enabled = С.микрофон; });
      кнМикрофон.classList.toggle('выкл', !С.микрофон);
      кнМикрофон.innerHTML = CW.значок(С.микрофон ? 'микрофон' : 'тихо');
      CW.сказать(Т(С.микрофон ? 'Микрофон включён' : 'Микрофон выключен'));
    });

    var кнКамера = null;
    if (видео) {
      кнКамера = кнопка('камера', Т('Камера'), function () {
        С.камера = !С.камера;
        дорожки('video').forEach(function (д) { д.enabled = С.камера; });
        кнКамера.classList.toggle('выкл', !С.камера);
        экран.classList.toggle('без-камеры', !С.камера);
      });
    }

    var кнЗвук = кнопка(видео ? 'повтор' : 'звук',
                        Т(видео ? 'Другая камера' : 'Громкая связь'),
                        function () {
      if (видео) { сменитьКамеру(); return; }
      С.громко = !С.громко;
      кнЗвук.classList.toggle('выкл', !С.громко);
      /* Браузер не даёт выбирать динамик без разрешения на устройства
         вывода, и на телефоне этого нет вовсе. Честно говорим. */
      CW.сказать(Т(С.громко ? 'Громкая связь' : 'Через трубку'));
    });

    var кнТрубка = кнопка(null, Т('Положить трубку'), положить);
    кнТрубка.classList.add('трубка');
    кнТрубка.innerHTML = CW.рисунок(
      'M3.5 9.5c5-4 11.5-4 16.5 0l1.5 1.5-3 3-2-1.5v-2.5c-3-1.5-6.5-1.5-9.5 0v2.5l-2 1.5-3-3z');

    ряд.appendChild(кнМикрофон);
    if (кнКамера) ряд.appendChild(кнКамера);
    ряд.appendChild(кнЗвук);
    ряд.appendChild(кнТрубка);

    function кнопка(знак, подсказка, делать) {
      var б = э('button', 'зв-кн');
      б.type = 'button';
      б.title = подсказка;
      if (знак) б.innerHTML = CW.значок(знак);
      б.onclick = делать;
      return б;
    }

    /* ── микрофон и камера ──────────────────────────────────────── */
    var сказатьГотов = null, сказатьБеду = null;
    var готов = new Promise(function (д, б) { сказатьГотов = д; сказатьБеду = б; });
    просить();

    function просить() {
      if (!окно.navigator.mediaDevices || !окно.navigator.mediaDevices.getUserMedia) {
        сказатьСостояние('Этот браузер не умеет звонить');
        return;
      }
      сказатьСостояние(видео ? 'прошу камеру и микрофон…' : 'прошу микрофон…');

      окно.navigator.mediaDevices.getUserMedia({
        audio: true,
        video: видео ? { facingMode: 'user' } : false
      }).then(function (поток) {
        С.поток = поток;
        if (картинка) картинка.srcObject = поток;
        собратьКамеры();
        сказатьСостояние(н.ждать || '');
        ОКНО.имя(null, видео ? Т('видеозвонок') : Т('звонок'));
        сказатьГотов(поток);
      }).catch(function (е) {
        /* Отказ в доступе и отсутствие устройства — разные беды, и
           человеку надо сказать, какая именно: в одном случае он
           поменяет разрешение, в другом воткнёт наушники. */
        var имя = (е && е.name) || '';
        сказатьСостояние(
          имя === 'NotAllowedError'  ? (видео ? 'Камеру и микрофон не дали'
                                              : 'Микрофон не дали')
        : имя === 'NotFoundError'    ? (видео ? 'Камеры или микрофона нет'
                                              : 'Микрофона нет')
        : имя === 'NotReadableError' ? 'Устройство занято другой программой'
        : 'Не вышло открыть микрофон');
        ОКНО.имя(null, Т('не получилось'));
        сказатьБеду(е);
      });
    }

    function собратьКамеры() {
      if (!видео || !окно.navigator.mediaDevices.enumerateDevices) return;
      окно.navigator.mediaDevices.enumerateDevices().then(function (все) {
        С.камеры = все.filter(function (у) { return у.kind === 'videoinput'; });
        if (кнЗвук) кнЗвук.disabled = С.камеры.length < 2;
      }).catch(function () {});
    }

    function сменитьКамеру() {
      if (С.камеры.length < 2) { CW.сказать(Т('Вторая камера не нашлась')); return; }
      С.какая = (С.какая + 1) % С.камеры.length;
      var ид = С.камеры[С.какая].deviceId;
      окно.navigator.mediaDevices.getUserMedia({
        audio: true, video: { deviceId: { exact: ид } }
      }).then(function (новый) {
        закрытьПоток();
        С.поток = новый;
        if (картинка) картинка.srcObject = новый;
        CW.сказать(Т('Камера переключена'));
      }).catch(function () { CW.сказать(Т('Эта камера не открылась')); });
    }

    function дорожки(вид) {
      if (!С.поток) return [];
      return вид === 'audio' ? С.поток.getAudioTracks() : С.поток.getVideoTracks();
    }

    /* ── ВТОРАЯ СТОРОНА ──
       Поток чужого приходит из shared/звонки.js, когда соединение
       встало. Своё лицо при этом уходит в угол: разговаривают с тем,
       кто на экране, а не с собой. */
    function чужой(ид, поток, имя) {
      ид = String(ид);
      var ч = ЧУЖИЕ[ид];
      if (!ч) {
        var узел = э('div', 'зв-чужой');
        var в = э('video');
        в.autoplay = true; в.playsInline = true;
        /* Звук чужого играем ВСЕГДА, даже в аудиозвонке: там тот же
           элемент, просто его не видно. Отдельного <audio> не заводим —
           два пути для одного потока однажды разойдутся. */
        узел.appendChild(в);
        узел.appendChild(э('div', 'подпись', имя || ('#' + ид)));
        чужие.appendChild(узел);
        ч = ЧУЖИЕ[ид] = { узел: узел, видео: в };
      }
      ч.видео.srcObject = поток;
      var пуск = ч.видео.play();
      if (пуск && пуск.catch) пуск.catch(function () {});
      экран.classList.add('есть-чужой');
      экран.classList.toggle('многие', Object.keys(ЧУЖИЕ).length > 1);
      сказатьСостояние('');
      return ч;
    }

    function убрать(ид) {
      var ч = ЧУЖИЕ[String(ид)];
      if (!ч) return;
      if (ч.узел.parentNode) ч.узел.parentNode.removeChild(ч.узел);
      delete ЧУЖИЕ[String(ид)];
      var сколько = Object.keys(ЧУЖИЕ).length;
      экран.classList.toggle('есть-чужой', сколько > 0);
      экран.classList.toggle('многие', сколько > 1);
      return сколько;
    }

    /* Счётчик времени готов и ждёт своего часа: когда соединение
       появится, пойдёт отсюда. Ноль на экране не держим — ноль
       выглядит как сломанный разговор. */
    function пошёл() {
      С.начали = Date.now();
      тик();
      С.часы = setInterval(тик, 1000);
    }

    function тик() {
      var сек = Math.floor((Date.now() - С.начали) / 1000);
      var м = Math.floor(сек / 60), с = сек % 60;
      время.textContent = м + ':' + (с < 10 ? '0' : '') + с;
    }

    function сказатьСостояние(что) {
      состояние.textContent = что || '';
      состояние.style.display = что ? '' : 'none';
    }

    /* ── конец ──────────────────────────────────────────────────── */
    function закрытьПоток() {
      if (!С.поток) return;
      С.поток.getTracks().forEach(function (д) { try { д.stop(); } catch (е) {} });
      С.поток = null;
    }

    var наТрубку = [];
    function положить() {
      /* Камеру и микрофон отпускаем ОБЯЗАТЕЛЬНО. Не отпустишь — на маке
         остаётся гореть зелёный огонёк, и человек справедливо решает,
         что программа за ним подсматривает. */
      наТрубку.forEach(function (ф) { try { ф(); } catch (е) {} });
      наТрубку = [];
      закрытьПоток();
      clearInterval(С.часы);
      ОКНО.закрыть();
      if (н.назад) н.назад();
    }

    /* Страницу закрыли крестиком браузера — тот же разговор про
       огонёк. Вешаем на оба события: pagehide ловит телефон, где
       beforeunload часто не срабатывает вовсе. */
    окно.addEventListener('beforeunload', закрытьПоток);
    окно.addEventListener('pagehide', закрытьПоток);

    return {
      окно: ОКНО,
      готов: готов,
      поток: function () { return С.поток; },
      состояние: сказатьСостояние,
      чужой: чужой,
      убрать: убрать,
      сколькоЧужих: function () { return Object.keys(ЧУЖИЕ).length; },
      пошёл: пошёл,
      идёт: function () { return !!С.начали; },
      наТрубку: function (ф) { наТрубку.push(ф); },
      положить: положить
    };
  };

})(window, document);
