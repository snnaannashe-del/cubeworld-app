/* ═══════════════════════════════════════════════════════════════════════
   ПЕРЕВОД СООБЩЕНИЯ.
   /home/claude/новое/cubeworld-app/shared/перевод.js

       CW.перевод.языки                  список языков для полки
       CW.перевод.можно()                умеет ли браузер переводить
       CW.перевод.сделать(текст, 'en')   → обещание со строкой

   ── ЧЕМ ПЕРЕВОДИМ ──
   Своим переводчиком браузера. В Chrome есть встроенный: он работает
   на самом устройстве, не отправляет текст никуда и не требует ключей.
   Это важнее удобства: переписка — частное дело, и возить её через
   чужую контору ради «перевести» мы не будем.

   Первый перевод на новую пару языков браузер может скачивать —
   несколько секунд и десяток мегабайт. Поэтому об ожидании говорим
   вслух, а не молчим с пустым окном.

   Браузер не умеет (старый Chrome, Safari, Firefox) — честно говорим
   это одной строкой. Отправлять текст на чужой сервер вместо этого
   нельзя: см. выше.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  /* Десять языков: те, на которые и правда переводят в переписке. */
  var ЯЗЫКИ = [
    { к: 'en', имя: 'Английский' },
    { к: 'ru', имя: 'Русский' },
    { к: 'uk', имя: 'Украинский' },
    { к: 'es', имя: 'Испанский' },
    { к: 'de', имя: 'Немецкий' },
    { к: 'fr', имя: 'Французский' },
    { к: 'it', имя: 'Итальянский' },
    { к: 'tr', имя: 'Турецкий' },
    { к: 'zh', имя: 'Китайский' },
    { к: 'ar', имя: 'Арабский' }
  ];

  function переводчикЕсть() {
    return !!(окно.Translator && окно.Translator.create)
        || !!(окно.translation && окно.translation.createTranslator);
  }

  /* Откуда переводим. Сперва спрашиваем определитель языка браузера,
     а если его нет — смотрим на буквы: кириллица это русский (или
     украинский, но для переводчика разница невелика), иначе
     английский. Ошибиться здесь не страшно: переводчик всё равно
     разберётся, а пустое поле «откуда» он не принимает. */
  function откуда(текст) {
    var запас = /[Ѐ-ӿ]/.test(текст) ? 'ru' : 'en';
    var О = окно.LanguageDetector || (окно.translation && окно.translation.createDetector
            ? { create: окно.translation.createDetector } : null);
    if (!О || !О.create) return Promise.resolve(запас);
    return О.create().then(function (д) {
      return д.detect(текст.slice(0, 400));
    }).then(function (сп) {
      var п = сп && сп[0] && сп[0].detectedLanguage;
      return (п && п.slice(0, 2)) || запас;
    }).catch(function () { return запас; });
  }

  function завести(из, в) {
    if (окно.Translator && окно.Translator.create) {
      return окно.Translator.create({ sourceLanguage: из, targetLanguage: в });
    }
    return окно.translation.createTranslator({ sourceLanguage: из, targetLanguage: в });
  }

  function сделать(текст, язык) {
    var т = String(текст == null ? '' : текст).trim();
    if (!т) return Promise.reject(new Error(Т('Переводить нечего')));
    if (!переводчикЕсть()) {
      /* Фраза целиком одним ключом. Прежде она была склеена из двух:
         первая половина переводилась, вторая оставалась русской — и в
         английском окне человек читал полрусской строки. */
      return Promise.reject(new Error(Т('Этот браузер не умеет переводить сам. '
        + 'В Chrome это есть; слать переписку на чужой сервер мы не будем.')));
    }
    return откуда(т).then(function (из) {
      if (из === язык) {
        throw new Error(Т.с('Это уже {язык}',
                            { язык: имяЯзыка(язык).toLowerCase() }));
      }
      return завести(из, язык);
    }).then(function (п) {
      return п.translate(т);
    });
  }

  /* Имя языка — надпись на экране, значит через машинку. Раньше
     список языков перевода стоял по-русски даже в английском окне. */
  function имяЯзыка(к) {
    for (var i = 0; i < ЯЗЫКИ.length; i++)
      if (ЯЗЫКИ[i].к === к) return (окно.Т ? окно.Т(ЯЗЫКИ[i].имя) : ЯЗЫКИ[i].имя);
    return к;
  }

  CW.перевод = {
    языки: ЯЗЫКИ,
    можно: переводчикЕсть,
    сделать: сделать,
    имя: имяЯзыка
  };
})(window);
