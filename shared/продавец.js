/* ═══════════════════════════════════════════════════════════════════════
   КАРТОЧКА ПРОДАВЦА: РЕЙТИНГ, СДЕЛКИ, ОТЗЫВЫ.
   /home/claude/новое/cubeworld-app/shared/продавец.js

       CW.продавец.привязать(узел, номер)   навёл — выехала карточка
       CW.продавец.окно(номер)              полное окно с отзывами
       CW.продавец.звёзды(4.5)              разметка пяти звёзд
       CW.продавец.сводка(номер)            обещание со сводкой

   ── ЗАЧЕМ ──────────────────────────────────────────────────────────
   Человек видит имя продавца и не знает о нём ничего: сколько у того
   было сделок, доволен ли был кто-то до него. Покупать вслепую никто
   не любит.

   Поэтому имя продавца становится дверью. Навёл мышь — через треть
   секунды выехала маленькая карточка: звёзды, сколько сделок, сколько
   довольных и недовольных, с какого дня человек на площадке. Нажал —
   открылось окно со всеми отзывами и своей оценкой.

   ── ОТКУДА ЧИСЛА ───────────────────────────────────────────────────
   Всё с сервера и всё настоящее. Сделки считаются по заказам, а не со
   слов продавца. Отзыв оставляет только тот, кто у него покупал, и
   только один: второй раз — правка прежнего. Накрутить вечером рейтинг
   не выйдет.

   ── ДВА РАЗДЕЛА: ТОВАРЫ И СИГНАЛЫ ──────────────────────────────────
   Один человек может и продавать товары, и выкладывать платные
   сигналы. Это два разных дела, и одно число на двоих врёт: отличный
   продавец фотографий бывает никаким автором сигналов, а общая
   «четыре с половиной» об этом не скажет.

   Поэтому в карточке две строки, а в окне две полки, и у каждой свои
   числа, свои отзывы и своя оценка:

       Маркет   звёзды · сделки (цифровой маркет + магазин)
       Сигналы  звёзды · подписки · живые подписчики · точность

   Оценить можно только тот раздел, где была сделка. Купил товар —
   говоришь о товарах; брал сигналы — о сигналах. Одно не открывает
   дверь в другое, и это написано словами, а не угадывается.

   ── ПОЧЕМУ КАРТОЧКА, А НЕ СТРАНИЦА ─────────────────────────────────
   Человек смотрит товар. Увести его на страницу продавца значит
   прервать это занятие. Карточка отвечает на вопрос «кто продаёт» там
   же, где вопрос возник, и исчезает, когда мышь ушла.

   На телефоне наведения нет, и ждать его бессмысленно: там нажатие
   сразу открывает полное окно.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  var ПАМЯТЬ = {};              /* номер → {когда, сводка} */
  var ЖИВЁТ = 120000;           /* две минуты: рейтинг меняется не каждую секунду */
  var ЖДЁМ = 320;               /* сколько держать мышь, чтобы выехала карточка */

  var КАРТОЧКА = null;          /* сейчас показанная */
  var ТАЙМЕР = null;

  /* ── ДВА РАЗДЕЛА ОДНИМ СПИСКОМ ──
     Всё, чем они отличаются, лежит здесь: название, значок, за что
     оценивают и чего ждать, если человек там ещё не работал. Ниже по
     файлу ни одного «если сигналы» с переписанными словами. */
  var ВИДЫ = [
    { ключ: 'market', имя: 'Маркет', знак: 'сумка',
      право: 'Оценить может тот, кто покупал у него товар.',
      пусто: 'Товары этот человек ещё не продавал.',
      оцени: 'Оцени продавца' },
    { ключ: 'signals', имя: 'Сигналы', знак: 'столбики',
      право: 'Оценить может тот, кто брал его платные сигналы.',
      пусто: 'Платные сигналы этот человек ещё не продавал.',
      оцени: 'Оцени автора сигналов' }
  ];

  function видом(ключ) {
    for (var i = 0; i < ВИДЫ.length; i++) if (ВИДЫ[i].ключ === ключ) return ВИДЫ[i];
    return ВИДЫ[0];
  }

  /* Сервер старой версии разделов не знает. Тогда считаем, что всё, что
     он прислал, относится к товарам: так было до этой правки. */
  function разделом(с, ключ) {
    var р = (с && с.разделы && с.разделы[ключ]) || null;
    if (р) return р;
    if (ключ === 'market') {
      return { отзывов: Number((с && с.отзывов) || 0),
               'звёзд': Number((с && с['звёзд']) || 0),
               плюсов: Number((с && с.плюсов) || 0),
               минусов: Number((с && с.минусов) || 0),
               сделок: Number((с && с.сделок) || 0),
               могу: !!(с && с['могу_оценить']),
               'моё': (с && с['мой_отзыв']) || null, старый: true };
    }
    return { отзывов: 0, 'звёзд': 0, плюсов: 0, минусов: 0, сделок: 0,
             подписок: 0, подписчиков: 0, сигналов: 0, закрыто: 0,
             точность: null, могу: false, 'моё': null, старый: true };
  }

  /* Есть ли в разделе хоть что-то, о чём стоит говорить. Пустая строка
     «Сигналы: 0 подписок, 0 отзывов» в карточке только мешает. */
  function живой(р) {
    return (Number(р.сделок) || 0) > 0 || (Number(р.отзывов) || 0) > 0
        || (Number(р.подписок) || 0) > 0 || (Number(р.сигналов) || 0) > 0;
  }

  function трогают() {
    return окно.matchMedia && окно.matchMedia('(hover: none)').matches;
  }

  /* ── ЗВЁЗДЫ ──
     Пять серых, поверх них золотые, обрезанные по доле. Так видно и
     4,5, и 3,8 — а не «четыре с чем-то». */
  function звезда(размер) {
    return '<svg viewBox="0 0 24 24" width="' + размер + '" height="' + размер
         + '" fill="currentColor"><path d="M12 3.4 14.6 9l6 .9-4.3 4.2 1 6'
         + '-5.3-2.8-5.3 2.8 1-6L3.4 9.9 9.4 9z"/></svg>';
  }

  function звёзды(сколько, размер) {
    размер = размер || 14;
    сколько = Math.max(0, Math.min(5, Number(сколько) || 0));
    var ряд = '';
    for (var i = 0; i < 5; i++) ряд += звезда(размер);
    return '<span class="оц-звёзды" style="--кегль:' + размер + 'px">'
         + '<span class="пусто">' + ряд + '</span>'
         + '<span class="полно" style="width:' + (сколько / 5 * 100) + '%">'
         + ряд + '</span></span>';
  }

  /* ── СВОДКА С СЕРВЕРА ──
     С памятью: на витрине десяток товаров одного продавца, и спрашивать
     сервер на каждое наведение незачем. */
  function сводка(номер, свежо) {
    номер = Number(номер) || 0;
    if (!номер) return Promise.reject(new Error('нет продавца'));
    var было = ПАМЯТЬ[номер];
    if (!свежо && было && (Date.now() - было.когда) < ЖИВЁТ) {
      return Promise.resolve(было.сводка);
    }
    /* «тихо» здесь НЕ ставим нарочно: молчаливый отказ превращался в
       «Рейтинг не приехал» без единого слова о том, почему. Беду ловим
       и объясняем словами — см. почему(). */
    return CW.спросить('/sellers/' + номер + '/rating', { сроком: 12000 })
      .then(function (о) {
        var с = (о && о.продавец) || null;
        if (с) ПАМЯТЬ[номер] = { когда: Date.now(), сводка: с };
        return с;
      });
  }

  /* ── ПОЧЕМУ НЕ ВЫШЛО ──
     Три разные беды выглядели одинаково, и понять было нечего.

     404 — сервер этой ручки не знает: на нём старая версия. Для
     хозяйки площадки это самый частый случай и самый важный: нужна
     выкладка сервера, а не починка окна. Так и пишем. */
  function почему(е) {
    if (!е) return 'Рейтинг не приехал';
    if (е.сеть) return 'Нет связи с сервером';
    if (е.код === 404) {
      return 'Сервер пока не умеет считать рейтинг, на нём старая версия. '
           + 'Рейтинг появится после выкладки сервера.';
    }
    if (е.код === 401) return 'Войди заново: ключ устарел';
    return (е.message || 'Рейтинг не приехал');
  }

  /* ═════════════════════════════════════════════════════════════════
     МАЛЕНЬКАЯ КАРТОЧКА
     ═════════════════════════════════════════════════════════════════ */
  function убрать() {
    clearTimeout(ТАЙМЕР);
    if (КАРТОЧКА && КАРТОЧКА.parentNode) КАРТОЧКА.parentNode.removeChild(КАРТОЧКА);
    КАРТОЧКА = null;
  }

  function карточка(узел, номер) {
    убрать();
    var к = документ.createElement('div');
    к.className = 'оц-карточка';
    к.innerHTML = '<div class="оц-ждём">Загрузка…</div>';
    документ.body.appendChild(к);
    КАРТОЧКА = к;
    поставить(к, узел);

    /* Мышь может уйти с имени НА карточку — это не «ушла». */
    к.addEventListener('mouseenter', function () { clearTimeout(ТАЙМЕР); });
    к.addEventListener('mouseleave', function () { ТАЙМЕР = setTimeout(убрать, 160); });

    сводка(номер).then(function (с) {
      if (КАРТОЧКА !== к) return;
      if (!с) { к.innerHTML = '<div class="оц-ждём">О продавце пока нечего сказать</div>';
                поставить(к, узел); return; }
      к.innerHTML = нутро(с);
      var б = к.querySelector('.оц-кн');
      if (б) б.onclick = function () { убрать(); окноПродавца(номер); };
      поставить(к, узел);
    }).catch(function (е) {
      if (КАРТОЧКА !== к) return;
      к.innerHTML = '<div class="оц-ждём">' + CW.безопасно(почему(е)) + '</div>';
      поставить(к, узел);
    });
    return к;
  }

  /* ── СТРОКА РАЗДЕЛА В КАРТОЧКЕ ──
     Название раздела, его звёзды и его числа: чтобы читалось не «4,6 у
     человека», а «4,6 за товары и 5,0 за сигналы». */
  function строкаРаздела(в, р) {
    var отзывов = Number(р.отзывов) || 0;
    var числа = [];
    if (в.ключ === 'market') {
      var сделок = Number(р.сделок) || 0;
      числа.push(сделок + словом(сделок, 'сделка', 'сделки', 'сделок'));
    } else {
      var подписок = Number(р.подписок) || Number(р.сделок) || 0;
      числа.push(подписок + словом(подписок, 'подписка', 'подписки', 'подписок'));
      /* В карточке «61%» без слова «точность»: слово не влезает рядом с
         подписками, а в окне оно подписано под числом полностью. */
      if (р.точность != null) числа.push(Number(р.точность) + '%');
      else if (Number(р.сигналов)) числа.push(Number(р.сигналов) + ' сигн.');
    }
    return '<div class="оц-раздел">'
      + '<span class="оц-ярлык">' + CW.значок(в.знак, 13)
      +   '<b>' + в.имя + '</b></span>'
      + '<span class="оц-оц">' + звёзды(р.звёзд, 12)
      +   '<span class="оц-число">' + (отзывов ? Number(р.звёзд).toFixed(1) : '-')
      +   '</span></span>'
      + '<span class="оц-мелко">' + CW.безопасно(числа.join(' · ')) + '</span>'
      + '</div>';
  }

  function нутро(с) {
    var отзывов = Number(с.отзывов) || 0;
    var строки = '';
    var было = 0;
    ВИДЫ.forEach(function (в) {
      var р = разделом(с, в.ключ);
      if (!живой(р)) return;
      было++;
      строки += строкаРаздела(в, р);
    });
    /* Ни товаров, ни сигналов: честно говорим это одной строкой, а не
       рисуем два нуля в красивых рамках. */
    if (!было) строки = '<div class="оц-мелко">Сделок пока не было</div>';

    return ''
      + '<div class="оц-верх">'
      +   '<span class="оц-лицо">' + лицом(с) + '</span>'
      +   '<span class="оц-имя">' + CW.безопасно(с.имя || ('Человек #' + с.user_id))
      +     '</span>'
      + '</div>'
      + '<div class="оц-оценка">' + звёзды(с.звёзд, 15)
      +   '<span class="оц-число">' + (отзывов ? (Number(с.звёзд).toFixed(1)) : '-')
      +   '</span>'
      +   '<span class="оц-мелко">' + отзывов
      +     словом(отзывов, 'отзыв', 'отзыва', 'отзывов') + ' всего</span>'
      + '</div>'
      + строки
      + (с.с_нами ? '<div class="оц-мелко">На площадке с ' + датой(с.с_нами) + '</div>' : '')
      + '<button type="button" class="оц-кн">'
      +   (отзывов ? 'Отзывы и оценка' : 'Оценить продавца') + '</button>';
  }

  function лицом(с) {
    var л = String(с.лицо || '');
    if (!л) return '<i class="оц-пусто">' + CW.значок('человек', 15) + '</i>';
    if (CW.картинкаЛи && CW.картинкаЛи(л)) {
      return '<img alt="" src="' + CW.безопасно(CW.файл(л)) + '">';
    }
    return '<i class="смайл-зн">' + CW.безопасно(л) + '</i>';
  }

  function словом(ч, один, пара, много) {
    ч = Math.abs(Number(ч) || 0);
    var д = ч % 100, е = ч % 10;
    var слово = (д > 10 && д < 20) ? много
              : (е === 1 ? один : (е >= 2 && е <= 4 ? пара : много));
    return ' ' + слово;
  }

  /* «с ноября 2026», а не «с ноябрь 2026 г.»: браузер отдаёт месяц в
     именительном падеже, и после предлога это звучит сломанно. */
  var МЕСЯЦЫ = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля',
                'августа', 'сентября', 'октября', 'ноября', 'декабря'];

  function датой(строка) {
    try {
      var д = new Date(String(строка).replace(' ', 'T') + 'Z');
      if (isNaN(д.getTime())) return String(строка).slice(0, 10);
      return МЕСЯЦЫ[д.getMonth()] + ' ' + д.getFullYear();
    } catch (е) { return String(строка).slice(0, 10); }
  }

  /* Карточка встаёт под именем, а если места внизу нет — над ним. И
     никогда не выезжает за край экрана: на узком окне это главное. */
  function поставить(к, узел) {
    var р = узел.getBoundingClientRect();
    var ш = к.offsetWidth || 230;
    var в = к.offsetHeight || 140;
    var поле = 10;
    var x = Math.min(Math.max(поле, р.left), окно.innerWidth - ш - поле);
    var y = р.bottom + 8;
    if (y + в > окно.innerHeight - поле) y = Math.max(поле, р.top - в - 8);
    к.style.left = Math.round(x) + 'px';
    к.style.top = Math.round(y) + 'px';
  }

  /* о.значок — узел уже кнопка со своим нажатием (звезда в шапке
     портфолио). Тогда ни подчёркивания, ни второго обработчика: своё
     нажатие у неё есть, от нас нужна только карточка при наведении. */
  function привязать(узел, номер, о) {
    if (!узел || !номер) return;
    о = о || {};
    узел.setAttribute('data-продавец', String(номер));

    if (!о.значок) {
      узел.classList.add('оц-дверь');
      узел.addEventListener('click', function (е) {
        е.preventDefault();
        е.stopPropagation();
        убрать();
        /* о.раздел — с какой полки открывать. Из витрины сигналов
           открываем сигналы, из маркета товары: человек нажал имя там,
           где смотрел, и ждёт разговора про то же самое. */
        окноПродавца(номер, { раздел: о.раздел });
      });
    } else {
      /* Своя кнопка открывает окно сама — карточку перед этим убираем,
         иначе она останется висеть поверх открытого окна. */
      узел.addEventListener('click', убрать);
    }

    if (трогают()) return;          /* на телефоне наведения нет */

    узел.addEventListener('mouseenter', function () {
      clearTimeout(ТАЙМЕР);
      ТАЙМЕР = setTimeout(function () { карточка(узел, номер); }, ЖДЁМ);
    });
    узел.addEventListener('mouseleave', function () {
      clearTimeout(ТАЙМЕР);
      ТАЙМЕР = setTimeout(убрать, 160);
    });
  }

  /* Прокрутка и уход со страницы карточку убирают: висящая в воздухе
     подсказка над уехавшим именем выглядит поломкой. */
  документ.addEventListener('scroll', убрать, true);
  окно.addEventListener('resize', убрать);


  /* ═════════════════════════════════════════════════════════════════
     ПОЛНОЕ ОКНО: ДВЕ ПОЛКИ, ОТЗЫВЫ И СВОЯ ОЦЕНКА

     Полка «Маркет» и полка «Сигналы» живут раздельно: свои числа,
     свои отзывы, своя оценка. Переключение не ходит на сервер заново
     за сводкой — она одна на оба раздела, — а отзывы берёт по разделу
     и держит у себя, чтобы второе нажатие было мгновенным.
     ═════════════════════════════════════════════════════════════════ */
  function окноПродавца(номер, о) {
    о = о || {};
    var М = CW.модалка({
      имя: 'продавец',
      знак: 'человек',
      заголовок: 'Продавец',
      подзаголовок: 'рейтинг и отзывы'
    });

    М.тело.innerHTML = '<div class="оц-ждём">Загрузка…</div>';
    М.открыть();

    var ГДЕ = видом(о.раздел === 'signals' || о.раздел === 'сигналы'
                    ? 'signals' : 'market').ключ;
    var МОИ = 0;                 /* сколько звёзд ставлю я в этом разделе */
    var СВОДКА = null;
    var ОТЗЫВЫ = {};             /* раздел → список, уже принесённый */

    начать();

    /* ── СВОДКА ──
       Одна на оба раздела: внутри неё лежат оба. Второй раз её тянем
       только после своей оценки, когда числа правда поменялись. */
    function начать(свежо) {
      if (свежо) ОТЗЫВЫ = {};
      сводка(номер, свежо).then(function (с) {
        СВОДКА = с;
        if (!СВОДКА) {
          М.тело.innerHTML = '<div class="оц-ждём">' + CW.безопасно(почему(null))
                           + '</div>';
          return;
        }
        М.шапку({
          знак: 'человек',
          заголовок: СВОДКА.имя || ('Человек #' + номер),
          подзаголовок: СВОДКА.с_нами ? ('на площадке с ' + датой(СВОДКА.с_нами)) : ''
        });
        /* Если человек ничего не продавал в том разделе, с которого нас
           просили начать, но работал в другом — показываем тот. Пустая
           полка первой выглядит как поломка. */
        if (!живой(разделом(СВОДКА, ГДЕ))) {
          ВИДЫ.forEach(function (в) {
            if (живой(разделом(СВОДКА, в.ключ))) ГДЕ = ГДЕ === в.ключ ? ГДЕ : в.ключ;
          });
        }
        каркас();
        полкой();
      }).catch(function (е) {
        М.тело.innerHTML = '<div class="оц-ждём">' + CW.безопасно(почему(е)) + '</div>';
      });
    }

    /* ── КАРКАС ──
       Полка с двумя кнопками и пустое место под раздел. Рисуется один
       раз: при переключении меняется только нижняя часть. */
    function каркас() {
      var кнопки = '';
      ВИДЫ.forEach(function (в) {
        var р = разделом(СВОДКА, в.ключ);
        var отзывов = Number(р.отзывов) || 0;
        кнопки += '<button type="button" class="оц-вкладка'
          + (в.ключ === ГДЕ ? ' тут' : '') + '" data-раздел="' + в.ключ + '">'
          + CW.значок(в.знак, 14) + '<span>' + в.имя + '</span>'
          + '<i class="оц-счётчик">' + (отзывов || '·') + '</i>'
          + '</button>';
      });
      М.тело.innerHTML = '<div class="оц-полка">' + кнопки + '</div>'
                       + '<div class="оц-место"></div>';

      Array.prototype.forEach.call(М.тело.querySelectorAll('.оц-вкладка'),
        function (б) {
          б.onclick = function () {
            var ключ = б.getAttribute('data-раздел');
            if (ключ === ГДЕ) return;
            ГДЕ = ключ;
            Array.prototype.forEach.call(М.тело.querySelectorAll('.оц-вкладка'),
              function (д) {
                д.classList.toggle('тут', д.getAttribute('data-раздел') === ГДЕ);
              });
            полкой();
          };
        });
    }

    /* ── ОДНА ПОЛКА ──
       Числа этого раздела, его отзывы и своя оценка. Отзывы спрашиваем
       по разделу: «section=signals» приносит только сигнальные. */
    function полкой() {
      var место = М.тело.querySelector('.оц-место');
      if (!место) return;
      var ключ = ГДЕ;
      var в = видом(ключ);
      var р = разделом(СВОДКА, ключ);
      МОИ = (р['моё'] && р['моё']['звёзд'])
         || (ключ === 'market' && СВОДКА['мой_отзыв'] && СВОДКА['мой_отзыв']['звёзд'])
         || 0;

      место.innerHTML = шапкаРаздела(в, р) + числаРаздела(в, р)
                      + '<div class="оц-отзывы"><div class="оц-ждём">Загрузка…</div></div>'
                      + '<div class="оц-моё"></div>';
      моёМесто(место.querySelector('.оц-моё'), в, р);

      if (ОТЗЫВЫ[ключ]) { положить(место, ОТЗЫВЫ[ключ], в); return; }
      CW.спросить('/sellers/' + номер + '/reviews?section=' + ключ, { тихо: true })
        .then(function (д) {
          var список = (д && д.отзывы) || [];
          /* Сервер старой версии раздела не знает и отдаёт всё подряд.
             Тогда фильтруем сами, чтобы в сигналах не оказались
             товарные отзывы. */
          if (д && !д.раздел) {
            список = список.filter(function (у) {
              return (у.раздел || 'market') === ключ;
            });
          }
          ОТЗЫВЫ[ключ] = список;
          if (ГДЕ === ключ) положить(место, список, в);
        })
        .catch(function () {
          ОТЗЫВЫ[ключ] = [];
          if (ГДЕ === ключ) положить(место, [], в);
        });
    }

    function шапкаРаздела(в, р) {
      var отзывов = Number(р.отзывов) || 0;
      return '<div class="оц-шапка">'
        + '<div class="оц-крупно' + (отзывов ? '' : ' пусто') + '">'
        +   (отзывов ? Number(р['звёзд']).toFixed(1) : '-') + '</div>'
        + '<div>' + звёзды(р['звёзд'], 18)
        +   '<div class="оц-мелко">' + отзывов
        +     словом(отзывов, 'отзыв', 'отзыва', 'отзывов')
        +     ' о разделе «' + в.имя + '»</div>'
        + '</div>'
        + '<div class="оц-итоги">'
        +   '<span class="оц-плюс">' + CW.значок('галка', 14)
        +     (Number(р.плюсов) || 0) + '</span>'
        +   '<span class="оц-минус">' + CW.значок('крест', 14)
        +     (Number(р.минусов) || 0) + '</span>'
        + '</div>'
        + '</div>';
    }

    /* ── ЧИСЛА РАЗДЕЛА ──
       У товаров и у сигналов они разные, и подписаны они по-разному:
       в этом вся затея с разделами. Клеточку, в которой нечего
       сказать, не рисуем вовсе. */
    function числаРаздела(в, р) {
      var счёты = [];
      if (в.ключ === 'market') {
        счёты.push([Number(р.сделок) || 0, 'сделок всего']);
        if (Number(р.маркет)) счёты.push([Number(р.маркет), 'цифровой маркет']);
        if (Number(р.магазин)) счёты.push([Number(р.магазин), 'магазин']);
      } else {
        счёты.push([Number(р.подписок) || Number(р.сделок) || 0, 'подписок всего']);
        if (Number(р.подписчиков)) счёты.push([Number(р.подписчиков), 'сейчас платят']);
        if (Number(р.сигналов)) счёты.push([Number(р.сигналов), 'сигналов']);
        if (р.точность != null) счёты.push([Number(р.точность) + '%', 'точность']);
        else if (Number(р.закрыто)) счёты.push([Number(р.закрыто), 'закрыто']);
      }
      if (!счёты.length || !Number(счёты[0][0])) {
        return '<div class="оц-мелко оц-низ">' + в.пусто + '</div>';
      }
      var полотно = '';
      счёты.forEach(function (с) {
        полотно += '<div class="оц-счёт"><b>' + CW.безопасно(String(с[0])) + '</b>'
                 + '<span>' + с[1] + '</span></div>';
      });
      return '<div class="оц-счёты">' + полотно + '</div>';
    }

    function положить(место, отзывы, в) {
      var где = место.querySelector('.оц-отзывы');
      if (!где) return;
      где.innerHTML = '';
      if (!отзывы.length) {
        где.innerHTML = '<div class="оц-ждём">Отзывов в разделе «' + в.имя
                      + '» пока нет. Первый оставит тот, кто там купит.</div>';
        return;
      }
      отзывы.forEach(function (о) {
        var у = документ.createElement('div');
        у.className = 'оц-отзыв';
        у.innerHTML = '<div class="оц-кто">'
          + '<b>' + CW.безопасно(о.имя || '') + '</b>'
          + звёзды(о['звёзд'], 12)
          + '<span class="оц-мелко">' + (CW.когда ? CW.когда(о.когда) : '') + '</span>'
          + '</div>'
          + (о.текст ? '<div class="оц-текст">' + CW.безопасно(о.текст) + '</div>' : '');
        где.appendChild(у);
      });
    }

    /* ── МОЯ ОЦЕНКА В ЭТОМ РАЗДЕЛЕ ──
       Видна только тому, у кого в ЭТОМ разделе была сделка. Купил товар
       и не брал сигналы — в сигналах оценки нет, и так и написано:
       иначе кнопка обещала бы то, чего сервер не разрешит. */
    function моёМесто(где, в, р) {
      if (!где) return;
      if (!р.могу) {
        где.innerHTML = '<div class="оц-мелко оц-низ">' + в.право + '</div>';
        return;
      }
      var моё = р['моё'] || (в.ключ === 'market' ? СВОДКА['мой_отзыв'] : null);

      где.innerHTML = '<div class="оц-подзаг">'
        + (моё ? ('Твоя оценка: ' + в.имя) : в.оцени) + '</div>'
        + '<div class="оц-выбор"></div>'
        + '<textarea class="оц-поле" rows="2" maxlength="1000" '
        +   'placeholder="Как прошла сделка? (необязательно)"></textarea>'
        + '<div class="оц-ряд2">'
        +   '<button type="button" class="кнопка главная оц-слать">'
        +     (моё ? 'Изменить отзыв' : 'Оставить отзыв') + '</button>'
        +   (моё ? '<button type="button" class="кнопка опасная оц-снять">'
        +     'Убрать</button>' : '')
        + '</div>';

      var поле = где.querySelector('.оц-поле');
      поле.value = (моё && моё.текст) || '';

      var выбор = где.querySelector('.оц-выбор');
      нарисоватьВыбор();

      function нарисоватьВыбор() {
        выбор.innerHTML = '';
        for (var i = 1; i <= 5; i++) (function (н) {
          var б = документ.createElement('button');
          б.type = 'button';
          б.className = 'оц-выбор-звезда' + (н <= МОИ ? ' горит' : '');
          б.innerHTML = звезда(22);
          б.title = н + ' из 5';
          б.onclick = function () { МОИ = н; нарисоватьВыбор(); };
          выбор.appendChild(б);
        })(i);
      }

      где.querySelector('.оц-слать').onclick = function () {
        if (!МОИ) { CW.сказать('Поставь оценку от одной до пяти звёзд'); return; }
        М.занят(true);
        CW.спросить('/sellers/' + номер + '/reviews', {
          способ: 'POST',
          тело: { stars: МОИ, text: поле.value.trim(), section: в.ключ }
        }).then(function () {
          М.занят(false);
          CW.сказать('Спасибо, отзыв записан', 3000);
          delete ПАМЯТЬ[номер];
          начать(true);
        }).catch(function (е) {
          М.занят(false);
          CW.сказать((е && е.message) || 'Отзыв не записался', 5000);
        });
      };

      var снять = где.querySelector('.оц-снять');
      if (снять) снять.onclick = function () {
        М.занят(true);
        CW.спросить('/sellers/' + номер + '/reviews?section=' + в.ключ,
                    { способ: 'DELETE' })
          .then(function () {
            М.занят(false);
            delete ПАМЯТЬ[номер];
            МОИ = 0;
            начать(true);
          }).catch(function (е) {
            М.занят(false);
            CW.сказать((е && е.message) || 'Не убралось');
          });
      };
    }

    return М;
  }

  CW.продавец = {
    привязать: привязать,
    привязатьЗначок: function (узел, номер, о) {
      о = о || {};
      о.значок = true;
      привязать(узел, номер, о);
    },
    карточка: карточка,
    окно: окноПродавца,
    звёзды: звёзды,
    сводка: сводка,
    разделы: ВИДЫ,
    убрать: убрать
  };

})(window, document);
