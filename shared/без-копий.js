/* ═══════════════════════════════════════════════════════════════════════
   ЗАПРЕТ КОПИРОВАНИЯ.      /home/claude/новое/cubeworld-app/shared/без-копий.js

   Из программы ничего не копируется: ни переписка, ни карточки, ни
   подписи под ними. Выделение убрано правилом в shared/style.css, а
   этот файл закрывает то, чего правилом не закрыть: Ctrl+C и Ctrl+X с
   клавиатуры, «Копировать» из меню браузера, длинное нажатие на
   телефоне. Одного правила мало: выделить мышью нельзя, но Ctrl+A в
   поле ввода по-прежнему выделяет, и оттуда можно унести текст.

   ── Одно исключение ──────────────────────────────────────────────────

   Содержимое окна файла (.фл-тело): поле текста, поле кода, клетки
   таблицы, лист документа и слайда. Файл человек завёл сам, это его
   работа, и забирать у него возможность вынести свой же текст было бы
   не защитой, а помехой. Всё остальное окно файла — имя, чип вида,
   кнопки — под общим запретом.

   ── Чего запрет не трогает ───────────────────────────────────────────

   Кнопки, которые кладут в буфер сами: «скопировать ключ», «ссылка на
   куб», UID. Это не копирование чужого текста со страницы, а действие,
   которое человек нажал нарочно, и оно идёт мимо события copy.

   Вставка (paste) тоже свободна: таблица принимает кусок из Excel,
   а в поля вставляют ключи и ссылки.
   ═══════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  var МОЖНО = '.фл-тело';
  var последний = 0;

  function внутри(узел) {
    while (узел && узел.nodeType === 3) узел = узел.parentNode;
    return !!(узел && узел.closest && узел.closest(МОЖНО));
  }

  /* Откуда берут текст: обычно это узел события, но при Ctrl+C событие
     приходит на документ, и спрашивать надо выделение или поле под
     курсором. */
  function откуда() {
    var с = window.getSelection && window.getSelection();
    if (с && с.rangeCount) {
      var у = с.getRangeAt(0).commonAncestorContainer;
      if (у) return у;
    }
    return document.activeElement;
  }

  function сторож(е) {
    if (внутри(е.target) || внутри(откуда())) return;
    е.preventDefault();
    try {
      var б = е.clipboardData || window.clipboardData;
      /* Буфер чистим нарочно: без этого в нём останется то, что лежало
         там раньше, и человек решит, что копирование прошло. */
      if (б) б.setData('text/plain', '');
    } catch (б1) {}
    /* Говорим один раз в три секунды: иначе зажатый Ctrl+C завалит
       экран одинаковыми подсказками. */
    var т = Date.now();
    if (т - последний > 3000 && window.CW && CW.сказать) {
      последний = т;
      CW.сказать('Копирование в программе закрыто', 2500);
    }
  }

  document.addEventListener('copy', сторож, true);
  document.addEventListener('cut', сторож, true);

  /* Перетаскивание текста мышью — тот же вынос наружу, только без
     буфера. Картинки и файлы, которые кладут в переписку, тянут за
     себя сами и события dragstart на тексте не поднимают. */
  document.addEventListener('dragstart', function (е) {
    if (внутри(е.target)) return;
    var с = window.getSelection && window.getSelection();
    if (с && String(с).length) е.preventDefault();
  }, true);
})();
