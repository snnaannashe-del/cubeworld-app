/* ═══════════════════════════════════════════════════════════════════════
   ВРЕМЯ.

   Сервер отдаёт время по Гринвичу и без буквы Z: «2026-11-16 18:12:52».
   Браузер такую строку читает как МЕСТНОЕ время, и подпись у сообщения
   уезжает ровно на часовой пояс. Своя же копия («я только что отправил»)
   подписывается настоящими местными часами — поэтому одно и то же
   сообщение в переписке показывалось с двумя разными временами.

   Здесь одно место, через которое время читают все экраны.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  /* Приводим к виду, который браузер понимает однозначно. */
  CW.кГринвичу = function (с) {
    var т = String(с == null ? '' : с);
    if (!т) return т;
    if (/[zZ]$/.test(т) || /[+\-]\d\d:?\d\d$/.test(т)) return т;
    return т.replace(' ', 'T') + 'Z';
  };

  CW.миг = function (с) {
    var д = new Date(CW.кГринвичу(с));
    var ч = д.getTime();
    return isNaN(ч) ? 0 : ч;
  };

  /* Только часы: 14:07 */
  CW.часы = function (с) {
    var д = new Date(CW.кГринвичу(с));
    if (isNaN(д.getTime())) return '';
    return д.toLocaleTimeString('ru', { hour: '2-digit', minute: '2-digit' });
  };

  /* Для списка: сегодня — часы, вчера — «вчера», раньше — дата. */
  CW.когда = function (с) {
    var д = new Date(CW.кГринвичу(с));
    if (isNaN(д.getTime())) return '';
    var сейчас = new Date();
    if (д.toDateString() === сейчас.toDateString()) return CW.часы(с);
    var вчера = new Date(сейчас.getTime() - 86400000);
    if (д.toDateString() === вчера.toDateString()) return 'вчера';
    var тотЖеГод = д.getFullYear() === сейчас.getFullYear();
    return д.toLocaleDateString('ru', тотЖеГод
      ? { day: '2-digit', month: '2-digit' }
      : { day: '2-digit', month: '2-digit', year: '2-digit' });
  };

  /* Полная подпись под сообщением: «16.11 02:20» или «02:20». */
  CW.подпись = function (с) {
    var д = new Date(CW.кГринвичу(с));
    if (isNaN(д.getTime())) return '';
    var сегодня = д.toDateString() === new Date().toDateString();
    return сегодня ? CW.часы(с) : (CW.когда(с) + ' ' + CW.часы(с));
  };

  /* ── «сегодня в 19:22» ──
     Длинная подпись словами: её просят меню сообщения, комментарии и
     посты. Короткая («19:22») остаётся у пузыря в переписке: там
     рядом сотня таких, и слово «сегодня» сто раз подряд — шум.

         CW.когдаСловами('2026-11-21T19:22:00')  «сегодня в 19:22»
                                                 «вчера в 19:22»
                                                 «17 ноября в 19:22» */
  CW.когдаСловами = function (с) {
    var д = new Date(CW.кГринвичу(с));
    if (isNaN(д.getTime())) return '';
    var часы = CW.часы(с);
    var сейчас = new Date();
    if (д.toDateString() === сейчас.toDateString()) return 'сегодня в ' + часы;
    var вчера = new Date(сейчас.getTime() - 86400000);
    if (д.toDateString() === вчера.toDateString()) return 'вчера в ' + часы;
    var тотЖеГод = д.getFullYear() === сейчас.getFullYear();
    var день = д.toLocaleDateString('ru', тотЖеГод
      ? { day: 'numeric', month: 'long' }
      : { day: 'numeric', month: 'long', year: 'numeric' });
    return день + ' в ' + часы;
  };

  /* Сколько осталось: «5м», «3ч», «2д». Для записей со сроком. */
  CW.остаток = function (когдаИстечёт) {
    var мс = CW.миг(когдаИстечёт) - Date.now();
    if (мс <= 0) return '0м';
    var м = Math.floor(мс / 60000);
    if (м < 60) return м + 'м';
    var ч = Math.floor(м / 60);
    if (ч < 24) return ч + 'ч';
    return Math.floor(ч / 24) + 'д';
  };

  /* Сколько прошло: «только что», «5 мин назад», «вчера». */
  CW.прошло = function (с) {
    var мс = Date.now() - CW.миг(с);
    if (мс < 0 || !CW.миг(с)) return '';
    var м = Math.floor(мс / 60000);
    if (м < 1) return 'только что';
    if (м < 60) return м + ' мин назад';
    var ч = Math.floor(м / 60);
    if (ч < 24) return ч + ' ч назад';
    return CW.когда(с);
  };

  /* ── ЧАСОВОЙ: ТО, ЧТО ДОЛЖНО ИСЧЕЗНУТЬ, ИСЧЕЗАЕТ САМО ─────────────

         CW.гаснет(узел, когда)        следить за этим узлом
         CW.гаснет.снять(узел)         перестать следить

     Срок у сообщения и комментария работал наполовину: сервер убирал
     просроченное, и человек узнавал об этом, только перезайдя в
     переписку. Пока окно открыто, сообщение «исчезнет через 5м» висело
     и через час — то есть обещание было ложным.

     Часовой тикает раз в полминуты, один на страницу: сто сообщений —
     это сто записей в списке, а не сто таймеров. Когда время вышло,
     узел убирается со страницы, а подпись «исчезнет через …»
     пересчитывается на каждом тике — иначе «5м» остаётся «5м» и через
     четыре минуты.

     Запас в полминуты нарочный: часы у человека и у сервера расходятся
     на секунды, и убирать сообщение раньше, чем его уберёт сервер,
     значит показать пустоту там, где у собеседника ещё есть текст. */
  var ПОД_ЧАСОВЫМ = [];
  var ЧАСЫ = null;

  function тик() {
    var сейчас = Date.now();
    var осталось = [];
    ПОД_ЧАСОВЫМ.forEach(function (з) {
      var узел = з.узел;
      if (!узел || !узел.parentNode) return;             /* ушёл сам */
      var мс = CW.миг(з.когда) - сейчас;
      if (мс <= -30000) {
        узел.parentNode.removeChild(узел);
        return;
      }
      var подпись = узел.querySelector('.срок');
      if (подпись) подпись.textContent = CW.остаток(з.когда);
      осталось.push(з);
    });
    ПОД_ЧАСОВЫМ = осталось;
    if (!ПОД_ЧАСОВЫМ.length) { clearInterval(ЧАСЫ); ЧАСЫ = null; }
  }

  CW.гаснет = function (узел, когда) {
    if (!узел || !когда || !CW.миг(когда)) return узел;
    CW.гаснет.снять(узел);
    ПОД_ЧАСОВЫМ.push({ узел: узел, когда: когда });
    if (!ЧАСЫ) ЧАСЫ = setInterval(тик, 30000);
    return узел;
  };

  CW.гаснет.снять = function (узел) {
    ПОД_ЧАСОВЫМ = ПОД_ЧАСОВЫМ.filter(function (з) { return з.узел !== узел; });
  };

})(window);
