/* ═══════════════════════════════════════════════════════════════════════
   СЛАЙДЫ.

       CW.правкаСлайды(узел, файл, {менялось, счёт}) → {тело()}

   Слайд — тот же лист с оформлением, что и документ, поэтому полоса у
   них одна на двоих и лежит в shared/правка-слово.js. Здесь только то,
   чего у документа нет: лента номеров, «новый», «убрать», «левее»,
   «правее» и сама смена слайда.

   Хранится показ своим списком:

       {"слайды":[{"разметка":"<div>…</div>"}, …]}

   Почему списком, а не одной разметкой с разделителями: разделитель
   рано или поздно встретится в тексте, и показ развалится на месте,
   где его никто не делил. Старый файл простым текстом тоже откроется —
   он станет первым слайдом.

   Наружу показ уйдёт настоящим PDF, страница на слайд. Это отдельная
   часть, её ещё нет: пока «Скачать» отдаёт то, что лежит в файле.
   ═══════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  function эл(тег, класс) {
    var у = document.createElement(тег);
    if (класс) у.className = класс;
    return у;
  }

  function слайдыИзТела(тело) {
    var д = null;
    try { д = JSON.parse(тело || ''); } catch (е) {}
    if (д && д.слайды && д.слайды.length) {
      return д.слайды.map(function (с) {
        return { разметка: String((с && с.разметка) || '') };
      });
    }
    var т = String(тело || '').trim();
    if (т) return [{ разметка: CW.листПравки.разметкой(т) }];
    return [{ разметка: '<div><br></div>' }];
  }

  CW.правкаСлайды = function (куда, ф, зов) {
    var слайды = слайдыИзТела(ф.body);
    var сейчас = 0;

    var столбец = эл('div', 'фл-столбец');
    var полоса = CW.листПравки.полоса({});
    var лента = эл('div', 'фл-лента');
    var сцена = эл('div', 'фл-сцена');
    var лист = эл('div', 'фл-лист фл-слайд');
    лист.contentEditable = 'true';
    лист.spellcheck = true;
    лист.setAttribute('data-подсказка', 'Заголовок и текст слайда…');
    сцена.appendChild(лист);
    столбец.appendChild(полоса);
    столбец.appendChild(лента);
    столбец.appendChild(сцена);
    куда.appendChild(столбец);

    function снять() { слайды[сейчас] = { разметка: CW.листПравки.телом(лист) }; }

    function показать(н) {
      сейчас = Math.max(0, Math.min(слайды.length - 1, н));
      лист.innerHTML = слайды[сейчас].разметка || '<div><br></div>';
      /* Предметы нового слайда пришли разметкой — без ручек. Оживляем
         их, иначе картинку на втором слайде не сдвинуть. */
      if (зовЛиста.оживить) зовЛиста.оживить();
      нарисоватьЛенту();
      посчитать();
    }

    function нарисоватьЛенту() {
      лента.innerHTML = '';
      слайды.forEach(function (_, и) {
        var б = эл('button', 'фл-слайд-кн' + (и === сейчас ? ' выбран' : ''));
        б.type = 'button';
        б.textContent = и + 1;
        б.title = 'Слайд ' + (и + 1);
        б.dataset.н = и;
        лента.appendChild(б);
      });
      лента.appendChild(эл('span', 'щель'));
      [['добавить', '+', 'Новый слайд'],
       ['убрать', '−', 'Убрать слайд'],
       ['левее', '◀', 'Левее'],
       ['правее', '▶', 'Правее']].forEach(function (к) {
        var б = эл('button');
        б.type = 'button';
        б.dataset.сл = к[0];
        б.textContent = к[1];
        б.title = к[2];
        лента.appendChild(б);
      });
    }

    лента.addEventListener('mousedown', function (е) {
      if (е.target.tagName === 'BUTTON') е.preventDefault();
    });

    лента.addEventListener('click', function (е) {
      var к = е.target.closest && е.target.closest('button');
      if (!к) return;
      снять();
      if (к.dataset.н !== undefined) { показать(Number(к.dataset.н)); return; }
      var д = к.dataset.сл, а;
      if (д === 'добавить') {
        слайды.splice(сейчас + 1, 0, { разметка: '<div><br></div>' });
        зов.менялось();
        показать(сейчас + 1);
      } else if (д === 'убрать') {
        /* Последний слайд не убираем: показ без единого слайда — это
           не пустой показ, а сломанный файл. */
        if (слайды.length < 2) { CW.сказать('Последний слайд не убрать', 3000); return; }
        слайды.splice(сейчас, 1);
        зов.менялось();
        показать(Math.min(сейчас, слайды.length - 1));
      } else if (д === 'левее' && сейчас > 0) {
        а = слайды[сейчас]; слайды[сейчас] = слайды[сейчас - 1]; слайды[сейчас - 1] = а;
        зов.менялось();
        показать(сейчас - 1);
      } else if (д === 'правее' && сейчас < слайды.length - 1) {
        а = слайды[сейчас]; слайды[сейчас] = слайды[сейчас + 1]; слайды[сейчас + 1] = а;
        зов.менялось();
        показать(сейчас + 1);
      }
    });

    function посчитать() {
      CW.листПравки.пустота(лист);
      зов.счёт('слайдов ' + слайды.length + ' · сейчас ' + (сейчас + 1));
    }

    var зовЛиста = { менялось: зов.менялось, посчитать: посчитать };
    CW.листПравки.оформлением(полоса, лист, зовЛиста);
    показать(0);
    setTimeout(function () { CW.встать(лист); }, 60);

    return {
      тело: function () { снять(); return JSON.stringify({ слайды: слайды }); }
    };
  };
})();
