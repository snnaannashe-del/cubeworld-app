/* ═══════════════════════════════════════════════════════════════════════
   ОКНО ВЫДАННОГО КЛЮЧА — одно на две страницы.

       shared/ключ-окно.js  (вид — shared/ключ-окно.css)

   ── Зачем отдельный файл ───────────────────────────────────────────
   Это окно было написано дважды: на титулке и на странице тарифа. Оба
   раза одно и то же — бирка, заголовок, крутилка, рамка с ключом,
   кнопка «В мир», значки «Копировать» и «Назад» в углу. Но имена у них
   разъехались: там «ключ-коробка», тут «коробка-ключа», там
   «кн-назад», тут «кн-закрыть-ключ». Чинили его тоже дважды.

   Теперь окно одно. Страница даёт место, куда его поставить, и говорит,
   что делать по «Назад». Всё остальное — здесь.

   ── Что умеет ──────────────────────────────────────────────────────
       CW.ключОкно.собрать(где, { назад: fn })   построить окно внутри «где»
       CW.ключОкно.завести()                     попросить у сервера ключ
       CW.ключОкно.обновить()                    перевести подписи значков
       CW.ключОкно.ключ()                        выданный ключ или ''

   Ключ показывается один раз и восстановлению не подлежит — поэтому
   окно ничего не закрывает само и ничего не перерисовывает, пока
   человек сам не нажмёт «Назад».
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  var выданный = '';
  var корень = null;

  function $(и) { return документ.getElementById(и); }

  function весть(текст, вид) {
    var в = $('кл-весть');
    if (!в) return;
    в.textContent = текст || '';
    в.className = 'весть' + (вид ? ' ' + вид : '');
  }

  function значки() {
    if (корень && CW.расставитьЗначки) CW.расставитьЗначки(корень);
  }

  /* У значков в углу слов нет — подписи всплывающие, из словаря. */
  function подписи() {
    [['кл-назад', 'bk'], ['кл-копировать', 'kcp']].forEach(function (п) {
      var к = $(п[0]); if (!к) return;
      к.title = CW.сл(п[1]);
      к.setAttribute('aria-label', CW.сл(п[1]));
    });
  }

  CW.ключОкно = {

    ключ: function () { return выданный; },

    собрать: function (где, о) {
      о = о || {};
      if (!где) return;

      где.innerHTML =
        '<div class="ключ-окно">'
      +   '<div class="углы-ключа">'
      +     '<button class="уголок-кнопка" id="кл-копировать">'
      +       '<span class="зн" data-знак="копия" data-размер="17"></span></button>'
      +     '<button class="уголок-кнопка" id="кл-назад">'
      +       '<span class="зн" data-знак="стрелка" data-размер="17"></span></button>'
      +   '</div>'
      +   '<div class="верх-ключа">'
      +     '<span class="ключ-бирка" data-сл="fkb"></span>'
      +     '<h2 data-сл="kgt"></h2>'
      +   '</div>'
      +   '<div class="середина-ключа">'
      +     '<div class="крутилка" id="кл-крутилка"></div>'
      +     '<div class="ключ-коробка" id="кл-коробка">'
      +       '<div class="ключ-рамка">'
      +         '<div class="ключ-подпись" data-сл="kak"></div>'
      +         '<div class="ключ-значение" id="кл-значение"></div>'
      +       '</div>'
      +     '</div>'
      +   '</div>'
      +   '<div class="низ-ключа">'
      +     '<div class="ключ-кнопки">'
      +       '<button class="кнопка главная" id="кл-в-мир" data-сл="wc"></button>'
      +     '</div>'
      +     '<div class="весть" id="кл-весть"></div>'
      +   '</div>'
      + '</div>';

      корень = где.firstChild;
      значки();
      if (CW.перевести) CW.перевести(где);
      подписи();

      $('кл-назад').onclick = function () {
        if (о.назад) о.назад();
      };

      $('кл-копировать').onclick = function () {
        if (!выданный) return;
        CW.вбуфер(выданный, CW.сл('kcp') + ' ✓');
      };

      $('кл-в-мир').onclick = function () {
        if (!выданный) return;
        $('кл-в-мир').disabled = true;
        весть(CW.сл('mConn'), 'ждём');

        /* Render засыпает, и первый ответ идёт долго. Через пять секунд
           говорим об этом словами, а не оставляем человека смотреть на
           замершую кнопку. */
        var будильник = setTimeout(function () {
          весть(CW.сл('mWake'), 'ждём');
        }, 5000);

        CW.войти(выданный).then(function () {
          clearTimeout(будильник);
          CW.уйти('world.html');
        }).catch(function (е) {
          clearTimeout(будильник);
          $('кл-в-мир').disabled = false;
          весть(е.сеть ? CW.сл('mNet') : CW.сл('mNoKey'), 'плохо');
        });
      };
    },

    обновить: function () {
      значки();
      подписи();
    },

    завести: function () {
      $('кл-крутилка').style.display = 'block';
      $('кл-коробка').classList.remove('видно');
      весть('');

      return CW.завестиКлюч().then(function (д) {
        выданный = д.key;
        $('кл-значение').textContent = д.key;
        $('кл-крутилка').style.display = 'none';
        $('кл-коробка').classList.add('видно');
        return д;
      }).catch(function (е) {
        $('кл-крутилка').style.display = 'none';
        весть(е.сеть ? CW.сл('mNet') : е.message, 'плохо');
      });
    }
  };

})(window, document);
