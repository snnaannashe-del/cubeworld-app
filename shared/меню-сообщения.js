/* ═══════════════════════════════════════════════════════════════════════
   МЕНЮ СООБЩЕНИЯ — ОДНО НА ВСЮ ПРОГРАММУ.
   /home/claude/новое/cubeworld-app/shared/меню-сообщения.js

       CW.менюСообщения({
         род: 'текст',          чем является сообщение (список ниже)
         своё: true,            автор — я (от этого «Изменить»)
         когда: 'сегодня в 19:22',
         закреплено: false,
         текст: 'привет',       для «Скопировать» и «Форматировать»
         действия: {
           ответить:   function (цитата) {},
           скопировать:function () {},
           изменить:   function (новыйТекст) {},   вернуть обещание
           сохранить:  function () {},             снимок или ролик на диск
           закрепить:  function (надо) {},
           переслать:  function () {},
           удалить:    function () {},
           кнопки:     {набор:[…], вряд:3, цвет:'#4ade80',
                        сохранить: function (сп, вряд, цвет) {}}
         }
       }, x, y);

   ── РОД СООБЩЕНИЯ ──
       текст · смайлы · фото · видео · файл-фото · файл-видео ·
       аудио · место · файл · звонок · голос · кружок

   ── ПРАВИЛО ──
   В меню стоит ТОЛЬКО то, что и правда сработает: пункт без своего
   действия не рисуется вовсе. Пустая кнопка хуже отсутствующей —
   человек жмёт её и решает, что сломалась вся программа.

   «Изменить» и «Форматировать» показываются только автору: чужое
   сообщение править нельзя, и сервер это тоже запрещает (403).

   ── ФОРМАТИРОВАТЬ ──
   Девять пометок, и все они из одного набора разметки (CW.сРазметкой):

       **жирный**  __курсив__  ~~зачёркнутый~~  ++подчёркнутый++
       `моноширинный`  ||скрытый||  > цитата  [текст](адрес)

   Пометка ложится на ВЕСЬ текст сообщения: выделять кусок в меню
   нечем, а править по буквам человек будет в «Изменить».
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  /* Пометки ставит и снимает общий ящик (shared/ui.js): их же зовёт
     полка формата у поля ввода. Здесь только короткое имя. */
  var пометить = CW.пометить;

  /* ── МАЛЕНЬКОЕ ОКНО ПРАВКИ ──
     Одно на все виды сообщений: текст, подпись под снимком, подпись
     под роликом. Больше тут ничего не нужно — поле и две кнопки. */
  CW.правкаТекста = function (н) {
    н = н || {};
    var КОРЗИНА = [];                 /* выбранные файлы замены */
    var ПРЕДЕЛ = 10;                  /* «всего до 10 штук общая корзина» */

    var кнопкиШапки = [];
    if (н.файлы) {
      кнопкиШапки.push({ имя: 'скрепка', зн: 'скрепка',
                         подсказка: Т('Выбрать другие файлы (до 10)'),
                         делать: function () { поле.click(); } });
    }

    var М = CW.модалка({
      имя: 'правка-сообщения',
      знак: 'карандаш',
      заголовок: н.заголовок || 'Изменить',
      подзаголовок: н.подзаголовок || '',
      кнопки: кнопкиШапки,
      главная: { зн: 'галка', подсказка: Т('Сохранить'), делать: сохранить }
    });

    var поле = документ.createElement('textarea');
    поле.className = 'правка-поле';
    поле.rows = 4;
    поле.maxLength = н.предел || 5000;
    поле.value = н.текст || '';
    поле.placeholder = н.намёк || 'Текст сообщения';
    М.тело.appendChild(поле);

    /* ── КОРЗИНА ФАЙЛОВ ──
       У снимка, ролика и файла «Изменить» — это ещё и «взять другой».
       Скрепка в шапке открывает выбор, в корзину влезает до десяти:
       первый встаёт на место этого сообщения, остальные уходят
       следом отдельными сообщениями. Столько же держит и строка
       ввода, и это не случайность: корзина общая по смыслу. */
    var поле = null, полка = null;
    if (н.файлы) {
      поле = документ.createElement('input');
      поле.type = 'file';
      поле.multiple = true;
      поле.accept = н.берём || '';
      поле.style.display = 'none';
      М.тело.appendChild(поле);

      полка = документ.createElement('div');
      полка.className = 'правка-корзина';
      М.тело.appendChild(полка);

      поле.onchange = function () {
        var взяли = [].slice.call(поле.files || []);
        поле.value = '';
        взяли.forEach(function (ф) {
          if (КОРЗИНА.length >= ПРЕДЕЛ) return;
          КОРЗИНА.push(ф);
        });
        if (взяли.length && КОРЗИНА.length >= ПРЕДЕЛ) {
          CW.сказать(Т('В корзину влезает ') + ПРЕДЕЛ + ' файлов', 3000);
        }
        нарисоватьКорзину();
      };
      нарисоватьКорзину();
    }

    function нарисоватьКорзину() {
      if (!полка) return;
      полка.innerHTML = '';
      if (!КОРЗИНА.length) {
        var п = документ.createElement('div');
        п.className = 'правка-корзина-пусто';
        п.textContent = Т('Файл остаётся прежним. Скрепка в шапке, взять другие, до ')
                      + ПРЕДЕЛ + '.';
        полка.appendChild(п);
        return;
      }
      КОРЗИНА.forEach(function (ф, и) {
        var строка = документ.createElement('div');
        строка.className = 'правка-файл';
        строка.innerHTML = '<span class="нм">' + CW.безопасно(ф.name || 'файл') + '</span>'
          + '<span class="рз">' + (CW.вес ? CW.вес(ф.size || 0) : '') + '</span>';
        var снять = документ.createElement('button');
        снять.type = 'button';
        снять.className = 'правка-снять';
        снять.title = Т('Убрать из корзины');
        снять.innerHTML = CW.рисунок('M6 6 18 18M18 6 6 18', 14);
        снять.onclick = function () { КОРЗИНА.splice(и, 1); нарисоватьКорзину(); };
        строка.appendChild(снять);
        полка.appendChild(строка);
      });
      var счёт = документ.createElement('div');
      счёт.className = 'правка-корзина-пусто';
      счёт.textContent = Т('В корзине ') + КОРЗИНА.length + ' из ' + ПРЕДЕЛ
                       + '. Первый встанет на место этого сообщения.';
      полка.appendChild(счёт);
    }

    М.открыть();
    поле2().focus();
    try { поле2().setSelectionRange(поле2().value.length, поле2().value.length); } catch (е) {}
    function поле2() { return М.тело.querySelector('.правка-поле'); }

    function сохранить() {
      var т = поле2().value.trim();
      if (!т && !н.пустоеМожно) { CW.сказать(Т('Пустое сообщение не сохраняем')); return; }
      М.занят(true);
      var дело = КОРЗИНА.length && н.файлы
        ? н.файлы(КОРЗИНА.slice(), т)
        : н.сохранить(т);
      Promise.resolve(дело).then(function () {
        М.убрать();
      }).catch(function (е) {
        М.занят(false);
        CW.сказать((е && е.message) || 'Не сохранилось');
      });
    }
    return М;
  };

  /* Общий файл кнопок уже стоит на странице у всех трёх переписок —
     им он нужен, чтобы вообще нарисовать пузырь. Тащить его вторым
     <script> нельзя: второй заход стёр бы кнопки, которые ждут
     отправки. Поэтому сначала смотрим, не приехал ли он сам. */
  function сКнопками(дальше) {
    if (CW.кнопкиСообщения) { дальше(); return; }
    CW.нужен('shared/кнопки-сообщения.js').then(дальше)
      .catch(function () { CW.сказать(Т('Кнопки не приехали')); });
  }

  /* ── САМО МЕНЮ ── */
  CW.менюСообщения = function (н, x, y) {
    н = н || {};
    var д = н.действия || {};
    var род = н.род || 'текст';
    var пункты = [];

    /* Время сверху — так в работающей программе: сначала «когда», потом
       черта, потом действия. У звонков и места его нет: там время уже
       написано в самой карточке. */
    var безВремени = (род === 'звонок' || род === 'место');
    if (н.когда && !безВремени) пункты.push({ заголовок: н.когда });

    function пункт(зн, подпись, делать, ещё) {
      if (!делать) return;
      var э = { зн: CW.значок(зн, 16), подпись: подпись, делать: делать };
      if (ещё) for (var к in ещё) if (ещё.hasOwnProperty(к)) э[к] = ещё[к];
      пункты.push(э);
    }

    пункт('ответить', 'Ответить', д.ответить && function () { д.ответить(н.текст || ''); });

    /* Копировать нечего там, где текста нет вовсе. */
    if (д.скопировать && (н.текст || род === 'текст' || род === 'смайлы')) {
      пункт('копия', 'Скопировать', function () { д.скопировать(); });
    }

    /* ── ЗАМЕНИТЬ ОДИН ФАЙЛ ──
       В пачке из десяти снимков один оказался не тот. Меняем только
       его: остальные девять остаются как лежали, и сообщение не
       уезжает в конец переписки.

       Пункт даётся только на СВОЁ вложение: чужое сообщение правкой
       не трогают. */
    if (д.заменить && н.адрес && н.своё) {
      /* Чем заменять, решает род: снимок меняют на снимок, ролик на
         ролик. Окну это передаём строкой выбора, ту же самую берёт
         окно правки подписи. */
      пункт('скрепка', 'Заменить файл', function () { д.заменить(берёмДля(род)); });
    }

    /* ── ЧЕМ ПОКАЗЫВАТЬ ВЛОЖЕНИЕ ──
       Избранное держит заметки у себя и может показать снимок и
       строкой файла, и картинкой: выбор человека, а не наш. Пункт
       появляется только там, где окно его дало. В переписке и в
       группе его нет: там выбор сделан при отправке, и сообщение уже
       ушло собеседнику - менять задним числом нечего. */
    if (д.показатьИначе) {
      пункт(д.показатьИначе.файлом ? 'лист' : 'картинка',
            д.показатьИначе.файлом ? 'Показать файлом' : 'Показать картинкой',
            function () { д.показатьИначе.делать(); });
    }

    /* ── В МУЗЫКУ И В ПАПКУ ──
       Оба действия меню делает само: музыка (shared/музыка.js) и папки
       (/folders) — общие склады программы, и каждому окну переписки
       знать о них незачем. Нужен только адрес файла, его окно и так
       передаёт. */
    if ((род === 'аудио' || род === 'голос') && н.адрес) {
      пункт('нота', 'В музыку', function () { вМузыку(н); });
    }
    if (н.адрес && род !== 'место' && род !== 'звонок') {
      пункт('папка', 'В папку', function () { вПапку(н); });
    }

    if (род === 'фото' || род === 'файл-фото') {
      пункт('картинка', 'Сохранить фото', д.сохранить);
    } else if (род === 'видео' || род === 'файл-видео' || род === 'кружок') {
      пункт('плёнка', 'Сохранить видео', д.сохранить);
    } else if (род === 'аудио' || род === 'голос') {
      пункт('нота', 'Сохранить звук', д.сохранить);
    } else if (род === 'файл') {
      пункт('лист', 'Сохранить файл', д.сохранить);
    }

    /* Править можно только своё — и только там, где есть что править:
       у звонка и у места текста нет. */
    var можноПравить = н.своё && д.изменить && род !== 'звонок' && род !== 'место';
    if (можноПравить) {
      var словоПравки = (род === 'текст' || род === 'смайлы')
        ? 'Изменить' : 'Изменить подпись';
      пункт('карандаш', словоПравки, function () {
        CW.правкаТекста({
          заголовок: словоПравки,
          подзаголовок: н.когда || '',
          текст: н.текст || '',
          пустоеМожно: род !== 'текст' && род !== 'смайлы',
          /* Брать другие файлы можно там, где файл вообще есть. */
          файлы: д.файлы || null,
          берём: берёмДля(род),
          сохранить: function (т) { return д.изменить(т); }
        });
      });
      /* ── «ФОРМАТИРОВАТЬ» ТОЛЬКО ТАМ, ГДЕ ЕСТЬ ТЕКСТ ──
         У снимка, ролика или файла БЕЗ подписи форматировать нечего:
         пометка легла бы на пустоту, и кнопка обещала бы работу,
         которой нет. Появилась подпись — появился и пункт, и пометки
         работают в ней так же, как в обычном сообщении.

         То же и с «Перевести»: переводить пустую строку не из чего. */
      if ((н.текст || '').trim()) {
        пункты.push({
          зн: CW.значок('буквы', 16), подпись: Т('Форматировать'),
          делать: function () { форматом(н, x, y); }
        });
      }
    }

    /* ── КНОПКИ ПОД СООБЩЕНИЕМ ──
       Автор может поправить их когда угодно: названия, порядок, куда
       ведут, сколько в ряду. Всё окно правки — в общем файле
       (shared/кнопки-сообщения.js), здесь только пункт.

       У чужого сообщения пункта нет: кнопки ставит автор, и сервер
       чужую правку всё равно не примет. */
    if (н.своё && д.кнопки && д.кнопки.сохранить && род !== 'звонок') {
      var скольких = (д.кнопки.набор || []).length;
      пункт('кнопка', скольких ? ('Кнопки · ' + скольких) : 'Добавить кнопки',
        function () {
          сКнопками(function () {
            CW.кнопкиСообщения.править({
              заголовок: Т('Кнопки сообщения'),
              набор: { сп: д.кнопки.набор || [], вряд: д.кнопки.вряд,
                       цвет: д.кнопки.цвет },
              потом: function (сп, вряд, цвет) {
                д.кнопки.сохранить(сп, вряд, цвет);
              }
            });
          });
        });
    }

    if (д.закрепить && род !== 'звонок') {
      пункт('булавка', н.закреплено ? 'Открепить' : 'Закрепить', function () {
        д.закрепить(!н.закреплено);
      });
    }

    if (д.переслать && род !== 'звонок') {
      пункт('поделиться', 'Переслать', function () { д.переслать(); });
    }

    /* У звонка выбор не нужен: по списку из папки 25 у него ровно два
       действия — «Ответить» и «Удалить». */
    if (д.выбрать && род !== 'звонок') {
      пункт('галка', 'Выбрать', function () { д.выбрать(); });
    }

    if (д.удалить) {
      пункты.push('-');
      пункты.push({ зн: CW.значок('урна', 16), подпись: Т('Удалить'),
                    опасная: true, делать: function () { д.удалить(); } });
    }

    CW.лист(пункты, (x != null && y != null) ? { x: x, y: y } : null);
  };

  /* Полка пометок. Отдельным листом, как в работающей программе: в
     одном списке с «Ответить» девять пометок утопили бы всё остальное. */
  function форматом(н, x, y) {
    var д = н.действия || {};
    function пометкой(вид, подпись, зн) {
      return {
        зн: зн || '',
        подпись: подпись,
        делать: function () {
          if (вид === 'ссылка') {
            CW.спроситьСтроку
              ? CW.спроситьСтроку('Адрес ссылки', 'https://', function (а) {
                  if (а) д.изменить(пометить(н.текст, 'ссылка', а));
                })
              : д.изменить(пометить(н.текст, 'ссылка', окно.prompt('Адрес ссылки', 'https://') || ''));
            return;
          }
          д.изменить(пометить(н.текст, вид));
        }
      };
    }
    CW.лист([
      { заголовок: Т('Форматировать') },
      { зн: CW.значок('глобус', 15), подпись: Т('Перевод'),
        делать: function () { переводом(н, x, y); } },
      пометкой('цитата', 'Цитата', '❝'),
      пометкой('скрытый', 'Скрытый', '▮'),
      пометкой('жирный', 'Жирный', 'Ж'),
      пометкой('курсив', 'Курсив', 'К'),
      пометкой('моно', 'Моноширинный', '⌗'),
      пометкой('ссылка', 'Ссылка', CW.значок('поделиться', 15)),
      пометкой('зачёркнутый', 'Зачёркнутый', 'З'),
      пометкой('подчёркнутый', 'Подчёркнутый', 'П'),
      '-',
      { зн: CW.значок('назад', 16), подпись: Т('Назад'),
        делать: function () { CW.менюСообщения(н, x, y); } }
    ], (x != null && y != null) ? { x: x, y: y } : null);
  }

  /* Песня уходит на общую полку музыки — ту же, что в окне «Звуки».
     Второго склада песен в программе нет и не будет. */
  function вМузыку(н) {
    CW.нужен('shared/музыка.js').then(function () {
      CW.музыка.добавить({
        имя: н.имя || (н.род === 'голос' ? 'Голосовое' : 'Песня'),
        адрес: н.адрес,
        сколько: н.размер || 0
      });
      CW.сказать(Т('На полке музыки'), 2500);
    }).catch(function () { CW.сказать(Т('Музыка не приехала')); });
  }

  /* В папку: сперва спрашиваем, в какую. Папки живут на сервере, и
     список берём у него же — выдуманных папок тут быть не может. */
  function вПапку(н) {
    CW.спросить('/folders', { сроком: 20000 }).then(function (о) {
      var список = Array.isArray(о) ? о : ((о && (о.items || о.folders)) || []);
      if (!список.length) {
        CW.сказать(Т('Папок пока нет: заведи первую в «Папках»'), 4000);
        return;
      }
      CW.лист([{ заголовок: Т('В какую папку') }].concat(
        список.slice(0, 20).map(function (п) {
          return { зн: CW.значок('папка', 16), подпись: п.name || ('Папка #' + п.id),
                   делать: function () { положитьВ(п, н); } };
        })
      ));
    }).catch(function () { CW.сказать(Т('Папки не приехали')); });
  }

  function положитьВ(папка, н) {
    var имя = н.имя || 'файл';
    CW.спросить('/folders/' + папка.id + '/files', {
      способ: 'POST', сроком: 20000,
      тело: {
        name: имя,
        kind: родДляПапки(н.род),
        url: н.адрес,
        mime: '',
        size: н.размер || 0
      }
    }).then(function () {
      CW.сказать(Т('Лежит в папке «') + (папка.name || папка.id) + '»', 3000);
    }).catch(function (е) {
      CW.сказать((е && е.message) || 'В папку не легло');
    });
  }

  /* Какие файлы предлагать в замену: у снимка — снимки, у ролика —
     ролики, у файла — что угодно. */
  function берёмДля(род) {
    if (род === 'фото' || род === 'файл-фото') return 'image/*';
    if (род === 'видео' || род === 'файл-видео' || род === 'кружок') return 'video/*';
    if (род === 'аудио' || род === 'голос') return 'audio/*';
    return '';
  }

  function родДляПапки(род) {
    if (род === 'фото' || род === 'файл-фото') return 'photo';
    if (род === 'видео' || род === 'файл-видео' || род === 'кружок') return 'video';
    if (род === 'аудио' || род === 'голос') return 'audio';
    return 'doc';
  }

  /* ── ПЕРЕВОД ──
     Полка языков, потом сам перевод. Переводит браузер у себя на
     устройстве (shared/перевод.js): переписка никуда не уезжает.

     Готовый перевод показываем окном, а не подменяем им сообщение:
     чужое сообщение трогать нельзя вовсе, да и своё человек, может,
     просто хотел прочитать. Захочет заменить — для своего есть
     кнопка, и она делает ту же правку, что «Изменить». */
  function переводом(н, x, y) {
    var д = н.действия || {};
    CW.нужен('shared/перевод.js').then(function () {
      if (!CW.перевод.можно()) {
        CW.сказать(Т('Этот браузер не умеет переводить сам, попробуй в Chrome'), 4000);
        return;
      }
      CW.лист([{ заголовок: Т('Перевод на язык') }].concat(
        CW.перевод.языки.map(function (я) {
          return { подпись: я.имя, делать: function () { перевести(н, я, д); } };
        })
      ), (x != null && y != null) ? { x: x, y: y } : null);
    }).catch(function () { CW.сказать(Т('Переводчик не приехал')); });
  }

  function перевести(н, язык, д) {
    CW.сказать(Т('Перевожу…'), 2500);
    CW.перевод.сделать(н.текст || '', язык.к).then(function (готово) {
      var кнопки = [];
      if (д.изменить) {
        кнопки.push({ зн: 'галка', подсказка: Т('Заменить текст'),
                      делать: function () {
                        д.изменить(готово);
                        М.убрать();
                      } });
      }
      var М = CW.модалка({
        имя: 'перевод',
        знак: 'глобус',
        заголовок: Т('Перевод'),
        подзаголовок: язык.имя.toLowerCase(),
        кнопки: кнопки
      });
      var т = документ.createElement('div');
      т.className = 'перевод-текст';
      т.innerHTML = CW.сРазметкой(готово);
      М.тело.appendChild(т);

      var ряд = документ.createElement('div');
      ряд.className = 'перевод-кнопки';
      var копия = документ.createElement('button');
      копия.type = 'button';
      копия.className = 'кнопка';
      копия.textContent = Т('Скопировать');
      копия.onclick = function () { CW.вбуфер(готово, Т('Скопировано')); };
      ряд.appendChild(копия);
      М.тело.appendChild(ряд);

      М.открыть();
    }).catch(function (е) {
      CW.сказать((е && е.message) || 'Перевести не вышло', 4000);
    });
  }

  /* ── РОД СООБЩЕНИЯ ПО ТОМУ, ЧТО ПРИШЛО С СЕРВЕРА ──
     Один разбор на все окна: в переписке, в группе и в избранном
     сообщение одно и то же, и решать, чем оно является, дважды
     незачем. */
  CW.родСообщения = function (вид, имяФайла, адрес) {
    вид = String(вид || '');
    var имя = String(имяФайла || адрес || '').toLowerCase().split('?')[0];
    if (вид === 'image') return 'фото';
    if (вид === 'video') return 'видео';
    if (вид === 'circle') return 'кружок';
    if (вид === 'voice') return 'голос';
    if (вид === 'audio') return 'аудио';
    if (вид === 'geo') return 'место';
    if (вид === 'call' || вид === 'call-video') return 'звонок';
    if (вид === 'file') {
      if (/\.(jpe?g|png|gif|webp|bmp|heic|avif)$/.test(имя)) return 'файл-фото';
      if (/\.(mp4|webm|mov|m4v|ogv|avi|mkv)$/.test(имя)) return 'файл-видео';
      if (/\.(mp3|wav|ogg|m4a|flac|aac|opus)$/.test(имя)) return 'аудио';
      return 'файл';
    }
    return 'текст';
  };

  /* ── СОХРАНИТЬ К СЕБЕ ──
     Браузер сам кладёт файл в «Загрузки»: нам надо только дать ему
     адрес и имя. Чужой адрес (другой сервер) скачать так нельзя — он
     просто откроется в новой вкладке, и это честнее пустого нажатия. */
  CW.сохранитьФайл = function (адрес, имя) {
    if (!адрес) { CW.сказать(Т('Сохранять нечего')); return; }
    var а = документ.createElement('a');
    а.href = CW.файл ? CW.файл(адрес) : адрес;
    а.download = имя || '';
    а.target = '_blank';
    а.rel = 'noopener';
    документ.body.appendChild(а);
    а.click();
    документ.body.removeChild(а);
  };
})(window, document);
