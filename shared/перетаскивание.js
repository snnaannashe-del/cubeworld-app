/* ═══════════════════════════════════════════════════════════════════════
   ПЕРЕТАСКИВАНИЕ СТРОК.  /home/claude/новое/cubeworld-app/shared/перетаскивание.js

       CW.перетаскивание(где, {
         строка: '.пп-ряд',            что тащим
         сложили: function (узлы) {}   когда отпустили и порядок изменился
       });

   Папки и файлы человек расставляет сам: зажал строку, повёл — она
   поехала за рукой и встала туда, куда её привели.

   Как это сделано. Строка не улетает отдельным «призраком»: она просто
   переставляется в списке, когда рука проходит середину соседа. Так
   видно сразу и наверняка, куда она встанет, и не нужно держать в
   голове два изображения одной строки — настоящее и летящее.

   Пока строку ведут, сама она мышь не ловит (класс «тащим» снимает
   pointer-events): иначе под рукой всегда оказывалась бы она же, и
   узнать, над каким соседом рука, было бы нельзя.

   Нажатие и перетаскивание различаем по сдвигу: пока рука не прошла
   пять точек, это обычное нажатие, и папка откроется как всегда.
   А на пальце ждём ещё и четверть секунды: иначе список нельзя было бы
   просто пролистать — он бы разъезжался под пальцем.

   ── Чего здесь нарочно НЕТ: захвата указателя ──
   Сперва на нажатие ставился setPointerCapture на весь список. Это
   сломало вход в папку: при захвате браузер шлёт нажатие захватившему
   узлу, а не строке, и обработчик строки его не видел. Папка просто не
   открывалась. Поэтому ведём по слушателям на документе: они ловят
   руку и за пределами окна, а нажатие остаётся нетронутым.

   Отпустили — зовём «сложили» со списком узлов в новом порядке. Кто
   звал, тот и решает, что с этим делать: папки шлют порядок на сервер.
   ═══════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  var ПОРОГ = 5;            /* точек, после которых это уже перенос */
  var ЖДАТЬ = 250;          /* мс удержания пальцем до начала переноса */

  CW.перетаскивание = function (где, что) {
    что = что || {};
    var ЧТО = что.строка || '.пп-ряд';

    var узел = null;          /* строка, которую ведут */
    var начало = 0;           /* откуда повели */
    var ведём = false;        /* перенос начался */
    var пальцем = false;
    var ждём = null;
    var менялось = false;

    /* Пока ведём пальцем, страницу листать нельзя: иначе список уедет
       вместе со строкой. Слушатель нарочно не пассивный — только такой
       имеет право отменить листание. */
    document.addEventListener('touchmove', function (е) {
      if (ведём) е.preventDefault();
    }, { passive: false });

    /* Ни одна строка не должна остаться «взятой». Взятая не ловит мышь,
       и в такую папку потом не войти — нажатие просто некуда класть.
       Поэтому чистим весь список, а не только ту строку, что помним. */
    function отпустить() {
      [].slice.call(где.querySelectorAll(ЧТО + '.тащим')).forEach(function (э) {
        э.classList.remove('тащим');
      });
    }

    где.addEventListener('pointerdown', function (е) {
      if (е.button) return;
      /* Кнопки в строке — это кнопки: карандаш и крестик должны
         нажиматься, а не таскать строку. */
      if (е.target.closest('button, input, select, textarea, a')) return;
      var р = е.target.closest(ЧТО);
      if (!р || !где.contains(р)) return;

      отпустить();
      узел = р;
      начало = е.clientY;
      ведём = false;
      менялось = false;
      пальцем = (е.pointerType === 'touch');

      if (пальцем) {
        ждём = setTimeout(function () { ждём = null; взяли(); }, ЖДАТЬ);
      }
    });

    function взяли() {
      if (!узел || ведём) return;
      ведём = true;
      узел.classList.add('тащим');
    }

    document.addEventListener('pointermove', function (е) {
      if (!узел) return;
      if (!ведём) {
        if (пальцем) return;                       /* ждём удержания */
        if (Math.abs(е.clientY - начало) < ПОРОГ) return;
        взяли();
      }
      /* Над кем рука. Сама ведомая строка мыши не ловит, поэтому под
         рукой оказывается именно сосед. */
      var под = document.elementFromPoint(е.clientX, е.clientY);
      var сосед = под && под.closest ? под.closest(ЧТО) : null;
      if (!сосед || сосед === узел || !где.contains(сосед)) return;

      var р = сосед.getBoundingClientRect();
      var ниже = е.clientY > р.top + р.height / 2;
      var было = узел.nextSibling;
      if (ниже) сосед.parentNode.insertBefore(узел, сосед.nextSibling);
      else сосед.parentNode.insertBefore(узел, сосед);
      if (узел.nextSibling !== было) менялось = true;
    });

    ['pointerup', 'pointercancel'].forEach(function (с) {
      document.addEventListener(с, function () {
        if (ждём) { clearTimeout(ждём); ждём = null; }
        узел = null;
        отпустить();
        if (!ведём) return;
        ведём = false;
        /* Отпустили после переноса — это не нажатие. Гасим ближайшее
           нажатие, иначе папка откроется ровно в тот миг, когда её
           только что поставили на место. */
        глушитель();
        if (менялось && что.сложили) {
          что.сложили([].slice.call(где.querySelectorAll(ЧТО)));
        }
        менялось = false;
      });
    });

    function глушитель() {
      function разом(е) {
        е.stopPropagation();
        е.preventDefault();
        document.removeEventListener('click', разом, true);
      }
      document.addEventListener('click', разом, true);
      setTimeout(function () {
        document.removeEventListener('click', разом, true);
      }, 350);
    }
  };
})();
