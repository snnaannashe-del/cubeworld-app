    b = серый + (b - серый) * s;

    var t = (число(з.t, 0)) / 100;
    if (t < 0) { var k = 1 + t; r *= k; g *= k; b *= k; }
    else if (t > 0) { r += (255 - r) * t; g += (255 - g) * t; b += (255 - b) * t; }

    return [зажать(r), зажать(g), зажать(b)].join(',');
