/* ═══════════════════════════════════════════════════════════════════════
   ОБЩИЕ КУСКИ ЭКРАНА.

   Подсказка, лист с пунктами, кружок с лицом, безопасный текст. Всё то,
   что иначе каждый экран напишет себе заново — и получится пять разных
   подсказок и четыре разных кружка.

   Правило файла: здесь только то, чем пользуются ДВА и больше экранов.
   Нужное одному экрану живёт в самом экране.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';

  var CW = окно.CW = окно.CW || {};

  /* ── ОДНА МЕРКА ДЛЯ ВСЕХ ПОИСКОВ ─────────────────────────────────────
     Слово, по которому сравниваем: без заглавных и без ё.

     Ровно это же делает сервер в своих поисках (искомое() в database.py).
     Если здесь мерить иначе, получается разнобой: окно поиска находит
     «Петра» по запросу «пет», а список чатов на том же запросе его
     прячет — и человек решает, что переписка пропала.

     Почему ё превращается в е: имя у человека с ё, а набирают его чаще
     через е. Ждать попадания в нужную букву — терять находки впустую. */
  CW.ровно = function (т) {
    return String(т == null ? '' : т).toLowerCase().replace(/ё/g, 'е');
  };

  /* ── текст, который не сломает разметку ──────────────────────────── */
  CW.безопасно = function (с) {
    return String(с == null ? '' : с)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;')
      .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  };

  /* Ссылки делаем кликабельными, остальное оставляем как есть. */
  CW.сСсылками = function (текст) {
    return CW.безопасно(текст).replace(
      /(https?:\/\/[^\s<]+)/g,
      '<a href="$1" target="_blank" rel="noopener">$1</a>');
  };

  /* ── текст с пометками формата ──────────────────────────────────────
     То же, что «сСсылками», плюс четыре пометки, которые ставит кнопка
     «форматировать» у поля ввода:

         **жирный**   __курсив__   ~~зачёркнутый~~   `код`

     Порядок важен. Сначала ссылки, потом пометки — и пометки обходят
     то, что уже стало ссылкой: в адресе легко встречается и нижнее
     подчёркивание, и волна, и разбор превратил бы половину адреса в
     курсив, а ссылка после этого вела бы не туда.

     Разрешаем пометке закрываться только на той же строке: иначе одна
     забытая звёздочка в начале делает жирным весь остаток переписки. */
  CW.сРазметкой = function (текст) {
    /* Порядок здесь важен, и он такой:

       1. Обезвредили чужие угловые скобки.
       2. Ссылка с подписью «[текст](адрес)» — ПЕРВОЙ. Если сначала
          сделать ссылками голые адреса, разбор увидит «[текст](<a…»,
          и подпись потеряется, а ссылка поедет не туда.
       3. Голые адреса в оставшемся тексте.
       4. Пометки формата — только ВНЕ готовых ссылок: в адресе легко
          встречается и нижнее подчёркивание, и волна.
       5. Цитата по строкам: у неё нет закрывающего знака.
       6. Смайлы в своих значках, чтобы их красил выбранный цвет. */
    var готово = CW.безопасно(текст).replace(
      /\[([^\]\n]+)\]\((https?:\/\/[^\s)<]+)\)/g,
      '<a href="$2" target="_blank" rel="noopener">$1</a>');

    готово = готово.split(/(<a\b[^>]*>[\s\S]*?<\/a>)/g).map(function (кусок) {
      if (кусок.slice(0, 2) === '<a') return кусок;
      return кусок.replace(/(https?:\/\/[^\s<]+)/g,
        '<a href="$1" target="_blank" rel="noopener">$1</a>');
    }).join('');

    готово = готово.split(/(<a\b[^>]*>[\s\S]*?<\/a>)/g).map(function (кусок) {
      if (кусок.slice(0, 2) === '<a') return кусок;
      return кусок
        .replace(/\*\*([^*\n]+)\*\*/g, '<b>$1</b>')
        .replace(/__([^_\n]+)__/g, '<i>$1</i>')
        .replace(/~~([^~\n]+)~~/g, '<s>$1</s>')
        .replace(/\+\+([^+\n]+)\+\+/g, '<u>$1</u>')
        .replace(/\|\|([^|\n]+)\|\|/g, '<span class="скрытый">$1</span>')
        .replace(/`([^`\n]+)`/g, '<code>$1</code>');
    }).join('');

    готово = готово.split('\n').map(function (строка) {
      return /^&gt;\s?/.test(строка)
        ? '<span class="цитата">' + строка.replace(/^&gt;\s?/, '') + '</span>'
        : строка;
    }).join('\n');

    return CW.смайлы ? CW.смайлы.вТексте(готово) : готово;
  };

  /* ── ПОМЕТКИ ФОРМАТА: ПОСТАВИТЬ И СНЯТЬ ───────────────────────────
     Одна на всю программу: её зовут и полка формата у поля ввода, и
     меню сообщения, и чаты, и группы, и избранное, и лента.

         CW.пометить('текст', 'жирный')      «**текст**»
         CW.пометить('**текст**', 'жирный')  «текст»
         CW.пометить('**текст**', 'курсив')  «__**текст**__»
         CW.пометить('__**т**__', 'жирный')  «__т__»

     ── ПОЧЕМУ ЭТО НЕ ПРОСТО «ПРИКЛЕИТЬ ЗВЁЗДОЧКИ» ──
     Пометки вкладываются одна в другую, и снять надо ИМЕННО ту, по
     которой нажали, где бы она ни лежала — снаружи или внутри.
     Прежде проверялся только самый внешний слой: нажал «Жирный» на
     «__**текст**__» — и получалось «**__**текст**__**», мусор из
     звёздочек, который человек видел в поле ввода.

     Поэтому сперва разбираем строку на слои, а потом собираем обратно
     без того слоя, который сняли (или с новым слоем снаружи). */
  var ПАРЫ = {
    'жирный':       '**',
    'курсив':       '__',
    'моно':         '`',
    'зачёркнутый':  '~~',
    'подчёркнутый': '++',
    'скрытый':      '||'
  };
  CW.пометкиФормата = ПАРЫ;

  function разобратьСлои(текст) {
    var слои = [], ядро = String(текст == null ? '' : текст), шло = true;
    while (шло) {
      шло = false;
      for (var имя in ПАРЫ) {
        if (!ПАРЫ.hasOwnProperty(имя)) continue;
        var м = ПАРЫ[имя], д = м.length;
        if (ядро.length > д * 2 && ядро.slice(0, д) === м && ядро.slice(-д) === м) {
          /* Знак должен закрывать именно эту обёртку, а не встретиться
             в середине: «**а** и **б**» — не жирная строка целиком. */
          var внутри = ядро.slice(д, ядро.length - д);
          if (внутри.indexOf(м) < 0 || внутри.indexOf(м) !== внутри.lastIndexOf(м)) {
            слои.push(имя); ядро = внутри; шло = true; break;
          }
        }
      }
    }
    return { слои: слои, ядро: ядро };
  }

  function собратьСлои(слои, ядро) {
    var т = ядро;
    for (var i = слои.length - 1; i >= 0; i--) т = ПАРЫ[слои[i]] + т + ПАРЫ[слои[i]];
    return т;
  }

  CW.пометить = function (текст, вид, ссылка) {
    var т = String(текст == null ? '' : текст);

    if (вид === 'цитата') {
      /* У цитаты нет закрывающего знака: она живёт строкой. */
      var строки = т.split('\n');
      var ужеВсе = строки.every(function (с) { return /^>\s?/.test(с) || !с.trim(); });
      return строки.map(function (с) {
        if (!с.trim()) return с;
        return ужеВсе ? с.replace(/^>\s?/, '') : '> ' + с;
      }).join('\n');
    }

    if (вид === 'ссылка') {
      var уже = т.match(/^\[([\s\S]+)\]\((\S+)\)$/);
      if (!ссылка) return уже ? уже[1] : т;      /* без адреса — снимаем */
      return '[' + (уже ? уже[1] : т) + '](' + ссылка + ')';
    }

    if (!ПАРЫ[вид]) return т;
    if (!т) return ПАРЫ[вид] + ПАРЫ[вид];        /* пустое поле: ставим пару */

    /* ── ПОМЕТКА ВНУТРИ ЦИТАТЫ ──
       Цитата — это знак «>» в начале строки, и он должен остаться
       первым. Если положить жирный поверх цитаты, выйдет «**> текст**»:
       знак цитаты попадёт внутрь звёздочек, строка перестанет быть
       цитатой, а звёздочки человек увидит как мусор — ровно это и
       показывала Анна. Поэтому у цитаты снимаем знаки, работаем с
       содержимым и возвращаем знаки на место. */
    var строкиЦ = т.split('\n');
    var цитатаВся = строкиЦ.some(function (с) { return /^>\s?/.test(с); })
      && строкиЦ.every(function (с) { return /^>\s?/.test(с) || !с.trim(); });
    if (цитатаВся) {
      return строкиЦ.map(function (с) {
        if (!с.trim()) return с;
        var без = с.replace(/^>\s?/, '');
        return '> ' + CW.пометить(без, вид);
      }).join('\n');
    }

    var р = разобратьСлои(т);
    var где = р.слои.indexOf(вид);
    if (где >= 0) р.слои.splice(где, 1);          /* сняли именно её */
    else р.слои.unshift(вид);                     /* новая — снаружи */
    return собратьСлои(р.слои, р.ядро);
  };

  /* ── СТРОКА БЕЗ ПОМЕТОК ──
     Для списков: в строке «последнее сообщение» разметку не рисуют
     (там одна строка простым текстом), и звёздочки с волнами человек
     видит как мусор — «**вывыва**». Поэтому в списках показываем
     сообщение без знаков разметки, а сами знаки остаются в тексте.

         CW.безМеток('**привет** и `код`')  →  «привет и код» */
  CW.безМеток = function (текст) {
    текст = String(текст == null ? '' : текст);
    /* Кнопки под сообщением лежат его последней строкой. В списке
       чатов и в любом другом коротком показе этой строки быть не
       должно. Снимает её тот же файл, что её и пишет
       (shared/кнопки-сообщения.js): второго знания о метке в
       программе нет. */
    if (CW.кнопкиСообщения) текст = CW.кнопкиСообщения.без(текст);
    return текст
      .replace(/^>\s?/gm, '')
      .replace(/\[([^\]\n]+)\]\((https?:[^\s)]+)\)/g, '$1')
      .replace(/\*\*|__|~~|\+\+|\|\||`/g, '');
  };

  /* Скрытый текст («||так||») открывается нажатием. Слушатель один на
     страницу и ловит нажатия всплытием: пузырей в ленте сотни, и
     вешать на каждый свой обработчик незачем. */
  документ.addEventListener('click', function (е) {
    var с = е.target && е.target.closest && е.target.closest('.скрытый');
    if (с) с.classList.toggle('открыт');
  });

  /* ── ЛИЦО: КАРТИНКА ИЛИ СМАЙЛ ─────────────────────────────────────
     Сервер хранит лицо человека и значок куба ОДНОЙ строкой: там может
     лежать и адрес картинки, и смайл. Отличать их приходилось в
     четырёх местах (полоса разделов, мир, профиль, кружок в списках),
     и три из них этого не делали — смайл уезжал в адрес картинки, и
     браузер честно просил у сервера страницу «/😄».

         CW.картинкаЛи('data:image/…')   true
         CW.картинкаЛи('😄')             false

     Длинная строка — всегда картинка: относительные адреса сервера
     («media/ab12.jpg») не начинаются ни со слэша, ни с http. Смайл
     длиннее шестнадцати знаков не бывает даже с модификаторами. */
  CW.картинкаЛи = function (что) {
    что = String(что || '');
    if (!что) return false;
    return /^(https?:|data:|blob:|\/)/.test(что) || что.length > 16;
  };

  /* Ролик это или снимок — решаем по концу адреса. Признак один на всю
     программу: его спрашивают склад лиц, кольцо в портфолио и окно
     создания куба. Хвост с «?» отрезаем: у адресов бывает подпись.

         CW.видеоЛи('/uploads/ab12.mp4')  true
         CW.видеоЛи('/uploads/ab12.jpg')  false */
  CW.видеоЛи = function (что) {
    var а = String(что || '').split('?')[0].toLowerCase();
    return /\.(mp4|webm|mov|m4v|ogv)$/.test(а) || а.indexOf('data:video') === 0;
  };

  /* ── ЦВЕТ: ПЕРЕВОДЫ И ТОН ЗНАКА ───────────────────────────────────
     Переводы «#rrggbb» ↔ RGB ↔ HSV и фильтр перекраски смайла. Лежат
     здесь, в общем ящике, а не в окне выбора знака: цвет значка теперь
     спрашивают четверо — само окно выбора, строка цвета в «Создать
     куб», табличка над кубом в мире и окно ключа. Держать их в окне
     выбора значило бы тащить ради одной формулы восемь полок смайлов.

         CW.вRGB('#0095F6')    {r:0, g:149, b:246}
         CW.изRGB(0,149,246)   '#0095f6'
         CW.вТон('#0095F6')    {h:223.6, s:1, v:0.96}
         CW.тонЗнака('#00c853') 'grayscale(1) sepia(1) …'

     Смайл красим фильтром, а не цветом текста: цветной смайл — это
     картинка в шрифте, и «color» ей не указ. Обесцвечиваем, кладём
     сепию (её жёлтый тон около 50°) и доворачиваем до нужного тона, а
     насыщенность с яркостью берём у самого цвета. */
  CW.вRGB = function (ц) {
    var т = String(ц).replace('#', '');
    if (т.length === 3) т = т[0]+т[0]+т[1]+т[1]+т[2]+т[2];
    return { r: parseInt(т.slice(0,2),16) || 0,
             g: parseInt(т.slice(2,4),16) || 0,
             b: parseInt(т.slice(4,6),16) || 0 };
  };
  CW.изRGB = function (r, g, b) {
    return '#' + [r,g,b].map(function (ч) {
      return ('0' + Math.round(ч).toString(16)).slice(-2);
    }).join('');
  };
  CW.вHSV = function (ц) {
    var п = CW.вRGB(ц), r = п.r/255, g = п.g/255, b = п.b/255;
    var макс = Math.max(r,g,b), мин = Math.min(r,g,b), д = макс - мин;
    var h = 0;
    if (д) {
      if (макс === r) h = 60 * (((g - b) / д) % 6);
      else if (макс === g) h = 60 * ((b - r) / д + 2);
      else h = 60 * ((r - g) / д + 4);
    }
    if (h < 0) h += 360;
    return { h: h, s: макс ? д / макс : 0, v: макс };
  };
  CW.изHSV = function (о) {
    var c = о.v * о.s, x = c * (1 - Math.abs(((о.h / 60) % 2) - 1)), m = о.v - c;
    var р = [[c,x,0],[x,c,0],[0,c,x],[0,x,c],[x,0,c],[c,0,x]][Math.floor(о.h / 60) % 6];
    return CW.изRGB((р[0]+m)*255, (р[1]+m)*255, (р[2]+m)*255);
  };
  CW.вТон = function (ц) { return CW.вHSV(ц); };
  CW.тонЗнака = function (ц) {
    var h = CW.вHSV(ц);
    return 'grayscale(1) sepia(1)'
         + ' hue-rotate(' + Math.round(h.h - 50) + 'deg)'
         + ' saturate(' + (1 + h.s * 5).toFixed(2) + ')'
         + ' brightness(' + (0.75 + h.v * 0.55).toFixed(2) + ')';
  };

  /* ── ЦВЕТ ЗНАЧКА КУБА ─────────────────────────────────────────────
     Цвет значка куба лежит у куба на сервере (поле icon_color). Но
     сервер обновляют не в ту же минуту, что страницы, и пока на нём
     старая сборка, он это поле молча выбрасывает: человек выбрал цвет,
     а в мире снова обычный смайл.

     Поэтому тот браузер, в котором куб создавали, помнит выбранный
     цвет и у себя. Сервер главнее: как только он начнёт отдавать своё
     значение, берётся оно, и цвет видят все, а не только создатель.

         CW.цветЗначка(куб)              '#4fc3f7' или ''
         CW.цветЗначка.запомнить(id, ц)  после создания куба
  */
  var ПАМЯТЬЦВ = 'cw_цвет_значка';
  function прочестьЦвета() {
    try { return JSON.parse(localStorage.getItem(ПАМЯТЬЦВ) || '{}') || {}; }
    catch (е) { return {}; }
  }
  CW.цветЗначка = function (куб) {
    if (!куб) return '';
    if (куб.icon_color) return куб.icon_color;
    var н = куб.id != null ? куб.id : куб;
    return прочестьЦвета()[String(н)] || '';
  };
  CW.цветЗначка.запомнить = function (номер, цвет) {
    if (номер == null || !цвет) return;
    try {
      var в = прочестьЦвета();
      в[String(номер)] = цвет;
      localStorage.setItem(ПАМЯТЬЦВ, JSON.stringify(в));
    } catch (е) {}
  };

  /* ── КУБ В МОЙ ЮНИВЕРС ────────────────────────────────────────────
     Юниверс — это отбор кубов, которые человек хочет видеть в мире.
     Куб, который он только что создал или в который только что вошёл
     по ключу, нужен ему наверняка: иначе он вернётся в мир и не найдёт
     там куба, которым минуту назад занимался.

     Пустой отбор значит «показываем всё» — трогать его нельзя: запись
     превратила бы «всё» в «только этот куб».

         CW.вЮниверс(14)   → Promise

     Отбор ложится и в браузер (мгновенно, мир перерисуется сам), и на
     сервер (чтобы с другого устройства мир был тот же). Сервер не
     ответил — в браузере уже лежит, этого хватит. */
  CW.вЮниверс = function (ид) {
    ид = String(ид == null ? '' : ид);
    if (!ид) return Promise.resolve();
    var отбор = [];
    try {
      var с = JSON.parse(CW.взять('cw_юниверс') || '[]');
      if (Array.isArray(с)) отбор = с.map(String);
    } catch (е) {}
    if (отбор.indexOf(ид) >= 0) return Promise.resolve();

    /* Пустой отбор значит «в мире стоят кубы площадки». Положить в него
       один номер — значит выгнать их из мира, поэтому сначала собираем
       туда кубы площадки, а потом добавляем новый. */
    var сперва = отбор.length ? Promise.resolve(отбор)
      : CW.спросить('/cubes', { тихо: true }).then(function (о) {
          var все = Array.isArray(о) ? о : ((о && о.items) || []);
          return все.filter(function (к) { return к && к.owner_id == null; })
                    .map(function (к) { return String(к.id); });
        }).catch(function () { return []; });

    return сперва.then(function (список) {
      if (список.indexOf(ид) < 0) список.push(ид);
      try { CW.положить('cw_юниверс', JSON.stringify(список)); } catch (е) {}
      return CW.спросить('/me/universe', {
        способ: 'POST', тело: { universe: список }, тихо: true
      }).catch(function () {});
    });
  };

  /* ── ДРОЖЬ ТЕЛЕФОНА ───────────────────────────────────────────────
     Одна на всю программу: игра трясёт телефон при ударе, остальные
     могут позвать её же.

         CW.вибро()        короткий щелчок: палец коснулся куба
         CW.вибро(3)       три толчка подряд: задето три куба
         CW.вибро(1, 'сильно')  один долгий: прямой удар

     Чем больше кубов задето, тем длиннее дрожь, но не бесконечно:
     восьми толчков хватает, чтобы почувствовать «много», а всё, что
     дольше секунды, читается уже как поломка телефона.

     Ни один браузер на маке и на айфоне этого не умеет, и это
     нормально: вызов просто ничего не делает. Телефон на андроиде
     чувствует всё.
  */
  CW.вибро = function (сколько, вид) {
    try {
      if (!окно.navigator || !окно.navigator.vibrate) return false;
      var н = Math.max(1, Math.min(8, Math.round(сколько || 1)));
      if (вид === 'сильно') return окно.navigator.vibrate(Math.min(220, 70 + н * 30));
      if (н === 1) return окно.navigator.vibrate(вид === 'тихо' ? 12 : 32);
      var ряд = [];
      for (var i = 0; i < н; i++) { ряд.push(34, 46); }
      ряд.pop();
      return окно.navigator.vibrate(ряд);
    } catch (е) { return false; }
  };

  /* ── подсказка внизу экрана ──────────────────────────────────────── */
  var часыПодсказки;
  CW.сказать = function (текст, сколько) {
    var п = документ.getElementById('cw-подсказка');
    if (!п) {
      п = документ.createElement('div');
      п.id = 'cw-подсказка';
      п.style.cssText =
        'position:fixed;left:50%;bottom:96px;transform:translateX(-50%);' +
        'border:1px solid var(--край2);border-radius:12px;' +
        'padding:9px 17px;font-size:0.8667rem;opacity:0;pointer-events:none;' +
        'transition:opacity .18s;z-index:9000;max-width:88vw;text-align:center;' +
        'color:var(--текст)';
      документ.body.appendChild(п);
    }
    п.textContent = текст;
    п.style.opacity = '1';
    clearTimeout(часыПодсказки);
    часыПодсказки = setTimeout(function () { п.style.opacity = '0'; },
                               сколько || 2300);
  };

  /* ── лист с пунктами ─────────────────────────────────────────────────
     Одно меню на всю программу: меню сообщения, выбор срока, подтверждение
     удаления — всё это он. В прежней программе таких листов было девять
     штук, каждый со своим поведением.

     Пункты:
       {зн: CW.значок('копия', 16), подпись:'Копировать', делать:fn, опасная:true, выбран:true}
       '-'                               черта
       {заголовок:'Скрыть через'}        подпись раздела
     Куда: {x, y}    — около какой точки показать (лист встаёт НАД ней);
           {узел: кнопка} — повиснуть ПОД этой кнопкой, по её правому
                            краю. Так ведут себя меню у кнопок в шапке:
                            меню должно выезжать из-под своей кнопки, а
                            не всплывать посреди окна — иначе непонятно,
                            чьё оно и к чему относится.
           {вКадре: узел} — выехать снизу ВНУТРИ этого узла, во всю его
                            ширину. Так в ленте открываются «Действия»:
                            лист принадлежит кадру с роликом, а не
                            экрану, и ролик из-за него виден.
           ничего       — посередине экрана. */
  CW.лист = function (пункты, куда) {
    CW.закрытьЛист();

    var вКадре = куда && куда.вКадре;
    var сквозь = !!(куда && куда.прозрачный);
    var подложка = документ.createElement('div');
    подложка.id = 'cw-подложка';
    подложка.style.cssText = вКадре
      /* Внутри кадра затемнения почти нет: полка и так пропускает
         ролик сквозь себя, а второй тёмный слой поверх него сводил
         всю прозрачность на нет. */
      ? 'position:absolute;inset:0;background:rgba(3,4,10,.14);z-index:40'
      /* «Прозрачный» — меню поверх мира: ни затемнения, ни второго
         слоя. Мир за ним виден целиком, а меню всё равно ловит
         нажатие мимо себя и закрывается. */
      : сквозь
        ? 'position:fixed;inset:0;background:transparent;z-index:9100'
        : 'position:fixed;inset:0;background:rgba(0,0,0,.55);z-index:9100';

    var лист = документ.createElement('div');
    /* Имя класса нужно оформлению: зона «Мелкие окна и меню» красит
       именно эти листы, а найти их по стилю в строке нельзя. */
    лист.className = 'cw-лист' + (сквозь ? ' прозрачный' : '');
    лист.style.cssText =
      'position:absolute;border:1px solid var(--край2);' +
      'border-radius:15px;box-shadow:var(--тень);overflow:hidden;' +
      'min-width:210px;padding:5px;visibility:hidden';

    пункты.forEach(function (э) {
      if (э === '-') {
        var ч = документ.createElement('div');
        ч.style.cssText = 'border-top:1px solid var(--край);margin:5px 0';
        лист.appendChild(ч);
        return;
      }
      if (э.заголовок) {
        var з = документ.createElement('div');
        з.style.cssText =
          'font-size:0.7rem;letter-spacing:.09em;text-transform:uppercase;' +
          'color:var(--текст3);padding:9px 13px 6px';
        з.textContent = э.заголовок;
        лист.appendChild(з);
        return;
      }
      var б = документ.createElement('button');
      б.style.cssText =
        'display:flex;align-items:center;gap:11px;width:100%;border:none;' +
        'background:none;font-size:0.9333rem;padding:11px 13px;cursor:pointer;' +
        'text-align:left;border-radius:10px;color:' +
        (э.опасная ? 'var(--красный)' : э.выбран ? 'var(--синий)' : 'var(--текст)');
      б.onmouseenter = function () { б.style.background = 'var(--поле)'; };
      б.onmouseleave = function () { б.style.background = 'none'; };
      б.innerHTML =
        '<span style="width:20px;text-align:center;opacity:.85;flex:0 0 20px">' +
        (э.зн || '') + '</span><span>' + CW.безопасно(э.подпись) + '</span>';
      б.onclick = function () {
        CW.закрытьЛист();
        if (э.делать) э.делать();
      };
      лист.appendChild(б);
    });

    подложка.appendChild(лист);
    подложка.onclick = function (е) {
      if (е.target === подложка) CW.закрытьЛист();
    };

    /* Escape закрывает меню, как и любое окно программы. Раньше его
       закрывало только нажатие мимо: человек жал Escape, меню стояло,
       и следующее нажатие доставалось подложке вместо кнопки под ней.
       Слушатель живёт, только пока меню открыто, и снимает себя сам. */
    документ.addEventListener('keydown', ключЛиста, true);
    (вКадре || документ.body).appendChild(подложка);

    /* ставим так, чтобы помещался на экране */
    requestAnimationFrame(function () {
      var ш = лист.offsetWidth, в = лист.offsetHeight;
      var x, y;

      if (вКадре) {
        /* Снизу во всю ширину кадра: это не всплывающее меню у кнопки,
           а полка, выехавшая из нижнего края. Вид задаёт класс в
           window.css — там же, где «окно в кадре»: один вид описан в
           одном месте, а не здесь строкой и там правилом. */
        лист.classList.add('вкадре');
        лист.style.visibility = 'visible';
        return;
      }

      if (куда && куда.узел && куда.узел.getBoundingClientRect) {
        /* Под кнопкой и с ней вровень. С какой стороны ровнять —
           решает место кнопки: у правого края шапки меню встаёт
           правыми краями, у левого (кружок лица в мире) — левыми.
           Иначе меню уезжало от своей кнопки через полэкрана и
           читалось как чужое. Не влезает вниз — уходит вверх. */
        var р = куда.узел.getBoundingClientRect();
        /* Широкая кнопка (строка списка в форме) — меню встаёт ровно по
           ней, во всю её ширину: так список читается как продолжение
           строки, а не как случайное окошко рядом. */
        if (куда.поШирине && р.width > ш) лист.style.width = Math.round(р.width) + 'px';
        var слева = (р.left + р.width / 2) < окно.innerWidth / 2;
        x = куда.поШирине ? р.left : (слева ? р.left : р.right - ш);
        ш = лист.offsetWidth;
        x = Math.min(Math.max(8, x), окно.innerWidth - ш - 8);
        y = р.bottom + 8;
        if (y + в > окно.innerHeight - 8) y = Math.max(8, р.top - в - 8);
      } else {
        var цx = (куда && куда.x) || окно.innerWidth / 2;
        var цy = (куда && куда.y) || окно.innerHeight / 2;
        x = Math.min(Math.max(8, цx - ш / 2), окно.innerWidth - ш - 8);
        y = цy - в - 8;
        if (y < 8) y = Math.min(цy + 12, окно.innerHeight - в - 8);
      }

      лист.style.left = x + 'px';
      лист.style.top = Math.max(8, y) + 'px';
      лист.style.visibility = 'visible';
    });
  };

  function ключЛиста(е) {
    if (е.key !== 'Escape') return;
    if (!документ.getElementById('cw-подложка')) return;
    /* Гасим событие: под меню стоит окно, и оно тоже закрывается по
       Escape. Человек хотел убрать меню, а закрыл бы всё окно. */
    е.stopPropagation();
    е.preventDefault();
    CW.закрытьЛист();
  }

  CW.закрытьЛист = function () {
    документ.removeEventListener('keydown', ключЛиста, true);
    var п = документ.getElementById('cw-подложка');
    if (п && п.parentNode) п.parentNode.removeChild(п);
  };

  /* ── положить в буфер обмена ──────────────────────────────────────
     Одна на всю программу. Своя такая же лежала в десяти файлах: в
     ключе куба, в подарке ключа, в приглашениях, в «поделиться», в
     выводе денег, в свайпе, в избранном, в рефералах, на титульной и
     в тарифах — десять раз один и тот же текстарий за экраном.

     Запасной путь обязателен: буфер обмена браузер даёт только по
     https и только в ответ на жест человека. Без запасного пути
     кнопка в половине случаев молчит, и человек читает это как
     поломку.

         CW.вбуфер(ссылка, 'Ссылка скопирована');
  */
  CW.вбуфер = function (текст, весть) {
    текст = String(текст == null ? '' : текст);
    весть = весть || 'Скопировано';
    function старым() {
      var п = документ.createElement('textarea');
      п.value = текст;
      п.style.cssText = 'position:fixed;left:-9999px;top:0';
      документ.body.appendChild(п);
      п.select();
      var вышло = false;
      try { вышло = документ.execCommand('copy'); } catch (е) {}
      документ.body.removeChild(п);
      CW.сказать(вышло ? весть : 'Браузер не дал скопировать');
      return вышло;
    }
    var б = окно.navigator && окно.navigator.clipboard;
    if (б && б.writeText) {
      return б.writeText(текст)
        .then(function () { CW.сказать(весть); return true; })
        .catch(function () { return старым(); });
    }
    return Promise.resolve(старым());
  };

  /* ── ужать картинку ───────────────────────────────────────────────
     Своя такая же лежала в четырёх местах: значок куба (64 точки), лицо
     в профиле, обложка Портфолио и обои для чатов (720). Разница между
     ними была только в числе — и в том, что одна из них считала сторону
     по ширине, а другая по длинной стороне, и картинка «лёжа» в разных
     окнах выходила разного размера.

     Считаем по длинной стороне: так ни одна сторона не вылезет за
     заданный предел, какой бы ни была картинка.

         CW.ужать(файл, 720).then(function (адрес) { … });

     Отдаёт строку data:image/jpeg. Качество по умолчанию 0.82 —
     середина между прежними 0.75 и 0.86.
  */
  CW.ужать = function (файл, бок, качество) {
    бок = бок || 720;
    return new Promise(function (готово, беда) {
      var чтец = new окно.FileReader();
      чтец.onerror = беда;
      чтец.onload = function () {
        var и = new окно.Image();
        и.onerror = беда;
        и.onload = function () {
          var к = Math.min(1, бок / Math.max(и.width, и.height));
          var ш = Math.max(1, Math.round(и.width * к));
          var в = Math.max(1, Math.round(и.height * к));
          var холст = документ.createElement('canvas');
          холст.width = ш; холст.height = в;
          холст.getContext('2d').drawImage(и, 0, 0, ш, в);
          готово(холст.toDataURL('image/jpeg', качество || 0.82));
        };
        и.src = String(чтец.result || '');
      };
      чтец.readAsDataURL(файл);
    });
  };

  /* ── склонение по числу ───────────────────────────────────────────
     Правило русского числа одно на всю программу, а написано оно было
     семь раз: в группах, в маркетплейсе, в комментариях, в участниках,
     в юниверсе, в аналитике и в окне группы. Шесть раз одинаково, а
     седьмой — с ошибкой: в юниверсе выходило «3 кубов» и «1 куба».

         CW.склонение(3, 'куб', 'куба', 'кубов')   → 'куба'
  */
  /* ── ЧИСЛО ПО ПРАВИЛАМ ЯЗЫКА ──
         CW.число(1234567)        русский: 1 234 567   английский: 1,234,567
         CW.число(12.5, 2)        русский: 12,50       английский: 12.50

     В программе больше десятка мест писали toLocaleString('ru'), и на
     английской программе баланс выглядел по-русски: «1 234,56». Разряды
     и запятая - свойство языка, а не кошелька. */
  CW.число = function (з, знаков) {
    var н = Number(з);
    if (!isFinite(н)) return '0';
    var язык = (CW.язык && CW.язык()) || 'ru';
    try {
      return н.toLocaleString(язык, знаков == null ? undefined
        : { minimumFractionDigits: знаков, maximumFractionDigits: знаков });
    } catch (е) {
      return знаков == null ? String(н) : н.toFixed(знаков);
    }
  };

  /* Правило выбора формы зависит от языка: по-английски форм две, по-русски
     три. Поэтому сам выбор делает shared/lang.js (Т.мн) — он один знает,
     на каком языке сейчас программа. Здесь остаётся русское правило на
     случай, если словаря на странице нет: программа должна работать и
     без перевода. */
  CW.склонение = function (н, один, два, много, иное) {
    if (окно.Т && окно.Т.мн) return окно.Т.мн(н, один, два, много, иное);
    var ч = Math.abs(Number(н) || 0) % 100;
    var х = ч % 10;
    if (ч >= 11 && ч <= 14) return много;
    if (х === 1) return один;
    if (х >= 2 && х <= 4) return два;
    return много;
  };

  /* ── выйти из программы ───────────────────────────────────────────
     Тот же вопрос, слово в слово, стоял в двух общих файлах: в меню
     раздела (shell.js) и в меню лица (account.js). Два одинаковых
     вопроса — это два места, где однажды разойдутся слова.

         CW.спроситьВыход(узел);   узел — кнопка, под которой встать

     Вопрос встаёт под той самой кнопкой, из меню которой его позвали,
     и ничего за собой не затемняет: мир виден сквозь него. Посреди
     экрана, на чёрной подложке, он читался как беда, хотя человек
     всего лишь задел пункт меню.

     Строки «Остаться» в нём нет: кнопка, которая ничего не делает,
     занимает ровно столько же места, сколько настоящая. Остаться —
     значит нажать мимо или Escape, как в любом нашем меню.
  */
  CW.спроситьВыход = function (узел) {
    CW.лист([
      { заголовок: Т('Выйти из CubeWorld?') },
      { зн: CW.значок('выйти', 16), подпись: Т('Выйти'), опасная: true,
        делать: function () {
          CW.выйти(true).then(function () { CW.уйти(CW.раздел('index')); });
        } }
    ], { узел: узел || null, прозрачный: true });
  };

  /* ── узел ─────────────────────────────────────────────────────────
     Три строки, которые лежали в двадцати четырёх файлах своими
     копиями: «ок», «кусок», «э». Разница между копиями была одна и
     незаметная: одни клали текст (textContent), другие разметку
     (innerHTML). Теперь это видно по имени.

         CW.эл('div', 'имя', 'текст')     текстом
         CW.элВ('div', 'имя', '<b>…</b>') разметкой
         CW.кусок('имя', '<b>…</b>')      то же, но всегда div
  */
  CW.эл = function (тег, класс, текст) {
    var у = документ.createElement(тег);
    if (класс) у.className = класс;
    if (текст != null && текст !== '') у.textContent = текст;
    return у;
  };
  CW.элВ = function (тег, класс, внутри) {
    var у = документ.createElement(тег);
    if (класс) у.className = класс;
    if (внутри != null) у.innerHTML = внутри;
    return у;
  };
  CW.кусок = function (класс, внутри) { return CW.элВ('div', класс, внутри); };

  /* ── «СЕЙЧАС ПОСМОТРЮ»: ОДНА СТРОКА ОЖИДАНИЯ НА ВСЮ ПРОГРАММУ ─────
         CW.ждём(узел)          поставить строку ожидания
         CW.ждём.слово          само слово, если нужно вставить в разметку

     Слов было три, и человек видел их вперемешку: в папках «Смотрю…»,
     в кошельке «Спрашиваю сервер…», в маркетплейсе «Открываю…». Одно и
     то же ожидание, три разных слова — списки выглядели так, будто их
     писали разные люди. Теперь слово одно и лежит в одном месте.

     Слово - «Загрузка». Прежде здесь стояло «Смотрю…», от первого
     лица, как говорит остальная программа. Анна попросила заменить:
     «Смотрю» звучит так, будто программа что-то разглядывает, а она
     просто грузит страницу. */
  CW.ждём = function (куда) {
    if (!куда) return куда;
    куда.innerHTML = '<div class="пусто-строка">' + CW.ждём.слово + '</div>';
    return куда;
  };
  CW.ждём.слово = 'Загрузка…';

  /* ── кружок с лицом ──────────────────────────────────────────────────
     ОДИН хозяин у кружка. Картинка грузится ВНЕ страницы и попадает в
     кружок только загруженной. Не загрузилась — остаётся значок, и
     пустого чёрного кружка не бывает.

     Это та самая правка, из-за которой кружок группы принимал пять видов:
     прежде <img> клали сразу, а правило «есть снимок — прячем значок»
     срабатывало по наличию узла, а не по наличию пикселей. */
  CW.кружок = function (настройки) {
    настройки = настройки || {};
    var размер = настройки.размер || 42;
    var к = документ.createElement('div');
    к.className = 'cw-кружок';
    к.style.cssText =
      'width:' + размер + 'px;height:' + размер + 'px;flex:0 0 ' + размер + 'px;' +
      'border-radius:50%;overflow:hidden;position:relative;display:flex;' +
      'align-items:center;justify-content:center;font-size:' +
      Math.round(размер * 0.44) + 'px;background:' +
      /* Заглушка голубо-розовая - одна на всю программу и на обе темы.
         Краска названа в shared/style.css, именами --лицо-заливка и
         --лицо-краска, и берётся отсюда, а не пишется числом: прежде
         здесь стоял белый, и на светлой теме кружок без снимка
         пропадал на белой странице. Свой цвет куба, если он передан,
         остаётся своим. */
      (настройки.цвет || 'var(--лицо-заливка)') +
      ';color:var(--лицо-краска);user-select:none';

    /* ── ОДНО ЛИЦО НА ВСЮ ПРОГРАММУ ──
       Прежде сюда приходил смайл: '👤' у человека, '👥' у группы, '📦'
       у куба. Смайл у каждой системы свой, и человек видел в чатах одно
       лицо, в поиске другое, в уведомлениях третье. Теперь кружок сам
       переводит смайл в наш значок, а когда значка не передали — рисует
       знак по роду. Чего в нашем наборе нет — остаётся смайлом: лучше
       чужой знак, чем пустое место.

       ── ЧТО СТОИТ, ПОКА СВОЕГО ЛИЦА НЕТ ──
       Пустых мест у нас не бывает, и выдумывать для каждого списка
       свою заглушку нельзя: Анна прислала два снимка, где у одного и
       того же человека в ленте одна картинка, а в комментариях другая.

       Теперь заглушка одна и зависит только от РОДА:

           человек   значок «человек»   (он же у себя в шапке)
           группа    значок «люди»
           куб       значок «куб»
           эфир      значок «плёнка»

       Род можно назвать прямо («род: "группа"»), а можно не называть:
       кружок с номером человека - это человек, с номером группы -
       группа. Буквы имени вместо лица здесь больше нет: в ленте
       стояла первая буква, и у человека без имени это был ноль из
       номера, а у всех остальных - кружок со значком. */
    var знак = документ.createElement('span');
    var что = настройки.значок || '';
    var свой = '';           /* имя нашего значка, если оно уже известно */

    /* Куб подписывают тремя способами: смайлом, своей фотографией и
       именем нашего значка с приставкой «зн:» - так подписаны восемь
       готовых кубов площадки, у которых хозяина нет. Разбирает это
       CW.значокКуба, тот же, что в мире и в Юниверсе. Без него в
       поиске у этих кубов в кружке стояли буквы «зн:свет». */
    if (что && что.indexOf('зн:') === 0 && CW.значокКуба) {
      var разбор = CW.значокКуба(что);
      if (разбор.вид === 'линия') { свой = разбор.имя; что = ''; }
      else if (разбор.вид === 'фото') { настройки.снимок = разбор.адрес; что = ''; }
      else { что = разбор.знак || ''; }
    }

    var наш = свой || ((CW.знакПоСмайлу && что) ? CW.знакПоСмайлу(что) : '');
    var ПОРОДУ = { человек: 'человек', группа: 'люди', куб: 'куб', эфир: 'плёнка' };
    var род = настройки.род
            || (настройки.группа ? 'группа' : '')
            || (настройки.кто ? 'человек' : '');
    if (!что) наш = ПОРОДУ[род] || 'человек';
    if (наш && CW.значок) {
      /* Тот же знак и та же мерка, что у склада лиц: имя класса
         «лицо-знак», а как он стоит и какой он доли - сказано один раз
         в shared/style.css. Прежде здесь была своя мерка (46 сотых
         кружка) и свой строчный flex: рядом с кружками склада (60
         сотых) значки выходили разного размера, и Анна это увидела.

         Строчным остаётся только свой цвет, если его передали: у куба
         он свой. */
      знак.className = 'лицо-знак';
      if (настройки.цветЗнака) знак.style.color = настройки.цветЗнака;
      знак.innerHTML = CW.значок(наш);
    } else {
      знак.textContent = что || '👤';
      /* Смайл цветом не красится: это картинка в шрифте. Красим
         фильтром — тем же, что в окне выбора значка. */
      if (настройки.цветЗнака && CW.тонЗнака) {
        знак.style.filter = CW.тонЗнака(настройки.цветЗнака);
      }
    }
    к.appendChild(знак);

    /* ── ЛИЦО ЧЕЛОВЕКА — ЧЕРЕЗ ОДИН СКЛАД ──
       Передали «кто» (номер человека) — снимком распоряжается
       shared/лица.js: он помнит, у кого какое лицо, просит картинку
       один раз на всех и перерисовывает кружок, когда человек сменил
       снимок. Кружки без номера (группа, куб, эфир) идут прежним
       путём: у них не лицо, а свой значок или своя картинка. */
    if (настройки.кто && CW.лица) {
      CW.лица.знать(настройки.кто, настройки.снимок, настройки.версия);
      CW.лица.одеть(к, настройки.кто);
      return к;
    }

    /* Картинка группы — тот же склад, только ключ с пометкой «г:».
       Иначе лицо человека №5 встало бы группе №5. */
    if (настройки.группа && CW.лица) {
      CW.лица.группа(к, настройки.группа, настройки.версия);
      return к;
    }

    /* Короткая строка — это смайл, а не адрес: ставим его знаком и
       картинку не просим. */
    if (настройки.снимок && !CW.картинкаЛи(настройки.снимок)) {
      знак.textContent = настройки.снимок;
      знак.style.cssText = 'display:flex;align-items:center;justify-content:center;'
                         + 'font-size:' + Math.round(размер * 0.52) + 'px';
    } else if (настройки.снимок) {
      var и = new Image();
      и.alt = '';
      и.onload = function () {
        и.style.cssText =
          'position:absolute;inset:0;width:100%;height:100%;object-fit:cover';
        к.appendChild(и);
        знак.style.display = 'none';
      };
      и.onerror = function () { /* остаётся значок — и это законный вид */ };
      /* Через CW.файл: сервер отдаёт адреса относительными, а
         страницы живут на другом домене. */
      и.src = CW.файл ? CW.файл(настройки.снимок) : настройки.снимок;
      if (и.complete && и.naturalWidth > 0) и.onload();
    }
    return к;
  };

  /* ── ЛИЦО ЧЕЛОВЕКА ПО ЕГО НОМЕРУ ──────────────────────────────────

     Списки переписок, участников и прочие ряды приходят с сервера без
     фотографии: в ответе есть имя и номер, а снимок лежит отдельно по
     адресу /users/{номер}/avatar. Поэтому в чатах у всех стояло одно и
     то же лицо линиями, и отличить Фатиму от Тандира можно было только
     по подписи.

     Этот помощник дорисовывает настоящее лицо поверх значка:

       • просит снимок, только когда строка доехала до глаз, и ровно
         один раз на человека — иначе список из полусотни переписок
         уходил бы полусотней запросов в одну секунду;
       • фотографии нет — сервер отдаёт прозрачную точку 1×1. Её мы
         узнаём по ширине и оставляем значок: пустой серый круг хуже
         честного значка;
       • сорвалось — тоже остаётся значок. Пустоты не бывает никогда.

     Снимок сервер разрешает брать кому угодно и держать сутки в памяти
     браузера, так что ключ здесь не нужен и повторных запросов не
     будет. */
  /* узел — кружок (.лицо, .картинка, что угодно), внутри которого уже
     нарисован значок. Номер — чей это человек.

     Сам снимок тянет склад лиц (shared/лица.js): здесь остаётся
     только сказать ему, чьё лицо в этом узле. Своего запроса у этого
     помощника больше нет — иначе одно лицо жило бы в программе
     дважды, и две копии расходились бы при смене снимка. */
  CW.лицоЧеловека = function (узел, номер, версия) {
    if (!узел || !номер || !CW.лица) return;
    if (версия) CW.лица.знать(номер, '', версия);
    CW.лица.одеть(узел, номер);
  };

  /* ── ТЕГИ: ОДНО МЕСТО НА ВСЮ ПРОГРАММУ ────────────────────────────

     Теги в программе живут в трёх видах, и это не наша прихоть, а
     то, что приезжает с сервера: списком ['танцы'], строкой с JSON
     внутри '["танцы"]' и просто строкой, которую человек напечатал
     руками: «#танцы #море». Разбор был написан трижды — в ленте, в
     «Новом посте» и в правке записи, — и все три раза по-своему.

         CW.теги(что)        → ['#танцы', '#море']   всегда список
         CW.тегиСтрокой(что) → '#танцы #море'        для поля ввода

     Решётку ставим сами: человек пишет и с ней, и без неё, а хранить
     надо одинаково, иначе «#танцы» и «танцы» станут разными тегами. */
  CW.теги = function (что) {
    var ряд = [];

    if (Array.isArray(что)) ряд = что;
    else if (что && typeof что === 'object') ряд = что.tags || [];
    else if (typeof что === 'string' && что.trim()) {
      var т = что.trim();
      if (т.charAt(0) === '[') {
        try { var р = JSON.parse(т); ряд = Array.isArray(р) ? р : [т]; }
        catch (е) { ряд = [т]; }
      } else {
        /* Напечатанное руками: берём слова с решёткой, а если решёток
           нет вовсе — делим по пробелам и запятым. */
        ряд = т.match(/#[\wа-яёА-ЯЁ]+/gi) || т.split(/[,\s]+/);
      }
    }

    var было = {}, итог = [];
    ряд.forEach(function (с) {
      var з = String(с == null ? '' : с).trim();
      if (!з) return;
      if (з.charAt(0) !== '#') з = '#' + з;
      var ключ = з.toLowerCase();
      if (было[ключ]) return;        /* один тег дважды — это не два тега */
      было[ключ] = 1;
      итог.push(з);
    });
    return итог;
  };

  CW.тегиСтрокой = function (что) { return CW.теги(что).join(' '); };

  /* ── СКАЧАТЬ ФАЙЛ ─────────────────────────────────────────────────
     Ссылка с пометкой download, нажатая за человека. Было написано в
     четырёх местах: в ленте, в звуках, в маркетплейсе и в окне файла.

     Про «скачается или откроется»: пометку download браузер слушает
     только для своего домена. Файл с чужого (а наши лежат в
     хранилище) он откроет в новой вкладке — это тоже сохранение,
     просто на шаг длиннее, и соврать тут нечем. */
  CW.скачать = function (адрес, имя) {
    if (!адрес) { CW.сказать(Т('Файла нет')); return false; }
    var а = документ.createElement('a');
    а.href = адрес;
    а.download = имя || '';
    а.target = '_blank';
    а.rel = 'noopener';
    документ.body.appendChild(а);
    а.click();
    документ.body.removeChild(а);
    return true;
  };

  /* ── долгое нажатие и правая кнопка — одно и то же меню ──────────── */
  CW.наДолгоеНажатие = function (узел, делать) {
    узел.oncontextmenu = function (е) {
      е.preventDefault();
      делать(е.clientX, е.clientY);
    };
    var часы;
    узел.addEventListener('touchstart', function (е) {
      var т = е.touches[0];
      часы = setTimeout(function () { делать(т.clientX, т.clientY); }, 500);
    }, { passive: true });
    ['touchend', 'touchmove', 'touchcancel'].forEach(function (с) {
      узел.addEventListener(с, function () { clearTimeout(часы); },
                            { passive: true });
    });
  };

  /* ── ПРАВИЛО: из любого окна выходят касанием мимо него ─────────────
     Одно место на всю программу. Окно, которое закрывается только
     крестиком, — это окно, из которого человек не знает, как выйти.
     Escape делает то же самое: на мониторе это привычнее касания.

         CW.мимоОкна(подложка, закрыть);

     Закрываем по нажатию, а не по отпусканию: если начали выделять текст
     внутри окна и отпустили мышь снаружи, окно закрываться не должно. */
  CW.мимоОкна = function (подложка, закрыть) {
    if (!подложка || !закрыть) return;
    var началиВнутри = false;

    подложка.addEventListener('mousedown', function (е) {
      /* Полоса прокрутки подложки — часть самой подложки, и нажатие на
         неё приходит сюда же. Закрывать по нему нельзя: человек хотел
         пролистать длинную форму, а окно схлопнулось. Полоса лежит
         правее содержимого — по этому её и отличаем. */
      if (е.offsetX > подложка.clientWidth) { началиВнутри = true; return; }
      началиВнутри = (е.target !== подложка);
    });
    подложка.addEventListener('click', function (е) {
      if (е.target === подложка && !началиВнутри) закрыть();
      началиВнутри = false;
    });
    документ.addEventListener('keydown', function (е) {
      if (е.key !== 'Escape') return;
      /* Закрываем только то окно, которое сейчас на экране. */
      var видно = подложка.classList.contains('видно')
               || подложка.style.display === 'flex'
               || подложка.style.display === 'block';
      if (видно) закрыть();
    });
  };

  /* ── ПРАВИЛО: перезагрузка возвращает в то же окно ──────────────────
     Человек открыл правку профиля, нажал обновить — и оказался в
     портфолио. Это потеря места, и она раздражает ровно так же, как
     потеря текста. Запоминаем, какое окно открыто, на время вкладки.

         CW.гдеБыл({окно:'правка'});      запомнить
         CW.гдеБыл();                     прочитать
         CW.гдеБыл(null);                 забыть

     Память живёт в sessionStorage: переживает перезагрузку и умирает
     вместе со вкладкой — чужую вкладку чужим окном не тревожим. */
  CW.гдеБыл = function (что) {
    var ключ = 'cw_окно:' + (окно.location.pathname || '/');
    if (что === undefined) {
      try { return JSON.parse(окно.sessionStorage.getItem(ключ) || 'null'); }
      catch (е) { return null; }
    }
    try {
      if (что === null) окно.sessionStorage.removeItem(ключ);
      else окно.sessionStorage.setItem(ключ, JSON.stringify(что));
    } catch (е) {}
    return что;
  };

  /* ── окошко под кнопкой ──────────────────────────────────────────
     Короткое пояснение, которое читают один раз: что такое сигналы,
     как считается уровень, почему площадка держит деньги.

     Полосой над списком такое держать нельзя: прочитал в первый день,
     а место она занимает всегда. Поэтому — кнопка в шапке и окошко
     под ней. Нажал — показали, нажал ещё раз или мимо — убрали.

         CW.окошко(кнопка, 'текст пояснения');

     Ставится по месту кнопки и прижимается к краю, если не влезает:
     окошко, наполовину уехавшее за экран, хуже, чем его отсутствие. */
  CW.окошко = function (кнопка, текст) {
    if (!кнопка) return null;

    var у = документ.createElement('div');
    у.className = 'cw-окошко';
    у.textContent = текст || '';
    документ.body.appendChild(у);

    function поставить() {
      var р = кнопка.getBoundingClientRect();
      var ш = у.offsetWidth || 340;
      var л = Math.min(р.left, окно.innerWidth - ш - 12);
      у.style.left = Math.max(12, Math.round(л)) + 'px';
      у.style.top = Math.round(р.bottom + 8) + 'px';
    }

    function показать() {
      у.classList.add('видно');
      кнопка.classList.add('горит');
      /* Ставим после того, как окошко получило размер: до этого
         offsetWidth равен нулю и прижатие к краю считается неверно. */
      окно.requestAnimationFrame(поставить);
    }

    function скрыть() {
      у.classList.remove('видно');
      кнопка.classList.remove('горит');
    }

    кнопка.onclick = function (е) {
      е.stopPropagation();
      if (у.classList.contains('видно')) скрыть(); else показать();
    };

    /* Касание мимо и Escape — закрыть. То же правило, что у окон. */
    документ.addEventListener('click', function (е) {
      if (!у.classList.contains('видно')) return;
      if (е.target === у || (у.contains && у.contains(е.target))) return;
      скрыть();
    });
    документ.addEventListener('keydown', function (е) {
      if (е.key === 'Escape') скрыть();
    });
    окно.addEventListener('resize', function () {
      if (у.classList.contains('видно')) поставить();
    });

    return { узел: у, показать: показать, скрыть: скрыть };
  };

  /* ── ПРАВИЛО: где мы стоим в дереве папок ───────────────────────────
     Разделы меню лежат в корне, окна поверх — в windows/, модалки — в
     modals/. Из окна путь до корня на одну папку длиннее. Писать эту
     разницу в каждом переходе — значит однажды её забыть и уехать на
     windows/feed.html, которой нет. Считаем один раз здесь, и дальше
     никто в программе не пишет '.html' руками.

         CW.уйти(CW.раздел('feed'));       лента      (../feed.html из окна)
         CW.уйти(CW.окно('profile'));      профиль    (profile.html из окна)
         CW.путь('modals/share.js');       подключить модалку           */
  CW.вОкне = /\/windows\//.test(окно.location.pathname || '');
  CW.корень = CW.вОкне ? '../' : '';

  /* ── ПАЛЬЦЕМ ИЛИ МЫШЬЮ ──
     Одно место на всю программу вместо пятнадцати matchMedia по
     файлам. Считается один раз: вид указателя за жизнь страницы не
     меняется. */
  CW.пальцем = !!(окно.matchMedia && окно.matchMedia('(pointer: coarse)').matches);

  /* ── КУРСОР В ПОЛЕ СТАВИТ ЧЕЛОВЕК, А НЕ ОКНО ───────────────────
         CW.встать(поле)

     На настольном экране поставить курсор в первое поле - вежливость:
     окно открылось, можно печатать. На телефоне это грубость: вместе
     с курсором выезжает клавиатура на пол-экрана, окно ужимается, и
     человек, который просто хотел посмотреть, что внутри, видит
     вместо окна его верхнюю треть. Анна сказала про это так: «они
     сразу на поле ввода сами заходят и тянут, некрасиво».

     Поэтому на пальце курсор сам никуда не встаёт. Это только про
     открытие окна: когда человек нажал «добавить строку» или крестик
     очистки, поле зовут напрямую - там клавиатура и нужна. */
  CW.встать = function (узел) {
    if (!узел || !узел.focus || CW.пальцем) return;
    try { узел.focus(); } catch (е) {}
  };

  /* ═════════════════════════════════════════════════════════════════
     ОДИН РЯД КРАСОК НА ВСЮ ПРОГРАММУ

         var ряд = CW.рядКрасок({ выбран: '#4a9eff',
                                  выбрать: function (ц) { … } });

     Краски берём из оформления (shared/theme.js): те же шесть и в том
     же порядке, что в окне «Оформление». Прежде у каждого места был
     свой список — восемь холодных в «Цвете куба», восемь других в
     цвете фигуры товара, шесть в оформлении, — и человек в одной
     программе видел три разные палитры. Анна прислала три снимка
     рядом и попросила оставить одну.

     Первый кружок — радуга: за ней палитра на свой цвет (её открывает
     тот, кто ряд позвал, — палитра приезжает отдельным файлом).
     Выбранный кружок помечен галкой, как в «Оформлении».

     Отдаём готовый узел. У него есть .показать(цвет) — перерисовать
     отметку, когда цвет сменили со стороны (например, из палитры). */
  CW.рядКрасок = function (н) {
    н = н || {};
    var краски = [];
    var таблица = (CW.оформление && CW.оформление.ЦВЕТА) || null;
    if (таблица) {
      Object.keys(таблица).forEach(function (имя) {
        краски.push({ ц: таблица[имя].знач, имя: таблица[имя].подпись });
      });
    } else {
      /* Оформление не приехало — краски те же, но вписанные числом:
         ряд цветов не повод оставить окно без выбора. */
      [['#4a9eff', 'Синий'], ['#8b7cf6', 'Сирень'], ['#34d399', 'Зелёный'],
       ['#fbbf24', 'Янтарь'], ['#f472b6', 'Розовый'], ['#22d3ee', 'Бирюза']]
        .forEach(function (п) { краски.push({ ц: п[0], имя: п[1] }); });
    }

    var ряд = документ.createElement('div');
    ряд.className = 'оф-цвета' + (н.класс ? ' ' + н.класс : '');

    var галка = '<span class="галка">'
              + (CW.значок ? CW.значок('галка') : '✓') + '</span>';

    var радуга = документ.createElement('button');
    радуга.type = 'button';
    радуга.className = 'оф-цвет радуга';
    радуга.title = Т('Свой цвет');
    радуга.innerHTML = галка;
    радуга.onclick = function () { if (н.свой) н.свой(радуга); };
    ряд.appendChild(радуга);

    краски.forEach(function (к) {
      var б = документ.createElement('button');
      б.type = 'button';
      б.className = 'оф-цвет';
      б.style.setProperty('--он', к.ц);
      б.dataset.ц = к.ц;
      б.title = Т(к.имя);
      б.innerHTML = галка;
      б.onclick = function () {
        показать(к.ц);
        if (н.выбрать) н.выбрать(к.ц);
      };
      ряд.appendChild(б);
    });

    function показать(цвет) {
      var свой = true;
      [].slice.call(ряд.children).forEach(function (б) {
        if (!б.dataset.ц) return;
        var он = String(б.dataset.ц).toLowerCase() === String(цвет || '').toLowerCase();
        б.classList.toggle('выбран', он);
        if (он) свой = false;
      });
      /* Цвет не из ряда — значит взят в палитре: горит радуга, и в её
         середине стоит сам цвет, иначе непонятно, какой он. */
      радуга.classList.toggle('выбран', !!цвет && свой);
      радуга.style.setProperty('--он', (цвет && свой) ? цвет : '');
    }

    показать(н.выбран || '');
    ряд.показать = показать;
    return ряд;
  };

  /* ═════════════════════════════════════════════════════════════════
     ЭКРАН СТОИТ НА МЕСТЕ.

     Две беды с одним корнем: программа нарисована по размеру экрана и
     приклеена к его краям, а телефон этот размер иногда меняет у неё
     за спиной.

     ПЕРВАЯ - ЩИПОК. Два пальца, и Сафари увеличивает страницу целиком.
     Шапка и нижний ряд, приклеенные к краям, уезжают за край экрана, а
     вернуть их можно только перезагрузкой. Метку viewport в шапке
     страниц Сафари на айфоне не чтит с десятой версии - нарочно, ради
     тех, кому нужно увеличить мелкий текст. Но он слушает отмену
     своего жеста, и это единственный способ сказать «здесь не
     газета». Правило для пальца (touch-action) лежит в style.css,
     метка - в шапке каждой страницы; здесь третий замок, для Сафари.

     ВТОРАЯ - КЛАВИАТУРА. Когда она выезжает, видимая часть экрана
     становится ниже, а наши 100dvh об этом не знают: низ программы
     уходит под клавиатуру, и Сафари вдобавок прокручивает саму
     страницу, чтобы показать поле. Со стороны это выглядит как «всё
     поехало»: шапка наполовину за верхним краем, окно сдвинуто.

     Поэтому меряем видимую часть сами и кладём её в --видимая-высота.
     Рама программы и окна берут высоту оттуда и ужимаются ровно до
     того, что видно: клавиатура ничего не накрывает, прокрутка идёт
     внутри списка, а сама страница стоит на месте. Её сдвиг, если
     Сафари всё же его сделал, тут же отменяем - но только там, где
     странице и нечего прокручивать.
     ═════════════════════════════════════════════════════════════════ */
  /* ═════════════════════════════════════════════════════════════════
     КРАЙ ЭКРАНА НЕ ЛИСТАЕТ СТРАНИЦУ.

     Палец от левой кромки - и браузер уезжает «назад», показывая
     из-под программы предыдущую страницу. Анна прислала это снимком:
     окно справа, а слева видна витрина, с которой пришли. Для
     человека это не жест браузера, а развалившаяся программа.

     Запрет в оформлении (overscroll-behavior-x) чтут не все, поэтому
     здесь вторая застава: касание, начатое в двух миллиметрах от
     кромки, странице двигаться вбок не даёт.

     Чего она НЕ трогает:
       · прокрутку вверх-вниз - смотрим только боковое движение;
       · ленты внутри (разделы витрины, сторис, снимки товара) - если
         под пальцем лежит то, что само листается вбок, не вмешиваемся;
       · свои жесты окон (истории, кадры ленты) - они слушают те же
         касания и получают их по-прежнему, мы отменяем только
         СОБСТВЕННОЕ действие браузера.
     ═════════════════════════════════════════════════════════════════ */
  (function кромка() {
    var ЗОНА = 24;            /* точек от края, где жест и живёт */
    var стеречь = false, началоX = 0, началоY = 0;

    function лентаПод(узел) {
      for (var у = узел; у && у !== документ.body; у = у.parentNode) {
        if (!у.scrollWidth || у.nodeType !== 1) continue;
        if (у.scrollWidth - у.clientWidth > 4) {
          var как = окно.getComputedStyle(у).overflowX;
          if (как === 'auto' || как === 'scroll') return true;
        }
      }
      return false;
    }

    документ.addEventListener('touchstart', function (с) {
      стеречь = false;
      if (!с.touches || с.touches.length !== 1) return;
      var т = с.touches[0];
      var ширина = окно.innerWidth || 0;
      if (т.clientX > ЗОНА && т.clientX < ширина - ЗОНА) return;
      if (лентаПод(с.target)) return;
      стеречь = true; началоX = т.clientX; началоY = т.clientY;
    }, { passive: true });

    документ.addEventListener('touchmove', function (с) {
      if (!стеречь || !с.touches || с.touches.length !== 1) return;
      var т = с.touches[0];
      var вбок = Math.abs(т.clientX - началоX);
      var вверх = Math.abs(т.clientY - началоY);
      if (вбок > вверх && вбок > 3 && с.cancelable) {
        try { с.preventDefault(); } catch (е) {}
      }
    }, { passive: false });

    ['touchend', 'touchcancel'].forEach(function (имя) {
      документ.addEventListener(имя, function () { стеречь = false; }, { passive: true });
    });
  })();

  (function () {
    ['gesturestart', 'gesturechange', 'gestureend'].forEach(function (имя) {
      документ.addEventListener(имя, function (с) {
        try { с.preventDefault(); } catch (е) {}
      }, { passive: false });
    });

    var вв = окно.visualViewport;
    if (!вв) return;

    var ждём = 0;
    function померить() {
      ждём = 0;
      var корень = документ.documentElement;
      корень.style.setProperty('--видимая-высота', Math.round(вв.height) + 'px');
      /* ── ГДЕ НАЧИНАЕТСЯ ВИДИМОЕ ──
         Высоты мало. Когда клавиатура выезжает, а прокручивать
         странице нечего, Сафари на айфоне не прокручивает её - он
         СДВИГАЕТ видимое окошко внутрь страницы, чтобы показать поле.
         Всё, что приклеено к краям (position:fixed), приклеено к
         СТРАНИЦЕ, а не к этому окошку: шапка уезжает за верхний край,
         снизу открывается пустота, и каждый раз по-разному - сдвиг
         зависит от того, в какое поле ткнули.

         Этот сдвиг браузер и называет offsetTop. Кладём его рядом с
         высотой, и рама с окнами встают не по странице, а по тому,
         что человек сейчас видит. */
      корень.style.setProperty('--видимый-верх', Math.round(вв.offsetTop || 0) + 'px');
      /* Страницу возвращаем на место только если ей и нечего
         прокручивать: на длинной титульной странице это был бы прыжок
         вверх посреди чтения. */
      var естьКуда = корень.scrollHeight > корень.clientHeight + 4;
      if (!естьКуда && окно.scrollY) {
        try { окно.scrollTo(0, 0); } catch (е) {}
      }
    }
    function позже() {
      if (ждём) return;
      ждём = окно.requestAnimationFrame
        ? окно.requestAnimationFrame(померить)
        : окно.setTimeout(померить, 16);
    }
    вв.addEventListener('resize', позже);
    вв.addEventListener('scroll', позже);
    померить();
  })();

  /* ── строка поиска: одна на всю программу ───────────────────────────
     Было четырнадцать полей поиска, и каждое нарисовано по-своему.
     Теперь собирает их это место, а вид лежит в shell.css, в правиле
     «.поиск-строка». Меняем вид — меняется везде.

         CW.строкаПоиска({
           подпись:   'Название группы…',   что написано в пустом поле
           значение:  'уже введённое',
           спрятан:   true,                 поле есть, но не видно
           вРяду:     true,                 стоит в ряду с кнопками
           стереть:   true,                 крестик «очистить» в поле
           подождать: 250,                  мс тишины перед поиском
           искать:    function (текст) {}
         });

     Наружу отдаёт узел, у которого есть .поле (сам input), .показать(),
     .спрятать() и .очистить(). */
  CW.строкаПоиска = function (настройки) {
    настройки = настройки || {};
    var с = CW.эл('div', 'поиск-строка'
      + (настройки.спрятан ? ' спрятан' : '')
      + (настройки.вРяду ? ' в-ряду' : ''));
    с.innerHTML = '<span class="лупа">' + CW.значок('лупа') + '</span>'
      + '<input type="text" spellcheck="false" autocomplete="off" placeholder="'
      + CW.безопасно(настройки.подпись || 'Поиск…') + '">'
      + (настройки.стереть
          ? '<button type="button" class="стереть" title="' + CW.безопасно(Т('Очистить')) + '">'
            + CW.значок('крест') + '</button>'
          : '');

    var поле = с.querySelector('input');
    поле.value = настройки.значение || '';
    var часы = null;

    function отметить() {
      с.classList.toggle('есть-текст', !!поле.value);
    }
    отметить();

    поле.oninput = function () {
      clearTimeout(часы);
      отметить();
      var текст = поле.value.trim();
      часы = setTimeout(function () {
        if (настройки.искать) настройки.искать(текст);
      }, настройки.подождать || 0);
    };

    var крестик = с.querySelector('.стереть');
    if (крестик) крестик.onclick = function () { с.очистить(); поле.focus(); };

    с.поле = поле;
    с.показать = function () {
      с.classList.remove('спрятан');
      поле.focus();
      return с;
    };
    с.спрятать = function () { с.classList.add('спрятан'); return с; };
    с.очистить = function (тихо) {
      поле.value = '';
      отметить();
      if (!тихо && настройки.искать) настройки.искать('');
      return с;
    };
    return с;
  };

  CW.путь = function (что) { return CW.корень + что; };

  CW.раздел = function (имя, куб) {
    return CW.корень + имя + '.html' + (куб ? '?id=' + куб : '');
  };

  CW.окно = function (имя, куб) {
    return CW.корень + 'windows/' + имя + '.html' + (куб ? '?id=' + куб : '');
  };

  /* ── переход на другой экран ─────────────────────────────────────── */
  CW.уйти = function (куда) { окно.location.href = куда; };

  /* ── ОТКРЫТЬ ЧЬЁ-ТО ПОРТФОЛИО И ВЕРНУТЬСЯ ТУДА ЖЕ ─────────────────
         CW.вПортфолио(номер)        чужое портфолио
         CW.вПортфолио()             своё
         CW.откудаПришли()           адрес, куда возвращаться

     Зачем отдельный помощник. Портфолио — не окошко поверх страницы, а
     своя страница: уйдя в него, браузер забывает, где мы были. Раньше
     запоминался только РАЗДЕЛ («чаты», «группы»), и возврат из
     портфолио, открытого из переписки с человеком, кидал в общий
     список чатов, а то и в тот раздел, где человек был до этого.
     Теперь запоминается точный адрес с его вопросом: переписка с
     номером собеседника, группа с её номером, лента.

     Адрес живёт в памяти вкладки (sessionStorage) и переживает
     перезагрузку страницы, но не переживает закрытие вкладки — ровно
     столько, сколько нужно. */
  var КЛЮЧ_ОТКУДА = 'cw_откуда_адрес';

  CW.запомнитьГде = function () {
    try {
      окно.sessionStorage.setItem(КЛЮЧ_ОТКУДА,
        окно.location.pathname + окно.location.search);
    } catch (е) {}
  };

  CW.откудаПришли = function () {
    var а = '';
    try { а = окно.sessionStorage.getItem(КЛЮЧ_ОТКУДА) || ''; } catch (е) {}

    /* ── ПОЧЕМУ ЗДЕСЬ БОЛЬШЕ НЕ ТРЕБУЕТСЯ «.html» ──
       Проверка стояла такая: адрес годится, только если кончается на
       «.html». На стенде так и есть, и возврат из портфолио работал.
       А на боевой площадке адрес выглядит иначе: cube-world.space
       отдаёт страницы без расширения, и в адресной строке стоит
       «/feed?id=6», а не «/feed.html?id=6». Проверка такой адрес
       отбрасывала, возвращалось пустое - и портфолио уходило к
       запасному пути «по разделу», то есть в начало ленты. Анна:
       «это не сработало».

       Проверяем теперь то, ради чего проверка и стоит: чтобы адрес был
       СВОЙ, а не чужой сайт. Для этого довольно трёх условий - путь
       начинается с одной косой черты (значит, он наш, относительный),
       не содержит двух косых подряд (с них начинается «//чужой.сайт»)
       и не пытается выйти наверх двумя точками. Расширение к делу
       отношения не имеет. */
    var путь = а.split('?')[0];
    var вопрос = а.slice(путь.length);
    if (!/^\/[A-Za-z0-9._\-\/]*$/.test(путь)) return '';
    if (путь.indexOf('//') >= 0 || путь.indexOf('..') >= 0) return '';
    if (вопрос && /[\s<>"'\\]/.test(вопрос)) return '';
    return а;
  };

  CW.вПортфолио = function (кто) {
    CW.запомнитьГде();
    CW.уйти(CW.окно('profile') + (кто ? '?кто=' + encodeURIComponent(кто) : ''));
  };

  /* ═══════════════════════════════════════════════════════════════════
     МУЗЫКА ПРОДОЛЖАЕТСЯ НА НОВОЙ СТРАНИЦЕ

     Анна: «музыка играет, в этот момент перезагрузка страницы или
     открылась другая страница - музыка не выключается, пока я не нажму
     СТОП».

     Переход между разделами это перезагрузка, и узел <audio> умирает
     вместе со страницей. Поэтому проигрыватель (shared/музыка.js) при
     каждом изменении пишет закладку: какая песня и на какой секунде.
     Здесь мы эту закладку читаем и, если песня шла, подтягиваем
     проигрыватель и заводим её с той же секунды.

     Почему здесь, а не в самом проигрывателе: его на странице обычно
     НЕТ. Он приезжает по требованию, когда открывают окно музыки, и
     возить его на каждой странице ради тех, кто музыку не слушает,
     незачем. А эта проверка - одно чтение из памяти браузера.

     Останавливают музыку только СТОП и крестик: они стирают закладку,
     и тогда здесь ничего не происходит. */
  (function музыкаДальше() {
    var есть = false;
    try {
      var з = JSON.parse(окно.localStorage.getItem('cw_музыка_сейчас') || 'null');
      есть = !!(з && з.играло && з.песня && з.песня.адрес);
    } catch (е) { есть = false; }
    if (!есть) return;

    function завести() {
      if (!CW.нужен) return;                 /* окна ещё не приехали */
      CW.нужен('shared/музыка.js')
        .then(function () {
          if (CW.музыка && CW.музыка.продолжить) CW.музыка.продолжить();
        })
        .catch(function () {});
    }
    /* CW.нужен лежит в shared/window.js, а порядок тегов на страницах
       разный. Не дождались - пробуем ещё раз на готовой странице. */
    if (CW.нужен) завести();
    else документ.addEventListener('DOMContentLoaded', завести, { once: true });
  })();

})(window, document);
