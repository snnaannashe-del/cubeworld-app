/* ═══════════════════════════════════════════════════════════════════════
   ЗАЛ ИГР: ОБЩАЯ ОБОЛОЧКА ВОСЬМИ ИГР.

       cubeworld-app/shared/игры.js

       CW.игрыСписок()        восемь игр: ключ, имя, значок, цвет
       CW.рекордИгры(ключ)    личный рекорд, 0 если его нет
       CW.играть(ключ)        привезти игру и открыть окно
       CW.игра_(ключ, fn)     так игра объявляет себя (её зовёт файл игры)

   ── Зачем оболочка ────────────────────────────────────────────────
   У восьми игр одно и то же: окно, холст, счёт, рекорд, ряд кнопок,
   конец партии. Если это писать в каждой игре заново, восемь игр
   разойдутся: в одной счёт слева, в другой справа, в третьей выход не
   сохраняет рекорд. Поэтому всё общее — здесь, а игра знает только про
   себя: как начать, как сделать шаг и как нарисоваться.

   ── Наш размер окна ───────────────────────────────────────────────
   В боевой игра занимала весь экран. У нас окна одного размера — 10 см,
   — и игра не исключение: холст подгоняется под окно, а не окно под
   холст. Поэтому у каждой игры есть «сторона» (во сколько раз она шире
   своей высоты) или «тянется» — тогда берёт всё, что дают.

   ── Файл на игру ──────────────────────────────────────────────────
   Каждая игра лежит отдельно, в games/<ключ>.js, и приезжает только
   когда её открыли: восемь игр разом — это лишние полсотни килобайт на
   каждой странице у того, кто не играет вовсе.

   ── Что даётся игре ───────────────────────────────────────────────
   Один свёрток «И»: И.очки, И.прибавить, И.состояние, И.конец,
   И.кнопки, И.кнопкаГорит, И.прям, И.текст, И.холст(), И.жива(),
   И.слово, И.шаб. Разметки игра не касается вовсе — ни своей, ни чужой.

   ── Про CUBE честно ───────────────────────────────────────────────
   Игры дают очки и личный рекорд, а не монеты. Начисление CUBE живёт на
   сервере, и рисовать монеты в браузере значило бы врать: после
   перезагрузки они всё равно исчезнут.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  /* ── ВОСЕМЬ ИГР ──
     Значки наши, не чужие картинки: в программе один набор линий, и
     зал игр из него не выпадает. Цвет у каждой свой — восемь одинаковых
     синих плиток читаются как одна. */
  var СПИСОК = [
    { к: 'tetris',   имя: 'CryptoTetris',   зн: 'клетки',   цвет: '#f472b6' },
    { к: 'run',      имя: 'CubeRun',        зн: 'молния',   цвет: '#8b7cf6' },
    { к: 'datamine', имя: 'DataMine',       зн: 'гора',     цвет: '#fbbf24' },
    { к: 'cipher',   имя: 'CipherBreak',    зн: 'замок',    цвет: '#4ade80' },
    { к: 'phantom',  имя: 'Phantom Escape', зн: 'призрак',  цвет: '#fb923c' },
    { к: 'trade',    имя: 'Block Trade',    зн: 'рост',     цвет: '#22d3ee' },
    { к: 'chain',    имя: 'TrustChain',     зн: 'звено',    цвет: '#60a5fa' },
    { к: 'builder',  имя: 'CubeBuilder',    зн: 'столбики', цвет: '#34d399' }
  ];
  CW.игрыСписок = function () { return СПИСОК.slice(); };

  /* ── РЕКОРДЫ ──
     Имена те же, что в боевой (cw_best_<ключ>): человек, перешедший со
     старой площадки в том же браузере, своих рекордов не теряет. */
  CW.рекордИгры = function (к) {
    var н = parseInt(CW.взять('cw_best_' + к), 10);
    return isNaN(н) ? 0 : н;
  };
  function записать(к, о) {
    if (о > CW.рекордИгры(к)) CW.положить('cw_best_' + к, String(о));
  }

  /* ── ЗАВОДЫ ИГР ──
     Файл игры при загрузке зовёт CW.игра_('ключ', fn) — ровно как
     модалки зовут CW.модаль. Сама fn выполняется при запуске партии. */
  var заводы = {};
  CW.игра_ = function (к, ф) { заводы[к] = ф; };

  /* ═════════════════════════════════════════════════════════════════════
     ОКНО
     ═════════════════════════════════════════════════════════════════════ */
  var М = null, холст = null, кт = null, ТЕК = null, РАФ = 0, ПРОШЛО = 0;
  var ОЧКИ = 0, ЖИВА = false, узлы = {};

  function слово(т) { return t2(т); }
  function t2(т) { return String(т == null ? '' : т); }
  function шаб(т, з) { return t2(т).replace('{1}', з); }

  var И = {
    очки: function (n) { очки(n); },
    прибавить: function (n) { очки(ОЧКИ + n); },
    состояние: состояние,
    конец: конец,
    кнопки: кнопки,
    кнопкаГорит: function (н, да) {
      var б = узлы.ряд && узлы.ряд.querySelectorAll('.зи-кн')[н];
      if (б) б.classList.toggle('гл', !!да);
    },
    прям: прям, текст: текст,
    холст: function () { return холст; },
    жива: function () { return ЖИВА; },
    слово: слово, шаб: шаб
  };

  function собрать() {
    М = CW.модалка({
      имя: 'игра',
      знак: 'кубок',
      заголовок: 'Игра',
      поля: false,
      кнопки: [{ имя: 'зал', зн: 'клетки', подсказка: 'В зал игр',
                 делать: function () { закрыть(); CW.открыть('games'); } }],
      при_закрытии: остановить
    });

    М.тело.innerHTML =
        '<div class="иг-чипы">'
      +   '<span class="иг-чип иг-доп" style="display:none"></span>'
      +   '<span class="иг-чип">Счёт <b class="иг-очки">0</b></span>'
      +   '<span class="иг-чип иг-рек">Рекорд 0</span>'
      + '</div>'
      + '<div class="иг-поле"><canvas class="иг-холст"></canvas>'
      +   '<div class="иг-итог"><div class="к">'
      +     '<h4 class="иг-итог-з">Готово</h4><div class="п иг-итог-п"></div>'
      +     '<div class="ч"><div><b class="иг-итог-о">0</b><span>очки</span></div>'
      +     '<div><b class="иг-итог-р">0</b><span>рекорд</span></div></div>'
      +     '<button type="button" class="ещё">Ещё раз</button>'
      +     '<button type="button" class="хва">В зал игр</button>'
      +   '</div></div>'
      + '</div>'
      + '<div class="иг-низ"><div class="иг-подск"></div>'
      +   '<div class="иг-ряд"></div></div>';

    узлы = {
      чипы:   М.тело.querySelector('.иг-чипы'),
      доп:    М.тело.querySelector('.иг-доп'),
      очки:   М.тело.querySelector('.иг-очки'),
      рек:    М.тело.querySelector('.иг-рек'),
      поле:   М.тело.querySelector('.иг-поле'),
      итог:   М.тело.querySelector('.иг-итог'),
      итогЗ:  М.тело.querySelector('.иг-итог-з'),
      итогП:  М.тело.querySelector('.иг-итог-п'),
      итогО:  М.тело.querySelector('.иг-итог-о'),
      итогР:  М.тело.querySelector('.иг-итог-р'),
      подск:  М.тело.querySelector('.иг-подск'),
      ряд:    М.тело.querySelector('.иг-ряд')
    };
    холст = М.тело.querySelector('.иг-холст');
    кт = холст.getContext('2d');

    М.тело.querySelector('.ещё').onclick = function () { if (ТЕК) начать(ТЕК); };
    М.тело.querySelector('.хва').onclick = function () {
      закрыть(); CW.открыть('games');
    };

    завестиРуки();
    окно.addEventListener('resize', подогнать);
    return М;
  }

  /* ═════════════════════════════════════════════════════════════════════
     РУКИ: ПАЛЕЦ, МЫШЬ, КЛАВИШИ

     Три способа на одну игру, потому что в боевой играли только с
     клавиатуры — и на телефоне не игралось вовсе.
     ═════════════════════════════════════════════════════════════════════ */
  function завестиРуки() {
    var долгийТаймер = null, долгоеБыло = false, п0 = null;

    function вХолсте(е) {
      var р = холст.getBoundingClientRect();
      return [(е.clientX - р.left) * (холст.width / р.width),
              (е.clientY - р.top) * (холст.height / р.height)];
    }

    холст.addEventListener('pointerdown', function (е) {
      долгоеБыло = false;
      п0 = { x: е.clientX, y: е.clientY };
      if (ТЕК && ТЕК.долгий) {
        var т = вХолсте(е);
        clearTimeout(долгийТаймер);
        долгийТаймер = setTimeout(function () {
          долгоеБыло = true; ТЕК.долгий(т[0], т[1]);
        }, 420);
      }
      if (!ТЕК || !ТЕК.тык || ТЕК.долгий) return;
      var к = вХолсте(е);
      ТЕК.тык(к[0], к[1]);
    });

    /* Там, где есть долгое нажатие, обычное срабатывает на отпускании —
       иначе клетка открылась бы раньше, чем встанет флажок. */
    холст.addEventListener('pointerup', function (е) {
      clearTimeout(долгийТаймер);
      if (ТЕК && ТЕК.тык && ТЕК.долгий && !долгоеБыло) {
        var к = вХолсте(е);
        ТЕК.тык(к[0], к[1]);
      }
      долгоеБыло = false;
      if (!п0 || !ТЕК || !ТЕК.жать) { п0 = null; return; }
      var dx = е.clientX - п0.x, dy = е.clientY - п0.y; п0 = null;
      if (Math.abs(dx) < 24 && Math.abs(dy) < 24) return;
      ТЕК.жать(Math.abs(dx) > Math.abs(dy) ? (dx > 0 ? 'право' : 'лево')
                                           : (dy > 0 ? 'вниз' : 'вверх'));
    });
    холст.addEventListener('pointercancel', function () {
      clearTimeout(долгийТаймер); п0 = null;
    });

    документ.addEventListener('keydown', function (е) {
      if (!ТЕК || !М || !М.подложка.classList.contains('видно')) return;
      if (!ТЕК.жать) return;
      var к = { ArrowLeft: 'лево', ArrowRight: 'право', ArrowUp: 'вверх',
                ArrowDown: 'вниз', ' ': 'огонь', Enter: 'огонь' }[е.key];
      if (к) { е.preventDefault(); ТЕК.жать(к); }
    });
  }

  /* ── холст под окно, а не окно под холст ── */
  function подогнать() {
    if (!холст || !ТЕК) return;
    var ш = узлы.поле.clientWidth - 12;
    if (ш <= 0) return;
    /* Высоту ограничиваем экраном: окно у нас одно на всё, и игра не
       имеет права вытолкнуть собственные кнопки за край. */
    var предел = Math.min(окно.innerHeight * 0.52, 430);
    var Ш, В;
    if (ТЕК.тянется) {
      Ш = ш; В = предел;
    } else {
      var стор = ТЕК.сторона || 1;
      Ш = ш; В = Ш / стор;
      if (В > предел) { В = предел; Ш = В * стор; }
    }
    var пкс = Math.min(2, окно.devicePixelRatio || 1);
    холст.style.width = Math.round(Ш) + 'px';
    холст.style.height = Math.round(В) + 'px';
    холст.width = Math.round(Ш * пкс);
    холст.height = Math.round(В * пкс);
    if (ТЕК.размер) ТЕК.размер(холст.width, холст.height);
  }

  /* ── ряд кнопок под полем ── */
  function кнопки(список) {
    узлы.ряд.innerHTML = '';
    (список || []).forEach(function (к) {
      if (к.крест) {
        var с = документ.createElement('div');
        с.className = 'иг-крест';
        [['', '↑', ''], ['←', '↓', '→']].forEach(function (ряд) {
          ряд.forEach(function (з) {
            var б = документ.createElement('button');
            б.type = 'button';
            б.className = 'зи-кн' + (з ? '' : ' пусто');
            б.textContent = з || '·';
            if (з) б.onclick = function () {
              if (ТЕК && ТЕК.жать) {
                ТЕК.жать({ '↑': 'вверх', '↓': 'вниз', '←': 'лево', '→': 'право' }[з]);
              }
            };
            с.appendChild(б);
          });
        });
        узлы.ряд.appendChild(с);
        return;
      }
      var б = документ.createElement('button');
      б.type = 'button';
      б.className = 'зи-кн' + (к.гл ? ' гл' : '') + (к.мал ? ' мал' : '');
      б.textContent = к.имя;
      б.onclick = к.как;
      узлы.ряд.appendChild(б);
    });
  }

  /* ── счёт, состояние, конец ── */
  function очки(н) {
    ОЧКИ = Math.max(0, Math.round(н));
    if (узлы.очки) узлы.очки.textContent = ОЧКИ;
  }
  /* Состояние — чипом в шапке, а не надписью поверх поля: в боевой
     «ключей 0 из 5» лежало прямо на нижнем ряду лабиринта. */
  function состояние(т) {
    if (!узлы.доп) return;
    узлы.доп.textContent = т || '';
    узлы.доп.style.display = т ? '' : 'none';
  }

  function конец(заголовок, пояснение) {
    ЖИВА = false;
    записать(ТЕК.к, ОЧКИ);
    узлы.итогЗ.textContent = заголовок || 'Готово';
    узлы.итогП.textContent = пояснение || '';
    узлы.итогО.textContent = ОЧКИ;
    узлы.итогР.textContent = CW.рекордИгры(ТЕК.к);
    узлы.рек.textContent = 'Рекорд ' + CW.рекордИгры(ТЕК.к);
    узлы.итог.classList.add('вид');
  }

  /* ── помощники рисования ── */
  function прям(к, x, y, ш, в, цвет, радиус) {
    к.fillStyle = цвет;
    var р = радиус || 0;
    к.beginPath();
    if (к.roundRect) к.roundRect(x, y, ш, в, р); else к.rect(x, y, ш, в);
    к.fill();
  }
  function текст(к, т, x, y, р, цвет, жир) {
    к.fillStyle = цвет || '#fff';
    к.font = (жир ? '800 ' : '600 ') + р + 'px system-ui,-apple-system,sans-serif';
    к.textAlign = 'center'; к.textBaseline = 'middle';
    к.fillText(т, x, y);
  }

  /* ═════════════════════════════════════════════════════════════════════
     ЗАПУСК И ОСТАНОВКА
     ═════════════════════════════════════════════════════════════════════ */
  CW.играть = function (ключ) {
    var о = null;
    СПИСОК.forEach(function (и) { if (и.к === ключ) о = и; });
    if (!о) return Promise.reject(new Error('нет такой игры'));

    return (заводы[ключ] ? Promise.resolve()
                         : CW.нужен('games/' + ключ + '.js'))
      .then(function () {
        if (!заводы[ключ]) throw new Error('игра не объявилась');
        if (!М) собрать();
        М.открыть();
        начать(заводы[ключ](И));
      })
      .catch(function (е) {
        CW.сказать('Игра не приехала: проверь связь');
        throw е;
      });
  };

  function начать(игра) {
    ТЕК = игра;
    М.имя(игра.имя, '');
    /* Значок в шапке — тот же, что на карточке в зале, и того же цвета:
       иначе во всех восьми играх стоит один кубок, и по открытому окну
       не видно, во что играешь. */
    var о = null;
    СПИСОК.forEach(function (и) { if (и.к === игра.к) о = и; });
    var зн = М.шапка && М.шапка.querySelector('.ок-знак');
    if (зн && о) { зн.innerHTML = CW.значок(о.зн); зн.style.color = о.цвет; }
    узлы.подск.textContent = игра.подсказка || '';
    узлы.рек.textContent = 'Рекорд ' + CW.рекордИгры(игра.к);
    узлы.итог.classList.remove('вид');
    очки(0); состояние('');
    кнопки(игра.кнопки || []);
    ЖИВА = true;
    подогнать();
    игра.начать();
    ПРОШЛО = (окно.performance || Date).now();
    if (!РАФ) РАФ = requestAnimationFrame(кадр);
  }

  function кадр(t) {
    РАФ = requestAnimationFrame(кадр);
    if (!ТЕК || !М || !М.подложка.classList.contains('видно')) return;
    var дт = Math.min(0.05, (t - ПРОШЛО) / 1000); ПРОШЛО = t;
    if (ЖИВА && ТЕК.шаг) ТЕК.шаг(дт);
    if (ТЕК.рисовать) ТЕК.рисовать(кт, холст.width, холст.height);
  }

  /* Вышел посреди партии — набранное всё равно засчитываем: иначе
     рекорд можно было бы получить, только проиграв до конца. */
  function остановить() {
    if (ЖИВА && ТЕК) записать(ТЕК.к, ОЧКИ);
    ЖИВА = false;
    if (РАФ) { cancelAnimationFrame(РАФ); РАФ = 0; }
    if (ТЕК && ТЕК.стоп) { try { ТЕК.стоп(); } catch (е) {} }
    ТЕК = null;
  }
  function закрыть() { if (М) М.закрыть(); else остановить(); }

})(window, document);
