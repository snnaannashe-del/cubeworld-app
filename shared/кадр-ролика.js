/* ═══════════════════════════════════════════════════════════════════════
   ПРИВЬЮ РОЛИКА — ОДИН ФАЙЛ НА ВСЮ ПРОГРАММУ.
   /home/claude/новое/cubeworld-app/shared/кадр-ролика.js

   Кадр — это картинка, которую видно ВМЕСТО ролика, пока ролик не
   тронули. В разметке она зовётся poster, у нас — кадр.

   ── ЗАЧЕМ ЭТОТ ФАЙЛ ────────────────────────────────────────────────
   Браузер сам кадр не рисует. На телефоне — тем более: в режиме
   экономии заряда Safari не качает из ролика вообще ничего, даже
   заголовок, и на месте привью остаётся пустое место с серым кружком
   пуска. Ровно это Анна и сняла: снимок рядом виден, а ролик — пустой
   прямоугольник.

   Лечится это одним: кадр надо СНЯТЬ ЗАРАНЕЕ, у отправителя, пока
   файл ещё лежит у него в руках, залить его обычной картинкой и
   приложить к сообщению. Тогда получателю привью приезжает картинкой
   весом в сотню килобайт и видно его сразу — ролик при этом не
   качается ни байтом.

   ── ГДЕ КАДР ЕДЕТ ──────────────────────────────────────────────────
   В самом сообщении, служебной строкой — тем же приёмом, которым едут
   кнопки под сообщением (shared/кнопки-сообщения.js):

       /uploads/clip/2026/11/23/ролик.mp4
       cw-кадр:/uploads/image/2026/11/23/кадр.jpg
       cw-кнопки:{"вряд":2,"сп":[…]}

   Почему строкой, а не новым полем на сервере. Новое поле — это
   правка таблицы, правка всех трёх переписок на сервере и выкладка
   ради одной картинки. Строкой кадр едет тем же путём, что и адрес
   ролика: уходит собеседнику, возвращается в истории, переживает
   правку, пересылку и поиск. Сервер менять не нужно вовсе.

   Платим тем же, чем и кнопки: строку надо СНИМАТЬ везде, где берут
   адрес файла. Снимает её одна функция — разобрать(), — и зовут её
   все окна переписки. Строка всегда стоит ПЕРЕД строкой кнопок,
   потому что кнопки ищут себя последней строкой.

   ── КАК ЗОВУТ ──────────────────────────────────────────────────────
       CW.кадрРолика.снять(файл)        → Promise<File|null>
       CW.кадрРолика.вшить(текст, адрес)→ строка для сервера
       CW.кадрРолика.разобрать(строка)  → { текст, кадр }
       CW.кадрРолика.меткой(адрес)      → адрес ролика с «#t=0.1»

   ── ЕСЛИ КАДРА НЕТ ─────────────────────────────────────────────────
   У ролика, отправленного до этой сборки, кадра нет и взяться ему
   неоткуда: файл давно у хранилища, а не у отправителя. Для таких
   есть меткой(): к адресу приписывается «#t=0.1» — это просьба к
   браузеру показать кадр на десятой доле секунды. Safari её понимает
   и рисует привью, скачав только начало файла. В режиме экономии
   заряда не поможет и она, но это уже лучшее, что можно сделать, не
   имея самого файла.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  var МЕТКА  = 'cw-кадр:';
  var ШИРИНА = 960;        /* шире привью не нужно: это не сам ролик */
  var КАЧЕСТВО = 0.82;
  var ЖДЁМ   = 15000;      /* дольше ждать кадр, чем заливать ролик, глупо */

  /* ═════════════════════════════════════════════════════════════════
     СНЯТЬ КАДР

     Берём не нулевую секунду: у половины роликов начало чёрное —
     затемнение, заставка, свет ещё не включился. Отступаем на треть
     длины, но не дальше первой секунды: дальше уже не «начало».

     Возвращаем null, а не ошибку, на любой заминке. Кадр — это
     украшение: не вышло — ролик уедет и без него, и человек об этом
     знать не обязан.
     ═════════════════════════════════════════════════════════════════ */
  function снять(файл) {
    return new Promise(function (дать) {
      if (!файл || !/^video\//i.test(файл.type || '')) { дать(null); return; }

      var адрес;
      try { адрес = окно.URL.createObjectURL(файл); }
      catch (е) { дать(null); return; }

      var в = документ.createElement('video');
      в.muted = true; в.playsInline = true; в.preload = 'auto';
      в.setAttribute('muted', '');          /* старому Safari нужен атрибут */
      в.setAttribute('playsinline', '');
      /* crossOrigin не ставим: файл свой, из руки человека, холст от
         него не портится.

         Ролик кладём НА СТРАНИЦУ, хоть и за её краем. Safari на
         телефоне не раскодирует кадр у отдельно созданного узла:
         рисунок с него выходит чёрным, а то и вовсе не выходит.
         Два пиксельных квадратика за левым краем экрана человеку не
         видны и ничего не двигают. */
      в.style.cssText = 'position:fixed;left:-9999px;top:0;width:2px;'
                      + 'height:2px;opacity:0;pointer-events:none';
      var отдали = false, часы = null, запас = null;

      function всё(кадр) {
        if (отдали) return;
        отдали = true;
        if (часы) окно.clearTimeout(часы);
        if (запас) окно.clearTimeout(запас);
        try { окно.URL.revokeObjectURL(адрес); } catch (е) {}
        try { в.pause(); } catch (е) {}
        try { в.removeAttribute('src'); в.load(); } catch (е) {}
        try { if (в.parentNode) в.parentNode.removeChild(в); } catch (е) {}
        дать(кадр || null);
      }

      в.onloadeddata = function () {
        /* Перемотка иногда не случается вовсе: ролик короче отступа,
           или браузер уже стоит на нужной секунде и «перемотался»
           молча. Поэтому рядом с перемоткой ставим запасные часы: не
           пришло seeked за полторы секунды — снимаем, что есть. */
        if (запас) окно.clearTimeout(запас);
        запас = окно.setTimeout(снимок, 1500);
        try { в.currentTime = Math.min(1, (в.duration || 3) / 3); }
        catch (е) { снимок(); }
      };
      в.onseeked = снимок;
      в.onerror = function () { всё(null); };
      часы = окно.setTimeout(function () { всё(null); }, ЖДЁМ);
      try { документ.body.appendChild(в); } catch (е) {}

      function снимок() {
        var ш = в.videoWidth || 0, вы = в.videoHeight || 0;
        if (!ш || !вы) { всё(null); return; }
        var к = Math.min(1, ШИРИНА / ш);
        var х = документ.createElement('canvas');
        х.width  = Math.max(1, Math.round(ш * к));
        х.height = Math.max(1, Math.round(вы * к));
        try { х.getContext('2d').drawImage(в, 0, 0, х.width, х.height); }
        catch (е) { всё(null); return; }
        /* toBlob есть не везде: в старом Safari его нет вовсе. Там
           берём строку и переводим её в байты сами. */
        if (х.toBlob) {
          х.toBlob(function (б) { всё(б ? файлом(б) : null); },
                   'image/jpeg', КАЧЕСТВО);
        } else {
          var строка = '';
          try { строка = х.toDataURL('image/jpeg', КАЧЕСТВО); }
          catch (е) { всё(null); return; }
          всё(файлом(каплей(строка)));
        }
      }

      в.src = адрес;
      /* Загрузку просим явно: без этого Safari на телефоне ждёт
         нажатия и onloadeddata не приходит никогда. Беззвучному
         ролику телефон играть разрешает и без нажатия — а раз он
         играет, значит, и кадр раскодирован. */
      try { в.load(); } catch (е) {}
      try { var и = в.play(); if (и && и.catch) и.catch(function () {}); }
      catch (е) {}
    });
  }

  function файлом(капля) {
    if (!капля) return null;
    try { return new окно.File([капля], 'кадр.jpg', { type: 'image/jpeg' }); }
    catch (е) { return капля; }      /* старый браузер: сойдёт и Blob */
  }

  function каплей(строка) {
    try {
      var байты = окно.atob(String(строка).split(',')[1] || '');
      var сп = new окно.Uint8Array(байты.length);
      for (var i = 0; i < байты.length; i++) сп[i] = байты.charCodeAt(i);
      return new окно.Blob([сп], { type: 'image/jpeg' });
    } catch (е) { return null; }
  }

  /* ═════════════════════════════════════════════════════════════════
     СНЯТЬ И СРАЗУ ПОЛОЖИТЬ НА СКЛАД

     Отдаёт адрес залитой картинки или пустую строку. Ошибку наружу не
     пускает по той же причине: ролик уедет и без кадра.
     ═════════════════════════════════════════════════════════════════ */
  function заготовить(файл) {
    return снять(файл).then(function (кадр) {
      if (!кадр || !CW.залить) return '';
      return CW.залить(кадр, 'image').then(function (о) {
        return (о && о.адрес) || '';
      });
    }).catch(function () { return ''; });
  }

  /* ═════════════════════════════════════════════════════════════════
     СЛУЖЕБНАЯ СТРОКА
     ═════════════════════════════════════════════════════════════════ */
  function вшить(текст, адрес) {
    текст = String(текст == null ? '' : текст);
    адрес = String(адрес == null ? '' : адрес).trim();
    /* Перевод строки в адресе картинки означал бы, что нам подсунули
       не адрес: такую строку не вшиваем вовсе. */
    if (!адрес || /[\r\n]/.test(адрес)) return текст;
    return текст + '\n' + МЕТКА + адрес;
  }

  function разобрать(строка) {
    var с = String(строка == null ? '' : строка);
    var где = с.indexOf('\n' + МЕТКА);
    var сдвиг = 1;
    if (где < 0 && с.indexOf(МЕТКА) === 0) { где = 0; сдвиг = 0; }
    if (где < 0) return { текст: с, кадр: '' };

    var чисто = с.slice(0, где);
    var хвост = с.slice(где + сдвиг + МЕТКА.length);
    /* Строку могли обрезать на показ (список чатов берёт первые сорок
       знаков): тогда хвоста нет, но текст уже чистый — и это главное. */
    var кадр = хвост.split('\n')[0].trim();
    /* Остальные строки после кадра — не наше дело: там могут стоять
       кнопки. Возвращаем их тексту, иначе их разбор ничего не найдёт. */
    var ещё = хвост.indexOf('\n');
    if (ещё >= 0) чисто += хвост.slice(ещё);
    return { текст: чисто, кадр: кадр };
  }

  /* Метка времени для ролика без кадра. Ставим её только своим
     адресам: у чужой ссылки может быть своя решётка, и дописывать к
     ней нашу — портить ссылку. */
  function меткой(адрес) {
    var а = String(адрес == null ? '' : адрес);
    if (!а || а.indexOf('#') >= 0) return а;
    return а + '#t=0.1';
  }

  CW.кадрРолика = {
    МЕТКА: МЕТКА,
    снять: снять,
    заготовить: заготовить,
    вшить: вшить,
    разобрать: разобрать,
    меткой: меткой
  };

})(window, document);
