/* ═══════════════════════════════════════════════════════════════════════
   ЛИЦА ЛЮДЕЙ: ОДИН СКЛАД НА ВСЮ ПРОГРАММУ.
   /home/claude/новое/cubeworld-app/shared/лица.js

       CW.лица.знать(кто, снимок, версия)   запомнить то, что приехало
       CW.лица.узнать(кто)                  что мы про него знаем
       CW.лица.одеть(узел, кто)             нарисовать лицо в кружке
       CW.лица.сменилось(кто, снимок, вер)  перерисовать везде разом

   ЗАЧЕМ ЭТОТ ФАЙЛ. Лицо человека показывается в двух десятках мест:
   лента, комментарии, чаты, переписка, группы, поиск, подписки,
   приглашения, кубы, перевод, кошелёк, уведомления, вести, звонки,
   истории, портфолио и шапка страницы. Рисовали его три разных
   способа, и каждый брал снимок откуда придётся: один из поля
   avatar_url, второй по короткой метке avatar_ver, третий лепил
   <img> руками. Отсюда и бралось то, на что жаловались: в ленте
   человек с фотографией, в чатах тот же человек значком, после
   перезахода лицо подпрыгивало — сперва значок, через секунду снимок.

   КАК УСТРОЕНО ТЕПЕРЬ. Склад помнит про каждого человека две вещи:
   куда смотреть за снимком (адрес или короткая метка версии) и ничего
   больше. Любой список, в котором приехали люди, кладёт это на склад.
   Любой кружок спрашивает склад, а не сервер.

   ПОЧЕМУ НЕ ПРЫГАЕТ. Склад переживает перезаход страницы — он лежит в
   памяти браузера. Поэтому знакомое лицо ставится сразу, первым же
   кадром, из картинок, которые браузер уже держит у себя. Значок
   остаётся только у того, про кого мы правда ничего не знаем.

   ПОЧЕМУ ВЕРНЫЙ ЧЕЛОВЕК. Ключ склада — номер человека, а не строка
   списка. Пришёл список без снимков — спрашиваем сервер одним
   запросом сразу про всех: /users/avatars?ids=1,2,3. Подставлять
   «похожее» лицо нельзя: чужое лицо хуже пустого кружка.

   ПОЧЕМУ СРАЗУ У ОБОИХ. Сервер, когда человек меняет снимок, говорит
   об этом всем, кто в сети (письмо profile_changed). Слушаем его
   здесь, в одном месте, и перерисовываем все кружки этого человека на
   странице — без перезагрузки и без мигания: новая картинка
   загружается в стороне и встаёт готовой.

   ЧЕГО ЗДЕСЬ НЕТ. Нет своей отрисовки кружка: рисует по-прежнему
   CW.кружок в shared/ui.js, это его дело. Здесь только память и
   решение, что показать.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно) {
  'use strict';
  var CW = окно.CW = окно.CW || {};
  var документ = окно.document;

  var КЛЮЧ = 'cw-лица';
  var ПРЕДЕЛ = 400;          /* сколько лиц помним между заходами */

  /* номер человека → { адрес, вер } */
  var ПАМЯТЬ = (function () {
    try {
      var с = JSON.parse(окно.localStorage.getItem(КЛЮЧ) || '{}');
      return (с && typeof с === 'object') ? с : {};
    } catch (е) { return {}; }
  })();

  var записать = (function () {
    var часы = null;
    return function () {
      clearTimeout(часы);
      часы = setTimeout(function () {
        try {
          var ключи = Object.keys(ПАМЯТЬ);
          if (ключи.length > ПРЕДЕЛ) {
            /* Выкидываем самых давних: склад не должен расти вечно. */
            ключи.slice(0, ключи.length - ПРЕДЕЛ).forEach(function (к) {
              delete ПАМЯТЬ[к];
            });
          }
          окно.localStorage.setItem(КЛЮЧ, JSON.stringify(ПАМЯТЬ));
        } catch (е) {}
      }, 400);
    };
  })();

  function номер(кто) {
    var н = (кто && кто.user_id) || (кто && кто.id) || кто;
    н = String(н == null ? '' : н).trim();
    return (!н || н === 'null' || н === 'undefined') ? '' : н;
  }

  /* Короткая строка — это смайл, а не адрес картинки. */
  function смайлЛи(что) {
    return !!что && !(CW.картинкаЛи ? CW.картинкаЛи(что) : /^(https?:|data:|\/)/i.test(что));
  }

  /* ── ЧТО ЗАПОМНИЛИ ────────────────────────────────────────────────
     Пустую запись тоже храним: «у этого человека лица нет» — такое же
     знание, как и адрес, и второй раз спрашивать о нём незачем. */
  function знать(кто, снимок, версия) {
    var н = номер(кто);
    if (!н) return null;
    var адрес = String(снимок == null ? '' : снимок);
    var вер = String(версия == null ? '' : версия);
    var было = ПАМЯТЬ[н];

    /* Пустое не затирает известное: списки приезжают разные, и в
       половине из них снимка нет вовсе. Лицо из такого списка пропало
       бы на глазах. */
    if (!адрес && !вер) {
      if (было) return было;
      ПАМЯТЬ[н] = { адрес: '', вер: '' };
      записать();
      return ПАМЯТЬ[н];
    }

    if (было && было.адрес === адрес && было.вер === вер) return было;
    ПАМЯТЬ[н] = { адрес: адрес, вер: вер };
    записать();
    return ПАМЯТЬ[н];
  }

  function узнать(кто) {
    var н = номер(кто);
    return н ? (ПАМЯТЬ[н] || null) : null;
  }

  /* ── ИМЯ ЧЕЛОВЕКА ─────────────────────────────────────────────────
     Та же беда, что со снимком, и то же лечение. Списки приезжают
     разные: в одном у человека есть имя, в другом только номер. Строка
     показывала «Участник #16», через секунду приезжал список с именем,
     и подпись на глазах менялась — это и есть «дёргается текст».

     Склад помнит имя между заходами. Поэтому знакомый человек подписан
     сразу и правильно, а «Участник #16» остаётся только у того, про
     кого мы правда ничего не знаем.

     Правило, КАК звать человека, здесь не живёт: оно одно на всю
     программу, в CW.имяЧеловека (shared/api.js). Здесь только память. */
  function имяЗнать(кто, имя) {
    var н = номер(кто);
    if (!н) return '';
    var и = String(имя == null ? '' : имя).trim();
    var з = ПАМЯТЬ[н] || (ПАМЯТЬ[н] = { адрес: '', вер: '' });
    /* Пустое и «Участник #16» именем не считаем: это заглушка, и ею
       нельзя затирать настоящее имя, которое мы уже знали. */
    if (!и || /^Участник\b/.test(и) || /^#\d+$/.test(и)) return з.имя || '';
    if (з.имя !== и) { з.имя = и; записать(); }
    return и;
  }

  function имя(кто) {
    var з = узнать(кто);
    return (з && з.имя) || '';
  }

  /* Подписать узел именем человека и запомнить, чей он: когда человек
     сменит имя, подпись сменится сама, без перезагрузки. */
  function подписать(узел, кто, имяСейчас) {
    if (!узел) return узел;
    var н = номер(кто);
    if (!н) return узел;
    узел.dataset.имя = н;
    var было = имяЗнать(н, имяСейчас);
    var текст = было || String(имяСейчас || '').trim()
             || (CW.имяЧеловека ? CW.имяЧеловека({ id: н }) : ('Участник #' + н));
    if (узел.textContent !== текст) узел.textContent = текст;
    return узел;
  }

  function переподписать(кто) {
    var н = номер(кто);
    if (!н || !документ) return;
    var текст = имя(н) || (CW.имяЧеловека ? CW.имяЧеловека({ id: н }) : ('Участник #' + н));
    var все = документ.querySelectorAll('[data-имя="' + н + '"]');
    [].forEach.call(все, function (у) {
      if (у.textContent !== текст) у.textContent = текст;
    });
  }

  /* ── КУДА СМОТРЕТЬ ЗА СНИМКОМ ─────────────────────────────────────
     Адрес, если он пришёл. Иначе короткая метка версии и наша ручка:
     у человека /users/{номер}/avatar, у группы /groups/{номер}/avatar.
     Сервер отдаёт картинку на сутки в память браузера, а метка в
     адресе меняется вместе со снимком — поэтому старое лицо не
     залёживается, и при возврате на страницу оно встаёт мгновенно,
     из той же памяти. */
  /* ── АДРЕС БЕЗ МЕТКИ ВЕРСИИ ──
     Лицо лежит по адресу «/users/16/avatar?v=7». Номер версии меняется
     при каждой правке профиля — и адрес становится ДРУГОЙ строкой,
     хотя картинка та же. Из-за этого готовый снимок считался
     незнакомым, грузился заново, и кружок моргал на каждой
     перерисовке списка.

     Поэтому и склад готовых, и проверка «это лицо уже стоит» живут по
     адресу БЕЗ метки. Настоящая смена снимка меняет сам адрес (другой
     номер человека или другой файл) — её это не скрывает: при новой
     версии мы грузим новую картинку молча, не снимая старую, и
     подменяем её только когда новая готова. */
  function база(адрес) { return String(адрес || '').split('?')[0]; }

  function ссылка(н, з) {
    if (!з) return '';
    if (з.адрес && !смайлЛи(з.адрес)) return CW.файл ? CW.файл(з.адрес) : з.адрес;
    var группа = н.charAt(0) === 'г' && н.charAt(1) === ':';
    var ид = группа ? н.slice(2) : н;
    if (группа) {
      return (CW.адрес || '') + '/groups/' + encodeURIComponent(ид) + '/avatar'
           + (з.вер ? '?v=' + encodeURIComponent(з.вер) : '');
    }
    if (з.вер) {
      return (CW.адрес || '') + '/users/' + encodeURIComponent(ид)
           + '/avatar?v=' + encodeURIComponent(з.вер);
    }
    return '';
  }

  /* ── СПРОСИТЬ ПРО НЕЗНАКОМЫХ ОДНИМ ЗАПРОСОМ ───────────────────────
     Список участников или поиск приезжают без снимков. Спрашивать по
     одному — полсотни запросов в секунду; поэтому копим номера
     несколько мгновений и спрашиваем сразу про всех. */
  var ОЧЕРЕДЬ = {}, часыОчереди = null, СПРОШЕНО = {};

  function дозапросить(н) {
    if (!н || ПАМЯТЬ[н] || ОЧЕРЕДЬ[н] || СПРОШЕНО[н]) return;
    ОЧЕРЕДЬ[н] = 1;
    clearTimeout(часыОчереди);
    часыОчереди = setTimeout(послатьОчередь, 60);
  }

  function послатьОчередь() {
    var номера = Object.keys(ОЧЕРЕДЬ);
    ОЧЕРЕДЬ = {};
    if (!номера.length || !CW.спросить) return;
    номера.forEach(function (н) { СПРОШЕНО[н] = 1; });

    CW.спросить('/users/avatars?ids=' + номера.join(','), { тихо: true })
      .then(function (о) {
        var люди = (о && о.люди) || (о && о.people) || null;
        if (!люди) return;              /* сервер постарше — молчим, значок остаётся */
        номера.forEach(function (н) {
          var з = люди[н] || люди[String(н)];
          знать(н, (з && (з.url || з.адрес)) || '', (з && (з.ver || з.вер)) || '');
        });
        номера.forEach(перерисовать);
      })
      .catch(function () {});
  }

  /* ── НАРИСОВАТЬ В ОДНОМ КРУЖКЕ ────────────────────────────────────
     Узел — кружок из CW.кружок: внутри значок, а снимок кладётся
     поверх. Картинка грузится в стороне и встаёт уже готовой, поэтому
     подмены на глазах не видно. */
  /* Ролик это или снимок — спрашиваем общий ящик (shared/ui.js): этот
     же признак читают кольцо в портфолио и окно создания куба. */
  function видеоЛи(адрес) {
    return !!(CW.видеоЛи && CW.видеоЛи(адрес));
  }

  function одеть(узел, кто) {
    if (!узел) return узел;
    var н = номер(кто);
    if (!н) return узел;
    узел.dataset.лицо = н;
    пустомуЗнак(узел);
    нарисовать(узел);
    if (!ПАМЯТЬ[н]) дозапросить(н);
    return узел;
  }


  /* ── ПУСТОЙ КРУЖОК ПОЛУЧАЕТ ТОТ ЖЕ ЗНАК, ЧТО И ВЕЗДЕ ──
     Кружки, нарисованные своей разметкой (полоса историй, список «кто
     смотрел», строки чатов), приходят сюда пустыми: значок в них никто
     не клал, его ждали вместе со снимком. У кого снимка нет, у того и
     оставался серый круг - и один и тот же человек выглядел в ленте
     значком, а в истории пустотой.

     Поэтому пустому кружку кладём общий знак человека - тот же самый,
     что рисует CW.кружок. Снимок, когда приедет, ляжет поверх и
     спрячет его, как прятал всегда. */
  function пустомуЗнак(узел) {
    if (!узел || узел.children.length || (узел.textContent || '').trim()) return;
    if (!CW.значок) return;
    var з = документ.createElement('span');
    з.className = 'лицо-знак';
    /* Как он стоит внутри кружка - забота краски (shared/style.css), а
       не этой строчки. Прежде здесь стояло строчное
       «display:flex;align-items:center…», и оно же всё портило: когда
       снимка нет, кружок показывает прежнее содержимое через
       показать(), а тот ставит style.display = '' - и стирает строчный
       flex вместе с ним. Значок оставался блоком и прижимался к левому
       верхнему углу: Анна «иконка человечек крива, её почти не видно».
       Теперь строчных стилей у него нет вовсе, и стирать нечего. */
    з.innerHTML = CW.значок('человек');
    узел.appendChild(з);
  }

  /* Всё, что лежало в кружке до нас: наш значок линиями, смайл,
     буква имени. Прячем это, когда встаёт снимок, и возвращаем, когда
     снимка нет. Пустого кружка в программе не бывает. */
  function прежнее(узел) {
    return [].slice.call(узел.children).filter(function (д) {
      if (!д.classList) return true;
      return !д.classList.contains('лицо-снимок');
    });
  }

  /* Ролик, который перестал быть лицом (сменили на снимок или на
     смайл), надо убрать руками: он не картинка, и место под картинку
     его не заменит. */
  function убратьРолик(узел) {
    var в = узел.querySelector('video.лицо-снимок');
    if (в && в.parentNode) { try { в.pause(); } catch (е) {} в.parentNode.removeChild(в); }
  }

  function показать(узлы, видно) {
    узлы.forEach(function (д) { д.style.display = видно ? '' : 'none'; });
  }

  /* ── РАЗМЕР СМАЙЛА — ПО ВЫСОТЕ КРУЖКА ──
     Кружки в программе от 24 точек до 96, и одним числом их не
     накрыть: в шапке эфира смайл выходил с ноготок и жался в угол.
     Берём 58 сотых высоты - ровно столько же занимает наш значок
     человека (shared/style.css, .лицо-знак svg).

     Списки собираются в стороне и вставляются в страницу готовыми: у
     такого кружка высоты ещё нет, и мерить нечего. Тогда меряем на
     следующем кадре, когда он уже стоит на месте. Один кадр смайл
     постоит запасным размером из style.css - этого не видно. */
  function кегль(узел, сп) {
    var в = узел.clientHeight || 0;
    if (в) { сп.style.fontSize = Math.round(в * 0.58) + 'px'; return; }
    if (сп.dataset.ждём) return;
    сп.dataset.ждём = '1';
    (окно.requestAnimationFrame || окно.setTimeout)(function () {
      delete сп.dataset.ждём;
      var в2 = узел.clientHeight || 0;
      if (в2) сп.style.fontSize = Math.round(в2 * 0.58) + 'px';
    }, 0);
  }

  function нарисовать(узел) {
    var н = узел.dataset ? узел.dataset.лицо : '';
    if (!н) return;
    var з = ПАМЯТЬ[н];
    var было = узел.querySelector('img.лицо-снимок');

    /* Снимок ложится поверх значка, а значит кружок должен быть точкой
       отсчёта. Без этого картинка считает края от прадеда и уезжает в
       середину страницы — это и были «дёргающиеся» лица в чатах, где
       кружок нарисован не кружком CW.кружок, а своей разметкой. */
    var поза = '', край = '';
    try {
      /* Узел, которого ещё нет в странице, вычисленных стилей не имеет:
         списки собираются в стороне и вставляются готовыми. Поэтому
         спрашиваем стиль только у вставленного, а строящейся строке
         ставим правило сразу — для кружка оно безвредно. */
      if (узел.isConnected) {
        var с = окно.getComputedStyle(узел);
        поза = с.position; край = с.overflow;
      }
    } catch (е) {}
    if ((!поза || поза === 'static') && !узел.style.position) узел.style.position = 'relative';
    if ((!край || край === 'visible') && !узел.style.overflow) узел.style.overflow = 'hidden';

    /* Смайл вместо фотографии — это не картинка, а знак. */
    if (з && з.адрес && смайлЛи(з.адрес)) {
      if (было && было.parentNode) было.parentNode.removeChild(было);
      убратьРолик(узел);
      var сп = узел.querySelector('span.лицо-смайл');
      if (!сп) {
        сп = документ.createElement('span');
        сп.className = 'лицо-смайл';
        узел.appendChild(сп);
      }
      показать(прежнее(узел).filter(function (д) { return д !== сп; }), false);
      сп.style.display = '';
      сп.textContent = з.адрес;
      /* Размер смайла - по высоте кружка, а не по шрифту соседей.
         Кружки в программе от 24 точек до 96, и одной меркой их не
         накрыть: в шапке эфира смайл выходил с ноготок и сидел в углу.
         Берём 58 сотых высоты - ровно столько же занимает наш значок
         человека (shared/style.css, .лицо-знак svg). */
      кегль(узел, сп);
      return;
    }

    var куда = ссылка(н, з);
    if (!куда) {
      /* Про этого никого не знаем — остаётся значок. */
      if (было && было.parentNode) было.parentNode.removeChild(было);
      убратьРолик(узел);
      показать(прежнее(узел), true);
      return;
    }
    if (было && база(было.dataset.откуда) === база(куда)) {
      /* Это же лицо уже стоит. Если метка версии сменилась, тихо
         догружаем новое и подменяем готовым — без мигания. */
      if (было.dataset.откуда !== куда) догрузить(узел, было, куда);
      return;
    }

    /* ── УЖЕ ЗАГРУЖЕННОЕ ЛИЦО СТАВИМ БЕЗ ЗАГРУЗКИ ──
       Список переписок перерисовывается при каждом новом сообщении, и
       строки собираются заново. Прежде каждая новая строка заводила
       новую картинку и ждала её загрузки — пусть мгновение, но значок
       успевал мелькнуть, и лица «мигали» при каждом обновлении.

       Поэтому держим у себя уже загруженную картинку на каждый адрес и
       ставим её копию тем же кадром, без ожидания. Копия картинки,
       которая уже загружена, готова сразу. */
    /* ── ЖИВАЯ ИКОНКА ──
       Человек мог выбрать себе не снимок, а короткий ролик. Тогда в
       кружке стоит не картинка, а само видео: без звука, само собой и
       по кругу — иначе это не иконка, а проигрыватель. Склад готовых
       картинок роликам не нужен: браузер держит их сам. */
    if (видеоЛи(куда)) {
      if (было && было.dataset.откуда === куда) return;
      var стар = узел.querySelector('video.лицо-снимок');
      if (стар && стар.dataset.откуда === куда) return;
      var в = документ.createElement('video');
      в.className = 'лицо-снимок';
      в.dataset.откуда = куда;
      в.muted = true; в.loop = true; в.autoplay = true;
      в.playsInline = true;
      в.setAttribute('muted', ''); в.setAttribute('playsinline', '');
      в.src = куда;
      в.style.cssText =
        'position:absolute;inset:0;width:100%;height:100%;object-fit:cover;display:block';
      в.onloadeddata = function () {
        if (было && было.parentNode) было.parentNode.removeChild(было);
        if (стар && стар.parentNode) стар.parentNode.removeChild(стар);
        показать(прежнее(узел).filter(function (д) { return д !== в; }), false);
        var игра = в.play();
        if (игра && игра.catch) игра.catch(function () {});
      };
      в.onerror = function () { /* не доехал — остаётся значок */ };
      узел.appendChild(в);
      return;
    }

    убратьРолик(узел);

    var готовое = ГОТОВЫЕ[база(куда)];
    if (готовое) {
      var к = готовое.cloneNode(false);
      к.className = 'лицо-снимок';
      к.dataset.откуда = куда;
      к.style.cssText =
        'position:absolute;inset:0;width:100%;height:100%;object-fit:cover;display:block';
      if (было && было.parentNode) было.parentNode.removeChild(было);
      показать(прежнее(узел), false);
      узел.appendChild(к);
      return;
    }

    var и = new окно.Image();
    и.alt = '';
    и.className = 'лицо-снимок';
    и.dataset.откуда = куда;
    и.onload = function () {
      /* Прозрачная точка 1×1 — ответ «снимка нет»: значок честнее. */
      if (и.naturalWidth <= 2) return;
      запомнитьКартинку(куда, и);
      и.style.cssText =
        'position:absolute;inset:0;width:100%;height:100%;object-fit:cover;display:block';
      if (было && было.parentNode) было.parentNode.removeChild(было);
      показать(прежнее(узел), false);
      узел.appendChild(и);
    };
    и.onerror = function () { /* остаётся значок — законный вид */ };
    и.src = куда;
    /* Картинка уже в памяти браузера — ставим её тем же кадром, без
       мигания значком. Это и есть «лицо не прыгает». */
    if (и.complete && и.naturalWidth > 0) и.onload();
  }

  /* Новая версия того же лица: грузим в стороне и подменяем только
     когда готово. Старая картинка всё это время стоит на месте —
     человек не видит ни пустоты, ни вспышки значка. */
  function догрузить(узел, стояло, куда) {
    if (стояло.dataset.грузим === куда) return;
    стояло.dataset.грузим = куда;
    var и = new окно.Image();
    и.onload = function () {
      if (и.naturalWidth <= 2) return;
      запомнитьКартинку(куда, и);
      if (!стояло.parentNode) return;
      стояло.src = куда;
      стояло.dataset.откуда = куда;
      стояло.removeAttribute('data-грузим');
    };
    и.onerror = function () { стояло.removeAttribute('data-грузим'); };
    и.src = куда;
  }

  /* Склад загруженных картинок: адрес → готовая картинка. Держим
     немного — сотню; лиц на экране единицы, а память не бездонна. */
  var ГОТОВЫЕ = {};
  var ГОТОВЫХПРЕДЕЛ = 100;

  function запомнитьКартинку(куда, и) {
    куда = база(куда);
    if (ГОТОВЫЕ[куда]) return;
    var ключи = Object.keys(ГОТОВЫЕ);
    if (ключи.length >= ГОТОВЫХПРЕДЕЛ) delete ГОТОВЫЕ[ключи[0]];
    ГОТОВЫЕ[куда] = и.cloneNode(false);
  }

  function перерисовать(кто) {
    var н = номер(кто);
    if (!н || !документ) return;
    var все = документ.querySelectorAll('[data-лицо="' + н + '"]');
    [].forEach.call(все, нарисовать);
  }

  /* ── СНИМОК СМЕНИЛСЯ ──────────────────────────────────────────────
     Приходит двумя путями: от себя (поменял в портфолио) и от сервера
     (поменял другой человек). Путь дальше один и тот же, поэтому и
     написан один раз. */
  function сменилось(кто, снимок, версия) {
    var н = номер(кто);
    if (!н) return;
    delete СПРОШЕНО[н];
    ПАМЯТЬ[н] = {
      адрес: String(снимок == null ? '' : снимок),
      вер: String(версия == null ? '' : версия)
    };
    записать();
    перерисовать(н);
    /* Кружки перерисованы. Но лицо есть и там, где кружка нет: своя
       кнопка в шапке страницы, своё кольцо в портфолио. Эти места
       слушают одно короткое событие и перерисовываются сами. */
    try {
      документ.dispatchEvent(new окно.CustomEvent('cw-лицо', { detail: { кто: н } }));
    } catch (е) {}
  }

  /* ── КАРТИНКА ГРУППЫ ──────────────────────────────────────────────
     Та же работа и тот же склад, только ключ с пометкой «г:»: номера
     людей и номера групп совпадают, и без пометки лицо человека №5
     встало бы группе №5. Своей ручки у группы тоже своя: сервер
     отдаёт её картинку без ключа, обычным <img>. */
  function одетьГруппу(узел, ид, версия) {
    if (!узел || !ид) return узел;
    var н = 'г:' + String(ид);
    if (версия) {
      ПАМЯТЬ[н] = { адрес: '', вер: String(версия) };
      записать();
    } else if (!ПАМЯТЬ[н]) {
      ПАМЯТЬ[н] = { адрес: '', вер: '' };
      записать();
    }
    узел.dataset.лицо = н;
    нарисовать(узел);
    return узел;
  }

  CW.лица = {
    знать: знать,
    группа: одетьГруппу,
    имяЗнать: имяЗнать,
    имя: имя,
    подписать: подписать,
    переподписать: переподписать,
    узнать: узнать,
    одеть: одеть,
    перерисовать: перерисовать,
    сменилось: сменилось,
    ссылка: function (кто) { var н = номер(кто); return ссылка(н, ПАМЯТЬ[н]); }
  };

  /* ── ЖИВАЯ СМЕНА ──────────────────────────────────────────────────
     Сокет поднимаем сами и только для вошедших: гостю на титульной
     странице живая связь не нужна, а лишнее соединение — это лишняя
     батарея телефона. */
  function слушатьСервер() {
    if (!CW.токен || !CW.токен()) return;
    if (!CW.нужен) return;
    CW.нужен('shared/сокет.js').then(function () {
      if (!CW.сокет) return;
      CW.сокет.завести();
      CW.сокет.слушать('profile_changed', function (п) {
        if (!п) return;
        сменилось(п.user_id, п.avatar_url || '', п.avatar_ver || '');
        /* Имя человек меняет там же, где снимок, и видно оно в тех же
           двадцати одном месте. Чинить это отдельно незачем. */
        if (п.display_name || п.username) {
          правкаИмени(п);
        }
      });

      function правкаИмени(п) {
        var н = номер(п.user_id);
        if (!н) return;
        var новое = CW.имяЧеловека
          ? CW.имяЧеловека({ id: н, display_name: п.display_name, username: п.username })
          : (п.display_name || '');
        var з = ПАМЯТЬ[н] || (ПАМЯТЬ[н] = { адрес: '', вер: '' });
        з.имя = новое;
        записать();
        переподписать(н);
      }
    }).catch(function () {});
  }

  if (документ.readyState === 'loading') {
    документ.addEventListener('DOMContentLoaded', слушатьСервер);
  } else {
    слушатьСервер();
  }
})(window);
