/* ═══════════════════════════════════════════════════════════════════════
   ЧЕРНОВИКИ И ОТЛОЖЕННЫЕ ПУБЛИКАЦИИ.
   /home/claude/новое/cubeworld-app/shared/черновики.js

       CW.черновики.список()            все записи, свежие сверху
       CW.черновики.сохранить(о)         создать или переписать
       CW.черновики.убрать(ид)
       CW.черновики.ждут()               только те, у кого назначено время
       CW.черновики.часовой()            запустить проверку времени
       CW.черновики.опубликовать(ч)      отправить сейчас

   ── ГДЕ ОНИ ЛЕЖАТ ──────────────────────────────────────────────────
   В этом браузере. У сервера полей «черновик» и «опубликовать в
   19:00» нет вовсе, и выдумывать их на стороне окна нельзя: человек
   решил бы, что запись уйдёт с выключенным ноутбуком.

   Поэтому правило сказано прямо и в окне, и здесь:

       ЧЕРНОВИК виден только на этом устройстве.
       ОТЛОЖЕННАЯ запись уходит, когда настанет время И CubeWorld
       открыт. Закрыт браузер — запись подождёт и уйдёт при первом
       открытии после срока.

   Файлы в черновике уже лежат на сервере: окно публикации грузит их
   сразу, а здесь остаются только адреса. Поэтому черновик весит
   полкилобайта, а не пятьдесят мегабайт, и переживает перезагрузку.

   ── ЧТО БЫЛО БЫ ПРАВИЛЬНЕЕ ─────────────────────────────────────────
   Поле publish_at у записи и часовой на сервере: тогда отложенное
   уходило бы и с закрытым браузером. Это работа по серверу, и когда
   до неё дойдут руки, окно менять не придётся — здесь поменяется
   одна функция «опубликовать».
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  var КЛЮЧ = 'cw_черновики';
  var ПРЕДЕЛ = 50;            /* больше полусотни черновиков никто не ведёт */
  var ШАГ = 30000;            /* как часто смотрим на часы */

  function взять() {
    try {
      var сп = JSON.parse(окно.localStorage.getItem(КЛЮЧ) || '[]');
      return Array.isArray(сп) ? сп : [];
    } catch (е) { return []; }
  }

  function положить(сп) {
    try {
      окно.localStorage.setItem(КЛЮЧ, JSON.stringify(сп.slice(-ПРЕДЕЛ)));
    } catch (е) { /* память браузера полна — молчим, но не роняем окно */ }
  }

  function список() {
    return взять().sort(function (а, б) {
      return (б.правлен || 0) - (а.правлен || 0);
    });
  }

  function сохранить(о) {
    о = о || {};
    var сп = взять();
    var ид = о.ид || ('ч' + Date.now() + Math.random().toString(36).slice(2, 6));
    var было = null;
    for (var i = 0; i < сп.length; i++) if (сп[i].ид === ид) { было = i; break; }

    var запись = {
      ид: ид,
      куб: о.куб || null,
      вид: о.вид || 'short',
      видео: о.видео || '',
      обложка: о.обложка || '',
      вложение: о.вложение || '',
      вложениеИмя: о.вложениеИмя || '',
      заголовок: о.заголовок || '',
      музыка: о.музыка || '',
      описание: о.описание || '',
      теги: о.теги || '',
      когда: о.когда || 0,          /* 0 — просто черновик */
      правлен: Date.now(),
      беда: ''
    };
    if (было == null) сп.push(запись); else сп[было] = запись;
    положить(сп);
    return запись;
  }

  function убрать(ид) {
    положить(взять().filter(function (ч) { return ч.ид !== ид; }));
  }

  function ждут() {
    return взять().filter(function (ч) { return ч.когда > 0; })
                  .sort(function (а, б) { return а.когда - б.когда; });
  }

  /* ── ОТПРАВКА ──
     Тело собираем ровно такое же, какое шлёт окно публикации: один
     вид запроса на оба пути, иначе отложенная запись однажды уедет
     не так, как уехала бы руками. */
  function телом(ч) {
    var тело = {
      cube_id: ч.куб,
      post_type: ч.вид,
      title: ч.заголовок || '',
      music: ч.музыка || '',
      description: ч.описание || '',
      tags: CW.теги ? CW.теги(ч.теги || '') : [],
      video_url: '',
      image_url: ''
    };
    if (ч.вид === 'short') {
      тело.video_url = ч.видео;
      тело.image_url = ч.обложка;
    } else {
      тело.image_url = ч.вложение;
      тело.file_url = ч.вложение;
    }
    if (!тело.description) тело.description = тело.title || '-';
    return тело;
  }

  function опубликовать(ч) {
    if (!ч || !ч.куб) return Promise.reject(new Error(Т('У записи не указан куб')));
    if (ч.вид === 'short' && !ч.видео) {
      return Promise.reject(new Error(Т('У отложенного ролика нет видео')));
    }
    return CW.спросить('/feed/post', { способ: 'POST', тело: телом(ч), сроком: 25000 })
      .then(function (ответ) {
        убрать(ч.ид);
        return ответ;
      });
  }

  /* ── ЧАСОВОЙ ──
     Смотрит на часы раз в полминуты и отправляет то, чему вышел срок.
     Один на страницу: второй отправил бы те же записи второй раз.

     Записи, которые сервер не принял, НЕ выбрасываем и не шлём по
     кругу: помечаем бедой и оставляем человеку. Молча потерянный
     пост — худшее, что может сделать отложенная публикация. */
  var ИДЁТ = false;
  var ЧАСЫ = null;

  function часовой() {
    if (ЧАСЫ) return;
    проверить();
    ЧАСЫ = окно.setInterval(проверить, ШАГ);
    /* Вернулись во вкладку — смотрим сразу: ноутбук мог проспать час,
       и ждать ещё полминуты незачем. */
    документ.addEventListener('visibilitychange', function () {
      if (!документ.hidden) проверить();
    });
  }

  function проверить() {
    if (ИДЁТ) return;
    if (!CW.спросить || !окно.localStorage.getItem('cw_access_token')) return;
    var пора = ждут().filter(function (ч) {
      return !ч.беда && ч.когда <= Date.now();
    });
    if (!пора.length) return;

    ИДЁТ = true;
    var шаг = Promise.resolve();
    пора.forEach(function (ч) {
      шаг = шаг.then(function () {
        return опубликовать(ч).then(function () {
          if (CW.сказать) {
            CW.сказать(Т('Отложенная запись опубликована: ')
                       + (ч.заголовок || ч.описание || 'без названия'), 5000);
          }
        }).catch(function (е) {
          пометить(ч.ид, (е && е.message) || 'не отправилось');
          if (CW.сказать) {
            CW.сказать(Т('Отложенная запись не ушла: ')
                       + ((е && е.message) || 'непонятно почему'), 6000);
          }
        });
      });
    });
    шаг.then(function () { ИДЁТ = false; }, function () { ИДЁТ = false; });
  }

  function пометить(ид, беда) {
    var сп = взять();
    сп.forEach(function (ч) { if (ч.ид === ид) ч.беда = беда; });
    положить(сп);
  }

  /* Время словами: «сегодня в 19:30», «завтра в 8:00», «3 дек в 12:00».
     Так его пишут во всех наших окнах (shared/time.js), и здесь не
     заводим второго способа — только короткая обёртка. */
  function когдаСловами(миг) {
    if (!миг) return '';
    if (CW.когдаСловами) return CW.когдаСловами(new Date(миг).toISOString());
    return new Date(миг).toLocaleString();
  }

  CW.черновики = {
    список: список,
    сохранить: сохранить,
    убрать: убрать,
    пометить: пометить,
    ждут: ждут,
    опубликовать: опубликовать,
    проверить: проверить,
    часовой: часовой,
    когдаСловами: когдаСловами
  };

})(window, document);
