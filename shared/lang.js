  var ГОТОВЫ = { 'ru': 1, 'en-US': 1, 'en-GB': 1, 'en-CA': 1, 'en-AU': 1 };
  CW.переведён = function (код) { return !!ГОТОВЫ[код || СЕЙЧАС]; };

