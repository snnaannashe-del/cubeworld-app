/* ═══════════════════════════════════════════════════════════════════════
   РАЗВЕЯТЬ — одно красивое удаление на всю программу.

       shared/развеять.js

       CW.развеять(узел)              → обещание, сбудется, когда строки нет
       CW.развеять(узел, {вид:'взрыв'})  → этот раз другим видом
       CW.развеять([узел, узел…])     → несколько строк разом
       CW.развеятьПузырь(ид)          → сообщение по номеру
       CW.развеятьИУбрать(узлы)       → развеять и выбросить из вёрстки
       CW.видыУдаления()              → список видов для «Оформления»

   ── ЗАЧЕМ ──────────────────────────────────────────────────────────
   Анна прислала запись: в Телеграме удалённое не исчезает щелчком, а
   рассыпается в мелкую пыль, пыль сносит вверх, и список спокойно
   смыкается. Разница не в красоте: исчезнувшее мгновенно человек не
   успевает связать со своим нажатием и каждый раз думает «а что
   пропало?». Рассыпание отвечает на этот вопрос само.

   Потом она попросила десять видов на выбор — и выбор этот живёт в
   «Оформлении», рядом с размером текста. Один выбор на три места:
   чаты, группы и избранное. Так и правильно: это не три разных
   удаления, а одно, и человек настраивает его один раз.

   ── КАК СДЕЛАНО, И ПОЧЕМУ ИМЕННО ТАК ───────────────────────────────
   Настоящая пыль — это пиксели строки, разлетающиеся врозь. Чтобы
   получить пиксели, страницу надо перерисовать в картинку, а в
   браузере это умеет только связка SVG foreignObject → canvas. Она
   ломается ровно там, где нам больно: на чужих картинках (аватарки
   приезжают с сервера, и холст от них «портится»), на шрифтах и на
   половине правил вёрстки. Отдать красоту ценой пустых аватарок в
   пыли — плохая сделка.

   Поэтому пыль собрана из самой строки. Строка клонируется столько
   раз, сколько в ней клеточек, и каждый клон обрезан по своей
   клеточке. На экране это та же строка, разрезанная на полсотни
   кусочков, — с аватаркой, шрифтами и цветами, какие есть, потому что
   это и есть она. Дальше каждый кусочек летит своей дорогой.

   Клонов много, но живут они полсекунды и только у одной строки:
   списка это не касается.

   ── ОДНА ОСНОВА НА ДЕСЯТЬ ВИДОВ ────────────────────────────────────
   Виды не десять разных движков, а десять описаний в одной таблице
   ВИДЫ. Каждое отвечает на четыре вопроса: насколько крупно резать,
   сколько лететь, когда трогается этот кусочек и какой у него путь.
   Остальное — нарезка, облако, смыкание — общее. Поэтому новый вид
   стоит десяти строк, а не нового файла, и ни один из них не может
   сломать другой.

   Три вида режут строку не на кусочки, а работают с ней целиком:
   улёт, помехи и исчезание. Им нарезка не нужна и даже вредна —
   «смахнуть» должно уехать одним куском. У них в описании стоит
   `цельно`, и облако для них не строится вовсе: дешевле и честнее.

   ── ДВА ШАГА ───────────────────────────────────────────────────────
   1. Полёт. Кусочки расходятся — каждый вид по-своему.
   2. Смыкание (≈200 мс). Высота самой строки сходит в ноль, и список
      закрывает дыру. Только после этого обещание сбывается, и тот,
      кто звал, меняет данные и перерисовывает список. Если сделать
      наоборот, список дёрнется до того, как пыль улетит.

   ── КОМУ ДВИЖЕНИЕ МЕШАЕТ ───────────────────────────────────────────
   При prefers-reduced-motion любой выбранный вид заменяется
   исчезанием: строка просто бледнеет и смыкается за треть секунды.
   Это не упрощение ради лени — для людей с вестибулярными
   расстройствами летящие куски экрана это плохо.
   ═══════════════════════════════════════════════════════════════════════ */
