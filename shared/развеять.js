/* ═══════════════════════════════════════════════════════════════════════
   РАЗВЕЯТЬ В ПЫЛЬ — одно красивое удаление на всю программу.

       shared/развеять.js

       CW.развеять(узел)            → обещание, сбудется, когда строки нет
       CW.развеять(узел, {вверх})   → пыль летит вверх (по умолчанию да)
       CW.развеять([узел, узел…])   → несколько строк разом

   ── ЗАЧЕМ ──────────────────────────────────────────────────────────
   Анна прислала запись: в Телеграме удалённое не исчезает щелчком, а
   рассыпается в мелкую пыль, пыль сносит вверх, и список спокойно
   смыкается. Разница не в красоте: исчезнувшее мгновенно человек не
   успевает связать со своим нажатием и каждый раз думает «а что
   пропало?». Рассыпание отвечает на этот вопрос само.

   ── КАК СДЕЛАНО, И ПОЧЕМУ ИМЕННО ТАК ───────────────────────────────
   Настоящая пыль — это пиксели строки, разлетающиеся врозь. Чтобы
   получить пиксели, страницу надо перерисовать в картинку, а в
   браузере это умеет только связка SVG foreignObject → canvas. Она
   ломается ровно там, где нам больно: на чужих картинках (аватарки
   приезжают с сервера, и холст от них «портится»), на шрифтах и на
   половине правил вёрстки. Отдать красоту ценой пустых аватарок в
   пыли — плохая сделка.

   Поэтому пыль собрана из самой строки. Строка клонируется столько
   раз, сколько в ней клеточек, и каждый клон обрезан по своей
   клеточке. На экране это та же строка, разрезанная на полсотни
   кусочков, — с аватаркой, шрифтами и цветами, какие есть, потому что
   это и есть она. Дальше каждый кусочек летит своей дорогой.

   Клонов много, но живут они полсекунды и только у одной строки:
   списка это не касается.

   ── ДВА ШАГА ───────────────────────────────────────────────────────
   1. Пыль (≈560 мс). Кусочки разлетаются, бледнеют и размываются.
      Левые трогаются первыми — волной слева направо, как на записи.
   2. Смыкание (≈200 мс). Высота самой строки сходит в ноль, и список
      закрывает дыру. Только после этого обещание сбывается, и тот,
      кто звал, меняет данные и перерисовывает список. Если сделать
      наоборот, список дёрнется до того, как пыль улетит.

   ── КОМУ ДВИЖЕНИЕ МЕШАЕТ ───────────────────────────────────────────
   При prefers-reduced-motion пыли нет вовсе: строка просто бледнеет и
   смыкается за треть секунды. Это не упрощение ради лени — для людей
   с вестибулярными расстройствами летящие куски экрана это плохо.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  var ПЫЛЬ_МС = 720;        /* сколько летит пыль */
  var СМЫК_МС = 200;        /* сколько смыкается список */
  /* Сторона кусочка. Мерено глазами по кадрам: на 22 точках это не
     пыль, а обломки с читаемыми буквами; на 13 строка рассыпается в
     крупу, как на записи. Меньше делать нельзя — клонов станет втрое
     больше, а разницы уже не видно. */
  var КЛЕТКА = 13;
  var МАКС_КУСКОВ = 170;    /* потолок: больше — только нагрузка */

  function тихо() {
    try {
      return окно.matchMedia
        && окно.matchMedia('(prefers-reduced-motion: reduce)').matches;
    } catch (е) { return false; }
  }

  /* Видео и рамки в клонах не нужны: каждый клон завёл бы свой
     проигрыватель, а на пыли их всё равно не разглядеть. Меняем на
     пустое место того же размера, чтобы кусочки не поехали. */
  function обезвредить(клон) {
    var тяжёлые = клон.querySelectorAll('video, iframe, canvas, audio');
    for (var и = 0; и < тяжёлые.length; и++) {
      var т = тяжёлые[и];
      var пусто = документ.createElement('div');
      пусто.style.cssText = 'width:' + т.offsetWidth + 'px;height:'
                          + т.offsetHeight + 'px';
      if (т.parentNode) т.parentNode.replaceChild(пусто, т);
    }
    /* Чужие нажатия и подписи клону ни к чему. */
    клон.removeAttribute('id');
    var сИд = клон.querySelectorAll('[id]');
    for (var к = 0; к < сИд.length; к++) сИд[к].removeAttribute('id');
  }

  /* Смыкание высоты. Отдельно от пыли: его делают и когда пыли нет. */
  function сомкнуть(узел, мс) {
    return new Promise(function (готово) {
      var высота = узел.getBoundingClientRect().height;
      var стиль = узел.style;
      стиль.overflow = 'hidden';
      стиль.height = высота + 'px';
      стиль.transition = 'none';
      /* Перечитываем вёрстку, иначе браузер склеит два присваивания в
         одно и перехода не будет. */
      void узел.offsetHeight;
      стиль.transition = 'height ' + мс + 'ms ease, margin ' + мс + 'ms ease,'
                       + ' padding ' + мс + 'ms ease, opacity ' + мс + 'ms ease';
      стиль.height = '0px';
      стиль.marginTop = '0px';
      стиль.marginBottom = '0px';
      стиль.paddingTop = '0px';
      стиль.paddingBottom = '0px';
      стиль.opacity = '0';
      окно.setTimeout(готово, мс + 30);
    });
  }

  function развеятьОдин(узел, настройки) {
    настройки = настройки || {};
    if (!узел || !узел.parentNode) return Promise.resolve();

    var место = узел.getBoundingClientRect();
    if (!место.width || !место.height) return сомкнуть(узел, 120);
    if (тихо()) {
      узел.style.transition = 'opacity 140ms ease';
      узел.style.opacity = '0';
      return сомкнуть(узел, 180);
    }

    var колонок = Math.max(6, Math.min(34, Math.round(место.width / КЛЕТКА)));
    var строк = Math.max(2, Math.min(10, Math.round(место.height / КЛЕТКА)));
    while (колонок * строк > МАКС_КУСКОВ && колонок > 6) колонок--;
    var шагX = место.width / колонок;
    var шагY = место.height / строк;

    var облако = документ.createElement('div');
    облако.setAttribute('aria-hidden', 'true');
    облако.style.cssText =
      'position:fixed;left:' + место.left + 'px;top:' + место.top + 'px;'
      + 'width:' + место.width + 'px;height:' + место.height + 'px;'
      + 'pointer-events:none;z-index:9500;overflow:visible;'
      + 'contain:layout style;';

    var образец = узел.cloneNode(true);
    обезвредить(образец);
    образец.style.margin = '0';
    образец.style.width = место.width + 'px';
    образец.style.height = место.height + 'px';

    var куски = [];
    for (var р = 0; р < строк; р++) {
      for (var к = 0; к < колонок; к++) {
        var кусок = документ.createElement('div');
        кусок.style.cssText =
          'position:absolute;overflow:hidden;will-change:transform,opacity;'
          + 'left:' + (к * шагX) + 'px;top:' + (р * шагY) + 'px;'
          /* Плюс точка к стороне: без неё между кусочками видны щели. */
          + 'width:' + (шагX + 1) + 'px;height:' + (шагY + 1) + 'px;';
        var внутри = образец.cloneNode(true);
        внутри.style.position = 'absolute';
        внутри.style.left = (-к * шагX) + 'px';
        внутри.style.top = (-р * шагY) + 'px';
        кусок.appendChild(внутри);
        облако.appendChild(кусок);
        куски.push({ узел: кусок, к: к, р: р });
      }
    }

    документ.body.appendChild(облако);
    /* Саму строку прячем, но места не отдаём: его отнимет смыкание.
       Видимость, а не display — иначе список дёрнется раньше пыли. */
    узел.style.visibility = 'hidden';

    куски.forEach(function (п) {
      /* Волна слева направо: левые кусочки трогаются первыми. */
      var задержка = (п.к / колонок) * (ПЫЛЬ_МС * 0.38);
      var вбок = (Math.random() * 30 - 7) + п.к * 0.6;
      var ввысь = -(12 + Math.random() * 40);
      if (настройки.вниз) ввысь = -ввысь;
      var поворот = (Math.random() * 44 - 22);
      try {
        п.узел.animate([
          { transform: 'translate(0,0) scale(1) rotate(0deg)',
            opacity: 1, filter: 'blur(0px)' },
          /* Крупа держится яркой почти до конца и бледнеет в последнюю
             треть. Прежде она гасла сразу: на тёмном оформлении
             полупрозрачные крошки сливаются с фоном, и пыль пропадала
             за полтора десятка кадров — любоваться было нечем. */
          { transform: 'translate(' + (вбок * 0.3) + 'px,' + (ввысь * 0.3)
                       + 'px) scale(.9) rotate(' + (поворот * 0.25) + 'deg)',
            opacity: 1, filter: 'blur(.3px)', offset: .3 },
          { transform: 'translate(' + (вбок * 0.66) + 'px,' + (ввысь * 0.66)
                       + 'px) scale(.7) rotate(' + (поворот * 0.6) + 'deg)',
            opacity: .75, filter: 'blur(.9px)', offset: .66 },
          { transform: 'translate(' + вбок + 'px,' + ввысь
                       + 'px) scale(.42) rotate(' + поворот + 'deg)',
            opacity: 0, filter: 'blur(2px)' }
        ], {
          duration: ПЫЛЬ_МС,
          delay: задержка,
          easing: 'cubic-bezier(.25,.6,.3,1)',
          fill: 'forwards'
        });
      } catch (е) {
        /* Старый браузер без Web Animations: пусть просто исчезнет. */
        п.узел.style.opacity = '0';
      }
    });

    return new Promise(function (готово) {
      окно.setTimeout(function () {
        if (облако.parentNode) облако.parentNode.removeChild(облако);
        сомкнуть(узел, СМЫК_МС).then(готово);
      }, ПЫЛЬ_МС + ПЫЛЬ_МС * 0.38 - 60);
    });
  }

  /* ── НАРУЖУ ──
     Один узел или несколько. Несколько — это выделение, как на записи
     Анны: отмечено две строки, и обе рассыпаются разом. */
  CW.развеять = function (что, настройки) {
    var список = Array.isArray(что) ? что.filter(Boolean) : (что ? [что] : []);
    if (!список.length) return Promise.resolve();
    return Promise.all(список.map(function (у) {
      return развеятьОдин(у, настройки);
    }));
  };

  /* Удобная обёртка: развеять и выбросить из вёрстки совсем. Нужна
     там, где список не перерисовывается целиком. */
  CW.развеятьИУбрать = function (что, настройки) {
    var список = Array.isArray(что) ? что.filter(Boolean) : (что ? [что] : []);
    return CW.развеять(список, настройки).then(function () {
      список.forEach(function (у) {
        if (у && у.parentNode) у.parentNode.removeChild(у);
      });
    });
  };

})(window, document);
