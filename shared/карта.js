  /* ── 6. УЛИЦЫ OPENSTREETMAP ─────────────────────────────────────────
     Настоящие тайлы. Берутся только в плоской проекции и только когда
     слой включён: качать их «на всякий случай» нельзя — это чужой
     бесплатный сервер, и у него есть правила. Если тайл не дошёл, слой
     честно говорит об этом, а карта остаётся своей. */
  var тайлы = {}, тайловОшибок = 0, тайловВсего = 0;
  function тайл(z, x, y){
    var ключ = z + '/' + x + '/' + y;
    if(тайлы[ключ]) return тайлы[ключ];
    var и = new Image();
    и.crossOrigin = 'anonymous';
    и.__готов = false;
    и.onload = function(){ и.__готов = true; };
    и.onerror = function(){ и.__плохо = true; тайловОшибок++; };
    и.src = 'https://tile.openstreetmap.org/' + z + '/' + x + '/' + y + '.png';
    тайлы[ключ] = и; тайловВсего++;
    /* Память не бесконечна: старые тайлы выкидываем. */
    var ключи = Object.keys(тайлы);
    if(ключи.length > 220) for(var i = 0; i < 60; i++) delete тайлы[ключи[i]];
    return и;
  }
  function рисоватьУлицы(){
    if(!К.слои.улицы || К.проекция !== 'плоско') return;
    var z = Math.max(0, Math.min(19, Math.round(К.зум)));
    var n = Math.pow(2, z);
    var мш = мирШирина();
    var размер = мш / n;
    var цx = (К.д + 180) / 360 * n;
    var цy = меркY(К.ш) * n;
    var слева = цx - (Ш / 2) / размер, сверху = цy - (В / 2) / размер;
    var x0 = Math.floor(слева), y0 = Math.floor(сверху);
    var x1 = Math.ceil(слева + Ш / размер), y1 = Math.ceil(сверху + В / размер);
    кт.save();
    кт.globalAlpha = (К.вид === 'улицы') ? 1 : 0.72;
    for(var x = x0; x <= x1; x++){
      for(var y = Math.max(0, y0); y <= Math.min(n - 1, y1); y++){
        var тx = ((x % n) + n) % n;
        var и = тайл(z, тx, y);
        if(!и.__готов) continue;
        кт.drawImage(и, (x - слева) * размер, (y - сверху) * размер, размер + 1, размер + 1);
      }
    }
    кт.restore();
    /* Так просят правила OpenStreetMap, и это честно. */
    кт.font = '10px system-ui,sans-serif';
    кт.textAlign = 'right'; кт.textBaseline = 'bottom';
    кт.fillStyle = 'rgba(0,0,0,.45)';
    кт.fillRect(Ш - 142, В - 16, 138, 14);
    кт.fillStyle = 'rgba(255,255,255,.8)';
    кт.fillText('© OpenStreetMap', Ш - 7, В - 4);
  }
