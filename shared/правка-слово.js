/* ═══════════════════════════════════════════════════════════════════════
   ЛИСТ С ОФОРМЛЕНИЕМ: документ (pdf, docx).

       CW.правкаСлово(узел, файл, {менялось, счёт}) → {тело()}

   Здесь же лежит общая часть, которой пользуются и слайды
   (shared/правка-слайды.js): полоса оформления, привязка полосы к
   листу, разбор и сборка разметки.

   Имя с хвостом «Правки» нарочно: CW.лист — это меню-полка, одно на
   всю программу, и занимать это имя листом документа нельзя. Такое
   уже случилось: кнопка «Подписать» падала с «CW.лист is not a
   function», потому что лист затёр меню.

       CW.листПравки.полоса({линия:true})     собрать полосу
       CW.листПравки.оформлением(полоса, лист, после)
       CW.листПравки.разметкой(тело)          текст или разметка → разметка
       CW.листПравки.телом(лист)              лист → что записать в файл

   Почему лист, а не поле с текстом. В документе есть жирное, цвет,
   заголовки, списки, картинки — всё это разметка, и держать её в
   голом поле означало бы заставить человека писать её руками. Браузер
   умеет править такую разметку сам (contenteditable), мы даём кнопки и
   храним то, что получилось.

   Наружу разметка уходит настоящим .docx или раскладывается по
   страницам PDF — это отдельная часть, и её ещё нет: пока «Скачать»
   отдаёт то, что лежит в файле.

   Чего здесь нет нарочно: переноса предметов и выбора знака. Предмет
   поверх листа живёт в shared/предметы.js, выбор подписи или печати —
   в shared/знаки.js. То и другое нужно ещё и таблице (csv, xlsx), а
   два разных переноса одной и той же картинки — это два разных
   поведения, которые разойдутся на первой же правке.
   ═══════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  var РАЗМЕРЫ = [10, 12, 14, 18, 24, 32, 48];

  function эл(тег, класс) {
    var у = document.createElement(тег);
    if (класс) у.className = класс;
    return у;
  }

  /* ── Полоса оформления ────────────────────────────────────────── */
  function полоса(что) {
    что = что || {};
    var п = эл('div', 'фл-полоса');

    function кн(д, знак, подпись, класс) {
      var б = эл('button', класс || '');
      б.type = 'button'; б.dataset.д = д; б.title = подпись;
      б.innerHTML = знак;
      п.appendChild(б);
      return б;
    }
    function щель() { п.appendChild(эл('span', 'щель')); }

    кн('bold', 'Ж', 'Жирный', 'жирно');
    кн('italic', 'К', 'Курсив', 'курсив');
    кн('underline', 'Ч', 'Подчёркнутый', 'черта');
    щель();

    var размер = эл('select');
    размер.dataset.д = 'размер';
    размер.title = 'Размер';
    var пусто = document.createElement('option');
    пусто.value = ''; пусто.textContent = 'Размер';
    размер.appendChild(пусто);
    РАЗМЕРЫ.forEach(function (р) {
      var о = document.createElement('option');
      о.value = р; о.textContent = р;
      размер.appendChild(о);
    });
    п.appendChild(размер);

    var цвет = эл('button', 'фл-цвет');
    цвет.type = 'button'; цвет.dataset.д = 'цвет'; цвет.title = 'Цвет текста';
    цвет.style.setProperty('--цвет', '#e8e8f0');
    п.appendChild(цвет);

    щель();
    кн('justifyLeft', '◧', 'По левому краю');
    кн('justifyCenter', '◫', 'По центру');
    кн('justifyRight', '◨', 'По правому краю');
    щель();
    кн('з1', 'Н1', 'Заголовок');
    кн('з2', 'Н2', 'Подзаголовок');
    кн('insertUnorderedList', '•', 'Список точками');
    кн('insertOrderedList', '1.', 'Список числами');
    if (что.линия) кн('insertHorizontalRule', '-', 'Линия');
    щель();
    кн('картинка', CW.значок('картинка', 15), 'Картинка');
    кн('ролик', CW.значок('плёнка', 15), 'Ролик');
    кн('подписать', CW.значок('карандаш', 15), 'Подписать');
    щель();
    кн('removeFormat', '⌫', 'Снять оформление');
    return п;
  }

  /* Одно скрытое поле выбора на всё окно: картинка или ролик. */
  function выбратьФайл(приём, когда) {
    var поле = document.getElementById('фл-выбор');
    if (!поле) {
      поле = document.createElement('input');
      поле.type = 'file';
      поле.id = 'фл-выбор';
      поле.style.cssText = 'position:fixed;left:-9999px;top:0;opacity:0';
      document.body.appendChild(поле);
    }
    поле.value = '';
    поле.accept = приём;
    поле.onchange = function () {
      var ф = поле.files && поле.files[0];
      if (ф) когда(ф);
    };
    поле.click();
  }

  /* Кадр из ролика снимает общий файл shared/кадр-ролика.js: тот же
     кадр нужен переписке, и двух таких съёмок в программе быть не
     должно. Здесь только зовём и, если файла рядом нет, тихо
     обходимся без привью — документ примет ролик и так. */
  function кадрИзРолика(файл) {
    var готов = CW.кадрРолика
      ? Promise.resolve()
      : (CW.нужен ? CW.нужен('shared/кадр-ролика.js') : Promise.reject());
    return готов.then(function () {
      return CW.кадрРолика ? CW.кадрРолика.снять(файл) : null;
    }).catch(function () { return null; });
  }

  /* ── Привязка полосы к листу ──────────────────────────────────── */
  function оформлением(п, лист, зов) {
    try { document.execCommand('styleWithCSS', false, true); } catch (е) {}

    /* ── Предметы поверх листа ──
       Картинка, кадр ролика, подпись и печать не встают в строку
       текста: они лежат ПОВЕРХ листа и ставятся куда угодно. Как их
       переносят и тянут за уголок — в shared/предметы.js: ровно то же
       нужно таблице, и двух таких переносов в программе быть не
       должно.

       Слайды переписывают лист целиком при смене слайда, и предметы
       на новом листе приходят без ручек. Поэтому «оживить» наружу:
       слайды зовут его после каждой смены. */
    var пред = CW.предметы(лист, зов);
    зов.предмет = пред.ставить;
    зов.оживить = пред.оживить;

    /* Обвести выделенное своим кусочком разметки: так ставится размер,
       когда браузер отказывается это делать сам. */
    function обвести(примерить) {
      var сел = window.getSelection();
      if (!сел || !сел.rangeCount) return false;
      var r = сел.getRangeAt(0);
      if (r.collapsed || !лист.contains(r.commonAncestorContainer)) return false;
      var кусок = r.extractContents();
      var обёртка = document.createElement('span');
      примерить(обёртка);
      обёртка.appendChild(кусок);
      r.insertNode(обёртка);
      сел.removeAllRanges();
      var нов = document.createRange();
      нов.selectNodeContents(обёртка);
      сел.addRange(нов);
      return true;
    }

    /* Нажатие кнопки не должно уводить курсор из листа: иначе
       выделение пропадает ровно тогда, когда его надо оформить. */
    п.addEventListener('mousedown', function (е) {
      if (е.target.tagName === 'BUTTON') е.preventDefault();
    });

    п.addEventListener('click', function (е) {
      var к = е.target.closest && е.target.closest('button[data-д]');
      if (!к) return;
      var д = к.dataset.д;

      if (д === 'цвет') { палитрой(к); return; }

      if (д === 'картинка') {
        выбратьФайл('image/*', function (ф) {
          CW.сказать('Загружаю…', 60000);
          CW.залить(ф, 'image').then(function (о) {
            пред.ставить('<img src="' + CW.безопасно(о.адрес) + '" alt="">', 0.34);
            CW.сказать('Картинка в документе · её можно двигать', 3500);
          }).catch(function (б) {
            CW.сказать((б && б.message) || 'Файл не загрузился', 6000);
          });
        });
        return;
      }

      if (д === 'ролик') {
        выбратьФайл('video/*', function (ф) {
          CW.сказать('Загружаю…', 120000);
          Promise.all([
            CW.залить(ф, 'movie'),
            кадрИзРолика(ф).then(function (к0) {
              return к0 ? CW.залить(к0, 'image') : null;
            }).catch(function () { return null; })
          ]).then(function (пара) {
            var ролик = пара[0], кадр = пара[1];
            /* Ролик внутрь документа не кладётся ни в одной программе:
               кладём кадр, а под ним ссылку. */
            пред.ставить('<a href="' + CW.безопасно(ролик.адрес) + '" data-ролик="1">'
              + (кадр ? '<img src="' + CW.безопасно(кадр.адрес) + '" alt="">'
                      : CW.безопасно(ф.name))
              + '</a><span class="фл-ролик">▷ ' + CW.безопасно(ф.name) + '</span>', 0.34);
            CW.сказать('Ролик в документе · его можно двигать', 3500);
          }).catch(function (б) {
            CW.сказать((б && б.message) || 'Файл не загрузился', 6000);
          });
        });
        return;
      }

      /* Подписать: выбор знака и снимок с него — в shared/знаки.js,
         потому что тем же путём подписывают таблицу. Сюда возвращается
         только адрес картинки. Ширина по умолчанию — четверть листа:
         столько занимает подпись на бумаге. */
      if (д === 'подписать') {
        CW.знаки.выбрать(function (адрес) {
          пред.ставить('<img src="' + CW.безопасно(адрес) + '" alt="">', 0.26);
          CW.сказать('Знак в документе · его можно двигать', 3500);
        });
        return;
      }

      лист.focus();
      try { document.execCommand('styleWithCSS', false, true); } catch (б) {}
      try {
        if (д === 'з1' || д === 'з2') {
          document.execCommand('formatBlock', false, д === 'з1' ? 'H1' : 'H2');
        } else {
          document.execCommand(д, false, null);
        }
      } catch (б) {}
      зов.менялось();
      зов.посчитать();
    });

    /* Размер в документе Word — в пунктах; на странице пишем в точках. */
    п.querySelector('[data-д="размер"]').addEventListener('change', function () {
      var р = Number(this.value);
      this.value = '';
      if (!р) return;
      лист.focus();
      if (!обвести(function (э) { э.style.fontSize = Math.round(р * 4 / 3) + 'px'; })) {
        CW.сказать('Сначала выдели текст', 3000);
      }
      зов.менялось();
      зов.посчитать();
    });

    /* Цвет — своей палитрой, как везде в программе. */
    var палитра = null;
    function палитрой(кн) {
      if (палитра) { палитра.убрать(); палитра = null; return; }
      CW.нужен('shared/выбор-знака.js').then(function () {
        палитра = CW.палитраЦвета(лист.closest('.ок-окно') || лист.parentNode, {
          цвет: '#e8e8f0',
          меняется: function (ц) {
            кн.style.setProperty('--цвет', ц);
            лист.focus();
            var вышло = false;
            try {
              document.execCommand('styleWithCSS', false, true);
              вышло = document.execCommand('foreColor', false, ц);
            } catch (е) {}
            if (!вышло) обвести(function (э) { э.style.color = ц; });
            зов.менялось();
            зов.посчитать();
          },
          закрыли: function () { палитра = null; }
        });
        палитра.узел.classList.add('под-полосой');
      });
    }

    лист.addEventListener('input', function () {
      зов.менялось();
      зов.посчитать();
    });
  }

  /* Обычный текст приводим к разметке построчно: файл мог лежать
     простым текстом (например, пришёл загрузкой). */
  function разметкой(тело) {
    var т = String(тело == null ? '' : тело);
    if (!т) return '<div><br></div>';
    if (/<[a-z!\/]/i.test(т)) return т;
    return т.split('\n').map(function (с) {
      return '<div>' + (CW.безопасно(с) || '<br>') + '</div>';
    }).join('');
  }

  /* В файл уходит чистый лист: уголок, крестик и отметка «взят» —
     это ручки для правки, а не часть документа. Их снимаем с копии,
     чтобы не трогать то, что человек сейчас видит. */
  function телом(лист) {
    var копия = лист.cloneNode(true);
    [].slice.call(копия.querySelectorAll('.фл-уг, .фл-убрать')).forEach(function (э) {
      if (э.parentNode) э.parentNode.removeChild(э);
    });
    [].slice.call(копия.querySelectorAll('.фл-пред')).forEach(function (э) {
      э.classList.remove('взят');
    });
    return копия.innerHTML;
  }

  /* Пустой лист отмечаем классом: по нему виден текст подсказки. */
  function пустота(лист) {
    лист.classList.toggle('пусто', !String(лист.textContent || '').trim()
                                   && !лист.querySelector('img'));
  }

  CW.листПравки = {
    полоса: полоса,
    пустота: пустота,
    оформлением: оформлением,
    разметкой: разметкой,
    телом: телом
  };

  /* ── Документ: pdf и docx ─────────────────────────────────────── */
  CW.правкаСлово = function (куда, ф, зов) {
    var столбец = эл('div', 'фл-столбец');
    var п = полоса({ линия: true });
    var сцена = эл('div', 'фл-сцена');
    var лист = эл('div', 'фл-лист');
    лист.contentEditable = 'true';
    лист.spellcheck = true;
    лист.setAttribute('data-подсказка', 'Пишите здесь…');
    лист.innerHTML = разметкой(ф.body);
    сцена.appendChild(лист);
    столбец.appendChild(п);
    столбец.appendChild(сцена);
    куда.appendChild(столбец);

    function посчитать() {
      пустота(лист);
      var т = лист.textContent || '';
      /* В документе строки считаем абзацами: переводов строки внутри
         разметки нет, и «1 строк» стояло бы всегда. */
      /* Предмет поверх листа — не абзац: он не в тексте, а над ним. */
      var абзацев = лист.querySelectorAll(
        'div:not(.фл-пред):not(.фл-уг),p,li,h1,h2').length || 1;
      зов.счёт(т.length + ' знаков · ' + абзацев + ' абзацев');
    }

    оформлением(п, лист, { менялось: зов.менялось, посчитать: посчитать });
    посчитать();
    setTimeout(function () { CW.встать(лист); }, 60);

    return { тело: function () { return телом(лист); } };
  };
})();
