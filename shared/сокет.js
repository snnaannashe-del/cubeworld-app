/* ═══════════════════════════════════════════════════════════════════════
   ЖИВАЯ СВЯЗЬ С СЕРВЕРОМ — один сокет на страницу.

   До этого файла в программе не было ни одного веб-сокета: всё
   спрашивалось запросами. Для переписки это терпимо, для звонка — нет:
   пока один набирает, другой должен услышать звонок за секунду, а не
   за двадцать.

       CW.сокет.завести();                   поднять связь
       CW.сокет.слушать('call_sig', fn);     что приходит
       CW.сокет.послать({ type:'…' });       что уходит
       CW.сокет.насвязи();                   да или нет

   КАК ЭТО УСТРОЕНО У СЕРВЕРА. Ручка /ws/{ключ} уже есть и работает:
   через неё ходят личные сообщения и сведение эфиров. Своей ручки для
   звонков у сервера нет, и мы её не просим: звонки идут по той же
   дорожке, что эфиры (type: stream_sig). Сервер в неё не смотрит — он
   просто передаёт письмо тому, кому оно адресовано. Поэтому звонки
   работают на сервере, который УЖЕ выложен, и ничего доставлять на
   Render не нужно.

   ЧТО ДЕЛАЕМ ПРИ ОБРЫВЕ. Связь рвётся постоянно: уснул телефон,
   сменилась сеть, прокси закрыл тихое соединение. Поэтому сокет сам
   встаёт обратно, с нарастающей паузой (1, 2, 4… до 30 секунд), и шлёт
   «ping» раз в 25 секунд — иначе посредники закрывают молчащее
   соединение через минуту, и человек не узнаёт об этом до первого
   неотправленного письма.

   ЧЕГО ЗДЕСЬ НЕТ НАРОЧНО. Сокет не хранит сообщений и не повторяет их:
   если связь легла, письмо не уходит, и тот, кто его отправил, узнаёт
   об этом сразу (послать() вернёт false). Молчаливая очередь, которая
   «когда-нибудь доставит», в звонке хуже честного отказа.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  var сокет = null;
  var хотим = false;          /* нужна ли связь вообще */
  var попытка = 0;
  var часыПинга = null;
  var часыВозврата = null;
  var слушатели = {};         /* тип → [функции] */

  function адресСокета() {
    var ключ = CW.токен();
    if (!ключ) return '';
    var основа = String(CW.адрес || '');
    if (!основа) {
      основа = окно.location.protocol + '//' + окно.location.host;
    }
    return основа.replace(/^http/i, 'ws').replace(/\/+$/, '')
         + '/ws/' + encodeURIComponent(ключ);
  }

  /* Слушателя роняет его собственная ошибка, а не наша: ловим, чтобы
     одна поломка не оборвала разговор всем остальным. Но МОЛЧА не
     глотаем — пишем в журнал браузера: ошибка, о которой никто не
     узнал, ищется потом часами. */
  function сказатьВсем(письмо) {
    var тип = (письмо && письмо.type) || '';
    (слушатели[тип] || []).concat(слушатели['*'] || []).forEach(function (ф) {
      try { ф(письмо); }
      catch (е) {
        try { окно.console.error('сокет: слушатель «' + тип + '» упал', е); } catch (_) {}
      }
    });
  }

  function завести() {
    хотим = true;
    if (сокет && (сокет.readyState === 0 || сокет.readyState === 1)) return сокет;
    var адрес = адресСокета();
    if (!адрес) return null;

    try { сокет = new окно.WebSocket(адрес); }
    catch (е) { сокет = null; позже(); return null; }

    сокет.onopen = function () {
      попытка = 0;
      сказатьВсем({ type: 'связь', состояние: 'есть' });
      clearInterval(часыПинга);
      часыПинга = setInterval(function () {
        послать({ type: 'ping' });
      }, 25000);
    };

    сокет.onmessage = function (е) {
      var письмо = null;
      try { письмо = JSON.parse(е.data); } catch (_) { return; }
      if (!письмо || письмо.type === 'pong') return;
      сказатьВсем(письмо);
    };

    сокет.onclose = function () {
      clearInterval(часыПинга);
      сказатьВсем({ type: 'связь', состояние: 'нет' });
      if (хотим) позже();
    };

    /* Ошибку отдельно не разбираем: за ней всегда идёт close, и
       лечение у них одно — встать заново. */
    сокет.onerror = function () {};

    return сокет;
  }

  function позже() {
    clearTimeout(часыВозврата);
    var пауза = Math.min(30000, 1000 * Math.pow(2, Math.min(5, попытка++)));
    часыВозврата = setTimeout(function () { if (хотим) завести(); }, пауза);
  }

  function послать(письмо) {
    if (!сокет || сокет.readyState !== 1) return false;
    try { сокет.send(JSON.stringify(письмо)); return true; }
    catch (е) { return false; }
  }

  function закрыть() {
    хотим = false;
    clearInterval(часыПинга);
    clearTimeout(часыВозврата);
    if (сокет) { try { сокет.close(); } catch (е) {} }
    сокет = null;
  }

  CW.сокет = {
    завести: завести,
    закрыть: закрыть,
    послать: послать,
    насвязи: function () { return !!сокет && сокет.readyState === 1; },

    слушать: function (тип, ф) {
      (слушатели[тип] = слушатели[тип] || []).push(ф);
      return function снять() {
        слушатели[тип] = (слушатели[тип] || []).filter(function (х) { return х !== ф; });
      };
    },

    /* Дождаться связи — нужно тому, кто звонит сразу после открытия
       страницы: сокет в этот миг ещё поднимается. */
    дождаться: function (сколькоЖдать) {
      if (CW.сокет.насвязи()) return Promise.resolve(true);
      завести();
      return new Promise(function (готово) {
        var снято = false;
        var снять = CW.сокет.слушать('связь', function (п) {
          if (п.состояние !== 'есть' || снято) return;
          снято = true; снять(); готово(true);
        });
        setTimeout(function () {
          if (снято) return;
          снято = true; снять(); готово(CW.сокет.насвязи());
        }, сколькоЖдать || 6000);
      });
    }
  };

  /* Страницу закрывают — закрываем и связь: висящий сокет держит у
     сервера запись «этот человек в сети» дольше правды. */
  окно.addEventListener('pagehide', закрыть);

})(window);
