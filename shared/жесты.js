/* ═══════════════════════════════════════════════════════════════════════
   ЖЕСТЫ ПЕРЕД КАМЕРОЙ — рукой, головой, ногой, всем телом.

       CW.нужен('shared/жесты.js').then(function () {
         CW.жесты(true);          включить
         CW.жестыИдут();          идут ли
         CW.жесты(false);         выключить
       });

   Жест уходит в игру: CW.игра.жест('влево', 'рука').

   ── Почему без библиотеки распознавания рук ────────────────────────
   Готовые решения тянут модель на 8–10 МБ со стороннего сервера, просят
   много памяти и садят батарею. А нам не нужны пальцы — нужно знать,
   где рука и куда она движется. Это считается по разнице соседних
   кадров: кадр ужимается до 64×48 точек, и мы смотрим, где картинка
   изменилась. Весит ноль, работает без сети и на слабом телефоне.

   ── Почему отдельным файлом ────────────────────────────────────────
   Он приезжает только тогда, когда жесты включают. Код, который просит
   камеру, не должен лежать на странице у человека, который играет
   нажатиями: камера — это разрешение, и спрашивать его надо ровно в тот
   миг, когда оно понадобилось.

   ── Камеру гасим сами ──────────────────────────────────────────────
   Выключили жесты, ушли со страницы, свернули вкладку — поток
   останавливается. Держать камеру включённой просто так нельзя: это и
   батарея, и доверие.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно, документ) {
  'use strict';
  var CW = окно.CW = окно.CW || {};

  var Ш = 64, В = 48;                 /* размер рабочего кадра */
  var полотно = null, кт = null, прошлый = null;
  var видео = null, поток = null, часы = null;
  var идут = false;

  /* Что видим прямо сейчас. Всё в долях кадра, 0…1. */
  var вижу = { есть: false, сила: 0, x: 0.5, y: 0.5, dx: 0, dy: 0, площадь: 0 };
  var след = [];                      /* последние центры — по ним читаем круг */
  var когдаЖест = 0;

  /* ═════════════════════════════════════════════════════════════════════
     1. КАДРЫ С КАМЕРЫ
     ═════════════════════════════════════════════════════════════════════ */
  function завестиКамеру() {
    return new Promise(function (готово, беда) {
      if (!navigator.mediaDevices || !navigator.mediaDevices.getUserMedia) {
        беда(new Error('нет камеры')); return;
      }
      navigator.mediaDevices.getUserMedia({
        video: { facingMode: 'user', width: { ideal: 320 }, height: { ideal: 240 } },
        audio: false
      }).then(function (п) {
        поток = п;
        var в = документ.createElement('video');
        в.muted = true; в.playsInline = true; в.autoplay = true;
        в.srcObject = п;
        /* Картинку с камеры на экран не выводим: она нужна счёту, а не
           глазу. Но и display:none нельзя — браузер тогда не крутит
           кадры. Поэтому два пикселя за краем экрана. */
        в.style.cssText = 'position:fixed;left:-9999px;width:2px;height:2px';
        документ.body.appendChild(в);
        в.play().catch(function () {});
        в.onloadeddata = function () { готово(в); };
        setTimeout(function () { готово(в); }, 1500);
      }).catch(беда);
    });
  }

  function погасить() {
    if (поток) {
      try { поток.getTracks().forEach(function (д) { д.stop(); }); } catch (е) {}
    }
    поток = null;
    if (видео && видео.parentNode) видео.parentNode.removeChild(видео);
    видео = null;
  }

  function кадр() {
    if (!видео || видео.readyState < 2) return;
    if (!полотно) {
      полотно = документ.createElement('canvas');
      полотно.width = Ш; полотно.height = В;
      кт = полотно.getContext('2d', { willReadFrequently: true });
    }
    try { кт.drawImage(видео, 0, 0, Ш, В); } catch (е) { return; }
    var д;
    try { д = кт.getImageData(0, 0, Ш, В).data; } catch (е) { return; }

    var сейчас = new Uint8Array(Ш * В);
    for (var i = 0, п = 0; i < д.length; i += 4, п++) {
      сейчас[п] = (д[i] * 77 + д[i + 1] * 151 + д[i + 2] * 28) >> 8;   /* в серый */
    }
    if (!прошлый) { прошлый = сейчас; return; }

    /* Где картинка изменилась — там и движение. Порог отсекает шум
       матрицы: без него «движение» видно даже на неподвижной стене. */
    var сх = 0, су = 0, точек = 0;
    for (var y = 0; y < В; y++) {
      for (var x = 0; x < Ш; x++) {
        var к = y * Ш + x;
        var р = сейчас[к] - прошлый[к]; if (р < 0) р = -р;
        if (р > 22) { сх += x; су += y; точек++; }
      }
    }
    прошлый = сейчас;

    var было = { x: вижу.x, y: вижу.y };
    var доля = точек / (Ш * В);
    вижу.площадь = доля;
    вижу.сила = Math.min(1, доля * 7);
    вижу.есть = точек > 28;
    if (вижу.есть) {
      /* Камера показывает зеркало: поднятая правая рука видна слева.
         Переворачиваем, иначе «вправо» бросало бы влево. */
      вижу.x = 1 - (сх / точек) / Ш;
      вижу.y = (су / точек) / В;
      вижу.dx = вижу.x - было.x;
      вижу.dy = вижу.y - было.y;
      след.push({ x: вижу.x, y: вижу.y });
      if (след.length > 14) след.shift();
    } else {
      вижу.dx = вижу.dy = 0;
      if (след.length) след.shift();
    }
  }

  /* ═════════════════════════════════════════════════════════════════════
     2. ЖЕСТЫ

     Разбираем не отдельный кадр, а весь кусочек пути за последние
     полсекунды. Иначе взмах и круг не отличить: прямая линия, проходящая
     через середину, накручивает ровно тот же угол, что и оборот, — на
     этом первая версия и попалась, круг срабатывал на всё подряд.

     Различает их длина пути против смещения: у взмаха рука прошла
     примерно столько, на сколько сместилась, у круга — втрое больше при
     почти нулевом смещении.
     ═════════════════════════════════════════════════════════════════════ */
  function путь() {
    if (след.length < 7) return null;
    var п = след.slice(-12);
    var н = п[0], к = п[п.length - 1];
    var смещение = Math.hypot(к.x - н.x, к.y - н.y);
    var длина = 0;
    for (var i = 1; i < п.length; i++) {
      длина += Math.hypot(п[i].x - п[i - 1].x, п[i].y - п[i - 1].y);
    }
    var mx = 0, my = 0;
    п.forEach(function (т) { mx += т.x; my += т.y; });
    mx /= п.length; my /= п.length;

    var угол = 0, мин = 9, сум = 0, плюс = 0;
    for (var j = 1; j < п.length; j++) {
      var r = Math.hypot(п[j].x - mx, п[j].y - my);
      if (r < мин) мин = r;
      сум += r;
      var a1 = Math.atan2(п[j - 1].y - my, п[j - 1].x - mx);
      var a2 = Math.atan2(п[j].y - my, п[j].x - mx);
      var d = a2 - a1;
      while (d > Math.PI) d -= Math.PI * 2;
      while (d < -Math.PI) d += Math.PI * 2;
      угол += d;
      if (d > 0) плюс++;
    }
    return {
      смещение: смещение, длина: длина, угол: угол,
      минR: мин, средR: сум / (п.length - 1),
      вОднуСторону: Math.max(плюс, п.length - 1 - плюс) / (п.length - 1),
      dx: к.x - н.x, dy: к.y - н.y
    };
  }

  function жест() {
    if (!вижу.есть) return '';
    var п = путь();

    /* Круг: путь намного длиннее смещения, угол за оборот с лишним,
       крутится в одну сторону и не проваливается в середину. */
    if (п && Math.abs(п.угол) > 4.6 && п.длина > п.смещение * 2.6
        && п.минR > п.средR * 0.42 && п.вОднуСторону > 0.78 && п.длина > 0.5) {
      return 'круг';
    }
    /* Обе руки: движения много и оно по всему кадру. */
    if (вижу.сила > 0.8 && вижу.площадь > 0.32) return 'хаос';

    /* Взмах: рука прошла примерно столько, на сколько сместилась. */
    if (п && п.смещение > 0.26 && п.длина < п.смещение * 1.9) {
      if (Math.abs(п.dx) > Math.abs(п.dy) * 1.25) return п.dx > 0 ? 'вправо' : 'влево';
      if (Math.abs(п.dy) > Math.abs(п.dx) * 1.25) return п.dy > 0 ? 'вниз' : 'вверх';
    }
    /* Ладонь вперёд: пятно растёт, а центр стоит на месте. */
    if (вижу.сила > 0.5 && (!п || п.смещение < 0.09) && вижу.площадь > 0.12) {
      return 'толчок';
    }
    return '';
  }

  /* ── ЧЕМ ДВИГАЛИ ──
     Камера не узнаёт части тела и обещать этого нельзя. Зато она точно
     знает, ГДЕ в кадре движение и насколько оно крупное, а человек
     перед камерой стоит предсказуемо: голова вверху кадра, руки
     посередине, ноги внизу, а когда двигается всё тело — меняется весь
     кадр. Этого хватает, чтобы у головы, ноги и тела были свои
     действия, и это честно написано в окне. */
  CW.частьТела = function (в) {
    в = в || вижу;
    if (!в || !в.есть) return '';
    if (в.площадь > 0.34) return 'тело';
    if (в.y < 0.34) return 'голова';
    if (в.y > 0.62) return 'нога';
    return 'рука';
  };

  function тик() {
    кадр();
    if (CW.игра && CW.игра.сила) CW.игра.сила(вижу.сила);
    var ж = жест();
    if (!ж) return;
    /* Пауза между жестами. Один взмах длится несколько кадров, и без
       паузы он превратился бы в десяток команд подряд. */
    var теперь = Date.now();
    if (теперь - когдаЖест < 850) return;
    когдаЖест = теперь;
    след = [];
    /* Когда включён персонаж, жест обращён к нему, а не к кубам: бить
       соседа и одновременно разбрасывать кубы — два разных занятия. */
    if (CW.персонаж && CW.персонаж.жест(ж, вижу)) return;
    if (CW.игра && CW.игра.жест) CW.игра.жест(ж, CW.частьТела(вижу));
  }

  /* ═════════════════════════════════════════════════════════════════════
     3. ВКЛЮЧИТЬ И ВЫКЛЮЧИТЬ
     ═════════════════════════════════════════════════════════════════════ */
  CW.жесты = function (надо) {
    if (надо === идут) return Promise.resolve(идут);

    if (!надо) {
      идут = false;
      clearInterval(часы); часы = null;
      прошлый = null; след = [];
      погасить();
      if (CW.игра && CW.игра.сила) CW.игра.сила(0);
      return Promise.resolve(false);
    }

    return завестиКамеру().then(function (в) {
      видео = в; идут = true; прошлый = null; след = [];
      if (CW.игра && CW.игра.включить) CW.игра.включить(true);
      clearInterval(часы);
      /* Двадцать кадров в секунду: глазу этого хватает, а считать надо
         вдвое меньше, чем при полной частоте экрана. */
      часы = setInterval(тик, 50);
      if (CW.сказать) CW.сказать('Жесты включены');
      return true;
    }).catch(function () {
      идут = false;
      CW.сказать('Без камеры жесты не работают, играй нажатиями');
      return false;
    });
  };

  CW.жестыИдут = function () { return идут; };
  CW.жестыВыкл = function () { return CW.жесты(false); };

  /* Свернули вкладку или ушли со страницы — камера гаснет. */
  документ.addEventListener('visibilitychange', function () {
    if (документ.hidden && идут) CW.жесты(false);
  });
  окно.addEventListener('pagehide', function () { if (идут) CW.жесты(false); });

})(window, document);
