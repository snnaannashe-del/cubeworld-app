/* ═══════════════════════════════════════════════════════════════════════
   ЭФИР НЕ ТЕРЯЕТСЯ ПРИ ПЕРЕХОДЕ.
   /home/claude/новое/cubeworld-app/shared/эфир.js

   Человек в эфире заходит в куб, открывает меню, идёт в кошелёк — это
   РАЗНЫЕ СТРАНИЦЫ, и окно эфира вместе со страницей исчезало. Для него
   это выглядело как обрыв: кнопку «Закончить» он не нажимал, а эфира
   нет.

   Этот файл — две строки работы: посмотреть, остался ли эфир в памяти
   вкладки, и открыть его окно заново, свёрнутым и на том же месте.
   Сам эфир на сервере всё это время шёл: его держат часы биения, а не
   открытое окно.

   Память пишет окно эфира (modals/live.js) в sessionStorage под ключом
   «cw_эфир»: {ид, свой, свёрнут, x, y}. Пропадает она вместе с
   вкладкой — это правильно: открытая заново программа не должна
   воскрешать вчерашний эфир.

   ЧЕГО ЗДЕСЬ НЕТ. Камеры: свёрнутое окно её не просит. Человек
   развернёт полоску — и камера включится там же, где он находится.
   ═══════════════════════════════════════════════════════════════════════ */
(function (окно) {
  'use strict';
  var CW = окно.CW = окно.CW || {};
  var документ = окно.document;

  function вернуть() {
    var з = null;
    try { з = JSON.parse(окно.sessionStorage.getItem('cw_эфир') || 'null'); }
    catch (е) { з = null; }
    if (!з || !з.ид) return;
    if (!CW.токен || !CW.токен()) return;       /* вышел из программы */
    if (документ.querySelector('.ок-подложка[data-окно="эфир"]')) return;

    /* Спрашиваем сервер, идёт ли он ещё: эфир могли закончить с другого
       устройства, и возвращать мёртвое окно нельзя. */
    CW.спросить('/streams/' + з.ид, { тихо: true }).then(function (о) {
      var э = (о && о.stream) || null;
      if (!э || э.status !== 'идёт') {
        try { окно.sessionStorage.removeItem('cw_эфир'); } catch (е) {}
        return;
      }
      CW.открыть('live', { эфир: э, ид: з.ид, свой: !!з.свой, свёрнут: true });
    });
  }

  if (документ.readyState === 'loading') {
    документ.addEventListener('DOMContentLoaded', function () {
      /* Даём странице встать на ноги: окно эфира ложится поверх неё, и
         открывать его раньше, чем появится полоса меню, незачем. */
      окно.setTimeout(вернуть, 400);
    });
  } else {
    окно.setTimeout(вернуть, 400);
  }
})(window);
