/* ═══════════════════════════════════════════════════════════════════════
   РИСУНОК (svg): холст, кисть, ластик.

       CW.правкаРисунок(узел, файл, {менялось, счёт}) → {тело()}

   Файл остаётся настоящим .svg: каждый мазок — это <path> с точками,
   цветом и толщиной. Поэтому рисунок можно открыть заново и дорисовать,
   а не только посмотреть: картинка в точках (png) этого не позволила бы.

   Холст всегда 1000 × 700 и белый. Белый — не из упрямства: svg кладут
   в документ и отправляют собеседнику, а прозрачный лист на светлой
   бумаге превращается в невидимые линии. Размер один, чтобы рисунок,
   начатый на телефоне, открылся на большом экране тем же, а не растянул
   мазки вдвое: на экран холст подгоняется только видом, точки в файле
   те же.

   Ластик — не стиратель, а кисть цветом листа и вдвое толще. Так он
   работает в работающей программе, и у него есть видимое достоинство:
   «Отменить» снимает мазок ластика ровно так же, как любой другой.
   ═══════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  var ХОЛСТ_Ш = 1000, ХОЛСТ_В = 700, ЛИСТ = '#ffffff';
  var ТОЛЩИНЫ = [2, 5, 9, 16, 28];

  function эл(тег, класс) {
    var у = document.createElement(тег);
    if (класс) у.className = класс;
    return у;
  }

  function путьИзТочек(точки) {
    return точки.map(function (т, и) {
      return (и ? 'L' : 'M') + Math.round(т[0]) + ' ' + Math.round(т[1]);
    }).join(' ');
  }

  function вСВГ(штрихи) {
    var пути = (штрихи || []).map(function (ш) {
      if (!ш.точки || ш.точки.length < 2) return '';
      return '<path d="' + путьИзТочек(ш.точки) + '" stroke="' + ш.цвет
        + '" stroke-width="' + ш.толщина + '" fill="none" stroke-linecap="round"'
        + ' stroke-linejoin="round"/>';
    }).join('');
    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + ХОЛСТ_Ш
      + ' ' + ХОЛСТ_В + '" width="' + ХОЛСТ_Ш + '" height="' + ХОЛСТ_В + '">'
      + '<rect width="' + ХОЛСТ_Ш + '" height="' + ХОЛСТ_В + '" fill="' + ЛИСТ + '"/>'
      + пути + '</svg>';
  }

  /* Читаем обратно свои же мазки. Чужой svg (из редактора или из сети)
     тоже откроется, если он нарисован путями: кривые Безье мы при этом
     разложим в точки и на следующем сохранении запишем ломаной. Поэтому
     чужой файл сюда и не несём — только свой. */
  function изСВГ(текст) {
    if (!текст) return [];
    try {
      var д = new DOMParser().parseFromString(текст, 'image/svg+xml');
      return [].slice.call(д.getElementsByTagName('path')).map(function (п) {
        var d = п.getAttribute('d') || '';
        var числа = d.match(/-?\d+(?:\.\d+)?/g) || [];
        var точки = [];
        for (var i = 0; i + 1 < числа.length; i += 2) точки.push([+числа[i], +числа[i + 1]]);
        return {
          цвет: п.getAttribute('stroke') || '#000000',
          толщина: Number(п.getAttribute('stroke-width')) || 4,
          точки: точки
        };
      }).filter(function (ш) { return ш.точки.length > 1; });
    } catch (е) { return []; }
  }

  /* Разбор и сборка мазков нужны не только рисунку: подпись хранит
     росчерк теми же штрихами и открывает старые файлы, записанные
     обычным svg. Поэтому они наружу, а не спрятаны внутри. */
  CW.мазки = { вСВГ: вСВГ, изСВГ: изСВГ, путьИзТочек: путьИзТочек };

  CW.правкаРисунок = function (куда, ф, зов) {
    var штрихи = изСВГ(ф.body);
    var цвет = '#0095F6', толщина = 5, ластик = false;

    var столбец = эл('div', 'фл-столбец');
    var полоса = эл('div', 'фл-полоса');

    function кн(д, знак, подсказка, выбран) {
      var б = эл('button', выбран ? 'выбран' : '');
      б.type = 'button'; б.dataset.д = д; б.title = подсказка;
      б.innerHTML = знак;
      полоса.appendChild(б);
      return б;
    }

    кн('кисть', CW.значок('карандаш', 15), 'Кисть', true);
    кн('ластик', '⌫', 'Ластик', false);
    полоса.appendChild(эл('span', 'щель'));

    /* Цвет берём своей палитрой, а не полем браузера: то рисует
       системное окно чужого вида и чужих красок, и в тёмной программе
       оно выглядит заплаткой. Своя палитра одна на всю программу —
       та же, что за кружком-радугой в оформлении. */
    var полеЦвета = эл('button', 'фл-цвет');
    полеЦвета.type = 'button';
    полеЦвета.title = Т('Цвет кисти');
    полеЦвета.style.setProperty('--цвет', цвет);
    полоса.appendChild(полеЦвета);

    var палитра = null;
    полеЦвета.onclick = function () {
      if (палитра) { палитра.убрать(); палитра = null; return; }
      CW.нужен('shared/выбор-знака.js').then(function () {
        палитра = CW.палитраЦвета(куда.closest('.ок-окно') || куда, {
          цвет: цвет,
          меняется: function (ц) {
            цвет = ц;
            полеЦвета.style.setProperty('--цвет', ц);
            взять(false);
          },
          закрыли: function () { палитра = null; }
        });
        палитра.узел.classList.add('под-полосой');
      });
    };

    var полеТолщины = эл('select');
    полеТолщины.title = Т('Толщина');
    ТОЛЩИНЫ.forEach(function (т) {
      var о = document.createElement('option');
      о.value = т; о.textContent = т;
      if (т === толщина) о.selected = true;
      полеТолщины.appendChild(о);
    });
    полоса.appendChild(полеТолщины);

    полоса.appendChild(эл('span', 'щель'));
    кн('назад', '↺', 'Отменить последний мазок');
    кн('очистить', CW.значок('урна', 15), 'Очистить лист');

    var обёртка = эл('div', 'фл-холст-обёртка');
    var холст = эл('canvas', 'фл-холст');
    холст.width = ХОЛСТ_Ш;
    холст.height = ХОЛСТ_В;
    обёртка.appendChild(холст);

    столбец.appendChild(полоса);
    столбец.appendChild(обёртка);
    куда.appendChild(столбец);

    var г = холст.getContext('2d');
    перерисовать();
    посчитать();

    function перерисовать() {
      г.fillStyle = ЛИСТ;
      г.fillRect(0, 0, ХОЛСТ_Ш, ХОЛСТ_В);
      г.lineCap = 'round';
      г.lineJoin = 'round';
      штрихи.forEach(function (ш) {
        if (!ш.точки.length) return;
        г.strokeStyle = ш.цвет;
        г.lineWidth = ш.толщина;
        г.beginPath();
        ш.точки.forEach(function (т, и) {
          if (и) г.lineTo(т[0], т[1]); else г.moveTo(т[0], т[1]);
        });
        г.stroke();
      });
    }

    function посчитать() {
      зов.счёт(Т.с('{н} мазков', { н: штрихи.length }));
    }

    /* Точка пальца — в точках холста, а не экрана: холст показан
       уменьшенным, и без пересчёта линия шла бы мимо руки. */
    function где(е) {
      var р = холст.getBoundingClientRect();
      return [(е.clientX - р.left) * ХОЛСТ_Ш / р.width,
              (е.clientY - р.top) * ХОЛСТ_В / р.height];
    }

    var ведём = null;
    холст.addEventListener('pointerdown', function (е) {
      е.preventDefault();
      try { холст.setPointerCapture(е.pointerId); } catch (б) {}
      ведём = {
        цвет: ластик ? ЛИСТ : цвет,
        толщина: ластик ? толщина * 2.4 : толщина,
        точки: [где(е)]
      };
      штрихи.push(ведём);
    });
    холст.addEventListener('pointermove', function (е) {
      if (!ведём) return;
      ведём.точки.push(где(е));
      перерисовать();
    });
    ['pointerup', 'pointercancel', 'pointerleave'].forEach(function (с) {
      холст.addEventListener(с, function () {
        if (!ведём) return;
        /* Одно касание без движения — не мазок, а промах: в файл такой
           путь не кладём, иначе в svg копятся пустые линии. */
        if (ведём.точки.length < 2) штрихи.pop();
        ведём = null;
        зов.менялось();
        посчитать();
      });
    });

    полоса.addEventListener('click', function (е) {
      var к = е.target.closest && е.target.closest('button[data-д]');
      if (!к) return;
      var д = к.dataset.д;
      if (д === 'кисть' || д === 'ластик') { взять(д === 'ластик'); return; }
      if (д === 'назад') {
        if (!штрихи.length) return;
        штрихи.pop();
        перерисовать(); зов.менялось(); посчитать();
        return;
      }
      if (д === 'очистить') {
        if (!штрихи.length) return;
        CW.открыть('delete', {
          чего: 'лист',
          что: ф.name || 'рисунок',
          ещё: Т.с('Все {н} мазков уйдут.', { н: штрихи.length }),
          кнопка: Т('Очистить'),
          навсегда: true,
          делать: function () {
            штрихи.length = 0;
            перерисовать(); зов.менялось(); посчитать();
          }
        });
      }
    });

    function взять(этоЛастик) {
      ластик = !!этоЛастик;
      полоса.querySelector('[data-д="кисть"]').classList.toggle('выбран', !ластик);
      полоса.querySelector('[data-д="ластик"]').classList.toggle('выбран', ластик);
    }

    полеТолщины.addEventListener('change', function () {
      толщина = Number(this.value) || 5;
    });

    return { тело: function () { return вСВГ(штрихи); } };
  };
})();
