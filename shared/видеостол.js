  /* ═══════════════════════════════════════════════════════════════
     ЗВУКОВАЯ ЦЕПЬ УЗЛА

     Узел помнит свой вход в граф: завести второй - ошибка браузера.
     Поэтому цепь строится один раз и навсегда, а эффекты не
     пересобирают её, а только крутят ручки у готовых узлов. В
     нейтральном положении цепь слышно так же, как без неё:
     обрезка снизу на 10 Гц, сверху на 20 кГц, сжатие в один к
     одному, кольцо на единице, эхо в ноль.

         вход → ВЧ → НЧ → жим → кольцо ─┬─────────────→ выход
                                        └→ задержка → эхо ┘

     ── ЧТО ЭТО УМЕЕТ ЧЕСТНО ──
     Шумоподавление здесь - обрезка низкого гула и ровнитель
     громкости, а не студийная чистка: шипение улицы оно уберёт
     наполовину, а не насухо. Голос выше или ниже мы НЕ делаем:
     в браузере это тянет за собой и длину записи, а значит
     разъехалось бы с картинкой. Поэтому «Робот» сделан кольцевой
     модуляцией, а не сдвигом тона, и длина не меняется.
     ═══════════════════════════════════════════════════════════════ */
  function подключить(ac, узел) {
    if (!узел.cwЦепь) узел.cwЦепь = цепью(ac, узел);
    return узел.cwЦепь.выход;
  }

  function цепью(ac, узел) {
    var ц = { ac: ac };
    ц.вход = ac.createMediaElementSource(узел);

    ц.вч = ac.createBiquadFilter();
    ц.вч.type = 'highpass'; ц.вч.frequency.value = 10;
    ц.нч = ac.createBiquadFilter();
    ц.нч.type = 'lowpass';  ц.нч.frequency.value = 20000;

    ц.жим = ac.createDynamicsCompressor();
    ц.жим.threshold.value = 0; ц.жим.ratio.value = 1; ц.жим.knee.value = 0;

    ц.кольцо = ac.createGain();  ц.кольцо.gain.value = 1;
    ц.ген = ac.createOscillator(); ц.ген.frequency.value = 30;
    ц.глубина = ac.createGain(); ц.глубина.gain.value = 0;
    ц.ген.connect(ц.глубина); ц.глубина.connect(ц.кольцо.gain);
    try { ц.ген.start(); } catch (е) {}

    ц.задержка = ac.createDelay(1.2); ц.задержка.delayTime.value = 0.19;
    ц.отклик = ac.createGain(); ц.отклик.gain.value = 0.32;
    ц.мокро = ac.createGain(); ц.мокро.gain.value = 0;

    ц.выход = ac.createGain(); ц.выход.gain.value = 1;

    ц.вход.connect(ц.вч); ц.вч.connect(ц.нч); ц.нч.connect(ц.жим);
    ц.жим.connect(ц.кольцо);
    ц.кольцо.connect(ц.выход);
    ц.кольцо.connect(ц.задержка);
    ц.задержка.connect(ц.отклик); ц.отклик.connect(ц.задержка);
    ц.задержка.connect(ц.мокро); ц.мокро.connect(ц.выход);
    /* Чтобы звук и дальше было слышно в окне показа. */
    ц.выход.connect(ac.destination);
    return ц;
  }

