  /* Один голос: волна, дорожка частоты, громкость и фильтр. */
  function голос(о) {
    var а = звукОК(); if (!а) return;
    var т = а.currentTime;
    var г = а.createGain();
    var ф = а.createBiquadFilter();
    ф.type = о.фильтр || 'lowpass';
    ф.frequency.value = о.срез || 2600;
    ф.Q.value = о.q || 1;
    var ос = а.createOscillator();
    ос.type = о.волна || 'sawtooth';
    var д = о.тон;
    ос.frequency.setValueAtTime(д[0], т);
    for (var i = 1; i < д.length; i++) {
      ос.frequency.exponentialRampToValueAtTime(Math.max(30, д[i]),
        т + о.длина * (i / (д.length - 1)));
    }
    г.gain.setValueAtTime(0.0001, т);
    г.gain.exponentialRampToValueAtTime(о.громко || 0.22, т + (о.атака || 0.03));
    г.gain.exponentialRampToValueAtTime(0.0001, т + о.длина);
    ос.connect(ф); ф.connect(г); г.connect(а.destination);
    ос.start(т); ос.stop(т + о.длина + 0.05);
  }

  /* Шум — для шипения, хлопка и хруста. */
  function шум(длина, срез, громко) {
    var а = звукОК(); if (!а) return;
    var н = Math.floor(а.sampleRate * длина);
    var б = а.createBuffer(1, н, а.sampleRate);
    var д = б.getChannelData(0);
    for (var i = 0; i < н; i++) д[i] = (Math.random() * 2 - 1) * (1 - i / н);
    var и = а.createBufferSource(); и.buffer = б;
    var ф = а.createBiquadFilter(); ф.type = 'bandpass';
    ф.frequency.value = срез || 1200; ф.Q.value = 0.8;
    var г = а.createGain(); г.gain.value = громко || 0.18;
    и.connect(ф); ф.connect(г); г.connect(а.destination);
    и.start();
  }

