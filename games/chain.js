/* ═══════════════════════════════════════════════════════════════════════
   TRUSTCHAIN — СОБЕРИ ЦЕПЬ.

   Блоки показывают числа. Нажимай по возрастанию. Ошибся — цепь
   рвётся. Каждый круг цепь длиннее на один блок, а времени столько же.

       cubeworld-app/games/chain.js

   Игра не рисует себе окна и не знает, где она идёт: окно, счёт,
   рекорд, кнопки и конец партии — всё это даёт общая оболочка
   shared/игры.js и передаёт сюда одним свёртком «И».
   ═══════════════════════════════════════════════════════════════════════ */
CW.игра_('chain', function (И) {
  'use strict';

  var ИГРА = {
    к:'chain', имя:'TrustChain', знак:'🔗', сторона:1,
    начать:function(){
      this.длина = 4; this.круг = 1; this.разложить();
    },
    разложить:function(){
      var n = this.длина;
      this.блоки = [];
      var места = [];
      for(var i = 0; i < n; i++){
        var п, попыток = 0;
        do{
          п = {x:0.1 + Math.random() * 0.8, y:0.12 + Math.random() * 0.74};
          попыток++;
        }while(попыток < 60 && места.some(function(м){
          return Math.abs(м.x - п.x) < 0.19 && Math.abs(м.y - п.y) < 0.17; }));
        места.push(п);
        this.блоки.push({x:п.x, y:п.y, н:i + 1, снят:false});
      }
      this.след = 1;
      this.часы = 7 + this.длина * 0.7;
    },
    тык:function(x, y){
      if(!И.жива()) return;
      var Ш = И.холст().width, В = И.холст().height, р = Ш * 0.075;
      for(var i = 0; i < this.блоки.length; i++){
        var б = this.блоки[i]; if(б.снят) continue;
        if(Math.abs(x - б.x * Ш) < р && Math.abs(y - б.y * В) < р){
          if(б.н === this.след){
            б.снят = true; this.след++; И.прибавить(15);
            if(this.след > this.длина){
              И.прибавить(60 + this.длина * 10);
              this.длина++; this.круг++; this.разложить();
            }
          }else{
            И.конец('Цепь порвалась', И.шаб('Собрано кругов: {1}.', this.круг - 1));
          }
          return;
        }
      }
    },
    шаг:function(дт){
      this.часы -= дт;
      if(this.часы <= 0) И.конец('Время вышло', И.шаб('Собрано кругов: {1}.', this.круг - 1));
    },
    рисовать:function(к, Ш, В){
      к.clearRect(0, 0, Ш, В);
      var р = Ш * 0.075;
      /* Уже собранную часть соединяем линией — видно, что это цепь. */
      var собраны = this.блоки.filter(function(б){ return б.снят; })
                        .sort(function(a, b){ return a.н - b.н; });
      if(собраны.length > 1){
        к.beginPath();
        собраны.forEach(function(б, i){
          i ? к.lineTo(б.x * Ш, б.y * В) : к.moveTo(б.x * Ш, б.y * В);
        });
        к.strokeStyle = 'rgba(74,222,128,.5)'; к.lineWidth = Math.max(2, Ш / 180); к.stroke();
      }
      this.блоки.forEach(function(б){
        var x = б.x * Ш, y = б.y * В;
        И.прям(к, x - р, y - р, р * 2, р * 2,
             б.снят ? 'rgba(74,222,128,.28)' : 'rgba(96,165,250,.3)', р * 0.35);
        И.текст(к, String(б.н), x, y, р * 0.95, б.снят ? 'rgba(255,255,255,.45)' : '#fff', true);
      });
      var доля = Math.max(0, this.часы) / (7 + this.длина * 0.7);
      И.прям(к, 0, В - В * 0.025, Ш * доля, В * 0.025,
           доля > 0.3 ? '#4ade80' : '#f87171', 0);
      И.состояние(И.шаб('круг {1}', this.круг) + ' · ' + И.шаб('дальше {1}', this.след));
    }
  };

  return ИГРА;
});
