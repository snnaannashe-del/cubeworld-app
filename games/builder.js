/* ═══════════════════════════════════════════════════════════════════════
   CUBEBUILDER — БАШНЯ.

   Плита ходит вбок, нажатие её роняет. Что свесилось — отваливается,
   и следующая плита уже уже. Промахнулся мимо башни — конец.

       cubeworld-app/games/builder.js

   Игра не рисует себе окна и не знает, где она идёт: окно, счёт,
   рекорд, кнопки и конец партии — всё это даёт общая оболочка
   shared/игры.js и передаёт сюда одним свёртком «И».
   ═══════════════════════════════════════════════════════════════════════ */
CW.игра_('builder', function (И) {
  'use strict';

  var ИГРА = {
    к:'builder', имя:'CubeBuilder', знак:'🏗️', тянется:true,
    кнопки:[{имя:'Положить', гл:true, как:function(){ ИГРА.класть(); }}],
    начать:function(){
      this.башня = [{x:0.3, ш:0.4}];
      this.ход = 1; this.скорость = 0.5; this.текX = 0;
      this.ширина = 0.4; this.высота = 0;
      this.сдвигКамеры = 0;
    },
    жать:function(){ this.класть(); },
    тык:function(){ this.класть(); },
    класть:function(){
      if(!И.жива()) return;
      var верх = this.башня[this.башня.length - 1];
      var лево = Math.max(this.текX, верх.x);
      var право = Math.min(this.текX + this.ширина, верх.x + верх.ш);
      var ш = право - лево;
      if(ш <= 0.004){
        И.конец('Мимо', И.шаб('Башня встала на {1}-м ярусе.', this.башня.length));
        return;
      }
      var точно = ш > this.ширина - 0.012;
      this.башня.push({x:лево, ш:ш});
      this.ширина = ш;
      И.прибавить(точно ? 30 : 10);
      this.скорость = Math.min(1.5, this.скорость + 0.045);
      this.текX = (this.башня.length % 2) ? 0 : 1 - this.ширина;
      this.ход = (this.башня.length % 2) ? 1 : -1;
    },
    шаг:function(дт){
      this.текX += this.ход * this.скорость * дт;
      if(this.текX < 0){ this.текX = 0; this.ход = 1; }
      if(this.текX + this.ширина > 1){ this.текX = 1 - this.ширина; this.ход = -1; }
    },
    рисовать:function(к, Ш, В){
      к.clearRect(0, 0, Ш, В);
      /* Камера висит над верхушкой: самая свежая плита всегда на одной
         высоте, а башня уходит вниз за край. Раньше ярусы рисовались в
         обратном порядке, и башня выглядела перевёрнутой. */
      var в = Math.max(14, В / 15);
      /* На широком экране башня строится в колонке посередине: иначе
         плита растягивается на пол-экрана и попасть в неё нечем. */
      var КШ = Math.min(Ш, В * 0.75), К0 = (Ш - КШ) / 2;
      /* Пока башня низкая, она стоит на полу — пустого неба под ней нет.
         Когда дорастает до верха, камера поднимается вместе с плитой. */
      var yПлиты = Math.max(В * 0.1, В - (this.башня.length + 1) * в - 6);
      var n = this.башня.length;
      var видно = Math.min(n, Math.ceil(В / в) + 1);
      for(var i = 0; i < видно; i++){
        var б = this.башня[n - 1 - i];       // верхняя — сразу под плитой
        var y = yПлиты + (i + 1) * в;
        if(y > В) break;
        var ц = 'hsl(' + ((n - i) * 27 % 360) + ',70%,58%)';
        И.прям(к, К0 + б.x * КШ, y, б.ш * КШ, в - 2, ц, 4);
      }
      И.прям(к, К0 + this.текX * КШ, yПлиты, this.ширина * КШ, в - 2, 'rgba(255,255,255,.9)', 4);
      И.состояние(И.шаб('ярус {1}', n));
    }
  };

  return ИГРА;
});
