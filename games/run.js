/* ═══════════════════════════════════════════════════════════════════════
   CUBERUN — ЗАБЕГ.

       cubeworld-app/games/run.js

   Куб бежит сам, ты только прыгаешь: нажатие по полю, кнопка «Прыжок»,
   пробел или стрелка вверх. Чем дальше убежал, тем быстрее бег и тем
   чаще препятствия.

   ── Второй прыжок ─────────────────────────────────────────────────
   В воздухе разрешён ровно один добор. Без него забег превращается в
   лотерею: две тумбы подряд на большой скорости не перепрыгнуть никак,
   и человек проигрывает не по своей вине.
   ═══════════════════════════════════════════════════════════════════════ */
CW.игра_('run', function (И) {
  'use strict';

  var ЗЕМЛЯ = 0.78;        /* доля высоты, на которой лежит пол */

  var ИГРА = {
    к: 'run', имя: 'CubeRun', знак: '🏃', сторона: 1.9,
    кнопки: [{ имя: 'Прыжок', гл: true, как: function () { ИГРА.прыжок(); } }],

    начать: function () {
      this.y = 0;            /* высота над полом, в долях высоты поля */
      this.вверх = 0;        /* скорость по вертикали */
      this.прыжков = 0;
      this.скорость = 0.42;  /* ширины поля в секунду */
      this.путь = 0;
      this.тумбы = [{ x: 1.3, ш: 0.055, в: 0.12 }];
      this.земля = 0;
    },

    прыжок: function () {
      if (!И.жива()) return;
      if (this.y <= 0.001) { this.вверх = 0.78; this.прыжков = 1; return; }
      if (this.прыжков < 2) { this.вверх = 0.66; this.прыжков++; }
    },
    жать: function (к) { if (к !== 'вниз') this.прыжок(); },
    тык: function () { this.прыжок(); },

    шаг: function (дт) {
      /* Тяжесть и движение считаем от долей поля, а не от точек: поле у
         нас подгоняется под окно, и в точках игра на телефоне и на
         столе шла бы с разной скоростью. */
      this.вверх -= 2.6 * дт;
      this.y += this.вверх * дт;
      if (this.y <= 0) { this.y = 0; this.вверх = 0; this.прыжков = 0; }

      this.скорость = Math.min(1.1, 0.42 + this.путь * 0.02);
      var д = this.скорость * дт;
      this.путь += д;
      this.земля = (this.земля + д) % 0.1;
      И.очки(Math.floor(this.путь * 100));

      var я = { x: 0.12, ш: 0.07, в: 0.1 };
      for (var i = this.тумбы.length - 1; i >= 0; i--) {
        var т = this.тумбы[i];
        т.x -= д;
        if (т.x + т.ш < -0.1) { this.тумбы.splice(i, 1); continue; }
        /* Столкновение: по горизонтали пересеклись, а куб ниже верха
           тумбы. Ширину куба считаем честно, без поблажек по краям. */
        if (т.x < я.x + я.ш && т.x + т.ш > я.x && this.y < т.в) {
          И.конец('Врезался', И.шаб('Пробежал {1}.', Math.floor(this.путь * 100)));
          return;
        }
      }
      var последняя = this.тумбы.length ? this.тумбы[this.тумбы.length - 1] : null;
      /* Расстояние между тумбами держим не меньше того, что успеваешь
         перепрыгнуть на нынешней скорости. */
      var зазор = 0.45 + this.скорость * 0.5 + Math.random() * 0.35;
      if (!последняя || последняя.x < 1 - зазор) {
        this.тумбы.push({
          x: 1.05,
          ш: 0.045 + Math.random() * 0.03,
          в: 0.1 + Math.random() * 0.09
        });
      }
    },

    рисовать: function (к, ш, в) {
      к.clearRect(0, 0, ш, в);
      var пол = в * ЗЕМЛЯ;

      /* Полоски под полом — чтобы бег был виден. Без них куб висит на
         месте, а мир вокруг неподвижен. */
      к.strokeStyle = 'rgba(255,255,255,.12)'; к.lineWidth = 2;
      for (var п = -this.земля; п < 1; п += 0.1) {
        к.beginPath();
        к.moveTo(п * ш, пол + в * 0.03);
        к.lineTo((п + 0.05) * ш, пол + в * 0.03);
        к.stroke();
      }
      к.strokeStyle = 'rgba(74,158,255,.5)';
      к.beginPath(); к.moveTo(0, пол); к.lineTo(ш, пол); к.stroke();

      var сам = this;
      this.тумбы.forEach(function (т) {
        И.прям(к, т.x * ш, пол - т.в * в, т.ш * ш, т.в * в, '#f472b6', 3);
      });

      var стор = 0.07 * ш;
      И.прям(к, 0.12 * ш, пол - сам.y * в - стор, стор, стор, '#4a9eff', 4);

      И.состояние(И.шаб('скорость {1}', this.скорость.toFixed(2)));
    }
  };

  return ИГРА;
});
