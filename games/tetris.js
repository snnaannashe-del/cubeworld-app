/* ═══════════════════════════════════════════════════════════════════════
   CRYPTOTETRIS — ПАДАЮЩИЕ БЛОКИ.

       cubeworld-app/games/tetris.js

   Десять клеток в ширину, восемнадцать в высоту. Семь фигур. Собрал
   полный ряд — он исчезает, за четыре ряда разом дают вчетверо больше.
   Каждые десять рядов — уровень, и падение ускоряется.

   ── Почему не как в боевой ────────────────────────────────────────
   Там тетрис был отдельной разметкой и играл только с клавиатуры: на
   телефоне в него нельзя было сыграть вовсе. Здесь он такая же игра,
   как остальные семь: холст, кнопки под пальцем, свайп по полю и
   стрелки на клавиатуре — всё сразу.
   ═══════════════════════════════════════════════════════════════════════ */
CW.игра_('tetris', function (И) {
  'use strict';

  var Ш = 10, В = 18;

  /* Семь фигур в виде точек. Четвёртая координата не нужна: поворот
     считаем вокруг середины фигуры, а не по таблице положений. */
  var ФИГУРЫ = [
    { т: [[0,1],[1,1],[2,1],[3,1]], ц: '#22d3ee' },   /* палка   */
    { т: [[0,0],[0,1],[1,1],[2,1]], ц: '#60a5fa' },   /* Г       */
    { т: [[2,0],[0,1],[1,1],[2,1]], ц: '#fbbf24' },   /* обратная Г */
    { т: [[1,0],[2,0],[1,1],[2,1]], ц: '#facc15' },   /* квадрат */
    { т: [[1,0],[2,0],[0,1],[1,1]], ц: '#4ade80' },   /* S       */
    { т: [[1,0],[0,1],[1,1],[2,1]], ц: '#a78bfa' },   /* Т       */
    { т: [[0,0],[1,0],[1,1],[2,1]], ц: '#f87171' }    /* Z       */
  ];

  var ИГРА = {
    к: 'tetris', имя: 'CryptoTetris', знак: '🟦', сторона: Ш / В,
    подсказка: 'Кнопками ниже, свайпом по полю или стрелками на клавиатуре. '
      + 'Вверх — поворот, вниз — уронить.',
    кнопки: [
      { имя: '⟳', как: function () { ИГРА.повернуть(); } },
      { имя: '←', как: function () { ИГРА.сдвиг(-1); } },
      { имя: '↓', как: function () { ИГРА.вниз(); } },
      { имя: '→', как: function () { ИГРА.сдвиг(1); } },
      { имя: 'Пауза', мал: true, как: function () { ИГРА.пауза = !ИГРА.пауза; } }
    ],

    начать: function () {
      this.поле = [];
      for (var y = 0; y < В; y++) this.поле.push(new Array(Ш).fill(null));
      this.рядов = 0; this.уровень = 1; this.пауза = false;
      this.часы = 0;
      this.новая();
    },

    новая: function () {
      var ф = ФИГУРЫ[Math.floor(Math.random() * ФИГУРЫ.length)];
      this.фиг = { т: ф.т.map(function (п) { return [п[0], п[1]]; }), ц: ф.ц,
                   x: 3, y: 0 };
      if (!this.можно(this.фиг.т, this.фиг.x, this.фиг.y)) {
        И.конец('Стакан полон', И.шаб('Собрано рядов: {1}.', this.рядов));
      }
    },

    можно: function (т, сx, сy) {
      for (var i = 0; i < т.length; i++) {
        var x = сx + т[i][0], y = сy + т[i][1];
        if (x < 0 || x >= Ш || y >= В) return false;
        if (y >= 0 && this.поле[y][x]) return false;
      }
      return true;
    },

    сдвиг: function (д) {
      if (!И.жива() || this.пауза) return;
      if (this.можно(this.фиг.т, this.фиг.x + д, this.фиг.y)) this.фиг.x += д;
    },

    повернуть: function () {
      if (!И.жива() || this.пауза) return;
      /* Поворот вокруг середины фигуры: y → x, x → (высота−1−y). */
      var макс = 0;
      this.фиг.т.forEach(function (п) { макс = Math.max(макс, п[1]); });
      var новая = this.фиг.т.map(function (п) { return [макс - п[1], п[0]]; });
      /* Если у стены не помещается — пробуем подвинуть на клетку. */
      var сдвиги = [0, -1, 1, -2, 2];
      for (var i = 0; i < сдвиги.length; i++) {
        if (this.можно(новая, this.фиг.x + сдвиги[i], this.фиг.y)) {
          this.фиг.т = новая; this.фиг.x += сдвиги[i]; return;
        }
      }
    },

    вниз: function () {
      if (!И.жива() || this.пауза) return;
      if (this.можно(this.фиг.т, this.фиг.x, this.фиг.y + 1)) {
        this.фиг.y++; И.прибавить(1); return;
      }
      this.положить();
    },

    положить: function () {
      var п = this.поле, ф = this.фиг;
      ф.т.forEach(function (т) {
        var y = ф.y + т[1], x = ф.x + т[0];
        if (y >= 0 && y < В && x >= 0 && x < Ш) п[y][x] = ф.ц;
      });
      /* Полные ряды снимаем сверху вниз, чтобы не сбить отсчёт. */
      var снято = 0;
      for (var y = В - 1; y >= 0; y--) {
        var полон = true;
        for (var x = 0; x < Ш; x++) if (!п[y][x]) { полон = false; break; }
        if (!полон) continue;
        п.splice(y, 1);
        п.unshift(new Array(Ш).fill(null));
        снято++; y++;
      }
      if (снято) {
        this.рядов += снято;
        /* Четыре разом стоят вчетверо дороже четырёх по одному — иначе
           собирать «колодец» незачем. */
        И.прибавить([0, 100, 300, 600, 1200][снято]);
        this.уровень = 1 + Math.floor(this.рядов / 10);
      }
      this.новая();
    },

    жать: function (к) {
      if (к === 'лево') this.сдвиг(-1);
      else if (к === 'право') this.сдвиг(1);
      else if (к === 'вниз') this.вниз();
      else this.повернуть();
    },
    тык: function () { this.повернуть(); },

    шаг: function (дт) {
      if (this.пауза) return;
      this.часы += дт;
      var срок = Math.max(0.09, 0.62 - this.уровень * 0.05);
      if (this.часы < срок) return;
      this.часы = 0;
      this.вниз();
    },

    рисовать: function (к, ш, в) {
      к.clearRect(0, 0, ш, в);
      var с = ш / Ш;
      /* Сетка еле видна: она нужна, чтобы считать клетки взглядом, и не
         нужна настолько, чтобы спорить с фигурами. */
      к.strokeStyle = 'rgba(255,255,255,.05)'; к.lineWidth = 1;
      for (var i = 1; i < Ш; i++) {
        к.beginPath(); к.moveTo(i * с, 0); к.lineTo(i * с, в); к.stroke();
      }
      for (var j = 1; j < В; j++) {
        к.beginPath(); к.moveTo(0, j * с); к.lineTo(ш, j * с); к.stroke();
      }
      var п = this.поле;
      for (var y = 0; y < В; y++) for (var x = 0; x < Ш; x++) {
        if (п[y][x]) И.прям(к, x * с + 1, y * с + 1, с - 2, с - 2, п[y][x], с * 0.2);
      }
      var ф = this.фиг;
      if (ф) ф.т.forEach(function (т) {
        var y = ф.y + т[1];
        if (y < 0) return;
        И.прям(к, (ф.x + т[0]) * с + 1, y * с + 1, с - 2, с - 2, ф.ц, с * 0.2);
      });
      И.состояние(this.пауза ? 'пауза'
                             : ('ряды ' + this.рядов + ' · уровень ' + this.уровень));
    }
  };

  return ИГРА;
});
