/* ═══════════════════════════════════════════════════════════════════════
   BLOCK TRADE — БИРЖА НА ПОЛТОРЫ МИНУТЫ.

   Цена блока идёт сама, ты покупаешь и продаёшь. Начинаешь с тысячи,
   счёт — то, что заработал сверх неё.

   Экран подписан нарочно подробно: первая его version показывала строку
   «7 · блоков 13 по 76 · −246 · 82 с» без единой подписи, и понять, что
   происходит, было нельзя.

       cubeworld-app/games/trade.js

   Игра не рисует себе окна и не знает, где она идёт: окно, счёт,
   рекорд, кнопки и конец партии — всё это даёт общая оболочка
   shared/игры.js и передаёт сюда одним свёртком «И».
   ═══════════════════════════════════════════════════════════════════════ */
CW.игра_('trade', function (И) {
  'use strict';

  var ИГРА = {
    к:'trade', имя:'Block Trade', знак:'📈', тянется:true,
    /* v=558 · Подсказка была про правила вообще. Теперь она говорит,
       что делать: три шага, по порядку. */
    начать:function(){
      /* Немного предыстории: иначе первые секунды на графике три отрезка,
         и понять, куда идёт цена, не по чему. */
      this.цена = 100; this.ряд = []; this.тренд = 0;
      for(var i = 0; i < 40; i++){
        this.тренд = this.тренд * 0.86 + (Math.random() - 0.5) * 0.9;
        this.цена = Math.max(8, this.цена * (1 + this.тренд * 0.03));
        this.ряд.push(this.цена);
      }
      this.деньги = 1000; this.штук = 0;
      /* v=557 · Средняя цена покупки. Без неё игра была угадайкой: на
         экране цена сейчас, а по какой ты купил — помни сам. Теперь она
         и в строке состояния, и пунктиром на графике. */
      this.вложено = 0;
      this.часы = 90; this.тик = 0; this.тренд = 0;
      И.кнопки([
        {имя:'Купить', гл:true, как:function(){ ИГРА.купить(); }},
        {имя:'Продать', как:function(){ ИГРА.продать(); }},
        {имя:'Всё в сделку', мал:true, как:function(){ ИГРА.всё(); }},
        /* v=557 · Симметричная кнопка. Раньше «всё» можно было только
           купить, а продавать — по одному блоку: набрав десяток, человек
           десять раз тыкал в «Продать», пока цена уходила. */
        {имя:'Продать всё', мал:true, как:function(){ ИГРА.всёНазад(); }}
      ]);
    },
    средняя:function(){
      return this.штук > 0 ? (this.вложено / this.штук) : 0;
    },
    купить:function(){
      if(!И.жива() || this.деньги < this.цена) return;
      this.деньги -= this.цена; this.штук++; this.вложено += this.цена;
    },
    всё:function(){
      if(!И.жива()) return;
      var n = Math.floor(this.деньги / this.цена);
      if(n <= 0) return;
      this.деньги -= n * this.цена; this.штук += n; this.вложено += n * this.цена;
    },
    продать:function(){
      if(!И.жива() || this.штук <= 0) return;
      this.вложено -= this.средняя();          /* уносим долю средней цены */
      this.деньги += this.цена; this.штук--;
      if(this.штук === 0) this.вложено = 0;
    },
    всёНазад:function(){
      if(!И.жива() || this.штук <= 0) return;
      this.деньги += this.штук * this.цена;
      this.штук = 0; this.вложено = 0;
    },
    шаг:function(дт){
      this.часы -= дт; this.тик += дт;
      if(this.тик >= 0.35){
        this.тик = 0;
        this.тренд = this.тренд * 0.86 + (Math.random() - 0.5) * 0.9;
        this.цена = Math.max(8, this.цена * (1 + this.тренд * 0.035 + (Math.random() - 0.5) * 0.02));
        this.ряд.push(this.цена);
        if(this.ряд.length > 120) this.ряд.shift();
        var итог = this.деньги + this.штук * this.цена;
        И.очки(Math.max(0, итог - 1000));
      }
      if(this.часы <= 0){
        var всё = this.деньги + this.штук * this.цена;
        var разница = Math.round(всё - 1000);
        И.очки(Math.max(0, разница));
        /* v=557 · Говорим правду про убыток. Раньше при минусе счёт
           показывал 0 и пояснение «На руках 870 при старте 1000» — а
           насколько ушёл в минус, человек считал в уме. */
        И.конец(разница >= 0 ? 'В плюсе' : 'В минусе',
              разница >= 0
                ? И.шаб('Заработано {1} сверх тысячи.', разница)
                : И.шаб('Потеряно {1} из тысячи.', Math.abs(разница)));
      }
    },
    рисовать:function(к, Ш, В){
      /* v=558 · Экран переписан так, чтобы было видно, ЧТО происходит.
         Было: крошечная строчка в шапке «7 · блоков 13 по 76 · −246 ·
         82 с» без единой подписи — поди пойми, что 7 это деньги, а −246
         убыток, — и огромная цена посреди пустого графика. Анна так и
         сказала: «я не понимаю, что там происходит».
         Стало: подписанные числа, прибыль словом, полоса времени и
         подсказка, что делать прямо сейчас. */
      к.clearRect(0, 0, Ш, В);
      var р = this.ряд, n = р.length;
      var мин = Math.min.apply(null, р), макс = Math.max.apply(null, р);
      if(макс - мин < 1){ макс = мин + 1; }

      var ср = this.средняя();
      var итого = this.деньги + this.штук * this.цена;
      var дельта = Math.round(итого - 1000);
      var было = n > 1 ? р[n - 2] : р[n - 1];
      var растёт = this.цена >= было;
      var зелёный = '#4ade80', красный = '#f87171', тихий = 'rgba(255,255,255,.55)';

      /* Раскладку считаем сверху вниз бегунком, а не долями высоты.
         Доли ломались на широком экране: три подписанных числа налезали
         на строку «цена за блок», потому что высота окна там маленькая,
         а доли те же. Теперь каждая строка знает, сколько места заняла
         предыдущая. */
      var рц  = Math.max(20, Math.min(Ш, В) / 11);     /* цена */
      var рлб = Math.max(10, рц * 0.4);                /* подпись под ценой */
      var рз  = Math.max(14, Math.min(Ш, В) / 21);     /* значения столбцов */
      var рн  = Math.max(9, рз * 0.5);                 /* подписи столбцов */
      var рп2 = Math.max(13, Math.min(Ш, В) / 23);     /* прибыль */
      var у = В * 0.02 + рц * 0.6;
      var уЦена = у;
      у += рц * 0.62 + рлб * 0.6;
      var уЦенаПодпись = у;
      у += рлб * 0.7 + рз * 0.7;
      var уЗнач = у;
      var уПодпись = уЗнач + рз * 0.82;
      у = уПодпись + рн * 0.7 + рп2 * 0.9;
      var уПрибыль = у;

      var низ = В * 0.795;
      var верх = Math.min(низ - В * 0.25, уПрибыль + рп2 * 0.9);

      к.beginPath();
      for(var i = 0; i < n; i++){
        var x = Ш * i / Math.max(1, n - 1);
        var y = низ - (р[i] - мин) / (макс - мин) * (низ - верх);
        i ? к.lineTo(x, y) : к.moveTo(x, y);
      }
      к.strokeStyle = (р[n-1] >= р[0]) ? зелёный : красный;
      к.lineWidth = Math.max(2, Ш / 300); к.stroke();
      к.lineTo(Ш, низ); к.lineTo(0, низ); к.closePath();
      к.fillStyle = (р[n-1] >= р[0]) ? 'rgba(74,222,128,.12)' : 'rgba(248,113,113,.12)';
      к.fill();

      /* Пунктир по своей цене — и подпись к нему: без подписи это просто
         полоска неизвестно про что. */
      if(ср > 0 && ср >= мин && ср <= макс){
        var уср = низ - (ср - мин) / (макс - мин) * (низ - верх);
        к.save();
        к.setLineDash([5, 5]);
        к.strokeStyle = 'rgba(255,255,255,.5)';
        к.lineWidth = Math.max(1, Ш / 600);
        к.beginPath(); к.moveTo(0, уср); к.lineTo(Ш, уср); к.stroke();
        к.setLineDash([]);
        var рп = Math.max(10, Math.min(Ш, В) / 36);
        к.font = '700 ' + рп + 'px system-ui,-apple-system,sans-serif';
        к.textAlign = 'left'; к.textBaseline = 'bottom';
        к.fillStyle = 'rgba(255,255,255,.75)';
        к.fillText(И.шаб('твоя цена {1}', Math.round(ср)), Ш * 0.03, уср - рп * 0.4);
        к.restore();
      }

      /* ── Цена ─────────────────────────────────────────────────── */
      И.текст(к, (растёт ? '\u25B2 ' : '\u25BC ') + Math.round(this.цена),
            Ш / 2, уЦена, рц, растёт ? зелёный : красный, true);
      И.текст(к, И.слово('цена за блок'), Ш / 2, уЦенаПодпись, рлб, тихий, false);

      /* ── Три подписанных числа ────────────────────────────────── */
      /* Столбцы держим в середине, а не по третям всей ширины: на
         мониторе «деньги» уезжали к левому краю, «всего» — к правому, и
         взглядом их было не собрать. */
      var полоса = Math.min(Ш * 0.92, Math.max(300, В * 0.95));
      var слева = (Ш - полоса) / 2;
      var столбцы = [
        [И.слово('деньги'), String(Math.round(this.деньги))],
        [И.слово('блоков'), String(this.штук)],
        [И.слово('всего'),  String(Math.round(итого))]
      ];
      столбцы.forEach(function(ст, j){
        var x = слева + полоса * (j + 0.5) / 3;
        И.текст(к, ст[1], x, уЗнач, рз, '#fff', true);
        И.текст(к, ст[0], x, уПодпись, рн, тихий, false);
      });

      /* ── Прибыль словом, а не одним знаком ────────────────────── */
      И.текст(к,
        (дельта >= 0 ? И.шаб('прибыль +{1}', дельта)
                     : И.шаб('убыток −{1}', Math.abs(дельта))),
        Ш / 2, уПрибыль, рп2, дельта >= 0 ? зелёный : красный, true);

      /* ── Время полосой ────────────────────────────────────────── */
      var сек = Math.max(0, Math.ceil(this.часы));
      var доля = Math.max(0, Math.min(1, this.часы / 90));
      var пy = В * 0.845, пв = Math.max(4, В / 150);
      к.fillStyle = 'rgba(255,255,255,.12)';
      к.fillRect(Ш * 0.06, пy, Ш * 0.88, пв);
      к.fillStyle = сек <= 15 ? красный : 'rgba(255,255,255,.55)';
      к.fillRect(Ш * 0.06, пy, Ш * 0.88 * доля, пв);
      И.текст(к, И.шаб('осталось {1} с', сек), Ш / 2, пy + пв + Math.max(12, В / 44),
            Math.max(11, Math.min(Ш, В) / 29), сек <= 15 ? красный : тихий, true);

      /* ── Что делать прямо сейчас ──────────────────────────────── */
      var совет;
      if(this.штук === 0){
        совет = (this.деньги >= this.цена)
          ? И.слово('Блоков нет — купи, пока дёшево')
          : И.слово('Не хватает денег на блок');
      } else if(this.цена > ср){
        совет = И.шаб('Цена выше твоей на {1} — можно продать',
                       Math.round(this.цена - ср));
      } else {
        совет = И.шаб('Цена ниже твоей на {1} — подожди или докупи',
                       Math.round(ср - this.цена));
      }
      И.текст(к, совет, Ш / 2, В * 0.955, Math.max(11, Math.min(Ш, В) / 31),
            'rgba(255,255,255,.78)', false);

      /* Чип в шапке больше не нужен: всё то же самое теперь на экране
         крупно и с подписями, а две строки об одном спорили бы. */
      И.состояние('');
    }
  };

  return ИГРА;
});
